#!/usr/bin/env python3
"""Generates the matrix test of system calls whose first argument is a
string, of TEST_SUITE.md ("Mechanism matrix"), in tests/cli/.

  tools/gen_builtin_call_matrix.py           # writes the files
  tools/gen_builtin_call_matrix.py --check   # exit 1 if a file differs from what it would write

A call is a built-in method of the string type (6.16) or of an
enumeration (6.19.5) only when it is one, whatever its first argument;
slang gives a method's object as the first argument, and a system task
or function may take a string there too. A system task or function that
kirimasim does not implement yet is reported as one, "system task $x"
or "system function $x", and kirimasim ends with exit code 2 before
anything runs (CLI.md 5).

The axes: the call (system functions and tasks whose first argument is
a string literal, a string variable and a concatenation of strings) and
the container (an initial procedure, an automatic task, a function and a
branch of a fork; the subroutines are called from initial procedures of
their own). tests/cli/run_cli_tests.py runs the file and checks the exit
code 2, an empty stdout and exactly these lines, in any order.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "cli"
NAME = "builtin_call_matrix"
# The version of the rules below. Raise it whenever they change.
VERSION = 4

# (the statement, with ERR at the call, what it is)
CALLS = [
    ('fd = ERR$system("x");', "system function $system"),
    ("fd = ERR$system(name);", "system function $system"),
    ('fd = ERR$system({name, " y"});', "system function $system"),
    ('ERR$sdf_annotate("x.sdf");', "system task $sdf_annotate"),
    ("ERR$sdf_annotate(name);", "system task $sdf_annotate"),
    ('ERR$sdf_annotate({name, ".sdf"});', "system task $sdf_annotate"),
]
CONTAINERS = ["initial", "task", "function", "fork"]


def files():
    lines = [f"// Generated by tools/gen_builtin_call_matrix.py (version {VERSION}); do not edit.",
             "module top;",
             "  integer fd;",
             '  string name = "x";',
             "  logic [7:0] mem [0:3];"]
    err = []

    def add(text, what):
        column = text.index("ERR") + 1
        lines.append(text.replace("ERR", ""))
        err.append(f"{NAME}.sv:{len(lines)}:{column}: error: unsupported: {what} "
                   "(not implemented yet)")

    for container in CONTAINERS:
        for k, (stmt, what) in enumerate(CALLS):
            if container == "initial":
                add(f"  initial {stmt}", what)
            elif container == "task":
                lines.append(f"  task automatic t{k}();")
                add(f"    {stmt}", what)
                lines += ["  endtask", f"  initial t{k}();"]
            elif container == "function":
                lines.append(f"  function automatic void f{k}();")
                add(f"    {stmt}", what)
                lines += ["  endfunction", f"  initial f{k}();"]
            else:
                lines.append("  initial fork")
                add(f"    {stmt}", what)
                lines.append("  join")
    lines += ["endmodule", ""]
    return {f"{NAME}.sv": "\n".join(lines), f"{NAME}.stderr": "\n".join(err) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_builtin_call_matrix: {path.relative_to(OUT.parent.parent)} is out of "
                      "date; run tools/gen_builtin_call_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
