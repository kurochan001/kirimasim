"""Generates the real to integer conversion matrix test of TEST_SUITE.md
("Mechanism matrix") in tests/suite/values/.

  tools/gen_real_convert_matrix.py           # writes the files
  tools/gen_real_convert_matrix.py --check   # exit 1 if a file differs from what it would write

A real becomes an integer by rounding to the nearest, half away from
zero, then keeping the low bits of that integer's two's complement, at
any magnitude; NaN and the infinities give x in every bit of a
four-state target and 0 of a two-state one (VALUE_SEMANTICS.md 1.5,
7.4). The same holds however the conversion is written. The axes: the
value (halves, the double below 0.5, around 2^63 and 2^64, far past 64
bits, NaN, the infinities, -0.0); the target (8, 32, 64, 100 and 128
bits, two- and four-state, signed and unsigned); the spelling (from a
real variable at run time, from a constant expression, a cast, the
initializer of a declaration); and the container (module variables and
automatic variables of a function).

The expected outputs are computed with Python's exact integers. A person
checks them once for all the tests made from them (TEST_SUITE.md, "Sampling
by people").
"""

import argparse
import math
import sys
from pathlib import Path

from gen_wide_matrix import V, allx, hexdigits

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "values"
NAME = "real_convert_matrix"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

# (tag, declared type, width, four-state)
TARGETS = [
    ("b8", "bit [7:0]", 8, False), ("l8", "logic [7:0]", 8, True),
    ("int", "int", 32, False), ("integer", "integer", 32, True),
    ("longint", "longint", 64, False), ("l64", "logic [63:0]", 64, True),
    ("l100", "logic [99:0]", 100, True), ("sl100", "logic signed [99:0]", 100, True),
    ("b128", "bit [127:0]", 128, False),
]
NAN, INF = float("nan"), float("inf")
VALUES = [2.5, -2.5, 0.49999999999999994, -0.5, 1e20, -1e20, 9.3e18, 2.0 ** 63, -(2.0 ** 63),
          2.0 ** 64, 1.5e30, -1.5e30, 1e300, NAN, INF, -INF, 0.0, -0.0]


def spell(d):
    """A constant expression of real value d."""
    if math.isnan(d):
        return "(0.0 / 0.0)"
    if math.isinf(d):
        return "(1.0 / 0.0)" if d > 0 else "(-1.0 / 0.0)"
    return repr(d)


def convert(d, width, four):
    if math.isnan(d) or math.isinf(d):
        return allx(width) if four else V(width, 0)
    whole = math.floor(abs(d))
    n = int(whole) + (1 if abs(d) - whole >= 0.5 else 0)
    if d < 0:
        n = -n
    return V(width, n % (1 << width))


def files():
    head = [
        "/*",
        f":name: {NAME}",
        ":description: real to integer conversions at any magnitude, NaN and the infinities, "
        "to two- and four-state targets of 8 to 128 bits, from variables, constants, casts and "
        "initializers, in module and automatic variables",
        ":tags: values real",
        ":type: simulation",
        ":lrm: 1800-2023 6.12.1 6.24.1 10.7",
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: yes",
        ":nondeterministic: no",
        f":generator: gen_real_convert_matrix.py@{VERSION}",
        f":expected_stdout: @{NAME}.expected",
        "*/",
        "// Generated by tools/gen_real_convert_matrix.py; change the generator, not this file.",
        "// Icarus Verilog 14.0 (devel) f190dbb stores x for NaN and the infinities in two-state",
        "// targets too, which cannot hold x (1.2); it agrees on every other line.",
        "module top;",
        "  real r;",
    ]
    decls, st, exp = [], [], []
    for tag, ty, w, four in TARGETS:
        decls.append(f"  typedef {ty} {tag}_t;")
        decls.append(f"  {ty} {tag}_v;")
        for k, d in enumerate(VALUES):
            decls.append(f"  {ty} {tag}_i{k} = {spell(d)};")
    funcs = []
    for tag, ty, w, four in TARGETS:
        funcs += [f"  function automatic {tag}_t {tag}_f(real x);", f"    {ty} t;", "    t = x;",
                  "    return t;", "  endfunction"]
    for tag, ty, w, four in TARGETS:
        for k, d in enumerate(VALUES):
            want = hexdigits(convert(d, w, four))
            st += [f"    r = {spell(d)};",
                   f"    {tag}_v = r; $display(\"{tag} {k} run %h\", {tag}_v);",
                   f"    {tag}_v = {spell(d)}; $display(\"{tag} {k} const %h\", {tag}_v);",
                   f"    $display(\"{tag} {k} cast %h\", {tag}_t'(r));",
                   f"    $display(\"{tag} {k} init %h\", {tag}_i{k});",
                   f"    $display(\"{tag} {k} function %h\", {tag}_f(r));"]
            exp += [f"{tag} {k} {s} {want}" for s in ("run", "const", "cast", "init", "function")]
    sv = head + decls + funcs + ["  initial begin"] + st + ["  end", "endmodule", ""]
    return {f"{NAME}.sv": "\n".join(sv), f"{NAME}.expected": "\n".join(exp) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_real_convert_matrix: {path.relative_to(OUT.parent.parent.parent)} is "
                      "out of date; run tools/gen_real_convert_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
