"""Generates the matrix tests of $fread into memories of unpacked
structures (TEST_SUITE.md, "Mechanism matrix") in tests/suite/proc/.

  tools/gen_fread_struct_matrix.py           # writes the files
  tools/gen_fread_struct_matrix.py --check   # exit 1 if a file differs from what it would write

The rules (21.3.4.4, SYSTEM_TASKS.md 6.3):

- A memory is read element by element, from start (its lowest address by
  default) toward its highest address, for at most count elements.
- An element that is an unpacked structure is read member by member in
  declaration order, the members of a nested structure in place.
- Each member is read as an integral variable: ceil(width / 8) bytes, the
  first in the most significant place, the bits above its width dropped.
  When the file ends partway, the bytes not read keep their old value, and
  the reading stops there.
- $fread returns the number of bytes read.

The axes: the way of reading (the cells below: the whole memory, a start,
a start and a count, a memory declared high to low, a file that ends
between members; the whole memory's file ends inside one) and the container of the call (an initial procedure, a task, a
function, a fork branch, a task in a generate block).

The expected outputs follow from the rules above, without reading
kirimasim's code. Icarus 14.0 devel has no unpacked structures, so it was
not compared (checked 2026-10-21).
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "proc"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

CONTAINERS = ["initial", "task", "function", "fork", "generate"]

# The members in declaration order, nested ones in place: (name, width,
# the value they start with).
LEAVES = [("a", 8, 0xee), ("b", 12, 0xeee), ("n.c", 4, 0xe), ("n.d", 8, 0xee)]
TYPE = ("typedef struct { logic [7:0] a; bit [11:0] b; "
        "struct { logic [3:0] c; byte d; } n; } s_t;")
# The memories: name -> (declaration, its addresses from low to high).
MEMS = {"up": ("s_t up [0:3];", [0, 1, 2, 3]), "dn": ("s_t dn [3:0];", [0, 1, 2, 3])}

# Each cell: (name, memory, bytes in the file, start, count).
CELLS = [
    ("whole", "up", 12, None, None),
    ("start", "up", 20, 2, None),
    ("start_count", "up", 20, 1, 2),
    ("high_to_low", "dn", 10, None, None),
    ("ends_between_members", "dn", 8, 1, None),
]


def file_bytes(n):
    return [0x11 * (k % 15 + 1) & 0xff if k < 15 else k + 1 for k in range(n)]


def model(mem, n, start, count):
    """The values after the read, by address, and the bytes read."""
    data = file_bytes(n)
    addrs = MEMS[mem][1]
    values = {a: [v for _, _, v in LEAVES] for a in addrs}
    at = 0
    total = 0
    a = addrs[0] if start is None else start
    left = len(addrs) if count is None else count
    while a <= addrs[-1] and left > 0:
        for i, (_, w, _) in enumerate(LEAVES):
            nb = (w + 7) // 8
            got = data[at:at + nb]
            at += len(got)
            total += len(got)
            if not got:
                return values, total
            v = values[a][i]
            for k, b in enumerate(got):
                shift = (nb - 1 - k) * 8
                v = (v & ~(0xff << shift)) | (b << shift)
            values[a][i] = v & ((1 << w) - 1)
            if len(got) < nb:
                return values, total
        a += 1
        left -= 1
    return values, total


def hexw(v, w):
    return format(v, f"0{(w + 3) // 4}x")


def test(container):
    name = f"fread_struct_{container}"
    lines = ["/*", f":name: {name}",
             ":description: $fread into memories of unpacked structures reads each element's "
             "members in declaration order, called from "
             f"{'an' if container[0] in 'aeiou' else 'a'} {container}",
             ":tags: proc", ":type: simulation", ":lrm: 1800-2023 21.3.4.4", ":oracle: spec",
             ":spec_check: ai", ":fourstate: yes", ":nondeterministic: no",
             f":generator: gen_fread_struct_matrix.py@{VERSION}", ":top_module: top",
             f":expected_stdout: @{name}.expected", f":expected_stderr: @{name}.stderr", "*/",
             "// Generated by tools/gen_fread_struct_matrix.py; change the generator, not this "
             "file.", "`timescale 1ns/1ns", "module top;", f"  {TYPE}"]
    lines += [f"  {d}" for d, _ in MEMS.values()]
    lines.append("  integer fd, r;")
    body = []
    stdout = []
    for key, mem, n, start, count in CELLS:
        extra = "" if start is None else f", {start}" + ("" if count is None else f", {count}")
        body += [f"foreach ({mem}[i]) begin",
                 "  " + " ".join(f"{mem}[i].{leaf} = {w}'h{hexw(v, w)};" for leaf, w, v in LEAVES),
                 "end",
                 f'fd = $fopen("{key}.bin", "rb");',
                 f"r = $fread({mem}, fd{extra});",
                 "$fclose(fd);"]
        fmt = " | ".join(" ".join("%h" for _ in LEAVES) for _ in MEMS[mem][1])
        refs = ", ".join(f"{mem}[{a}].{leaf}" for a in MEMS[mem][1] for leaf, _, _ in LEAVES)
        body.append(f'$display("{key}: %0d | {fmt}", r, {refs});')
        values, total = model(mem, n, start, count)
        parts = [" ".join(hexw(values[a][i], w) for i, (_, w, _) in enumerate(LEAVES))
                 for a in MEMS[mem][1]]
        stdout.append(f"{key}: {total} | " + " | ".join(parts))
    if container == "task":
        lines += ["  task load;"] + ["    " + b for b in body] + ["  endtask"]
        calls = ["load;"]
    elif container == "function":
        lines += ["  function void load();"] + ["    " + b for b in body] + ["  endfunction"]
        calls = ["load();"]
    elif container == "generate":
        lines += ["  if (1) begin : g", "    task load;"] + ["      " + b for b in body] + [
            "    endtask", "  end"]
        calls = ["g.load;"]
    elif container == "fork":
        calls = ["fork begin"] + ["  " + b for b in body] + ["end join"]
    else:
        calls = body
    lines.append("  initial begin")
    for key, _, n, _, _ in CELLS:
        chars = "".join("%c" for _ in range(n))
        values = ", ".join(f"8'h{b:02x}" for b in file_bytes(n))
        lines += [f'    fd = $fopen("{key}.bin", "wb");', f'    $fwrite(fd, "{chars}", {values});',
                  "    $fclose(fd);"]
    lines += ["    " + c for c in calls]
    lines += ["  end", "endmodule"]
    return name, lines, stdout


def files():
    out = {}
    for container in CONTAINERS:
        name, lines, stdout = test(container)
        out[f"{name}.sv"] = "\n".join(lines) + "\n"
        out[f"{name}.expected"] = "\n".join(stdout) + "\n"
        out[f"{name}.stderr"] = ""
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_fread_struct_matrix: {path.relative_to(OUT.parent.parent.parent)} is "
                      "out of date; run tools/gen_fread_struct_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
