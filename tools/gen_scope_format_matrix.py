"""Generates the matrix tests of names printed through %m, %l and
$printtimescale (TEST_SUITE.md, "Mechanism matrix") in tests/suite/values/.

  tools/gen_scope_format_matrix.py           # writes the files
  tools/gen_scope_format_matrix.py --check   # exit 1 if a file differs from what it would write

The rule: SYSTEM_TASKS.md 3.8 and 21.2.1.6 of the standard. %m prints the
hierarchical name of the scope and %l the library and cell, as they are:
a % inside the name (an escaped identifier may hold one) is part of the
name and not a conversion, and takes no argument. The axes: the module's
name (a plain one, and escaped ones holding %d, %s, %% and %m); the task
($display, $write, $sformatf and $printtimescale) with %m and %l; a value
after the name, which has to stay with its own conversion; and the
container (the module's initial, a named block and a function).

One test per name, as the name is the module's. The expected output is
written from the names below. A person checks it once for all the tests
made from it (TEST_SUITE.md, "Sampling by people").
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "values"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

# The module: the test's suffix, its name as written, and as printed (an
# escaped identifier prints with its backslash and the space that ends it).
MODULES = [
    ("plain", "plain_m", "plain_m"),
    ("percent_d", "\\t%d ", "\\t%d "),
    ("percent_s", "\\t%s ", "\\t%s "),
    ("percent_percent", "\\t%% ", "\\t%% "),
    ("percent_m", "\\t%m ", "\\t%m "),
]


def files():
    out = {}
    for suffix, written, printed in MODULES:
        name = f"scope_format_{suffix}"
        cell = "work." + printed.lstrip("\\").rstrip(" ")
        sv = [
            "/*",
            f":name: {name}",
            ":description: %m, %l and $printtimescale print a name that holds a % as it is, "
            "and the conversions after it keep their arguments",
            ":tags: values",
            ":type: simulation",
            ":lrm: 1800-2023 21.2.1.6 20.4.2 5.6.1",
            ":oracle: spec",
            ":spec_check: ai",
            ":fourstate: no",
            ":nondeterministic: no",
            f":generator: gen_scope_format_matrix.py@{VERSION}",
            f":expected_stdout: @{name}.expected",
            "*/",
            "// Generated by tools/gen_scope_format_matrix.py; change the generator, not this file.",
            "`timescale 1ns/1ps",
            f"module {written};",
            "  function automatic void show();",
            '    $display("function display [%m] %0d", 3);',
            '    $display("function sformatf %s", $sformatf("<%m> %0d", 4));',
            "  endfunction",
            "  initial begin",
            '    $display("initial display [%m] %0d", 1);',
            '    $write("initial write [%m] %0d\\n", 2);',
            '    $display("initial sformatf %s", $sformatf("<%m> %0d", 5));',
            '    $display("initial cell [%l] %0d", 6);',
            "    $printtimescale;",
            "    begin : blk",
            '      $display("block display [%m] %0d", 7);',
            '      $write("block write [%m] %0d\\n", 8);',
            "    end",
            "    show();",
            "  end",
            "endmodule",
            "",
        ]
        expected = [
            f"initial display [{printed}] 1",
            f"initial write [{printed}] 2",
            f"initial sformatf <{printed}> 5",
            f"initial cell [{cell}] 6",
            f"Time scale of ({printed}) is 1ns / 1ps",
            f"block display [{printed}.blk] 7",
            f"block write [{printed}.blk] 8",
            f"function display [{printed}.show] 3",
            f"function sformatf <{printed}.show> 4",
        ]
        out[f"{name}.sv"] = "\n".join(sv)
        out[f"{name}.expected"] = "\n".join(expected) + "\n"
    return out


BLOCKS = "scope_format_blocks"


def shown(name):
    """A part of a hierarchical name as %m prints it: an escaped identifier
    with its backslash and the space that ends it."""
    return name if name.replace("_", "a").isalnum() else "\\" + name + " "


def written(name):
    return name if name.replace("_", "a").isalnum() else "\\" + name + " "


def block_files():
    """Every kind of scope with an escaped name and with a plain one: an
    instance, a generate block, a function, a task, and a named block of
    statements in each of them and inside another named block."""
    sv = [
        "/*",
        f":name: {BLOCKS}",
        ":description: %m prints an escaped name of a named block as it prints one of an "
        "instance, a generate block or a subroutine, with its backslash and the space that "
        "ends it",
        ":tags: values",
        ":type: simulation",
        ":lrm: 1800-2023 21.2.1.6 5.6.1",
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: no",
        ":nondeterministic: no",
        f":generator: gen_scope_format_matrix.py@{VERSION}",
        ":top_module: top",
        f":expected_stdout: @{BLOCKS}.expected",
        "*/",
        "// Generated by tools/gen_scope_format_matrix.py; change the generator, not this file.",
        "`timescale 1ns/1ps",
    ]
    expected = []
    kinds = [("e", "b+1", "in.2"), ("p", "blk", "inner")]
    # A module below, one instance with each kind of name.
    sv += ["module leaf #(parameter int at = 0);", "  initial begin : " + written("lb*3"),
           "    #at;", '    $display("leaf block [%m]");', "  end", "endmodule", "module top;"]
    for key, outer, inner in kinds:
        inst = "i.1" if key == "e" else "inst"
        gen = "g*1" if key == "e" else "gen"
        fn = "f/x" if key == "e" else "fn"
        task = "t-1" if key == "e" else "tk"
        sv += [f"  leaf #({4 if key == 'e' else 5}) {written(inst)}();",
               f"  function automatic void {written(fn)}();",
               f"    begin : {written(outer)}",
               f'      $display("{key} function block [%m]");',
               "    end", "  endfunction",
               f"  task {written(task)};",
               f"    begin : {written(outer)}",
               f'      $display("{key} task block [%m]");',
               "    end", "  endtask",
               f"  if (1) begin : {written(gen)}",
               f"    initial begin : {written(outer)}",
               f"      #{1 if key == 'e' else 2};",
               f'      $display("{key} generate block [%m]");',
               "    end", "  end",
               f"  initial begin : {written(outer)}",
               f"    #{3 if key == 'e' else 6};",
               f'    $display("{key} block [%m]");',
               f'    $display("{key} sformatf %s", $sformatf("<%m>"));',
               f"    begin : {written(inner)}",
               f'      $display("{key} nested [%m]");',
               "    end",
               f"    {written(fn)}();",
               f"    {written(task)};",
               "  end"]
    sv += ["endmodule", ""]
    lb = shown("lb*3")
    # Each process prints at a time of its own, so the order of the lines
    # does not depend on the order of processes (4.7).
    events = []
    for key, outer, inner in kinds:
        inst = shown("i.1" if key == "e" else "inst")
        gen = shown("g*1" if key == "e" else "gen")
        fn = shown("f/x" if key == "e" else "fn")
        task = shown("t-1" if key == "e" else "tk")
        o, i = shown(outer), shown(inner)
        at = 1 if key == "e" else 2
        events.append((at, f"{key} generate block [top.{gen}.{o}]"))
        at = 3 if key == "e" else 6
        events += [(at, f"{key} block [top.{o}]"), (at, f"{key} sformatf <top.{o}>"),
                   (at, f"{key} nested [top.{o}.{i}]"),
                   (at, f"{key} function block [top.{fn}.{o}]"),
                   (at, f"{key} task block [top.{task}.{o}]")]
        events.append((4 if key == "e" else 5, f"leaf block [top.{inst}.{lb}]"))
    events.sort(key=lambda e: e[0])
    expected = [e[1] for e in events]
    return {f"{BLOCKS}.sv": "\n".join(sv), f"{BLOCKS}.expected": "\n".join(expected) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in {**files(), **block_files()}.items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_scope_format_matrix: {path.relative_to(OUT.parent.parent.parent)} is "
                      "out of date; run tools/gen_scope_format_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
