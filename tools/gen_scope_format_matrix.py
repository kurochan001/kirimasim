"""Generates the matrix tests of names printed through %m, %l and
$printtimescale (TEST_SUITE.md, "Mechanism matrix") in tests/suite/values/.

  tools/gen_scope_format_matrix.py           # writes the files
  tools/gen_scope_format_matrix.py --check   # exit 1 if a file differs from what it would write

The rule: SYSTEM_TASKS.md 3.8 and 21.2.1.6 of the standard. %m prints the
hierarchical name of the scope and %l the library and cell, as they are:
a % inside the name (an escaped identifier may hold one) is part of the
name and not a conversion, and takes no argument. The axes: the module's
name (a plain one, and escaped ones holding %d, %s, %% and %m); the task
($display, $write, $sformatf and $printtimescale) with %m and %l; a value
after the name, which has to stay with its own conversion; and the
container (the module's initial, a named block and a function).

One test per name, as the name is the module's. The expected output is
written from the names below. A person checks it once for all the tests
made from it (TEST_SUITE.md, "Sampling by people").
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "values"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

# The module: the test's suffix, its name as written, and as printed (an
# escaped identifier prints with its backslash and the space that ends it).
MODULES = [
    ("plain", "plain_m", "plain_m"),
    ("percent_d", "\\t%d ", "\\t%d "),
    ("percent_s", "\\t%s ", "\\t%s "),
    ("percent_percent", "\\t%% ", "\\t%% "),
    ("percent_m", "\\t%m ", "\\t%m "),
]


def files():
    out = {}
    for suffix, written, printed in MODULES:
        name = f"scope_format_{suffix}"
        cell = "work." + printed.lstrip("\\").rstrip(" ")
        sv = [
            "/*",
            f":name: {name}",
            ":description: %m, %l and $printtimescale print a name that holds a % as it is, "
            "and the conversions after it keep their arguments",
            ":tags: values",
            ":type: simulation",
            ":lrm: 1800-2023 21.2.1.6 20.4.2 5.6.1",
            ":oracle: spec",
            ":spec_check: ai",
            ":fourstate: no",
            ":nondeterministic: no",
            f":generator: gen_scope_format_matrix.py@{VERSION}",
            f":expected_stdout: @{name}.expected",
            "*/",
            "// Generated by tools/gen_scope_format_matrix.py; change the generator, not this file.",
            "`timescale 1ns/1ps",
            f"module {written};",
            "  function automatic void show();",
            '    $display("function display [%m] %0d", 3);',
            '    $display("function sformatf %s", $sformatf("<%m> %0d", 4));',
            "  endfunction",
            "  initial begin",
            '    $display("initial display [%m] %0d", 1);',
            '    $write("initial write [%m] %0d\\n", 2);',
            '    $display("initial sformatf %s", $sformatf("<%m> %0d", 5));',
            '    $display("initial cell [%l] %0d", 6);',
            "    $printtimescale;",
            "    begin : blk",
            '      $display("block display [%m] %0d", 7);',
            '      $write("block write [%m] %0d\\n", 8);',
            "    end",
            "    show();",
            "  end",
            "endmodule",
            "",
        ]
        expected = [
            f"initial display [{printed}] 1",
            f"initial write [{printed}] 2",
            f"initial sformatf <{printed}> 5",
            f"initial cell [{cell}] 6",
            f"Time scale of ({printed}) is 1ns / 1ps",
            f"block display [{printed}.blk] 7",
            f"block write [{printed}.blk] 8",
            f"function display [{printed}.show] 3",
            f"function sformatf <{printed}.show> 4",
        ]
        out[f"{name}.sv"] = "\n".join(sv)
        out[f"{name}.expected"] = "\n".join(expected) + "\n"
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_scope_format_matrix: {path.relative_to(OUT.parent.parent.parent)} is "
                      "out of date; run tools/gen_scope_format_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
