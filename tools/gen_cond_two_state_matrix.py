"""Generates the matrix tests of the conditional operator with an x or z
condition and two sides of one 2-state type (TEST_SUITE.md, "Mechanism
matrix") in tests/suite/values/.

  tools/gen_cond_two_state_matrix.py           # writes the files
  tools/gen_cond_two_state_matrix.py --check   # exit 1 if a file differs from what it would write

The rule: 11.4.11 and Table 11-20 of the standard, VALUE_SEMANTICS.md
3.9. With a condition that is x or z, integral sides are combined bit by
bit: a bit that is the same on both sides keeps its value, and a bit that
differs is x. This holds for every integral type of the sides, also for
2-state ones: an enumeration is an integral type (6.11.1) as int is.
The x bits become 0 only when the value is then stored in a 2-state
variable.

The axes: the type of the two sides (int, a bit vector, a signed byte,
an enumeration with the default base type, an enumeration with a 2-state
base type, a 2-state packed structure, a typedef of a bit vector), the
condition (x, z, a vector with one x bit and no 1 bit), the use (printed
with %b, stored in a 4-state variable of the same width, stored in a
variable of the type itself), and the container (an initial procedure, a
function, a continuous assignment).

The expected output is computed here from the two values, without
reading kirimasim's code. A person checks it once for all the tests made
from it (TEST_SUITE.md, "Sampling by people"). For reference, checked
2026-11-12: Icarus 13.0 prints the x bits for the enumerations too.
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "values"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

# (key, declarations before the variables, the type, its width, the first
# value as written and its bits, the second value as written and its bits).
# A cast takes the name of a type: the vector written out has n_t for it.
TYPES = [
    ("int", "", "int", 32, "6", 6, "3", 3),
    ("bits", "typedef bit [3:0] n_t;", "bit [3:0]", 4, "4'b1010", 0b1010, "4'b0110", 0b0110),
    ("byte", "", "byte", 8, "-8'sd2", 0xFE, "8'sd5", 0x05),
    ("enum", "typedef enum {E0, E1, E2} e_t;", "e_t", 32, "E1", 1, "E2", 2),
    ("enum_bit", "typedef enum bit [1:0] {B0, B1, B2} b_t;", "b_t", 2, "B1", 1, "B2", 2),
    ("struct", "typedef struct packed { bit [1:0] f; bit g; } p_t;", "p_t", 3, "3'b101", 0b101,
     "3'b011", 0b011),
    ("typedef", "typedef bit [5:0] v_t;", "v_t", 6, "6'd33", 33, "6'd12", 12),
]
CONDS = [("x", "1'bx"), ("z", "1'bz"), ("vector", "2'b0x")]
CONTAINERS = ["initial", "function", "assign"]


def merged(width, a, b):
    return "".join(str((a >> i) & 1) if ((a >> i) & 1) == ((b >> i) & 1) else "x"
                   for i in reversed(range(width)))


def test(container):
    name = f"cond_two_state_{container}"
    where = {"initial": "an initial procedure", "function": "a function",
             "assign": "a continuous assignment"}[container]
    sv = ["/*", f":name: {name}",
          ":description: a conditional operator with an x or z condition merges two sides of "
          f"one 2-state type bit by bit, the bits that differ being x, in {where}",
          ":tags: values", ":type: simulation", ":lrm: 1800-2023 11.4.11 6.11.1", ":oracle: spec",
          ":spec_check: ai", ":fourstate: yes", ":nondeterministic: no",
          f":generator: gen_cond_two_state_matrix.py@{VERSION}", ":top_module: top",
          f":expected_stdout: @{name}.expected", "*/",
          "// Generated by tools/gen_cond_two_state_matrix.py; change the generator, not this "
          "file.", "`timescale 1ns/1ns", "module top;"]
    decls, body, expected, extra, casts = [], [], [], [], {}
    for key, pre, typ, width, va, a, vb, b in TYPES:
        if pre:
            decls.append(pre)
        decls.append(f"{typ} {key}_a, {key}_b, {key}_two;")
        casts[key] = "n_t" if key == "bits" else typ
        decls.append(f"logic [{width - 1}:0] {key}_four;")
        body.append(f"{key}_a = {casts[key]}'({va}); {key}_b = {casts[key]}'({vb});")
    for key, pre, typ, width, va, a, vb, b in TYPES:
        for ckey, cond in CONDS:
            label = f"{key} {ckey}"
            expr = f"c_{ckey} ? {key}_a : {key}_b"
            m = merged(width, a, b)
            two = m.replace("x", "0")
            if container == "initial":
                body.append(f'$display("{label} shown: %b", {expr});')
                body.append(f"{key}_four = {expr};")
                body.append(f"{key}_two = {casts[key]}'({expr});")
                body.append(f'$display("{label} stored: %b %b", {key}_four, {key}_two);')
            elif container == "function":
                fn = f"f_{key}_{ckey}"
                extra.append(f"function automatic logic [{width - 1}:0] {fn}"
                             f"(logic [1:0] c, {typ} a, {typ} b);")
                extra.append("  return c ? a : b;" if ckey == "vector" else "  return c[0] ? a : b;")
                extra.append("endfunction")
                call = f"{fn}({cond if ckey == 'vector' else '{1' + chr(39) + 'b0, ' + cond + '}'}, " \
                       f"{key}_a, {key}_b)"
                body.append(f'$display("{label} shown: %b", {call});')
                body.append(f"{key}_four = {call};")
                body.append(f"{key}_two = {casts[key]}'({call});")
                body.append(f'$display("{label} stored: %b %b", {key}_four, {key}_two);')
            else:
                extra.append(f"wire [{width - 1}:0] w_{key}_{ckey};")
                extra.append(f"assign w_{key}_{ckey} = {expr};")
                extra.append(f"{typ} t_{key}_{ckey};")
                extra.append(f"assign t_{key}_{ckey} = {casts[key]}'({expr});")
                body.append(f'$display("{label} shown: %b", w_{key}_{ckey});')
                body.append(f'$display("{label} stored: %b %b", w_{key}_{ckey}, '
                            f't_{key}_{ckey});')
            expected.append(f"{label} shown: {m}")
            expected.append(f"{label} stored: {m} {two}")
    sv += ["  " + d for d in decls]
    sv += [f"  logic c_x = 1'bx, c_z = 1'bz;", "  logic [1:0] c_vector = 2'b0x;"]
    sv += ["  " + e for e in extra]
    sv += ["  initial begin"]
    if container == "assign":
        # The values first; the nets follow them before they are printed.
        sv += ["    " + b for b in body[:len(TYPES)]] + ["    #1;"]
        sv += ["    " + b for b in body[len(TYPES):]]
    else:
        sv += ["    " + b for b in body]
    sv += ["  end", "endmodule"]
    return name, sv, expected


def files():
    out = {}
    for container in CONTAINERS:
        name, sv, expected = test(container)
        out[f"{name}.sv"] = "\n".join(sv) + "\n"
        out[f"{name}.expected"] = "\n".join(expected) + "\n"
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_cond_two_state_matrix: {path.relative_to(OUT.parent.parent.parent)} "
                      "is out of date; run tools/gen_cond_two_state_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
