"""Original fixed-array event selection matrix (IEEE 1800 7.4.5/9.4.2/15.5).

Existing permanent events, runtime selectors and shared typed place lowering.
This does not generate automatic default event declarations or change GC timing.
"""
import argparse
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / 'tests' / 'suite' / 'sched'
VERSION = 1
HOMES = ('initial', 'task', 'automatic', 'fork', 'interface', 'package', 'generate', 'program')
SHAPES = ('ascending', 'descending', 'rank2')
MODES = ('named', 'mixed', 'nba', 'triggered')


def layout(shape):
    if shape == 'rank2':
        return '[2:1][-1:1]', (2, -1), (1, 1)
    return ('[1:3]' if shape == 'ascending' else '[3:1]'), (1, 0), (3, 0)


def wrap(home, declarations, body):
    if home in ('interface', 'package'):
        kind = home
        source = (f'{kind} worker;\n{declarations}\ntask automatic run_check();\n{body}\nendtask\n'
                  f'end{kind}\n')
        start = 'worker w(); initial w.run_check();' if home == 'interface' else 'initial worker::run_check();'
        return source + f'module top; {start} endmodule\n'
    if home == 'program':
        return f'program worker;\n{declarations}\ninitial begin\n{body}\nend\nendprogram\nmodule top; worker p(); endmodule\n'
    if home == 'generate':
        return f'module top; if(1) begin:g\n{declarations}\ninitial begin\n{body}\nend\nend endmodule\n'
    if home in ('task', 'automatic'):
        automatic = 'automatic ' if home == 'automatic' else ''
        run = f'task {automatic}run_check();\n{body}\nendtask\ninitial run_check();'
    elif home == 'fork':
        run = f'initial fork begin\n{body}\nend join'
    else:
        run = f'initial begin\n{body}\nend'
    return f'module top;\n{declarations}\n{run}\nendmodule\n'


def output(name, source, expected, exit_code=0, instance='top'):
    header = f'''/*
:name: {name}
:description: Typed runtime fixed-array event selection keeps concrete targets and executed object reads
:tags: sched event array
:type: simulation
:lrm: 1800-2023 7.4.5 9.4.2 15.5
:oracle: spec
:spec_check: ai
:fourstate: yes
:nondeterministic: no
:generator: gen_indexed_event_matrix.py@{VERSION}
:top_module: top
:expected_stdout: @{name}.expected
:expected_stderr: @{name}.stderr
:expected_exit: {exit_code}
*/
// Generated by tools/gen_indexed_event_matrix.py; edit the generator.
`timescale 1ns/1ns
'''
    text = header + source
    stderr = ''
    if exit_code == 2:
        positions = [i for i, line in enumerate(text.splitlines(), 1) if '@(' in line]
        assert len(positions) == 1
        stderr = f'{name}.sv:{positions[0]}: error: wait on a null event [{instance} @ 0ns]\n'
    return {name+'.sv': text, name+'.expected': expected, name+'.stderr': stderr}


def main_case(home, spelling, shape, mode):
    dims, first, second = layout(shape)
    rank2 = shape == 'rank2'
    prefix = {'interface': 'top.w.', 'package': 'worker::', 'generate': 'top.g.',
              'program': 'top.p.'}.get(home, 'top.') if spelling == 'qualified' else ''
    event = prefix + 'events'
    def at(index, column='column'):
        return f'{event}[{index}]' + (f'[{column}]' if rank2 else '')
    a, b = at(first[0], first[1]), at(second[0], second[1])
    selected, picked = at('index'), at('pick(index)', 'pick_column(column)')
    declarations = f'''event events{dims};
int index, column;
bit enabled, clk;
int target_calls, column_calls, delay_calls, order;
function automatic int pick(input int value); target_calls++;order=order*10+1;return value;endfunction
function automatic int pick_column(input int value); column_calls++;order=order*10+3;return value;endfunction
'''
    if mode == 'nba':
        declarations += f'''function automatic int delay_value(ref int index, ref int column);
 delay_calls++;order=order*10+2;index={second[0]};column={second[1]};return 2;
endfunction
'''
    body = ('automatic int index,column;\n' if home in ('automatic', 'fork') else '')
    body += f'index={first[0]};column={first[1]};\n'
    if mode in ('named', 'mixed'):
        expr = picked if mode == 'named' else f'{picked} iff enabled or posedge clk'
        initial_false = f'->{a};' if mode == 'mixed' else ''
        body += f'''fork
 begin @({expr});$display("wake %0t",$time);end
 begin #1;{initial_false}index={second[0]};column={second[1]};enabled=1;->{selected};
 #1;->{a};end
join
$display("calls %0d %0d %0d",target_calls,column_calls,order);
'''
        expected = f'wake 2\ncalls 1 {int(rank2)} {13 if rank2 else 1}\n'
    elif mode == 'nba':
        body += f'''fork
 begin @({a});$display("first %0t",$time);end
 begin @({b});$display("second %0t",$time);end
 begin #1;->> #(delay_value(index,column)) {picked};#3;->{b};end
join
$display("calls %0d %0d %0d %0d",target_calls,column_calls,delay_calls,order);
'''
        expected = f'first 3\nsecond 4\ncalls 1 {int(rank2)} 1 {132 if rank2 else 12}\n'
    else:
        body += f'''fork
 begin wait({selected}.triggered);$display("wake %0t",$time);end
 begin #1;index={second[0]};column={second[1]};->{a};#1;->{b};end
join
$display("state %0d %0d",{a}.triggered,{b}.triggered);
'''
        expected = 'wake 2\nstate 0 1\n'
    name = f'indexed_event_{home}_{spelling}_{shape}_{mode}'
    return output(name, wrap(home, declarations, body), expected)


def null_case(home, shape, invalid, waiting):
    dims, first, _ = layout(shape)
    rank2 = shape == 'rank2'
    index_type, value = {'below': ('int', '0'), 'unknown': ('logic[128:0]', "'x"),
                         'highz': ('logic[128:0]', "'z"),
                         'wide': ('logic[128:0]', "129'h100000000000000000000000000000000")}[invalid]
    declarations = f'event events{dims};\n{index_type} index;\n'
    selected = 'events[index]' + (f'[{first[1]}]' if rank2 else '')
    body = f'index={value};\n'
    if waiting:
        body += f'$display("before");\n@({selected});\n$display("after");\n'
        expected, code = 'before\n', 2
    else:
        body += f'''->{selected};
->> #(65'd18446744073709551616) {selected};
$display("null %0d",{selected}.triggered);
#1;$display("done %0t",$time);
'''
        expected, code = 'null 0\ndone 1\n', 0
    name = f'indexed_event_null_{home}_{shape}_{invalid}_' + ('wait' if waiting else 'trigger')
    instance = {'package': 'worker', 'program': 'top.p'}.get(home, 'top')
    return output(name, wrap(home, declarations, body), expected, code, instance)


def generated():
    files = {}
    for h, home in enumerate(HOMES):
        for j, spelling in enumerate(('local', 'qualified')):
            for m, mode in enumerate(MODES):
                shape = SHAPES[(h+j+m) % len(SHAPES)]
                files.update(main_case(home, spelling, shape, mode))
    for home in ('initial', 'automatic', 'package', 'program'):
        for shape in SHAPES:
            for invalid in ('below', 'unknown', 'highz', 'wide'):
                for waiting in (False, True):
                    files.update(null_case(home, shape, invalid, waiting))
    assert len(files) == 160 * 3
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    files = generated()
    if args.check:
        stale = [name for name, text in files.items() if not (OUT/name).exists() or (OUT/name).read_text() != text]
        extra = {p.name for p in OUT.glob('indexed_event_*')} - files.keys()
        if stale or extra:
            print('stale indexed event files: '+', '.join(stale+sorted(extra)))
            return 1
    else:
        OUT.mkdir(parents=True, exist_ok=True)
        for name, text in files.items():
            (OUT/name).write_text(text)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
