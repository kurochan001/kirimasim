#!/usr/bin/env python3
"""Generates the matrix tests of unconnected input ports under
`unconnected_drive, of TEST_SUITE.md ("Mechanism matrix"), in
tests/suite/hier/.

  tools/gen_unconnected_drive_matrix.py           # writes the files
  tools/gen_unconnected_drive_matrix.py --check   # exit 1 if a file differs from what it would write

An input port of a module or interface declared where `unconnected_drive
pull1 (or pull0) is in effect, and left unconnected in an instance, gets
one more driver on its net: a pullup (or pulldown) on every bit, at pull
strength, resolved with the net's other drivers (22.9, 28.10, 28.12;
VALUE_SEMANTICS.md 5.3). `nounconnected_drive and `resetall end it, and
it holds to the end of the sources when nothing ends it (22.3, 22.9).
inout and output ports, connected ports and the ports of a top module
are not pulled. A variable input port is not pulled either: it keeps the
initial value of its type, with a warning (23.3.3.2;
UNSPECIFIED_BEHAVIOR.md N10).

The axes: the directive (pull1, pull0, none, pull1 ended by `resetall,
pull0 never ended); the container of the port (module, interface); how
the port is left open (left out of a list by name, named with empty
parentheses, empty in an ordered list, no list, an array of instances
with no list); the width (1, 4, and 70 bits, over one word); how the
port is read (through a continuous assignment or a net declaration
assignment, and by a process through a hierarchical name). Further
tests resolve the pull with other drivers inside the definition, on
wire, tri0, tri1, wand and wor nets, and check the ports that are not
pulled.

Each top prints from one initial procedure at time 1, after the
drivers have run, so that the output does not depend on the order of
processes. The expected outputs follow from the rules above, computed
below. A person checks them once for all the tests made from them
(TEST_SUITE.md, "Sampling by people").
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "hier"
PREFIX = "unconnected_drive_"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

# directive: (lines before the definition, lines after it, the value an
# unconnected input port takes: "1", "0" or "z")
DIRECTIVES = {
    "pull1": (["`unconnected_drive pull1"], ["`nounconnected_drive"], "1"),
    "pull0": (["`unconnected_drive pull0"], ["`nounconnected_drive"], "0"),
    "none": ([], [], "z"),
    "resetall": (["`unconnected_drive pull1", "`resetall"], [], "z"),
    "unclosed": (["`unconnected_drive pull0"], [], "0"),
}
DIRECTIVE_TEXT = {
    "pull1": "`unconnected_drive pull1",
    "pull0": "`unconnected_drive pull0",
    "none": "no directive",
    "resetall": "`unconnected_drive pull1 ended by `resetall",
    "unclosed": "`unconnected_drive pull0 never ended",
}

# How the four inputs a1, a4, a70 and c are left open: (label, the
# connections of a module instance, of an interface instance, whether c
# is connected to 1'b0, the name read through hierarchical names).
OPENINGS = [
    ("named, left out", "u1(.c(1'b0), .y(y1))", "u1(.c(1'b0))", True, "u1"),
    ("named, empty", "u2(.a1(), .a4(), .a70(), .c(1'b0), .y(y2))",
     "u2(.a1(), .a4(), .a70(), .c(1'b0))", True, "u2"),
    ("ordered, empty", "u3(, , , 1'b0, y3)", "u3(, , , 1'b0)", True, "u3"),
    ("no list", "u4()", "u4()", False, "u4"),
    ("array, no list", "u5[1:0]()", "u5[1:0]()", False, "u5[1]"),
]


def hexval(width, v):
    """%h of a value of `width` bits that are all v."""
    digits = (width + 3) // 4
    if v != "1":
        return v * digits
    top = width % 4 or 4
    return format((1 << top) - 1, "x") + "f" * (digits - 1)


def header(name, description, lrm, extra=()):
    return [
        "/*",
        f":name: {name}",
        f":description: {description}",
        ":tags: hierarchy directives",
        ":type: simulation",
        ":lrm: 1800-2023 " + " ".join(lrm),
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: yes",
        ":nondeterministic: no",
        f":generator: gen_unconnected_drive_matrix.py@{VERSION}",
        ":issue: 17",
        f":expected_stdout: @{name}.expected",
        *extra,
        "*/",
        "// Generated by tools/gen_unconnected_drive_matrix.py; change the generator, not "
        "this file.",
    ]


def matrix_case(directive, container):
    before, after, v = DIRECTIVES[directive]
    name = f"{PREFIX}{directive}_{container}"
    if container == "module":
        definition = [
            "module leaf(input wire a1, input wire [3:0] a4, input wire [69:0] a70, "
            "input wire c,",
            "            output wire [74:0] y);",
            "  assign y = {a1, a4, a70};",
            "endmodule",
        ]
        decl = ["  wire [74:0] y1, y2, y3;"]
        insts = [f"  leaf {conn};" for _, conn, _, _, _ in OPENINGS]
    else:
        definition = [
            "interface leaf(input wire a1, input wire [3:0] a4, input wire [69:0] a70, "
            "input wire c);",
            "  wire [74:0] y = {a1, a4, a70};",
            "endinterface",
        ]
        decl = []
        insts = [f"  leaf {conn};" for _, _, conn, _, _ in OPENINGS]
    lines, expected = [], []
    for i, (label, _, _, connected, at) in enumerate(OPENINGS):
        # A module's y is read through its output port where one is
        # connected; an interface's through its hierarchical name.
        y = f"y{i + 1}" if container == "module" and i < 3 else f"{at}.y"
        lines.append(f'    $display("{label}: a1=%b a4=%b a70=%h c=%b y=%h", '
                     f"{at}.a1, {at}.a4, {at}.a70, {at}.c, {y});")
        c = "0" if connected else v
        expected.append(f"{label}: a1={v} a4={v * 4} a70={hexval(70, v)} c={c} "
                        f"y={hexval(75, v)}")
    lrm = ["22.9", "23.3.2.1", "23.3.2.2", "23.3.3.3", "23.3.3.5", "28.10"]
    if directive == "resetall":
        lrm.insert(0, "22.3")
    if container == "interface":
        lrm.append("25.4")
    description = (f"unconnected input ports of a {container} under "
                   f"{DIRECTIVE_TEXT[directive]}")
    text = header(name, description, lrm) + before + definition + after + [
        "module top;", *decl, *insts, "  initial begin", "    #1;", *lines, "  end",
        "endmodule"
    ]
    return name, text, expected


# (module name, net kind, directive, the driver inside or None, the value)
RESOLVE = [
    ("weak0_in", "wire", "pull1", "(weak0, weak1) a = 1'b0", "1"),
    ("strong0_in", "wire", "pull1", "a = 1'b0", "0"),
    ("pull0_in", "wire", "pull1", "(pull0, pull1) a = 1'b0", "x"),
    ("weak1_in", "wire", "pull0", "(weak0, weak1) a = 1'b1", "0"),
    ("strong1_in", "wire", "pull0", "a = 1'b1", "1"),
    ("tri0_pull1", "tri0", "pull1", None, "x"),
    ("tri1_pull1", "tri1", "pull1", None, "1"),
    ("tri0_pull0", "tri0", "pull0", None, "0"),
    ("tri1_pull0", "tri1", "pull0", None, "x"),
    ("wand_pull1", "wand", "pull1", "(pull0, pull1) a = 1'b0", "0"),
    ("wor_pull0", "wor", "pull0", "(pull0, pull1) a = 1'b1", "1"),
    ("wand_weak", "wand", "pull1", "(weak0, weak1) a = 1'b0", "1"),
]


def resolve_case():
    name = PREFIX + "resolve"
    text, labels, expected = [], [], []
    for mod, kind, directive, inside, value in RESOLVE:
        text += [f"`unconnected_drive {directive}",
                 f"module {mod}(input {kind} a, output wire y);"]
        if inside is not None:
            text.append(f"  assign {inside};")
        text += ["  assign y = a;", "endmodule", "`nounconnected_drive"]
        labels.append(mod)
        expected.append(f"{mod}={value}")
    top = ["module top;", "  wire " + ", ".join(f"y_{m}" for m in labels) + ";"]
    top += [f"  {m} u_{m}(.y(y_{m}));" for m in labels]
    top += ["  initial begin", "    #1;"]
    top += [f'    $display("{m}=%b", y_{m});' for m in labels]
    top += ["  end", "endmodule"]
    lrm = ["6.6.3", "22.9", "28.10", "28.12.2", "28.12.4", "28.15.1"]
    description = ("the pull on an unconnected input port is resolved with the drivers "
                   "inside the definition and the kind of the net")
    return name, header(name, description, lrm) + text + top, expected


def not_pulled_case():
    name = PREFIX + "not_pulled"
    text = [
        "`unconnected_drive pull1",
        "module leaf(inout wire io, output wire o, input wire a, output wire y);",
        "  assign y = a;",
        "endmodule",
        "module top_ports(input wire t);",
        '  initial #2 $display("port of a top module: t=%b", t);',
        "endmodule",
        "`nounconnected_drive",
        "module after(input wire a);",
        "endmodule",
        "module top;",
        "  wire y;",
        "  leaf u(.a(1'b0), .y(y));",
        "  after w();",
        "  initial begin",
        "    #1;",
        '    $display("inout=%b output=%b connected=%b after the end=%b", u.io, u.o, y, w.a);',
        "  end",
        "endmodule",
    ]
    expected = ["inout=z output=z connected=0 after the end=z", "port of a top module: t=z"]
    lrm = ["22.9", "23.3.3.3"]
    description = ("ports that `unconnected_drive does not pull: inout, output, connected, "
                   "of a top module, declared after `nounconnected_drive")
    return name, header(name, description, lrm) + text, expected


def variable_case():
    name = PREFIX + "variable"
    ports = [("a", "input var logic a,", "x"), ("b", "input var logic [3:0] b,", "xxxx"),
             ("c", "input var bit [3:0] c,", "0000"), ("n", "input wire n", "1")]
    body = ["`unconnected_drive pull1", "module leaf("]
    body += [f"  {decl}" for _, decl, _ in ports]
    body += [");", "endmodule", "`nounconnected_drive", "module top;",
             "  leaf u(" + ", ".join(f".{p}()" for p, _, _ in ports) + ");",
             "  initial begin", "    #1;",
             '    $display("' + " ".join(f"{p}=%b" for p, _, _ in ports) + '", ' +
             ", ".join(f"u.{p}" for p, _, _ in ports) + ");", "  end", "endmodule"]
    expected = [" ".join(f"{p}={v}" for p, _, v in ports)]
    lrm = ["22.9", "23.3.3.2", "23.3.3.3"]
    description = ("variable input ports are not pulled by `unconnected_drive: they keep "
                   "the initial value of their type")
    text = header(name, description, lrm, [f":expected_stderr: @{name}.stderr"]) + body
    # The warning stands at each variable port's name in the declaration.
    stderr = []
    for p, decl, _ in ports[:3]:
        line = text.index(f"  {decl}") + 1
        column = f"  {decl}".rindex(p) + 1
        stderr.append(f"{name}.sv:{line}:{column}: warning: `unconnected_drive does not pull "
                      f"input port '{p}', a variable; it keeps the initial value of its type")
    return name, text, expected, stderr


def files():
    out = {}
    cases = [matrix_case(d, c) for d in DIRECTIVES for c in ("module", "interface")]
    cases += [resolve_case(), not_pulled_case()]
    for name, text, expected in cases:
        out[f"{name}.sv"] = "\n".join(text) + "\n"
        out[f"{name}.expected"] = "\n".join(expected) + "\n"
    name, text, expected, stderr = variable_case()
    out[f"{name}.sv"] = "\n".join(text) + "\n"
    out[f"{name}.expected"] = "\n".join(expected) + "\n"
    out[f"{name}.stderr"] = "\n".join(stderr) + "\n"
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_unconnected_drive_matrix: {path.relative_to(OUT.parent.parent.parent)} "
                      "is out of date; run tools/gen_unconnected_drive_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
