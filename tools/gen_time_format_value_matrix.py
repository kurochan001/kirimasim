"""Generates the matrix tests of %t with signed and wide integral arguments
(TEST_SUITE.md, "Mechanism matrix") in tests/suite/values/.

  tools/gen_time_format_value_matrix.py           # writes the files
  tools/gen_time_format_value_matrix.py --check   # exit 1 if a file differs from what it would write

The rule: SYSTEM_TASKS.md 3.7. %t takes an integral argument as the value
it has: a signed one keeps its sign, a negative one prints with a minus
sign (none when it rounds to zero), and one wider than 64 bits is
converted whole; the caller's time unit scales the value, and the unit
and the digits of $timeformat shift and round it, half away from zero.
The axes: the time scale of the module (the unit equal to the precision,
and 1000 times it: one test each); the argument (int, longint and time,
signed and unsigned vectors of 65 and 100 bits; negative, zero, small and
past 64 bits); $timeformat (the default, a larger unit with digits after
the point, and a smaller unit); and the task ($display and $sformatf).

The expected output comes from the model below, in whole numbers. A
person checks it once for all the tests made from it (TEST_SUITE.md,
"Sampling by people").
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "values"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

# The module: the suffix, the `timescale, log10 of unit / precision.
SCALES = [("unit", "1ns/1ns", 0), ("scaled", "1ns/1ps", 3)]
# The argument: its name, declaration, value.
ARGUMENTS = [
    ("int_negative", "int", "-1", -1),
    ("int_small", "int", "1499", 1499),
    ("int_negative_half", "int", "-1500", -1500),
    ("int_tiny", "int", "-49", -49),
    ("longint_negative", "longint", "-64'sd2", -2),
    ("time_large", "time", "64'hffff_ffff_ffff_ffff", 2**64 - 1),
    ("zero", "int", "0", 0),
    ("signed65", "logic signed [64:0]", "-(65'sd1 << 63)", -(1 << 63)),
    ("unsigned65", "logic [64:0]", "65'd1 << 64", 1 << 64),
    ("signed100", "bit signed [99:0]", "-(100'sd5 << 70)", -(5 << 70)),
    ("unsigned100", "logic [99:0]", "100'd5 << 70", 5 << 70),
]
# $timeformat: its name, the call (None: the default), the unit as a power
# of ten below the precision's (the default prints in the precision), the
# digits after the point, the suffix and the minimum width.
FORMATS = [
    ("default", None, 0, 0, "", 20),
    ("larger", '$timeformat(-6, 2, " us", 8);', 3, 2, " us", 8),
    ("smaller", '$timeformat(-12, 0, "ps", 0);', None, 0, "ps", 0),
]


def render(ticks, k, decimals, suffix, width):
    """ticks * 10^k as a whole number, rounded half away from zero, with
    `decimals` digits after the point."""
    negative, n = ticks < 0, abs(ticks)
    if k >= 0:
        n *= 10 ** k
    else:
        q, r = divmod(n, 10 ** -k)
        n = q + (1 if 2 * r >= 10 ** -k else 0)
    digits = str(n)
    if decimals:
        digits = digits.rjust(decimals + 1, "0")
        digits = digits[:-decimals] + "." + digits[-decimals:]
    if negative and n != 0:
        digits = "-" + digits
    return (digits + suffix).rjust(width)


def files():
    out = {}
    for suffix, scale, shift in SCALES:
        name = f"time_format_value_{suffix}"
        precision = -9 - shift  # the exponent of the precision
        sv = [
            "/*",
            f":name: {name}",
            ":description: %t prints a signed argument with its sign and an argument wider than "
            "64 bits whole, scaled by the time unit and shifted and rounded by $timeformat",
            ":tags: values",
            ":type: simulation",
            ":lrm: 1800-2023 20.4.3 21.2.1.3",
            ":oracle: spec",
            ":spec_check: ai",
            ":fourstate: no",
            ":nondeterministic: no",
            f":generator: gen_time_format_value_matrix.py@{VERSION}",
            f":expected_stdout: @{name}.expected",
            "*/",
            "// Generated by tools/gen_time_format_value_matrix.py; change the generator, not "
            "this file.",
            f"`timescale {scale}",
            "module top;",
        ]
        for arg, decl, literal, _ in ARGUMENTS:
            sv.append(f"  {decl} {arg} = {literal};")
        sv += ["  string s;", "  initial begin"]
        expected = []
        for fname, call, unit_shift, decimals, fsuffix, width in FORMATS:
            if call:
                sv.append(f"    {call}")
            # The exponent of the unit printed: the precision by default.
            unit = precision if call is None else (-6 if fname == "larger" else -12)
            k = precision - unit + decimals
            for arg, _, _, value in ARGUMENTS:
                ticks = value * 10 ** shift
                text = render(ticks, k, decimals, fsuffix, width)
                sv.append(f'    $display("{fname} {arg} display [%t]", {arg});')
                sv.append(f'    s = $sformatf("[%t]", {arg});')
                sv.append(f'    $display("{fname} {arg} sformatf %s", s);')
                expected.append(f"{fname} {arg} display [{text}]")
                expected.append(f"{fname} {arg} sformatf [{text}]")
        sv += ["  end", "endmodule", ""]
        out[f"{name}.sv"] = "\n".join(sv)
        out[f"{name}.expected"] = "\n".join(expected) + "\n"
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_time_format_value_matrix: {path.relative_to(OUT.parent.parent.parent)} "
                      "is out of date; run tools/gen_time_format_value_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
