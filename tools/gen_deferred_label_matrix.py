"""Generate selective pending-report cancellation matrices (16.4.4).

Eighteen sources cross directive, observed/final queue and initial/task/fork
entry. Five isolated periods cancel before registration, after two reports,
between registrations, never, and after settling. The same assertion label
registers both action wrappers. Siblings and an offset process remain controls.
Actions only display; final actions do not write static state in Postponed.
Two further sources cancel a completed, directly labeled initial statement.
"""

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'tests/suite/sched'


def reference(directive):
    result = []
    for phase in range(5):
        time = 10 * (phase + 1)
        reports = [(2, phase * 10 + 3, 2, time, 0)]
        selected = [0] if directive == 'cover' else [0, 1]
        if phase == 1:
            selected = []
        elif phase == 2:
            selected = [k for k in selected if k != 0]
        for k in selected:
            reports.append((0, phase * 10 + k + 1, 1 - k, time,
                            phase * 100 + (7 if phase == 4 else 99)))
        reports += [(3, phase * 10 + 4, 3, time + (phase == 4), 0),
                    (1, phase * 10 + 5, 1, time + 2, phase * 100 + 1099)]
        result += [f'report id={i} value={v} polarity={pol} time={t} live={live}'
                   for i, v, pol, t, live in reports]
        n = phase + 1
        result.append(f'snapshot phase={phase} ev0={n * (1 if directive == "cover" else 2)} '
                      f'ev1={n} ev2={n} ev3={n} tails={n}')
    return '\n'.join(result) + '\n'


def source(directive, queue, container):
    name = f'deferred_label_matrix_{directive}_{queue}_{container}'
    delay = '#0' if queue == 'observed' else 'final'
    lines = ['/*', f':name: {name}',
             ':description: Label disable cancels only pending reports of its assertion, '
             'preserving arguments, siblings, order and settled history',
             ':tags: sched', ':type: simulation',
             ':lrm: 1800-2023 16.4.4 16.4.1 16.4.2 9.6.2 13.5.1',
             ':oracle: spec', ':spec_check: ai', ':fourstate: no', ':nondeterministic: no',
             ':generator: gen_deferred_label_matrix.py@1',
             f':expected_stdout: @{name}.expected', '*/',
             '// Generated by tools/gen_deferred_label_matrix.py; edit the generator.',
             '`timescale 1ns/1ns', f'module {name};',
             "  int ev[4] = '{default: 0};", "  int live[4] = '{default: 0};",
             '  int tails = 0;',
             '  function automatic int capture(input int id, value);',
             '    ev[id]++;', '    return value;', '  endfunction',
             '  function automatic void report(input int id, value, polarity);',
             '    $display("report id=%0d value=%0d polarity=%0d time=%0d live=%0d",',
             '             id, value, polarity, $time, live[id]);', '  endfunction']
    body = ['    for (int phase = 0; phase < 5; phase++) begin : worker',
            '      #10;', '      live[0] = phase * 100 + 7;',
            f'      sibling_before: assert {delay} (1) report(2, capture(2, phase*10+3), 2);',
            '      for (int k = 0; k < 2; k++) begin : issuing',
            '        if (phase == 0 && k == 0) disable target_chk;',
            f'        target_chk: {directive} {delay} (k == 0)',
            '          report(0, capture(0, phase*10+k+1), 1)'
            + (';' if directive == 'cover' else
               '; else report(0, capture(0, phase*10+k+1), 0);'),
            '        if ((phase == 1 && k == 1) || (phase == 2 && k == 0))',
            '          disable target_chk;',
            '        if (phase == 4 && k == 1) begin',
            '          #1;', '          disable target_chk;', '        end', '      end',
            '      live[0] = phase * 100 + 99;',
            f'      sibling_after: assert {delay} (1) report(3, capture(3, phase*10+4), 3);',
            '      tails++;', '    end']
    if container == 'task':
        lines += ['  task automatic issue();', *body, '  endtask', '  initial issue();']
    elif container == 'fork':
        lines += ['  initial begin', '    fork', '      begin', *body,
                  '      end', '    join', '  end']
    else:
        lines += ['  initial begin', *body, '  end']
    # The last worker delay takes one tick. Its last snapshot is still at 53.
    lines += ['  initial begin : control', '    #2;',
              '    for (int phase = 0; phase < 5; phase++) begin : worker',
              '      #10;', '      live[1] = phase*100+1007;',
              f'      target_chk: assert {delay} (1) report(1, capture(1, phase*10+5), 1);',
              '      live[1] = phase*100+1099;', '    end', '  end',
              '  initial begin', '    #3;',
              '    for (int phase = 0; phase < 5; phase++) begin', '      #10;',
              '      $display("snapshot phase=%0d ev0=%0d ev1=%0d ev2=%0d ev3=%0d tails=%0d",',
              '               phase, ev[0], ev[1], ev[2], ev[3], tails);', '    end',
              '    $finish;', '  end', 'endmodule', '']
    return name, '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for directive in ('assert', 'assume', 'cover'):
        for queue in ('observed', 'final'):
            for container in ('initial', 'task', 'fork'):
                name, sv = source(directive, queue, container)
                for suffix, text in [('.sv', sv), ('.expected', reference(directive))]:
                    path = OUT / (name + suffix)
                    if args.check:
                        if not path.is_file() or path.read_text() != text:
                            stale.append(path.relative_to(ROOT).as_posix())
                    else:
                        path.write_text(text)
    for queue in ('observed', 'final'):
        name = f'deferred_label_root_{queue}'
        delay = '#0' if queue == 'observed' else 'final'
        sv = f'''/*
:name: {name}
:description: A completed directly labeled assertion retains cancellable reports without a block activation
:tags: sched
:type: simulation
:lrm: 1800-2023 16.4.4 16.4.1 9.6.2
:oracle: spec
:spec_check: ai
:fourstate: no
:nondeterministic: no
:generator: gen_deferred_label_matrix.py@1
:expected_stdout: @{name}.expected
*/
// Generated by tools/gen_deferred_label_matrix.py; edit the generator.
module {name};
  initial target_chk: assert {delay} (1) $display("cancelled target");
  initial begin
    #0;
    disable target_chk;
  end
  initial sibling: assert {delay} (1) $display("sibling retained");
  initial #1 begin
    $display("completed");
    $finish;
  end
endmodule
'''
        for suffix, text in [('.sv', sv), ('.expected', 'sibling retained\ncompleted\n')]:
            path = OUT / (name + suffix)
            if args.check:
                if not path.is_file() or path.read_text() != text:
                    stale.append(path.relative_to(ROOT).as_posix())
            else:
                path.write_text(text)
    if stale:
        parser.exit(1, 'stale deferred label matrix: ' + ', '.join(stale) + '\n')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
