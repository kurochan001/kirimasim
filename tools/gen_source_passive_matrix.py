"""Original source passive-switch matrix, IEEE 1800-2023 4.9.5/28.8/28.13/28.14.

Oracles enumerate root points and conducting worlds under the approved
mos-switch-proposal contract. No external simulator source/tests are used.
"""
import argparse
import itertools
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / 'tests/suite/nets'
KINDS = ('tran', 'rtran', 'tranif0', 'tranif1', 'rtranif0', 'rtranif1')
LEVELS = (('weak', 3), ('pull', 5), ('strong', 6), ('supply', 7))
LOADS = ((None, 0), ('weak', -3), ('weak', 3), ('pull', -5), ('pull', 5), ('strong', -6), ('strong', 6))


def projection(points):
    lo, hi = min(points), max(points)
    return 'z' if lo == hi == 0 else '0' if hi < 0 else '1' if lo > 0 else 'x'


def root_points(value, rank):
    return (0,) if value == 'z' else (-rank,) if value == '0' else (rank,) if value == '1' else range(-rank, rank+1)


def reduce_point(kind, point):
    ranks = (0, 1, 1, 2, 2, 3, 5, 5)
    magnitude = ranks[abs(point)] if kind.startswith('r') else min(abs(point), 6)
    return magnitude if point >= 0 else -magnitude


def pair_result(kind, value, rank, control, load, reverse):
    conditional = 'if' in kind
    active = '0' if kind.endswith('0') else '1'
    worlds = (False, True) if conditional and control in 'xz' else (not conditional or control == active,)
    outcomes = [[], []]
    for on, point in itertools.product(worlds, root_points(value, rank)):
        carried = reduce_point(kind, point) if on else 0
        background = reduce_point(kind, load) if on else 0
        contributions = ((point, background), (carried, load))
        for node, choices in enumerate(contributions):
            maximum = max(abs(p) for p in choices)
            outcomes[node].extend(p for p in choices if abs(p) == maximum)
    result = tuple(projection(points) for points in outcomes)
    return result[::-1] if reverse else result


def header(name):
    return f'''/*
:name: {name}
:description: Passive switches preserve physical roots, bidirectionality and complete strengths
:tags: nets strength switches
:type: simulation
:lrm: 1800-2023 4.9.5 28.8 28.13 28.14
:oracle: spec
:spec_check: ai
:fourstate: yes
:nondeterministic: no
:generator: gen_source_passive_matrix.py@1
:top_module: top
:expected_stdout: @{name}.expected
*/
// Generated by tools/gen_source_passive_matrix.py; edit the generator.
`timescale 1ns/1ns
'''


def scalar(kind, level, home):
    strength, rank = level
    name = f'source_passive_{kind}_{strength}_{home}'
    decl = 'logic data,control;\n'
    gates = ''
    probes = []
    for i, ((load_name, load), reverse) in enumerate(itertools.product(LOADS, (False, True))):
        decl += f'wire a{i},b{i}; assign ({strength}1,{strength}0) '+(f'b{i}' if reverse else f'a{i}')+'=data;\n'
        if load_name:
            decl += f'assign ({load_name}1,{load_name}0) '+(f'a{i}' if reverse else f'b{i}')+f"=1'b{int(load > 0)};\n"
        prefix = 'bus.' if home == 'interface' else ''
        gates += f'{kind} m{i}({prefix}a{i},{prefix}b{i}'+(','+prefix+'control' if 'if' in kind else '')+');\n'
        probes.extend((f'a{i}', f'b{i}'))
    body = ''
    expected = ''
    for control, data in itertools.product('01xz' if 'if' in kind else '1', '01xz'):
        body += f"control=1'b{control};data=1'b{data};#1;\n"
        body += '$display("'+' '.join('%b' for _ in probes)+'",'+','.join(probes)+');\n'
        values = []
        for (_, load), reverse in itertools.product(LOADS, (False, True)):
            values.extend(pair_result(kind, data, rank, control, load, reverse))
        expected += ' '.join(values)+'\n'
    inner = decl+gates+'initial begin\n'+body+'end\n'
    if home == 'interface':
        source = 'interface channel_if;\n'+decl+'initial begin\n'+body+'end endinterface\nmodule top;channel_if bus();\n'+gates+'endmodule\n'
    elif home == 'generate':
        source = 'module top; if(1) begin:channels\n'+inner+'end endmodule\n'
    else:
        source = 'module top;\n'+inner+'endmodule\n'
    return name, source, expected


def arrays(kind, width, vector_control=False):
    name = f'source_passive_array_{kind}_{width}'+('_controls' if vector_control else '')
    pattern = ''.join('10xz'[bit % 4] for bit in range(width))
    control = "1'b0" if kind.endswith('0') else "1'b1"
    control_pattern = ''.join('10xz'[bit % 4] for bit in range(width))
    if vector_control: control = f"{width}'b{control_pattern}"
    source = f'''module leaf(inout wire [{width-1}:0] a,b);
{kind} device[{width-1}:0](a,b'''+(','+control if 'if' in kind else '')+'''); endmodule
module top;
'''+f'''logic [{width-1}:0] data; wire [{width-1}:0] a,b;
assign (supply1,supply0) a=data; leaf port(a,b);
initial begin data={width}'b{pattern};#1;$display("%b %b",a,b);data='z;#1;$display("%b %b",a,b);end
endmodule
'''
    output = pattern
    if vector_control:
        active = '0' if kind.endswith('0') else '1'
        output = ''.join(value if ctl == active else 'z' if ctl in '01' or value == 'z' else 'x'
                         for value,ctl in zip(pattern,control_pattern))
    return name, source, pattern+' '+output+'\n'+'z'*width+' '+'z'*width+'\n'


def special_cases():
    for kind in ('bufif0','bufif1','notif0','notif1'):
        name = 'source_passive_highz_root_'+kind
        invert = kind.startswith('not')
        off = '1' if kind.endswith('0') else '0'
        source = f"module top;logic data,control;wire a,b;{kind} gate(a,data,control);tran path(a,b);assign(weak1,weak0) b="+('~data' if invert else 'data')+f";initial begin data=0;control='x;#1;$display(\"%b%b\",a,b);data=1;#1;$display(\"%b%b\",a,b);control='z;#1;$display(\"%b%b\",a,b);control=1'b{off};#1;$display(\"%b%b\",a,b);end endmodule\n"
        yield name, source, '11\n00\n00\n00\n' if invert else '00\n11\n11\n11\n'
    yield 'source_passive_rootless_ring', '''module top;logic enable;wire a,b,c;
assign a=enable?1'b1:1'bz;tran t0(a,b),t1(b,c),t2(c,a);
initial begin enable=1;#1;$display("%b%b%b",a,b,c);enable=0;#1;$display("%b%b%b",a,b,c);enable=1;#1;$display("%b%b%b",a,b,c);end endmodule
''', '111\nzzz\n111\n'
    yield 'source_passive_correlated_worlds', '''module top;wire a,b;
assign (strong1,strong0) a=1'b1;assign (pull1,pull0) a=1'b0;
assign (weak1,weak0) b=1'b1;tranif1 t(a,b,1'bx);
initial begin #1;$display("%b%b",a,b);end endmodule
''', '11\n'
    yield 'source_passive_mixed_wired_kind', '''module top;wire a,c;wand b;
assign a=1'b1;assign c=1'b0;tran t0(a,b),t1(b,c);
initial begin #1;$display("%b%b%b",a,b,c);end endmodule
''', 'x0x\n'
    yield 'source_passive_control_strength_sensitivity', '''module top;
logic level=0,flag=1;integer calls=0,changes=0,before_calls,before_changes;
wire a,b,q;assign (weak1,weak0) a=1'b1;assign a=level?1'b1:1'bz;
assign (pull1,pull0) q=1'b0;
function automatic logic choose(input logic c);calls++;return c;endfunction
tranif1 t(a,b,choose(flag));nmos m(q,b,1'b1);
always @(a) changes++;
initial begin #2;$display("%b%b%b",a,b,q);before_calls=calls;before_changes=changes;
level=1;#2;$display("%b%b%b %0d %0d",a,b,q,calls-before_calls,changes-before_changes);end endmodule
''', '110\n111 0 0\n'
    for kind in ('tranif0','tranif1','rtranif0','rtranif1'):
        name = f'source_passive_delayed_conduction_{kind}'
        on, off = ('0','1') if kind.endswith('0') else ('1','0')
        source = f'''module top;logic data=1,control=1'b{off};wire a,b;assign a=data;
{kind} #(8,6) t(a,b,control);
initial begin #2;control=1'b{on};#2;control=1'b{off};#2;control=1'b{on};
#5;$display("%b",b);#4;$display("%b",b);control=1'b{off};
#2;data=0;#2;$display("%b",b);#3;$display("%b",b);
control=1'bx;#7;$display("%b",b);end endmodule
'''
        yield name, source, 'z\n1\n0\nz\nx\n'
    for shape in ('ascending','nested','unpacked'):
        name = 'source_passive_static_terminal_'+shape
        decl, left, right = ('wire [0:8] a,b;', 'a[0]', 'b[8]') if shape == 'ascending' else (
            ('wire [1:0][0:8] a,b;', 'a[1][0]', 'b[0][8]') if shape == 'nested' else
            ('wire [8:0] a[2:1],b[4:5];', 'a[2][8]', 'b[5][0]'))
        yield name, 'module top;'+decl+f"assign {left}=1'b1;tran t({left},{right});initial begin #1;$display(\"%b%b\",{left},{right});end endmodule\n", '11\n'


def connection_mappings(kind):
    control = '10xz11001'
    active = '0' if kind.endswith('0') else '1'
    expected = ''.join('1' if c == active else 'z' if c in '01' else 'x' for c in control)
    for shape in ('ascending', 'rank2', 'concat'):
        name = f'source_passive_mapping_{kind}_{shape}'
        dims = '[0:8]' if shape == 'ascending' else '[2:0][0:2]' if shape == 'rank2' else '[8:0]'
        decl = "wire [8:0] a,b;assign a=9'b111111111;"
        left,right,observed = 'a','b','b'
        if shape == 'concat':
            decl = "wire [4:0] ah,bl;wire[3:0] al,bh;assign {ah,al}=9'b111111111;"
            left,right,observed = '{ah,al}','{bh,bl}','{bh,bl}'
        source = f"module top;{decl}{kind} t{dims}({left},{right},9'b{control});initial begin #1;$display(\"%b\",{observed});end endmodule\n"
        yield name, source, expected+'\n'
    name = f'source_passive_scalar_broadcast_{kind}'
    on = '0' if kind.endswith('0') else '1'
    off = '1' if on == '0' else '0'
    source = f"module top;logic[8:0] control;wire a,b;assign a=1'b1;{kind} t[8:0](a,b,control);initial begin control='b{off*8+on};#1;$display(\"%b%b\",a,b);control='b{off*9};#1;$display(\"%b%b\",a,b);control='x;#1;$display(\"%b%b\",a,b);end endmodule\n"
    yield name, source, '11\n1z\n1x\n'


def cases():
    for kind, level, home in itertools.product(KINDS, LEVELS, ('module','generate','interface')):
        yield scalar(kind, level, home)
    for kind, width in itertools.product(KINDS, (1,9,65,129)):
        yield arrays(kind, width)
    for kind, width in itertools.product(KINDS[2:], (1,9,65,129)):
        yield arrays(kind, width, True)
    for kind in KINDS[2:]:
        yield from connection_mappings(kind)
    yield from special_cases()


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    files={}
    for name,source,expected in cases():
        files[OUT/(name+'.sv')]=header(name)+source
        files[OUT/(name+'.expected')]=expected
    bad=[]
    for path,content in files.items():
        if args.check:
            if not path.exists() or path.read_text()!=content: bad.append(str(path.relative_to(OUT)))
        else: path.write_text(content)
    extras=set(OUT.glob('source_passive_*'))-set(files)
    if extras: bad.extend(str(p.relative_to(OUT)) for p in extras)
    if bad:
        print('source passive matrix differs: '+', '.join(sorted(bad)))
        return 1
    print(f'{len(files)//2} original source passive designs '+('checked' if args.check else 'written'))
    return 0


if __name__=='__main__':
    raise SystemExit(main())
