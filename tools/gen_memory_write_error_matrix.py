"""Generates the matrix tests of $writememb and $writememh to a file that
cannot be opened (TEST_SUITE.md, "Mechanism matrix") in tests/suite/proc/.

  tools/gen_memory_write_error_matrix.py           # writes the files
  tools/gen_memory_write_error_matrix.py --check   # exit 1 if a file differs from what it would write

The rule (SYSTEM_TASKS.md 7.2; 21.5 does not say): a file that cannot be
opened for writing, or written whole, is a run-time error of the design.
The run ends there with code 2; final procedures still run.

The axes: the task and the container of the call (an initial procedure, a
task, a function, a fork branch, a task in a generate block). The file is
in a directory that does not exist, which cannot be opened on any system.
A write that fails after the file opened (a full disk) has no test: no
file that does so exists on every system the tests run on.

The expected outputs follow from the rule above, without reading
kirimasim's code.
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "proc"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

TASKS = ["$writememb", "$writememh"]
CONTAINERS = ["initial", "task", "function", "fork", "generate"]
FILE = "no_such_directory/w.mem"


def test(task, container):
    name = f"memory_write_error_{task[1:]}_{container}"
    lines = ["/*", f":name: {name}",
             f":description: {task} to a file that cannot be opened is a run-time error that "
             f"ends the run, called from {'an' if container[0] in 'aeiou' else 'a'} {container}",
             ":tags: proc", ":type: simulation", ":lrm: 1800-2023 21.5", ":oracle: spec",
             ":spec_check: ai", ":fourstate: yes", ":nondeterministic: no",
             f":generator: gen_memory_write_error_matrix.py@{VERSION}", ":top_module: top",
             f":expected_stdout: @{name}.expected", ":expected_exit: 2",
             f":expected_stderr: @{name}.stderr", "*/",
             "// Generated by tools/gen_memory_write_error_matrix.py; change the generator, not "
             "this file.", "`timescale 1ns/1ns", "module top;", "  logic [7:0] m [0:1];"]
    call = f'{task}("{FILE}", m);'
    if container == "task":
        lines += ["  task dump;", f"    {call}"]
        at = len(lines)
        lines += ["  endtask"]
        start = "dump;"
    elif container == "function":
        lines += ["  function void dump();", f"    {call}"]
        at = len(lines)
        lines += ["  endfunction"]
        start = "dump();"
    elif container == "generate":
        lines += ["  if (1) begin : g", "    task dump;", f"      {call}"]
        at = len(lines)
        lines += ["    endtask", "  end"]
        start = "g.dump;"
    lines += ["  initial begin", "    m[0] = 8'h11;", "    m[1] = 8'h22;", '    $display("start");']
    if container == "fork":
        lines += ["    fork", f"      #1 {call}"]
        at = len(lines)
        lines += ["    join"]
    elif container == "initial":
        lines += [f"    #1 {call}"]
        at = len(lines)
    else:
        lines += [f"    #1 {start}"]
    lines += ['    $display("not reached");', "  end",
              '  final $display("final %h %h", m[0], m[1]);', "endmodule"]
    stderr = [f'{name}.sv:{at}: error: {task}: cannot open "{FILE}" for writing [top @ 1ns]']
    return name, lines, ["start", "final 11 22"], stderr


def files():
    out = {}
    for task in TASKS:
        for container in CONTAINERS:
            name, lines, stdout, stderr = test(task, container)
            out[f"{name}.sv"] = "\n".join(lines) + "\n"
            out[f"{name}.expected"] = "\n".join(stdout) + "\n"
            out[f"{name}.stderr"] = "".join(f"{e}\n" for e in stderr)
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print("gen_memory_write_error_matrix: "
                      f"{path.relative_to(OUT.parent.parent.parent)} is out of date; run "
                      "tools/gen_memory_write_error_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
