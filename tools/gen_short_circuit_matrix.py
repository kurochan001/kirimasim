"""Generates the short-circuit matrix test of TEST_SUITE.md ("Mechanism
matrix") in tests/suite/values/.

  tools/gen_short_circuit_matrix.py           # writes the files
  tools/gen_short_circuit_matrix.py --check   # exit 1 if a file differs from what it would write

The rule: VALUE_SEMANTICS.md 3.1 and 3.9, and 11.3.5, 11.4.7 and 11.4.11
of the standard. &&, || and -> skip their right operand when the left one
decides, and ?: evaluates only the side its known condition picks; the
operand skipped does not run, so the function it calls does not count.
The axes: the operator and the side it skips (each with a control that
evaluates the same operand once), the kind of expression around the call
in that operand (a call alone, an operator, inside, an assignment
pattern, a streaming concatenation, a concatenation, a nested ?: and an
argument of a pure system function), and the container of the statement
(a module's initial, an automatic task, a static class method, a fork
branch and a function's return).

A person checks the expected output once for all the tests made from it
(TEST_SUITE.md, "Sampling by people").
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "values"
NAME = "short_circuit_matrix"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

# The operand: its SystemVerilog text around f(), which counts its calls
# and returns 4'd1, and its value as 8 bits.
OPERANDS = [
    ("call", "f()", 1),
    ("operator", "(f() + 4'd1)", 2),
    ("inside", "(f() inside {1, 2})", 1),
    ("pattern", "pair_t'{f(), 4'h2}", 0x12),
    ("streaming", "pair_t'({<<4{f(), 4'h2}})", 0x21),
    ("concatenation", "{f(), 4'h2}", 0x12),
    ("conditional", "(hi ? f() : 4'd0)", 1),
    ("system", '$sformatf("%0d", f()).len()', 1),
]

# The form: its name, the expression with X for the operand, whether the
# operand is skipped, and the value of r: a number, or None for the
# operand's own value, or "bool" for its truth.
FORMS = [
    ("and-skip", "lo && X", True, 0),
    ("and-eval", "hi && X", False, "bool"),
    ("or-skip", "hi || X", True, 1),
    ("or-eval", "lo || X", False, "bool"),
    ("implies-skip", "lo -> X", True, 1),
    ("implies-eval", "hi -> X", False, "bool"),
    ("then-skip", "lo ? X : 8'd7", True, 7),
    ("then-eval", "hi ? X : 8'd7", False, None),
    ("else-skip", "hi ? 8'd7 : X", True, 7),
    ("else-eval", "lo ? 8'd7 : X", False, None),
]

CONTAINERS = ["initial", "task", "method", "fork", "function"]


def cases():
    for operand, text, value in OPERANDS:
        for form, shape, skipped, result in FORMS:
            r = value if result is None else (1 if value else 0) if result == "bool" else result
            yield f"{operand} {form}", shape.replace("X", text), r, 0 if skipped else 1


def files():
    sv = [
        "/*",
        f":name: {NAME}",
        ":description: &&, || and -> skip their right operand and ?: the side its condition "
        "does not pick, whatever expression holds the call and whatever container holds the "
        "statement",
        ":tags: values",
        ":type: simulation",
        ":lrm: 1800-2023 11.3.5 11.4.7 11.4.11 11.4.13 11.4.14",
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: no",
        ":nondeterministic: no",
        f":generator: gen_short_circuit_matrix.py@{VERSION}",
        f":expected_stdout: @{NAME}.expected",
        "*/",
        "// Generated by tools/gen_short_circuit_matrix.py; change the generator, not this file.",
        "module top;",
        "  typedef struct packed { logic [3:0] hi, lo; } pair_t;",
        "  int n;",
        "  logic lo, hi;",
        "  logic [7:0] r;",
        "  function automatic logic [3:0] f();",
        "    n++;",
        "    return 4'd1;",
        "  endfunction",
    ]
    body = {c: [] for c in CONTAINERS}
    functions, expected = [], []
    for k, (label, expr, r, n) in enumerate(cases()):
        for c in CONTAINERS:
            show = f'$display("{c} {label} r=%0d n=%0d", r, n);'
            if c == "function":
                functions += [f"  function automatic logic [7:0] fn{k}();",
                              f"    return {expr};",
                              "  endfunction"]
                body[c] += [f"    n = 0; r = fn{k}(); {show}"]
            elif c == "fork":
                body[c] += [f"    fork begin n = 0; r = {expr}; {show} end join"]
            else:
                body[c] += [f"    n = 0; r = {expr}; {show}"]
            expected.append(f"{c} {label} r={r} n={n}")
    # The output lists every case of one container before the next.
    expected.sort(key=lambda line: CONTAINERS.index(line.split(" ", 1)[0]))
    sv += functions
    sv += ["  task automatic run_task();"] + body["task"] + ["  endtask"]
    sv += ["  class K;", "    static function void run();"]
    sv += ["  " + line for line in body["method"]]
    sv += ["    endfunction", "  endclass"]
    sv += ["  initial begin", "    lo = 0;", "    hi = 1;"]
    sv += body["initial"]
    sv += ["    run_task();", "    K::run();"]
    sv += body["fork"] + body["function"]
    sv += ["  end", "endmodule", ""]
    return {f"{NAME}.sv": "\n".join(sv), f"{NAME}.expected": "\n".join(expected) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_short_circuit_matrix: {path.relative_to(OUT.parent.parent.parent)} is "
                      "out of date; run tools/gen_short_circuit_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
