"""Generates the matrix tests of the largest width and precision of a
format (TEST_SUITE.md, "Mechanism matrix") in tests/suite/values/.

  tools/gen_format_limit_matrix.py           # writes the files
  tools/gen_format_limit_matrix.py --check   # exit 1 if a file differs from what it would write

The rule: SYSTEM_TASKS.md 3.3 (21.2.1.2 of the standard sets no largest
width). A written width or precision over 100000 is not taken: a format
written in the source is an error where it is compiled, at the format,
and the design does not run; the largest ones that are taken print.

The axes: the field (a width, a precision), the conversion (%d, %h, %s
and %t for a width; %f, %e and %g for a precision), the task ($display,
$write, $sformatf, $strobe), and the container (an initial procedure, a
function). One test per rejected format, as one error ends the
compilation; one test prints the fields of 100000, the largest taken;
and two give the format in a variable, where the error is a run-time
error of the design at the call that uses the format.

The expected errors and output are written from the rule above, without
reading kirimasim's code.
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "values"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

# (the field's kind, the conversion, the value printed).
WIDTHS = [("d", "7"), ("h", "8'h3c"), ("s", '"ab"'), ("t", "$time")]
PRECISIONS = [("f", "7.5"), ("e", "7.5"), ("g", "7.5")]
TASKS = ["$display", "$write", "$sformatf", "$strobe"]
CONTAINERS = ["initial", "function"]


def header(name, description, extra):
    return ["/*", f":name: {name}", f":description: {description}", ":tags: values",
            f":type: {'elaboration' if 'should_fail' in extra[0] else 'simulation'}",
            ":lrm: 1800-2023 21.2.1.2", ":oracle: spec", ":spec_check: ai", ":fourstate: no",
            ":nondeterministic: no", f":generator: gen_format_limit_matrix.py@{VERSION}",
            ":top_module: top"] + extra + [
                "*/",
                "// Generated by tools/gen_format_limit_matrix.py; change the generator, not "
                "this file.", "`timescale 1ns/1ns", "module top;", "  string s;"]


def rejected(kind, conv, value, task, container):
    name = f"format_limit_{kind}_{conv}_{task[1:]}_{container}"
    spec = f"%100001{conv}" if kind == "width" else f"%.100001{conv}"
    call = (f's = $sformatf("{spec}", {value});' if task == "$sformatf"
            else f'{task}("{spec}", {value});')
    indent = "    "
    column = len(indent) + call.index('"') + 1
    why = f"a format has a {kind} over 100000"
    lines = header(name, f"a {kind} over 100000 in a format of {task} is an error at the format, "
                         f"in {'an' if container == 'initial' else 'a'} {container}",
                   [f":should_fail_because: {why}", ":expected_error: LINE"])
    if container == "function":
        lines += ["  function void show();"]
    else:
        lines += ["  initial begin"]
    lines.append(indent + call)
    at = len(lines)
    lines += ["  endfunction", "  initial show();"] if container == "function" else ["  end"]
    lines += ["endmodule"]
    text = "\n".join(lines) + "\n"
    return name, text.replace(":expected_error: LINE",
                              f":expected_error: {at}:{column}: error: format {kind} over 100000")


def largest():
    name = "format_limit_largest"
    lines = header(name, "a width and a precision of 100000, the largest taken, print in full",
                   [f":expected_stdout: @{name}.expected"])
    lines += ["  initial begin",
              '    s = $sformatf("%100000d", 7);',
              '    $display("width: %0d %s", s.len(), s.substr(s.len() - 2, s.len() - 1));',
              '    s = $sformatf("%.100000f", 0.5);',
              '    $display("precision: %0d %s", s.len(), s.substr(0, 3));',
              "  end", "endmodule"]
    # 0.5 with 100000 digits after the point: "0." and the digits.
    return name, "\n".join(lines) + "\n", "width: 100000  7\nprecision: 100002 0.50\n"


def at_run_time(kind):
    # A format held in a variable is read when it is used (3.13): the
    # error is a run-time error of the design, which ends the run.
    name = f"format_limit_{kind}_run_time"
    spec = "%100001d" if kind == "width" else "%.100001f"
    lines = header(name, f"a {kind} over 100000 in a format made at run time is a run-time "
                         "error where the format is used",
                   [f":expected_stdout: @{name}.expected", ":expected_exit: 2",
                    f":expected_stderr: @{name}.stderr"])
    lines += ["  string f;", "  initial begin", f'    f = "{spec}";', '    $display("before");',
              f"    s = $sformatf(f, {'7' if kind == 'width' else '7.5'});"]
    at = len(lines)
    lines += ['    $display("not reached");', "  end", "endmodule"]
    stderr = (f"{name}.sv:{at}: error: string format: unsupported: the format {kind} is too "
              "large (not implemented yet) [top @ 0ns]\n")
    return name, "\n".join(lines) + "\n", "before\n", stderr


def files():
    out = {}
    for kind in ("width", "precision"):
        name, text, expected, stderr = at_run_time(kind)
        out[f"{name}.sv"] = text
        out[f"{name}.expected"] = expected
        out[f"{name}.stderr"] = stderr
    n = 0
    for kind, cells in (("width", WIDTHS), ("precision", PRECISIONS)):
        for conv, value in cells:
            # Each conversion meets every task and container in turn.
            for k in range(2):
                task = TASKS[(n + k) % len(TASKS)]
                container = CONTAINERS[(n + k) % len(CONTAINERS)]
                name, text = rejected(kind, conv, value, task, container)
                out[f"{name}.sv"] = text
            n += 1
    name, text, expected = largest()
    out[f"{name}.sv"] = text
    out[f"{name}.expected"] = expected
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_format_limit_matrix: {path.relative_to(OUT.parent.parent.parent)} is "
                      "out of date; run tools/gen_format_limit_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
