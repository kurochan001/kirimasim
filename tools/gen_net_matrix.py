"""Generates the net matrix tests of TEST_SUITE.md ("Net matrix") in
tests/suite/nets/.

  tools/gen_net_matrix.py           # writes the files
  tools/gen_net_matrix.py --check   # exit 1 if a file differs from what it would write

The axes so far: every kind of net (6.6.1 to 6.6.6) with no driver, and the
kinds whose value with one driver is the driver's value (wire, tri, uwire)
with one continuous driver of each value 0, 1, x and z. The driver is an
assign statement, a net declaration assignment or an output port. Several
drivers, drive strengths and the kinds that resolve even one driver against
their own pull or supply are in tools/gen_resolution_matrix.py
(VALUE_SEMANTICS.md 5).

The expected outputs follow from the rule tables below. A person checks the
tables against the standard once for all the tests made from them
(TEST_SUITE.md, "Sampling by people").
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "nets"
# The version of the rule tables below (TEST_SUITE.md, :generator:). Raise
# it whenever a table changes.
VERSION = 1

# The value of a net that nothing drives: z (6.7.1); tri0 and tri1 have
# their pull (6.6.5); supply0 models ground and supply1 power (28.15.3).
UNDRIVEN = {
    "wire": "z", "tri": "z", "wand": "z", "triand": "z", "wor": "z", "trior": "z",
    "tri0": "0", "tri1": "1", "supply0": "0", "supply1": "1", "uwire": "z",
}

# Kinds whose value with exactly one driver is the driver's value, z
# included (6.6.1, table 6-2 with one side z; 6.6.2).
ONE_DRIVER = ["wire", "tri", "uwire"]
VALUES = ["0", "1", "x", "z"]
VECTOR = "01xz"  # a 4-bit value with every bit value


def header(name: str, description: str, lrm: str) -> str:
    return (f"/*\n:name: {name}\n:description: {description}\n:tags: nets\n:type: simulation\n"
            f":lrm: 1800-2023 {lrm}\n:oracle: spec iverilog@13.0\n:spec_check: ai\n"
            f":fourstate: yes\n:nondeterministic: no\n:generator: gen_net_matrix.py@{VERSION}\n"
            f":expected_stdout: @{name}.expected\n*/\n"
            "// Generated by tools/gen_net_matrix.py; change the generator, not this file.\n")


def undriven() -> tuple[str, str]:
    name = "net_undriven"
    sv = header(name, "The value of every kind of net that nothing drives, scalar and vector",
                "6.7.1 6.6.5 28.15.3")
    sv += "module top;\n"
    for k in UNDRIVEN:
        sv += f"  {k} s_{k};\n  {k} [3:0] v_{k};\n"
    sv += "  initial begin\n    #1;\n"
    for k in UNDRIVEN:
        sv += f'    $display("{k} %b %b", s_{k}, v_{k});\n'
    sv += "  end\nendmodule\n"
    exp = "".join(f"{k} {v} {v * 4}\n" for k, v in UNDRIVEN.items())
    return sv, exp


def one_driver(form: str) -> tuple[str, str]:
    name = f"net_one_driver_{form}"
    what = {"assign": "an assign statement", "decl": "a net declaration assignment",
            "port": "an output port"}[form]
    lrm = {"assign": "10.3.2 6.6.1 6.6.2", "decl": "10.3.1 6.6.1 6.6.2",
           "port": "23.3.3 4.9.6 6.6.1 6.6.2"}[form]
    sv = header(name, f"wire, tri and uwire with one driver, {what}, take each value it drives",
                lrm)
    if form == "port":
        sv += ("module drv (input logic s, input logic [3:0] v, output wire os, "
               "output wire [3:0] ov);\n  assign os = s;\n  assign ov = v;\nendmodule\n")
    sv += "module top;\n  logic s;\n  logic [3:0] v;\n"
    for k in ONE_DRIVER:
        if form == "decl":
            sv += f"  {k} s_{k} = s;\n  {k} [3:0] v_{k} = v;\n"
        else:
            sv += f"  {k} s_{k};\n  {k} [3:0] v_{k};\n"
    for k in ONE_DRIVER:
        if form == "assign":
            sv += f"  assign s_{k} = s;\n  assign v_{k} = v;\n"
        elif form == "port":
            sv += f"  drv d_{k} (.s(s), .v(v), .os(s_{k}), .ov(v_{k}));\n"
    sv += "  initial begin\n"
    fmt = " ".join(f"{k}=%b" for k in ONE_DRIVER)
    args = ", ".join(f"s_{k}" for k in ONE_DRIVER)
    vargs = ", ".join(f"v_{k}" for k in ONE_DRIVER)
    exp = ""
    for val in VALUES:
        sv += f"    s = 1'b{val};\n    #1 $display(\"s=%b {fmt}\", s, {args});\n"
        exp += f"s={val} " + " ".join(f"{k}={val}" for k in ONE_DRIVER) + "\n"
    sv += f"    v = 4'b{VECTOR};\n    #1 $display(\"v=%b {fmt}\", v, {vargs});\n"
    exp += f"v={VECTOR} " + " ".join(f"{k}={VECTOR}" for k in ONE_DRIVER) + "\n"
    sv += "  end\nendmodule\n"
    return sv, exp


def files() -> dict[str, str]:
    out = {}
    for name, (sv, exp) in [("net_undriven", undriven())] + [
            (f"net_one_driver_{f}", one_driver(f)) for f in ("assign", "decl", "port")]:
        out[f"{name}.sv"] = sv
        out[f"{name}.expected"] = exp
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_net_matrix: {path.relative_to(OUT.parent.parent.parent)} is out of "
                      "date; run tools/gen_net_matrix.py", file=sys.stderr)
                bad += 1
        else:
            OUT.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
