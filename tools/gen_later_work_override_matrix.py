"""Generates the matrix tests of functions that schedule work to run after
they return, called from the callers SCHEDULER_SPEC.md 6.5 added on
2026-10-20, of TEST_SUITE.md ("Mechanism matrix"): a design whose calls
are all errors, in tests/cli/ (run_cli_tests.py compares its error and
note lines), and simulation tests, in tests/suite/proc/.

  tools/gen_later_work_override_matrix.py           # writes the files
  tools/gen_later_work_override_matrix.py --check   # exit 1 if a file differs from what it would write

The right side of a procedural assign or force is evaluated again
whenever what it reads changes, by the statement's own override process,
not by the thread that ran the statement (10.6.1, 10.6.2). A function
there that makes a nonblocking assignment, a nonblocking trigger ->> or
a fork ... join_none, or that calls a function that does, is an error at
the call, with a note at the statement, and exit code 2, as from the
callers of tools/gen_later_work_matrix.py (13.4.4, SCHEDULER_SPEC.md
6.5). A blocking ->, $strobe and a deferred assertion do not count there
either.

The arguments of $strobe and $monitor and the action of a final deferred
assertion run in the Postponed region, where each of the three
statements is a run-time error (4.4.2.9, SCHEDULER_SPEC.md 2.2): front
does not check them again (6.5).

The axes: for the errors, the place of the statement (initial, always, a
task called from initial, a fork branch), the form (assign, force of a
variable, force of a net), the statement (<=, ->>, fork ... join_none)
and the depth (the function itself, or a function that calls it); for
the right sides that run, the statement that does not count (->,
$strobe, a deferred assertion) and the form (assign, force); for the
Postponed region, the statement and the caller ($strobe, $monitor,
assert final).

The expected outputs follow from the rules above, computed below.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CLI = ROOT / "tests" / "cli"
SUITE = ROOT / "tests" / "suite" / "proc"
NAME = "later_work_override"
PREFIX = "later_work_"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1
ERROR = ("'{f}' schedules work that runs after it returns, so it can be called only from an "
         "initial or always procedure, not from the right side of a procedural assign or force")
POSTPONED = "a write or an event in the Postponed region [top @ 1ns]"

# The statements that count: (name, the lines of the function's body
# before its return, what the note calls it, the text the note points at)
COUNTED = [
    ("nba", ["q <= v;"], "a nonblocking assignment", "q <= v;"),
    ("trigger", ["->> ev;"], "a nonblocking event trigger", "->> ev;"),
    ("fork", ["fork", "  $display(\"forked\");", "join_none"], "a fork with join_none", "fork"),
]
# The places of the statement: (name, the items of top with {S} for it)
PLACES = [
    ("initial", ["initial {S}"]),
    ("always", ["always @(a) {S}"]),
    ("task", ["task automatic tk_{I}();", "  {S}", "endtask", "initial tk_{I}();"]),
    ("fork", ["initial fork", "  {S}", "join"]),
]
# The forms: (name, the statement with {C} for the call)
FORMS = [
    ("assign", "assign t = {C};"),
    ("force", "force t = {C};"),
    ("force_net", "force tn = {C};"),
]


def cli_files():
    """The design whose calls are all errors, and its error and note lines."""
    lines = [f"// Generated by tools/gen_later_work_override_matrix.py (version {VERSION}); "
             "do not edit.",
             "module top;", "  logic a = 1'b0;", "  logic q = 1'b0;", "  logic t;", "  wire tn;",
             "  event ev;"]
    notes = {}
    for name, body, what, text in COUNTED:
        lines.append(f"  function automatic logic f_{name}(logic v);")
        for x in body:
            if x == text:
                notes[name] = (len(lines) + 1, 5, f"{what} in 'f_{name}'")
            lines.append(f"    {x}")
        lines += ["    return v;", "  endfunction"]
    for name, _, _, _ in COUNTED:
        lines += [f"  function automatic logic g_{name}(logic v);",
                  f"    return f_{name}(v);", "  endfunction"]
    file = f"{NAME}.sv"
    stderr = []
    for place, items in PLACES:
        for form, statement in FORMS:
            for depth in ("f", "g"):
                for name, _, _, _ in COUNTED:
                    f = f"{depth}_{name}"
                    s = statement.replace("{C}", f"{f}(a)")
                    for x in items:
                        x = "  " + x.replace("{S}", s).replace("{I}", f"{form}_{f}")
                        if s in x:
                            column = x.index(f"{f}(") + 1
                            stderr.append(f"{file}:{len(lines) + 1}:{column}: error: "
                                          + ERROR.format(f=f))
                            line, col, what = notes[name]
                            stderr.append(f"{file}:{line}:{col}: note: {what}")
                        lines.append(x)
    lines.append("endmodule")
    return {CLI / file: "\n".join(lines) + "\n", CLI / f"{NAME}.stderr": "\n".join(stderr) + "\n"}


def header(name, description, lrm, error):
    lines = [
        "/*",
        f":name: {name}",
        f":description: {description}",
        ":tags: proc function",
        ":type: simulation",
        ":lrm: 1800-2023 " + " ".join(lrm),
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: no",
        ":nondeterministic: no",
        f":generator: gen_later_work_override_matrix.py@{VERSION}",
        ":issue: 13",
        ":top_module: top",
        f":expected_stdout: @{name}.expected",
    ]
    if error:
        lines += [":expected_exit: 2", f":expected_stderr: @{name}.stderr"]
    return lines + [
        "*/",
        "// Generated by tools/gen_later_work_override_matrix.py; change the generator, not this "
        "file.",
        "`timescale 1ns/1ns",
    ]


# The statements that do not count: (name, the function's body before its
# return, what the description calls it)
UNCOUNTED = [
    ("blocking_trigger", ["-> ev;"], "a blocking ->"),
    ("strobe", ["$strobe(\"strobe at %0t\", $time);"], "a $strobe"),
    ("deferred", ["assert #0 (v == 1'b0) else $display(\"deferred failed at %0t\", $time);"],
     "a deferred assertion"),
]


def uncounted_case(statement, form):
    sname, body, what = statement
    name = f"{PREFIX}override_{sname}_{form}"
    lines = ["module top;", "  logic a = 1'b0;", "  logic t;", "  event ev;",
             "  function automatic logic f(logic v);"]
    lines += [f"    {x}" for x in body] + ["    return v;", "  endfunction"]
    if sname == "blocking_trigger":
        lines.append("  always @ev $display(\"ev at %0t\", $time);")
    lines += ["  initial begin", "    #1;", f"    {form} t = f(a);", "    #1 a = 1'b1;",
              "    #1 $display(\"t=%b\", t);", "  end", "endmodule"]
    # The override process runs at 1 with a = 0 and at 2 with a = 1. The
    # trigger and $strobe print each time; the deferred assertion fails
    # when v is 1.
    out = {"blocking_trigger": ["ev at 1", "ev at 2"], "strobe": ["strobe at 1", "strobe at 2"],
           "deferred": ["deferred failed at 2"]}[sname] + ["t=1"]
    description = (f"a function with {what} may be called from the right side of a procedural "
                   f"{form}: it schedules no later work")
    lrm = ["10.6.1" if form == "assign" else "10.6.2", "13.4.4"]
    lrm += ["16.4", "21.2.2"] if sname != "blocking_trigger" else ["15.5.1"]
    return name, header(name, description, lrm, False) + lines, out, None


# The statements in the Postponed region, each on one line: (name, the
# function's body, what the description calls it)
POSTPONED_STATEMENTS = [
    ("nba", "q <= 1'b1;", "a nonblocking assignment"),
    ("trigger", "->> ev;", "a nonblocking event trigger"),
    ("fork", "fork $display(\"forked\"); join_none", "a fork with join_none"),
]
# (name, the statement of initial that runs the function in the Postponed
# region, what the description calls the caller, the clauses)
POSTPONED_CALLERS = [
    ("strobe", "$strobe(\"%0d\", side());", "the arguments of $strobe", ["21.2.2"]),
    ("monitor", "$monitor(\"%0d\", side());", "the arguments of $monitor", ["21.2.3"]),
    ("final", "assert final (0) else touch();", "the action of a final deferred assertion",
     ["16.4"]),
]


def postponed_case(statement, caller):
    sname, text, what = statement
    cname, call, where, clauses = caller
    name = f"{PREFIX}postponed_{sname}_{cname}"
    lines = ["module top;", "  logic q = 1'b0;", "  event ev;", "  function void touch();",
             f"    {text}", "  endfunction", "  function int side();", "    touch();",
             "    return 7;", "  endfunction", "  initial begin", "    #1;", f"    {call}",
             "  end", "  final $display(\"final ran\");", "endmodule"]
    description = (f"a function with {what} called from {where}, which runs in the Postponed "
                   "region, is a run-time error, not a compile-time one")
    head = header(name, description, ["13.4.4", "4.4.2.9"] + clauses, True)
    at = len(head) + lines.index(f"    {text}") + 1
    return name, head + lines, ["final ran"], [f"{name}.sv:{at}: error: {POSTPONED}"]


def files():
    out = cli_files()
    cases = [uncounted_case(s, f) for s in UNCOUNTED for f in ("assign", "force")]
    cases += [postponed_case(s, c) for s in POSTPONED_STATEMENTS for c in POSTPONED_CALLERS]
    for name, text, expected, stderr in cases:
        out[SUITE / f"{name}.sv"] = "\n".join(text) + "\n"
        out[SUITE / f"{name}.expected"] = "\n".join(expected) + "\n"
        if stderr is not None:
            out[SUITE / f"{name}.stderr"] = "\n".join(stderr) + "\n"
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for path, text in files().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_later_work_override_matrix: {path.relative_to(ROOT)} is out of date; "
                      "run tools/gen_later_work_override_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
