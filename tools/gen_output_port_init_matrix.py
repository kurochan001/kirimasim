"""Generates the matrix tests of the initial value of an output port that
is a variable (TEST_SUITE.md, "Mechanism matrix") in tests/suite/ports/.

  tools/gen_output_port_init_matrix.py           # writes the files
  tools/gen_output_port_init_matrix.py --check   # exit 1 if a file differs from what it would write

The rule: 23.2.2.2 and 23.2.2.1 of the standard with 6.8. An output port
that is a variable may be declared with an initial value, "output logic
[3:0] y = 4'b1010" or, in the list of port declarations, "output reg
[2:0] q = 3'd4". It is the initial value of the variable: the variable
has it before any procedure runs, inside the design element and, through
the port, outside.

The axes: the type of the port (a 4-state vector, int, byte, bit,
integer, string, real, an unpacked array), the form of the declaration
(in the port list; in the declarations after it), the design element (a
module, an interface, a program) and where the value is read (inside
before any write, outside through the connection, and after a clocked
update of a port that started from its initial value).

The expected output is computed here from the values, without reading
kirimasim's code. A person checks it once for all the tests made from it
(TEST_SUITE.md, "Sampling by people"). For reference, checked
2026-11-12: Verilator 5.052 prints the same values for these shapes.
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "ports"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

# (name, the type before the name, the dimensions after it, the initial
# value, the declaration of the variable or net outside, the format, how
# it prints, the expressions printed after the name).
PORTS = [
    ("y", "logic [3:0]", "", "4'b1010", "wire [3:0] y;", "%b", "1010", [""]),
    ("n", "int", "", "7", "int n;", "%0d", "7", [""]),
    ("b", "byte", "", "-3", "byte b;", "%0d", "-3", [""]),
    ("t", "bit", "", "1", "bit t;", "%b", "1", [""]),
    ("g", "integer", "", "9", "integer g;", "%0d", "9", [""]),
    ("s", "string", "", '"hi"', "string s;", "%s", "hi", [""]),
    ("r", "real", "", "2.5", "real r;", "%g", "2.5", [""]),
    ("a", "int", " [2]", "'{4, 5}", "int a [2];", "%0d %0d", "4 5", ["[0]", "[1]"]),
]
ELEMENTS = ["module", "interface", "program"]


def show(label):
    fmt = " ".join(f"{p[0]}={p[5]}" for p in PORTS)
    args = ", ".join(f"{p[0]}{e}" for p in PORTS for e in p[7])
    return f'$display("{label}: {fmt}", {args});'


def line(label):
    return f"{label}: " + " ".join(f"{p[0]}={p[6]}" for p in PORTS)


def test(element):
    name = f"output_port_init_{element}"
    end = {"module": "endmodule", "interface": "endinterface", "program": "endprogram"}[element]
    sv = ["/*", f":name: {name}",
          ":description: an output port that is a variable has the initial value it is "
          f"declared with, inside and outside {'an' if element == 'interface' else 'a'} {element}",
          ":tags: ports", ":type: simulation", ":lrm: 1800-2023 23.2.2.2 23.2.2.1 6.8",
          ":oracle: spec", ":spec_check: ai", ":fourstate: yes", ":nondeterministic: no",
          f":generator: gen_output_port_init_matrix.py@{VERSION}", ":top_module: top",
          f":expected_stdout: @{name}.expected", "*/",
          "// Generated by tools/gen_output_port_init_matrix.py; change the generator, not this "
          "file.", "`timescale 1ns/1ns"]
    # The initial values written in the port list.
    ports = ", ".join(f"output {p[1]} {p[0]}{p[2]} = {p[3]}" for p in PORTS)
    sv += [f"{element} listed ({ports});", f"  initial #1 {show('inside')}"]
    if element == "program":
        sv += ["  initial #9;"]
    sv += [end]
    # The initial values written in the declarations after the port list;
    # a module then counts up from one of them at each clock edge.
    if element == "module":
        sv += ["module after (clk, q, k);", "  input clk;", "  output reg [2:0] q = 3'd4;",
               "  output integer k = -2;", "  always @(posedge clk) q <= q + 1;", "endmodule"]
    sv += ["module top;"] + ["  " + p[4] for p in PORTS]
    sv += [f"  listed u ({', '.join(p[0] for p in PORTS)});"]
    if element == "module":
        sv += ["  logic clk = 0;", "  wire [2:0] q;", "  integer k;", "  after v (clk, q, k);"]
    sv += ["  initial begin", f"    #2 {show('outside')}"]
    expected = [line("inside"), line("outside")]
    if element == "module":
        sv += ['    $display("after: q=%0d k=%0d", q, k);', "    clk = 1;",
               '    #1 $display("clocked: q=%0d", q);']
        expected += ["after: q=4 k=-2", "clocked: q=5"]
    sv += ["  end", "endmodule"]
    return name, sv, expected


def files():
    out = {}
    for element in ELEMENTS:
        name, sv, expected = test(element)
        out[f"{name}.sv"] = "\n".join(sv) + "\n"
        out[f"{name}.expected"] = "\n".join(expected) + "\n"
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_output_port_init_matrix: {path.relative_to(OUT.parent.parent.parent)} "
                      "is out of date; run tools/gen_output_port_init_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
