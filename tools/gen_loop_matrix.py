#!/usr/bin/env python3
"""Generates the loop control matrix test of TEST_SUITE.md ("Mechanism matrix") in
tests/suite/proc/.

  tools/gen_loop_matrix.py           # writes the files
  tools/gen_loop_matrix.py --check   # exit 1 if a file differs from what it would write

continue goes to the next iteration (the step of a for, the condition of a
while or do-while, the next element of a foreach), break leaves the
innermost loop, and return leaves the subroutine (12.8). The same statements
do the same in every container (CLAUDE.md, "The container does not change
meaning"). The axes: the loop (for, while, do-while, repeat, forever,
foreach); where the statement is (directly in the body, in a named block in
the body, or in a named block that is the target of a disable, which a task,
a function and a fork branch keep as a scope that the statement leaves,
SIR_SPEC.md 7.2); the container (an initial procedure, an automatic task, a
function, a fork branch); and how the loop ends (break, or return from the
task or the function).

Each case runs five iterations, i = 0 to 4, adding (i + 1) * 10 to a sum:
it continues at i = 1 and leaves at i = 3, so the sum is 10 + 30 = 40.
A person checks the expected output once for all the tests made from it
(TEST_SUITE.md, "Sampling by people").
"""

import argparse
import itertools
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "proc"
NAME = "loop_control_matrix"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1
LOOPS = ["for", "while", "do-while", "repeat", "forever", "foreach"]
PLACES = ["body", "named", "disabled"]
CONTAINERS = ["initial", "task", "function", "fork"]


def loop(kind, body, pad):
    """The loop around body, which uses i (0 to 4) and may continue or leave."""
    inner = [pad + "  " + line for line in body]
    if kind == "for":
        return [f"{pad}for (int i = 0; i < 5; i++) begin"] + inner + [f"{pad}end"]
    if kind == "foreach":
        return [f"{pad}foreach (arr[i]) begin"] + inner + [f"{pad}end"]
    if kind == "while":
        return ([f"{pad}j = 0;", f"{pad}while (j < 5) begin", f"{pad}  i = j;", f"{pad}  j++;"]
                + inner + [f"{pad}end"])
    if kind == "do-while":
        return ([f"{pad}j = 0;", f"{pad}do begin", f"{pad}  i = j;", f"{pad}  j++;"] + inner
                + [f"{pad}end while (j < 5);"])
    if kind == "repeat":
        return ([f"{pad}j = 0;", f"{pad}repeat (5) begin", f"{pad}  i = j;", f"{pad}  j++;"]
                + inner + [f"{pad}end"])
    return ([f"{pad}j = 0;", f"{pad}forever begin", f"{pad}  if (j == 5) break;", f"{pad}  i = j;",
             f"{pad}  j++;"] + inner + [f"{pad}end"])


def body(k, place, leave):
    """The statements of one iteration; `leave` is break or return."""
    stmts = ["if (i == 1) continue;", f"if (i == 3) {leave};", "sum = sum + (i + 1) * 10;"]
    if place == "body":
        return stmts
    block = [f"begin : b{k}"] + ["  " + s for s in stmts]
    if place == "disabled":
        block.append(f"  if (i == 9) disable b{k};")  # never taken
    return block + ["end"]


def declared(kind):
    """What the loop needs besides sum: i, and j for the counting loops."""
    if kind in ("for", "foreach"):
        return []
    return ["int i, j;"]


def cases():
    out = []
    for c, kind, place in itertools.product(CONTAINERS, LOOPS, PLACES):
        out.append((c, kind, place, "break"))
        if c in ("task", "function"):
            out.append((c, kind, place, "return"))
    return out


def files():
    head = [
        "/*",
        f":name: {NAME}",
        ":description: continue, break and return in for, while, do-while, repeat, forever and "
        "foreach loops, directly, in a named block and in a named block that is a disable "
        "target, in an initial procedure, an automatic task, a function and a fork branch",
        ":tags: proc loop",
        ":type: simulation",
        ":lrm: 1800-2023 12.7 12.8 13.3 13.4.1 9.6.2",
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: no",
        ":nondeterministic: no",
        f":generator: gen_loop_matrix.py@{VERSION}",
        f":expected_stdout: @{NAME}.expected",
        "*/",
        "// Generated by tools/gen_loop_matrix.py; change the generator, not this file.",
        "// Icarus Verilog 14.0 (devel) f190dbb leaves only the named block on a break or a",
        "// continue inside one (90 for 40) and does not end the repeat loop of that case;",
        "// 12.8 says both act on the innermost loop.",
        "module top;",
        "  int arr[5];",
    ]
    subs, main, exp = [], ["  initial begin"], []
    for k, (c, kind, place, leave) in enumerate(cases()):
        tag = f"{c} {kind} {place} {leave}"
        b = body(k, place, leave if leave == "break" else "return")
        if c == "initial":
            main += ["    begin", "      int sum;"] + ["      " + d for d in declared(kind)]
            main += ["      sum = 0;"] + loop(kind, b, "      ")
            main += [f"      $display(\"{tag} %0d\", sum);", "    end"]
        elif c == "fork":
            main += ["    fork", "      begin", "        int sum;"]
            main += ["        " + d for d in declared(kind)]
            main += ["        sum = 0;"] + loop(kind, b, "        ")
            main += [f"        $display(\"{tag} %0d\", sum);", "      end", "    join"]
        elif c == "task":
            # return leaves the task; the sum so far goes back through out.
            b = [s.replace("return;", "begin out = sum; return; end") for s in b]
            subs += [f"  task automatic t{k}(output int out);", "    int sum;"]
            subs += ["    " + d for d in declared(kind)]
            subs += ["    sum = 0;"] + loop(kind, b, "    ") + ["    out = sum;", "  endtask"]
            main += ["    begin", "      int r;", f"      t{k}(r);",
                     f"      $display(\"{tag} %0d\", r);", "    end"]
        else:
            b = [s.replace("return;", "return sum;") for s in b]
            subs += [f"  function automatic int f{k}();", "    int sum;"]
            subs += ["    " + d for d in declared(kind)]
            subs += ["    sum = 0;"] + loop(kind, b, "    ") + ["    return sum;", "  endfunction"]
            main.append(f"    $display(\"{tag} %0d\", f{k}());")
        exp.append(f"{tag} 40")
    sv = head + subs + main + ["  end", "endmodule", ""]
    return {f"{NAME}.sv": "\n".join(sv), f"{NAME}.expected": "\n".join(exp) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_loop_matrix: {path.relative_to(OUT.parent.parent.parent)} is out of "
                      "date; run tools/gen_loop_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
