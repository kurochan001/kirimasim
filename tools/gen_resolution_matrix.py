"""Generates the net resolution matrix tests of TEST_SUITE.md ("Net matrix",
"4-state matrix") in tests/suite/nets/.

  tools/gen_resolution_matrix.py           # writes the files
  tools/gen_resolution_matrix.py --check   # exit 1 if a file differs from what it would write

The axes: every kind of net that resolves (6.6.1 to 6.6.6) with two
drivers of each value 0, 1, x and z at strong strength; two drivers of
every pair of driving strengths (supply, strong, pull, weak) on wire,
wand and wor; tri0, tri1, supply0 and supply1 with one driver of each
strength; drivers with highz for one value (H and L); a 4-bit net whose
bits resolve separately; and drivers that meet through an output or an
input port. The drivers are continuous assignments, net declaration
assignments and ports. A port between a variable and a net drives
strong; a port between nets merges them into one net, which resolves
the drivers of both sides with their strengths (VALUE_SEMANTICS.md 5.3),
of the kind of table 23-1 (SIR_SPEC.md 3.5).

The expected outputs follow from the rule of VALUE_SEMANTICS.md 5.4,
written again below without reading kirimasim's code. A person checks
the rule against the standard once for all the tests made from it
(TEST_SUITE.md, "Sampling by people").
"""

import argparse
import itertools
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "nets"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

VALUES = ["0", "1", "x", "z"]
# Driving strengths (table 28-7) and their keywords.
STRENGTHS = {7: "supply", 6: "strong", 5: "pull", 3: "weak", 0: "highz"}
KINDS = ["wire", "tri", "wand", "triand", "wor", "trior", "tri0", "tri1", "supply0", "supply1"]
# The net's own driver (28.15.1, 28.15.3) as a range.
OWN = {"tri0": (-5, -5), "tri1": (5, 5), "supply0": (-7, -7), "supply1": (7, 7)}


# --- The rule of VALUE_SEMANTICS.md 5 ---------------------------------------------

def driver_range(value, s1, s0):
    """5.3: 0 is [-s0, -s0], 1 is [s1, s1], x is [-s0, s1], z is [0, 0]."""
    return {"0": (-s0, -s0), "1": (s1, s1), "x": (-s0, s1), "z": (0, 0)}[value]


def combine(kind, points):
    """5.4 step 2: the strongest point wins; points of both values at the
    greatest strength give x, or 0 on wand and triand, 1 on wor and trior."""
    m = max(abs(p) for p in points)
    if m == 0:
        return 0, 0
    zero, one = -m in points, m in points
    if zero and one:
        if kind in ("wand", "triand"):
            return -m, -m
        if kind in ("wor", "trior"):
            return m, m
        return -m, m
    return (-m, -m) if zero else (m, m)


def resolve(kind, drivers):
    """5.4: every choice of one point per driver, then the narrowest range
    holding every outcome. `drivers` are (value, s1, s0)."""
    ranges = [driver_range(*d) for d in drivers]
    if kind in OWN:
        ranges.append(OWN[kind])
    if not ranges:
        return 0, 0
    outcomes = [combine(kind, pts)
                for pts in itertools.product(*[range(lo, hi + 1) for lo, hi in ranges])]
    return min(o[0] for o in outcomes), max(o[1] for o in outcomes)


def value_of(r):
    """5.2: z, 0, 1, or x (also for L and H)."""
    lo, hi = r
    if lo == hi == 0:
        return "z"
    if hi < 0:
        return "0"
    if lo > 0:
        return "1"
    return "x"


def resolved(kind, drivers):
    return value_of(resolve(kind, drivers))


# --- The tests ---------------------------------------------------------------------

def header(name, description, lrm, note=""):
    return (f"/*\n:name: {name}\n:description: {description}\n:tags: nets\n:type: simulation\n"
            f":lrm: 1800-2023 {lrm}\n:oracle: spec iverilog@13.0\n:spec_check: ai\n"
            f":fourstate: yes\n:nondeterministic: no\n:generator: gen_resolution_matrix.py@{VERSION}\n"
            f":expected_stdout: @{name}.expected\n*/\n"
            "// Generated by tools/gen_resolution_matrix.py; change the generator, not this file.\n"
            + note)


def strength_spec(s1, s0):
    return f"({STRENGTHS[s1]}1, {STRENGTHS[s0]}0)"


def two_drivers():
    """Every kind with two strong drivers of every pair of values: the
    tables of 6.6.1 to 6.6.5 and 28.12.4 at equal strength."""
    name = "net_two_drivers"
    sv = header(name, "Every kind of net that resolves, with two strong drivers of each pair of "
                "values 0, 1, x and z", "6.6.1 6.6.3 6.6.5 6.6.6 28.12.1 28.12.2 28.12.4 28.15")
    sv += "module top;\n  logic a, b;\n"
    for k in KINDS:
        sv += f"  {k} n_{k};\n  assign n_{k} = a;\n  assign n_{k} = b;\n"
    sv += "  initial begin\n"
    fmt = " ".join(f"{k}=%b" for k in KINDS)
    args = ", ".join(f"n_{k}" for k in KINDS)
    exp = ""
    for a, b in itertools.product(VALUES, VALUES):
        sv += f"    a = 1'b{a}; b = 1'b{b};\n    #1 $display(\"{a}{b} {fmt}\", {args});\n"
        exp += f"{a}{b} " + " ".join(f"{k}={resolved(k, [(a, 6, 6), (b, 6, 6)])}"
                                     for k in KINDS) + "\n"
    sv += "  end\nendmodule\n"
    return name, sv, exp


DRIVING = [7, 6, 5, 3]


def strengths(kind):
    """Two drivers of every pair of driving strengths on one kind of net,
    with every pair of values."""
    name = f"net_strengths_{kind}"
    lrm = "10.3.4 28.11 28.12.1 28.12.2" + (" 28.12.4" if kind != "wire" else "")
    note = ""
    if kind != "wire":
        note = ("// Icarus 13.0 applies the wired logic even when the strengths differ (for\n"
                "// a wand, a weak 0 and a strong 1 give its strong 0); 28.12.4 and the table\n"
                "// of figure 28-25 let the stronger driver win, and so do these lines.\n")
    sv = header(name, f"A {kind} with two drivers of every pair of driving strengths and "
                "values", lrm, note)
    pairs = list(itertools.product(DRIVING, DRIVING))
    sv += "module top;\n  logic a, b;\n"
    for i, (sa, sb) in enumerate(pairs):
        sv += (f"  {kind} n{i};\n  assign {strength_spec(sa, sa)} n{i} = a;\n"
               f"  assign {strength_spec(sb, sb)} n{i} = b;\n")
    sv += "  initial begin\n"
    labels = " ".join(f"{STRENGTHS[sa][:2]}{STRENGTHS[sb][:2]}=%b" for sa, sb in pairs)
    args = ", ".join(f"n{i}" for i in range(len(pairs)))
    exp = ""
    for a, b in itertools.product(VALUES, VALUES):
        sv += f"    a = 1'b{a}; b = 1'b{b};\n    #1 $display(\"{a}{b} {labels}\", {args});\n"
        exp += f"{a}{b} " + " ".join(
            f"{STRENGTHS[sa][:2]}{STRENGTHS[sb][:2]}={resolved(kind, [(a, sa, sa), (b, sb, sb)])}"
            for sa, sb in pairs) + "\n"
    sv += "  end\nendmodule\n"
    return name, sv, exp


def own_driver():
    """tri0 and tri1 with one driver of each strength, given by a net
    declaration assignment, and supply0 and supply1 with one driver, which
    takes no strength (10.3.4)."""
    name = "net_own_driver"
    sv = header(name, "tri0 and tri1 with one driver of each driving strength and value, supply0 "
                "and supply1 with one driver of each value, against their own pull or supply", "6.6.5 6.6.6 10.3.1 10.3.4 28.15.1 "
                "28.15.3 28.12.1")
    kinds = ["tri0", "tri1", "supply0", "supply1"]
    sv += "module top;\n  logic a;\n"
    nets = []
    for k in kinds:
        for s in DRIVING if k.startswith("tri") else [6]:
            if k.startswith("supply"):
                sv += f"  {k} {k}_{STRENGTHS[s]} = a;\n"
            else:
                sv += f"  {k} {strength_spec(s, s)} {k}_{STRENGTHS[s]} = a;\n"
            nets.append((k, s))
    sv += "  initial begin\n"
    labels = " ".join(f"{k}.{STRENGTHS[s][:2]}=%b" for k, s in nets)
    args = ", ".join(f"{k}_{STRENGTHS[s]}" for k, s in nets)
    exp = ""
    for a in VALUES:
        sv += f"    a = 1'b{a};\n    #1 $display(\"{a} {labels}\", {args});\n"
        exp += f"{a} " + " ".join(f"{k}.{STRENGTHS[s][:2]}={resolved(k, [(a, s, s)])}"
                                  for k, s in nets) + "\n"
    sv += "  end\nendmodule\n"
    return name, sv, exp


def highz():
    """Drivers with highz for one value (H and L, 28.12.2) against a second
    driver of each strength, and a 4-bit net whose bits resolve apart."""
    name = "net_highz_strengths"
    sv = header(name, "Drivers with highz for one value give z for that value and H or L for x; "
                "the bits of a vector net resolve apart", "10.3.4 28.11 28.12.2 28.12.3")
    cases = []  # (net, (s1, s0) of the first driver, strength of the second)
    for first in [(6, 0), (0, 6), (5, 0), (0, 3)]:
        for second in [6, 5, 3]:
            cases.append(first + (second,))
    sv += "module top;\n  logic a, b;\n"
    for i, (s1, s0, sb) in enumerate(cases):
        sv += (f"  wire h{i};\n  assign {strength_spec(s1, s0)} h{i} = a;\n"
               f"  assign {strength_spec(sb, sb)} h{i} = b;\n")
    sv += ("  logic [3:0] va, vb;\n  wire [3:0] v;\n  assign (weak1, weak0) v = va;\n"
           "  assign (strong1, highz0) v = vb;\n  initial begin\n")
    labels = " ".join(f"{STRENGTHS[s1][:2]}{STRENGTHS[s0][:2]}.{STRENGTHS[sb][:2]}=%b"
                      for s1, s0, sb in cases)
    args = ", ".join(f"h{i}" for i in range(len(cases)))
    exp = ""
    for a, b in itertools.product(VALUES, VALUES):
        sv += f"    a = 1'b{a}; b = 1'b{b};\n    #1 $display(\"{a}{b} {labels}\", {args});\n"
        exp += f"{a}{b} " + " ".join(
            f"{STRENGTHS[s1][:2]}{STRENGTHS[s0][:2]}.{STRENGTHS[sb][:2]}="
            f"{resolved('wire', [(a, s1, s0), (b, sb, sb)])}" for s1, s0, sb in cases) + "\n"
    for va, vb in [("01xz", "0000"), ("01xz", "1111"), ("01xz", "xxxx"), ("1100", "z1x0")]:
        sv += f"    va = 4'b{va}; vb = 4'b{vb};\n    #1 $display(\"v {va} {vb} %b\", v);\n"
        bits = "".join(resolved("wire", [(x, 3, 3), (y, 6, 0)]) for x, y in zip(va, vb))
        exp += f"v {va} {vb} {bits}\n"
    sv += "  end\nendmodule\n"
    return name, sv, exp


def port_drivers(between_nets):
    """A weak driver on one side of a port and a driver on the other side.
    Between nets, through an output port (the child drives, the parent
    drives too) and an input port (the parent drives, the child drives
    too): both drivers keep their strengths on one net (5.3, 23.3.3.7).
    From an output port of a variable to a net, which may have more
    drivers (23.3.3.2): the port drives strong. A variable on the outer
    side of an input port the child drives is left out: such a port turns
    inout (23.3.3.1), which takes no variable (23.3.3.2)."""
    name = "net_port_drivers_" + ("net" if between_nets else "var")
    if between_nets:
        description = ("Drivers that meet through output and input ports between nets "
                       "resolve on one net with their own strengths")
        note = ""
    else:
        description = ("An output port of a variable drives the net outside strong, "
                       "against another driver of that net")
        note = ("// Icarus 13.0 stops with an error (it takes the net for a uwire) and Verilator\n"
                "// 5.052 does not support the design; 23.3.3.2 allows more drivers on a net\n"
                "// that an output port of a variable drives, and the lines follow 10.3.4 and\n"
                "// 28.12.\n")
    sv = header(name, description, "4.9.6 23.3.3.1 23.3.3.2 23.3.3.7 10.3.4 28.12.1 28.12.2",
                note)
    if between_nets:
        sv += ("module outc (output wire o);\n  logic cv;\n  assign (weak1, weak0) o = cv;\n"
               "endmodule\n")
    else:
        sv += "module outc (output logic o);\n  logic cv;\n  assign o = cv;\nendmodule\n"
    if between_nets:
        sv += ("module inc (input wire i);\n  logic cv;\n  assign (weak1, weak0) i = cv;\n"
               "endmodule\n")
    sv += "module top;\n  logic pv;\n  wire po" + (", pi;\n" if between_nets else ";\n")
    sv += "  outc u (.o(po));\n  assign (weak1, weak0) po = pv;\n"
    if between_nets:
        sv += "  assign (weak1, weak0) pi = pv;\n  inc v (.i(pi));\n"
    sv += "  initial begin\n"
    port = 3 if between_nets else 6
    exp = ""
    for c, p in itertools.product(VALUES, VALUES):
        out = resolved("wire", [(c, port, port), (p, 3, 3)])
        if between_nets:
            sv += (f"    u.cv = 1'b{c}; v.cv = 1'b{c}; pv = 1'b{p};\n"
                   f"    #1 $display(\"{c}{p} out=%b in=%b\", po, v.i);\n")
            inn = resolved("wire", [(p, port, port), (c, 3, 3)])
            exp += f"{c}{p} out={out} in={inn}\n"
        else:
            sv += (f"    u.cv = 1'b{c}; pv = 1'b{p};\n"
                   f"    #1 $display(\"{c}{p} out=%b\", po);\n")
            exp += f"{c}{p} out={out}\n"
    sv += "  end\nendmodule\n"
    return name, sv, exp


def port_drivers_part():
    """As net_port_drivers_net, but the ports connect to one bit of a
    vector net: the drivers of both sides still meet with their strengths
    (5.3). kirimasim merges whole nets only (SIR_SPEC.md 3.5) and reports
    this form as unsupported, so the test is skipped until parts are
    merged too."""
    name = "net_port_drivers_part"
    sv = header(name, "Drivers that meet through output and input ports connected to a bit of "
                "a vector net resolve with their own strengths",
                "4.9.6 23.3.3.1 23.3.3.7 10.3.4 28.12.1 28.12.2")
    sv += ("module outc (output wire o);\n  logic cv;\n  assign (weak1, weak0) o = cv;\n"
           "endmodule\n"
           "module inc (input wire i);\n  logic cv;\n  assign (weak1, weak0) i = cv;\n"
           "endmodule\n")
    sv += "module top;\n  logic pv;\n  wire [1:0] po, pi;\n"
    sv += "  outc u (.o(po[1]));\n  assign (weak1, weak0) po[1] = pv;\n"
    sv += "  assign (weak1, weak0) pi[1] = pv;\n  inc v (.i(pi[1]));\n"
    sv += "  initial begin\n"
    exp = ""
    for c, p in itertools.product(VALUES, VALUES):
        sv += (f"    u.cv = 1'b{c}; v.cv = 1'b{c}; pv = 1'b{p};\n"
               f"    #1 $display(\"{c}{p} out=%b in=%b\", po[1], v.i);\n")
        out = resolved("wire", [(c, 3, 3), (p, 3, 3)])
        exp += f"{c}{p} out={out} in={out}\n"
    sv += "  end\nendmodule\n"
    return name, sv, exp


# Table 23-1, the kind of a net merged by a port: rows are the internal
# (port) kind, columns the external (connection) kind; "E" external, "I"
# internal (the warnings of the table are left out here).
MERGE_KINDS = ["wire", "wand", "wor", "tri0", "tri1", "supply0", "supply1"]
MERGE_TABLE = {
    "wire":    "EEEEEEE",
    "wand":    "IEEEEEE",
    "wor":     "IEEEEEE",
    "tri0":    "IEEEEEE",
    "tri1":    "IEEEEEE",
    "supply0": "IIIIIEE",
    "supply1": "IIIIIEE",
}


def merged(internal, external):
    c = MERGE_TABLE[internal][MERGE_KINDS.index(external)]
    return external if c == "E" else internal


def merge_kinds():
    """A child's inout net of each kind connected to a parent's net of each
    kind: one net of the kind of table 23-1, with a strong driver on each
    side (23.3.3.7)."""
    name = "net_port_merge_kinds"
    sv = header(name, "An inout port merges the child's net and the parent's net into one net "
                "of the kind of table 23-1, which resolves the drivers of both sides",
                "23.3.3.7 4.9.6 6.6 28.12 28.15",
                "// slang warns about the combinations that table 23-1 marks with a warning.\n"
                "// Icarus 13.0 differs on six pairs: with a wand or wor and a supply net it\n"
                "// applies the wired logic though the strengths differ (28.12.4), and with\n"
                "// supply0 and supply1 it gives x, keeping both supplies, where table 23-1\n"
                "// makes one net of the external kind. The lines follow the standard.\n")
    for k in MERGE_KINDS:
        sv += f"module c_{k} (inout {k} w, input logic v);\n  assign w = v;\nendmodule\n"
    sv += "module top;\n  logic cv, pv;\n"
    pairs = [(i, e) for i in MERGE_KINDS for e in MERGE_KINDS]
    for i, e in pairs:
        sv += (f"  {e} n_{i}_{e};\n  assign n_{i}_{e} = pv;\n"
               f"  c_{i} u_{i}_{e} (.w(n_{i}_{e}), .v(cv));\n")
    sv += "  initial begin\n"
    exp = ""
    for c, p in itertools.product(VALUES, VALUES):
        sv += f"    cv = 1'b{c}; pv = 1'b{p};\n    #1 $display(\"{c}{p}"
        sv += "".join(f" %b" for _ in pairs) + "\", " + ", ".join(f"n_{i}_{e}" for i, e in pairs)
        sv += ");\n"
        exp += f"{c}{p}" + "".join(
            " " + resolved(merged(i, e), [(c, 6, 6), (p, 6, 6)]) for i, e in pairs) + "\n"
    sv += "  end\nendmodule\n"
    return name, sv, exp


def files():
    out = {}
    for name, sv, exp in [two_drivers(), strengths("wire"), strengths("wand"), strengths("wor"),
                          own_driver(), highz(), port_drivers(False), port_drivers(True),
                          port_drivers_part(), merge_kinds()]:
        out[f"{name}.sv"] = sv
        out[f"{name}.expected"] = exp
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_resolution_matrix: {path.relative_to(OUT.parent.parent.parent)} is "
                      "out of date; run tools/gen_resolution_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
