"""Original event initialization-sharing checks (6.8, 6.21, 10.9, 15.5).

Grounds: approved automatic-capture contract 5/6. No external code or tests.
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / 'tests/suite/sched'
HOMES = ('initial', 'task', 'function', 'fork', 'interface', 'package', 'program', 'generate')


def wrap(home, declarations, body):
    if home == 'package':
        return (f'package unit;\n{declarations}\nfunction automatic void run();\n{body}\n'
                'endfunction\nendpackage\nmodule top;initial unit::run();endmodule\n')
    action = f'initial begin\n{body}\nend\n'
    if home in ('task', 'function'):
        ret = 'void ' if home == 'function' else ''
        action = f'{home} automatic {ret}run();\n{body}\nend{home}\ninitial run();\n'
    elif home == 'fork':
        action = f'initial fork begin\n{body}\nend join\n'
    elif home == 'generate':
        action = 'if(1) begin:generated\n' + action + 'end\n'
    if home in ('interface', 'program'):
        kind = 'program automatic' if home == 'program' else home
        return f'{kind} unit;\n{declarations}\n{action}end{home}\nmodule top;unit u();endmodule\n'
    return f'module top;\n{declarations}\n{action}endmodule\n'


def emit(name, source, expected='errors=0'):
    header = f'''/*
:name: {name}
:description: Event declaration initialization shares object identity without rebinding
:tags: sched event initialization lifetime
:type: simulation
:lrm: 1800-2023 6.8 6.21 10.9 13.5 15.5
:oracle: spec
:spec_check: ai
:fourstate: no
:nondeterministic: no
:generator: gen_event_initializer_matrix.py@1
:top_module: top
:expected_stdout: {expected}
:timeout: 10
*/
// Generated by tools/gen_event_initializer_matrix.py; edit the generator.
`timescale 1ns/1ns
'''
    return name, '\n'.join(line.rstrip() for line in (header + source).splitlines()) + '\n'


def scalar(home, legacy, shape):
    dimensions, actual, target, start, after = {
        'scalar': ('', 'original', 'original', 0, 0),
        'selected': ('[-1:1]', 'original[index++]', 'original[0]', 0, 1),
        'rank2': ('[-1:0][3:2]', 'original[index++][2]', 'original[-1][2]', -1, 0),
        'null': ('', 'null', '', 0, 0),
    }[shape]
    global_decl = f'static event original{dimensions};' if legacy else ''
    local_decl = '' if legacy else f'automatic event original{dimensions};'
    expected = 0 if shape == 'null' else 1
    original_check = f'if(!{target}.triggered) ++errors;' if target else ''
    body = f'''automatic int errors=0;
for(int round=0;round<{'1' if legacy else '64'};++round) begin
  {local_decl}
  automatic int index={start};
  automatic event shared={actual};
  automatic event forwarded=shared;
  if(shared.triggered || forwarded.triggered) ++errors;
  if(index!={after}) ++errors;
  ->forwarded;
  if(shared.triggered!={expected} || forwarded.triggered!={expected}) ++errors;
  {original_check}
end
$display("errors=%0d",errors);
'''
    return emit(f'event_initializer_scalar_{home}_{"legacy" if legacy else "managed"}_{shape}',
                wrap(home, global_decl, body))


def static_once(home):
    declarations = '''int calls=0;
static event original[0:1];
function automatic int pick();++calls;return 1;endfunction
'''
    body = '''automatic int errors=0;
if(calls!=1) ++errors;
for(int round=0;round<3;++round) begin
  static event shared=original[pick()];
  ->shared;
  if(!original[1].triggered || original[0].triggered) ++errors;
end
if(calls!=1) ++errors;
$display("calls=%0d errors=%0d",calls,errors);
'''
    return emit('event_initializer_static_once_' + home, wrap(home, declarations, body),
                'calls=1 errors=0')


def pattern(home, static, shape):
    dims, initializer, trigger, first_check, rest, all_check = {
        'vector': ('[3:1]', "'{original[0],original[1],original[2]}", 'shared[3]',
                   '!original[0].triggered || original[1].triggered || original[2].triggered || shared[2].triggered || shared[1].triggered',
                   '->shared[2];->shared[1];',
                   '!original[0].triggered || !original[1].triggered || !original[2].triggered'),
        'rank2': ('[-1:0][3:2]', "'{'{original[0],original[1]},'{original[2],original[3]}}", 'shared[-1][3]',
                  '!original[0].triggered || original[1].triggered || original[2].triggered || original[3].triggered || shared[-1][2].triggered || shared[0][3].triggered || shared[0][2].triggered',
                  '->shared[-1][2];->shared[0][3];->shared[0][2];',
                  '!original[0].triggered || !original[1].triggered || !original[2].triggered || !original[3].triggered'),
        'replicated': ('[-1:1]', "'{3{original[2]}}", 'shared[0]',
                       '!original[2].triggered || !shared[-1].triggered || !shared[1].triggered || original[0].triggered || original[1].triggered',
                       '', '!original[2].triggered'),
        'null': ('[-1:1]', "'{default:null}", 'shared[0]',
                 'shared[-1].triggered || shared[0].triggered || shared[1].triggered',
                 '->>shared[-1];', 'shared[-1].triggered || shared[1].triggered'),
    }[shape]
    global_decl = 'static event original[0:3];' if static else ''
    local_decl = '' if static else 'automatic event original[0:3];'
    body = f'''automatic int errors=0;
for(int round=0;round<{'1' if static else '64'};++round) begin
  {local_decl}
  {'static' if static else 'automatic'} event shared{dims}={initializer};
  ->{trigger};
  if({first_check}) ++errors;
  {rest}
  if({all_check}) ++errors;
end
$display("errors=%0d",errors);
'''
    return emit(f'event_initializer_pattern_{home}_{"static" if static else "automatic"}_{shape}',
                wrap(home, global_decl, body))


def capture(program, join, wait, legacy, delayed):
    waiting = {'named': '@(shared);', 'mixed': '@(shared or posedge dummy);',
               'triggered': 'wait(shared.triggered);'}[wait]
    trigger = '->> #1 original;' if delayed else '#1;->original;'
    source_decl = '' if legacy else 'event local_original;'
    actual = 'originals[tag]' if legacy else 'local_original'
    body = f'''int results[0:1];int errors=0;bit dummy=0;
static event originals[0:1];
task automatic churn();
  for(int i=0;i<64;++i) begin event scratch;->scratch;end
endtask
task automatic spawn(input event original,input int tag);
  event shared=original;
  fork
    begin {trigger} end
    begin
      churn();
      {waiting}
      if(!shared.triggered) ++errors;
      results[tag]=tag+1;
    end
  {join}
endtask
task automatic enter(input int tag);
  {source_decl}
  spawn({actual},tag);
endtask
initial begin
  enter(0);enter(1);wait fork;
  $display("total=%0d errors=%0d",results[0]+results[1],errors);
end
'''
    source = (f'program automatic unit;\n{body}endprogram\nmodule top;unit u();endmodule\n'
              if program else f'module top;\n{body}endmodule\n')
    name = f'event_initializer_capture_{"program" if program else "module"}_{join}_{wait}_{"legacy" if legacy else "managed"}_{"nba" if delayed else "active"}'
    return emit(name, source, 'total=3 errors=0')


def files():
    for home in HOMES:
        for legacy in (False, True):
            for shape in ('scalar', 'selected', 'rank2', 'null'):
                yield scalar(home, legacy, shape)
        yield static_once(home)
        for static in (False, True):
            for shape in ('vector', 'rank2', 'replicated', 'null'):
                yield pattern(home, static, shape)
    for program in (False, True):
        for join in ('join', 'join_any', 'join_none'):
            for wait in ('named', 'mixed', 'triggered'):
                for legacy in (False, True):
                    for delayed in (False, True):
                        yield capture(program, join, wait, legacy, delayed)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    bad = []
    for name, text in files():
        path = OUT / (name + '.sv')
        if args.check:
            if not path.exists() or path.read_text() != text:
                bad.append(path.name)
        else:
            path.write_text(text)
    if bad:
        print('gen_event_initializer_matrix: out of date: ' + ', '.join(bad), file=sys.stderr)
    return int(bool(bad))


if __name__ == '__main__':
    sys.exit(main())
