"""Generates the matrix tests of interface and program instances in the VCD
dump (WAVEFORM.md 2; 21.7.1.2, 21.7.2.3; TEST_SUITE.md, "Mechanism
matrix") in tests/suite/proc/.

  tools/gen_dump_instance_matrix.py           # writes the files
  tools/gen_dump_instance_matrix.py --check   # exit 1 if a file differs from what it would write

The rule: WAVEFORM.md 2 (amended 2026-10-31, approved): interface and
program instances are scopes of type module and count as levels of
instances in $dumpvars, as module instances do. The axes: what $dumpvars
names (nothing, levels alone, levels and the top, levels and a module
instance holding an interface, and variables of an interface and of a
program, the latter named from inside the program, as 24.3 requires; the
pinned slang takes only modules and variables as its arguments,
21.7.1.2), and where the instances stand (an
interface and a program in the top module, beside a module instance, and
an interface inside that module instance). Each design reads its dump
back as tools/gen_dump_matrix.py does, and the expected dumps come from
its model of WAVEFORM.md, written without reading kirimasim's code.
"""

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_dump_matrix as dm  # noqa: E402  the model of a dump

OUT = dm.OUT
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1


def i32(name, a, b):
    return dm.Var(name, "integer", 32, "[31:0]", [format(a, "032b"), format(b, "032b")])


def hierarchy():
    """top: ta, a module instance m holding an interface ib, an interface
    bus and a program job, in that order (WAVEFORM.md 2: depth first, in
    the order of elaboration)."""
    ib = dm.Scope("module", "ib", [i32("bv", 50, 51)])
    m = dm.Scope("module", "m", [i32("la", 20, 21)], [ib])
    return dm.Scope("module", "top", [i32("ta", 1, 2)],
                    [m, dm.Scope("module", "bus", [i32("bv", 30, 31)]),
                     dm.Scope("module", "job", [i32("pv", 40, 41)])])


# Each cell: (name, the calls in the top module, the calls in the program,
# the requests of the model).
CELLS = [
    ("all", ["$dumpvars;"], [], [(0, None, [])]),
    ("levels_1", ["$dumpvars(1);"], [], [(1, None, [])]),
    ("levels_2", ["$dumpvars(2);"], [], [(2, None, [])]),
    ("top_2", ["$dumpvars(2, top);"], [], [(2, ["top"], [])]),
    ("module_1", ["$dumpvars(1, top.m);"], [], [(1, ["top.m"], [])]),
    ("module_2", ["$dumpvars(2, top.m);"], [], [(2, ["top.m"], [])]),
    ("variables", ["$dumpvars(0, top.bus.bv, top.m.ib.bv);"], ["$dumpvars(0, pv);"],
     [(0, [], ["top.bus.bv", "top.m.ib.bv", "top.job.pv"])]),
]


def test(cell):
    key, calls, program_calls, requests = cell
    name = f"dump_instances_{key}"
    lines = ["/*", f":name: {name}",
             f":description: what {' '.join(calls + program_calls)} dumps of interface and "
             "program instances (21.7.1.2, WAVEFORM.md 2)",
             ":tags: proc", ":type: simulation", ":lrm: 1800-2023 21.7.1.2 21.7.2.3 24.3",
             ":oracle: spec", ":spec_check: ai", ":fourstate: yes", ":nondeterministic: no",
             f":generator: gen_dump_instance_matrix.py@{VERSION}", ":top_module: top",
             f":expected_stdout: @{name}.expected", f":expected_stderr: @{name}.stderr", "*/",
             "// Generated by tools/gen_dump_instance_matrix.py; change the generator, not "
             "this file.",
             "`timescale 1ns/1ns",
             "interface bus_if #(int init = 0);", "  int bv = init;", "endinterface",
             "program job_p;", "  int pv = 40;", "  initial begin"]
    lines += ["    " + c for c in program_calls]
    # The program lives on past the read back, so that its end, which ends
    # the run (24.7), comes after it.
    lines += ["    #1 pv = 41;", "    #5;", "  end", "endprogram",
              "module leaf;", "  int la = 20;", "  bus_if #(50) ib();",
              "endmodule",
              "module top;", "  int ta = 1;", "  leaf m();", "  bus_if #(30) bus();",
              "  job_p job();", dm.SHOW, "  initial begin", '    $dumpfile("d.vcd");']
    lines += ["    " + c for c in calls]
    lines += ["    #1 ta = 2; m.la = 21; bus.bv = 31; m.ib.bv = 51;", "    #1 show_vcd;", "  end",
              "endmodule"]
    top = hierarchy()
    vcd = dm.Vcd(top, dm.choose(top, requests), '$dumpfile("d.vcd")')
    vcd.section("$dumpvars", 0, 0)
    vcd.changes(1, 1)
    return name, lines, vcd.lines


def files():
    out = {}
    for cell in CELLS:
        name, lines, stdout = test(cell)
        out[f"{name}.sv"] = "\n".join(lines) + "\n"
        out[f"{name}.expected"] = "\n".join(stdout) + "\n"
        out[f"{name}.stderr"] = ""
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                where = path.relative_to(OUT.parent.parent.parent)
                print(f"gen_dump_instance_matrix: {where} is out of date; run "
                      "tools/gen_dump_instance_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
