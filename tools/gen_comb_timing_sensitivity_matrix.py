"""Generates the matrix tests of timing controls in the implicit
sensitivity of always_comb and always_latch, of TEST_SUITE.md ("Mechanism
matrix"), in tests/suite/proc/.

  tools/gen_comb_timing_sensitivity_matrix.py           # writes the files
  tools/gen_comb_timing_sensitivity_matrix.py --check   # exit 1 if a file differs from what it would write

A name that appears only in the expressions of timing controls is no part
of the implicit sensitivity (9.2.2.2.1; SCHEDULER_SPEC.md 6.3).
always_comb and always_latch take no statement that waits (9.2.2.2.2), so
such a name is in the intra-assignment timing control of a nonblocking
assignment: the value of a delay, the count of a repeat event control
(9.4.5), or an event expression. A name that the block also reads
elsewhere is in the sensitivity as before. always_latch has the same
sensitivity (9.2.2.3).

The axes: the block (always_comb, always_latch); the timing control and
where v is in it (the delay value alone, in an expression, as an index,
the repeat count, the event expression, its iff condition); and whether
the block reads v outside the timing control too. Each test changes v
once, after the block ran at time 0, and prints how many times it ran: 1
if v is only in the timing control, 2 if the block reads it elsewhere.

The count of a repeat event control is read here as an expression of a
timing control: 9.4.5 makes the whole form an intra-assignment timing
control (SCHEDULER_SPEC.md 6.3 says "timing controls"). A function called
from a delay value has no test: whether what its body reads is "only in
a timing control" is not confirmed, and kirimasim still takes it for the
sensitivity.

The expected outputs follow from the rules above, computed below.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "proc"
PREFIX = "comb_timing_sensitivity_"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

BLOCKS = ["always_comb", "always_latch"]
# (name, the timing control, what the description calls the place, the
# clauses beside 9.2.2.2.1)
CONTROLS = [
    ("delay", "#(v)", "the value of a delay", ["9.4.1"]),
    ("delay_expression", "#(v + 1)", "an expression that is the value of a delay", ["9.4.1"]),
    ("delay_index", "#(d[v])", "the index of an array element that is the value of a delay",
     ["9.4.1"]),
    ("repeat_count", "repeat (v) @(posedge clk)", "the count of a repeat event control",
     ["9.4.5"]),
    ("event", "@(v)", "an event expression", ["9.4.2"]),
    ("event_iff", "@(posedge clk iff v != 0)", "the iff condition of an event expression",
     ["9.4.2.3"]),
]
# (name, the assigned value, whether v is read outside the timing control)
VALUES = [("only", "a", False), ("also_read", "a + v", True)]


def header(name, description, lrm):
    return [
        "/*",
        f":name: {name}",
        f":description: {description}",
        ":tags: proc",
        ":type: simulation",
        ":lrm: 1800-2023 " + " ".join(lrm),
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: no",
        ":nondeterministic: no",
        f":generator: gen_comb_timing_sensitivity_matrix.py@{VERSION}",
        ":issue: 128",
        ":top_module: top",
        f":expected_stdout: @{name}.expected",
        "*/",
        "// Generated by tools/gen_comb_timing_sensitivity_matrix.py; change the generator, not "
        "this file.",
        "`timescale 1ns/1ns",
    ]


def case(block, control, value):
    cname, timing, where, clauses = control
    vname, rhs, sensitive = value
    name = f"{PREFIX}{block}_{cname}_{vname}"
    lines = ["module top;", "  int a = 1, v = 1, y;", "  int d [0:3] = '{1, 2, 3, 4};",
             "  logic clk = 0;", "  int runs;",
             f"  {block} begin", "    runs++;", f"    y <= {timing} {rhs};", "  end",
             "  initial begin", "    #1 v = 3;", "    #1 $display(\"runs=%0d\", runs);",
             "    $finish;", "  end", "endmodule"]
    lrm = ["9.2.2.2.1"] + clauses + (["9.2.2.3"] if block == "always_latch" else [])
    description = (f"{block} has v in {where} of a nonblocking assignment and in the value "
                   "assigned: a change of v runs it again" if sensitive else
                   f"{block} has v only in {where} of a nonblocking assignment: a change of v "
                   "does not run it")
    return name, header(name, description, lrm) + lines, [f"runs={2 if sensitive else 1}"]


def files():
    out = {}
    for block in BLOCKS:
        for control in CONTROLS:
            for value in VALUES:
                name, text, expected = case(block, control, value)
                out[f"{name}.sv"] = "\n".join(text) + "\n"
                out[f"{name}.expected"] = "\n".join(expected) + "\n"
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print("gen_comb_timing_sensitivity_matrix: "
                      f"{path.relative_to(OUT.parent.parent.parent)} is out of date; run "
                      "tools/gen_comb_timing_sensitivity_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
