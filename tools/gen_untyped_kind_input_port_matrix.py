"""Generates the matrix tests of input ports of a type that is not integral
and that are declared with no var keyword (TEST_SUITE.md, "Mechanism
matrix") in tests/suite/ports/.

  tools/gen_untyped_kind_input_port_matrix.py           # writes the files
  tools/gen_untyped_kind_input_port_matrix.py --check   # exit 1 if a file differs from what it would write

The rule: 23.3.3 of the standard. An input port follows the expression
it is connected to, as the target of a continuous assignment does, and
an input port with a default value takes that value when it is left
unconnected (23.2.2.4).

"input real r" has no var keyword, so 23.2.2.3 makes it a net, and
6.7.1 gives a net a 4-state integral type. slang takes the declaration
without a diagnostic, and kirimasim runs it as the variable that "input
var real r" declares: the port has one source, its connection. (For
reference, checked 2026-11-12: Icarus 13.0 and Verilator 5.052 run the
real forms too; Icarus rejects the queue form.)

The axes: the type (real, shortreal, realtime, string, a queue, a
dynamic array), the actual (a variable, an expression, the default
value of the port), and the design element that has the ports (a
module, a program, an interface).

Each instance reads its ports at its own times, between the changes of
the sources, so the output does not depend on the order of processes. The expected
output is computed here from the values, without reading kirimasim's
code. A person checks it once for all the tests made from it
(TEST_SUITE.md, "Sampling by people").
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "ports"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

ELEMENTS = ["module", "program", "interface"]

PORTS = ("input real r, input shortreal sr, input realtime rt, input string s, "
         "input int q [$], input int d [], input real dr = 2.5, input string ds = \"dd\"")
FORMAT = ('"%s %0d: r=%g sr=%g rt=%g s=%s q=%0d,%0d d=%0d,%0d dr=%g ds=%s", '
          "name, $time, r, sr, rt, s, q.size(), q[q.size() - 1], d.size(), d[0], dr, ds")


def row(name, time, r, sr, rt, s, q, d, dr, ds):
    def g(x):
        return f"{x:g}"
    return (f"{name} {time}: r={g(r)} sr={g(sr)} rt={g(rt)} s={s} q={len(q)},{q[-1]} "
            f"d={len(d)},{d[0]} dr={g(dr)} ds={ds}")


def test(element):
    name = f"untyped_kind_input_port_{element}"
    sv = ["/*", f":name: {name}",
          ":description: input ports of real, string, queue and dynamic array types declared "
          f"with no var keyword follow their connections, as ports of {'an' if element == 'interface' else 'a'} "
          f"{element}",
          ":tags: ports", ":type: simulation", ":lrm: 1800-2023 23.3.3 23.2.2.3 23.2.2.4",
          ":oracle: spec", ":spec_check: ai", ":fourstate: no", ":nondeterministic: no",
          f":generator: gen_untyped_kind_input_port_matrix.py@{VERSION}", ":top_module: top",
          f":expected_stdout: @{name}.expected", "*/",
          "// Generated by tools/gen_untyped_kind_input_port_matrix.py; change the generator, not "
          "this file.", "`timescale 1ns/1ns"]
    end = {"module": "endmodule", "program": "endprogram", "interface": "endinterface"}[element]
    # Each instance reads at its own times, between the changes of the
    # sources, so the order of the lines does not depend on the order of
    # the processes (4.7).
    sv += [f"{element} reader #(parameter string name = \"\", parameter int lag = 0) ({PORTS});",
           "  initial begin",
           f"    #(2 + lag) $display({FORMAT});",
           f"    #4 $display({FORMAT});",
           "  end", end]
    sv += ["module top;",
           "  real r; shortreal sr; realtime rt; string s; int q [$]; int d [];",
           # The variables themselves; the default values of the last two ports.
           '  reader #("variable", 0) u (.r(r), .sr(sr), .rt(rt), .s(s), .q(q), .d(d));',
           # Expressions, and values for the ports that have a default.
           '  reader #("expression", 1) v (.r(r * 2.0), .sr(sr + sr), .rt(rt - 1.0), '
           '.s({s, "!"}), .q(q), .d(d), .dr(r + 1.0), .ds({s, s}));',
           "  initial begin",
           '    #1 r = 1.5; sr = 0.5; rt = 3.0; s = "ab"; q = {1, 2}; d = new[3];',
           '    #4 r = -1.0; sr = 0.25; rt = 4.0; s = "cd"; q.push_back(3); d[0] = 9;',
           "    #4 $finish(0);",
           "  end", "endmodule"]
    q1, q2, d1, d2 = [1, 2], [1, 2, 3], [0, 0, 0], [9, 0, 0]
    expected = [row("variable", 2, 1.5, 0.5, 3.0, "ab", q1, d1, 2.5, "dd"),
                row("expression", 3, 3.0, 1.0, 2.0, "ab!", q1, d1, 2.5, "abab"),
                row("variable", 6, -1.0, 0.25, 4.0, "cd", q2, d2, 2.5, "dd"),
                row("expression", 7, -2.0, 0.5, 3.0, "cd!", q2, d2, 0.0, "cdcd")]
    return name, sv, expected


def files():
    out = {}
    for element in ELEMENTS:
        name, sv, expected = test(element)
        out[f"{name}.sv"] = "\n".join(sv) + "\n"
        out[f"{name}.expected"] = "\n".join(expected) + "\n"
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print("gen_untyped_kind_input_port_matrix: "
                      f"{path.relative_to(OUT.parent.parent.parent)} is out of date; run "
                      "tools/gen_untyped_kind_input_port_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
