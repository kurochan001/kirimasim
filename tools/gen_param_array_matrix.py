"""Generates the parameter array matrix test of TEST_SUITE.md ("Mechanism matrix")
in tests/suite/values/.

  tools/gen_param_array_matrix.py           # writes the files
  tools/gen_param_array_matrix.py --check   # exit 1 if a file differs from what it would write

An element of an unpacked array parameter has the parameter's value at
that index, whether the index is a constant or known only when it runs;
an index outside the array, x or z, reads the element type's default
(7.4.6, SIR_SPEC.md 6). The axes: where the parameter is declared (a
module parameter, a localparam, a package parameter, a parameter of two
instances of a child given different values, a localparam of a generate
block), its element type (int, a 4-state vector with x bits, real,
string), its shape (ascending and descending ranges, two dimensions), the
index (constant, a loop variable, outside the array, x), and where it is
read (an initial procedure, an automatic function, a task, a continuous
assignment, always_comb, a function of the child, a hierarchical name).

The expected outputs follow from the rules above. A person checks them
once for all the tests made from them (TEST_SUITE.md, "Sampling by people").
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "values"
NAME = "param_array_matrix"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

# Parameters: (name as read, declared range of each dimension as (left,
# right), values by index tuple, the %-format, the default, how a value is
# shown).
P = ("P", [(0, 3)], {(0,): 5, (1,): 6, (2,): 7, (3,): 8}, "%0d", "0")
L = ("L", [(3, 0)], {(3,): "0f", (2,): "x0", (1,): "33", (0,): "44"}, "%h", "xx")
R = ("R", [(0, 1)], {(0,): "1.50", (1,): "-2.25"}, "%0.2f", "0.00")
M = ("M", [(0, 1), (0, 2)], {(a, b): 3 * a + b + 1 for a in range(2) for b in range(3)}, "%0d",
     "0")
S = ("S", [(0, 1)], {(0,): "ab", (1,): "cde"}, "%s", "")
PA = ("pk::PA", [(0, 3)], {(i,): 10 * (i + 1) for i in range(4)}, "%0d", "0")
C1 = ("c1.CP", [(0, 2)], {(0,): 7, (1,): 8, (2,): 9}, "%0d", "0")
C2 = ("c2.CP", [(0, 2)], {(0,): 1, (1,): 2, (2,): 3}, "%0d", "0")
G = ("g.G", [(0, 1)], {(0,): 100, (1,): 200}, "%0d", "0")
PARAMS = [P, L, R, M, S, PA, C1, C2, G]


def indices(dims):
    """Every index tuple of the declared ranges, leftmost dimension first."""
    out = [()]
    for left, right in dims:
        step = 1 if left <= right else -1
        out = [t + (i,) for t in out for i in range(left, right + step, step)]
    return out


def show(v):
    return str(v)


def files():
    sv = (f"/*\n:name: {NAME}\n:description: Elements of unpacked array parameters at constant "
          "indices and at indices known only when they run, inside and outside the array: "
          "module, local, package, child instance and generate parameters of int, 4-state, "
          "real and string elements, in one and two dimensions, read in procedures, "
          "functions, tasks, continuous assignments, always_comb and by hierarchical names\n"
          ":tags: values\n:type: simulation\n:lrm: 1800-2023 6.20 7.4.6 23.10\n"
          ":oracle: spec\n:spec_check: ai\n:fourstate: yes\n:nondeterministic: no\n"
          f":generator: gen_param_array_matrix.py@{VERSION}\n"
          f":expected_stdout: @{NAME}.expected\n*/\n"
          "// Generated by tools/gen_param_array_matrix.py; change the generator, not this "
          "file.\n"
          "// Icarus Verilog 13.0 does not take unpacked array parameters. Verilator 5.052\n"
          "// gives the lines inside the arrays but for the x bits of L; outside them and at x\n"
          "// it reads an element of the array, where 7.4.6 reads the default.\n"
          "package pk;\n  parameter int PA[4] = '{10, 20, 30, 40};\nendpackage\n"
          "module child #(parameter int CP[3] = '{1, 2, 3});\n"
          "  function automatic int get(int k);\n    return CP[k];\n  endfunction\nendmodule\n"
          "module top;\n"
          "  parameter int P[4] = '{5, 6, 7, 8};\n"
          "  localparam logic [7:0] L[3:0] = '{8'h0f, 8'hx0, 8'h33, 8'h44};\n"
          "  localparam real R[2] = '{1.5, -2.25};\n"
          "  localparam int M[2][3] = '{'{1, 2, 3}, '{4, 5, 6}};\n"
          "  localparam string S[2] = '{\"ab\", \"cde\"};\n"
          "  child #(.CP('{7, 8, 9})) c1();\n  child c2();\n"
          "  if (1) begin : g\n    localparam int G[2] = '{100, 200};\n  end\n"
          "  int sel = 0;\n  logic [1:0] xi = 2'bx;\n"
          "  wire [7:0] w = L[sel];\n  real rc;\n  always_comb rc = R[sel];\n"
          "  function automatic int fp(int k);\n    return P[k];\n  endfunction\n"
          "  task automatic tm(int a, int b);\n"
          "    $display(\"task M[%0d][%0d] %0d\", a, b, M[a][b]);\n  endtask\n")
    exp = []
    body = []
    for name, dims, values, fmt, default in PARAMS:
        all_idx = indices(dims)
        # Constant indices, each one written out.
        args = ", ".join(f"{name}" + "".join(f"[{i}]" for i in t) for t in all_idx)
        body.append(f"    $display(\"{name} constant {' '.join([fmt] * len(all_idx))}\", "
                    f"{args});")
        exp.append(f"{name} constant " + " ".join(show(values[t]) for t in all_idx))
        # Indices known when they run: a loop over each dimension, one past
        # the end of the first.
        loops = []
        names = [f"k{d}" for d in range(len(dims))]
        for d, (left, right) in enumerate(dims):
            lo, hi = min(left, right), max(left, right)
            last = hi + 1 if d == 0 else hi
            loops.append((names[d], lo, last))
        pad = "    "
        for var, lo, last in loops:
            body.append(f"{pad}for (int {var} = {lo}; {var} <= {last}; {var}++)")
            pad += "  "
        sub = "".join(f"[{n}]" for n in names)
        body.append(f"{pad}$display(\"{name}{''.join('[%0d]' for _ in names)} {fmt}\", "
                    f"{', '.join(names)}, {name}{sub});")
        ranges = [range(lo, last + 1) for _, lo, last in loops]
        combos = [()]
        for r in ranges:
            combos = [c + (i,) for c in combos for i in r]
        for t in combos:
            v = values.get(t, default)
            exp.append(f"{name}" + "".join(f"[{i}]" for i in t) + f" {show(v)}")
        # An x index.
        xsub = "".join("[xi]" for _ in names)
        body.append(f"    $display(\"{name} at x {fmt}\", {name}{xsub});")
        exp.append(f"{name} at x {default}")
    # The other readers.
    body.append("    for (int k = 0; k < 5; k++)\n"
                "      $display(\"function P[%0d] %0d\", k, fp(k));")
    exp += [f"function P[{k}] {P[2].get((k,), 0)}" for k in range(5)]
    body.append("    tm(1, 2);\n    tm(0, 1);")
    exp += ["task M[1][2] 6", "task M[0][1] 2"]
    body.append("    for (int k = 0; k < 4; k++)\n"
                "      $display(\"child functions %0d %0d %0d\", k, c1.get(k), c2.get(k));")
    for k in range(4):
        exp.append(f"child functions {k} {C1[2].get((k,), 0)} {C2[2].get((k,), 0)}")
    body.append("    for (int k = 0; k < 4; k++) begin\n      sel = k;\n      #1;\n"
                "      $display(\"assign L[%0d] %h always_comb R[%0d] %0.2f\", k, w, k, rc);\n"
                "    end")
    for k in range(4):
        exp.append(f"assign L[{k}] {L[2].get((k,), 'xx')} always_comb R[{k}] "
                   f"{R[2].get((k,), '0.00')}")
    sv += "  initial begin\n" + "\n".join(body) + "\n  end\nendmodule\n"
    return {f"{NAME}.sv": sv, f"{NAME}.expected": "\n".join(exp) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_param_array_matrix: {path.relative_to(OUT.parent.parent.parent)} is "
                      "out of date; run tools/gen_param_array_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
