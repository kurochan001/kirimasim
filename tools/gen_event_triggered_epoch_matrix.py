"""Generate original named-event slot-state checks (15.5.3; SCHEDULER_SPEC 9.4)."""

import argparse
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / 'tests/suite/sched'
VERSION = 1


def output(name, source, expected):
    header = f'''/*
:name: {name}
:description: Named-event triggered state distinguishes no trigger from every valid tick
:tags: sched event triggered
:type: simulation
:lrm: 1800-2023 15.5.3
:fourstate: yes
:nondeterministic: no
:oracle: spec
:spec_check: ai
:generator: gen_event_triggered_epoch_matrix.py@{VERSION}
:top_module: top
:expected_stdout: @{name}.expected
:expected_stderr: @{name}.stderr
*/
// Generated by tools/gen_event_triggered_epoch_matrix.py (version {VERSION}); do not edit.
`timescale 1ns/1ns
'''
    return {name+'.sv': header+source+'\n', name+'.expected': expected, name+'.stderr': ''}


def generated():
    cases = {}
    for home in ('initial', 'task', 'function', 'package', 'interface', 'generate', 'program'):
        for tick in (0, 7, 18446744073709551615):
            name = f'event_triggered_epoch_{home}_{tick}'
            declaration = 'event ready, history, idle;'
            body = '''$display("fresh %0d",ready.triggered);
$display("history %0d",history.triggered);
->ready;
$display("fired %0d",ready.triggered);
$display("idle %0d",idle.triggered);'''
            prefix = f'->history;#(64\'d{tick});'
            if home == 'initial':
                source = f'module top;{declaration}\ninitial begin {prefix}\n{body}\nend endmodule'
            elif home in ('task', 'function'):
                if home == 'task':
                    routine = f'task automatic run_check();\n{body}\nendtask'
                    call = 'run_check();'
                else:
                    routine = f'function automatic int run_check();\n{body}\nreturn 0;endfunction'
                    call = 'unused=run_check();'
                    declaration += 'int unused;'
                source = f'module top;{declaration}\n{routine}\ninitial begin {prefix}{call}end endmodule'
            elif home == 'package':
                source = (f'package helper;{declaration}\ntask automatic run_check();\n{body}\nendtask\nendpackage\n'
                          f'module top;initial begin ->helper::history;#(64\'d{tick});helper::run_check();end endmodule')
            elif home == 'generate':
                source = f'module top;if(1) begin: region\n{declaration}\ninitial begin {prefix}\n{body}\nend end endmodule'
            else:
                keyword = 'interface' if home == 'interface' else 'program'
                source = (f'{keyword} helper;{declaration}\ninitial begin {prefix}\n{body}\nend end{keyword}\n'
                          'module top;helper h();endmodule')
            cases.update(output(name, source, f'fresh 0\nhistory {int(tick==0)}\nfired 1\nidle 0\n'))
    for home in ('global', 'private'):
        for tick in (0, 7, 18446744073709551615):
            name = f'event_triggered_epoch_function_wait_{home}_{tick}'
            event = 'event ready;' if home == 'global' else ''
            local = 'static event ready;' if home == 'private' else ''
            target = 'ready' if home == 'global' else 'top.seen_event.ready'
            source = f'''module top;
{event}
function automatic bit seen_event();{local}return ready.triggered;endfunction
function automatic bit nested_seen();return seen_event();endfunction
int woke;
initial begin
  fork
    begin wait(nested_seen());woke++;$display("woke %0t",$time);end
    begin #(64'd{tick});->{target};end
  join
  $display("total %0d",woke);
end
endmodule'''
            cases.update(output(name, source, f'woke {tick}\ntotal 1\n'))
    return cases


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    files = generated()
    if args.check:
        stale = [name for name, text in files.items() if not (OUT/name).exists() or (OUT/name).read_text() != text]
        if stale:
            print('stale event epoch files: '+', '.join(stale))
            return 1
    else:
        for name, text in files.items():
            (OUT/name).write_text(text)
    print(f'event triggered epoch matrix: {len(files)//3} source designs')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
