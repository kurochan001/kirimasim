"""Generate original program execution matrices (24.3, 24.3.1, 24.6, 24.7).

Axes: lexical subroutine scope, direct/task/fork entry, instance placement,
and 32/129-bit storage. Separate cases cover lifetime, exit, anonymous
program declarations, ports and final execution. Oracles follow the approved
program amendment; no simulator source or external tests are used.
"""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "tests" / "suite" / "proc"
VERSION = 1


def files_for(name, source, expected, top="top"):
    header = f"""/*
:name: {name}
:description: Program scheduling and lifetime mechanism matrix
:tags: proc program scheduling
:type: simulation
:lrm: 1800-2023 24.3 24.3.1 24.3.2 24.6 24.7
:oracle: spec
:spec_check: ai
:fourstate: yes
:nondeterministic: no
:generator: gen_program_execution_matrix.py@{VERSION}
:top_module: {top}
:expected_stdout: @{name}.expected
:expected_stderr: @{name}.stderr
*/
// Generated by tools/gen_program_execution_matrix.py; edit the generator.
`timescale 1ns/1ns
"""
    return {name + ".sv": header + source.rstrip() + "\n", name + ".expected": expected,
            name + ".stderr": ""}


def scheduling(scope, entry, placement, width):
    name = f"program_exec_{scope}_{entry}_{placement}_{width}"
    declaration = """  function automatic shared::value_t read_value(); return shared::source; endfunction
  task automatic step(ref shared::value_t target); target=read_value(); #0; endtask
"""
    package = f"package shared; typedef logic [{width-1}:0] value_t; value_t source;\n"
    package += (declaration if scope == "package" else "") + "endpackage\n"
    interface = "interface view;\n" + (declaration if scope == "interface" else "") + "endinterface\n"
    prefix = {"local": "", "package": "shared::", "module": "top.", "interface": "top.v."}[scope]
    work = {"direct": f"value={prefix}read_value();",
            "task": f"{prefix}step(value);",
            "fork": f"fork begin value={prefix}read_value(); #0; end join"}[entry]
    worker = "program worker;\n  shared::value_t value=0;\n" + (declaration if scope == "local" else "")
    worker += f"""  initial begin
    {work}
    $display("start %0d",value);
    value <= 9;
    #0; $display("inactive %0d",value);
    fork begin #0; $display("child %0d",{prefix}read_value()); end join
    #1; $display("later %0d",value);
  end
  final $display("final %0d",value);
endprogram
"""
    placement_text = {"direct": "worker p();", "generate": "if (1) begin:g worker p(); end",
                      "array": "worker p[2]();", "nested": "middle child();"}[placement]
    top = "module top; view v();\n" + (declaration if scope == "module" else "")
    top += f"""  {placement_text}
  initial begin shared::source=1; shared::source<=7; #10; $display("unexpected future"); end
endmodule
"""
    n = 2 if placement == "array" else 1
    expected = "".join(line * n for line in ["start 7\n", "inactive 7\n", "child 7\n", "later 9\n", "final 9\n"])
    return files_for(name, package + interface + worker + "module middle; worker p(); endmodule\n" + top, expected)


def special():
    cases = {}
    def add(name, source, expected, top="top"):
        cases.update(files_for("program_" + name, source, expected, top))
    add("lifetime_multiple", """program first;
  initial begin fork begin #2; $display("child alive"); #40; $display("unexpected child"); end join_none #1; end
  initial begin #3; $display("first ended"); end
endprogram
program second; initial begin #5; $display("second ended"); end endprogram
module top; first p(); second q(); initial begin #20; $display("unexpected module"); end
  final $display("final %0t",$time);
endmodule""", "child alive\nfirst ended\nsecond ended\nfinal 5\n")
    add("lifetime_join_none", """program worker;
  initial fork begin $display("unexpected child"); end join_none
endprogram
program keeper; initial begin #2; $display("keeper"); end endprogram
module top; worker p(); keeper q(); endmodule""", "keeper\n")
    add("empty_lifetime", """program empty; int value=3; endprogram
module top; empty p(); initial begin #2; $display("module continues"); end
 final $display("final %0t",$time); endmodule""", "module continues\nfinal 2\n")
    add("standalone", """program top;
 int value=6;
 initial begin #0; value<=9; #1; $display("value %0d",value); end
 final $display("final %0d",value);
endprogram""", "value 9\nfinal 9\n")
    add("ports", """program worker(input logic clk,input logic [3:0] d,output logic [3:0] q);
  initial begin @(posedge clk); $display("sample %0d",d); q=d;
    #0; $display("port %0d",top.q); #1; end
endprogram
module top;
 logic clk=0; logic [3:0] d=0; wire [3:0] q;
 worker p(clk,d,q);
 initial begin #2; d=5; d<=7; clk=1; #10; $display("unexpected future"); end
endmodule""", "sample 7\nport 7\n")
    add("anonymous", """package pkg;
 int value;
 program;
   function int read_value(); return value; endfunction
   task automatic pause(); #0; endtask
 endprogram
endpackage
program;
 function int unit_value(); return pkg::value; endfunction
endprogram
program worker;
 initial begin pkg::pause(); $display("program %0d %0d",pkg::read_value(),unit_value()); end
endprogram
module top;
 worker p();
 initial begin pkg::value=1; pkg::value<=7; $display("module %0d",pkg::value); end
endmodule""", "module 1\nprogram 7 7\n")
    add("exit_outside", """package pkg; function void stop_here(); $exit; endfunction endpackage
module top;
 initial begin $exit; pkg::stop_here(); #1; $display("continued"); end
endmodule""", "continued\n")
    add("explicit_finish", """program worker; initial begin #10; $display("unexpected program"); end
 final $display("program final"); endprogram
module top; worker p(); initial begin #1; $finish(0); end endmodule""", "program final\n")
    add("retained_nba", """program first;
 int value=0;
 initial begin value <= #2 9; #1; $exit; end
endprogram
program second;
 initial begin #3; $display("retained %0d",top.p.value); end
endprogram
module top; first p(); second q(); endmodule""", "retained 9\n")
    add("natural_nba", """program first;
 int value=0;
 initial value <= 9;
endprogram
program second;
 initial begin #1; $display("retained %0d",top.p.value); end
endprogram
module top; first p(); second q(); endmodule""", "retained 9\n")
    add("exit_expression", """package pkg;
 function int stop_value(); $exit; return 3; endfunction
 function int unexpected(); $display("unexpected operand"); return 4; endfunction
endpackage
program first; int value;
 initial begin #1; value=pkg::stop_value()+pkg::unexpected(); $display("unexpected caller"); end
endprogram
program second; initial begin #2; $display("keeper"); end endprogram
module top; first p(); second q(); endmodule""", "keeper\n")
    add("grandchild_lifetime", """program first;
 initial begin
   fork begin fork begin #20; $display("unexpected grandchild"); end join_none #1; end join_none
   #2;
 end
endprogram
program second; initial begin #4; $display("keeper"); end endprogram
module top; first p(); second q(); endmodule""", "keeper\n")
    add("deferred_after_completion", """program first;
 function automatic void report_value(); $display("action a"); $display("action b"); endfunction
 initial assert #0 (0) else report_value();
endprogram
program second; initial begin #2; $display("keeper"); end endprogram
module top; first p(); second q(); endmodule""", "action a\naction b\nkeeper\n")
    add("deferred_after_child_kill", """program first;
 function automatic void report_value(); $display("action a"); $display("action b"); endfunction
 initial begin
  fork begin assert #0 (0) else report_value(); #20; end join_none
  #0;
 end
endprogram
program second; initial begin #2; $display("keeper"); end endprogram
module top; first p(); second q(); endmodule""", "action a\naction b\nkeeper\n")
    add("continuous_exit_has_no_initial_origin", """program worker(output wire [31:0] value);
 function automatic int read_value(); $exit; return 7; endfunction
 assign value=read_value();
 initial begin #1; $display("value %0d",value); end
endprogram
module top; wire [31:0] value; worker p(value); endmodule""", "value 7\n")
    add("many_programs", """program worker #(parameter int ID=0);
 initial begin
  fork begin #100; $display("unexpected child"); end join_none
  #(ID+1); top.add_one();
 end
endprogram
module top;
 int ended=0;
 task add_one(); ended++; endtask
 for(genvar i=0;i<32;i++) begin:g worker #(i) p(); end
 final $display("ended %0d time %0t",ended,$time);
endmodule""", "ended 32 time 32\n")
    for scope in ("local", "package", "module", "interface"):
        for origin in ("root", "fork", "task"):
            declaration = "function automatic void stop_here(); $exit; $display(\"unexpected function\"); endfunction\n"
            package = "package pkg;\n" + (declaration if scope == "package" else "") + "endpackage\n"
            interface = "interface view;\n" + (declaration if scope == "interface" else "") + "endinterface\n"
            prefix = {"local": "", "package": "pkg::", "module": "top.", "interface": "top.v."}[scope]
            call = prefix + "stop_here();"
            work = {"root": "#1; " + call, "fork": "fork begin #1; " + call + " end join",
                    "task": "timed_exit();"}[origin]
            worker = "program worker;\n" + (declaration if scope == "local" else "")
            worker += f"""task automatic timed_exit(); #1; {call} endtask
 initial begin {work} $display("unexpected caller"); end
 initial begin #3; $display("unexpected sibling"); end
endprogram
program keeper; initial begin #4; $display("keeper"); end endprogram
"""
            top = "module top; view v(); worker p(); keeper q();\n" + (declaration if scope == "module" else "")
            top += "final $display(\"final %0t\",$time); endmodule\n"
            add(f"exit_{scope}_{origin}", package + interface + worker + top, "keeper\nfinal 4\n")
    return cases


def files():
    result = special()
    for scope in ("local", "package", "module", "interface"):
        for entry in ("direct", "task", "fork"):
            for placement in ("direct", "generate", "array", "nested"):
                for width in (32, 129):
                    result.update(scheduling(scope, entry, placement, width))
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    bad = False
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                print(f"{name}: run tools/gen_program_execution_matrix.py", file=sys.stderr)
                bad = True
        else:
            path.write_text(text)
    return int(bad)


if __name__ == "__main__":
    sys.exit(main())
