"""Orders within a region, of NBAs, and the forms of #0.

The standard fixes that Inactive and NBA follow Active, that NBAs of one process
take effect in order, and that #0 resumes in Inactive (4.4.2, 4.6, 10.4.2). What
it leaves open (4.7, 10.4.2), each test allows in <name>.expected, and
<name>.choice holds the result of SCHEDULER_SPEC.md 4.3 and 13: a change wakes the
processes waiting on it in the order they started to wait, a process runs until it
waits, NBAs apply in the order they were issued, and delayed NBAs come ahead of
those issued in the time slot, by the time they fall due and the order they were
issued. Every expected result is computed here from these rules, not from a run.
"""
import argparse
import itertools
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / 'tests/suite/sched'


def source(name, text, chosen, others=(), lrm='4.4.2 4.6 4.7 10.4.2'):
    """others: results the standard also allows; without any, it fixes the result."""
    name = 'region_order_' + name
    fixed = not others
    single = fixed and '\n' not in chosen
    expected_item = chosen if single else '@' + name + '.expected'
    head = f'''/*
:name: {name}
:description: Orders within a region, of NBAs and of #0 follow the rules of the scheduler
:tags: sched order
:type: simulation
:lrm: 1800-2023 {lrm}
:oracle: spec{'' if fixed else ' choice'}
:spec_check: ai
:fourstate: yes
:nondeterministic: {'no' if fixed else 'yes'}
:generator: gen_region_order_matrix.py@1
:top_module: top
:expected_stdout: {expected_item}
:timeout: 15
*/
// Generated by tools/gen_region_order_matrix.py; edit the generator.
`timescale 1ns/1ns
{text}'''
    candidates = [chosen, *others]
    expected = None if single else '---\n'.join(c + '\n' for c in candidates)
    return name, head, expected, None if fixed else chosen + '\n'


TRIGGERS = {
    'posedge': ('logic s=0;', '@(posedge s)', 's=1;'),
    'negedge': ('logic s=1;', '@(negedge s)', 's=0;'),
    'value': ('logic s=0;', '@(s)', 's=1;'),
    'wait': ('logic s=0;', 'wait(s)', 's=1;'),
}


def wake_order():
    """Waiters written 1, 2, 3 start to wait in every order; they wake in that order."""
    tokens = ('w1', 'w2', 'w3')
    for kind, (declaration, wait, fire) in TRIGGERS.items():
        for order in itertools.permutations((1, 2, 3)):
            starts = {w: position + 1 for position, w in enumerate(order)}
            waiters = ''.join(f'initial begin #{starts[i]}; {wait} $write("w{i},"); end\n' for i in (1, 2, 3))
            text = (f'module top;\n{declaration}\n{waiters}initial begin #10 {fire} #1 $display("end"); $finish; end\n'
                    'endmodule\n')
            chosen = ','.join(f'w{i}' for i in order) + ',end'
            others = [','.join(p) + ',end' for p in itertools.permutations(tokens) if ','.join(p) + ',end' != chosen]
            yield source(f'wake_{kind}_{"".join(map(str, order))}', text, chosen, others, '4.7 9.4.2')


def nbas():
    targets = {
        'whole': ('logic [3:0] v=0;', 'v', 'v'),
        'bit': ('logic [3:0] v=0;', 'v[1]', 'v[1]'),
        'element': ('logic [3:0] m[2]=\'{0,0};', 'm[1]', 'm[1]'),
    }
    for name, (declaration, lhs, read) in targets.items():
        # NBAs of one process: the standard fixes the last one.
        text = (f'module top;\n{declaration}\ninitial begin {lhs}<=1\'b0; {lhs}<=1\'b1; #1 $display("%0d",{read}); end\n'
                'endmodule\n')
        yield source(f'nba_same_process_{name}', text, '1')
        # NBAs of two processes: the order they were issued, whichever is written first.
        for order, starts in (('forward', (1, 2)), ('reverse', (2, 1))):
            last = 1 if starts[0] > starts[1] else 0
            text = (f'module top;\n{declaration}\nlogic go=0;\n'
                    f'initial begin #{starts[0]}; @(posedge go) {lhs}<=1\'b0; end\n'
                    f'initial begin #{starts[1]}; @(posedge go) {lhs}<=1\'b1; end\n'
                    f'initial begin #5 go=1; #1 $display("%0d",{read}); end\nendmodule\n')
            chosen = '0' if last else '1'
            yield source(f'nba_two_processes_{name}_{order}', text, chosen, ['1' if last else '0'])
    # A delayed NBA comes ahead of those issued in its time slot.
    yield source('nba_delayed_ahead_same_process',
                 'module top;\nint v=0;\ninitial begin v<=#1 1; #1 v<=2; #1 $display("%0d",v); end\nendmodule\n', '2', ['1'])
    yield source('nba_delayed_ahead_two_processes',
                 'module top;\nint v=0;\ninitial begin #1 v<=2; end\ninitial v<=#1 1;\ninitial #2 $display("%0d",v);\nendmodule\n',
                 '2', ['1'])
    # Delayed NBAs falling due together: the order they were issued.
    yield source('nba_delayed_same_due',
                 'module top;\nint v=0;\ninitial begin v<=#2 1; #1 v<=#1 2; #2 $display("%0d",v); end\nendmodule\n', '2', ['1'])
    # An NBA falling due earlier applies before a later one.
    yield source('nba_delayed_due_order',
                 'module top;\nint v=0;\ninitial begin v<=#2 1; v<=#1 2; #3 $display("%0d",v); end\nendmodule\n', '1')
    # An NBA is not seen before its region.
    yield source('nba_not_before_inactive',
                 'module top;\nint v=0;\ninitial begin v<=1; $write("%0d,",v); #0 $write("%0d,",v); #1 $display("%0d",v); end\nendmodule\n',
                 '0,0,1')
    yield source('nba_zero_delay_same_slot',
                 'module top;\nint v=0;\ninitial begin v<=#0 1; #0 $write("%0d,",v); #1 $display("%0d",v); end\nendmodule\n',
                 '0,1')
    yield source('nba_wakes_after_issuer',
                 'module top;\nint v=0;\nalways @(v) $write("w%0d,",v);\ninitial begin v<=1; $write("a,"); #1 $display("end"); $finish; end\nendmodule\n',
                 'a,w1,end')


def zero_delays():
    for order, parts in (('zero_first', ('initial begin #0 $write("b,"); end', 'initial $write("a,");')),
                         ('zero_second', ('initial $write("a,");', 'initial begin #0 $write("b,"); end'))):
        yield source(f'zero_after_active_{order}',
                     'module top;\n' + '\n'.join(parts) + '\ninitial #1 $display("end");\nendmodule\n', 'a,b,end')
    yield source('zero_twice_after_once',
                 'module top;\ninitial begin #0; #0; $write("p,"); end\ninitial begin #0; $write("q,"); end\ninitial #1 $display("end");\nendmodule\n',
                 'q,p,end')
    yield source('zero_before_nba_other_process',
                 'module top;\nint v=0;\ninitial begin #0 $write("%0d,",v); end\ninitial v<=1;\ninitial #1 $display("%0d",v);\nendmodule\n',
                 '0,1')
    yield source('zero_twice_before_nba',
                 'module top;\nint v=0;\ninitial begin v<=1; #0; #0 $write("%0d,",v); #1 $display("%0d",v); end\nendmodule\n',
                 '0,1')
    yield source('zero_intra_assignment',
                 'module top;\nint x=0;\nint y=1;\ninitial begin x=#0 y; $write("%0d,",x); end\ninitial begin $write("%0d,",x); y=2; end\ninitial #1 $display("end");\nendmodule\n',
                 '0,1,end')
    yield source('zero_in_program',
                 'program unit;\ninitial begin $write("p,"); #0 $display("q");\nend\nendprogram\nmodule top;\nunit u();\ninitial $write("m,");\nendmodule\n',
                 'm,p,q', lrm='4.4.2 4.4.3 24.3.1')


def run_to_wait():
    """A process runs until it waits (SCHEDULER_SPEC.md 4.3); the standard allows it to be suspended."""
    yield source('process_runs_to_wait',
                 'module top;\nint v=0;\nalways @(v) $write("w,");\ninitial begin v=1; $write("a,"); v=2; $write("b,"); #1 $display("end"); $finish; end\nendmodule\n',
                 'a,b,w,end', ['a,w,b,w,end'], '4.7 9.4.2')
    yield source('process_runs_to_wait_event',
                 'module top;\nevent e;\nalways @(e) $write("w,");\ninitial begin #1 ->e; $write("a,"); #1 $display("end"); $finish; end\nendmodule\n',
                 'a,w,end', ['w,a,end'], '4.7 15.5.1')


def cases():
    yield from wake_order()
    yield from nbas()
    yield from zero_delays()
    yield from run_to_wait()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = list(cases())
    assert len({c[0] for c in generated}) == len(generated)
    failed = False
    for name, text, expected, choice in generated:
        for suffix, content in (('.sv', text), ('.expected', expected), ('.choice', choice)):
            if content is None:
                continue
            path = OUT / (name + suffix)
            if args.check:
                if not path.exists() or path.read_text() != content:
                    print(f'out of date: {path.relative_to(OUT.parent.parent.parent)}')
                    failed = True
            else:
                path.write_text(content)
    print(f'region order matrix: {len(generated)} sources')
    return int(failed)


if __name__ == '__main__':
    raise SystemExit(main())
