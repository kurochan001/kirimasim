"""Generates the matrix test of aggregate initializers that read their own
variable, of TEST_SUITE.md ("Mechanism matrix"), in tests/suite/values/.

  tools/gen_aggregate_init_matrix.py           # writes the files
  tools/gen_aggregate_init_matrix.py --check   # exit 1 if a file differs from what it would write

The initializer of an unpacked array or structure variable is the right
side of an assignment to it, so its whole value is computed before any
element or member is written (VALUE_SEMANTICS.md 3.13; 6.8, 10.4.1,
11.2.2, 10.9.1, 10.9.2). An initializer that reads elements or members of
its own variable therefore reads the values from before the
initialization: here the default of a 2-state integral type, 0 (6.8, 6.21).
The explicit 2-state type keeps the oracle independent of X formatting.
The cases are a
positional pattern, a descending range, a two-dimensional array and a
structure; the containers are a module variable, a static variable of a
block, and automatic variables of a task and of a function, each entered
once. tools/gen_aggregate_assign_matrix.py covers the same rule for
assignments.

The expected outputs follow from the defaults by the rule above. A person
checks them once for all the tests made from them (TEST_SUITE.md,
"Sampling by people").
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "values"
NAME = "aggregate_self_init"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 2

# Cases: (label, type, the declaration with {v} for the variable's name,
# {element spelling with {v}: value after the initialization}); the
# spellings are shown in this order. Every element an initializer reads is
# still 0, the default of the explicit 2-state integer_t type.
CASES = [
    ("positional", "integer_t {v} [0:2] = '{{5, {v}[0], {v}[1]}};",
     {"{v}[0]": 5, "{v}[1]": 0, "{v}[2]": 0}),
    # A pattern for [2:0] fills from the left bound, {v}[2] first (10.9.1).
    ("descending", "integer_t {v} [2:0] = '{{5, {v}[2], {v}[1]}};",
     {"{v}[2]": 5, "{v}[1]": 0, "{v}[0]": 0}),
    ("nested", "integer_t {v} [0:1][0:1] = '{{'{{5, {v}[0][0]}}, '{{{v}[0][1], 6}}}};",
     {"{v}[0][0]": 5, "{v}[0][1]": 0, "{v}[1][0]": 0, "{v}[1][1]": 6}),
    ("struct", "point_t {v} = '{{5, {v}.x, {v}.y}};",
     {"{v}.x": 5, "{v}.y": 0, "{v}.z": 0}),
]


def decls(container, indent):
    """The declarations of every case, and the statements that show them."""
    pad = " " * indent
    dl, shows, exp = [], [], []
    for label, decl, after in CASES:
        v = f"{container}_{label}"
        dl.append(pad + decl.format(v=v))
        spellings = [s.format(v=v) for s in after]
        fmt = " ".join(["%0d"] * len(spellings))
        shows.append(f"{pad}$display(\"{container} {label} {fmt}\", {', '.join(spellings)});")
        exp.append(f"{container} {label} " + " ".join(str(x) for x in after.values()))
    return dl, shows, exp


def files():
    sv = (f"/*\n:name: {NAME}\n:description: The initializer of an unpacked array or structure "
          "computes its whole value before it writes an element or member, so an initializer "
          "that reads its own variable sees the values from before, for each shape, in a "
          "module, a block, a task and a function\n:tags: values\n:type: simulation\n"
          ":lrm: 1800-2023 6.8 6.21 10.4.1 11.2.2 10.9.1 10.9.2\n:oracle: spec\n"
          ":spec_check: ai\n:fourstate: no\n:nondeterministic: no\n"
          f":generator: gen_aggregate_init_matrix.py@{VERSION}\n"
          f":expected_stdout: @{NAME}.expected\n*/\n"
          "// Generated by tools/gen_aggregate_init_matrix.py; change the generator, not "
          "this file.\n"
          "module top;\n"
          "  typedef bit signed [31:0] integer_t;\n"
          "  typedef struct { integer_t x; integer_t y; integer_t z; } point_t;\n")
    exp = []
    module_decls, module_shows, module_exp = decls("module", 2)
    sv += "\n".join(module_decls) + "\n"
    block_decls, block_shows, block_exp = decls("block", 4)
    task_decls, task_shows, task_exp = decls("task", 4)
    func_decls, func_shows, func_exp = decls("function", 4)
    sv += ("  task automatic t();\n" + "\n".join(task_decls) + "\n" + "\n".join(task_shows)
           + "\n  endtask\n")
    sv += ("  function automatic void f();\n" + "\n".join(func_decls) + "\n"
           + "\n".join(func_shows) + "\n  endfunction\n")
    sv += "  initial begin\n"
    sv += "\n".join(f"  {s}" for s in module_shows) + "\n"
    sv += "    begin\n" + "\n".join(
        "  " + d.replace("integer_t ", "static integer_t ", 1).replace("point_t ", "static point_t ", 1)
        for d in block_decls) + "\n"
    sv += "\n".join(f"  {s}" for s in block_shows) + "\n    end\n"
    sv += "    t();\n    f();\n  end\nendmodule\n"
    exp = module_exp + block_exp + task_exp + func_exp
    return {f"{NAME}.sv": sv, f"{NAME}.expected": "\n".join(exp) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_aggregate_init_matrix: {path.relative_to(OUT.parent.parent.parent)} "
                      "is out of date; run tools/gen_aggregate_init_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
