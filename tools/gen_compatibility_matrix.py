"""Generate CLI 2.1 compatibility and strict executable-driver mechanism cases.

Slang owns mode names, parse acceptance and diagnostics. SIR_SPEC 3.4/10 and
SCHEDULER_SPEC 6.4 retain IEEE 1800 6.5/9.2 writer restrictions for execution.
"""

import argparse
import json
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / 'tests/cli/compatibility'
VERSION = 1
MODES = ('default', 'vcs', 'all')


def files():
    prefix = ('// Copyright (c) 2026 The kirimasim Authors\n'
              '// SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception\n'
              f'// Generated by tools/gen_compatibility_matrix.py@{VERSION}.\n')
    sources = {
        'clean.sv': 'module top; initial $display("7"); endmodule\n',
        'enum.sv': ('module top; typedef enum logic[1:0] {A=0,B=1} choice; choice q; int n=1;\n'
                    'initial begin q=n; $display("%0d",q); end endmodule\n'),
        'hierconst.sv': ('module leaf; parameter int P=7; endmodule\n'
                         'module top; leaf u(); localparam int N=u.P; initial $display("%0d",N); endmodule\n'),
        'beforedecl.sv': 'module top; initial $display("%0d",q); int q=7; endmodule\n',
        'stringint.sv': ('module top; string s="ABCD"; int n;\n'
                         'initial begin n=s; $display("%08h",n); end endmodule\n'),
        'local/select.svh': '`define SELECTED_VALUE 7\n',
        'include/select.svh': '`define SELECTED_VALUE 9\n',
        'local/include.sv': ('`include "select.svh"\n'
                              'module top; initial $display("%0d",`SELECTED_VALUE); endmodule\n'),
        'macro.sv': '`define VALUE 7 \\\n  + 1 \\ \n  + 1\nmodule top; initial $display("%0d",`VALUE); endmodule\n',
    }
    behaviors = [
        {'source': 'clean.sv', 'accepted': list(MODES), 'stdout': {m: '7\n' for m in MODES}},
        *[{'source': name + '.sv', 'accepted': ['vcs', 'all'],
           'stdout': {'vcs': out, 'all': out}}
          for name, out in [('enum', '1\n'), ('hierconst', '7\n'),
                            ('beforedecl', '7\n'), ('stringint', '41424344\n')]],
        {'source': 'local/include.sv', 'accepted': list(MODES), 'flags': ['-Iinclude'],
         'stdout': {'default': '7\n', 'vcs': '9\n', 'all': '7\n'}},
        {'source': 'macro.sv', 'accepted': ['vcs'], 'stdout': {'vcs': '9\n'}},
    ]
    drivers = []
    for kind in ('ff', 'comb', 'latch', 'cont', 'mixed'):
        for width in (1, 129):
            for context in ('module', 'interface', 'generate'):
                for overlap in (False, True):
                    for call in (('direct', 'function') if kind in ('ff', 'comb', 'latch') else ('direct',)):
                        name = f'{kind}_w{width}_{context}_{"overlap" if overlap else "separate"}_{call}'
                        first = 'q' if width == 1 else 'q[0]'
                        other = first if overlap else ('r' if width == 1 else 'q[128]')
                        declarations = f'logic [{width-1}:0] q; bit r,clk=0,d=1;\n'
                        if kind in ('ff', 'comb', 'latch'):
                            block = {'ff': f'always_ff @(posedge clk) {first}<=d;',
                                     'comb': f'always_comb {first}=d;',
                                     'latch': f'always_latch if(d) {first}=d;'}[kind]
                            writer = f'initial {other}=0;'
                            if call == 'function':
                                declarations += f'function void write_other(); {other}=0; endfunction\n'
                                writer = 'initial write_other();'
                            body = declarations + block + '\n' + writer + '\n'
                            warning = 'multiple-always-assigns'
                        elif kind == 'cont':
                            body = declarations + f'assign {first}=0; assign {other}=1;\n'
                            warning = 'multiple-cont-assigns'
                        else:
                            body = declarations + f'assign {first}=0; initial {other}=1;\n'
                            warning = 'mixed-var-assigns'
                        body += 'initial begin #1 clk=1; #1 $display("7"); end\n'
                        if context == 'module':
                            source = 'module top;\n' + body + 'endmodule\n'
                        elif context == 'interface':
                            source = 'interface holder;\n' + body + 'endinterface\nmodule top; holder u(); endmodule\n'
                        else:
                            source = 'module top; if(1) begin:g\n' + body + 'end endmodule\n'
                        sources[name + '.sv'] = source
                        drivers.append({'source': name + '.sv', 'overlap': overlap,
                                        'kind': kind, 'warning': warning})
    # Positive boundaries which must not acquire a false source-driver error.
    positives = {
        'resolved_net.sv': 'module top; wire q; assign q=0; assign q=1; initial #1 $display("%b",q); endmodule\n',
        'task_writer.sv': ('module top; bit q,clk=0; task write_other; q=0; endtask\n'
                            'initial write_other(); always_ff @(posedge clk) q<=1;\n'
                            'initial begin #1 clk=1; #1 $display("%b",q); end endmodule\n'),
        'static_init.sv': ('module top; bit q=0,clk=0; always_ff @(posedge clk) q<=1;\n'
                            'initial begin #1 clk=1; #1 $display("%b",q); end endmodule\n'),
    }
    sources.update(positives)
    sources = {name: prefix + content for name, content in sources.items()}
    sources['cases.json'] = json.dumps({'behaviors': behaviors, 'drivers': drivers,
                                      'positives': {'resolved_net.sv': 'x\n', 'task_writer.sv': '1\n',
                                                    'static_init.sv': '1\n'}}, indent=2) + '\n'
    return sources


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    failures = []
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                failures.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    for name in failures:
        print(f'gen_compatibility_matrix: regenerate {name}')
    return bool(failures)


if __name__ == '__main__':
    raise SystemExit(main())
