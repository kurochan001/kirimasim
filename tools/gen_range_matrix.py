"""Generates the slot range matrix tests of TEST_SUITE.md ("Mechanism matrix") in
tests/suite/values/.

  tools/gen_range_matrix.py           # writes the files
  tools/gen_range_matrix.py --check   # exit 1 if a file differs from what it would write

A write of every bit of a variable or element, spelled as a part, an
indexed part, a single-part concatenation or a member of a packed union,
is the same range as the whole (SIR_SPEC.md 3.4), next to a write of the
whole, in either order, in an initial procedure, a static task and an
always_comb (shown later by the initial procedure, so that no line
depends on the order of processes in a time step). Each line shows the
value after both writes, which is the second write's.

The expected outputs follow from the order of the writes. A person checks
them once for all the tests made from them (TEST_SUITE.md, "Sampling by people").
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "values"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

# Ways to write every bit: (label, statement with {t} for the target and
# {v} for the value, the target as a whole).
FORMS = [
    ("part", "{t}[7:0] = {v};"),
    ("indexed", "{t}[0 +: 8] = {v};"),
    ("concat", "{{{t}}} = {v};"),
]
TARGETS = [("var", "v", "v"), ("elem", "a[1]", "a[1]")]


def body(forms, union):
    """Statements, display lines and expected lines for one container."""
    stmts, exp = [], []
    k = 0
    for label, form in forms:
        targets = [("var", "u.word" if union else "v", "u" if union else "v")]
        if not union:
            targets.append(("elem", "a[1]", "a[1]"))
        for tname, part, whole in targets:
            for order in ("part-whole", "whole-part"):
                first, second = (8 + k) % 256, (100 + k) % 256
                p = form.format(t=part, v=f"8'd{first if order == 'part-whole' else second}")
                w = f"{whole} = 8'd{second if order == 'part-whole' else first};"
                if order == "whole-part":
                    p, w = w, p
                stmts.append((f"{label} {tname} {order}", [p, w], whole))
                exp.append(f"{label} {tname} {order} {second}")  # the second write's
                k += 1
    return stmts, exp


def test(union):
    name = "full_width_ranges" + ("_union" if union else "")
    forms = [("member", "{t} = {v};")] if union else FORMS
    stmts, exp = body(forms, union)
    decls = ("  typedef union packed { logic [7:0] word; logic [7:0] other; } u_t;\n  u_t u;\n"
             if union else "  logic [7:0] v;\n  logic [7:0] a [3];\n") + "  logic go = 1'b0;\n"
    sv = (f"/*\n:name: {name}\n:description: A write of every bit of a variable or element, "
          f"spelled {'as a member of a packed union' if union else 'as a part, an indexed part or a concatenation'}, "
          "and a write of the whole, in either order and in several containers, leave the "
          "second value\n:tags: values\n:type: simulation\n:lrm: 1800-2023 11.5.1 11.4.12 "
          f"{'7.3.1 ' if union else ''}10.4 9.2.2.2\n:oracle: spec iverilog@13.0\n:spec_check: ai\n"
          f":fourstate: no\n:nondeterministic: no\n:generator: gen_range_matrix.py@{VERSION}\n"
          f":expected_stdout: @{name}.expected\n*/\n"
          "// Generated by tools/gen_range_matrix.py; change the generator, not this file.\n"
          "module top;\n" + decls)
    lines = []
    for label, (s1, s2), whole in stmts:
        lines.append((label, s1, s2, whole))
    # The variables of the always_comb blocks, declared before use.
    for i in range(len(lines)):
        sv += f"  {'u_t' if union else 'logic [7:0]'} c{i};\n"
    # The initial procedure.
    sv += "  initial begin\n"
    for label, s1, s2, whole in lines:
        sv += f"    {s1}\n    {s2}\n    $display(\"init {label} %0d\", {whole});\n"
    sv += "    run();\n    #1 go = 1'b1;\n    #1;\n"
    for i, (label, s1, s2, whole) in enumerate(lines):
        sv += f"    $display(\"comb {label} %0d\", c{i});\n"
    sv += "  end\n"
    # A static task.
    sv += "  task static run();\n"
    for label, s1, s2, whole in lines:
        sv += f"    {s1}\n    {s2}\n    $display(\"task {label} %0d\", {whole});\n"
    sv += "  endtask\n"
    # always_comb blocks, one per line, woken by go.
    for i, (label, s1, s2, whole) in enumerate(lines):
        tgt = f"c{i}"
        s1c = s1.replace("u.", f"{tgt}.").replace("u =", f"{tgt} =") if union else \
            s1.replace("a[1]", f"{tgt}").replace("v[", f"{tgt}[").replace("{v}", "{" + tgt + "}").replace("v =", f"{tgt} =")
        s2c = s2.replace("u.", f"{tgt}.").replace("u =", f"{tgt} =") if union else \
            s2.replace("a[1]", f"{tgt}").replace("v[", f"{tgt}[").replace("{v}", "{" + tgt + "}").replace("v =", f"{tgt} =")
        sv += (f"  always_comb begin\n    if (go) begin\n      {s1c}\n      {s2c}\n"
               f"    end\n  end\n")
    sv += "endmodule\n"
    out = [f"init {e}" for e in exp] + [f"task {e}" for e in exp] + [f"comb {e}" for e in exp]
    return name, sv, "\n".join(out) + "\n"


def files():
    out = {}
    for union in (False, True):
        name, sv, exp = test(union)
        out[f"{name}.sv"] = sv
        out[f"{name}.expected"] = exp
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_range_matrix: {path.relative_to(OUT.parent.parent.parent)} is out of "
                      "date; run tools/gen_range_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
