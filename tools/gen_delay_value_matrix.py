#!/usr/bin/env python3
"""Generates the delay value matrix test of TEST_SUITE.md ("機構の行列")
in tests/suite/sched/.

  tools/gen_delay_value_matrix.py           # writes the files
  tools/gen_delay_value_matrix.py --check   # exit 1 if a file differs from what it would write

A delay counts time units of the module it is written in. It is rounded
to that module's precision, half away from zero, and then counted in the
design's finest precision; x or z is 0 and a negative value is a 64-bit
unsigned one (3.14.1, 9.4.1, SCHEDULER_SPEC.md 1, 8). A constant delay
and one known only when it runs give the same time (SIR_SPEC.md 7.2).
The axes: what the delay is (a literal, a variable, an expression, a
function call, a real rounded up and down, a shortreal, x and z in a
variable and in a literal, an unsigned and a signed vector, a variable of
the container), where it is used (a
delay control, a blocking and a nonblocking intra-assignment delay, ->>),
the container (an initial procedure, a static and an automatic task, a
fork branch), and the module's timescale (1ns/100ps, and 10ns/1ns in a
child module, so that the design's precision is 100ps). Negative delays
must not come before the end.

The expected outputs follow from the rules above. A person checks them
once for all the tests made from them (TEST_SUITE.md, "人の抜き取り").
"""

import argparse
import math
import sys
from fractions import Fraction
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "sched"
NAME = "delay_value_matrix"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 2

GLOBAL = -10  # the design's precision: 100ps


def ticks(value, unit, precision):
    """Ticks of the design's precision for a delay of `value` time units
    (an int, a Fraction for a real, or None for x and z)."""
    if value is None:
        return 0
    steps = Fraction(value) * Fraction(10) ** (unit - precision)
    whole = math.floor(abs(steps) + Fraction(1, 2))  # half away from zero
    whole = whole if steps >= 0 else -whole
    return whole * 10 ** (precision - GLOBAL)


# What a delay in the top module (1ns/100ps) is: (label, expression, value).
TOP = (-9, -10)
KINDS = [
    ("literal", "3", 3),
    ("variable", "d", 3),
    ("expression", "d + 1", 4),
    ("function", "twice(d)", 6),
    ("real up", "r", Fraction(275, 100)),
    ("real down", "r2", Fraction(104, 100)),
    ("shortreal", "sr", Fraction(1, 2)),
    ("x", "dx", None),
    ("z", "dz", None),
    ("x literal", "8'bx", None),
    ("z literal", "4'b1z01", None),
    ("unsigned vector", "d4", 15),
    ("signed vector", "ds", 5),
]
# The containers and the delay control in them; each also waits on its
# own variable, which is 2.
CONTAINERS = ["initial", "static task", "automatic task", "fork branch"]
# The other uses, in the initial procedure, with some of the kinds.
FORMS = ["blocking", "nonblocking", "trigger"]
FORM_KINDS = ["variable", "real up", "x"]


def kind(label):
    return next(k for k in KINDS if k[0] == label)


def files():
    lines = []
    now = 0

    def step(c, label, expr, value, pad, use="control"):
        nonlocal now
        now += ticks(value, *TOP)
        if use == "control":
            sv = f"{pad}#({expr}) $display(\"{c}: {label} %t\", $realtime);"
        elif use == "blocking":
            sv = (f"{pad}q = #({expr}) q + 1;\n"
                  f"{pad}$display(\"{c}: {label} %t\", $realtime);")
        elif use == "nonblocking":
            sv = (f"{pad}q <= #({expr}) q + 1;\n"
                  f"{pad}@q $display(\"{c}: {label} %t\", $realtime);")
        else:
            sv = (f"{pad}->> #({expr}) e;\n"
                  f"{pad}@e $display(\"{c}: {label} %t\", $realtime);")
        lines.append(f"{c}: {label} {now:>20}")
        return sv

    def body(c, pad):
        out = [step(c, k, e, v, pad) for k, e, v in KINDS]
        out.append(step(c, "container variable", "own", 2, pad))
        return out

    sv = (f"/*\n:name: {NAME}\n:description: Delays known only when they run give the same "
          "times as constant ones: variables, expressions, function calls, reals rounded to the "
          "precision, x and z, vectors, in delay controls, intra-assignment delays and ->>, in "
          "procedures, tasks and fork branches, and in a module of another timescale\n"
          ":tags: sched\n:type: simulation\n:lrm: 1800-2023 3.14.1 9.4.1 9.4.5 15.5.2\n"
          ":oracle: spec iverilog@13.0\n:spec_check: ai\n:fourstate: yes\n"
          ":nondeterministic: no\n"
          f":generator: gen_delay_value_matrix.py@{VERSION}\n"
          f":expected_stdout: @{NAME}.expected\n*/\n"
          "// Generated by tools/gen_delay_value_matrix.py; change the generator, not this "
          "file.\n"
          "// Icarus Verilog 13.0 does not take ->>; with fork #(d) -> e; join_none in its\n"
          "// place, it gives these lines. Verilator 5.052 gives the lines before the ->> ones\n"
          "// and no more, and lets the negative delays come; 9.4.1 reads them as unsigned.\n"
          "`timescale 1ns/100ps\n"
          "module top;\n"
          "  int d = 3;\n  real r = 2.75;\n  real r2 = 1.04;\n  shortreal sr = 0.5;\n"
          "  logic [7:0] dx = 8'bx;\n  logic [7:0] dz = 8'bz;\n  logic [3:0] d4 = 4'hf;\n"
          "  logic signed [3:0] ds = 4'sd5;\n  int neg = -1;\n  real rneg = -2.0;\n"
          "  int q;\n  event e;\n  child c();\n"
          "  function int twice(int v);\n    return 2 * v;\n  endfunction\n")
    # The order they run in: the initial procedure's own steps, the tasks,
    # the fork branch, the other uses, the child module.
    initial_steps = body("initial", "    ")
    static_steps = body("static task", "    ")
    auto_steps = body("automatic task", "    ")
    fork_steps = body("fork branch", "          ")
    form_steps = []
    for f in FORMS:
        for k in FORM_KINDS:
            label, expr, value = kind(k)
            form_steps.append(step(f, label, expr, value, "    ", f))
    child_unit = (-8, -9)
    now += ticks(3, *child_unit)
    lines.append(f"child: variable {now:>20}")
    now += ticks(Fraction(1, 4), *child_unit)
    lines.append(f"child: real {now:>20}")
    sv += ("  task static ts();\n    int own;\n    own = 2;\n" + "\n".join(static_steps) +
           "\n  endtask\n")
    sv += ("  task automatic ta(int own);\n" + "\n".join(auto_steps) + "\n  endtask\n")
    sv += "  initial begin : in_initial\n    int own;\n"
    # Negative delays wait for a time past the end.
    sv += ("    fork\n      #(neg) $display(\"negative int came\");\n"
           "      #(rneg) $display(\"negative real came\");\n    join_none\n")
    sv += "    own = 2;\n" + "\n".join(initial_steps) + "\n"
    sv += "    ts();\n    ta(2);\n"
    sv += ("    fork\n      begin : in_fork\n        int own;\n        own = 2;\n" +
           "\n".join(fork_steps) + "\n      end\n    join\n")
    sv += "\n".join(form_steps) + "\n"
    sv += "    c.run();\n    #1 $finish;\n  end\nendmodule\n"
    sv += ("`timescale 10ns/1ns\nmodule child;\n  int cd = 3;\n  real cr = 0.25;\n"
           "  task run();\n    #(cd) $display(\"child: variable %t\", $realtime);\n"
           "    #(cr) $display(\"child: real %t\", $realtime);\n  endtask\nendmodule\n")
    return {f"{NAME}.sv": sv, f"{NAME}.expected": "\n".join(lines) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_delay_value_matrix: {path.relative_to(OUT.parent.parent.parent)} is "
                      "out of date; run tools/gen_delay_value_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
