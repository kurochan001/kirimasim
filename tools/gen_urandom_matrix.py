"""Generates the matrix tests of $urandom, $urandom_range and the seed
(TEST_SUITE.md, "Mechanism matrix") in tests/suite/proc/.

  tools/gen_urandom_matrix.py           # writes the files
  tools/gen_urandom_matrix.py --check   # exit 1 if a file differs from what it would write

The rules (18.13, 18.14, SYSTEM_TASKS.md 13):

- Each generator is SplitMix64. A random number of 32 bits is the upper
  half of a step's value; a new generator is seeded with a whole step.
- Each module instance has an initialization generator, which starts from
  the default seed (--seed, 0 by default) XOR the FNV-1a hash of its
  hierarchical name. Its procedures take their seeds from it in the order
  of their declaration, before any static initializer runs; a static
  initializer then draws from it.
- A fork branch takes its seed from the forking process's generator,
  branches in order; tasks and functions draw from their caller's.
- $urandom(seed) starts the generator again from the seed's low 32 bits.
  $urandom_range(max, min) swaps the two when max is the smaller, and is
  min + floor(r * (max - min + 1) / 2^32).

The axes: the way of drawing (the cells below) and the container of the
calls (an initial procedure, a task, a function, a fork branch, a task in
a generate block); one more test checks the seeding of instances, static
initializers and nested fork branches, with and without --seed.

The expected outputs come from the rules above, computed here, without
reading kirimasim's code. No other simulator was compared: the standard
leaves the generator to each implementation.
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "proc"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

CONTAINERS = ["initial", "task", "function", "fork", "generate"]
MASK = (1 << 64) - 1


class Rng:
    """SplitMix64 (SYSTEM_TASKS.md 13.1)."""

    def __init__(self, state):
        self.state = state & MASK

    def next(self):
        self.state = (self.state + 0x9e3779b97f4a7c15) & MASK
        z = self.state
        z = ((z ^ (z >> 30)) * 0xbf58476d1ce4e5b9) & MASK
        z = ((z ^ (z >> 27)) * 0x94d049bb133111eb) & MASK
        return z ^ (z >> 31)

    def draw(self):
        return self.next() >> 32

    def child(self):
        return Rng(self.next())

    def range(self, maxval, minval=0):
        if maxval < minval:
            maxval, minval = minval, maxval
        return minval + ((self.draw() * (maxval - minval + 1)) >> 32)


def init(seed, name):
    h = 0xcbf29ce484222325
    for b in name.encode():
        h = ((h ^ b) * 0x100000001b3) & MASK
    return Rng(seed ^ h)


def header(name, description, args=None):
    lines = ["/*", f":name: {name}", f":description: {description}", ":tags: proc",
             ":type: simulation", ":lrm: 1800-2023 18.13 18.14", ":oracle: spec",
             ":spec_check: ai", ":fourstate: yes", ":nondeterministic: no",
             f":generator: gen_urandom_matrix.py@{VERSION}", ":top_module: top"]
    if args:
        lines.append(f":args: {args}")
    lines += [f":expected_stdout: @{name}.expected", f":expected_stderr: @{name}.stderr", "*/",
              "// Generated by tools/gen_urandom_matrix.py; change the generator, not this file.",
              "`timescale 1ns/1ns"]
    return lines


# The statements that draw, in order, and what they print.
BODY = [
    "v[0] = $urandom; v[1] = $urandom;",
    '$display("two: %0d %0d", v[0], v[1]);',
    "v[2] = $urandom_range(10, 1); v[3] = $urandom_range(3, 7); v[4] = $urandom_range(5);",
    "v[5] = $urandom_range(32'hffff_ffff, 0);",
    '$display("ranges: %0d %0d %0d %0d", v[2], v[3], v[4], v[5]);',
    "v[6] = $urandom(42); v[7] = $urandom;",
    '$display("seeded: %0d %0d", v[6], v[7]);',
]


def body_expected(g):
    out = []
    v0, v1 = g.draw(), g.draw()
    out.append(f"two: {v0} {v1}")
    r = [g.range(10, 1), g.range(3, 7), g.range(5), g.range(0xffffffff, 0)]
    out.append("ranges: " + " ".join(str(x) for x in r))
    g.state = 42
    out.append(f"seeded: {g.draw()} {g.draw()}")
    return out


def test(container):
    name = f"urandom_{container}"
    lines = header(name, "$urandom and $urandom_range draw from the generator of the process, "
                         "called from "
                         f"{'an' if container[0] in 'aeiou' else 'a'} {container}")
    lines += ["module top;", "  int unsigned v [0:7];"]
    if container == "task":
        lines += ["  task draw;"] + ["    " + b for b in BODY] + ["  endtask"]
        calls = ["draw;"]
    elif container == "function":
        lines += ["  function void draw();"] + ["    " + b for b in BODY] + ["  endfunction"]
        calls = ["draw();"]
    elif container == "generate":
        lines += ["  if (1) begin : g", "    task draw;"] + ["      " + b for b in BODY] + [
            "    endtask", "  end"]
        calls = ["g.draw;"]
    elif container == "fork":
        calls = ["fork begin"] + ["  " + b for b in BODY] + ["end join"]
    else:
        calls = BODY
    lines.append("  initial begin")
    lines += ["    " + c for c in calls]
    lines += ["  end", "endmodule"]
    main = init(0, "top").child()
    return name, lines, body_expected(main.child() if container == "fork" else main)


def hierarchy_test(seed):
    name = "urandom_hierarchy" + ("" if seed is None else "_seed")
    lines = header(name, "each instance's initialization generator seeds its procedures in "
                         "order before its static initializers draw, and fork branches are "
                         "seeded from their parent" +
                         ("" if seed is None else ", from the seed of --seed"),
                   None if seed is None else f"--seed={seed}")
    lines += ["module m;", "  int unsigned s = $urandom;", "  int unsigned p, q;",
              "  initial p = $urandom;", "  initial q = $urandom_range(100);", "endmodule",
              "module top;", "  m a();", "  m b();", "  int unsigned t = $urandom;",
              "  int unsigned x1, x2, y, after;", "  initial begin", "    fork",
              "      begin", "        x1 = $urandom;", "        fork y = $urandom; join",
              "      end", "      x2 = $urandom;", "    join", "    after = $urandom;",
              '    #1 $display("a: %0d %0d %0d", a.s, a.p, a.q);',
              '    $display("b: %0d %0d %0d", b.s, b.p, b.q);',
              '    $display("top: %0d %0d %0d %0d %0d", t, x1, y, x2, after);', "  end",
              "endmodule"]
    s = 0 if seed is None else seed
    out = []
    for inst in ("top.a", "top.b"):
        g = init(s, inst)
        p = g.child().draw()
        q = g.child().range(100)
        out.append(f"{inst[-1]}: {g.draw()} {p} {q}")
    g = init(s, "top")
    main = g.child()
    t = g.draw()
    b1, b2 = main.child(), main.child()
    x1 = b1.draw()
    y = b1.child().draw()
    x2 = b2.draw()
    out.append(f"top: {t} {x1} {y} {x2} {main.draw()}")
    return name, lines, out


def files():
    out = {}
    tests = [test(c) for c in CONTAINERS] + [hierarchy_test(None), hierarchy_test(12345)]
    for name, lines, stdout in tests:
        out[f"{name}.sv"] = "\n".join(lines) + "\n"
        out[f"{name}.expected"] = "\n".join(stdout) + "\n"
        out[f"{name}.stderr"] = ""
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_urandom_matrix: {path.relative_to(OUT.parent.parent.parent)} is out "
                      "of date; run tools/gen_urandom_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
