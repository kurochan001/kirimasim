"""Generate original blocking intra-assignment repeat-event tests (9.4.5).

Counts retain their width, signedness and four-state domain across waits.
The source value precedes the count; target selection follows the last event.
No external simulator source or tests are used.
"""

import argparse
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / 'tests/suite/sched'
VERSION = 1
HOMES = ('initial', 'task', 'automatic', 'fork', 'interface', 'package', 'program', 'generate')


def output(name, source, expected):
    header = f'''/*
:name: {name}
:description: Blocking repeated event control captures count and RHS once and selects its target after waiting
:tags: sched event repeat
:type: simulation
:lrm: 1800-2023 9.4.2 9.4.5 10.4.1
:oracle: spec
:spec_check: ai
:fourstate: yes
:nondeterministic: no
:generator: gen_repeated_event_matrix.py@{VERSION}
:top_module: top
:expected_stdout: @{name}.expected
:expected_stderr: @{name}.stderr
*/
// Generated by tools/gen_repeated_event_matrix.py; edit the generator.
`timescale 1ns/1ns
'''
    return {name + '.sv': header + source, name + '.expected': expected,
            name + '.stderr': ''}


def qualify(text, prefix, names):
    return re.sub(r'\b(' + '|'.join(names) + r')\b', lambda m: prefix + m[0], text)


def case(home, width, domain):
    name = f'repeated_event_{home}_{domain}_{width}'
    types = f'typedef {domain} [{width-1}:0] word_t;\n'
    declarations = types + '''bit clk=0, mutate=0;
event tick;
int trace, idx, n;
word_t data;
real real_source;
string string_source;
function automatic word_t take_value();
  trace=trace*10+1; return data;
endfunction
function automatic int count_value();
  trace=trace*10+2; data=0; real_source=0; string_source=""; return n;
endfunction
function automatic int pick();
  trace=trace*10+3; return idx++;
endfunction
'''
    body = '''word_t a[2];
logic signed [128:0] nonpositive;
real number;
string text;
time started_at;
a[0]=0; a[1]=0; trace=0; idx=0; n=2; data='1; mutate=1;
a[pick()] = repeat(count_value()) @(posedge clk) take_value();
mutate=0;
$display("capture %0d %0d %0t %b %b",trace,idx,$time,a[0],a[1]);
n=1; real_source=2.5;
number = repeat(count_value()) @(negedge clk) real_source;
$display("real %0.1f %0t",number,$time);
n=1; string_source="saved";
text = repeat(count_value()) @(posedge clk) string_source;
$display("string %s %0t",text,$time);
data='x; a[0] = repeat(n) @(negedge clk) data;
$display("x %b %0t",a[0],$time);
data='z; a[0] = repeat(n) @(posedge clk) data;
$display("z %b %0t",a[0],$time);
a[0] = repeat(2) @(tick) '1;
$display("named %b %0t",a[0],$time);
a[0] = repeat(2) @(tick or negedge clk) '0;
$display("mixed %b %0t",a[0],$time);
a[0] = repeat(2) @(clk ^ mutate) '1;
$display("watch %b %0t",a[0],$time);
{a[0],a[1]} = repeat(1) @(posedge clk) {word_t'('1),word_t'('0)};
$display("concat %b %b %0t",a[0],a[1],$time);
'''
    ones = '1' * width
    zeros = '0' * width
    expected = (f'capture 123 2 3 {zeros} {ones}\nreal 2.5 4\nstring saved 5\n'
                f'x {"x" * width if domain == "logic" else zeros} 6\n'
                f'z {"z" * width if domain == "logic" else zeros} 7\n'
                f'named {ones} 9\nmixed {zeros} 11\nwatch {ones} 13\n'
                f'concat {ones} {zeros} 15\n')
    for label, value in (('zero', '0'), ('negative', '-7'),
                         ('wide_negative', "129'sh1" + '0' * 32),
                         ('x', "'x"), ('z', "'z"),
                         ('mixed_x', "129'b1x"), ('mixed_z', "129'b1z")):
        body += f'''nonpositive={value}; started_at=$time;
a[0] = repeat(nonpositive) @(posedge clk) '1;
$display("skip_{label} %b %0d",a[0],$time-started_at);
'''
        expected += f'skip_{label} {ones} 0\n'
    body += '''trace=0; idx=0; n=0; data='1; started_at=$time;
a[pick()] = repeat(count_value()) @(posedge clk) take_value();
$display("zero_effects %0d %0d %0d %b",trace,idx,$time-started_at,a[0]);
$finish(0);
'''
    expected += f'zero_effects 123 1 0 {ones}\n'
    drive = '''always #1 begin
  clk=~clk;
  if (!clk && mutate) begin idx=1; n=9; end
  ->tick;
end
initial begin #100; $fatal(1,"repeated event timeout"); end
'''
    globals_ = ('clk', 'mutate', 'tick', 'trace', 'idx', 'n', 'data', 'real_source',
                'string_source', 'take_value', 'count_value', 'pick')
    if home in ('interface', 'package'):
        source = f'{home} worker;\n' + declarations + 'task automatic run();\n'
        source += body + f'endtask\nend{home}\nmodule top;\n'
        if home == 'interface':
            source += 'worker w(); initial w.run();\n'
            prefix = 'w.'
        else:
            source += 'initial worker::run();\n'
            prefix = 'worker::'
        source += qualify(drive, prefix, globals_) + 'endmodule\n'
    elif home == 'program':
        source = 'program worker;\n' + types + 'initial begin\n'
        source += qualify(body, 'top.', globals_) + 'end\nendprogram\n'
        source += 'module top;\n' + declarations + 'worker p();\n' + drive + 'endmodule\n'
    else:
        source = 'module top;\n' + ('if(1) begin:g\n' if home == 'generate' else '')
        source += declarations + drive
        if home in ('task', 'automatic'):
            source += ('task automatic run();\n' if home == 'automatic' else 'task run();\n')
            source += body + 'endtask\ninitial run();\n'
        elif home == 'fork':
            source += 'initial fork begin\n' + body + 'end join\n'
        else:
            source += 'initial begin\n' + body + 'end\n'
        source += ('end\n' if home == 'generate' else '') + 'endmodule\n'
    return output(name, source, expected)


def mechanisms():
    result = {}
    for width in (65, 129):
        for signed in (False, True):
            for domain in ('logic', 'bit'):
                suffix = '' if domain == 'logic' else 'bit_'
                name = f'repeated_event_wide_{suffix}{"signed" if signed else "unsigned"}_{width}'
                value = (1 << (width - (2 if signed else 1))) | 1
                source = f'''module top;
bit clk=0; int q;
{domain} {"signed " if signed else ""}[{width-1}:0] count;
always #1 clk=~clk;
initial begin
  count={width}'h{value:x};
  q = repeat(count) @(posedge clk) 7;
  $display("unexpected completion");
end
initial begin #6; $display("still waiting %0d",q); $finish(0); end
endmodule
'''
                result.update(output(name, source, 'still waiting 0\n'))
    result.update(output('repeated_event_count_types', '''module top;
bit clk=0, one;
bit signed [0:0] negative;
logic [0:0] unknown_count;
logic [3:0] two;
int q; time started_at;
always #1 clk=~clk;
initial begin
  one=1; q=repeat(one) @(posedge clk) 7;
  $display("one_bit_unsigned %0d %0t",q,$time);
  negative=1; started_at=$time; q=repeat(negative) @(posedge clk) 9;
  $display("one_bit_signed %0d %0d",q,$time-started_at);
  unknown_count='x; q=repeat(unknown_count) @(posedge clk) 10;
  $display("one_bit_x %0d %0d",q,$time-started_at);
  unknown_count='z; q=repeat(unknown_count) @(posedge clk) 11;
  $display("one_bit_z %0d %0d",q,$time-started_at);
  two=2; q=repeat(two) @(posedge clk) 14;
  $display("four_bit_count %0d %0t",q,$time);
  one=0; started_at=$time; q=repeat(one) @(posedge clk) 15;
  $display("two_state_zero %0d %0d",q,$time-started_at);
  $finish(0);
end
initial begin #100; $fatal(1,"count type timeout"); end
endmodule
''', 'one_bit_unsigned 7 1\none_bit_signed 9 0\none_bit_x 10 0\n'
        'one_bit_z 11 0\nfour_bit_count 14 5\ntwo_state_zero 15 0\n'))
    result.update(output('repeated_event_iff', '''module top;
event tick; logic enabled=0; bit clk=0, mask=1; int a,b;
initial begin
  a = repeat(2) @(tick iff enabled) 7;
  $display("guard %0d %0t",a,$time);
end
initial begin
  b = repeat(2) @(tick iff enabled or posedge (clk & mask)) 9;
  $display("mixed_guard %0d %0t",b,$time);
end
initial begin
  #1; ->tick;
  #1; enabled=1; clk=1;
  #1; ->tick;
  #1; enabled='x; ->tick;
  #1; enabled=1; ->tick;
  #1; $finish(0);
end
endmodule
''', 'mixed_guard 9 3\nguard 7 5\n'))
    result.update(output('repeated_event_container', '''module top;
bit clk=0; int q[$],r[$];
always #1 clk=~clk;
initial begin
  q='{7,9};
  r = repeat(2) @(posedge clk) q;
  $display("snapshot %0d %0d %0d %0d %0d",r.size(),r[0],r[1],q.size(),q[0]);
  r[0]=12; $display("independent %0d %0d",r[0],q[0]);
  $finish(0);
end
initial begin #2; q[0]=99; q.push_back(42); end
endmodule
''', 'snapshot 2 7 9 3 99\nindependent 12 99\n'))
    return result


def files():
    result = mechanisms()
    for home in HOMES:
        for width in (1, 32, 65, 129):
            for domain in ('bit', 'logic'):
                result.update(case(home, width, domain))
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    bad = []
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                bad.append(name)
        else:
            path.write_text(text)
    if bad:
        print('gen_repeated_event_matrix: out of date: ' + ', '.join(bad), file=sys.stderr)
    return int(bool(bad))


if __name__ == '__main__':
    sys.exit(main())
