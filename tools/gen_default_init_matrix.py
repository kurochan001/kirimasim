#!/usr/bin/env python3
"""Generates the default initial value matrix test of TEST_SUITE.md ("機構の
行列") in tests/suite/values/.

  tools/gen_default_init_matrix.py           # writes the files
  tools/gen_default_init_matrix.py --check   # exit 1 if a file differs from what it would write

An automatic variable declared without an initial value starts from the
default of its type each time its scope is entered (6.8, table 6-7,
6.21): x for four-state integral types, 0 for two-state ones, 0.0 for
reals and the empty string for strings; a member of an unpacked
structure from the default of its own type. Each variable is read before
it is written, then written, in a task and a function that are called
twice, a block with an automatic variable inside a static procedure
entered twice by a loop, and a branch of a fork. The second entry must
not see the value written by the first.

The expected outputs follow from table 6-7. A person checks them once for
all the tests made from them (TEST_SUITE.md, "人の抜き取り").
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "values"
NAME = "default_init_auto"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

# (label, declaration with {n} for the name, how to show it with {n}, the
# format, the expected text of the default, a statement writing it)
TYPES = [
    ("logic8", "logic [7:0] {n};", "{n}", "%b", "xxxxxxxx", "{n} = 8'h5a;"),
    ("bit8", "bit [7:0] {n};", "{n}", "%b", "00000000", "{n} = 8'h5a;"),
    ("int", "int {n};", "{n}", "%0d", "0", "{n} = 7;"),
    ("integer", "integer {n};", "{n}", "%0d", "x", "{n} = 7;"),
    ("real", "real {n};", "{n}", "%0.1f", "0.0", "{n} = 2.5;"),
    ("shortreal", "shortreal {n};", "{n}", "%0.1f", "0.0", "{n} = 2.5;"),
    ("string", "string {n};", "{n}", "\\\"%s\\\"", "\"\"", "{n} = \"set\";"),
    ("enum", "state_t {n};", "{n}", "%0d", "x", "{n} = B;"),
    ("packed", "pk_t {n};", "{n}", "%b", "xxxx", "{n} = 4'b1010;"),
    ("member logic", "pair_t {n};", "{n}.l", "%b", "xxxx", "{n}.l = 4'b0101;"),
    ("member string", "pair_t {n};", "{n}.s", "\\\"%s\\\"", "\"\"", "{n}.s = \"m\";"),
]

CONTAINERS = ["task", "function", "loop block", "fork"]


def reads(container, indent):
    """Declarations, then reads and writes of every type, and the lines they show."""
    pad = " " * indent
    decls, body, exp = [], [], []
    for i, (label, decl, show, fmt, default, write) in enumerate(TYPES):
        n = f"v{i}"
        decls.append(pad + decl.format(n=n))
        body.append(pad + f"$display(\"{container} {label} {fmt}\", {show.format(n=n)});")
        body.append(pad + write.format(n=n))
        exp.append(f"{container} {label} {default}")
    return decls, body, exp


def files():
    sv = (f"/*\n:name: {NAME}\n:description: An automatic variable without an initial value "
          "starts from the default of its type, members of unpacked structures included, each "
          "time its scope is entered, in tasks, functions, loop blocks and fork branches\n"
          ":tags: values\n:type: simulation\n:lrm: 1800-2023 6.8 6.21 13.3.1\n"
          ":oracle: spec\n:spec_check: ai\n:fourstate: yes\n:nondeterministic: no\n"
          f":generator: gen_default_init_matrix.py@{VERSION}\n"
          f":expected_stdout: @{NAME}.expected\n*/\n"
          "// Generated by tools/gen_default_init_matrix.py; change the generator, not this "
          "file.\nmodule top;\n"
          "  typedef enum logic [1:0] { A, B } state_t;\n"
          "  typedef struct packed { logic [1:0] h; logic [1:0] l; } pk_t;\n"
          "  typedef struct { logic [3:0] l; string s; } pair_t;\n")
    exp = []
    # A task, called twice.
    decls, body, e = reads("task", 4)
    sv += "  task automatic t();\n" + "\n".join(decls + body) + "\n  endtask\n"
    task_exp = e
    # A function, called twice.
    decls, body, e = reads("function", 4)
    sv += ("  function automatic int f();\n" + "\n".join(decls + body) +
           "\n    return 0;\n  endfunction\n")
    func_exp = e
    sv += "  int k;\n  initial begin\n"
    sv += "    t();\n    t();\n    k = f();\n    k = f();\n"
    # A block in a loop of a static procedure: its automatic variables are
    # made anew at each entry.
    decls, body, e = reads("loop block", 8)
    decls = [d.replace("        ", "        automatic ", 1) for d in decls]
    sv += "    for (int i = 0; i < 2; i++) begin\n" + "\n".join(decls + body) + "\n    end\n"
    loop_exp = e
    # A branch of a fork, twice.
    decls, body, e = reads("fork", 10)
    decls = [d.replace("          ", "          automatic ", 1) for d in decls]
    sv += ("    repeat (2) begin\n      fork\n        begin\n" + "\n".join(decls + body) +
           "\n        end\n      join\n    end\n")
    fork_exp = e
    sv += "  end\nendmodule\n"
    exp = task_exp * 2 + func_exp * 2 + loop_exp * 2 + fork_exp * 2
    return {f"{NAME}.sv": sv, f"{NAME}.expected": "\n".join(exp) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_default_init_matrix: {path.relative_to(OUT.parent.parent.parent)} is "
                      "out of date; run tools/gen_default_init_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
