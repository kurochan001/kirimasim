"""Original class/comb/latch checks under approved class contract 7 and scheduler 6.3.

Ordinary signal arguments wake the body; changing only a property or receiver
does not. Oracles are written from that rule, independently of native output.
"""
import argparse
from pathlib import Path

from gen_class_static_matrix import wrap

OUT = Path(__file__).resolve().parent.parent / 'tests/suite/sched'
HOMES = ('unit', 'module', 'package', 'interface', 'generate')
KINDS = ('comb', 'latch')
WIDTHS = (1, 33, 65, 129)


def source(name, text):
    name = 'class_implicit_' + name
    return name, f'''/*
:name: {name}
:description: Class operations preserve argument-only implicit sensitivity
:tags: sched class sensitivity lifetime
:type: simulation
:lrm: 1800-2023 8.4 9.2.2.2.1
:oracle: spec
:spec_check: ai
:fourstate: yes
:nondeterministic: no
:generator: gen_class_implicit_matrix.py@1
:top_module: top
:expected_stdout: errors=0
:timeout: 15
*/
// Generated by tools/gen_class_implicit_matrix.py; edit the generator.
`timescale 1ns/1ns
{text}'''


def cases():
    for home in HOMES:
        for kind in KINDS:
            for width in WIDTHS:
                definitions = f'''class Box;
logic[{width-1}:0] data;
function new(input logic[{width-1}:0] n='0);data=n;endfunction
function logic[{width-1}:0] read_value(input logic[{width-1}:0] n);return data^n;endfunction
endclass
'''
                for action in ('property', 'method', 'allocate'):
                    allocate = action == 'allocate'
                    declaration = 'Box object,saved;' if allocate else "Box object=new,saved;"
                    calculation = ('object=new(input_value);sampled=object.data;' if allocate
                                   else 'sampled=object.data^input_value;' if action == 'property'
                                   else 'sampled=object.read_value(input_value);')
                    gate = 'if(enable)' if kind == 'latch' else ''
                    actor = f'''{declaration}
logic[{width-1}:0] input_value='0,sampled;
bit enable=1;
int hits=0;
always_{kind} {gate} begin {calculation} ++hits;end
'''
                    body = "int errors=0;\n#1;if(sampled!=='0 || hits!=1)++errors;\n"
                    if allocate:
                        body += "saved=object;#1;if(object!=saved || hits!=1)++errors;\n"
                        for value in ("'1", "'x", "'z", "'0"):
                            body += f"input_value={value};#1;if(sampled!=={value} || object==saved)++errors;saved=object;\n"
                    else:
                        body += "object.data='1;#1;if(sampled!=='0 || hits!=1)++errors;\n"
                        body += "object=new;object.data='x;#1;if(sampled!=='0 || hits!=1)++errors;\n"
                        for field, value, expected in (("'x", "'1", "'x"), ("'0", "'x", "'x"),
                                                       ("'1", "'z", "'x"), ("'1", "'0", "'1")):
                            body += f"object.data={field};input_value={value};#1;if(sampled!=={expected})++errors;\n"
                    body += "if(hits!=5)++errors;\n"
                    if kind == 'latch':
                        expected = "'z" if allocate else "'x"
                        body += "enable=0;#1;input_value='1;#1;if(hits!=5)++errors;\n"
                        if not allocate:
                            body += "object.data='z;\n"
                        body += "input_value='z;#1;if(hits!=5)++errors;enable=1;#1;\n"
                        body += f"if(hits!=6 || sampled!=={expected})++errors;\n"
                    body += '$display("errors=%0d",errors);\n'
                    yield source(f'{home}_{kind}_{width}_{action}',
                                 wrap(home, definitions, body, actor=actor))


def probes():
    common = ('class Box;int value=7;function int read_value(input int n);'
              'return value+n;endfunction endclass\n')
    rows = [
        ('comb_method_argument', 'always_comb observed=object.read_value(input_value);',
         '8\n10\n10\n'),
        ('comb_property_signal', 'always_comb observed=object.value+input_value;',
         '8\n10\n10\n'),
        ('latch_method_argument', 'always_latch if(gate) observed=object.read_value(input_value);',
         '8\n10\n10\n'),
    ]
    for name, process, expected in rows:
        yield ('class_implicit_' + name, '8.4; 9.2.2.2.1',
               common + 'module top;Box object=new;int input_value=1,observed;bit gate=1;' +
               process + 'initial begin #1;$display("%0d",observed);input_value=3;'
               '#1;$display("%0d",observed);object.value=20;#1;$display("%0d",observed);'
               'end endmodule\n', expected, [])
    yield ('class_implicit_property_only', '8.4; 9.2.2.2.1',
           common + 'module top;Box object=new;int observed;always_comb observed=object.value;'
           'initial begin #1;$display("%0d",observed);object.value=20;'
           '#1;$display("%0d",observed);end endmodule\n', '7\n7\n', [])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = dict(cases())
    failed = False
    for name, text in generated.items():
        path = OUT / (name + '.sv')
        if args.check:
            if not path.exists() or path.read_text() != text:
                print(f'out of date: {path.name}')
                failed = True
        else:
            path.write_text(text)
    print(f'class implicit matrix: {len(generated)} sources')
    return int(failed)


if __name__ == '__main__':
    raise SystemExit(main())
