"""Generates the matrix test of NBAs to string characters of TEST_SUITE.md
("Mechanism matrix") in tests/suite/sched/.

  tools/gen_string_char_nba_matrix.py           # writes the files
  tools/gen_string_char_nba_matrix.py --check   # exit 1 if a file differs from what it would write

The rule: SCHEDULER_SPEC.md 13 (approved 2026-10-30), with 10.4.2, 6.16.2
and 13.5.2 of the standard. s[i] <= c, with a delay, with an event control
or with neither, keeps the string, the index and the byte from when the
statement runs, and writes the byte at that index of the string held when
the update applies, as putc would then: the other characters keep the
values they have then, and an index outside that string writes nothing.
The axes: the target (a string variable, an element of a string array at
a constant and at a run-time index, a string and an element of a string
array through `ref static`), the kind of NBA (none, #1, @e), the container
of the statement for the direct targets (initial, an automatic task, a fork
branch), and what happens between the NBA and its update (nothing, a
blocking write of another character, the string replaced by one of the
same length, shortened past the index, lengthened, and an NBA to another
character). The index and the array index change after the NBA is issued,
so a target computed late writes elsewhere. Each case shows the string one
step after the NBA, where only the update without a delay has applied, and
after e has triggered and the delay has passed.

A person checks the expected output once for all the tests made from it
(TEST_SUITE.md, "Sampling by people").
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "sched"
NAME = "string_char_nba_matrix"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

INITIAL = "abcd"
INDEX = 2
BYTE = "q"

# The target: the string the NBA writes, as the display names it, and the
# statement with T for the timing control.
TARGETS = [
    ("variable", "sv", "sv[i] <= T\"q\";", True),
    ("element", "sa[1]", "sa[1][i] <= T\"q\";", True),
    ("runtime_element", "sa[1]", "sa[k][i] <= T\"q\";", True),
    ("ref", "sv", None, False),
    ("ref_element", "sa[1]", None, False),
]
KINDS = [("plain", ""), ("delayed", "#1 "), ("event", "@e ")]
CONTAINERS = ["initial", "task", "fork"]
# What happens after the NBA is issued and before it applies: the
# statement on the target {X}, and the string it leaves (before the update).
BETWEEN = [
    ("nothing", "", INITIAL, None),
    ("neighbour", "{X}[0] = \"n\";", "nbcd", None),
    ("replaced", "{X} = \"WXYZ\";", "WXYZ", None),
    ("shortened", "{X} = \"AB\";", "AB", None),
    ("lengthened", "{X} = \"ABCDEFG\";", "ABCDEFG", None),
    ("other_nba", "{X}[0] <= \"o\";", INITIAL, (0, "o")),
]


def put(text, index, byte):
    """s.putc(index, byte) (6.16.2)."""
    if 0 <= index < len(text) and byte != "\0":
        text = text[:index] + byte + text[index + 1:]
    return text


def files():
    head = [
        "/*",
        f":name: {NAME}",
        ":description: an NBA to a string character, with a delay, an event control or neither, "
        "writes its byte into the string held when it applies, through variables, array "
        "elements and refs, in every container",
        ":tags: sched string",
        ":type: simulation",
        ":lrm: 1800-2023 10.4.2 6.16.2 13.5.2 9.4.2",
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: no",
        ":nondeterministic: no",
        f":generator: gen_string_char_nba_matrix.py@{VERSION}",
        f":expected_stdout: @{NAME}.expected",
        "*/",
        "// Generated by tools/gen_string_char_nba_matrix.py; change the generator, not this file.",
        "`timescale 1ns/1ns",
        "module top;",
        "  string sv, sa[3];",
        "  int i, k;",
        "  event e;",
    ]
    subs, body, expected = [], [], []
    n = 0
    for target, shown, statement, direct in TARGETS:
        for kind, timing in KINDS:
            for container in CONTAINERS if direct else ["task"]:
                for between, change, left, other in BETWEEN:
                    label = f"{target} {kind} {container} {between}"
                    if direct:
                        issue = statement.replace("T", timing)
                        if container == "initial":
                            run = [issue]
                        elif container == "task":
                            subs += [f"  task automatic t{n}();", f"    {issue}", "  endtask"]
                            run = [f"t{n}();"]
                        else:
                            run = ["fork", f"  begin {issue} end", "join"]
                    elif target == "ref":
                        subs += [f"  task automatic t{n}(ref static string r);",
                                 f"    r[i] <= {timing}\"q\";", "  endtask"]
                        run = [f"t{n}(sv);"]
                    else:
                        subs += [f"  task automatic t{n}(ref static string r[3]);",
                                 f"    r[k][i] <= {timing}\"q\";", "  endtask"]
                        run = [f"t{n}(sa);"]
                    body += [f"    // {label}",
                             f"    sv = \"{INITIAL}\"; sa = '{{\"{INITIAL}\", \"{INITIAL}\", "
                             f"\"{INITIAL}\"}}; i = {INDEX}; k = 1;"]
                    body += ["    " + line for line in run]
                    body += ["    i = 0; k = 2;"]
                    if change:
                        body += ["    " + change.replace("{X}", shown)]
                    # One step later the update without a delay has applied,
                    # the delayed one (due then, in NBA) and the one waiting
                    # for e have not; e then triggers it.
                    body += ["    #1;", f'    $display("{label} before %s", {shown});',
                             "    -> e;", "    #2;",
                             f'    $display("{label} after %s %s", {shown}, sa[2]);']
                    if other:
                        left = put(left, *other)
                    result = put(left, INDEX, BYTE)
                    expected.append(f"{label} before {result if kind == 'plain' else left}")
                    expected.append(f"{label} after {result} {INITIAL}")
                    n += 1
    sv = head + subs + ["  initial begin"] + body + ["  end", "endmodule", ""]
    return {f"{NAME}.sv": "\n".join(sv), f"{NAME}.expected": "\n".join(expected) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_string_char_nba_matrix: {path.relative_to(OUT.parent.parent.parent)} is "
                      "out of date; run tools/gen_string_char_nba_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
