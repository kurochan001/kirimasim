"""Generates the matrix tests of an unsized based literal whose leftmost
digit is x or z, in a context wider than 32 bits (TEST_SUITE.md,
"Mechanism matrix") in tests/suite/values/.

  tools/gen_unsized_xz_literal_matrix.py           # writes the files
  tools/gen_unsized_xz_literal_matrix.py --check   # exit 1 if a file differs from what it would write

The rule: 5.7.1 of the standard. An unsized unsigned based literal whose
leftmost digit is x or z is extended with x or z to the width of the
expression it is in, however wide that is. A literal whose leftmost
digit is a known digit is extended with 0, and so is a sized literal or
a variable that holds x: only the unsized literal carries x or z into
the bits it has no digit for.

The axes: the literal ('hx, 'hz, 'bx, 'oz, 'h?, x or z in front of
known digits, a known digit in front of x; and the controls: a sized
literal and a variable), the width of the target (31, 32, 33, 48, 64,
65, 129), the kind of assignment (the initializer of a declaration, a
blocking assignment, a nonblocking assignment, a continuous assignment,
the argument of a function), and the container (an initial procedure, a
task, a function).

The expected output is computed here from the digits, without reading
kirimasim's code. A person checks it once for all the tests made from it
(TEST_SUITE.md, "Sampling by people").
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "values"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

WIDTHS = [31, 32, 33, 48, 64, 65, 129]
CONTAINERS = ["initial", "task", "function"]

# (key, the literal, its digits as bits from the left, the bit that fills
# the bits above them).
LITERALS = [
    ("hx", "'hx", "xxxx", "x"),
    ("hz", "'hz", "zzzz", "z"),
    ("bx", "'bx", "x", "x"),
    ("oz", "'oz", "zzz", "z"),
    ("question", "'h?", "zzzz", "z"),
    ("z_then_digit", "'hZ5", "zzzz0101", "z"),
    ("x_then_digits", "'bx01", "x01", "x"),
    ("digit_then_x", "'h1x", "0001xxxx", "0"),
    # The controls: a sized literal and a variable are extended with 0.
    ("sized", "8'hx", "xxxxxxxx", "0"),
    ("variable", "held", "xxxxxxxx", "0"),
]
# (key, how the value reaches the target t from the source text s).
KINDS = ["declaration", "blocking", "nonblocking", "continuous", "argument"]


def bits(width, digits, fill):
    """The value at this width: the digits at the right, the fill above."""
    if len(digits) >= width:
        return digits[len(digits) - width:]
    return fill * (width - len(digits)) + digits


def test(container):
    name = f"unsized_xz_literal_{container}"
    where = {"initial": "an initial procedure", "task": "a task",
             "function": "a function"}[container]
    sv = ["/*", f":name: {name}",
          ":description: an unsized based literal whose leftmost digit is x or z fills a "
          "context of 31 to 129 bits with x or z, and a sized literal or a variable does "
          f"not, read from {where}",
          ":tags: values", ":type: simulation", ":lrm: 1800-2023 5.7.1 11.6.1", ":oracle: spec",
          ":spec_check: ai", ":fourstate: yes", ":nondeterministic: no",
          f":generator: gen_unsized_xz_literal_matrix.py@{VERSION}", ":top_module: top",
          f":expected_stdout: @{name}.expected", "*/",
          "// Generated by tools/gen_unsized_xz_literal_matrix.py; change the generator, not "
          "this file.", "`timescale 1ns/1ns", "module top;", "  logic [7:0] held = 8'hx;"]
    decls, first, second, expected = [], [], [], []
    for w in WIDTHS:
        decls.append(f"function automatic logic [{w - 1}:0] pass{w}(logic [{w - 1}:0] a); "
                     "return a; endfunction")
    for key, text, digits, fill in LITERALS:
        for w in WIDTHS:
            want = bits(w, digits, fill)
            for kind in KINDS:
                # An initializer is a constant expression: no variable there.
                if kind == "declaration" and key == "variable":
                    continue
                t = f"{key}_{kind}_{w}"
                label = f"{key} {kind} {w}"
                if kind == "declaration":
                    decls.append(f"logic [{w - 1}:0] {t} = {text};")
                elif kind == "continuous":
                    decls.append(f"wire [{w - 1}:0] {t};")
                    decls.append(f"assign {t} = {text};")
                else:
                    decls.append(f"logic [{w - 1}:0] {t};")
                    if kind == "blocking":
                        first.append(f"{t} = {text};")
                    elif kind == "nonblocking":
                        first.append(f"{t} <= {text};")
                    else:
                        first.append(f"{t} = pass{w}({text});")
                second.append(f'$display("{label}: %b", {t});')
                expected.append(f"{label}: {want}")
    sv += ["  " + d for d in decls]
    # The assignments first; the values are read one time unit later, after
    # the nonblocking and the continuous assignments.
    if container == "initial":
        sv += ["  initial begin"] + ["    " + x for x in first] + ["    #1;"]
        sv += ["    " + x for x in second] + ["  end"]
    elif container == "task":
        sv += ["  task automatic run();"] + ["    " + x for x in first] + ["    #1;"]
        sv += ["    " + x for x in second] + ["  endtask", "  initial run();"]
    else:
        sv += ["  function automatic void write();"] + ["    " + x for x in first]
        sv += ["  endfunction", "  function automatic void show();"]
        sv += ["    " + x for x in second] + ["  endfunction"]
        sv += ["  initial begin", "    write();", "    #1;", "    show();", "  end"]
    sv += ["endmodule"]
    return name, sv, expected


def files():
    out = {}
    for container in CONTAINERS:
        name, sv, expected = test(container)
        out[f"{name}.sv"] = "\n".join(sv) + "\n"
        out[f"{name}.expected"] = "\n".join(expected) + "\n"
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print("gen_unsized_xz_literal_matrix: "
                      f"{path.relative_to(OUT.parent.parent.parent)} is out of date; run "
                      "tools/gen_unsized_xz_literal_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
