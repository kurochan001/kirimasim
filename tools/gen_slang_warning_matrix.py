"""Generate source-warning CLI cases for the approved CLI.md 2.1 pass-through.

The axes are warning enable/suppression/error/ordering/unknown names, parse
or simulation, direct or argument-file options, and position before or after
the source. The reference for option behavior is the pinned slang driver;
source truncation itself follows IEEE 1800-2023 10.8 and 11.6.
"""

import argparse
import json
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / 'tests/cli/slang_warnings'
VERSION = 1


def files():
    prefix = ('// Copyright (c) 2026 The kirimasim Authors\n'
              '// SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception\n'
              f'// Generated by tools/gen_slang_warning_matrix.py@{VERSION}.\n')
    sources = {
        'width.sv': prefix + ('module top;\n  bit [7:0] wide = 18;\n  bit [3:0] narrow;\n'
                             '  initial begin\n    narrow = wide;\n'
                             '    $display("%0d", narrow);\n  end\nendmodule\n'),
        'clean.sv': prefix + 'module top; initial $display("7"); endmodule\n',
    }
    # name, options, source, exit, output, severity, diagnostic spelling
    rows = [
        ('default', [], 'width', 0, '2\n', '', ''),
        ('enable', ['-Wwidth-trunc'], 'width', 0, '2\n', 'warning', 'width-trunc'),
        ('suppress', ['-Wno-width-trunc'], 'width', 0, '2\n', '', ''),
        ('error', ['-Werror=width-trunc'], 'width', 2, '', 'error', 'width-trunc'),
        ('enable_then_suppress', ['-Wwidth-trunc', '-Wno-width-trunc'], 'width', 0, '2\n', '', ''),
        ('suppress_then_enable', ['-Wno-width-trunc', '-Wwidth-trunc'], 'width', 0, '2\n', 'warning', 'width-trunc'),
        ('global_error', ['-Wwidth-trunc', '-Werror'], 'width', 2, '', 'error', 'width-trunc'),
        ('global_error_suppressed', ['-Wwidth-trunc', '-Werror', '-Wno-width-trunc'], 'width', 0, '2\n', '', ''),
        ('global_error_clean', ['-Werror'], 'clean', 0, '7\n', '', ''),
        ('enabled_clean', ['-Wwidth-trunc'], 'clean', 0, '7\n', '', ''),
        ('unknown', ['-Wnot-a-slang-warning'], 'clean', 0, '7\n', 'warning', 'unknown-warning-option'),
        ('unknown_error', ['-Werror=unknown-warning-option', '-Wnot-a-slang-warning'], 'clean', 2, '', 'error', 'unknown-warning-option'),
    ]
    cases = [dict(zip(('name', 'flags', 'source', 'exit', 'stdout', 'severity', 'diagnostic'), row))
             for row in rows]
    return {**sources, 'cases.json': json.dumps(cases, indent=2) + '\n'}


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    bad = []
    for name, content in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                bad.append(name)
        else:
            OUT.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    for name in bad:
        print(f'gen_slang_warning_matrix: regenerate {name}')
    return bool(bad)


if __name__ == '__main__':
    raise SystemExit(main())
