"""Generates the matrix tests of input ports of an unpacked structure type
declared with no var keyword (TEST_SUITE.md, "Mechanism matrix") in
tests/suite/ports/.

  tools/gen_struct_net_input_port_matrix.py           # writes the files
  tools/gen_struct_net_input_port_matrix.py --check   # exit 1 if a file differs from what it would write

The rule: 23.3.3 of the standard and P1_SUPPORT.md, "Hierarchy". An
input port follows the expression it is connected to. "input st_t s"
has no var keyword, so 23.2.2.3 makes it a net; kirimasim runs it as the
variable that "input var st_t s" declares, as it does the input ports of
real and container types: the port has one source, its connection.

The axes: the structure (4-state members only, which 6.7.1 allows as
the type of a net; a 2-state member too; a nested structure; an array
member), the actual (a variable, a variable of a generate block), the
design element that has the port (a module, an interface, a program) and
the reader inside it (a procedure at fixed times, a continuous
assignment to an output).

Each instance reads at times of its own, between the changes of the
source. The expected output is computed here from the values, without
reading kirimasim's code. A person checks it once for all the tests made
from it (TEST_SUITE.md, "Sampling by people").
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "ports"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

ELEMENTS = ["module", "interface", "program"]
# (key, the typedefs, the members printed, their values at the two times).
STRUCTS = [
    ("four", "typedef struct { logic [7:0] a; logic b; } four_t;", ["a", "b"],
     [[0x3c, 1], [0x5a, 0]]),
    ("two", "typedef struct { int n; logic [3:0] c; } two_t;", ["n", "c"], [[7, 9], [-2, 3]]),
    ("nested", "typedef struct { four_t f; logic g; } nested_t;", ["f.a", "f.b", "g"],
     [[0x11, 0, 1], [0x22, 1, 0]]),
    ("array", "typedef struct { logic [3:0] r [2]; } array_t;", ["r[0]", "r[1]"],
     [[4, 5], [6, 7]]),
]


def assigns(target, struct, k):
    return " ".join(f"{target}.{m} = {v};" for m, v in zip(struct[2], struct[3][k]))


def test(element):
    name = f"struct_net_input_port_{element}"
    end = {"module": "endmodule", "interface": "endinterface", "program": "endprogram"}[element]
    sv = ["/*", f":name: {name}",
          ":description: an input port of an unpacked structure type declared with no var "
          f"keyword follows its connection, as a port of {'an' if element == 'interface' else 'a'} "
          f"{element}",
          ":tags: ports", ":type: simulation", ":lrm: 1800-2023 23.3.3 23.2.2.3", ":oracle: spec",
          ":spec_check: ai", ":fourstate: yes", ":nondeterministic: no",
          f":generator: gen_struct_net_input_port_matrix.py@{VERSION}", ":top_module: top",
          f":expected_stdout: @{name}.expected", "*/",
          "// Generated by tools/gen_struct_net_input_port_matrix.py; change the generator, not "
          "this file.", "`timescale 1ns/1ns"]
    sv += [s[1] for s in STRUCTS]
    expected = []
    top = []
    lag = 0
    for key, _, members, values in STRUCTS:
        fmt = " ".join(f"{m}=%0d" for m in members)
        args = ", ".join(f"s.{m}" for m in members)
        show = f'$display("{key} %0d: {fmt}", $time, {args});'
        sv += [f"{element} read_{key} (input {key}_t s);",
               f"  initial begin #{2 + lag} {show} #6 {show} end"]
        if element == "program":
            sv += ["  initial #20;"]
        sv += [end]
        top += [f"  {key}_t x_{key};", f"  read_{key} u_{key} (.s(x_{key}));"]
        for k, at in ((0, 2 + lag), (1, 8 + lag)):
            expected.append((at, f"{key} {at}: " + " ".join(
                f"{m}={v}" for m, v in zip(members, values[k]))))
        lag += 1
    # A module passes its input on with a continuous assignment; the
    # variable outside is in a generate block.
    sv += ["module pass (input four_t s, output four_t o);", "  assign o = s;", "endmodule"]
    sv += ["module top;"] + top
    sv += ["  if (1) begin : g", "    four_t y;", "  end", "  four_t z;",
           "  pass p (.s(g.y), .o(z));", "  initial begin"]
    sv += [f"    #1 {assigns('x_' + s[0], s, 0)}" if i == 0 else f"    {assigns('x_' + s[0], s, 0)}"
           for i, s in enumerate(STRUCTS)]
    sv += [f"    {assigns('g.y', STRUCTS[0], 0)}",
           '    #5 $display("passed %0d: a=%0d b=%0d", $time, z.a, z.b);']
    expected.append((6, f"passed 6: a={STRUCTS[0][3][0][0]} b={STRUCTS[0][3][0][1]}"))
    sv += [f"    #1 {assigns('x_' + s[0], s, 1)}" if i == 0 else f"    {assigns('x_' + s[0], s, 1)}"
           for i, s in enumerate(STRUCTS)]
    sv += [f"    {assigns('g.y', STRUCTS[0], 1)}",
           '    #5 $display("passed %0d: a=%0d b=%0d", $time, z.a, z.b);',
           "    #3 $finish(0);", "  end", "endmodule"]
    expected.append((12, f"passed 12: a={STRUCTS[0][3][1][0]} b={STRUCTS[0][3][1][1]}"))
    expected.sort(key=lambda e: e[0])
    return name, sv, [e[1] for e in expected]


def files():
    out = {}
    for element in ELEMENTS:
        name, sv, expected = test(element)
        out[f"{name}.sv"] = "\n".join(sv) + "\n"
        out[f"{name}.expected"] = "\n".join(expected) + "\n"
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print("gen_struct_net_input_port_matrix: "
                      f"{path.relative_to(OUT.parent.parent.parent)} is out of date; run "
                      "tools/gen_struct_net_input_port_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
