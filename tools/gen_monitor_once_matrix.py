"""Generates the matrix tests of how often $monitor and $fmonitor evaluate
their arguments (TEST_SUITE.md, "Mechanism matrix") in tests/suite/proc/.

  tools/gen_monitor_once_matrix.py           # writes the files
  tools/gen_monitor_once_matrix.py --check   # exit 1 if a file differs from what it would write

The rule: 21.2.3 of the standard and SYSTEM_TASKS.md 4. At the end of a
time when an argument changed, $monitor prints its arguments once, as
$display does: each argument is evaluated once, and the value that is
compared with the one shown last is the value that is printed.

Each test monitors a variable and a function of it that counts its calls
in a static variable of its own, which a function called in the Postponed
region may write (SCHEDULER_SPEC.md 2). The count printed is then the
number of times the monitor ran: 1 at the time of the call, and one more
at each time the variable changes.

The axes: the task ($monitor, its b, o and h forms, and $fmonitor to
standard output), the format of the variable (%0d, and %p, which prints
an int the same way), and the container of the call (an initial
procedure, a task, an initial procedure of a generate block).

The expected output is written from the rule above, without reading
kirimasim's code. A person checks it once for all the tests made from it
(TEST_SUITE.md, "Sampling by people").
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "proc"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

# (suffix, the call up to its format).
TASKS = [("monitor", "$monitor("), ("monitorb", "$monitorb("), ("monitoro", "$monitoro("),
         ("monitorh", "$monitorh("), ("fmonitor", "$fmonitor(1, ")]
FORMATS = [("d", "%0d"), ("p", "%p")]
CONTAINERS = ["initial", "task", "generate"]

# The values the variable takes, one time unit apart, after its start at 0.
VALUES = [5, 7, 1]


def test(task, call, key, conv, container):
    name = f"monitor_once_{task}_{key}_{container}"
    where = {"initial": "an initial procedure", "task": "a task",
             "generate": "an initial procedure of a generate block"}[container]
    lines = ["/*", f":name: {name}",
             f":description: ${task} called from {where} evaluates each argument once when it "
             f"prints: a function that counts its calls, beside a variable printed with {conv}",
             ":tags: proc", ":type: simulation", ":lrm: 1800-2023 21.2.3 21.3.2", ":oracle: spec",
             ":spec_check: ai", ":fourstate: no", ":nondeterministic: no",
             f":generator: gen_monitor_once_matrix.py@{VERSION}", ":top_module: top",
             f":expected_stdout: @{name}.expected", "*/",
             "// Generated by tools/gen_monitor_once_matrix.py; change the generator, not this "
             "file.", "`timescale 1ns/1ns", "module top;", "  int a;",
             "  function automatic int count(int x);", "    static int calls = 0;",
             "    calls++;", "    return calls;", "  endfunction"]
    start = f'{call}"{conv} %0d", a, count(a));'
    if container == "task":
        lines += ["  task start;", f"    {start}", "  endtask"]
        start = "start;"
    if container == "generate":
        lines += ["  if (1) begin : g", f"    initial {start}", "  end", "  initial begin"]
    else:
        lines += ["  initial begin", f"    {start}"]
    lines += [f"    #1 a = {v};" for v in VALUES]
    lines += ["    #1 $finish(0);", "  end", "endmodule"]
    stdout = [f"{v} {n + 1}" for n, v in enumerate([0] + VALUES)]
    return name, lines, stdout


def files():
    out = {}
    for task, call in TASKS:
        for key, conv in FORMATS:
            for container in CONTAINERS:
                name, lines, stdout = test(task, call, key, conv, container)
                out[f"{name}.sv"] = "\n".join(lines) + "\n"
                out[f"{name}.expected"] = "\n".join(stdout) + "\n"
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_monitor_once_matrix: {path.relative_to(OUT.parent.parent.parent)} is "
                      "out of date; run tools/gen_monitor_once_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
