"""The operand types of case equality and wildcard equality.

IEEE 1800-2023 table 11-1: === and !== take any type except real and shortreal, and
==? and !=? take integral types only. A string holds no x or z, so === and !== on
strings compare as == and != do (table 6-9, 11.4.5). What the table leaves out is
illegal, and slang lets some of it through. Every expected result is computed here
from these rules, not from a run.
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'tests/suite/values'
GENERATOR = 'gen_compare_operand_matrix.py@1'
CASE_MESSAGE = '=== and !== do not take a real operand (table 11-1)'
WILDCARD_MESSAGE = '==? and !=? take integral operands only (table 11-1)'
PAIRS = {'same': ('abc', 'abc'), 'differ': ('abc', 'abd'), 'empty': ('', ''), 'one_empty': ('a', ''),
         'prefix': ('ab', 'abc'), 'case': ('abc', 'ABC')}


def source(name, description, text, expected):
    name = 'compare_string_' + name
    return name, f'''/*
:name: {name}
:description: {description}
:tags: values string
:type: simulation
:lrm: 1800-2023 11.4.5 6.16 11.3.1
:oracle: spec
:spec_check: ai
:fourstate: yes
:nondeterministic: no
:generator: {GENERATOR}
:top_module: top
:expected_stdout: {expected}
:timeout: 15
*/
// Generated by tools/gen_compare_operand_matrix.py; edit the generator.
`timescale 1ns/1ns
{text}'''


def bit(value):
    return '1' if value else '0'


def values():
    """Every pair, with the operator on each spelling of an operand."""
    for name, (a, b) in PAIRS.items():
        equal = a == b
        lines = f'''module top;
string a = "{a}", b = "{b}";
initial begin
$write("%0d%0d%0d%0d", a === b, a !== b, a == b, a != b);
$write("%0d%0d", a === "{b}", a !== "{b}");
$write("%0d%0d", "{a}" === b, "{a}" !== b);
if (a === b) $write("T"); else $write("F");
$display("%s", a !== b ? "T" : "F");
end
endmodule
'''
        want = bit(equal) + bit(not equal) + bit(equal) + bit(not equal)
        want += bit(equal) + bit(not equal) + bit(equal) + bit(not equal)
        want += 'T' if equal else 'F'
        want += 'F' if equal else 'T'
        yield source(name, '=== and !== on strings compare the characters', lines, want)


BODY = '$display("%0d%0d%0d%0d", a === "x", a !== "x", a === b, a !== b);'
DECLARE = 'string a = "x", b = "y";\n'
PLACE_WANT = '1001'


def places():
    """The container does not change the operator."""
    for name, text in (
            ('task', f'module top;\ntask automatic run();\n{DECLARE}{BODY}\nendtask\ninitial run();\nendmodule\n'),
            ('function', f'module top;\nfunction automatic void run();\n{DECLARE}{BODY}\nendfunction\ninitial run();\nendmodule\n'),
            ('method', f'class box;\n{DECLARE}function void run();\n{BODY}\nendfunction\nendclass\nmodule top;\nbox k;\ninitial begin\nk = new;\nk.run();\nend\nendmodule\n'),
            ('fork', f'module top;\n{DECLARE}initial begin\nfork\nbegin\n{BODY}\nend\njoin\nend\nendmodule\n'),
            ('generate', f'module top;\nif (1) begin : g\n{DECLARE}initial begin\n{BODY}\nend\nend\nendmodule\n'),
            ('interface', f'interface unit;\n{DECLARE}initial begin\n{BODY}\nend\nendinterface\nmodule top;\nunit u();\nendmodule\n'),
            ('program', f'program automatic worker;\n{DECLARE}initial begin\n{BODY}\nend\nendprogram\nmodule top;\nworker u();\nendmodule\n'),
            ('package_function', f'package pkg;\nfunction automatic void run();\n{DECLARE}{BODY}\nendfunction\nendpackage\nmodule top;\ninitial pkg::run();\nendmodule\n')):
        yield source(f'place_{name}', 'The container does not change === and !== on strings', text, PLACE_WANT)
    # Where the operands come from.
    for name, declare, left, right in (
            ('struct_member', 'typedef struct {string p; string q;} s_t;\ns_t s = \'{"x", "y"};\n', 's.p', 's.q'),
            ('array_element', 'string s[2] = \'{"x", "y"};\n', 's[0]', 's[1]'),
            ('queue_element', 'string s[$] = \'{"x", "y"};\n', 's[0]', 's[1]'),
            ('function_result', 'function automatic string f(string v);\nreturn v;\nendfunction\n', 'f("x")', 'f("y")'),
            ('concatenation', 'string p = "x";\n', '{p, ""}', '{p, "y"}'),
            ('substring', 'string s = "xy";\n', 's.substr(0, 0)', 's.substr(1, 1)')):
        text = f'module top;\n{declare}initial $display("%0d%0d", {left} === {right}, {left} !== {right});\nendmodule\n'
        yield source(f'operand_{name}', '=== and !== take a string from any expression', text, '01')
    # A continuous assignment and a procedure sensitive to the operands.
    yield source('continuous', '=== and !== on strings in a continuous assignment',
                 'module top;\nstring a = "x", b = "x";\nwire e;\nassign e = a === b;\ninitial begin\n#1 $write("%b", e);\nb = "y";\n#1 $display("%b", e);\nend\nendmodule\n', '10')
    yield source('always_comb', '=== and !== on strings are read by always_comb',
                 'module top;\nstring a = "x", b = "x";\nlogic e;\nalways_comb e = a !== b;\ninitial begin\n#1 $write("%b", e);\nb = "y";\n#1 $display("%b", e);\nend\nendmodule\n', '01')


CLASS = 'class k;\nendclass\n'


def illegal_cases():
    """What table 11-1 leaves out. name, text before the module, declarations, expression, message."""
    for name, declare, expression in (
            ('real', 'real a = 1.5, b = 1.5;', 'a {} b'),
            ('shortreal', 'shortreal a = 1.5, b = 1.5;', 'a {} b'),
            ('realtime', 'realtime a = 1.5, b = 1.5;', 'a {} b'),
            ('real_left_int_right', 'real a = 1.5;\nint b = 1;', 'a {} b'),
            ('int_left_real_right', 'int a = 1;\nreal b = 1.5;', 'a {} b'),
            ('real_literal', 'real a = 1.5;', 'a {} 1.5'),
            ('real_member', 'typedef struct {real p;} s_t;\ns_t a, b;', 'a.p {} b.p'),
            ('real_element', 'real a[2];', 'a[0] {} a[1]')):
        for op_name, op in (('case_equal', '==='), ('case_differ', '!==')):
            yield f'{name}_{op_name}', '', declare, expression.format(op), CASE_MESSAGE
    for op_name, op in (('wildcard_equal', '==?'), ('wildcard_differ', '!=?')):
        yield f'class_{op_name}', CLASS, 'k a, b;', f'a {op} b', WILDCARD_MESSAGE


def illegal_source(name, before, declare, expression, message):
    name = 'illegal_compare_' + name
    body = f'{before}module top;\n{declare}\nlogic r;\ninitial r = {expression};\nendmodule\n'
    head = f'''/*
:name: {name}
:description: illegal: {message}
:tags: illegal values
:type: elaboration
:lrm: 1800-2023 11.3.1 11.4.5 11.4.6
:oracle: spec
:spec_check: ai
:fourstate: no
:nondeterministic: no
:generator: {GENERATOR}
:should_fail_because: {message}
:expected_error: @LINE@:@COLUMN@: error: {message}
*/
// Generated by tools/gen_compare_operand_matrix.py; edit the generator.
'''
    lines = (head + body).splitlines()
    line = next(i for i, text in enumerate(lines, 1) if text.startswith('initial r = '))
    column = len('initial r = ') + 1
    return name, head.replace('@LINE@', str(line)).replace('@COLUMN@', str(column)) + body


def cases():
    yield from values()
    yield from places()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = {OUT / (name + '.sv'): text for name, text in cases()}
    count = len(generated)
    for case in illegal_cases():
        name, text = illegal_source(*case)
        generated[OUT / (name + '.sv')] = text
    failed = False
    for path, text in generated.items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                print(f'out of date: {path.relative_to(ROOT)}')
                failed = True
        else:
            path.write_text(text)
    print(f'compare operand matrix: {count} sources, {len(generated) - count} illegal')
    return int(failed)


if __name__ == '__main__':
    raise SystemExit(main())
