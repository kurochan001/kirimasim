"""Generates the matrix tests of writes through tasks and the restriction of
always_comb, always_latch and always_ff, of TEST_SUITE.md ("Mechanism
matrix"): a design whose errors are all front's, in tests/cli/
(run_cli_tests.py compares its error and note lines), and tests in
tests/suite/proc/.

  tools/gen_task_write_matrix.py           # writes the files
  tools/gen_task_write_matrix.py --check   # exit 1 if a file differs from what it would write

What always_comb, always_latch and always_ff write, themselves and
through the functions they call, no other process may write (9.2.2.2,
9.2.2.3, 9.2.2.4). What the tasks they call write is not theirs: another
process may write it, and it stays in the sensitivity of always_comb
when the block reads it (9.2.2.2.1). slang reports another process's
write made directly or through a function; front reports one made
through a task, at the write in the task, with a note at the call, exit
code 2 (SCHEDULER_SPEC.md 6.3, 6.4; SIR_SPEC.md 3.4).

The axes: the block (always_comb, always_latch, always_ff); how the
write is made (directly, through a function, through a task, through a
function or a task that a task calls); who makes it (another process:
an error, slang's or front's; the block itself through a task, with
another process writing directly: legal).

The expected outputs follow from the rules above, computed below.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CLI = ROOT / "tests" / "cli"
SUITE = ROOT / "tests" / "suite" / "proc"
NAME = "task_write_matrix"
PREFIX = "task_write_"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1
ERROR = ("'top.{v}', which the {kind} procedure at {at} writes, may not be written by another "
         "process, here through a task it calls")
SLANG = "variable '{v}' driven by {kind} procedure cannot be written to by any other process"

# (name, the keyword, the block writing {v} from a)
BLOCKS = [
    ("comb", "always_comb", "always_comb {v} = a;"),
    ("latch", "always_latch", "always_latch if (en) {v} = a;"),
    ("ff", "always_ff", "always_ff @(posedge clk) {v} <= a;"),
]
# The ways through a task: (name, the subroutines with {v} for the
# variable, {s} for a suffix; the task called is tk{s})
TASK_WAYS = [
    ("task", ["task automatic tk{s}(input logic [7:0] x);", "  {v} = x;", "endtask"]),
    ("task_function", ["function automatic void fn{s}(logic [7:0] x);", "  {v} = x;",
                       "endfunction", "task automatic tk{s}(input logic [7:0] x);",
                       "  fn{s}(x);", "endtask"]),
    ("task_task", ["task automatic in{s}(input logic [7:0] x);", "  {v} = x;", "endtask",
                   "task automatic tk{s}(input logic [7:0] x);", "  in{s}(x);", "endtask"]),
]


def cli_files():
    """Another process writes through a task what each block writes."""
    file = f"{NAME}.sv"
    lines = [f"// Generated by tools/gen_task_write_matrix.py (version {VERSION}); do not edit.",
             "module top;", "  logic clk = 1'b0, en = 1'b1;", "  logic [7:0] a = 8'd1;"]
    stderr = []
    for bname, kind, block in BLOCKS:
        for wname, subs in TASK_WAYS:
            s = f"_{bname}_{wname}"
            v = f"t{s}"
            lines.append(f"  logic [7:0] {v};")
            write = None
            for x in subs:
                text = "  " + x.format(v=v, s=s)
                if text.strip() == f"{v} = x;":
                    write = (len(lines) + 1, text.index(v) + 1)
                lines.append(text)
            block_at = (len(lines) + 1, 3)
            lines.append("  " + block.format(v=v))
            call = f"  initial tk{s}(8'd7);"
            call_at = (len(lines) + 1, call.index("tk") + 1)
            lines.append(call)
            at = f"{file}:{block_at[0]}:{block_at[1]}"
            stderr.append(f"{file}:{write[0]}:{write[1]}: error: "
                          + ERROR.format(v=v, kind=kind, at=at))
            stderr.append(f"{file}:{call_at[0]}:{call_at[1]}: note: 'top.tk{s}' is called here")
    lines.append("endmodule")
    return {CLI / file: "\n".join(lines) + "\n", CLI / f"{NAME}.stderr": "\n".join(stderr) + "\n"}


def header(name, description, lrm, error=None):
    lines = [
        "/*",
        f":name: {name}",
        f":description: {description}",
        ":tags: proc drivers" + (" error" if error else ""),
        ":type: " + ("elaboration" if error else "simulation"),
        ":lrm: 1800-2023 " + " ".join(lrm),
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: no",
        ":nondeterministic: no",
        f":generator: gen_task_write_matrix.py@{VERSION}",
        ":issue: 21",
    ]
    if error:
        lines += [f":should_fail_because: {description}", f":expected_error: {error}"]
    else:
        lines += [":top_module: top", f":expected_stdout: @{name}.expected"]
    return lines + ["*/",
                    "// Generated by tools/gen_task_write_matrix.py; change the generator, not this "
                    "file.",
                    "`timescale 1ns/1ns"]


def clause(bname):
    return {"comb": "9.2.2.2", "latch": "9.2.2.3", "ff": "9.2.2.4"}[bname]


def slang_case(block, way):
    """Another process writes directly or through a function: slang's error."""
    bname, kind, text = block
    name = f"{PREFIX}{way}_{bname}"
    lines = ["module top;", "  logic clk = 1'b0, en = 1'b1;", "  logic [7:0] a = 8'd1, t;"]
    if way == "function":
        lines += ["  function automatic void fn(logic [7:0] x);", "    t = x;", "  endfunction"]
    lines.append("  " + text.format(v="t"))
    lines.append("  initial fn(8'd7);" if way == "function" else "  initial t = 8'd7;")
    lines.append("endmodule")
    how = "directly" if way == "direct" else "through a function it calls"
    description = f"another process writes {how} a variable that {kind} writes"
    # slang reports at the block's write; the header has as many lines
    # whatever the error says.
    row = len(header(name, description, [clause(bname)], "-")) + lines.index(
        "  " + text.format(v="t"))
    column = ("  " + text.format(v="t")).index(" t ") + 2
    error = f"{row + 1}:{column}: error: " + SLANG.format(v="t", kind=kind)
    return name, header(name, description, [clause(bname)], error) + lines, None


def legal_case(block, way):
    """The block writes through its task what another process writes."""
    bname, kind, _ = block
    wname, subs = way
    name = f"{PREFIX}own_{wname}_{bname}"
    lines = ["module top;", "  logic clk = 1'b0, en = 1'b1;", "  logic [7:0] a = 8'd1, t;"]
    lines += ["  " + x.format(v="t", s="") for x in subs]
    lines.append({"comb": "  always_comb tk(a);", "latch": "  always_latch if (en) tk(a);",
                  "ff": "  always_ff @(posedge clk) tk(a);"}[bname])
    # t is 7 from the initial procedure, then a from the block, which runs
    # again on a (or on the clock).
    lines += ["  initial begin", "    #1 t = 8'd7;", "    #1 $display(\"t=%0d\", t);",
              "    #1 a = 8'd2;", "    clk = 1'b1;", "    #1 $display(\"t=%0d\", t);", "  end",
              "endmodule"]
    how = {"task": "a task", "task_function": "a function that a task",
           "task_task": "a task that a task"}[wname]
    description = (f"{kind} writes a variable through {how} it calls, which another process "
                   "writes too: the restriction does not cover its tasks")
    return name, header(name, description, [clause(bname)]) + lines, ["t=7", "t=2"]


def read_case(block):
    """The block reads what its task writes: that is in its sensitivity."""
    bname, kind, _ = block
    name = f"{PREFIX}read_{bname}"
    lines = ["module top;", "  logic en = 1'b1;", "  logic [7:0] a = 8'd1, t, y;", "  int runs;",
             "  task automatic tk(input logic [7:0] x);", "    t = x;", "  endtask",
             f"  {kind} begin", "    runs++;", "    if (en) tk(a);", "    y = t;", "  end",
             "  initial begin", "    #1 t = 8'd7;", "    #1 $display(\"runs=%0d y=%0d\", runs, y);",
             "  end", "endmodule"]
    description = (f"{kind} reads a variable that only a task it calls writes: a change of it "
                   "runs the block again")
    return name, header(name, description, ["9.2.2.2.1"]) + lines, ["runs=2 y=1"]


def files():
    out = cli_files()
    cases = [slang_case(b, w) for b in BLOCKS for w in ("direct", "function")]
    cases += [legal_case(b, w) for b in BLOCKS for w in TASK_WAYS]
    cases += [read_case(b) for b in BLOCKS if b[0] != "ff"]
    for name, text, expected in cases:
        out[SUITE / f"{name}.sv"] = "\n".join(text) + "\n"
        if expected is not None:
            out[SUITE / f"{name}.expected"] = "\n".join(expected) + "\n"
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for path, text in files().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_task_write_matrix: {path.relative_to(ROOT)} is out of date; run "
                      "tools/gen_task_write_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
