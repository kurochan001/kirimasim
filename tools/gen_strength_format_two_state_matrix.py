"""Generates the matrix tests of %v with a 2-state value (TEST_SUITE.md,
"Mechanism matrix") in tests/suite/values/.

  tools/gen_strength_format_two_state_matrix.py           # writes the files
  tools/gen_strength_format_two_state_matrix.py --check   # exit 1 if a file differs from what it would write

The rule: SYSTEM_TASKS.md 3.10 (21.2.1.4 of the standard speaks of
scalar nets). A value that is no net is shown with the strong strength:
St1 for a 1 and St0 for a 0, and the bits of a vector from the most
significant, joined with "_". A 2-state value has the same bits as the
4-state value it converts to, so it prints the same.

The axes: the operand (a bit variable, a bit vector, a bit of a byte, a
constant, an expression of 2-state operands, a 2-state enumeration, a
2-state packed structure), the task ($display, $write, $sformatf,
$strobe) and the container (an initial procedure, a function, a task).

The expected output is computed here from the values, without reading
kirimasim's code. A person checks it once for all the tests made from it
(TEST_SUITE.md, "Sampling by people").
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "values"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

DECLS = ["bit b = 1;", "bit [2:0] v = 3'b101;", "byte y = 8'h82;",
         "typedef enum bit [1:0] {E0, E1, E2} e_t;", "e_t e = E2;",
         "typedef struct packed { bit f; bit g; } p_t;", "p_t p = 2'b01;"]
# (key, the operand, its bits from the most significant).
OPERANDS = [
    ("variable", "b", "1"),
    ("vector", "v", "101"),
    ("select", "y[1]", "1"),
    ("part", "y[7:6]", "10"),
    ("constant", "1'b0", "0"),
    ("sized", "2'b10", "10"),
    ("expression", "b & ~v[1]", "1"),
    ("enumeration", "e", "10"),
    ("structure", "p", "01"),
]
CONTAINERS = ["initial", "function", "task"]


def shown(bits):
    return "_".join("St" + c for c in bits)


def test(container):
    name = f"strength_format_two_state_{container}"
    sv = ["/*", f":name: {name}",
          ":description: %v shows a 2-state value with the strong strength, bit by bit, in "
          f"$display, $write, $sformatf and $strobe called from {'an' if container == 'initial' else 'a'} "
          f"{container}",
          ":tags: values", ":type: simulation", ":lrm: 1800-2023 21.2.1.4", ":oracle: spec",
          ":spec_check: ai", ":fourstate: no", ":nondeterministic: no",
          f":generator: gen_strength_format_two_state_matrix.py@{VERSION}", ":top_module: top",
          f":expected_stdout: @{name}.expected", "*/",
          "// Generated by tools/gen_strength_format_two_state_matrix.py; change the generator, "
          "not this file.", "`timescale 1ns/1ns", "module top;"]
    sv += ["  " + d for d in DECLS]
    body, expected, strobes = [], [], []
    for key, operand, bits in OPERANDS:
        body.append(f'$display("{key} display: %v", {operand});')
        body.append(f'$write("{key} write: %v\\n", {operand});')
        body.append(f'$display("{key} sformatf: %s", $sformatf("%v", {operand}));')
        body.append(f'$strobe("{key} strobe: %v", {operand});')
        expected += [f"{key} display: {shown(bits)}", f"{key} write: {shown(bits)}",
                     f"{key} sformatf: {shown(bits)}"]
        strobes.append(f"{key} strobe: {shown(bits)}")
    if container == "function":
        sv += ["  function void show();"] + ["    " + b for b in body] + ["  endfunction",
                                                                          "  initial show();"]
    elif container == "task":
        sv += ["  task show;"] + ["    " + b for b in body] + ["  endtask", "  initial show;"]
    else:
        sv += ["  initial begin"] + ["    " + b for b in body] + ["  end"]
    sv += ["endmodule"]
    # The strobes print at the end of the time, in the order they were called.
    return name, sv, expected + strobes


def files():
    out = {}
    for container in CONTAINERS:
        name, sv, expected = test(container)
        out[f"{name}.sv"] = "\n".join(sv) + "\n"
        out[f"{name}.expected"] = "\n".join(expected) + "\n"
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print("gen_strength_format_two_state_matrix: "
                      f"{path.relative_to(OUT.parent.parent.parent)} is out of date; run "
                      "tools/gen_strength_format_two_state_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
