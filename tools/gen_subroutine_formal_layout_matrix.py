"""Generates the matrix tests of how the layout of a subroutine's formal
arguments is read (TEST_SUITE.md, "Mechanism matrix") in
tests/suite/syntax/.

  tools/gen_subroutine_formal_layout_matrix.py           # writes the files
  tools/gen_subroutine_formal_layout_matrix.py --check   # exit 1 if a file differs from what it would write

The rule: white space only separates tokens (5.3), so the number of
spaces in front of a formal argument on its own line does not change the
declaration. A formal argument written without a direction is an input
when it is the first one, and takes the direction of the one before it
otherwise (13.3, 13.4, 13.5; the grammar of A.2.7). So f(string a,
<newline and any indentation> string b) declares two string inputs, the
same as with `input` written for both.

The axes: the number of spaces in front of the second formal argument
(1, 13, 14 and 18, around the boundary seen in issue 110, and 40), its
type (string, int), whether both directions are written (implicit,
input), the kind of subroutine (function, task), and where the
subroutines are declared (a package, the module, an interface, a class).
Each subroutine is called once and prints its two inputs, so that the
test shows both that the design is accepted and that the arguments
arrive as inputs.

The expected output is computed here from the arguments, without
reading kirimasim's code. A person checks it once for all the tests
made from it (TEST_SUITE.md, "Sampling by people").
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "syntax"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

SPACES = (1, 13, 14, 18, 40)
TYPES = ("string", "int")
DIRECTIONS = ("implicit", "input")
KINDS = ("function", "task")
PLACES = ("package", "module", "interface", "class")
# The arguments of each call, and how the two inputs are printed.
ARGS = {"string": ('"p"', '"q"'), "int": ("3", "4")}
VALUE = {"string": ("{a, b}", "%s", "pq"), "int": ("a * 10 + b", "%0d", "34")}
WHERE = {"package": "a package", "module": "the module", "interface": "an interface",
         "class": "a class"}


def subroutines(place):
    """Yields (name, kind, type, lines of the declaration)."""
    lifetime = "" if place == "class" else "automatic "
    for kind in KINDS:
        for ty in TYPES:
            for direction in DIRECTIONS:
                for spaces in SPACES:
                    name = f"{kind[0]}_{ty}_{direction}_{spaces}"
                    written = "input " if direction == "input" else ""
                    expr, fmt, _ = VALUE[ty]
                    head = f"  {kind} {lifetime}"
                    if kind == "function":
                        head += f"{ty} "
                    lines = [f"{head}{name}({written}{ty} a,",
                             " " * spaces + f"{written}{ty} b);"]
                    if kind == "function":
                        lines += [f"    return {expr};", "  endfunction"]
                    else:
                        lines += [f'    $display("{name} {fmt}", {expr});', "  endtask"]
                    yield name, kind, ty, lines


def test(place):
    name = f"subroutine_formal_layout_{place}"
    sv = ["/*", f":name: {name}",
          ":description: a formal argument on its own line is read the same whatever the "
          "spaces in front of it, with an implicit or a written input direction, for string "
          f"and int formals of functions and tasks declared in {WHERE[place]}",
          ":tags: syntax", ":type: simulation", ":lrm: 1800-2023 5.3 13.3 13.4 13.5 A.2.7",
          ":oracle: spec", ":spec_check: ai", ":fourstate: no", ":nondeterministic: no",
          f":generator: gen_subroutine_formal_layout_matrix.py@{VERSION}", ":top_module: top",
          ":issue: 110", f":expected_stdout: @{name}.expected", "*/",
          "// Generated by tools/gen_subroutine_formal_layout_matrix.py; change the generator, "
          "not this file.", "`timescale 1ns/1ns"]
    decls = []
    calls = []
    expected = []
    prefix = {"package": "p::", "module": "", "interface": "u.", "class": "c."}[place]
    for sub, kind, ty, lines in subroutines(place):
        decls += lines
        a, b = ARGS[ty]
        _, fmt, value = VALUE[ty]
        if kind == "function":
            calls.append(f'    $display("{sub} {fmt}", {prefix}{sub}({a}, {b}));')
        else:
            calls.append(f"    {prefix}{sub}({a}, {b});")
        expected.append(f"{sub} {value}")
    if place == "package":
        sv += ["package p;", *decls, "endpackage", "module top;"]
    elif place == "module":
        sv += ["module top;", *decls]
    elif place == "interface":
        sv += ["interface ifc;", *decls, "endinterface", "module top;", "  ifc u();"]
    else:
        sv += ["class C;", *decls, "endclass", "module top;", "  C c;"]
    sv += ["  initial begin"]
    if place == "class":
        sv += ["    c = new;"]
    sv += [*calls, "  end", "endmodule"]
    return name, sv, expected


def files():
    out = {}
    for place in PLACES:
        name, sv, expected = test(place)
        out[f"{name}.sv"] = "\n".join(sv) + "\n"
        out[f"{name}.expected"] = "\n".join(expected) + "\n"
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print("gen_subroutine_formal_layout_matrix: "
                      f"{path.relative_to(OUT.parent.parent.parent)} is out of date; run "
                      "tools/gen_subroutine_formal_layout_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
