"""Generates the program matrix test of TEST_SUITE.md ("Mechanism matrix") in
tests/cli/.

  tools/gen_program_matrix.py           # writes the files
  tools/gen_program_matrix.py --check   # exit 1 if a file differs from what it would write

Program instances execute in the reactive region set (24.3.1), as approved
on 2026-10-23 in docs/notes/program-execution-proposal.md. The existing
hierarchy fixture is preserved, with a versioned generated-header update.
All root initials print once; their relative order is unspecified, so the
CLI checks the sorted multiset. Anonymous declarations emit no diagnostic.
"""

import argparse
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "cli"
NAME = "program_matrix"
# The version of the rules below. Raise it whenever they change.
VERSION = 2

# «what» marks the position that an error line reports: a comma-separated
# list of instance paths, or "anonymous" for an anonymous program.
TEMPLATE = """\
// Generated by tools/gen_program_matrix.py (version {version}); do not edit.
package matrix_pkg;
  «anonymous»program;
    function int twice(int v);
      return 2 * v;
    endfunction
  endprogram
endpackage

«anonymous»program;
  function int thrice(int v);
    return 3 * v;
  endfunction
endprogram

program «solo»solo;
  initial $display("solo");
endprogram

program leaf(input logic a);
  initial $display("leaf %b", a);
endprogram

module middle;
  logic a = 1'b1;
  leaf «top.below.l»l(a);
endmodule

module top;
  logic a = 1'b1;
  leaf «top.direct»direct(a);
  if (1) begin : in_if
    leaf «top.in_if.l»l(a);
  end
  for (genvar i = 0; i < 2; i++) begin : in_for
    leaf «top.in_for[0].l,top.in_for[1].l»l(a);
  end
  leaf «top.row[0],top.row[1]»row[2](a);
  middle below();
  program inner;
    initial $display("inner");
  endprogram
  inner «top.nested»nested();
endmodule
"""


def files():
    sv = re.sub(r"«[^»]*»", "", TEMPLATE.format(version=VERSION))
    return {f"{NAME}.sv": sv, f"{NAME}.stderr": "",
            f"{NAME}.stdout": "\n".join(["inner"] + ["leaf 1"] * 7 + ["solo"]) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_program_matrix: {path.relative_to(OUT.parent.parent)} is out of "
                      "date; run tools/gen_program_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
