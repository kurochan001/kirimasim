"""The order in which a case statement evaluates its items.

IEEE 1800-2023 12.5 evaluates the case expression once and first, then the items
in the order written until one matches; the default item takes no part in this
search. 12.5.3 makes an exception of unique and unique0 only: their items may
come in any order, the evaluation goes on after a match, and the rest of an item
that has matched may be left out. <name>.choice holds what kirimasim does, every
item and expression in the order written (SCHEDULER_SPEC.md 15.1). A priority
case acts on the first match only and keeps the search of 12.5. 12.5.4 gives
case inside the same orders. Every expected result is computed here from these
rules, not from a run.
"""
import argparse
import itertools
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / 'tests/suite/proc'
PREFIX = 'case_item_order_'
HELPERS = """string trace="";
int r=-1;
function automatic int e(int v); trace={trace,"E"}; return v; endfunction
function automatic int t(int v,string tag); trace={trace,tag}; return v; endfunction
"""
SHOW = '$display("%s %0d",trace,r);'
KINDS = ('case', 'casez', 'casex')
QUALIFIERS = {'plain': '', 'priority': 'priority ', 'unique': 'unique ', 'unique0': 'unique0 '}
ITEMS = ((('a', 1),), (('b', 2),), (('c', 3),))
SELECTORS = ((1, 'first'), (2, 'second'), (3, 'third'), (9, 'none'))
PLACES = ('task', 'function', 'fork', 'generate', 'method', 'interface')


def opening(kind, qualifier, selector):
    keyword, tail = ('case', ' inside') if kind == 'inside' else (kind, '')
    return f'{QUALIFIERS[qualifier]}{keyword} ({selector}){tail}'


def scoped(place, statement):
    if place == 'initial':
        return f'module top;\n{HELPERS}initial begin\n{statement}\n{SHOW}\nend\nendmodule\n'
    if place == 'task':
        return f'module top;\n{HELPERS}task automatic run();\n{statement}\nendtask\ninitial begin\nrun();\n{SHOW}\nend\nendmodule\n'
    if place == 'function':
        return f'module top;\n{HELPERS}function automatic void run();\n{statement}\nendfunction\ninitial begin\nrun();\n{SHOW}\nend\nendmodule\n'
    if place == 'fork':
        return f'module top;\n{HELPERS}initial begin\nfork\nbegin\n{statement}\nend\njoin\n{SHOW}\nend\nendmodule\n'
    if place == 'generate':
        return f'module top;\nif(1) begin:g\n{HELPERS}initial begin\n{statement}\n{SHOW}\nend\nend\nendmodule\n'
    if place == 'method':
        return (f'class box;\n{HELPERS}function void run();\n{statement}\n{SHOW}\nendfunction\nendclass\n'
                'module top;\nbox k;\ninitial begin k=new; k.run(); end\nendmodule\n')
    return f'interface unit;\n{HELPERS}initial begin\n{statement}\n{SHOW}\nend\nendinterface\nmodule top;\nunit u();\nendmodule\n'


def source(name, text, chosen, others=(), stderr=None, lrm='12.5 12.5.1 12.5.3 12.5.4'):
    """name, source, .expected, .choice, .stderr; others are what else the standard allows."""
    name = PREFIX + name
    others = [o for o in others if o != chosen]
    fixed = not others
    report = f':expected_stderr: @{name}.stderr\n' if stderr else ''
    head = f'''/*
:name: {name}
:description: A case statement evaluates its items in the order its qualifier sets
:tags: proc case
:type: simulation
:lrm: 1800-2023 {lrm}
:oracle: spec{'' if fixed else ' choice'}
:spec_check: ai
:fourstate: yes
:nondeterministic: {'no' if fixed else 'yes'}
:generator: gen_case_item_order_matrix.py@1
:top_module: top
:expected_stdout: {chosen if fixed else '@' + name + '.expected'}
{report}:timeout: 15
*/
// Generated by tools/gen_case_item_order_matrix.py; edit the generator.
`timescale 1ns/1ns
'''
    whole = head + text
    if stderr:
        marker = stderr['statement']
        line = next(i for i, l in enumerate(whole.splitlines(), 1) if l.startswith(marker))
        stderr = f'{name}.sv:{line}: warning: {stderr["text"]}\n'
    return (name, whole, None if fixed else '---\n'.join(c + '\n' for c in (chosen, *others)),
            None if fixed else chosen + '\n', stderr)


def arms(groups):
    return ''.join(','.join(f't({v},"{tag}")' for tag, v in group) + f': r={group[0][1]};\n' for group in groups)


def searched(selector, groups):
    """The items in the order written until one matches (12.5)."""
    out = 'E'
    for group in groups:
        for tag, value in group:
            out += tag
            if value == selector:
                return out
    return out


def unordered(selector, groups):
    """Any order, going on after a match, with the rest of a matched item free (12.5.3)."""
    tags = [tag for group in groups for tag, _ in group]
    group_of = {tag: i for i, group in enumerate(groups) for tag, _ in group}
    hits = [tag for group in groups for tag, value in group if value == selector]
    out = set()
    for order in itertools.permutations(tags):
        out.add('E' + ''.join(order))
        for hit in hits:
            at = order.index(hit)
            free = [t for t in order[at + 1:] if group_of[t] == group_of[hit]]
            for n in range(1, len(free) + 1):
                for left_out in itertools.combinations(free, n):
                    out.add('E' + ''.join(t for t in order if t not in left_out))
    return sorted(out)


def expected(qualifier, selector, groups, result):
    """The chosen line and the other lines the standard allows."""
    if qualifier in ('plain', 'priority'):
        return f'{searched(selector, groups)} {result}', []
    written = 'E' + ''.join(tag for group in groups for tag, _ in group)
    return f'{written} {result}', [f'{trace} {result}' for trace in unordered(selector, groups)]


def forms(kinds):
    """Each qualifier stopping, or not, at each place a match can be."""
    for kind in kinds:
        for qualifier in QUALIFIERS:
            for selector, label in SELECTORS:
                statement = f'{opening(kind, qualifier, f"e({selector})")}\n{arms(ITEMS)}default: r=0;\nendcase'
                chosen, others = expected(qualifier, selector, ITEMS, selector if label != 'none' else 0)
                yield source(f'{kind}_{qualifier}_{label}', scoped('initial', statement), chosen, others)


def shapes(kinds):
    """The other shapes of an item list, through the same search."""
    several = ((('a', 1), ('b', 2), ('c', 3)), (('d', 4),))
    default_first = ITEMS
    for kind in kinds:
        for qualifier in QUALIFIERS:
            statement = f'{opening(kind, qualifier, "e(2)")}\n{arms(several)}default: r=0;\nendcase'
            chosen, others = expected(qualifier, 2, several, 1)
            yield source(f'{kind}_{qualifier}_several_in_an_item', scoped('initial', statement), chosen, others)
            statement = f'{opening(kind, qualifier, "e(2)")}\ndefault: r=0;\n{arms(default_first)}endcase'
            chosen, others = expected(qualifier, 2, default_first, 2)
            yield source(f'{kind}_{qualifier}_default_first', scoped('initial', statement), chosen, others)
        for qualifier in ('plain', 'priority'):
            # Two items match. Only the first acts, and the second is not reached.
            statement = f'{opening(kind, qualifier, "e(2)")}\nt(2,"a"): r=1;\nt(2,"b"): r=2;\ndefault: r=0;\nendcase'
            yield source(f'{kind}_{qualifier}_overlap', scoped('initial', statement), 'Ea 1')
            # An unknown selector: only casex takes its x bits as wildcards (12.5.1, 12.5.4).
            hit = kind == 'casex'
            statement = (f"logic [7:0] y='x;\n{opening(kind, qualifier, 'y')}\n"
                         't(1,"a"): r=1;\nt(2,"b"): r=2;\ndefault: r=0;\nendcase')
            yield source(f'{kind}_{qualifier}_unknown_selector', scoped('initial', statement),
                         'a 1' if hit else 'ab 0')
            if kind == 'inside':
                # A range is an item too. The standard does not order its two bounds.
                statement = (f'{opening(kind, qualifier, "e(5)")}\n[t(1,"a"):t(2,"b")]: r=1;\n'
                             '[t(4,"c"):t(6,"d")]: r=2;\nt(5,"f"): r=3;\ndefault: r=0;\nendcase')
                yield source(f'{kind}_{qualifier}_ranges', scoped('initial', statement), 'Eabcd 2',
                             ['Ebacd 2', 'Eabdc 2', 'Ebadc 2'])


def places(kinds):
    """The container does not change the order."""
    for kind in kinds:
        if kind in ('casez', 'casex'):
            continue
        for qualifier in ('plain', 'priority', 'unique'):
            for place in PLACES:
                statement = f'{opening(kind, qualifier, "e(2)")}\n{arms(ITEMS)}default: r=0;\nendcase'
                chosen, others = expected(qualifier, 2, ITEMS, 2)
                yield source(f'{kind}_{qualifier}_place_{place}', scoped(place, statement), chosen, others)


def violations(kinds):
    """No match and no default: every item is evaluated, and the report follows (12.5.3)."""
    for kind in kinds:
        for qualifier in ('priority', 'unique', 'unique0'):
            first = opening(kind, qualifier, 'e(9)')
            statement = f'{first}\n{arms(ITEMS)}endcase'
            chosen, others = expected(qualifier, 9, ITEMS, -1)
            report = None
            if qualifier != 'unique0':
                report = {'statement': first, 'text': f'{qualifier} case violation: no item matches [top @ 0ns]'}
            yield source(f'{kind}_{qualifier}_no_default', scoped('initial', statement), chosen, others, report)


def cases(kinds=KINDS):
    yield from forms(kinds)
    yield from shapes(kinds)
    yield from places(kinds)
    yield from violations(kinds)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = list(cases())
    assert len({g[0] for g in generated}) == len(generated)
    failed = False
    for name, text, listed, choice, stderr in generated:
        for suffix, content in (('.sv', text), ('.expected', listed), ('.choice', choice), ('.stderr', stderr)):
            if content is None:
                continue
            path = OUT / (name + suffix)
            if args.check:
                if not path.exists() or path.read_text() != content:
                    print(f'out of date: {path.relative_to(OUT.parent.parent.parent)}')
                    failed = True
            else:
                path.write_text(content)
    print(f'case item order matrix: {len(generated)} sources')
    return int(failed)


if __name__ == '__main__':
    raise SystemExit(main())
