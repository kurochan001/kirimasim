"""Generates the string conversion folding matrix test of TEST_SUITE.md
("Mechanism matrix") in tests/suite/values/.

  tools/gen_string_fold_matrix.py           # writes the files
  tools/gen_string_fold_matrix.py --check   # exit 1 if a file differs from what it would write

The rules: VALUE_SEMANTICS.md 7.6 and SIR_SPEC.md 6, and 6.16.9 and 6.16.10
of the standard. atoi, atohex, atooct and atobin read one leading minus, a
digit of their base at once, then digits and underscores, give 0 when the
text starts otherwise, and keep the low 32 bits, negated after the minus;
atoreal reads one leading sign and a real constant. slang folds these calls
on a constant string with the same reading, so the value is the same
wherever the call stands, in a parameter as at run time. The axes: the
method, the spelling (a minus, a plus, a leading underscore, a leading
space, an underscore inside), and where the call stands (a procedural
assignment, an expression, the initializer of a static variable, a
continuous assignment, the body of a function, an argument of $display,
and a local parameter, whose value slang computes).

A person checks the expected output once for all the tests made from it
(TEST_SUITE.md, "Sampling by people").
"""

import argparse
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "values"
NAME = "string_fold_matrix"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

BASES = {"atoi": 10, "atohex": 16, "atooct": 8, "atobin": 2}
CASES = [
    ("atoi", ["-5", "+5", "_5", " 5", "5_0"]),
    ("atohex", ["-ff", "+ff", "_ff", " ff", "f_F"]),
    ("atooct", ["-17", "+17", "_17", " 17", "1_7"]),
    ("atobin", ["-101", "+101", "_101", " 101", "1_01"]),
    ("atoreal", ["-2.5", "+2.5", "_2.5", " 2.5", "2_5.5"]),
]
REAL = re.compile(r"[+-]?[0-9][0-9_]*(\.[0-9][0-9_]*)?([eE][+-]?[0-9][0-9_]*)?")


def convert(method, text):
    if method == "atoreal":
        m = REAL.match(text)
        return float(m.group(0).replace("_", "")) if m else 0.0
    base, value = BASES[method], 0
    negative = text.startswith("-")
    digits = text[1:] if negative else text
    if not digits or digits[0] == "_":
        return 0
    for c in digits:
        if c == "_":
            continue
        try:
            d = int(c, base)
        except ValueError:
            break
        value = value * base + d
    value = (-value if negative else value) & 0xFFFFFFFF  # the low 32 bits, as an integer
    return value - (1 << 32) if value >> 31 else value


def files():
    sv = [
        "/*",
        f":name: {NAME}",
        ":description: string conversions of a constant string give the same value in an "
        "assignment, an expression, a static initializer, a continuous assignment, a function, "
        "a display argument and a local parameter",
        ":tags: values string",
        ":type: simulation",
        ":lrm: 1800-2023 6.16.9 6.16.10 6.20 10.3 10.5",
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: no",
        ":nondeterministic: no",
        f":generator: gen_string_fold_matrix.py@{VERSION}",
        f":expected_stdout: @{NAME}.expected",
        "*/",
        "// Generated by tools/gen_string_fold_matrix.py; change the generator, not this file.",
        "// For reference, Verilator 5.052 gives one value in every place and reads the minus",
        "// too, but it also reads a plus, a leading underscore and a leading space in atoi,",
        "// atohex, atooct and atobin, and skips a leading space and stops at an underscore in",
        "// atoreal (VALUE_SEMANTICS.md 7.6). Icarus Verilog 13.0 has no atooct.",
        "`timescale 1ns/1ns",
        "module top;",
    ]
    body, expected = [], []
    k = 0
    for method, spellings in CASES:
        real = method == "atoreal"
        t, fmt = ("real", "%f") if real else ("int", "%0d")
        for text in spellings:
            p, call = f"P{k}", f"P{k}.{method}()"
            sv += [f'  parameter string {p} = "{text}";',
                   f"  {t} st{k} = {call};",
                   f"  localparam {t} L{k} = {call};",
                   f"  {t} ct{k};",
                   f"  assign ct{k} = {call};",
                   f"  function automatic {t} fn{k}();",
                   f"    return {call};",
                   "  endfunction"]
            label = f'{method}(\\"{text}\\")'
            target = "rr" if real else "ri"
            body += [f"    {target} = {call};",
                     f'    $display("assign {label} {fmt}", {target});',
                     f"    {target} = {call} * 3 - {call} * 2;",
                     f'    $display("expression {label} {fmt}", {target});',
                     f'    $display("static {label} {fmt}", st{k});',
                     f'    $display("continuous {label} {fmt}", ct{k});',
                     f'    $display("function {label} {fmt}", fn{k}());',
                     f'    $display("display {label} {fmt}", {call});',
                     f'    $display("parameter {label} {fmt}", L{k});']
            value = convert(method, text)
            shown = f"{value:f}" if real else f"{value}"
            expected += [f'{where} {method}("{text}") {shown}' for where in
                         ("assign", "expression", "static", "continuous", "function", "display",
                          "parameter")]
            k += 1
    sv += ["  int ri;", "  real rr;", "  initial begin", "    #1;"] + body + ["  end", "endmodule",
                                                                          ""]
    return {f"{NAME}.sv": "\n".join(sv), f"{NAME}.expected": "\n".join(expected) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_string_fold_matrix: {path.relative_to(OUT.parent.parent.parent)} is "
                      "out of date; run tools/gen_string_fold_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
