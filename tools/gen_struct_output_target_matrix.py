"""Generates the matrix test of where an output or inout structure argument
is copied back, of TEST_SUITE.md ("Mechanism matrix"), in tests/suite/proc/.

  tools/gen_struct_output_target_matrix.py           # writes the files
  tools/gen_struct_output_target_matrix.py --check   # exit 1 if a file differs from what it would write

The rule: SIR_SPEC.md 8 ("Passing arguments", approved 2026-10-18), with
4.9.7 and 13.5 of the standard. The copy back of an output or inout is a
blocking assignment on return, so the indices of its actual are found
then; an inout's actual is also read at the call, with the indices it has
then. The axes: the actual (an element of an array of structures, a
structure member of such an element, a row of a two-dimensional array of
structures, and, for comparison, an int element, which the same rule
covers), the direction (output and inout), the callee and what changes
the index while it runs (an automatic function that changes it, an
automatic task that changes it before a wait, and an automatic and a
static task during whose wait another process changes it), and the
container of the call (an initial procedure, a static task and a fork
branch). Each case shows the whole array after the call.

The expected outputs follow from the rule, worked out below without
reading kirimasim's code. A person checks them once for all the tests made
from them (TEST_SUITE.md, "Sampling by people").
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "proc"
NAME = "struct_output_target_matrix"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

# The actual: (name, the formal's type, the actual with I for the index,
# the statement that shows the two elements, the part of the formal the
# callee writes: v for an output, what it read plus v for an inout).
ACTUALS = [
    ("element", "s_t", "sa[I]", "sa[0].a, sa[1].a", "r.a"),
    ("member", "s_t", "na[I].inner", "na[0].inner.a, na[1].inner.a", "r.a"),
    ("row", "row_t", "grid[I]", "grid[0][1].a, grid[1][1].a", "r[1].a"),
    ("int", "int", "ia[I]", "ia[0], ia[1]", "r"),
]
# The callee: (name, its body around WRITE, whether another process
# changes the index during the call).
CALLEES = [
    ("function", "function automatic void {f}({d} {t} r, input int v);\n"
                 "    k = 1;\n    WRITE\n  endfunction", False),
    ("task_before_wait", "task automatic {f}({d} {t} r, input int v);\n"
                         "    k = 1;\n    #1 WRITE\n  endtask", False),
    ("task_during_wait", "task automatic {f}({d} {t} r, input int v);\n"
                         "    #2 WRITE\n  endtask", True),
    ("static_task", "task static {f}({d} {t} r, input int v);\n"
                    "    #2 WRITE\n  endtask", True),
]
DIRECTIONS = ["output", "inout"]
CONTAINERS = ["initial", "task", "fork"]


def files():
    head = [
        "/*",
        f":name: {NAME}",
        ":description: the copy back of an output or inout structure argument finds its "
        "target's indices on return, as a blocking assignment does, from functions and from "
        "tasks that wait, in several containers",
        ":tags: proc",
        ":type: simulation",
        ":lrm: 1800-2023 13.5 4.9.7 7.6",
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: no",
        ":nondeterministic: no",
        f":generator: gen_struct_output_target_matrix.py@{VERSION}",
        f":expected_stdout: @{NAME}.expected",
        "*/",
        "// Generated by tools/gen_struct_output_target_matrix.py; change the generator, not this "
        "file.",
        "`timescale 1ns/1ns",
        "module top;",
        "  typedef struct { int a; } s_t;",
        "  typedef struct { int tag; s_t inner; } n_t;",
        "  typedef s_t row_t [0:1];",
        "  s_t sa [0:1];",
        "  n_t na [0:1];",
        "  s_t grid [0:1][0:1];",
        "  int ia [0:1];",
        "  int k;",
    ]
    subs, runs, expected = [], {c: [] for c in CONTAINERS}, []
    for label, ftype, expr, shown, part in ACTUALS:
        for cname, template, other in CALLEES:
            for direction in DIRECTIONS:
                f = f"{label}_{cname}_{direction}"
                write = f"{part} = v;" if direction == "output" else f"{part} = {part} + v;"
                subs.append("  " + template.format(f=f, d=direction, t=ftype)
                            .replace("WRITE", write))
                for container in CONTAINERS:
                    v = 3 if direction == "output" else 5
                    # 10 and 20 before; an output writes v, an inout what it
                    # read at the call (element 0) plus v; both go to
                    # element 1, chosen on return.
                    result = v if direction == "output" else 10 + v
                    call = f"{f}({expr.replace('I', 'k')}, {v});"
                    body = [f"// {container} {f}",
                            "sa[0].a = 10; sa[1].a = 20; na[0].inner.a = 10; na[1].inner.a = 20;",
                            "grid[0][1].a = 10; grid[1][1].a = 20; ia[0] = 10; ia[1] = 20;",
                            "k = 0;"]
                    if other:
                        body += ["fork", f"  {call}", "  #1 k = 1;", "join"]
                    else:
                        body.append(call)
                    body.append(f'$display("{container} {f} %0d %0d", {shown});')
                    runs[container] += body
                    expected.append(f"{container} {f} 10 {result}")
    # The cases run container by container, each in its own window.
    ordered = [line for c in CONTAINERS for line in expected if line.startswith(c + " ")]
    sv = head + subs
    sv += ["  initial begin"] + ["    " + line for line in runs["initial"]]
    sv += ["    run();", "    fork", "      begin"]
    sv += ["        " + line for line in runs["fork"]]
    sv += ["      end", "    join", "  end", "  task static run();"]
    sv += ["    " + line for line in runs["task"]]
    sv += ["  endtask", "endmodule", ""]
    return {f"{NAME}.sv": "\n".join(sv), f"{NAME}.expected": "\n".join(ordered) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                where = path.relative_to(OUT.parent.parent.parent)
                print(f"gen_struct_output_target_matrix: {where} is out of date; run "
                      "tools/gen_struct_output_target_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
