#!/usr/bin/env python3
"""Generates the matrix test of a subroutine's static variable named from
outside it, of TEST_SUITE.md ("Mechanism matrix"), in tests/suite/hier/.

  tools/gen_subroutine_variable_matrix.py           # writes the files
  tools/gen_subroutine_variable_matrix.py --check   # exit 1 if a file differs from what it would write

A static variable of a function can be named from outside it by a
hierarchical name (13.3.1, 23.6), and it is still the function's own
variable (SIR_SPEC.md 3.3): an event expression that calls the function
may write it (SCHEDULER_SPEC.md 9.5), and so may a function that $strobe
calls in the Postponed region (SCHEDULER_SPEC.md 2.2). That holds
whether the hierarchical name or the function comes first in the source.

The axes: where the variable is named first, before the function is
called (an event control on it, a read in a process, a write in a
process); what calls the function (a process, an event expression whose
operand changes, a $strobe argument; the event control waiter is not
combined with $strobe, whose writes come after the time slot's waits).
Each case has its own function and time.

The expected outputs follow from the rules above, computed below. A
person checks them once for all the tests made from them (TEST_SUITE.md,
"Sampling by people").
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "hier"
NAME = "subroutine_variable_matrix"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

FIRSTS = ["event_control", "read", "write"]
CALLERS = ["process", "event_expression", "strobe"]


def files():
    lines = [
        "/*",
        f":name: {NAME}",
        ":description: a function's static variable named by a hierarchical name before the "
        "function is called, waited on, read or written, stays the function's own: an event "
        "expression and a $strobe argument that call the function may write it",
        ":tags: hier functions",
        ":type: simulation",
        ":lrm: 1800-2023 13.3.1 23.6 9.4.2 21.2.2",
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: no",
        ":nondeterministic: no",
        f":generator: gen_subroutine_variable_matrix.py@{VERSION}",
        ":top_module: top",
        f":expected_stdout: @{NAME}.expected",
        "*/",
        "// Generated by tools/gen_subroutine_variable_matrix.py; change the generator, not "
        "this file.",
        "`timescale 1ns/1ns",
        "module top;",
    ]
    out = []
    k = 0
    for first in FIRSTS:
        for caller in CALLERS:
            if first == "event_control" and caller == "strobe":
                continue
            t = 10 * (k + 1)
            tag = f"case {k} {first} {caller}"
            lines += [f"  // {tag}",
                      f"  int r{k}, a{k} = 0;"]
            # The hierarchical name comes before the function in the source.
            if first == "event_control":
                lines.append(f'  initial begin @(top.f{k}.t); $display("%0t {tag} woke t=%0d", '
                             f"$time, top.f{k}.t); end")
                out.append((t, 1, f"{t} {tag} woke t={t}"))
            else:
                if first == "write":
                    lines.append(f"  initial #{t - 1} top.f{k}.t = 1;")
                lines.append(f'  initial #{t + 1} $display("%0t {tag} read t=%0d", $time, '
                             f"top.f{k}.t);")
                out.append((t + 1, 2, f"{t + 1} {tag} read t={t}"))
            lines += [f"  function int f{k}(int x);",
                      "    int t;",
                      "    t = x;",
                      "    return x;",
                      "  endfunction"]
            if caller == "process":
                lines.append(f"  initial #{t} r{k} = f{k}({t});")
            elif caller == "event_expression":
                lines += [f"  initial @(f{k}(a{k})) r{k} = a{k};",
                          f"  initial #{t} a{k} = {t};"]
            else:
                lines.append(f'  initial #{t} $strobe("%0t {tag} strobe f=%0d", $time, '
                             f"f{k}({t}));")
                out.append((t, 1, f"{t} {tag} strobe f={t}"))
            k += 1
    lines += ["endmodule", ""]
    expected = [text for _, _, text in sorted(out)]
    return {f"{NAME}.sv": "\n".join(lines), f"{NAME}.expected": "\n".join(expected) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_subroutine_variable_matrix: {path.relative_to(OUT.parent.parent.parent)}"
                      " is out of date; run tools/gen_subroutine_variable_matrix.py",
                      file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
