"""Generates the scope name matrix test of TEST_SUITE.md ("Mechanism matrix") in
tests/suite/proc/.

  tools/gen_scope_name_matrix.py           # writes the files
  tools/gen_scope_name_matrix.py --check   # exit 1 if a file differs from what it would write

%m gives the hierarchical name of the module instance, subroutine or
named block that calls it; unnamed blocks are not part of the hierarchy
(SYSTEM_TASKS.md 3.8, 21.2.1.5). The name is taken in every container:
the module body, a continuous assignment, a named block of an initial procedure, an unnamed block
inside it, nested named blocks, a static task, a static function, a named
generate block and a named fork; and in two ways: the initializer of a
static variable declared there or the right side of a continuous
assignment ($sformatf), and a statement run there ($sformat). Every name is kept in a string and shown at the end by one
process, so that no line depends on the order of processes.

The expected outputs follow from the rule above. A person checks them
once for all the tests made from them (TEST_SUITE.md, "Sampling by people").
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "proc"
NAME = "scope_names"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1


def files():
    sv = (f"/*\n:name: {NAME}\n:description: %m gives the hierarchical name of the instance, "
          "subroutine or named block that calls it, without unnamed blocks, in static variable "
          "initializers and in statements, in every kind of container\n:tags: proc\n"
          ":type: simulation\n:lrm: 1800-2023 21.2.1.5 6.21 9.3.5 27.6\n:oracle: spec\n"
          ":spec_check: ai\n:fourstate: no\n:nondeterministic: no\n"
          f":generator: gen_scope_name_matrix.py@{VERSION}\n"
          f":expected_stdout: @{NAME}.expected\n*/\n"
          "// Generated by tools/gen_scope_name_matrix.py; change the generator, not this "
          "file.\n"
          "module child;\n"
          "  string body_init = $sformatf(\"%m\");\n"
          "  string body_stmt, blk_stmt, unnamed_stmt, inner_stmt, task_stmt, func_stmt, "
          "fork_stmt;\n"
          "  string blk_init, unnamed_init, inner_init, task_init, func_init, cont;\n"
          "  assign cont = $sformatf(\"%m\");\n"
          "  task static t();\n"
          "    static string init = $sformatf(\"%m\");\n"
          "    task_init = init;\n"
          "    $sformat(task_stmt, \"%m\");\n"
          "  endtask\n"
          "  function static int f();\n"
          "    static string init = $sformatf(\"%m\");\n"
          "    func_init = init;\n"
          "    $sformat(func_stmt, \"%m\");\n"
          "    return 0;\n"
          "  endfunction\n"
          "  generate\n"
          "    if (1) begin : gen\n"
          "      string gen_init = $sformatf(\"%m\");\n"
          "      string gen_stmt, gen_cont;\n"
          "      assign gen_cont = $sformatf(\"%m\");\n"
          "      initial $sformat(gen_stmt, \"%m\");\n"
          "    end\n"
          "  endgenerate\n"
          "  initial $sformat(body_stmt, \"%m\");\n"
          "  initial begin : blk\n"
          "    static string init = $sformatf(\"%m\");\n"
          "    int k;\n"
          "    blk_init = init;\n"
          "    $sformat(blk_stmt, \"%m\");\n"
          "    begin\n"
          "      static string uinit = $sformatf(\"%m\");\n"
          "      unnamed_init = uinit;\n"
          "      $sformat(unnamed_stmt, \"%m\");\n"
          "      begin : inner\n"
          "        static string iinit = $sformatf(\"%m\");\n"
          "        inner_init = iinit;\n"
          "        $sformat(inner_stmt, \"%m\");\n"
          "      end\n"
          "    end\n"
          "    t();\n"
          "    k = f();\n"
          "    fork : forked\n"
          "      $sformat(fork_stmt, \"%m\");\n"
          "    join\n"
          "  end\n"
          "endmodule\n"
          "module top;\n"
          "  child u ();\n"
          "  initial begin\n"
          "    #1;\n")
    rows = [
        ("module init", "u.body_init", "top.u"),
        ("module statement", "u.body_stmt", "top.u"),
        ("named block init", "u.blk_init", "top.u.blk"),
        ("named block statement", "u.blk_stmt", "top.u.blk"),
        ("unnamed block init", "u.unnamed_init", "top.u.blk"),
        ("unnamed block statement", "u.unnamed_stmt", "top.u.blk"),
        ("nested named init", "u.inner_init", "top.u.blk.inner"),
        ("nested named statement", "u.inner_stmt", "top.u.blk.inner"),
        ("task init", "u.task_init", "top.u.t"),
        ("task statement", "u.task_stmt", "top.u.t"),
        ("function init", "u.func_init", "top.u.f"),
        ("function statement", "u.func_stmt", "top.u.f"),
        ("generate init", "u.gen.gen_init", "top.u.gen"),
        ("generate statement", "u.gen.gen_stmt", "top.u.gen"),
        ("fork statement", "u.fork_stmt", "top.u.blk.forked"),
        ("continuous assignment", "u.cont", "top.u"),
        ("generate continuous assignment", "u.gen.gen_cont", "top.u.gen"),
    ]
    for label, path, _ in rows:
        sv += f"    $display(\"{label}: %s\", {path});\n"
    sv += "  end\nendmodule\n"
    exp = "".join(f"{label}: {name}\n" for label, _, name in rows)
    return {f"{NAME}.sv": sv, f"{NAME}.expected": exp}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_scope_name_matrix: {path.relative_to(OUT.parent.parent.parent)} is "
                      "out of date; run tools/gen_scope_name_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
