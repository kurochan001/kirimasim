"""Generate runtime sformat/sformatf formats (21.3.3, SYSTEM_TASKS.md 3.13).

Five format representations in ten contexts, both APIs, arbitrary-width
four-state values, real/integer conversions, strings, time-unit scaling,
scope/cell metadata, argument evaluation order and changing formats at one
call site. Expected text is derived independently from the written values.
"""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "tests" / "suite" / "proc"
VERSION = 1
KINDS = ("string", "packed", "function", "array", "conditional")
CONTAINERS = ("initial", "always", "final", "static_task", "automatic", "function", "ref",
              "fork", "generate", "interface")
HEX = "1z23456789abcdef0123456789abcdef01"
WIDE = "".join("zzzz" if c == "z" else format(int(c, 16), "04b") for c in HEX)[-129:]
# tag, format, arguments, expected text; scope is filled for each container.
CASES = [
    ("radix", "n=%0d h=%04h b=%b o=%0o %%", "read_value(a), b, bits, b",
     "n=-12 h=0005 b=10xz o=5 %"),
    ("automatic_width", "%d|%h", "a, a", str(-12).rjust(11) + "|fffffff4"),
    ("wide", "%b", "wide", WIDE),
    ("strings", "%s|%0s|%s", 's, text_bits, "literal %m %0d"', "text%0d|A B |literal %m %0d"),
    ("reals", "%0.2f|%0.1E|%0.3g", "r, -2.0, b", "1.25|-2.0E+00|5"),
    ("real_as_int", "%0d|%0h", "1.5, 1.5", "2|2"),
    ("wide_as_real", "%0.0f", "129'h10000000000000000", str(2**64)),
    ("time", "%t|%8t", "2, 1.255", "2.00ns|  1.26ns"),
    ("scope", "%m|%l|%%m", "", None),
    ("empty_format", "", "", ""),
]


def test(kind, container):
    name = f"runtime_string_format_{kind}_{container}"
    expr = {"string": "fmt", "packed": "packed_fmt", "function": "get_format(fmt)",
            "array": "formats[0]", "conditional": '(select_format ? fmt : "%q")'}[kind]
    scope = ("top.run" if container in ("static_task", "automatic", "function", "ref")
             else "top.g" if container == "generate" else "top.u" if container == "interface"
             else "top")
    cell = "work.worker" if container == "interface" else "work.top"
    declarations = ["    int a, b;", "    logic [3:0] bits;", "    wide_t wide;",
                    "    logic [31:0] text_bits;", "    string s, result;", "    real r;"]
    locals_ = ["    string fmt, formats[1];", "    logic [1023:0] packed_fmt;",
               "    bit select_format;"]
    body, expected = ['    a = -12; b = 5; bits = 4\'b10xz; s = "text%0d"; r = 1.25;',
                      f"    wide = wide_t'(136'h{HEX}); text_bits = 32'h41004200;",
                      '    $timeformat(-9, 2, "ns", 0);'], []
    for api in ("f", "s"):
        for tag, fmt, args, want in CASES:
            body += [f'    fmt = "{fmt}"; packed_fmt = "{fmt}"; formats[0] = fmt; select_format = 1;',
                     "    trace = 0;"]
            actuals = expr + (", " + args if args else "")
            body += ([f"    result = $sformatf({actuals});"] if api == "f" else
                     [f"    $sformat(result, {actuals});"])
            body += [f'    $display("{api} {tag} [%s] %0d", result, trace);']
            trace = "1" if kind == "function" else ""
            if tag == "radix":
                trace += "2"
            if want is None:
                want = f"{scope}|{cell}|%m"
            expected += [f"{api} {tag} [{want}] {trace or '0'}"]
        body += ["    for (int i = 0; i < 2; i++) begin",
                 '      fmt = i == 0 ? "%0d" : "%04h";',
                 '      packed_fmt = i == 0 ? "%0d" : "%04h";',
                 "      formats[0] = fmt; select_format = 1; trace = 0;"]
        body += ([f"      result = $sformatf({expr}, 10);"] if api == "f" else
                 [f"      $sformat(result, {expr}, 10);"])
        body += [f'      $display("{api} repeat [%s] %0d", result, trace);', "    end"]
        trace = 1 if kind == "function" else 0
        expected += [f"{api} repeat [10] {trace}", f"{api} repeat [000a] {trace}"]
    lines = ["/*", f":name: {name}",
             f":description: Runtime string formats from {kind} in {container}, both APIs",
             ":tags: proc format", ":type: simulation", ":lrm: 1800-2023 21.3.3",
             ":oracle: spec", ":spec_check: ai", ":fourstate: yes", ":nondeterministic: no",
             f":generator: gen_runtime_string_format_matrix.py@{VERSION}", ":top_module: top",
             f":expected_stdout: @{name}.expected", f":expected_stderr: @{name}.stderr", "*/",
             "// Generated by tools/gen_runtime_string_format_matrix.py; edit the generator.",
             "`timescale 1ns/1ps", "interface worker;" if container == "interface" else "module top;",
             "  typedef logic [128:0] wide_t;", "  int trace;",
             "  function automatic string get_format(input string f);",
             "    trace = trace * 10 + 1; return f;", "  endfunction",
             "  function automatic int read_value(input int value);",
             "    trace = trace * 10 + 2; return value;", "  endfunction"]
    if container == "ref":
        lines += declarations + ["  task automatic run(ref string result);"] + locals_ + body
        lines += ["  endtask", "  initial run(result);"]
    elif container in ("automatic", "static_task", "function"):
        opening = {"automatic": "task automatic run();", "static_task": "task run();",
                   "function": "function automatic void run();"}[container]
        lines += ["  " + opening] + declarations + locals_ + body
        lines += ["  endfunction" if container == "function" else "  endtask", "  initial run();"]
    else:
        lines += declarations
        if container == "generate":
            lines += ["  if (1) begin : g"]
        if container == "always":
            lines += ["  event go;", "  initial #1 ->go;", "  always @(go) begin"]
        else:
            lines += ["  final begin" if container == "final" else "  initial begin"]
        lines += locals_
        lines += (["    fork", "      begin"] + body + ["      end", "    join"]
                  if container == "fork" else body)
        lines += ["  end"]
        if container == "generate":
            lines += ["  end"]
    lines += (["endinterface", "module top;", "  worker u();", "endmodule"]
              if container == "interface" else ["endmodule"])
    return {name + ".sv": "\n".join(lines) + "\n",
            name + ".expected": "\n".join(expected) + "\n", name + ".stderr": ""}


def files():
    return {name: text for kind in KINDS for container in CONTAINERS
            for name, text in test(kind, container).items()}


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    bad = False
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"{name}: run tools/gen_runtime_string_format_matrix.py", file=sys.stderr)
                bad = True
        else:
            path.write_text(text, encoding="utf-8")
    return int(bad)


if __name__ == "__main__":
    sys.exit(main())
