"""Generate original wide L/H side-mask cases under VALUE_SEMANTICS 5.8.

Weak backgrounds distinguish one-sided ambiguity from full X. Signals are
sampled only after zero-delay gate propagation has settled.
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / 'tests/suite/nets'
VERSION = 1
GATES = ('bufif0', 'bufif1', 'notif0', 'notif1')
WIDTHS = (33, 63, 64, 65, 129, 257)
HOMES = ('module', 'generate', 'interface')


def resolve(gate, data, control, background):
    value = str(1 - int(data)) if gate.startswith('not') and data in '01' else data
    if value == 'z':
        value = 'x'
    if control in '01':
        return value if control == gate[-1] else str(background)
    # L with weak0 is 0, H with weak1 is 1; the opposite weak drive can
    # win when the gate is highz and loses when the gate is enabled.
    return str(background) if value == str(background) else 'x'


def case(gate, width, home):
    name = f'wide_gate_side_{gate}_{home}_{width}'
    bound = f'0:{width-1}' if home == 'generate' else f'{width-1}:0'
    declarations = f'''logic [{width-1}:0] data; logic control;
wire [{bound}] q0,q1;
assign (weak1,weak0) q0='0;
assign (weak1,weak0) q1='1;
'''
    gates = (f'{gate} g0[{width-1}:0](q0,data,control);\n'
             f'{gate} g1[{width-1}:0](q1,data,control);\n')
    body, expected = '', ''
    for control in '01xz':
        for phase in range(4):
            data = ''.join('01xz'[(bit + phase) % 4] for bit in reversed(range(width)))
            label = f'{control}_{phase}'
            body += (f"data={width}'b{data}; control=1'b{control};\n"
                     f'#1; $display("{label} %b %b",q0,q1);\n')
            values = [''.join(resolve(gate, bit, control, background) for bit in data)
                      for background in (0, 1)]
            expected += f'{label} {values[0]} {values[1]}\n'
    body += '$finish(0);\n'
    if home == 'interface':
        # Primitive instances are module items. The interface owns the
        # signals and stimulus, with direct hierarchical gate connections.
        gates = gates.replace('(q0,data,control)', '(w.q0,w.data,w.control)')
        gates = gates.replace('(q1,data,control)', '(w.q1,w.data,w.control)')
        source = ('interface cell_if;\n' + declarations + 'initial begin\n' + body +
                  'end\nendinterface\nmodule top; cell_if w();\n' + gates + 'endmodule\n')
    else:
        source = 'module top;\n' + ('if(1) begin:g\n' if home == 'generate' else '')
        source += declarations + gates + 'initial begin\n' + body + 'end\n'
        source += ('end\n' if home == 'generate' else '') + 'endmodule\n'
    header = f'''/*
:name: {name}
:description: Wide tri-state L/H masks retain both halves across word boundaries and mixed driver lists
:tags: nets strength values
:type: simulation
:lrm: 1800-2023 28.6 28.12
:oracle: spec
:spec_check: ai
:fourstate: yes
:nondeterministic: no
:generator: gen_wide_gate_side_matrix.py@{VERSION}
:top_module: top
:expected_stdout: @{name}.expected
:expected_stderr: @{name}.stderr
*/
// Generated by tools/gen_wide_gate_side_matrix.py; edit the generator.
`timescale 1ns/1ns
'''
    return {name + '.sv': header + source, name + '.expected': expected, name + '.stderr': ''}


def files():
    result = {}
    for gate in GATES:
        for width in WIDTHS:
            for home in HOMES:
                result.update(case(gate, width, home))
    original = 'wide_gate_side_bufif1_module_65'
    expression = 'wide_gate_side_expression_control'
    for name, text in case('bufif1', 65, 'module').items():
        text = text.replace(original, expression)
        text = text.replace('bufif1 g0',
                            'function automatic logic read_control(input logic v); return v; endfunction\n'
                            'logic permit=1;\nbufif1 g0', 1)
        for target in ('q0', 'q1'):
            text = text.replace(f'({target},data,control)',
                                f'({target},data,permit && read_control(control))')
        result[name.replace(original, expression)] = text
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    bad = []
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                bad.append(name)
        else:
            path.write_text(text)
    if bad:
        print('gen_wide_gate_side: out of date: ' + ', '.join(bad), file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
