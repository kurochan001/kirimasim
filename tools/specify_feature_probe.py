"""Original specify availability matrix using explicitly chosen executables.

Simulator implementation sources and generated bytecode are never inspected.
Written expected traces are separate from observed reference/native outcomes.
This is a finite inventory for review, not a native P1 pass-rate gate.
"""
import argparse
import datetime
import hashlib
import json
from pathlib import Path
import tempfile

import bounded_run

TRANSITIONS=('01','10','0z','z1','1z','z0','0x','x1','1x','x0','xz','zx')
DELAY_LISTS=((3,), (3,5), (3,5,7), (2,3,5,7,11,13), tuple(range(1,13)))


def expanded(delays):
    # Independent review table: IEEE 1800-2017 30.5.1/30.5.2 was inspected.
    # No simulator output constructs an oracle. 2023 text recheck is pending.
    if len(delays)==1:return [delays[0]]*12
    if len(delays)==2:
        rise,fall=delays
        six=(rise,fall,rise,rise,fall,fall)
    elif len(delays)==3:
        rise,fall,off=delays;six=(rise,fall,off,rise,off,fall)
    elif len(delays)==6:six=delays
    else:return list(delays)
    a,b,c,d,e,f=six
    return [a,b,c,d,e,f,min(a,c),max(a,d),min(b,e),max(b,f),max(c,e),min(d,f)]


def cell(path='(a => q)=3;',functional='assign q=a;',ports='input wire a,output wire q',prefix=''):
    return '`timescale 1ns/1ns\n'+prefix+'module cell_under_test('+ports+');\n'+functional+'\nspecify\n'+path+'\nendspecify\nendmodule\n'


def transition(source,path,old,new):
    return cell(path,source)+f'''module top;
reg a=1'b{old};wire q;bit armed=0;
cell_under_test u(a,q);
always @(q)if(armed)$display("%0t %b",$time,q);
initial begin #20;armed=1;#1;a=1'b{new};#20;$display("end %b",q);end
endmodule
'''


def transition_cases():
    for delays in DELAY_LISTS:
        times=expanded(delays)
        spec='(a => q)=('+','.join(str(x) for x in delays)+');'
        for pair,delay in zip(TRANSITIONS,times):
            yield {'name':f'delay{len(delays)}_{pair}','area':'transition_delay','clauses':'1800-2017 30.5.1/30.5.2 checked; 2023 subclause recheck unconfirmed',
                   'source':transition('assign q=a;',spec,*pair),
                   'expected_stdout':f'{21+delay} {pair[1]}\nend {pair[1]}\n','mtm':'typ','oracle':'drafted-spec-table'}
    yield {'name':'existing_p1_probe','area':'measured_gap','clauses':'30',
           'source':'`timescale 1ns/1ns\nmodule delay_cell(input a,output b); assign b=a; specify (a=>b)=3; endspecify endmodule module top; reg a=0; wire b; delay_cell u(a,b); initial begin #5 a=1; #1 $display("%b",b); #3 $display("%b",b); end endmodule',
           'expected_stdout':'0\n1\n','mtm':'typ','oracle':'existing-frozen-probe'}
    for mode,delay in (('min',2),('typ',4),('max',6)):
        yield {'name':'mintypmax_'+mode,'area':'delay_selection','clauses':'30',
               'source':transition('assign q=a;','specparam D=2:4:6;(a=>q)=D;','0','1'),
               'expected_stdout':f'{21+delay} 1\nend 1\n','mtm':mode,'oracle':'drafted-explicit-time'}



def structural_cases():
    def design(name,ports,functional,path,top,expected,area='path_shape',mtm='typ'):
        return {'name':name,'area':area,'clauses':'30; detailed 2023 text recheck unconfirmed',
                'source':cell(path,functional,ports)+top,'expected_stdout':expected,'mtm':mtm,
                'oracle':'drafted-explicit-time' if expected is not None else 'observation-only'}
    top="""module top;
reg a=0,b=0;wire q;bit armed=0;cell_under_test u(a,b,q);
always @(q)if(armed)$display("%0t %b",$time,q);
initial begin #20;armed=1;#1;a=1;#20;b=1;#20;$display("end %b",q);end
endmodule
"""
    yield design('full_two_inputs','input wire a,b,output wire q','assign q=a^b;',
                 '(a,b *> q)=3;',top,'24 1\n44 0\nend 0\n')
    yield design('distinct_input_delays','input wire a,b,output wire q','assign q=a^b;',
                 '(a=>q)=7;(b=>q)=3;',top,'28 1\n44 0\nend 0\n','path_selection')
    simultaneous=top.replace('#1;a=1;#20;b=1;','#1;{a,b}=3;#20;{a,b}=0;')
    yield design('simultaneous_choose_min','input wire a,b,output wire q','assign q=a&b;',
                 '(a=>q)=7;(b=>q)=3;',simultaneous,'24 1\n44 0\nend 0\n','path_selection')
    for connection in ('=>','*>'):
        vec="""module top;
reg[2:0] a=0;wire[2:0] q;bit armed=0;cell_under_test u(a,q);
always @(q)if(armed)$display("%0t %b",$time,q);
initial begin #20;armed=1;#1;a=3'b101;#20;a=3'b011;#20;$display("end %b",q);end
endmodule
"""
        yield design('vector_'+('parallel' if connection=='=>' else 'full'),
                     'input wire[2:0] a,output wire[2:0] q','assign q=a;',
                     '(a '+connection+' q)=(2,4);',vec,'23 101\n43 111\n45 011\nend 011\n')
    for distributed in (0,4,9):
        yield {'name':f'distributed_{distributed}_path7','area':'distributed_delay','clauses':'1800-2017 30.6 checked; 2023 text recheck unconfirmed',
               'source':transition(f'buf #({distributed}) g(q,a);','(a=>q)=7;','0','1'),
               'expected_stdout':f'{21+max(distributed,7)} 1\nend 1\n','mtm':'typ','oracle':'drafted-explicit-time'}
    for edge in ('posedge','negedge'):
        initial='0' if edge=='posedge' else '1';active='1' if edge=='posedge' else '0'
        edge_top=f"""module top;
reg a=1'b{initial},d=0;wire q;bit armed=0;cell_under_test u(a,d,q);
always @(q)if(armed)$display("%0t %b",$time,q);
initial begin #20;armed=1;d=1;#1;a=1'b{active};#10;d=0;#10;a=1'b{initial};#10;a=1'b{active};#20;$display("end %b",q);end
endmodule
"""
        yield design('edge_'+edge,'input wire a,d,output wire q',
                     'reg state=0;always @('+edge+' a)state<=d;assign q=state;',
                     '('+edge+' a => (q +: d))=(2,5);',edge_top,'23 1\n56 0\nend 0\n','edge_path')
    cond_top=top.replace('#1;a=1;#20;b=1;','#1;a=1;#20;b=1;#10;a=0;')
    yield design('condition_ifnone','input wire a,b,output wire q','assign q=a;',
                 'if(b)(a=>q)=3;ifnone(a=>q)=7;',cond_top,'28 1\n54 0\nend 0\n','state_dependent')
    for width in (1,3,5,7):
        pulse=top.replace('#1;a=1;#20;b=1;',f'#1;a=1;#{width};a=0;')
        expected='end 0\n' if width<5 else f'26 1\n{26+width} 0\nend 0\n'
        yield design('pulse_width_'+str(width),'input wire a,b,output wire q','assign q=a;',
                     '(a=>q)=5;',pulse,expected,'default_pulse')
    # These observations deliberately do not assert a portable oracle yet.
    for style in ('','pulsestyle_onevent q;','pulsestyle_ondetect q;','showcancelled q;','noshowcancelled q;','specparam PATHPULSE$=1;'):
        key=style.split()[0].replace(';','').replace('$','') if style else 'default'
        pulse=top.replace('#1;a=1;#20;b=1;','#1;a=1;#1;a=0;')
        path='(a=>q)=(9,2);'
        if style.startswith('specparam'):
            pulse=top.replace('#1;a=1;#20;b=1;','#1;a=1;#3;a=0;')
            path='(a=>q)=(5,5);'
        yield design('pulse_control_'+key,'input wire a,b,output wire q','assign q=a;',
                     path+style,pulse,None,'pulse_control_observation')
    # A timing check must have an observable effect; successful parsing alone
    # is not evidence that a reference executes $setup.
    timing="""`timescale 1ns/1ns
module cell_under_test(input wire clk,d,output wire q);
reg notifier=0;assign q=notifier;
specify $setup(d,posedge clk,3,notifier);endspecify
endmodule
module top;reg clk=0,d=0;wire q;cell_under_test u(clk,d,q);
initial begin #19;d=1;#1;clk=1;#5;$display("notifier %b",q);end
endmodule
"""
    yield {'name':'setup_violation_observed','area':'timing_check_observation','clauses':'31 (native contract not proposed here)',
           'source':timing,'expected_stdout':None,'mtm':'typ','oracle':'observation-only'}



def boundary_cases():
    for delay,name in ((0,'zero'),(-3,'negative')):
        yield {'name':name+'_path_delay','area':'normalization','clauses':'1800-2017 30.5.1 checked; 2023 text recheck unconfirmed',
               'source':transition('assign q=a;',f'specparam D={delay};(a=>q)=D;','0','1'),
               'expected_stdout':'21 1\nend 1\n','mtm':'typ','oracle':'drafted-explicit-time'}
    source=transition('assign q=a;','(a=>q)=0;','0','1')
    source=source.replace('always @(q)if(armed)$display("%0t %b",$time,q);','')
    source=source.replace('#20;$display("end %b",q);','#0;$display("inactive %b",q);')
    yield {'name':'zero_path_before_inactive','area':'regions','clauses':'4, 30; 2023 text recheck unconfirmed',
           'source':source,'expected_stdout':'inactive 1\n','mtm':'typ','oracle':'drafted-region-order'}
    source=transition('assign q=a;','(a=>q)=0.25;','0','1').replace('1ns/1ns','1ns/100ps')
    source=source.replace('"%0t %b",$time,q','"%.1f %b",$realtime,q')
    yield {'name':'real_delay_round_once','area':'normalization','clauses':'3, 30; 2023 text recheck unconfirmed',
           'source':source,'expected_stdout':'21.3 1\nend 1\n','mtm':'typ','oracle':'drafted-explicit-time'}
    template=next(x for x in structural_cases() if x['name']=='edge_posedge')
    for label,annotation in (('negative_annotation','q -: d'),('no_polarity_annotation','q : d')):
        row=dict(template);row.update(name=label,source=template['source'].replace('q +: d',annotation))
        yield row
    row=dict(template);row.update(name='data_annotation_is_not_executed',
        source=template['source'].replace('reg state=0;',
            'integer calls=0;function marker;begin calls=calls+1;marker=d;end endfunction reg state=0;')
            .replace('q +: d','q +: marker()')
            .replace('$display("end %b",q);','$display("end %b calls %0d",q,u.calls);'),
        expected_stdout='23 1\n56 0\nend 0 calls 0\n')
    yield row
    force_top="""module top;reg a=0;wire q;cell_under_test u(a,q);
initial begin #20;a=1;#1;force u.q=0;#7;$display("forced %b",q);release u.q;#0;$display("released %b",q);end
endmodule
"""
    yield {'name':'forced_output_pending_path','area':'force_observation','clauses':'10.6, 30; integration review required',
           'source':cell('(a=>q)=5;')+force_top,'expected_stdout':None,'mtm':'typ','oracle':'observation-only'}
    internal="""`timescale 1ns/1ns
module cell_under_test(input wire a,output wire q);assign q=a;
specify(a=>q)=3;endspecify
initial begin #22;$display("inside early %b",q);#3;$display("inside late %b",q);end
endmodule
module top;reg a=0;wire q;cell_under_test u(a,q);
initial begin #21;a=1;#1;$display("outside early %b",q);#3;$display("outside late %b",q);end
endmodule
"""
    yield {'name':'internal_and_external_reads','area':'visibility','clauses':'30; 2023 text recheck unconfirmed',
           'source':internal,'expected_stdout':None,'mtm':'typ','oracle':'observation-only'}
    for value in ("1'b0","1'b1","1'bx","1'bz","2'b10","2'b11","2'b1x"):
        source=transition('assign q=a;',f'if({value})(a=>q)=3;ifnone(a=>q)=7;','0','1')
        delay=7 if value in ("1'b0","2'b10") else 3
        yield {'name':'condition_'+value.replace("'",'_'),'area':'condition_semantics',
               'clauses':'1800-2017 30.4.4.1 checked; 2023 text recheck unconfirmed',
               'source':source,'expected_stdout':f'{21+delay} 1\nend 1\n','mtm':'typ','oracle':'drafted-lsb-condition'}

def cases():
    yield from transition_cases()
    yield from structural_cases()
    yield from boundary_cases()

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--iverilog',type=Path,required=True)
    parser.add_argument('--vvp',type=Path,required=True)
    parser.add_argument('--kirimasim',type=Path)
    parser.add_argument('--case',action='append')
    parser.add_argument('--source-dir',type=Path,help='explicit original or fault-injected source copies')
    parser.add_argument('--export',type=Path)
    parser.add_argument('--output',type=Path,required=True)
    parser.add_argument('--fail-on-reference-mismatch',action='store_true',
                        help='exit 1 for an unmatched written reference oracle; otherwise exit 0 means the inventory was recorded, not that its cases passed')
    args=parser.parse_args()
    selected=[x for x in cases() if not args.case or x['name'] in args.case]
    assert selected and (not args.case or set(args.case)=={x['name'] for x in selected})
    tools={'iverilog':args.iverilog.resolve(),'vvp':args.vvp.resolve()}
    if args.kirimasim:tools['kirimasim']=args.kirimasim.resolve()
    report={'date':datetime.date.today().isoformat(),'scope':'Original finite specify inventory, not full coverage or an approved native oracle',
            'runner_sha256':hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
            'exit_policy':'fail-on-reference-mismatch' if args.fail_on_reference_mismatch else 'record-inventory-with-independent-failure-check',
            'tool_sha256':{k:hashlib.sha256(p.read_bytes()).hexdigest() for k,p in tools.items()},'versions':{},'cases':[]}
    for name,path in tools.items():
        ran=bounded_run.run([str(path),'--version' if name=='kirimasim' else '-V'],timeout=15)
        report['versions'][name]=next((line for line in (ran.stdout+ran.stderr).splitlines() if 'version' in line.lower() or name=='kirimasim'),'unconfirmed')
    if args.export:args.export.mkdir(parents=True,exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='kirimasim-specify-inventory-') as tmp:
        directory=Path(tmp)
        for case in selected:
            row=dict(case);source=(args.source_dir/(case['name']+'.sv')).read_text() if args.source_dir else case['source']
            row['source']=source;row['source_sha256']=hashlib.sha256(source.encode()).hexdigest()
            row['canonical_source_sha256']=hashlib.sha256(case['source'].encode()).hexdigest()
            if args.export:(args.export/(case['name']+'.sv')).write_text(source)
            path=directory/(case['name']+'.sv');path.write_text(source)
            def cleaned(text):return text.replace(str(directory),'<probe>')
            flags=['-g2012','-gspecify','-T'+case['mtm']]
            built=bounded_run.run([str(tools['iverilog']),*flags,'-s','top','-o','design.vvp',path.name],cwd=directory,timeout=15)
            reference={'compile_flags':flags,'compile_exit':built.returncode,'compile_stdout':cleaned(built.stdout),'compile_stderr':cleaned(built.stderr)}
            if built.returncode:reference['status']='compile_error'
            else:
                ran=bounded_run.run([str(tools['vvp']),'-n','design.vvp'],cwd=directory,timeout=15)
                reference.update({'run_exit':ran.returncode,'stdout':cleaned(ran.stdout),'stderr':cleaned(ran.stderr)})
                reference['status']=('observed' if case['expected_stdout'] is None else 'passed' if ran.stdout==case['expected_stdout'] else 'reference_mismatch') if ran.returncode==0 and not ran.stderr else 'reference_mismatch'
            reference['oracle_evaluated']=case['expected_stdout'] is not None
            messages=reference.get('compile_stderr','')+'\n'+reference.get('stderr','')
            reference['unsupported_diagnostics']=[x for x in messages.splitlines() if 'not supported' in x or 'not fully supported' in x]
            row['icarus']=reference
            if args.kirimasim:
                parsed=bounded_run.run([str(tools['kirimasim']),'parse',path.name],cwd=directory,timeout=15)
                ran=bounded_run.run([str(tools['kirimasim']),'--mintypmax='+case['mtm'],path.name],cwd=directory,timeout=15)
                diagnostics='\n'.join(x for x in ran.stderr.splitlines() if not x.startswith('kirimasim: info:'))
                if parsed.returncode!=0:
                    status='parse_failed'
                elif ran.returncode==0 and case['expected_stdout'] is None:
                    status='executed_without_oracle'
                elif ran.returncode==0 and ran.stdout==case['expected_stdout'] and 'error:' not in diagnostics:
                    status='passed'
                elif ran.returncode==2 and 'not implemented yet' in diagnostics and 'internal error' not in diagnostics:
                    status='unsupported'
                else:
                    status='failed'
                row['kirimasim']={'parse_exit':parsed.returncode,'exit':ran.returncode,'stdout':cleaned(ran.stdout),'stderr':cleaned(diagnostics),'status':status}
            report['cases'].append(row)
            print(case['name']+': '+reference['status']+((' / native '+row['kirimasim']['status']) if args.kirimasim else ''),flush=True)
    report['summary']={'total':len(selected),'reference_passed':sum(x['icarus']['status']=='passed' for x in report['cases']),
                       'reference_observed_without_oracle':sum(x['icarus']['status']=='observed' for x in report['cases']),
                       'native_evaluated':len(selected) if args.kirimasim else 0,
                       'native_passed':sum(x.get('kirimasim',{}).get('status')=='passed' for x in report['cases']) if args.kirimasim else None,
                       'native_unsupported':sum(x.get('kirimasim',{}).get('status')=='unsupported' for x in report['cases']) if args.kirimasim else None,
                       'native_executed':sum(x.get('kirimasim',{}).get('exit')==0 for x in report['cases']) if args.kirimasim else None}
    if args.export:(args.export/'manifest.json').write_text(json.dumps(report['cases'],indent=2)+'\n')
    args.output.parent.mkdir(parents=True,exist_ok=True);args.output.write_text(json.dumps(report,indent=2)+'\n')
    print(report['summary'])
    independent=any(row['icarus'].get('compile_exit',0) not in (0,1,2) or row['icarus'].get('run_exit',0) != 0 or row.get('kirimasim',{}).get('exit',0) not in (0,2) for row in report['cases'])
    unmatched=report['summary']['reference_passed']+report['summary']['reference_observed_without_oracle']!=len(selected)
    return 1 if independent or (args.fail_on_reference_mismatch and unmatched) else 0


if __name__=='__main__':raise SystemExit(main())
