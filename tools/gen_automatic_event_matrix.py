"""Generate original automatic-event construction and retained-extent checks.

IEEE 1800-2023 6.8/6.21/9.3.2/15.5; approved automatic-capture contract 5/6/8.
No external simulator sources, tests or quoted standard examples are used.
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests/suite/sched"
SHAPES = {
    "scalar": ("", "for (int i=0; i<1; ++i)", "events", 1),
    "ascending": ("[-1:1]", "for (int i=-1; i<=1; ++i)", "events[i]", 3),
    "descending": ("[3:1]", "for (int i=3; i>=1; --i)", "events[i]", 3),
    "rank2": ("[-1:0][3:2]", "for (int i=-1; i<=0; ++i) for (int j=3; j>=2; --j)",
              "events[i][j]", 4),
}


def header(name, description, expected):
    return f'''/*
:name: {name}
:description: {description}
:tags: sched event automatic capture
:type: simulation
:lrm: 1800-2023 6.8 6.21 9.3.2 15.5
:oracle: spec
:spec_check: ai
:fourstate: no
:nondeterministic: no
:generator: gen_automatic_event_matrix.py@1
:top_module: top
:expected_stdout: {expected}
:timeout: 10
*/
// Generated by tools/gen_automatic_event_matrix.py; edit the generator.
`timescale 1ns/1ns
'''


def defaults(home, shape):
    dims, loop, target, size = SHAPES[shape]
    name = f"automatic_event_default_{home}_{shape}"
    body = f'''    automatic int errors=0;
    automatic int checked=0;
    for (int round=0; round<64; ++round) begin
      automatic event events{dims};
      {loop} begin
        if ({target}.triggered) ++errors;
        -> {target};
        if (!{target}.triggered) ++errors;
        ++checked;
      end
    end
    $display("checked=%0d errors=%0d",checked,errors);
'''
    wrappers = {
        "initial": f"module top; initial begin\n{body}end endmodule\n",
        "task": f"module top; task automatic run();\n{body}endtask initial run(); endmodule\n",
        "function": f"module top; function automatic void run();\n{body}endfunction initial run(); endmodule\n",
        "fork": f"module top; initial fork begin\n{body}end join endmodule\n",
        "interface": f"interface unit; initial begin\n{body}end endinterface\nmodule top; unit u(); endmodule\n",
        "package": f"package unit; function automatic void run();\n{body}endfunction endpackage\nmodule top; initial unit::run(); endmodule\n",
        "program": f"program automatic unit; initial begin\n{body}end endprogram\nmodule top; unit u(); endmodule\n",
        "generate": f"module top; if (1) begin: generated initial begin\n{body}end end endmodule\n",
    }
    return name, header(name, "Each nonwaiting declaration entry constructs distinct fresh event objects",
                        f"checked={64 * size} errors=0") + wrappers[home]


def capture(program, join, shape, wait, delayed):
    dims = SHAPES[shape][0]
    target = {"scalar": "events", "ascending": "events[index]",
              "descending": "events[index]", "rank2": "events[index][2]"}[shape]
    index = -1 if shape in ("ascending", "rank2") else 2
    name = f"automatic_event_capture_{'program' if program else 'module'}_{join}_{shape}_{wait}_{'nba' if delayed else 'active'}"
    waiting = {"named": f"@({target});", "mixed": f"@({target} or posedge dummy);",
               "triggered": f"wait({target}.triggered);"}[wait]
    trigger = f"->> #1 {target};" if delayed else f"-> {target};"
    content = f'''  int results[0:1];
  int errors=0;
  bit dummy=0;
  task automatic spawn(input int tag);
    event events{dims};
    int index={index};
    fork
      begin
        #1;
        if ({target}.triggered) ++errors;
        {trigger}
      end
      begin
        {waiting}
        if (!{target}.triggered) ++errors;
        results[tag]=tag+1;
      end
    {join}
  endtask
  initial begin
    spawn(0);
    spawn(1);
    wait fork;
    $display("total=%0d errors=%0d",results[0]+results[1],errors);
  end
'''
    wrapper = (f"program automatic unit;\n{content}endprogram\nmodule top; unit u(); endmodule\n"
               if program else f"module top;\n{content}endmodule\n")
    return name, header(name, "Task descendants retain automatic event extents and concrete delayed targets",
                        "total=3 errors=0") + wrapper


def files():
    for home in ("initial", "task", "function", "fork", "interface", "package", "program", "generate"):
        for shape in SHAPES:
            yield defaults(home, shape)
    for program in (False, True):
        for join in ("join", "join_any", "join_none"):
            for shape in SHAPES:
                for wait in ("named", "mixed", "triggered"):
                    for delayed in (False, True):
                        yield capture(program, join, shape, wait, delayed)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    bad = []
    for name, text in files():
        path = OUT / f"{name}.sv"
        if args.check:
            if not path.exists() or path.read_text() != text:
                bad.append(path.name)
        else:
            path.write_text(text)
    if bad:
        print("gen_automatic_event_matrix: out of date: " + ", ".join(bad), file=sys.stderr)
    return int(bool(bad))


if __name__ == "__main__":
    sys.exit(main())
