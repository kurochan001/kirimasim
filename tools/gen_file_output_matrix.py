"""Generates the matrix tests of file output (TEST_SUITE.md, "Mechanism
matrix") in tests/suite/proc/.

  tools/gen_file_output_matrix.py           # writes the files
  tools/gen_file_output_matrix.py --check   # exit 1 if a file differs from what it would write

The rules (21.3.1, 21.3.2, SYSTEM_TASKS.md 6.1 and 6.2): $fdisplay,
$fwrite, $fstrobe and $fmonitor, in their plain, b, o and h forms, print
what $display, $write, $strobe and $monitor print, to the files their
first argument names: each file of an mcd (bit 0 is standard output), or
the file of an fd (32'h8000_0001 is standard output). $fstrobe and
$fmonitor read that descriptor when they are called, and their other
arguments in the Postponed region; $fclose ends a $fmonitor of its file.

The axes: the task and its form, the descriptor (an mcd of one file, an
mcd of two files, an mcd of a file and standard output, an fd, STDOUT),
and the container of the call (an initial procedure, a task, a function,
a fork branch, a task in a generate block). Each cell opens its files,
calls the task with a value A, then in the same time slot sets the
descriptor variable to 0 and the value to B; one time unit later the
value becomes C, and one more later the cell closes its files, opens
each again for reading and prints every line with $fgets. Every test
runs in an empty directory of its own (TEST_SUITE.md, "What is judged
now").

At the end of each test, one $fmonitor call of the container is made
twice, for two files: any number of $fmonitor calls run at once, each
from its own first print (21.3.2).

The expected outputs follow from the rules above, without reading
kirimasim's code: $fdisplay and $fwrite print A at the call, $fstrobe
prints B, and $fmonitor prints B and then C. For reference, checked
2026-10-20: Icarus 14.0 devel gives the same output for every test.
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "proc"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

TASKS = ["$fdisplay", "$fwrite", "$fstrobe", "$fmonitor"]
FORMS = ["", "b", "o", "h"]
DESCRIPTORS = ["mcd", "mcd2", "mcd_out", "fd", "stdout"]
CONTAINERS = ["initial", "task", "function", "fork", "generate"]
A, B, C = 0xA5, 0x3C, 0x07


def shown(value, form):
    """An 8-bit unsigned value as the display tasks print it with no
    format: decimal in 3 columns, or all the digits of the radix (21.2.1.3)."""
    if form == "b":
        return format(value, "08b")
    if form == "o":
        return format(value, "03o")
    if form == "h":
        return format(value, "02x")
    return format(value, "3d")


def cells():
    """(k, task, form, descriptor) of each cell."""
    out = []
    for task in TASKS:
        for form in FORMS:
            for desc in DESCRIPTORS:
                out.append((len(out), task, form, desc))
    return out


def call(k, task, form, dd):
    tail = ', "\\n"' if task == "$fwrite" else ""
    return f'{task}{form}({dd}, "c{k} ", v{k}{tail});'


def files_of(k, desc):
    return {"mcd": [f"c{k}.txt"], "mcd2": [f"c{k}a.txt", f"c{k}b.txt"],
            "mcd_out": [f"c{k}.txt"], "fd": [f"c{k}.txt"], "stdout": []}[desc]


def test(container):
    name = f"file_output_{container}"
    cs = cells()
    sv = (f"/*\n:name: {name}\n:description: $fdisplay, $fwrite, $fstrobe and $fmonitor in "
          f"every form, to an mcd of one or two files, an mcd with standard output, an fd and "
          f"STDOUT, called from {'an' if container[0] in 'aeiou' else 'a'} {container}: "
          f"each prints to the files its descriptor names at the call\n:tags: proc\n"
          f":type: simulation\n:lrm: 1800-2023 21.3.1 21.3.2 21.3.4.2\n:oracle: spec\n"
          f":spec_check: ai\n:fourstate: no\n:nondeterministic: no\n"
          f":generator: gen_file_output_matrix.py@{VERSION}\n:top_module: top\n"
          f":expected_stdout: @{name}.expected\n*/\n"
          "// Generated by tools/gen_file_output_matrix.py; change the generator, not this file.\n"
          "`timescale 1ns/1ns\nmodule top;\n  integer d, m1, m2, i;\n  reg [7:0] w;\n")
    sv += "".join(f"  reg [7:0] v{k};\n" for k, _, _, _ in cs)
    # Prints every line of a file, then a line that it ended.
    sv += ("  task show(input string name);\n    integer r, n;\n    string line;\n"
           "    r = $fopen(name, \"r\");\n    n = $fgets(line, r);\n"
           "    while (n > 0) begin\n      $write(\"%s: %s\", name, line);\n"
           "      n = $fgets(line, r);\n    end\n    $display(\"%s: end\", name);\n"
           "    $fclose(r);\n  endtask\n")
    for k, task, form, _ in cs:
        if container == "task":
            sv += f"  task t{k}(input integer dd);\n    {call(k, task, form, 'dd')}\n  endtask\n"
        elif container == "function":
            sv += (f"  function void f{k}(input integer dd);\n    {call(k, task, form, 'dd')}\n"
                   "  endfunction\n")
        elif container == "generate":
            sv += (f"  if (1) begin : g{k}\n    task t(input integer dd);\n"
                   f"      {call(k, task, form, 'dd')}\n    endtask\n  end\n")
    if container == "task":
        sv += '  task tw(input integer dd);\n    $fmonitor(dd, "w ", w);\n  endtask\n'
    elif container == "function":
        sv += ('  function void fw(input integer dd);\n    $fmonitor(dd, "w ", w);\n'
               "  endfunction\n")
    elif container == "generate":
        sv += ('  if (1) begin : gw\n    task t(input integer dd);\n'
               '      $fmonitor(dd, "w ", w);\n    endtask\n  end\n')
    sv += "  initial begin\n"
    exp = ""
    for k, task, form, desc in cs:
        names = files_of(k, desc)
        sv += f"    // {task}{form} to {desc}\n"
        # m1 keeps the files to close: those of d but standard output.
        if desc == "mcd":
            sv += f'    m1 = $fopen("{names[0]}");\n    d = m1;\n'
        elif desc == "mcd2":
            sv += (f'    m1 = $fopen("{names[0]}");\n    m2 = $fopen("{names[1]}");\n'
                   "    m1 = m1 | m2;\n    d = m1;\n")
        elif desc == "mcd_out":
            sv += f'    m1 = $fopen("{names[0]}");\n    d = m1 | 1;\n'
        elif desc == "fd":
            sv += f'    m1 = $fopen("{names[0]}", "w");\n    d = m1;\n'
        else:
            sv += "    d = 32'h8000_0001;\n"
        sv += f"    v{k} = 8'h{A:02x};\n"
        sv += "    " + {"initial": call(k, task, form, "d"), "task": f"t{k}(d);",
                        "function": f"f{k}(d);", "fork": f"fork {call(k, task, form, 'd')} join",
                        "generate": f"g{k}.t(d);"}[container] + "\n"
        sv += f"    d = 0;\n    v{k} = 8'h{B:02x};\n    #1 v{k} = 8'h{C:02x};\n    #1"
        sv += " $fclose(m1);\n" if desc != "stdout" else ";\n"
        for n in names:
            sv += f'    show("{n}");\n'
        if task in ("$fdisplay", "$fwrite"):
            lines = [f"c{k} {shown(A, form)}"]
        elif task == "$fstrobe":
            lines = [f"c{k} {shown(B, form)}"]
        else:
            lines = [f"c{k} {shown(B, form)}", f"c{k} {shown(C, form)}"]
        if desc in ("mcd_out", "stdout"):
            exp += "".join(line + "\n" for line in lines)
        for n in names:
            exp += "".join(f"{n}: {line}\n" for line in lines) + f"{n}: end\n"
    # One $fmonitor call made twice, for two files.
    sv += "    // one $fmonitor call, twice\n    w = 1;\n"
    sv += '    m1 = $fopen("w1.txt", "w");\n    m2 = $fopen("w2.txt", "w");\n'
    # A static loop variable: a fork branch reads no automatic one yet.
    sv += "    " + {"initial": "for (i = 0; i < 2; i++) $fmonitor(i == 0 ? m1 : m2, \"w \", w);",
                    "task": "tw(m1);\n    tw(m2);", "function": "fw(m1);\n    fw(m2);",
                    "fork": "for (i = 0; i < 2; i++) fork $fmonitor(i == 0 ? m1 : m2, \"w \", w); join",
                    "generate": "gw.t(m1);\n    gw.t(m2);"}[container] + "\n"
    sv += "    #1 w = 2;\n    #1 $fclose(m1);\n    $fclose(m2);\n"
    sv += '    show("w1.txt");\n    show("w2.txt");\n'
    for n in ("w1.txt", "w2.txt"):
        exp += f"{n}: w   1\n{n}: w   2\n{n}: end\n"
    sv += "  end\nendmodule\n"
    return name, sv, exp


def files():
    out = {}
    for container in CONTAINERS:
        name, sv, exp = test(container)
        out[f"{name}.sv"] = sv
        out[f"{name}.expected"] = exp
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_file_output_matrix: {path.relative_to(OUT.parent.parent.parent)} is "
                      "out of date; run tools/gen_file_output_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
