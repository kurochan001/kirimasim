"""Generates the matrix test of empty arguments of the display tasks, of
TEST_SUITE.md ("Mechanism matrix"), in tests/suite/proc/.

  tools/gen_empty_argument_matrix.py           # writes the files
  tools/gen_empty_argument_matrix.py --check   # exit 1 if a file differs from what it would write

An empty argument of $display and the tasks like it (a leading or
trailing comma, or two commas in a row) prints one space, and a list of
a single comma is two empty arguments (21.2.1, SYSTEM_TASKS.md 3.1). A
value without a specifier prints in the radix of the task's form with
the automatic width (3.1, 3.3), and a string literal that no specifier
takes is a format (3.1).

The axes: the task ($display, $write, the b, o and h forms of $display,
and $swrite into a string); where the empty arguments are (between two
values, leading, trailing, a single comma, two commas, between two
literals, after a value that a specifier took); the container (an
initial procedure, an automatic task, a function, a branch of a fork and
a final procedure). The value is 8 bits, 5.

The expected outputs follow from the rules above, computed below. A
person checks them once for all the tests made from them (TEST_SUITE.md,
"Sampling by people").
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "proc"
NAME = "empty_argument_matrix"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

VALUE, WIDTH = 5, 8
# (name, the arguments, what they print with a value printed as {v})
PATTERNS = [
    ("between", "v,,v", "{v} {v}"),
    ("leading", ",v", " {v}"),
    ("trailing", "v,", "{v} "),
    ("one_comma", ",", "  "),
    ("two_commas", ",,", "   "),
    ("literals", '"<",,">"', "< >"),
    ("after_spec", '"[%0d]", v,,v', "[5] {v}"),
]
# (task, radix of values without a specifier)
TASKS = [("$display", "d"), ("$write", "d"), ("$displayb", "b"), ("$displayo", "o"),
         ("$displayh", "h"), ("$swrite", "d")]
CONTAINERS = ["initial", "task", "function", "fork", "final"]


def shown(radix):
    """VALUE as a value of WIDTH bits without a specifier prints."""
    if radix == "d":
        return str(VALUE).rjust(len(str((1 << WIDTH) - 1)))
    bits = {"b": 1, "o": 3, "h": 4}[radix]
    digits = (WIDTH + bits - 1) // bits
    return format(VALUE, {"b": "b", "o": "o", "h": "x"}[radix]).rjust(digits, "0")


def statement(task, args, tag):
    if task == "$swrite":
        return f'$swrite(s, {args}); $display("{tag} [%s]", s);'
    if task == "$write":
        return f'$write("{tag} ["); $write({args}); $write("]\\n");'
    return f'$write("{tag} ["); {task}({args}); $write("]\\n");'


def expected(task, radix, out, tag):
    text = out.replace("{v}", shown(radix))
    if task in ("$display", "$displayb", "$displayo", "$displayh"):
        # The display ends its line before the closing bracket.
        return [f"{tag} [{text}", "]"]
    return [f"{tag} [{text}]"]


def files():
    lines, exp = {c: [] for c in CONTAINERS}, {c: [] for c in CONTAINERS}
    for container in CONTAINERS:
        for task, radix in TASKS:
            for pattern, args, out in PATTERNS:
                tag = f"{container} {task} {pattern}"
                lines[container].append(statement(task, args, tag))
                exp[container] += expected(task, radix, out, tag)
    head = [
        "/*",
        f":name: {NAME}",
        ":description: empty arguments of $display, $write, $displayb, $displayo, $displayh and "
        "$swrite print one space each, a single comma being two of them, between values, "
        "leading, trailing, between literals and after a specifier's value, in an initial "
        "procedure, an automatic task, a function, a fork branch and a final procedure",
        ":tags: proc display",
        ":type: simulation",
        ":lrm: 1800-2023 21.2.1 21.3.3",
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: no",
        ":nondeterministic: no",
        f":generator: gen_empty_argument_matrix.py@{VERSION}",
        ":top_module: top",
        f":expected_stdout: @{NAME}.expected",
        "*/",
        "// Generated by tools/gen_empty_argument_matrix.py; change the generator, not this file.",
        "`timescale 1ns/1ns",
        "module top;",
        f"  logic [{WIDTH - 1}:0] v = {WIDTH}'d{VALUE};",
        "  string s;",
        "  task automatic t();",
    ]
    body = (head + ["    " + x for x in lines["task"]] + ["  endtask", "  function void f();"]
            + ["    " + x for x in lines["function"]] + ["  endfunction", "  initial begin"]
            + ["    " + x for x in lines["initial"]] + ["    t();", "    f();", "    fork",
                                                         "      begin"]
            + ["        " + x for x in lines["fork"]] + ["      end", "    join", "  end",
                                                         "  final begin"]
            + ["    " + x for x in lines["final"]] + ["  end", "endmodule", ""])
    order = exp["initial"] + exp["task"] + exp["function"] + exp["fork"] + exp["final"]
    return {f"{NAME}.sv": "\n".join(body), f"{NAME}.expected": "\n".join(order) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_empty_argument_matrix: {path.relative_to(OUT.parent.parent.parent)} "
                      "is out of date; run tools/gen_empty_argument_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
