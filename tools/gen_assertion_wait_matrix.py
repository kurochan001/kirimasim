"""Generates the matrix tests of immediate assertions in the bodies whose
waits front looks at, of TEST_SUITE.md ("Mechanism matrix"), in
tests/suite/proc/.

  tools/gen_assertion_wait_matrix.py           # writes the files
  tools/gen_assertion_wait_matrix.py --check   # exit 1 if a file differs from what it would write

An immediate assertion waits only where its action blocks do. The action
blocks of a simple immediate assertion run in the thread that runs it
(16.3); the action of a deferred one, #0 or final, runs later, not in that
thread (16.4). So an always_ff with an assertion in its body still waits
only at its event control (SIR_SPEC.md 7.1), and a task with an assertion
whose actions do not wait may be called from always_comb, always_latch
and always_ff (SIR_SPEC.md 10, rule 5). A simple assertion whose action
block waits makes its task one that may wait.

The axes: the kind of assertion (simple, #0, final); where it is (in the
body of always_ff, in a task that always_ff, always_comb or always_latch
calls); and a simple assertion whose pass or fail action waits, in a task
an initial procedure calls.

The expected outputs follow from the rules above, computed below.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SUITE = ROOT / "tests" / "suite" / "proc"
PREFIX = "assertion_wait_"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

# (name, the word after assert, the clause)
KINDS = [("simple", "", "16.3"), ("observed", " #0", "16.4"), ("final", " final", "16.4")]
# (name, the block, with {stmt} for the assertion or the call of tk, the
# clause, what the description calls it)
CONTAINERS = [
    ("ff_body", ["always_ff @(posedge clk) begin", "  q <= d;", "  {assert}", "end"], "9.2.2.4",
     "the body of always_ff"),
    ("ff_task", ["always_ff @(posedge clk) begin", "  q <= d;", "  tk(d);", "end"], "9.2.2.4",
     "a task that always_ff calls"),
    ("comb_task", ["always_comb begin", "  q = d;", "  tk(d);", "end"], "9.2.2.2",
     "a task that always_comb calls"),
    ("latch_task", ["always_latch if (en) begin", "  q = d;", "  tk(d);", "end"], "9.2.2.3",
     "a task that always_latch calls"),
]
FAILED = "else $display(\"failed at %0t\", $time);"


def header(name, description, lrm):
    return [
        "/*",
        f":name: {name}",
        f":description: {description}",
        ":tags: proc",
        ":type: simulation",
        ":lrm: 1800-2023 " + " ".join(lrm),
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: no",
        ":nondeterministic: no",
        f":generator: gen_assertion_wait_matrix.py@{VERSION}",
        ":issue: 22",
        ":top_module: top",
        f":expected_stdout: @{name}.expected",
        "*/",
        "// Generated by tools/gen_assertion_wait_matrix.py; change the generator, not this file.",
        "`timescale 1ns/1ns",
    ]


def case(kind, container):
    kname, word, kclause = kind
    cname, block, cclause, where = container
    name = f"{PREFIX}{kname}_{cname}"
    lines = ["module top;", "  logic clk = 1'b0, en = 1'b1;", "  logic [7:0] d = 8'd0, q;"]
    if cname == "ff_body":
        stmt = f"assert{word} (d != 8'd1) {FAILED}"
    else:
        lines += ["  task automatic tk(logic [7:0] x);", f"    assert{word} (x != 8'd1) {FAILED}",
                  "  endtask"]
        stmt = ""
    lines += ["  " + x.format(**{"assert": stmt}) for x in block]
    # The assertion fails once, at 1, when d becomes 1 (on the clock for
    # always_ff); a final action runs at the end of that time slot.
    lines += ["  initial begin", "    #1 d = 8'd1;", "    clk = 1'b1;",
              "    #1 $display(\"q=%0d\", q);", "  end", "endmodule"]
    what = {"simple": "a simple immediate assertion", "observed": "a #0 deferred assertion",
            "final": "a final deferred assertion"}[kname]
    description = f"{what} in {where} does not wait"
    return name, header(name, description, [kclause, cclause]) + lines, ["failed at 1", "q=1"]


def waiting_case(action):
    """A simple assertion whose pass or fail action waits, in a task."""
    name = f"{PREFIX}simple_{action}_waits"
    cond, head = ("x == 8'd1", "") if action == "pass" else ("x != 8'd1", "else ")
    lines = ["module top;", "  task automatic tk(logic [7:0] x);",
             f"    assert ({cond}) {head}begin", f"      #1 $display(\"{action}ed at %0t\", $time);",
             "    end", "  endtask", "  initial begin", "    #1 tk(8'd1);",
             "    $display(\"back at %0t\", $time);", "  end", "endmodule"]
    description = (f"a simple immediate assertion whose {action} action block waits, in a task: "
                   "the task waits there")
    return name, header(name, description, ["16.3", "13.3"]) + lines, \
        [f"{action}ed at 2", "back at 2"]


def files():
    out = {}
    cases = [case(k, c) for k in KINDS for c in CONTAINERS]
    cases += [waiting_case(a) for a in ("pass", "fail")]
    for name, text, expected in cases:
        out[SUITE / f"{name}.sv"] = "\n".join(text) + "\n"
        out[SUITE / f"{name}.expected"] = "\n".join(expected) + "\n"
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for path, text in files().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_assertion_wait_matrix: {path.relative_to(ROOT)} is out of date; run "
                      "tools/gen_assertion_wait_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
