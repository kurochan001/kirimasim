"""Generates the atoreal sign matrix test of TEST_SUITE.md ("Mechanism matrix")
in tests/suite/values/.

  tools/gen_atoreal_sign_matrix.py           # writes the files
  tools/gen_atoreal_sign_matrix.py --check   # exit 1 if a file differs from what it would write

The rules: VALUE_SEMANTICS.md 7.6 and 6.16.10, 6.16.15 and 5.7.2 of the
standard. atoreal reads one leading + or -, then a real constant: digits
and underscores starting with a digit, a point with such a run after it,
and an exponent with its own sign; underscores are dropped, and it gives 0
when it has read no digit, so a sign not followed at once by a digit gives
0. realtoa writes as %g, and its negative numbers read back. The axes: the
spelling of the text, and the container (a module variable, an argument of
an automatic function, a variable of an automatic task after a delay, and a
variable of a fork branch); a negative number written by realtoa; and a
parameter, which slang computes, beside the same text read at run time.

A person checks the expected output once for all the tests made from it
(TEST_SUITE.md, "Sampling by people").
"""

import argparse
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "values"
NAME = "atoreal_sign_matrix"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

SPELLINGS = ["-2.5", "+2.5", "-7_2.5", "-1e3", "+1.5E-2", "-2.5e3x", "-0.25e+1", "-.5", "- 2.5",
             "--2.5", "+-1", "-_1", "-", " -1", "-x"]
REALTOA = ["-123.25", "-0.001", "-1e20", "2.5"]
PARAMETER = "-2.5"
SYNTAX = re.compile(r"[+-]?[0-9][0-9_]*(\.[0-9][0-9_]*)?([eE][+-]?[0-9][0-9_]*)?")


def atoreal(text):
    m = SYNTAX.match(text)
    return float(m.group(0).replace("_", "")) if m else 0.0


def files():
    sv = [
        "/*",
        f":name: {NAME}",
        ":description: string atoreal reads one leading sign and then a real constant, in "
        "module, function, task and fork variables, after realtoa, and as a parameter",
        ":tags: values string",
        ":type: simulation",
        ":lrm: 1800-2023 6.16.10 6.16.15 5.7.2",
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: no",
        ":nondeterministic: no",
        f":generator: gen_atoreal_sign_matrix.py@{VERSION}",
        f":expected_stdout: @{NAME}.expected",
        "*/",
        "// Generated by tools/gen_atoreal_sign_matrix.py; change the generator, not this file.",
        "// Icarus Verilog 13.0 and 14.0 (devel) and Verilator 5.052 read the sign too, but stop at",
        "// the underscore of \"-7_2.5\" (-7) and read \"-.5\" as -0.5, and Icarus skips the space of",
        "// \" -1\"; 5.7.2 drops the underscores and needs a digit before the point (VALUE_SEMANTICS.md",
        "// 7.6). Icarus 13.0 does not accept the automatic declaration of the fork branch.",
        "`timescale 1ns/1ns",
        "module top;",
        f'  parameter string P = "{PARAMETER}";',
        "  localparam real C = P.atoreal();",
        "  string s;",
        "  real r;",
        "  function automatic void in_function(input string text);",
        '    $display("function [%s] %f", text, text.atoreal());',
        "  endfunction",
        "  task automatic in_task(input string text);",
        "    string t;",
        "    #1 t = text;",
        '    $display("task [%s] %f", t, t.atoreal());',
        "  endtask",
        "  initial begin",
    ]
    expected = []
    for text in SPELLINGS:
        sv += [f'    s = "{text}";', '    $display("module [%s] %f", s, s.atoreal());',
               "    in_function(s);", "    in_task(s);",
               "    fork", "      begin", "        automatic string f = s;",
               '        $display("fork [%s] %f", f, f.atoreal());', "      end", "    join"]
        value = atoreal(text)
        expected += [f"{where} [{text}] {value:f}" for where in ("module", "function", "task", "fork")]
    for number in REALTOA:
        sv += [f"    r = {number};", "    s.realtoa(r);",
               '    $display("realtoa [%s] %f", s, s.atoreal());']
        written = "%g" % float(number)
        expected.append(f"realtoa [{written}] {atoreal(written):f}")
    sv += ["    s = P;", '    $display("parameter [%s] %f %f", P, C, s.atoreal());',
           "  end", "endmodule", ""]
    value = atoreal(PARAMETER)
    expected.append(f"parameter [{PARAMETER}] {value:f} {value:f}")
    return {f"{NAME}.sv": "\n".join(sv), f"{NAME}.expected": "\n".join(expected) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_atoreal_sign_matrix: {path.relative_to(OUT.parent.parent.parent)} is "
                      "out of date; run tools/gen_atoreal_sign_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
