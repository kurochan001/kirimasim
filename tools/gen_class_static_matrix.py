"""Original non-parameterized class-static checks (6.21, 8.9).

Grounds: approved class-runtime contract 2 and existing typed static storage.
No external implementation, reproducer or test is used.
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / 'tests/suite/proc'
HOMES = ('unit', 'module', 'package', 'interface', 'program', 'generate', 'nested', 'anonymous')
SHAPES = {
    'bit1': ('static bit data;', 'data !== 0', 'data=1;', 'data !== 1'),
    'bit129': ('static bit[128:0] data;', "data !== '0", "data='1;", "data !== '1"),
    'logic129': ('static logic[128:0] data;', "data !== 'x", "data='z;", "data !== 'z"),
    'int32': ('static int data;', 'data !== 0', 'data=7;', 'data !== 7'),
    'integer': ('static integer data;', "data !== 'x", 'data=7;', 'data !== 7'),
    'real': ('static real data;', 'data != 0.0', 'data=1.5;', 'data != 1.5'),
    'shortreal': ('static shortreal data;', 'data != 0.0', 'data=1.5;', 'data != 1.5'),
    'string': ('static string data;', 'data != ""', 'data="kept";', 'data != "kept"'),
    'event': ('static event data;', 'data.triggered', '->data;', '!data.triggered'),
    'queue': ('static int data[$];', 'data.size()!=0', 'data.push_back(7);data.push_back(9);',
              'data.size()!=2 || data[0]!==7 || data[1]!==9'),
    'dynamic': ('static int data[];', 'data.size()!=0', 'data=new[2];data[0]=7;data[1]=9;',
                'data.size()!=2 || data[0]!==7 || data[1]!==9'),
    'fixed': ('static integer data[-1:1];', "data[-1] !== 'x || data[0] !== 'x || data[1] !== 'x",
              "data='{3,5,7};", 'data[-1]!==3 || data[0]!==5 || data[1]!==7'),
    'fixed_int': ('static int data[-1:1];', 'data[-1]!==0 || data[0]!==0 || data[1]!==0',
                  "data='{3,5,7};", 'data[-1]!==3 || data[0]!==5 || data[1]!==7'),
    'struct': ('typedef struct {logic[128:0] bits;string text;} record_t;static record_t data;',
               "data.bits !== 'x || data.text!=\"\"", "data.bits='z;data.text=\"kept\";",
               "data.bits !== 'z || data.text!=\"kept\""),
}


def emit(name, text, expected='errors=0'):
    header = f'''/*
:name: {name}
:description: Class static properties use ordinary typed static storage and initialization
:tags: proc class static initialization
:type: simulation
:lrm: 1800-2023 6.21 8.9 13.5
:oracle: spec
:spec_check: ai
:fourstate: yes
:nondeterministic: no
:generator: gen_class_static_matrix.py@1
:top_module: top
:expected_stdout: {expected}
:timeout: 15
*/
// Generated by tools/gen_class_static_matrix.py; edit the generator.
`timescale 1ns/1ns
'''
    return name, '\n'.join(line.rstrip() for line in (header + text).splitlines()) + '\n'


def wrap(home, declarations, body, prefix='', actor=''):
    if home == 'anonymous':
        return (prefix + 'program;\n' + declarations + '\nendprogram\n'
                'program automatic unit;\n' + actor + '\ninitial begin\n' + body +
                '\nend endprogram\nmodule top;unit u();endmodule\n')
    if home == 'unit':
        return prefix + declarations + '\nmodule top;\n' + actor + '\ninitial begin\n' + body + '\nend endmodule\n'
    if home == 'package':
        return (prefix + 'package definitions;\n' + declarations + '\nendpackage\n'
                'module top;import definitions::*;\n' + actor + '\ninitial begin\n' + body + '\nend endmodule\n')
    if home in ('interface', 'program'):
        kind = 'program automatic' if home == 'program' else home
        return (prefix + f'{kind} unit;\n' + declarations + '\n' + actor + '\ninitial begin\n' + body +
                f'\nend end{home}\nmodule top;unit u();endmodule\n')
    if home == 'generate':
        return prefix + 'module top;if(1)begin:g\n' + declarations + '\n' + actor + '\ninitial begin\n' + body + '\nend end endmodule\n'
    return prefix + 'module top;\n' + declarations + '\n' + actor + '\ninitial begin\n' + body + '\nend endmodule\n'


def basic(home, shape, spelling):
    declaration, before, change, after = SHAPES[shape]
    exercise = f'''automatic int errors=0;
if({before}) ++errors;
{change}
if({after}) ++errors;
$display("errors=%0d",errors);
'''
    method = f'static function void exercise();\n{exercise}endfunction\n' if spelling == 'method' else ''
    definitions = f'class Box;\n{declaration}\n{method}endclass\n'
    if spelling == 'inherited':
        definitions += 'class Child extends Box;endclass\n'
    if home == 'nested':
        definitions = 'class Holder;\n' + definitions + 'endclass\n'
    root = ('Holder::' if home == 'nested' else '') + ('Child' if spelling == 'inherited' else 'Box')
    aliases = ''
    if spelling == 'alias':
        aliases = f'typedef {root} Alias;\n'
        if home != 'anonymous':
            definitions += aliases
            aliases = ''
        root = 'Alias'
    body = root + '::exercise();' if spelling == 'method' else exercise.replace('data', root + '::data')
    return emit(f'class_static_value_{home}_{shape}_{spelling}', wrap(home, definitions, body, actor=aliases))


def discovery(home, kind):
    prefix = '''package history;
int calls=0;int trace=0;
function automatic int mark(input int value);++calls;trace=trace*10+value;return value;endfunction
endpackage
'''
    definitions = '''class First;static int first=history::mark(1);int per_object=history::mark(9);endclass
class Second;static int second=history::mark(2);endclass
'''
    aliases = ''
    if kind == 'inherited':
        definitions += 'class Child extends First;endclass\n'
    elif kind == 'alias':
        aliases = 'typedef First Alias;typedef Alias AliasAgain;\n'
        if home != 'anonymous':
            definitions += aliases
            aliases = ''
    if home == 'nested':
        definitions = 'class Holder;\n' + definitions + 'endclass\n'
    body = '$display("calls=%0d trace=%0d",history::calls,history::trace);'
    return emit(f'class_static_discovery_{home}_{kind}', wrap(home, definitions, body, prefix, actor=aliases),
                'calls=2 trace=12')


def hidden(home):
    definitions = '''class Base;
static int data=3;
static function void set_base(input int value);data=value;endfunction
endclass
class Child extends Base;static int data=5;endclass
'''
    root = ''
    if home == 'nested':
        definitions = 'class Holder;\n' + definitions + 'endclass\n'
        root = 'Holder::'
    body = f'''automatic int errors=0;
if({root}Base::data!==3 || {root}Child::data!==5) ++errors;
{root}Child::set_base(9);
if({root}Base::data!==9 || {root}Child::data!==5) ++errors;
$display("errors=%0d",errors);
'''
    return emit('class_static_hidden_' + home, wrap(home, definitions, body))


def initializer(home, kind):
    prefix = ''
    if kind == 'forward':
        declaration = 'static int first=Box::second;static int second=7;'
        expected = 'first=0 second=7'
        observation = '$display("first=%0d second=%0d",ROOT::first,ROOT::second);'
    elif kind == 'method':
        declaration = '''static int count=0;
static function int mark();++count;return count;endfunction
static int first=mark();static int second=mark();'''
        expected = 'count=2 first=1 second=2'
        observation = '$display("count=%0d first=%0d second=%0d",ROOT::count,ROOT::first,ROOT::second);'
    else:
        prefix = '''package history;
int calls=0;int trace=0;
function automatic int mark(input int value);++calls;trace=trace*10+value;return value;endfunction
endpackage
'''
        declaration = '''typedef struct {int value=1;} record_t;
static record_t data;static int second=history::mark(2);'''
        expected = 'calls=1 trace=2 value=1'
        observation = '$display("calls=%0d trace=%0d value=%0d",history::calls,history::trace,ROOT::data.value);'
    definitions = 'class Box;\n' + declaration + '\nendclass\n'
    root = 'Box'
    if home == 'nested':
        definitions = 'class Holder;\n' + definitions + 'endclass\n'
        root = 'Holder::Box'
    return emit(f'class_static_initializer_{home}_{kind}',
                wrap(home, definitions, observation.replace('ROOT', root), prefix), expected)


def combinational(home, method):
    definitions = '''class Box;
static logic[128:0] data=0;
static function logic[128:0] read();return data;endfunction
endclass
'''
    root = 'Box'
    if home == 'nested':
        definitions = 'class Holder;\n' + definitions + 'endclass\n'
        root = 'Holder::Box'
    value = root + ('::read()' if method else '::data')
    actor = f'logic[128:0] observed;always_comb observed={value};'
    body = f'''automatic int errors=0;
#1;{root}::data='1;
#1;if(observed !== '1) ++errors;
$display("errors=%0d",errors);
'''
    return emit(f'class_static_comb_{home}_{"method" if method else "direct"}',
                wrap(home, definitions, body, actor=actor))


def argument(kind, direction):
    type_name, initial, formal_before, update, actual_after = {
        'integer': ('int', 'data=5;', 'value!==5', 'value=7;', 'data!==7'),
        'wide': ('bit[128:0]', "data='1;", "value !== '1", "value='0;", "data !== '0"),
        'string': ('string', 'data="first";', 'value!="first"', 'value="second";', 'data!="second"'),
        'queue': ('int', 'data.push_back(5);', 'value.size()!=1 || value[0]!==5',
                  'value.push_back(7);' if direction == 'output' else 'value[0]=7;',
                  'data.size()!=1 || data[0]!==7'),
    }[kind]
    dims = '[$]' if kind == 'queue' else ''
    checks = f'if({formal_before}) ++errors;' if direction != 'output' else ''
    edit = '' if direction == 'const ref' else update
    if direction in ('input', 'const ref'):
        actual_after = formal_before.replace('value', 'data')
    source = f'''module top;
class Box;static {type_name} data{dims};endclass
int errors=0;
task automatic act({direction} {type_name} value{dims});
  {checks}
  {edit}
endtask
initial begin
  {initial.replace('data', 'Box::data')}
  act(Box::data);
  if({actual_after.replace('data', 'Box::data')}) ++errors;
  $display("errors=%0d",errors);
end
endmodule
'''
    return emit(f'class_static_argument_{kind}_{direction.replace(" ", "_")}', source)


def waiting(home, kind, nba):
    declaration = 'static event data;' if kind == 'event' else 'static logic[128:0] data=0;'
    write = ('->> #1 data;' if nba else '#1;->data;') if kind == 'event' else (
        "data<=#1 '1;" if nba else "#1;data='1;")
    control = '@(Box::data);' if kind == 'event' else ("wait(Box::data === '1);" if kind == 'guard' else '@(posedge Box::data);')
    definitions = f'''class Box;
{declaration}
static task send();{write}endtask
endclass
int result=0;
'''
    body = f'''fork
  begin {control} result=1;end
  Box::send();
join
$display("result=%0d",result);
'''
    return emit(f'class_static_wait_{home}_{kind}_{"nba" if nba else "active"}',
                wrap(home, definitions, body), 'result=1')


def files():
    for home in HOMES:
        for shape in SHAPES:
            for spelling in ('qualified', 'alias', 'inherited', 'method'):
                yield basic(home, shape, spelling)
        for kind in ('unused', 'inherited', 'alias'):
            yield discovery(home, kind)
        yield hidden(home)
        for kind in ('forward', 'method', 'member'):
            yield initializer(home, kind)
    for kind in ('integer', 'wide', 'string', 'queue'):
        for direction in ('input', 'output', 'inout', 'ref', 'const ref'):
            yield argument(kind, direction)
    for home in ('unit', 'module', 'package', 'program'):
        for kind in ('event', 'guard', 'edge'):
            for nba in (False, True):
                yield waiting(home, kind, nba)
    for home in ('unit', 'module', 'package', 'interface', 'generate', 'nested'):
        for method in (False, True):
            yield combinational(home, method)
    for same in (False, True):
        source = f'''module child #(int ID=1)(output int observed);
class Box;static int data=ID;endclass
initial begin Box::data+=10;observed=Box::data;end
endmodule
module top;
int first,second;
child#(1)a(first);child#({'1' if same else '2'})b(second);
initial begin #1;$display("%0d %0d",first,second);end
endmodule
'''
        yield emit(f'class_static_identity_instances_{"same" if same else "different"}',
                   source, '11 11' if same else '11 12')
    yield emit('class_static_identity_package_shared', '''package definitions;
class Box;static int data=3;endclass
endpackage
module worker #(int ID=1);
initial begin #ID;definitions::Box::data+=ID;end
endmodule
module top;worker#(1)a();worker#(2)b();
initial begin #3;$display("value=%0d",definitions::Box::data);end
endmodule
''', 'value=6')


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    bad = []
    for name, text in files():
        path = OUT / (name + '.sv')
        if args.check:
            if not path.exists() or path.read_text() != text:
                bad.append(path.name)
        else:
            path.write_text(text)
    if bad:
        print('gen_class_static_matrix: out of date: ' + ', '.join(bad), file=sys.stderr)
    return int(bool(bad))


if __name__ == '__main__':
    sys.exit(main())
