"""Generates the matrix test of the logical operators with one integral and
one real operand (TEST_SUITE.md, "Mechanism matrix") in tests/suite/values/.

  tools/gen_logical_real_matrix.py           # writes the files
  tools/gen_logical_real_matrix.py --check   # exit 1 if a file differs from what it would write

The rule: VALUE_SEMANTICS.md 3.5 and 11.4.7 of the standard. Each operand
of &&, ||, -> and <-> is taken as true, false or unknown on its own: an
integral one by its bits, a real one as true unless it is 0.0. The width
of the integral operand does not change the truth of the real one. The
axes: the operator; the width of the integral operand (1, 8, 64, 65, 100
and 129 bits: one word, and more than one); two- and four-state; its
value (zero, not zero, and for four-state one with an x and no 1); the
real operand (0.0, 1.5 and -0.0, as real and as shortreal); the side the
real is on; and the container (a module's initial, a function's return
and a static class method).

The expected output comes from the small model below. A person checks it
once for all the tests made from it (TEST_SUITE.md, "Sampling by people").
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "values"
NAME = "logical_real_matrix"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

WIDTHS = [1, 8, 64, 65, 100, 129]
# The integral value: its name, its literal for a width, its truth.
VALUES = [
    ("zero", lambda w: f"{w}'d0", "0", True),
    ("one", lambda w: f"{w}'d1", "1", True),
    ("top", lambda w: f"({w}'d1 << {w - 1})", "1", True),
    ("x", lambda w: f"{{{w}{{1'bx}}}}", "x", False),
]
# The real operand: its name, its declaration type, its literal, its truth.
REALS = [
    ("real-zero", "real", "0.0", "0"),
    ("real-set", "real", "1.5", "1"),
    ("real-negative-zero", "real", "-0.0", "0"),
    ("shortreal-zero", "shortreal", "0.0", "0"),
    ("shortreal-set", "shortreal", "1.5", "1"),
]
OPERATORS = [("and", "&&"), ("or", "||"), ("implies", "->"), ("equivalent", "<->")]
CONTAINERS = ["initial", "function", "method"]


def lnot(a):
    return "x" if a == "x" else "1" if a == "0" else "0"


def land(a, b):
    return "0" if "0" in (a, b) else "x" if "x" in (a, b) else "1"


def lor(a, b):
    return "1" if "1" in (a, b) else "x" if "x" in (a, b) else "0"


def apply(op, a, b):
    if op == "and":
        return land(a, b)
    if op == "or":
        return lor(a, b)
    if op == "implies":
        return lor(lnot(a), b)
    return lor(land(a, b), land(lnot(a), lnot(b)))


def files():
    sv = [
        "/*",
        f":name: {NAME}",
        ":description: &&, ||, -> and <-> take a real operand as true unless it is 0.0, "
        "whatever the width of the integral operand on the other side",
        ":tags: values",
        ":type: simulation",
        ":lrm: 1800-2023 11.4.7 11.3.1",
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: yes",
        ":nondeterministic: no",
        f":generator: gen_logical_real_matrix.py@{VERSION}",
        f":expected_stdout: @{NAME}.expected",
        "*/",
        "// Generated by tools/gen_logical_real_matrix.py; change the generator, not this file.",
        "module top;",
    ]
    decls, functions, expected = [], [], []
    body = {c: [] for c in CONTAINERS}
    for name, kind, literal, _ in REALS:
        decls.append(f"  {kind} {name.replace('-', '_')} = {literal};")
    k = 0
    for w in WIDTHS:
        for state in ("bit", "logic"):
            for vname, literal, vtruth, two_state_ok in VALUES:
                if state == "bit" and not two_state_ok:
                    continue
                var = f"{state}_{w}_{vname}"
                decls.append(f"  {state} [{w - 1}:0] {var} = {literal(w)};")
                for rname, _, _, rtruth in REALS:
                    real = rname.replace("-", "_")
                    for oname, op in OPERATORS:
                        for side in ("left", "right"):
                            expr = f"{real} {op} {var}" if side == "left" else f"{var} {op} {real}"
                            a, b = (rtruth, vtruth) if side == "left" else (vtruth, rtruth)
                            want = apply(oname, a, b)
                            label = f"{state}{w} {vname} {rname} {oname} real-{side}"
                            for c in CONTAINERS:
                                show = f'$display("{c} {label} %b", r);'
                                if c == "function":
                                    functions += [f"  function automatic logic fn{k}();",
                                                  f"    return {expr};", "  endfunction"]
                                    body[c].append(f"    r = fn{k}(); {show}")
                                else:
                                    body[c].append(f"    r = {expr}; {show}")
                                expected.append(f"{c} {label} {want}")
                            k += 1
    expected.sort(key=lambda line: CONTAINERS.index(line.split(" ", 1)[0]))
    sv += decls + ["  logic r;"] + functions
    sv += ["  class K;", "    static function void run();"]
    sv += ["  " + line for line in body["method"]]
    sv += ["    endfunction", "  endclass"]
    sv += ["  initial begin"] + body["initial"] + body["function"] + ["    K::run();", "  end",
                                                                     "endmodule", ""]
    # The method container prints last: the order of the calls above.
    order = {"initial": 0, "function": 1, "method": 2}
    expected.sort(key=lambda line: order[line.split(" ", 1)[0]])
    return {f"{NAME}.sv": "\n".join(sv), f"{NAME}.expected": "\n".join(expected) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_logical_real_matrix: {path.relative_to(OUT.parent.parent.parent)} is "
                      "out of date; run tools/gen_logical_real_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
