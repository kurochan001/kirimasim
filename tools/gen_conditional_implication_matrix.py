"""Generates the matrix tests of the precedence of the conditional
operator against the implication operators (TEST_SUITE.md, "Mechanism
matrix") in tests/suite/values/.

  tools/gen_conditional_implication_matrix.py           # writes the files
  tools/gen_conditional_implication_matrix.py --check   # exit 1 if a file differs from what it would write

The rule: 11.3.2 of the standard, Table 11-2. The conditional operator
?: binds tighter than the implication -> and the equivalence <->, which
have the lowest precedence of all and group from the right; || binds
tighter than ?:. So a ? b : c -> d is (a ? b : c) -> d, and a -> b ? c : d
is a -> (b ? c : d). The operand between ? and : is a whole expression,
so a ? b -> c : d is a ? (b -> c) : d. For 1-bit operands, x -> y is
!x || y and x <-> y is x == y (11.4.7).

The axes: the form (the eight below, each beside the grouping the rule
gives, written with parentheses in the generator only), the operand
values (all 16 of four bits), and the place of the expression (the
right side of a procedural assignment, a continuous assignment, the
return value of a function, a localparam of a generate loop, which
slang evaluates as a constant, and the condition of an if statement).

The expected output is computed here from the groupings, without
reading kirimasim's code. A person checks it once for all the tests
made from it (TEST_SUITE.md, "Sampling by people").
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "values"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1


def imp(x, y):
    return int((not x) or y)


def eqv(x, y):
    return int(x == y)


def cond(x, y, z):
    return y if x else z


# (the expression as written, its value from the grouping of 11.3.2).
FORMS = [
    ("a ? b : c -> d", lambda a, b, c, d: imp(cond(a, b, c), d)),
    ("a ? b : c <-> d", lambda a, b, c, d: eqv(cond(a, b, c), d)),
    ("a -> b ? c : d", lambda a, b, c, d: imp(a, cond(b, c, d))),
    ("a <-> b ? c : d", lambda a, b, c, d: eqv(a, cond(b, c, d))),
    ("a ? b -> c : d", lambda a, b, c, d: cond(a, imp(b, c), d)),
    ("a ? b : c ? d : a -> b", lambda a, b, c, d: imp(cond(a, b, cond(c, d, a)), b)),
    ("a -> b <-> c", lambda a, b, c, d: imp(a, eqv(b, c))),
    ("a || b ? c : d -> a", lambda a, b, c, d: imp(cond(int(a or b), c, d), a)),
]
PLACES = ["procedural", "continuous", "function", "constant", "condition"]


def bits(i):
    return (i >> 3) & 1, (i >> 2) & 1, (i >> 1) & 1, i & 1


def test(place):
    name = f"conditional_implication_{place}"
    where = {"procedural": "the right side of a procedural assignment",
             "continuous": "a continuous assignment", "function": "the return value of a function",
             "constant": "a localparam of a generate loop", "condition": "the condition of an if"}[place]
    sv = ["/*", f":name: {name}",
          ":description: the conditional operator binds tighter than -> and <->, which group from "
          f"the right, for eight forms and all values of four bits, in {where}",
          ":tags: values", ":type: simulation", ":lrm: 1800-2023 11.3.2 11.4.7 11.4.11",
          ":oracle: spec", ":spec_check: ai", ":fourstate: no", ":nondeterministic: no",
          f":generator: gen_conditional_implication_matrix.py@{VERSION}", ":top_module: top",
          ":issue: 54", f":expected_stdout: @{name}.expected", "*/",
          "// Generated by tools/gen_conditional_implication_matrix.py; change the generator, not "
          "this file.", "`timescale 1ns/1ns"]
    n = len(FORMS)
    fmt = "%0d: " + " ".join(["%b"] * n)
    results = ", ".join(f"r{k}" for k in range(n))
    if place == "continuous":
        sv += ["module eval_m (input bit a, b, c, d, " +
               ", ".join(f"output wire r{k}" for k in range(n)) + ");"]
        sv += [f"  assign r{k} = {form};" for k, (form, _) in enumerate(FORMS)]
        sv += ["endmodule", "module top;", "  bit a, b, c, d;",
               f"  wire {results};",
               f"  eval_m u (.a(a), .b(b), .c(c), .d(d), " +
               ", ".join(f".r{k}(r{k})" for k in range(n)) + ");",
               "  initial begin",
               "    for (int i = 0; i < 16; i++) begin",
               "      {a, b, c, d} = 4'(i);",
               "      #1;",
               f'      $display("{fmt}", i, {results});',
               "    end", "  end", "endmodule"]
    elif place == "constant":
        sv += ["module top;", "  for (genvar i = 0; i < 16; i++) begin : g",
               "    localparam bit a = (i >> 3) & 1, b = (i >> 2) & 1, c = (i >> 1) & 1, d = i & 1;"]
        sv += [f"    localparam bit r{k} = {form};" for k, (form, _) in enumerate(FORMS)]
        sv += [f'    initial #(i) $display("{fmt}", i, {results});', "  end", "endmodule"]
    else:
        sv += ["module top;", "  bit a, b, c, d;", f"  bit {results};"]
        if place == "function":
            for k, (form, _) in enumerate(FORMS):
                sv.append(f"  function automatic bit f{k}(bit a, bit b, bit c, bit d); "
                          f"return {form}; endfunction")
        sv += ["  initial begin", "    for (int i = 0; i < 16; i++) begin",
               "      {a, b, c, d} = 4'(i);"]
        for k, (form, _) in enumerate(FORMS):
            if place == "procedural":
                sv.append(f"      r{k} = {form};")
            elif place == "function":
                sv.append(f"      r{k} = f{k}(a, b, c, d);")
            else:
                sv.append(f"      if ({form}) r{k} = 1; else r{k} = 0;")
        sv += [f'      $display("{fmt}", i, {results});', "      #1;", "    end", "  end",
               "endmodule"]
    expected = [f"{i}: " + " ".join(str(value(*bits(i))) for _, value in FORMS)
                for i in range(16)]
    return name, sv, expected


def files():
    out = {}
    for place in PLACES:
        name, sv, expected = test(place)
        out[f"{name}.sv"] = "\n".join(sv) + "\n"
        out[f"{name}.expected"] = "\n".join(expected) + "\n"
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print("gen_conditional_implication_matrix: "
                      f"{path.relative_to(OUT.parent.parent.parent)} is out of date; run "
                      "tools/gen_conditional_implication_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
