"""Generates the matrix tests of zero bytes read from a file into a string
(TEST_SUITE.md, "Mechanism matrix") in tests/suite/proc/.

  tools/gen_string_read_nul_matrix.py           # writes the files
  tools/gen_string_read_nul_matrix.py --check   # exit 1 if a file differs from what it would write

The rule: 6.16 of the standard and VALUE_SEMANTICS.md 7.6. A string
variable holds no zero byte. Characters read from a file into a string,
by $fgets and by %s of $fscanf, leave the zero bytes out, as a
conversion from an integer does; the count that $fgets returns is the
number of characters it read from the file (21.3.4.2). A packed target
keeps every byte (SYSTEM_TASKS.md 6.3).

The axes: the task ($fgets, $fscanf with %s), the target (a string
variable, an element of a queue of strings, a string property of a class
object; and a packed vector, which keeps the zero bytes), and the
container of the calls (an initial procedure, a task, a function).

The file holds A, a zero byte, B, two zero bytes, C and a newline. The
expected output is written from the rule above, without reading
kirimasim's code. A person checks it once for all the tests made from it
(TEST_SUITE.md, "Sampling by people").
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "proc"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

CONTAINERS = ["initial", "task", "function"]
# (key, the target).
TARGETS = [("variable", "s"), ("queue", "q[1]"), ("property", "o.t")]


def test(container):
    name = f"string_read_nul_{container}"
    sv = ["/*", f":name: {name}",
          ":description: $fgets and %s of $fscanf leave the zero bytes of a file out of a string "
          f"and keep them in a packed vector, called from {'an' if container == 'initial' else 'a'} "
          f"{container}",
          ":tags: proc", ":type: simulation", ":lrm: 1800-2023 6.16 21.3.4.2 21.3.4.3",
          ":oracle: spec", ":spec_check: ai", ":fourstate: yes", ":nondeterministic: no",
          f":generator: gen_string_read_nul_matrix.py@{VERSION}", ":top_module: top",
          f":expected_stdout: @{name}.expected", "*/",
          "// Generated by tools/gen_string_read_nul_matrix.py; change the generator, not this "
          "file.", "`timescale 1ns/1ns", "module top;",
          "  class item;", "    string t;", "  endclass",
          "  integer fd, r;", "  string s;", '  string q [$] = \'{"", ""};', "  item o = new;",
          "  logic [8*7:1] v;",
          # The bytes of a string, in decimal.
          "  function automatic string bytes(string x);",
          '    string out = "";',
          '    for (int i = 0; i < x.len(); i++) out = {out, $sformatf(" %0d", x[i])};',
          "    return out;", "  endfunction"]
    body, expected = [], []
    for key, target in TARGETS:
        body += ["r = $rewind(fd);", f"r = $fgets({target}, fd);",
                 f'$display("fgets {key}: r=%0d len=%0d bytes=%s", r, {target}.len(), '
                 f"bytes({target}));"]
        expected.append(f"fgets {key}: r=7 len=4 bytes= 65 66 67 10")
        body += ["r = $rewind(fd);", f'r = $fscanf(fd, "%s", {target});',
                 f'$display("fscanf {key}: r=%0d len=%0d bytes=%s", r, {target}.len(), '
                 f"bytes({target}));"]
        expected.append(f"fscanf {key}: r=1 len=3 bytes= 65 66 67")
    body += ["r = $rewind(fd);", "r = $fgets(v, fd);",
             '$display("fgets vector: r=%0d %h", r, v);']
    expected.append("fgets vector: r=7 4100420000430a")
    if container == "task":
        sv += ["  task read;"] + ["    " + b for b in body] + ["  endtask"]
        call = "read;"
    elif container == "function":
        sv += ["  function void read();"] + ["    " + b for b in body] + ["  endfunction"]
        call = "read();"
    sv += ["  initial begin",
           '    fd = $fopen("nul.dat", "w");',
           '    $fwrite(fd, "A%cB%c%cC\\n", 8\'d0, 8\'d0, 8\'d0);',
           "    $fclose(fd);",
           '    fd = $fopen("nul.dat", "r");']
    sv += ["    " + b for b in body] if container == "initial" else [f"    {call}"]
    sv += ["    $fclose(fd);", "  end", "endmodule"]
    return name, sv, expected


def files():
    out = {}
    for container in CONTAINERS:
        name, sv, expected = test(container)
        out[f"{name}.sv"] = "\n".join(sv) + "\n"
        out[f"{name}.expected"] = "\n".join(expected) + "\n"
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_string_read_nul_matrix: {path.relative_to(OUT.parent.parent.parent)} "
                      "is out of date; run tools/gen_string_read_nul_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
