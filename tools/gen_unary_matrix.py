#!/usr/bin/env python3
"""Generates the matrix test of the context-determined unary operators of
TEST_SUITE.md ("Mechanism matrix") in tests/suite/values/.

  tools/gen_unary_matrix.py           # writes the files
  tools/gen_unary_matrix.py --check   # exit 1 if a file differs from what it would write

Unary +, - and ~ take the width of their context: the operand is first
extended to the wider of its own width and the result's, by its own
signedness (11.6.1, 11.8.2), then the operator is applied. + and - are
arithmetic: x or z in any bit makes every bit x (11.4.3,
VALUE_SEMANTICS.md 3.2); ~ inverts each bit, x and z giving x (3.6).

The axes: the operator; the operand (4 bits unsigned, 4 bits signed, 70
bits unsigned) and its value (known, with an x, with a z); the width of
the result (2, 4 and 8 bits, and 72 for the wide operand); a variable or
a literal as the operand (kirimasim computes a literal's +, which slang
folds otherwise, SIR_SPEC.md 6); a module variable or an automatic one
as the result.

The expected outputs follow from the rules above, computed below. A
person checks them once for all the tests made from them (TEST_SUITE.md,
"Sampling by people").
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "values"
NAME = "unary_matrix"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

OPS = ["+", "-", "~"]
# (name, the type, width, signed, values as bits, most significant first,
# the result widths)
OPERANDS = [
    ("u4", "logic [3:0]", 4, False, ["0110", "1x01", "10z1"], [2, 4, 8]),
    ("s4", "logic signed [3:0]", 4, True, ["1010", "x011", "1z00"], [2, 4, 8]),
    ("u70", "logic [69:0]", 70, False,
     ["1" + "0" * 34 + "1" * 35, "x" + "0" * 69, "0" * 69 + "z"], [8, 72]),
]


def extend(bits, width, signed):
    fill = bits[0] if signed else "0"
    return fill * (width - len(bits)) + bits


def apply(op, bits, width):
    """op on bits already extended to width."""
    if op == "~":
        return "".join({"0": "1", "1": "0"}.get(c, "x") for c in bits)
    if any(c in "xz" for c in bits):
        return "x" * width
    if op == "+":
        return bits
    return format((-int(bits, 2)) % (1 << width), f"0{width}b")


def result(op, bits, wo, signed, wr):
    w = max(wo, wr)
    return apply(op, extend(bits, w, signed), w)[-wr:]


def literal(bits, signed):
    return f"{len(bits)}'{'s' if signed else ''}b{bits}"


def files():
    decl, body, auto_decl, auto_body, exp, auto_exp = [], [], [], [], [], []
    widths = sorted({w for *_, ws in OPERANDS for w in ws})
    decl += [f"  logic [{w - 1}:0] y{w};" for w in widths]
    auto_decl += [f"    logic [{w - 1}:0] ay{w};" for w in widths]
    for name, typ, wo, signed, values, results in OPERANDS:
        decl.append(f"  {typ} {name};")
        for vi, bits in enumerate(values):
            for op in OPS:
                for wr in results:
                    expect = result(op, bits, wo, signed, wr)
                    for form in ("variable", "literal"):
                        operand = name if form == "variable" else literal(bits, signed)
                        tag = f"{name} v{vi} {op} {wr} {form}"
                        set_ = f"{name} = {literal(bits, signed)}; " if form == "variable" else ""
                        body.append(f"{set_}y{wr} = {op}{operand}; "
                                    f'$display("module {tag} %b", y{wr});')
                        exp.append(f"module {tag} {expect}")
                        auto_body.append(f"{set_}ay{wr} = {op}{operand}; "
                                         f'$display("automatic {tag} %b", ay{wr});')
                        auto_exp.append(f"automatic {tag} {expect}")
    head = [
        "/*",
        f":name: {NAME}",
        ":description: unary +, - and ~ in a wider, equal or narrower context: the operand "
        "extended by its own signedness, + and - all x when any bit is x or z, ~ bit by bit, "
        "for unsigned, signed and wide operands, variables and literals, module and automatic "
        "results",
        ":tags: values operators",
        ":type: simulation",
        ":lrm: 1800-2023 11.4.3 11.4.8 11.6.1 11.8.2",
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: yes",
        ":nondeterministic: no",
        f":generator: gen_unary_matrix.py@{VERSION}",
        ":top_module: top",
        f":expected_stdout: @{NAME}.expected",
        "*/",
        "// Generated by tools/gen_unary_matrix.py; change the generator, not this file.",
        "`timescale 1ns/1ns",
        "module top;",
    ]
    task = ["  task automatic t;"] + auto_decl + ["    " + s for s in auto_body] + ["  endtask"]
    sv = (head + decl + task + ["  initial begin"] + ["    " + s for s in body]
          + ["    t();", "  end", "endmodule", ""])
    return {f"{NAME}.sv": "\n".join(sv), f"{NAME}.expected": "\n".join(exp + auto_exp) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_unary_matrix: {path.relative_to(OUT.parent.parent.parent)} is out "
                      "of date; run tools/gen_unary_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
