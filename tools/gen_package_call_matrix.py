#!/usr/bin/env python3
"""Generates the matrix test of package members used from the places of a
module of TEST_SUITE.md ("機構の行列") in tests/suite/hier/.

  tools/gen_package_call_matrix.py           # writes the files
  tools/gen_package_call_matrix.py --check   # exit 1 if a file differs from what it would write

A package's functions, tasks and variables are reached by name from any
module (26.3). Its variables, and those of its static subroutines, are
one per design (SIR_SPEC.md 3.3, 7.1), made the first time a module uses
the package, which may be while that module's processes are being made.
So besides the matrix, one small design per place uses a package that
has no variables for the first time at that place, with other processes
made after it.

The axes: the member (a function, a task with an output argument, a
variable, a function that reads the variable); the place (an initial
procedure, always_comb, always_ff, always @*, a continuous assignment, a
net declaration assignment, a variable's initial value, a function of
the module, a final procedure, a generate block, an instance of another
module, and a port connection of that instance). Each place reads its
own input and writes its own output; the driver sets the inputs, makes a
clock edge, and prints the outputs.

The expected outputs follow from the rules above, computed below. A
person checks them once for all the tests made from them (TEST_SUITE.md,
"人の抜き取り").
"""

from __future__ import annotations

import argparse
import random
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "hier"
NAME = "package_call_matrix"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

VAR = 0x21  # the package variable, set by the driver before the steps
# (name, the value with {x}, a statement with {x} and {y} for a task; the
# result for x)
MEMBERS = [
    ("func", "pk::g({x})", lambda x: x ^ 0x5A),
    ("task", "pk::t({x}, {y});", lambda x: (x + 3) & 0xFF),
    ("var", "{x} ^ pv::v", lambda x: x ^ VAR),
    ("reader", "pv::r({x})", lambda x: (x + VAR) & 0xFF),
]
# Places that run again when the inputs change; the rest are listed below.
PLACES = ["comb", "ff", "star", "cont", "netdecl", "modfunc", "gen", "sub", "port"]


# A package with no variables: its row is made at its first use.
PACKAGE = [
    "package pk;",
    "  function logic [7:0] g(logic [7:0] x);",
    "    return x ^ 8'h5a;",
    "  endfunction",
    "  task t(input logic [7:0] x, output logic [7:0] y);",
    "    y = x + 8'h03;",
    "  endtask",
    "endpackage",
    "",
]
CHILD = ["module child(input logic [7:0] i, output logic [7:0] o);",
         "  always_comb o = {e};", "endmodule", ""]
# (place, module items that set y; y for a = 8'h07 at time 1, or None when
# set from a = 8'h03 at time 0, and what else is printed)
FIRST = [
    ("initial", ["  initial y = pk::g(a);"], 0x03 ^ 0x5A, []),
    ("comb", ["  always_comb y = pk::g(a);"], 0x07 ^ 0x5A, []),
    ("ff", ["  always_ff @(posedge clk) y <= pk::g(a);"], 0x07 ^ 0x5A, []),
    ("star", ["  always @* y = pk::g(a);"], 0x07 ^ 0x5A, []),
    ("cont", ["  assign y = pk::g(a);"], 0x07 ^ 0x5A, []),
    ("netdecl", ["  wire [7:0] n = pk::g(a);", "  assign y = n;"], 0x07 ^ 0x5A, []),
    ("init", ["  logic [7:0] y0 = pk::g(8'h03);", "  initial y = y0;"], 0x03 ^ 0x5A, []),
    ("modfunc", ["  function automatic logic [7:0] m(logic [7:0] x);", "    return pk::g(x);",
                 "  endfunction", "  always_comb y = m(a);"], 0x07 ^ 0x5A, []),
    ("task", ["  always_comb pk::t(a, y);"], 0x07 + 3, []),
    ("gen", ["  if (1) begin : gb", "    always_comb y = pk::g(a);", "  end"], 0x07 ^ 0x5A, []),
    ("final", ["  initial y = 8'h00;", "  final $display(\"final %h\", pk::g(8'h20));"], 0,
     ["final 7a"]),
    ("sub", ["  child c(a, y);"], 0x07 ^ 0x5A, []),
    ("port", ["  child c(pk::g(a), y);"], (0x07 ^ 0x5A) + 1, []),
]


def first_use(place, items, y, after):
    """A design whose package is used for the first time at the place."""
    child = []
    if place in ("sub", "port"):
        child = [line.format(e="pk::g(i)" if place == "sub" else "i + 8'h01")
                 for line in CHILD]
    name = f"package_first_{place}"
    head = [
        "/*",
        f":name: {name}",
        f":description: a package with no variables used for the first time in {place}, "
        "with other processes made after it",
        ":tags: hier package",
        ":type: simulation",
        ":lrm: 1800-2023 26.3",
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: yes",
        ":nondeterministic: no",
        f":generator: gen_package_call_matrix.py@{VERSION}",
        ":top_module: top",
        f":expected_stdout: @{name}.expected",
        "*/",
        "// Generated by tools/gen_package_call_matrix.py; change the generator, not this file.",
        "`timescale 1ns/1ns",
    ]
    sv = head + PACKAGE + child + [
        "module top;",
        "  logic clk = 1'b0;",
        "  logic [7:0] a = 8'h03, y, z1, z2;",
        *items,
        "  always_comb z1 = a + 8'h01;",
        "  always_comb z2 = a + 8'h02;",
        "  initial begin",
        "    #1 a = 8'h07;",
        "    clk = 1'b1;",
        '    #1 $display("%h %h %h", y, z1, z2);',
        "  end",
        "endmodule",
        "",
    ]
    exp = [f"{y:02x} 08 09", *after]
    return {f"{name}.sv": "\n".join(sv), f"{name}.expected": "\n".join(exp) + "\n"}


def stmt(member, form, x, y):
    """A statement that sets y from x."""
    if member == "task":
        return form.format(x=x, y=y)
    return f"{y} = {form.format(x=x)};"


def files():
    rng = random.Random(3 * 4099)
    decl, items, sub_items, exp = [], [], [], []
    rows = []  # (input, output as printed, member, place)
    funcs = {name: fn for name, _, fn in MEMBERS}
    for member, form, _ in MEMBERS:
        task = member == "task"
        for place in PLACES:
            x, y = f"a_{place}_{member}", f"y_{place}_{member}"
            # a function may not call a task (13.4)
            if place in ("cont", "netdecl", "port", "modfunc") and task:
                continue
            if place == "comb":
                items.append(f"  always_comb {stmt(member, form, x, y)}")
            elif place == "ff":
                if task:
                    items.append(f"  always_ff @(posedge clk) begin {form.format(x=x, y=y + '_t')} "
                                 f"{y} <= {y}_t; end")
                else:
                    items.append(f"  always_ff @(posedge clk) {y} <= {form.format(x=x)};")
            elif place == "star":
                items.append(f"  always @* {stmt(member, form, x, y)}")
            elif place == "cont":
                items.append(f"  assign {y} = {form.format(x=x)};")
            elif place == "netdecl":
                items.append(f"  wire [7:0] {y}_n = {form.format(x=x)};")
            elif place == "modfunc":
                body = f"    y = {form.format(x='x')};"
                items.append(f"  function automatic logic [7:0] m_{member}(logic [7:0] x);\n"
                             f"    logic [7:0] y;\n{body}\n    return y;\n  endfunction")
                items.append(f"  always_comb {y} = m_{member}({x});")
            elif place == "gen":
                items.append(f"  if (1) begin : g_{member}\n    always_comb "
                             f"{stmt(member, form, x, y)}\n  end")
            elif place == "sub":
                sub_items.append(f"  always_comb {stmt(member, form, f'i_{member}', f'o_{member}')}")
            shown = {"netdecl": f"{y}_n", "sub": f"s.o_{member}", "port": f"s.p_{member}"}.get(
                place, y)
            if place not in ("netdecl", "sub", "port"):
                decl.append(f"  logic [7:0] {y}{', ' + y + '_t' if place == 'ff' and task else ''};")
            decl.append(f"  logic [7:0] {x};")
            rows.append((x, shown, member, place))
    ports = []
    for member, form, _ in MEMBERS:
        ports.append(f".i_{member}(a_sub_{member})")
        if member != "task":
            ports.append(f".p_{member}({form.format(x=f'a_port_{member}')})")
    sub = ["module child("]
    port_decls = []
    for member, _, _ in MEMBERS:
        port_decls.append(f"  input logic [7:0] i_{member}")
        if member != "task":
            port_decls.append(f"  input logic [7:0] p_{member}")
    sub.append(",\n".join(port_decls))
    sub.append(");")
    sub += [f"  logic [7:0] o_{member};" for member, _, _ in MEMBERS]
    sub += sub_items
    sub.append("endmodule")
    lines = [f"    pv::v = 8'h{VAR:02x};"]
    for step in range(3):
        vals = {x: rng.getrandbits(8) for x, _, _, _ in rows}
        lines.append("    #10 " + " ".join(f"{x} = 8'h{v:02x};" for x, v in vals.items()))
        lines.append("    #2 clk = 1'b1;")
        lines.append("    #2 clk = 1'b0;")
        for x, shown, member, place in rows:
            lines.append(f'    $display("{step} {member} {place} %h", {shown});')
            exp.append(f"{step} {member} {place} {funcs[member](vals[x]):02x}")
    # The initial value, read once; the driver's own calls; and a final
    # procedure.
    lines += [
        '    $display("init func %h", iv);',
        "    pk::t(8'h10, tr);",
        '    $display("initial task %h", tr);',
        '    $display("initial func %h", pk::g(8\'h10));',
    ]
    exp += ["init func 5b", "initial task 13", "initial func 4a"]
    finals = ['  final $display("final func %h", pk::g(8\'h20));']
    exp.append("final func 7a")
    head = [
        "/*",
        f":name: {NAME}",
        ":description: a package's function, task and variable, and a function that reads the "
        "variable, used from initial, always_comb, always_ff, always @*, a continuous "
        "assignment, a net declaration assignment, an initial value, a module function, a "
        "final procedure, a generate block, an instance and its port connection",
        ":tags: hier package",
        ":type: simulation",
        ":lrm: 1800-2023 6.8 9.2 10.3 13.4 23.3.2 26.3",
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: yes",
        ":nondeterministic: no",
        f":generator: gen_package_call_matrix.py@{VERSION}",
        ":top_module: top",
        f":expected_stdout: @{NAME}.expected",
        "*/",
        "// Generated by tools/gen_package_call_matrix.py; change the generator, not this file.",
        "`timescale 1ns/1ns",
    ] + PACKAGE + [
        "package pv;",
        "  logic [7:0] v;",
        "  function logic [7:0] r(logic [7:0] x);",
        "    return x + v;",
        "  endfunction",
        "endpackage",
        "",
    ]
    top = ["module top;", "  logic clk = 1'b0;", "  logic [7:0] tr;",
           "  logic [7:0] iv = pk::g(8'h01);"]
    sv = (head + sub + ["", *top] + decl + items + finals
          + ["  child s(" + ", ".join(ports) + ");", "  initial begin"] + lines
          + ["    $finish;", "  end", "endmodule", ""])
    out = {f"{NAME}.sv": "\n".join(sv), f"{NAME}.expected": "\n".join(exp) + "\n"}
    for place, place_items, y, after in FIRST:
        out.update(first_use(place, place_items, y, after))
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_package_call_matrix: {path.relative_to(OUT.parent.parent.parent)} "
                      "is out of date; run tools/gen_package_call_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
