import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests/suite/sched"


def emit(name, body, expected="errors=0", program=False):
    wrapper = (f"program automatic unit;\n{body}endprogram\nmodule top;unit u();endmodule\n"
               if program else f"module top;\n{body}endmodule\n")
    content = f'''/*
:name: {name}
:description: Input events share object identity through typed call storage
:tags: sched event input copy
:type: simulation
:lrm: 1800-2023 6.21 13.5 15.5
:oracle: spec
:spec_check: ai
:fourstate: no
:nondeterministic: no
:generator: gen_event_input_matrix.py@1
:top_module: top
:expected_stdout: {expected}
:timeout: 10
*/
// Generated by tools/gen_event_input_matrix.py; edit the generator.
`timescale 1ns/1ns
''' + wrapper
    return name, "\n".join(line.rstrip() for line in content.splitlines()) + "\n"


def scalars(program, lifetime, kind, actual):
    decl, target, value, after = {
        "slot": ("event root;", "root", "root", "0"),
        "frame": ("automatic event root;", "root", "root", "0"),
        "slot_select": ("event root[-1:1];", "root[0]", "root[index++]", "1"),
        "frame_select": ("automatic event root[-1:1];", "root[0]", "root[index++]", "1"),
        "hierarchical": ("", "pool.root", "pool.root", "0"),
        "constant_select": ("event root[-1:1];", "root[1]", "root[1]", "0"),
    }[actual]
    global_decl = "if(1) begin:pool event root;end\n" if actual == "hierarchical" else ""
    # The hierarchical source above is a module generate scope.
    if program and actual == "hierarchical":
        return None
    local = decl if actual.startswith("frame") else ""
    if not local:
        global_decl += decl + "\n"
    begin = "function" if kind == "function" else "task"
    returns = "void " if kind == "function" else ""
    body = f'''{global_decl}int errors=0;
{begin} {lifetime} {returns}leaf(input event value);
  if (!value.triggered) ++errors;
  -> value;
end{begin}
{begin} {lifetime} {returns}relay(input event value);
  leaf(value);
end{begin}
initial begin
  {local}
  int index=0;
  -> {target};
  relay({value});
  if (!{target}.triggered || index!={after}) ++errors;
  $display("errors=%0d",errors);
end
'''
    return emit(f"event_input_scalar_{'program' if program else 'module'}_{lifetime}_{kind}_{actual}",
                body, program=program)


def arrays(lifetime, kind, frame, rank):
    dimensions, formal, selected, loop, all_values = {
        "ascending": ("[-1:1]", "[3:1]", "value[i]", "for(int i=3;i>=1;--i)",
                      "root[-1].triggered && root[0].triggered && root[1].triggered"),
        "descending": ("[3:1]", "[-1:1]", "value[i]", "for(int i=-1;i<=1;++i)",
                       "root[3].triggered && root[2].triggered && root[1].triggered"),
        "rank2": ("[-1:0][3:2]", "[3:2][-1:0]", "value[i][j]",
                  "for(int i=3;i>=2;--i) for(int j=-1;j<=0;++j)",
                  "root[-1][3].triggered && root[-1][2].triggered && root[0][3].triggered && root[0][2].triggered"),
    }[rank]
    begin = "function" if kind == "function" else "task"
    ret = "void " if kind == "function" else ""
    decl = f"{'automatic ' if frame else ''}event root{dimensions};"
    body = f'''{'' if frame else decl}
int errors=0;
{begin} {lifetime} {ret}send(input event value{formal});
  {'#1;' if kind == 'waiting_task' else ''}
  {loop} begin
    if ({selected}.triggered) ++errors;
    -> {selected};
  end
end{begin}
initial begin
  {decl if frame else ''}
  send(root);
  if (!({all_values})) ++errors;
  $display("errors=%0d",errors);
end
'''
    return emit(f"event_input_array_{lifetime}_{kind}_{'frame' if frame else 'slot'}_{rank}", body)


def waiting(program, wait, delayed):
    waiting = {"named": "@(value);", "mixed": "@(value or posedge dummy);",
               "triggered": "wait(value.triggered);"}[wait]
    trigger = "->> #1 value;" if delayed else "#1;-> value;"
    body = f'''int result=0;bit dummy=0;
task automatic send(input event value); {trigger} endtask
task automatic receive(input event value);
  {waiting}
  if (value.triggered) ++result;
endtask
task automatic spawn();
  event value;
  fork send(value);receive(value);join_none
endtask
initial begin
  spawn();
  wait fork;
  $display("result=%0d",result);
end
'''
    return emit(f"event_input_wait_{'program' if program else 'module'}_{wait}_{'nba' if delayed else 'active'}",
                body, "result=1", program)


def special(name, body, expected="errors=0"):
    return emit("event_input_" + name, body, expected)


def files():
    for program in (False, True):
        for lifetime in ("automatic", "static"):
            for kind in ("function", "task"):
                for actual in ("slot", "frame", "slot_select", "frame_select", "hierarchical", "constant_select"):
                    item = scalars(program, lifetime, kind, actual)
                    if item:
                        yield item
    for lifetime in ("automatic", "static"):
        for kind in ("function", "task", "waiting_task"):
            for frame in (False, True):
                for rank in ("ascending", "descending", "rank2"):
                    yield arrays(lifetime, kind, frame, rank)
    for program in (False, True):
        for wait in ("named", "mixed", "triggered"):
            for delayed in (False, True):
                yield waiting(program, wait, delayed)
    yield special("null", '''int errors=0;
function automatic void send(input event value=null);
  -> value; ->> value;
  if(value.triggered) ++errors;
endfunction
initial begin send(null);send();#1;$display("errors=%0d",errors);end
''')
    yield special("recursive_gc", '''int errors=0;
function automatic void descend(input event value,input int depth);
  event scratch;
  if(depth>0) descend(value,depth-1);
  if(!value.triggered) ++errors;
  ->value;
endfunction
initial begin
  automatic event root;
  ->root;
  for(int round=0;round<64;++round) descend(root,8);
  if(!root.triggered) ++errors;
  $display("errors=%0d",errors);
end
''')
    for frame in (False, True):
        for suspends in (False, True):
            decl = f"{'automatic ' if frame else ''}event root[-1:1][3:2];"
            yield special(f"slice_{'frame' if frame else 'slot'}_{'waiting' if suspends else 'sync'}", f'''
{'' if frame else decl}
task automatic send(input event value[0:1]);
  {'#1;' if suspends else ''}
  -> value[0];
  -> value[1];
endtask
initial begin
  {decl if frame else ''}
  int index=0;
  int errors=0;
  send(root[index++]);
  if(index!=1 || !root[0][3].triggered || !root[0][2].triggered) ++errors;
  if(root[-1][3].triggered || root[-1][2].triggered || root[1][3].triggered || root[1][2].triggered) ++errors;
  $display("errors=%0d",errors);
end
''')
    for phase in ("#0", "final"):
        report = ('if(value.triggered) ++result;' if phase == '#0'
                  else '$display("result=%0d",value.triggered);')
        later = ('initial begin #1;$display("result=%0d",result);end' if phase == '#0' else '')
        yield special("deferred_" + ("observed" if phase == "#0" else "final"), f'''int result=0;
function automatic void report(input event value);
  event scratch;
  {report}
endfunction
task automatic run();
  event root;
  ->root;
  assert {phase} (0) else report(root);
endtask
initial run();
{later}
''', "result=1")
    for kind, type_name, first, second in (
            ("integral", "int", "17", "29"),
            ("fourstate", "logic[3:0]", "4'bx10z", "4'b0zx1"),
            ("real", "real", "1.5", "-2.25"),
            ("string", "string", '"first"', '"second"')):
        comparison = "!==" if kind in ("integral", "fourstate") else "!="
        yield special("slice_neighbor_" + kind, f'''int errors=0;
task automatic take(input {type_name} value[0:1]);
  #1;
  if(value[0] {comparison} {first} || value[1] {comparison} {second}) ++errors;
endtask
initial begin
  automatic {type_name} root[-1:1][3:2];
  int index=0;
  root[0][3]={first};root[0][2]={second};
  take(root[index++]);
  if(index!=1) ++errors;
  $display("errors=%0d",errors);
end
''')


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    bad = []
    for name, text in files():
        path = OUT / f"{name}.sv"
        if args.check:
            if not path.exists() or path.read_text() != text:
                bad.append(path.name)
        else:
            path.write_text(text)
    if bad:
        print("gen_event_input_matrix: out of date: " + ", ".join(bad), file=sys.stderr)
    return int(bool(bad))


if __name__ == "__main__":
    sys.exit(main())
