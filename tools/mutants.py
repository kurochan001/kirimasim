def run(cmd: list[str]) -> int:
    return subprocess.run(cmd, cwd=ROOT, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                          check=False).returncode


def run_tests(cmd: list[str]) -> tuple[int, set[str]]:
    """The exit code of ctest and the names of the tests it skipped."""
    p = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, check=False)
    skipped = set(re.findall(r"Test +#\d+: (\S+) \.*\*+Skipped", p.stdout))
    return p.returncode, skipped


def check(root: Path) -> int:
    """1 if the text of some mistake is not in its file exactly once."""
    bad = 0
    for name, rel, old, _ in MUTANTS:
        path = root / rel
        found = path.read_text(encoding="utf-8").count(old) if path.exists() else 0
        if found != 1:
            print(f"DOES NOT APPLY  {name} ({rel}: its text is there {found} times)")
            bad += 1
    print(f"mutants: {len(MUTANTS)} checked, {bad} do not apply")
    return 1 if bad else 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--preset", default="dev")
    ap.add_argument("--only", default="", help="only mutants whose name contains this")
    ap.add_argument("--shard", default="1/1", help="k/n: the k-th of every n mutants")
    ap.add_argument("--check", action="store_true",
                    help="only check that every mistake applies; build and run nothing")
    ap.add_argument("--root", type=Path, default=ROOT,
                    help="with --check: the tree whose files are checked")
    args = ap.parse_args()
    if args.check:
        return check(args.root)
    m = re.fullmatch(r"(\d+)/(\d+)", args.shard)
    if not m or not 1 <= int(m.group(1)) <= int(m.group(2)):
        print(f"mutants: --shard {args.shard}: expected k/n with 1 <= k <= n", file=sys.stderr)
        return 2
    k, n = int(m.group(1)), int(m.group(2))
    chosen = [mu for i, mu in enumerate(MUTANTS) if i % n == k - 1 and args.only in mu[0]]

    if run(["git", "diff", "--quiet", "--", "src"]) != 0:
        print("mutants: src/ has uncommitted changes; commit or stash them first",
              file=sys.stderr)
        return 2
    build = ["cmake", "--build", "--preset", args.preset]
    test = ["ctest", "--preset", args.preset, "-j8"]
    # Replacing an anchor intentionally makes these self-checks fail. That
    # failure proves nothing about simulated values. Keep both on the clean
    # baseline, but require another test to detect each compiled mutation.
    mutated_test = test + ["-E", "^(tools/mutants_apply|tools/negative_controls)$",
                           "--stop-on-failure"]
    if run(build) != 0:
        print("mutants: the unchanged sources do not build", file=sys.stderr)
        return 2
    rc, skipped_before = run_tests(test)
    if rc != 0:
        print("mutants: tests fail on the unchanged sources", file=sys.stderr)
        return 2

    print(f"mutants: {len(chosen)} of {len(MUTANTS)} (shard {k}/{n})")
    bad = 0
    for name, rel, old, new in chosen:
        path = ROOT / rel
        original = path.read_text(encoding="utf-8")
        if original.count(old) != 1:
            print(f"DOES NOT APPLY  {name} ({rel})")
            bad += 1
            continue
        try:
            path.write_text(original.replace(old, new), encoding="utf-8")
            if run(build) != 0:
                print(f"DOES NOT BUILD  {name}")
                bad += 1
                continue
            rc, skipped = run_tests(mutated_test)
            caught = rc != 0 or not skipped <= skipped_before
        finally:
            path.write_text(original, encoding="utf-8")
        print(f"{'caught' if caught else 'SURVIVED':14}  {name}")
        bad += 0 if caught else 1
    if run(build) != 0:
        print("mutants: the unchanged sources do not build", file=sys.stderr)
        return 2
    print(f"mutants: {bad} problem(s)")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
