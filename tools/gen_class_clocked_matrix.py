"""Original class-body/ordinary-clock checks under approved class contract 5-7.

Explicit trigger evaluation retains the object-observation boundary. Executing
an object operation in the triggered body does not add an implicit dependency.
No external simulator source or tests were used.
"""
import argparse
from pathlib import Path

from gen_class_static_matrix import wrap

OUT = Path(__file__).resolve().parent.parent / 'tests/suite/sched'
HOMES = ('unit', 'module', 'package', 'interface', 'generate')
KINDS = ('plain', 'ff')
WIDTHS = (1, 33, 65, 129)


def source(name, text):
    name = 'class_clocked_' + name
    header = f'''/*
:name: {name}
:description: Ordinary explicit clocks execute object bodies without observing object paths
:tags: sched class clock sensitivity lifetime
:type: simulation
:lrm: 1800-2023 8.4 8.6 9.2.2 9.4.2
:oracle: spec
:spec_check: ai
:fourstate: yes
:nondeterministic: no
:generator: gen_class_clocked_matrix.py@1
:top_module: top
:expected_stdout: errors=0
:timeout: 15
*/
// Generated by tools/gen_class_clocked_matrix.py; edit the generator.
`timescale 1ns/1ns
'''
    return name, '\n'.join(line.rstrip() for line in (header+text).splitlines())+'\n'


def declarations(width):
    return f'''class Box;
logic[{width-1}:0] data;
virtual function logic[{width-1}:0] read_value();return data;endfunction
endclass
'''


def cases():
    for home in HOMES:
        for kind in KINDS:
            clock = 'always_ff' if kind == 'ff' else 'always'
            for width in WIDTHS:
                for action in ('field_read', 'method_read', 'allocate'):
                    run = 'sampled=object.data;' if action == 'field_read' else (
                        ('object=new;' if action == 'allocate' else '')+
                        'object.data=next_value;sampled=object.read_value();')
                    actor = f'''Box object;bit clock=0;int hits=0,errors=0;
logic[{width-1}:0] next_value='0,sampled='0,held;
{clock} @(posedge clock) begin {run} ++hits;end
'''
                    body = '' if action == 'allocate' else 'object=new;\n'
                    body += '''#1;
for(int step=0;step<4;step++)begin
case(step) 0:next_value='1;1:next_value='x;2:next_value='z;3:next_value='0;endcase
'''
                    if action == 'field_read':body += 'object.data=next_value;\n'
                    body += '''clock=1;#1;
if(sampled!==next_value || hits!=step+1)++errors;
held=sampled;clock=0;#1;next_value=~held;
'''
                    if action == 'field_read':body += 'object.data=next_value;\n'
                    body += '''#1;if(sampled!==held || hits!=step+1)++errors;
end
$display("errors=%0d",errors);
'''
                    yield source(f'{home}_{kind}_{width}_{action}',wrap(home,declarations(width),body,actor=actor))
            for form in ('iff', 'expression'):
                trigger = 'posedge clock iff gate' if form == 'iff' else 'posedge (clock ^ invert)'
                actor = f'''Box object;bit clock=0,gate=0,invert=0;int hits=0,errors=0;
logic[128:0] sampled;
{clock} @({trigger}) begin sampled=object.read_value();++hits;end
'''
                body = '''object=new;object.data='z;
#1;clock=1;#1;clock=0;#1;
'''
                if form == 'iff':
                    body += 'if(hits!=0)++errors;gate=1;\n'
                else:
                    body += "if(hits!=1 || sampled!=='z)++errors;\n"
                body += "object.data='x;#1;"
                body += ('if(hits!=0)++errors;' if form=='iff' else 'if(hits!=1)++errors;')
                body += "clock=1;#1;"
                body += ("if(hits!=1 || sampled!=='x)++errors;" if form=='iff' else "if(hits!=2 || sampled!=='x)++errors;")
                body += '$display("errors=%0d",errors);\n'
                yield source(f'{home}_{kind}_{form}',wrap(home,declarations(129),body,actor=actor))
    for kind in KINDS:
        clock='always_ff' if kind=='ff' else 'always'
        for form in ('automatic_local','receiver_once'):
            definitions=declarations(65)
            actor='bit clock=0;int hits=0,errors=0,calls=0;logic[64:0] sampled;\n'
            if form=='automatic_local':
                actor+=f'''{clock} @(posedge clock)begin
 automatic Box temporary_object;temporary_object=new;temporary_object.data=65'h1_0123456789abcdef;
 sampled=temporary_object.read_value();++hits;end
'''
                body=''
            else:
                actor+='Box object;function automatic Box select_object();++calls;return object;endfunction\n'
                actor+=f'{clock} @(posedge clock)begin sampled=select_object().read_value();++hits;end\n'
                body="object=new;object.data=65'h1_0123456789abcdef;\n"
            body+='''#1;repeat(3)begin clock=1;#1;
if(sampled!==65'h1_0123456789abcdef)++errors;
clock=0;#1;end
if(hits!=3)++errors;
'''
            if form=='receiver_once':body+='if(calls!=3)++errors;\n'
            body+='$display("errors=%0d",errors);\n'
            yield source(f'module_{kind}_{form}',wrap('module',definitions,body,actor=actor))


def probes():
    base='class Box;int value=0;function void bump();value++;endfunction endclass\n'
    for kind in KINDS:
        clock='always_ff' if kind=='ff' else 'always'
        yield ('class_clocked_method_'+kind,'8.6; 9.2.2; 9.4.2',base+'module top;Box object;bit clock=0;'+clock+' @(posedge clock) object.bump();initial begin object=new;#1 clock=1;#1 clock=0;#1 clock=1;#1 $display("%0d",object.value);end endmodule\n','2\n',[])
    yield ('class_clocked_property_read','8.4; 9.4.2',base+'module top;Box object;bit clock=0;int value;always @(posedge clock) value=object.value;initial begin object=new;object.value=7;#1 clock=1;#1 $display("%0d",value);clock=0;object.value=9;#1 clock=1;#1 $display("%0d",value);end endmodule\n','7\n9\n',[])
    yield ('class_clocked_waiting_control','8.6; 9.2.2.1; 9.4.2','class Box;int value=0;task bump();#4 value++;endtask endclass module top;Box object;bit clock=0;always @(posedge clock) object.bump();initial begin object=new;#1 clock=1;#1 clock=0;#1 clock=1;#1 clock=0;#3 clock=1;#5 $display("%0d",object.value);end endmodule\n','2\n',[])


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args();rows=dict(cases());assert len(rows)==144
    stale=[]
    for name,text in rows.items():
        path=OUT/(name+'.sv')
        if args.check:
            if not path.exists() or path.read_text()!=text:stale.append(name)
        else:path.write_text(text)
    for name in stale:print('out of date: '+name)
    print(f'class clocked matrix: {len(rows)} sources')
    return bool(stale)


if __name__=='__main__':raise SystemExit(main())
