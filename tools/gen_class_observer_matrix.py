"""Original object/ordinary-observer coexistence matrix (8.4, 9.2, 9.4, 10.4).

Approved class contract 7 preserves ordinary observation and requires explicit
boundaries until actual object dependency paths are connected. Expectations
come from the written scheduling/value rules, not another simulator's output.
"""
import argparse
from pathlib import Path

from gen_class_static_matrix import wrap

OUT = Path(__file__).resolve().parent.parent / 'tests/suite/sched'
HOMES = ('unit', 'module', 'package', 'interface', 'program', 'generate')
REACTIVE = ('comb', 'atstar', 'latch', 'cont', 'ff')
PROCEDURAL = ('wait', 'event', 'iff', 'named', 'monitor', 'nba_named', 'nba_expression')


def source(name, text, expected='errors=0'):
    name = 'class_observer_' + name
    return name, f'''/*
:name: {name}
:description: Ordinary observation retains its semantics alongside class objects
:tags: sched class sensitivity wait monitor nba lifetime
:type: simulation
:lrm: 1800-2023 8.4 9.2 9.4 10.4 21.2
:oracle: spec
:spec_check: ai
:fourstate: yes
:nondeterministic: no
:generator: gen_class_observer_matrix.py@1
:top_module: top
:expected_stdout: {expected}
:timeout: 15
*/
// Generated by tools/gen_class_observer_matrix.py; edit the generator.
`timescale 1ns/1ns
{text}'''


def cases():
    for home in HOMES:
        for form in REACTIVE + PROCEDURAL:
            if home == 'program' and form in REACTIVE:
                continue
            for automatic in (False, True):
                for indirect in (False, True):
                    width = 129 if form in ('comb', 'cont', 'wait', 'event', 'nba_expression') else 1
                    scalar = 'logic' if indirect else 'bit'
                    definitions = 'class Box; int value=7; endclass\n'
                    actor = f'''typedef {scalar}[{width-1}:0] value_t;
value_t a='0;
event ready;
bit gate=1;
int hits=0;
function automatic value_t inner(input value_t n);return n;endfunction
function automatic value_t outer(input value_t n);return inner(n);endfunction
'''
                    read = 'outer(a)' if indirect else 'a'
                    ytype = 'wire' if form == 'cont' else scalar
                    actor += f'{ytype}[{width-1}:0] y;\n'
                    if form == 'comb':
                        actor += f'always_comb y={read};\n'
                    elif form == 'atstar':
                        actor += f'always @* y={read};\n'
                    elif form == 'latch':
                        actor += f'always_latch if(gate)y={read};\n'
                    elif form == 'cont':
                        actor += f'assign y={read};\n'
                    elif form == 'ff':
                        actor += f'always_ff @(posedge a[0])y<={read};\n'

                    body = 'object=new;\n'
                    expected = 'errors=0'
                    if form in REACTIVE:
                        body += "#1;\n"
                        if form not in ('ff', 'atstar'):
                            body += "if(y!=='0)++errors;\n"
                        body += "object.value=9;a='1;#1;\nif(y!=='1 || object.value!=9)++errors;\n"
                        if form == 'latch':
                            body += "gate=0;a='0;#1;if(y!=='1)++errors;\n"
                        elif form not in ('ff', 'atstar'):
                            body += "a='0;#1;if(y!=='0)++errors;\n"
                    elif form == 'monitor':
                        body += '''$monitor("sample=%b",a[0]);
#1;object.value=9;
#1;a='1;
#1;$monitoroff;
if(object.value!=9)++errors;
'''
                        expected = '@class_observer_unit_monitor_slot_direct.expected'
                    elif form.startswith('nba_'):
                        control = '@ready' if form == 'nba_named' else f'@({read})'
                        default = "'x" if indirect else "'0"
                        body += f'''y<={control} '1;
#1;object.value=9;
if(y!=={default})++errors;
a='1;->ready;
#1;if(y!=='1 || object.value!=9)++errors;
'''
                    else:
                        control = {
                            'wait': f"wait({read}==='1)",
                            'event': f'@({read})',
                            'iff': '@(posedge a[0] iff gate)',
                            'named': '@ready',
                        }[form]
                        body += f'''fork
begin {control};if(a!=='1)++errors;++hits;end
begin #1;object.value=9;a='1;->ready;end
join
if(hits!=1 || object.value!=9)++errors;
'''
                    body += '$display("errors=%0d",errors);\n'
                    if automatic:
                        actor += 'task automatic exercise();Box object;int errors=0;\n' + body + 'endtask\n'
                        body = 'exercise();'
                    else:
                        actor += 'Box object;\n'
                        body = 'int errors=0;\n' + body
                    name = f'{home}_{form}_{"frame" if automatic else "slot"}_{"calls" if indirect else "direct"}'
                    yield source(name, wrap(home, definitions, body, actor=actor), expected)

    # A waiting receiver stays rooted while an unrelated event wakes it.
    # Observer metadata itself must not replace the existing strong roots.
    for home in HOMES:
        for form in ('named', 'condition'):
            control = '@ready' if form == 'named' else 'wait(gate==1)'
            definitions = f'''class Box;
static int seen=0;
static bit gate=0;
int value=29;
task await_ready(input event ready);{control};seen=value;endtask
endclass
'''
            actor = 'Box object;event ready;\n'
            body = '''int errors=0;
object=new;
fork
object.await_ready(ready);
begin
#1;object=null;
repeat(400)begin automatic Box trash;trash=new;end
Box::gate=1;->ready;
end
join
if(Box::seen!=29 || object!=null)++errors;
$display("errors=%0d",errors);
'''
            yield source(home + '_waiting_receiver_gc_' + form,
                         wrap(home, definitions, body, actor=actor))


def probes():
    """Finite Icarus inventory; this does not claim general class parity."""
    common = 'class Box;int value=7;endclass\n'
    rows = [
        ('comb', 'int a=0,y;always_comb y=a+1;',
         'b=new;#1;a=7;#1;$display("%0d %0d",b.value,y);', '7 8\n'),
        ('cont', 'reg a=0;wire y=~a;',
         'b=new;#1;a=1;#1;$display("%0d %0d",b.value,y);', '7 0\n'),
        ('wait', 'int a=0;',
         'b=new;fork begin wait(a==1);$display("%0d",b.value);end begin #1;a=1;end join', '7\n'),
        ('named', 'event ready;',
         'b=new;fork begin @ready;$display("%0d",b.value);end begin #1;->ready;end join', '7\n'),
        ('nba_event', 'event ready;int a;',
         'b=new;a<=@ready 9;#1;->ready;#1;$display("%0d %0d",b.value,a);', '7 9\n'),
    ]
    for name, declarations, body, expected in rows:
        yield ('class_independent_' + name, '8.4; 9.2; 9.4; 10.4',
               common + 'module top;Box b;' + declarations + 'initial begin ' + body +
               '\nend endmodule', expected, [])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = dict(cases())
    failed = False
    for name, text in generated.items():
        path = OUT / (name + '.sv')
        if args.check:
            if not path.exists() or path.read_text() != text:
                print(f'out of date: {path.relative_to(OUT.parent.parent.parent)}')
                failed = True
        else:
            path.write_text(text)
    monitor = OUT / 'class_observer_unit_monitor_slot_direct.expected'
    text = 'sample=0\nsample=1\nerrors=0\n'
    if args.check:
        if not monitor.exists() or monitor.read_text() != text:
            print(f'out of date: {monitor.name}')
            failed = True
    else:
        monitor.write_text(text)
    print(f'class observer matrix: {len(generated)} sources')
    return int(failed)


if __name__ == '__main__':
    raise SystemExit(main())
