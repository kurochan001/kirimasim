"""Generate original aggregate blocking intra-assignment timing tests (9.4.5).

All RHS leaves are retained before the control; actual targets are selected
after it. Typed private frames retain snapshots across suspension and GC.
"""

import argparse
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / 'tests/suite/sched'
VERSION = 1
HOMES = ('initial', 'task', 'automatic', 'fork', 'interface', 'package', 'program', 'generate')


def output(name, source, expected):
    return {name + '.sv': f'''/*
:name: {name}
:description: Aggregate blocking timing retains all RHS leaves and selects the target after the control
:tags: sched arrays event
:type: simulation
:lrm: 1800-2023 7.6 9.4.2 9.4.5 10.4.1 10.9
:oracle: spec
:spec_check: ai
:fourstate: yes
:nondeterministic: no
:generator: gen_blocking_aggregate_timing_matrix.py@{VERSION}
:top_module: top
:expected_stdout: @{name}.expected
:expected_stderr: @{name}.stderr
*/
// Generated by tools/gen_blocking_aggregate_timing_matrix.py; edit the generator.
`timescale 1ns/1ns
''' + source, name + '.expected': expected, name + '.stderr': ''}


def qualify(text, prefix, names):
    return re.sub(r'\b(' + '|'.join(names) + r')\b', lambda m: prefix + m[0], text)


def case(home, width, domain):
    name = f'blocking_aggregate_timing_{home}_{domain}_{width}'
    declarations = f'''typedef {domain} [{width-1}:0] word_t;
typedef word_t pair_t[2:1];
typedef struct {{word_t words[2:1]; real fraction; string label;}} record_t;
word_t a[2][2:1], source[-2:-3];
record_t records[2], record_source;
bit clk,mutate;
event tick;
int trace,idx,n;
function automatic pair_t take_value();
  trace=trace*10+1; return '{{source[-2],source[-3]}};
endfunction
function automatic record_t take_record(); trace=trace*10+1; return record_source; endfunction
function automatic int pick();
  trace=trace*10+3;
  source[-2]=0; source[-3]=0;
  record_source='{{words:'{{0,0}},fraction:0.0,label:"changed"}};
  return idx++;
endfunction
function automatic int delay_value();
  trace=trace*10+2; source[-2]=0; source[-3]=0; return 2;
endfunction
function automatic int count_value();
  int saved=n;
  trace=trace*10+2; source[-2]=0; source[-3]=0; n=9; return saved;
endfunction
'''
    body = '''foreach(a[p,q]) a[p][q]=0;
idx=0; trace=0; source[-2]='1; source[-3]='z; mutate=1;
a[pick()] = #(delay_value()) take_value();
$display("delay %0d %0d %0t %b %b %b %b",trace,idx,$time,a[0][2],a[0][1],a[1][2],a[1][1]);
idx=0; trace=0; source[-2]='1; source[-3]='x;
a[pick()] = #0 take_value();
$display("zero %0d %0d %0t %b %b",trace,idx,$time,a[0][2],a[0][1]);
idx=0; trace=0; source[-2]='1; source[-3]='z; mutate=1;
a[pick()] = @(posedge clk) take_value();
$display("edge %0d %0d %0t %b %b",trace,idx,$time,a[1][2],a[1][1]);
idx=0; trace=0; n=2; source[-2]='1; source[-3]='z; mutate=1;
a[pick()] = repeat(count_value()) @(tick or negedge clk) take_value();
$display("repeat %0d %0d %0t %b %b",trace,idx,$time,a[1][2],a[1][1]);
idx=0; trace=0; n=0; source[-2]='1; source[-3]='z;
a[pick()] = repeat(count_value()) @(tick) take_value();
$display("skip %0d %0d %0t %b %b",trace,idx,$time,a[0][2],a[0][1]);
idx=0; trace=0; record_source='{words:'{'1,'z},fraction:2.5,label:"saved"}; mutate=1;
records[pick()] = #2 take_record();
$display("record %0d %0d %0t %b %b %0.1f %s",trace,idx,$time,records[1].words[2],records[1].words[1],records[1].fraction,records[1].label);
idx=9; trace=0; source[-2]='1; source[-3]='z;
a[pick()] = #1 take_value();
$display("invalid %0d %0d %0t %b %b",trace,idx,$time,a[0][2],a[0][1]);
$finish(0);
'''
    drive = '''always #1 begin
  if(mutate) begin
    idx=1; source[-2]=0; source[-3]=0; n=9;
    record_source='{words:'{0,0},fraction:0.0,label:"changed"}; mutate=0;
  end
  clk=~clk; ->tick;
end
initial begin #100; $fatal(1,"aggregate timing timeout"); end
'''
    globals_ = ('a', 'source', 'records', 'record_source', 'clk', 'mutate', 'tick',
                'trace', 'idx', 'n', 'take_value', 'take_record', 'pick', 'delay_value',
                'count_value')
    if home in ('interface', 'package'):
        source = f'{home} worker;\n' + declarations + 'task automatic run();\n'
        source += body + f'endtask\nend{home}\nmodule top;\n'
        if home == 'interface':
            source += 'worker w(); initial w.run();\n'
            prefix = 'w.'
        else:
            source += 'initial worker::run();\n'
            prefix = 'worker::'
        source += qualify(drive, prefix, globals_) + 'endmodule\n'
    elif home == 'program':
        source = 'program worker; initial begin\n'
        source += qualify(body, 'top.', globals_) + 'end\nendprogram\n'
        source += 'module top;\n' + declarations + 'worker p();\n' + drive + 'endmodule\n'
    else:
        source = 'module top;\n' + ('if(1) begin:g\n' if home == 'generate' else '')
        source += declarations + drive
        if home in ('task', 'automatic'):
            source += ('task automatic run();\n' if home == 'automatic' else 'task run();\n')
            source += body + 'endtask\ninitial run();\n'
        elif home == 'fork':
            source += 'initial fork begin\n' + body + 'end join\n'
        else:
            source += 'initial begin\n' + body + 'end\n'
        source += ('end\n' if home == 'generate' else '') + 'endmodule\n'
    zero, one = '0' * width, '1' * width
    x = 'x' * width if domain == 'logic' else zero
    z = 'z' * width if domain == 'logic' else zero
    expected = (f'delay 123 2 2 {zero} {zero} {one} {z}\n'
                f'zero 13 1 2 {one} {x}\nedge 13 2 3 {one} {z}\n'
                f'repeat 123 2 5 {one} {z}\nskip 123 1 5 {one} {z}\n'
                f'record 13 2 7 {one} {z} 2.5 saved\ninvalid 13 10 8 {one} {z}\n')
    return output(name, source, expected)


