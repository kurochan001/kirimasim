"""Generates the matrix tests of several defparams of one parameter
(TEST_SUITE.md, "Mechanism matrix") in tests/suite/hier/.

  tools/gen_defparam_last_matrix.py           # writes the files
  tools/gen_defparam_last_matrix.py --check   # exit 1 if a file differs from what it would write

The rule: 23.10.1 of the standard. When several defparams set one
parameter, the parameter takes the value of the last of them in the
source text. All the tests are one source file each, since the standard
leaves the choice open for defparams found in different files. A
defparam inside a generate block changes only parameters inside that
block.

The axes: where the defparams are written and what path they take (in
the top module to a child, in the top module through a module below it,
in the top module into a generate block, inside a generate block to a
child of the same block, and split between the top module and the module
below it, whose text comes before or after the top module's), how many
there are (two or three), and the order of their values (rising or
falling, so that neither the largest nor the smallest is the answer by
chance).

Each instance prints its parameter at a time of its own. The expected
output is computed here from the order of the defparams in the text,
without reading kirimasim's code. A person checks it once for all the
tests made from it (TEST_SUITE.md, "Sampling by people").
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "hier"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

COUNTS = (2, 3)
ORDERS = ("rising", "falling")
CHILD = ["module child #(parameter int P = 0, parameter int ID = 0);",
         '  initial #(ID) $display("%0d P=%0d", ID, P);', "endmodule"]


def cases():
    """Yields (id, count, order, values in text order)."""
    k = 0
    for count in COUNTS:
        for order in ORDERS:
            k += 1
            values = [10 * k + v for v in range(1, count + 1)]
            if order == "falling":
                values.reverse()
            yield k, count, order, values


def header(name, where):
    return ["/*", f":name: {name}",
            ":description: of several defparams of one parameter, the last in the source text "
            f"gives the value, with two or three of them in rising or falling order, {where}",
            ":tags: hier", ":type: simulation", ":lrm: 1800-2023 23.10.1",
            ":oracle: spec", ":spec_check: ai", ":fourstate: no", ":nondeterministic: no",
            f":generator: gen_defparam_last_matrix.py@{VERSION}", ":top_module: top",
            ":issue: 59", f":expected_stdout: @{name}.expected", "*/",
            "// Generated by tools/gen_defparam_last_matrix.py; change the generator, not this "
            "file.", "`timescale 1ns/1ns"]


def one_module(shape):
    """All the defparams in one module: top, nested, generate, inside."""
    where = {"top": "written in the top module for its own children",
             "nested": "written in the top module for the children of a module below it",
             "generate": "written in the top module for the children of a generate block",
             "inside": "written inside a generate block for its own children"}[shape]
    name = f"defparam_last_{shape}"
    sv = header(name, where) + CHILD
    expected = []
    insts, params = [], []
    for k, _, _, values in cases():
        insts.append(f"child #(.ID({k})) c{k}();")
        path = {"top": f"c{k}", "nested": f"m.c{k}", "generate": f"g.c{k}", "inside": f"c{k}"}[shape]
        params += [f"defparam {path}.P = {v};" for v in values]
        expected.append(f"{k} P={values[-1]}")
    if shape == "nested":
        sv += ["module mid;", *("  " + i for i in insts), "endmodule",
               "module top;", "  mid m();", *("  " + p for p in params), "endmodule"]
    elif shape == "generate":
        sv += ["module top;", "  if (1) begin : g", *("    " + i for i in insts), "  end",
               *("  " + p for p in params), "endmodule"]
    elif shape == "inside":
        sv += ["module top;", "  if (1) begin : g", *("    " + i for i in insts),
               *("    " + p for p in params), "  end", "endmodule"]
    else:
        sv += ["module top;", *("  " + i for i in insts), *("  " + p for p in params),
               "endmodule"]
    return name, sv, expected


def split(mid_first):
    """The defparams split between the module below the top and the top.

    The module below the top sets its child's parameter with a relative
    path, the top module with a path through that module. The values of
    the module whose text comes later are the later ones in the source.
    """
    name = f"defparam_last_split_{'mid_first' if mid_first else 'top_first'}"
    where = ("split between the top module and the module below it, whose text comes "
             + ("before" if mid_first else "after") + " the top module's")
    sv = header(name, where) + CHILD
    mid_lines, top_lines, expected = [], [], []
    for k, count, _, values in cases():
        # The first defparam goes in one module and the rest in the other,
        # alternating which module has more, so both sides hold the last
        # value of some case.
        lower, upper = (values[:1], values[1:]) if k % 2 else (values[1:], values[:1])
        mid_lines += [f"defparam c{k}.P = {v};" for v in lower]
        top_lines += [f"defparam m.c{k}.P = {v};" for v in upper]
        later = lower if not mid_first else upper
        expected.append(f"{k} P={later[-1]}")
    mid = ["module mid;", *(f"  child #(.ID({k})) c{k}();" for k, *_ in cases()),
           *("  " + p for p in mid_lines), "endmodule"]
    top = ["module top;", "  mid m();", *("  " + p for p in top_lines), "endmodule"]
    sv += (mid + top) if mid_first else (top + mid)
    return name, sv, expected


def files():
    out = {}
    tests = [one_module(s) for s in ("top", "nested", "generate", "inside")]
    tests += [split(True), split(False)]
    for name, sv, expected in tests:
        out[f"{name}.sv"] = "\n".join(sv) + "\n"
        out[f"{name}.expected"] = "\n".join(expected) + "\n"
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print("gen_defparam_last_matrix: "
                      f"{path.relative_to(OUT.parent.parent.parent)} is out of date; run "
                      "tools/gen_defparam_last_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
