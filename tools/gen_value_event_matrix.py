#!/usr/bin/env python3
"""Generates the matrix test of event controls on variables that are not
integral of TEST_SUITE.md ("Mechanism matrix") in tests/suite/sched/.

  tools/gen_value_event_matrix.py           # writes the files
  tools/gen_value_event_matrix.py --check   # exit 1 if a file differs from what it would write

An event control without an edge wakes when the value of what it waits
on changes (9.4.2, SCHEDULER_SPEC.md 9.1); writing the value a variable
already holds is no change. Here what is waited on is a real, a
shortreal, a realtime, a string, an element of an array of reals and a
real member of an unpacked structure; a write to a neighbouring element
or member changes nothing it waits on. -0.0 and NaN are left out: whether
a write of -0.0 over 0.0, or of NaN over NaN, is a change is not
settled by the text.

The axes: the variable; the step (the same value again, another value,
a neighbour); the container (an always procedure, a forever loop in an
initial procedure, in an automatic task and in a fork branch). Each
waiter counts its events; for each step the driver notes the counts,
writes, and prints the counts since.

The expected outputs follow from the rules above, computed below. A
person checks them once for all the tests made from them (TEST_SUITE.md,
"Sampling by people").
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "sched"
NAME = "value_event_matrix"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

# (name, what is waited on, its initial value, the steps: (statement,
# whether it changes the value waited on))
VARIABLES = [
    ("real", "r", [("r = 1.5;", True), ("r = 1.5;", False), ("r = -2.25;", True),
                   ("r = 1e300;", True), ("r = 1e300;", False)]),
    ("shortreal", "sr", [("sr = 0.5;", True), ("sr = 0.5;", False), ("sr = 3.75;", True)]),
    ("realtime", "rt", [("rt = 2.5;", True), ("rt = 2.5;", False)]),
    ("string", "s", [('s = "ab";', True), ('s = "ab";', False), ('s = "abc";', True),
                     ('s = "";', True), ('s = "";', False)]),
    ("element", "ra[1]", [("ra[1] = 4.5;", True), ("ra[0] = 7.0;", False),
                          ("ra[2] = 8.0;", False), ("ra[1] = 4.5;", False),
                          ("ra[1] = -4.5;", True)]),
    ("member", "st.f", [("st.f = 6.5;", True), ("st.g = 9;", False), ("st.f = 6.5;", False),
                        ("st.f = 0.25;", True)]),
]
CONTAINERS = ["always", "initial", "task", "fork"]


def waiter(cont, k, ctl):
    body = f"cnt[{k}]++;"
    if cont == "always":
        return [f"  always @({ctl}) {body}"]
    if cont == "initial":
        return [f"  initial forever @({ctl}) {body}"]
    if cont == "task":
        return [f"  task automatic t{k};\n    forever @({ctl}) {body}\n  endtask",
                f"  initial t{k}();"]
    return [f"  initial fork\n    forever @({ctl}) {body}\n  join_none"]


def files():
    waiters, idx = [], {}
    k = 0
    for name, expr, _ in VARIABLES:
        for cont in CONTAINERS:
            idx[(name, cont)] = k
            waiters += waiter(cont, k, expr)
            k += 1
    decl = [
        "  real r, ra [0:2];",
        "  shortreal sr;",
        "  realtime rt;",
        "  string s;",
        "  struct { int g; real f; } st;",
        f"  int cnt[0:{k - 1}], base[0:{k - 1}];",
    ]
    lines, exp = [], []
    for name, _, steps in VARIABLES:
        for n, (stmt, changes) in enumerate(steps):
            lines.append("    #10 base = cnt;")
            lines.append(f"    #2 {stmt}")
            lines.append("    #2;")
            for cont in CONTAINERS:
                c = idx[(name, cont)]
                tag = f"{name} {n} {cont}"
                lines.append(f'    $display("{tag} %0d", cnt[{c}] - base[{c}]);')
                exp.append(f"{tag} {int(changes)}")
    head = [
        "/*",
        f":name: {NAME}",
        ":description: event controls on a real, a shortreal, a realtime, a string, an element "
        "of an array of reals and a real member of an unpacked structure: a new value wakes, "
        "the same value or a neighbour does not, in always, initial, automatic task and fork",
        ":tags: sched",
        ":type: simulation",
        ":lrm: 1800-2023 9.4.2",
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: no",
        ":nondeterministic: no",
        f":generator: gen_value_event_matrix.py@{VERSION}",
        ":top_module: top",
        f":expected_stdout: @{NAME}.expected",
        "*/",
        "// Generated by tools/gen_value_event_matrix.py; change the generator, not this file.",
        "`timescale 1ns/1ns",
        "module top;",
    ]
    sv = head + decl + waiters + ["  initial begin"] + lines + ["    $finish;", "  end",
                                                              "endmodule", ""]
    return {f"{NAME}.sv": "\n".join(sv), f"{NAME}.expected": "\n".join(exp) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_value_event_matrix: {path.relative_to(OUT.parent.parent.parent)} is "
                      "out of date; run tools/gen_value_event_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
