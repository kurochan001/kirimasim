"""Generates the matrix tests of a system function called in a void cast
(TEST_SUITE.md, "Mechanism matrix") in tests/suite/proc/.

  tools/gen_void_cast_system_function_matrix.py           # writes the files
  tools/gen_void_cast_system_function_matrix.py --check   # exit 1 if a file differs from what it would write

The rule: 13.4.1 of the standard. void'(f(...)) calls f as a function and
discards its value. A system subroutine that can be called as a task and
as a function is therefore called as the function: $stacktrace returns
its lines and prints nothing (20.17.2, SYSTEM_TASKS.md 10.3), and $cast
returns 0 for a cast that fails, with no error (8.16). What the function
does besides returning a value still happens: $sscanf stores what it
read.

The axes: the function ($stacktrace with and without parentheses,
$test$plusargs, $value$plusargs, $sformatf, $urandom, $countones, $sscanf,
$cast of a class handle that does not fit) and the container of the call
(an initial procedure, a task, a function, a static method of a class).

Each call is followed by a line that names it, with the values the call
may have changed, so a call that printed something, stopped the run or
stored nothing shows. The expected output follows from the rule above,
without reading kirimasim's code. A person checks it once for all the
tests made from it (TEST_SUITE.md, "Sampling by people").
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "proc"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

CONTAINERS = ["initial", "task", "function", "method"]

# (label, the statements before the call, the call in the void cast, what is
# printed after it and its arguments, the text expected).
CALLS = [
    ("stacktrace", "", "$stacktrace", "", "", ""),
    ("stacktrace parentheses", "", "$stacktrace()", "", "", ""),
    ("test plusargs", "", '$test$plusargs("absent")', "", "", ""),
    ("value plusargs", "n = 4;", '$value$plusargs("absent=%d", n)', " n=%0d", ", n", " n=4"),
    ("sformatf", "n = 5;", '$sformatf("%0d", n)', " n=%0d", ", n", " n=5"),
    ("urandom", "", "$urandom", "", "", ""),
    ("countones", "n = 7;", "$countones(n)", " n=%0d", ", n", " n=7"),
    ("sscanf", "n = 0;", '$sscanf("12", "%d", n)', " n=%0d", ", n", " n=12"),
    ("cast", "b = new; d = null;", "$cast(d, b)", " null=%0d", ", d == null", " null=1"),
]


def test(container):
    name = f"void_cast_system_function_{container}"
    where = {"initial": "an initial procedure", "task": "a task", "function": "a function",
             "method": "a static method of a class"}[container]
    lines = ["/*", f":name: {name}",
             ":description: a system function called in a void cast is called as a function, "
             f"its value discarded, in {where}: $stacktrace prints nothing and a $cast that "
             "fails is no error",
             ":tags: proc", ":type: simulation", ":lrm: 1800-2023 13.4.1 20.17.2 8.16",
             ":oracle: spec", ":spec_check: ai", ":fourstate: no", ":nondeterministic: no",
             f":generator: gen_void_cast_system_function_matrix.py@{VERSION}", ":top_module: top",
             f":expected_stdout: @{name}.expected", "*/",
             "// Generated by tools/gen_void_cast_system_function_matrix.py; change the "
             "generator, not this file.", "`timescale 1ns/1ns",
             "class base; endclass", "class derived extends base; endclass"]
    body, stdout = [], []
    for label, before, call, fmt, args, text in CALLS:
        if before:
            body.append(before)
        body.append(f"void'({call});")
        body.append(f'$display("{label}:{fmt}"{args});')
        stdout.append(f"{label}:{text}")
    decls = "int n; base b; derived d;"
    if container == "method":
        lines += ["class holder;", "  static function void run();", f"    {decls}"]
        lines += ["    " + b for b in body] + ["  endfunction", "endclass"]
        lines += ["module top;", "  initial holder::run();", "endmodule"]
    else:
        lines += ["module top;"]
        if container == "initial":
            lines += ["  initial begin", f"    {decls}"]
            lines += ["    " + b for b in body] + ["  end"]
        else:
            head, tail = (("  task automatic run();", "  endtask") if container == "task" else
                          ("  function automatic void run();", "  endfunction"))
            lines += [head, f"    {decls}"] + ["    " + b for b in body] + [tail]
            lines += ["  initial run();"]
        lines += ["endmodule"]
    return name, lines, stdout


def files():
    out = {}
    for container in CONTAINERS:
        name, lines, stdout = test(container)
        out[f"{name}.sv"] = "\n".join(lines) + "\n"
        out[f"{name}.expected"] = "\n".join(stdout) + "\n"
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print("gen_void_cast_system_function_matrix: "
                      f"{path.relative_to(OUT.parent.parent.parent)} is out of date; run "
                      "tools/gen_void_cast_system_function_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
