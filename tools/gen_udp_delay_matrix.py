"""Generates the matrix tests of the delays of sequential UDP instances and
their initial values (TEST_SUITE.md, "Mechanism matrix") in
tests/suite/nets/.

  tools/gen_udp_delay_matrix.py           # writes the files
  tools/gen_udp_delay_matrix.py --check   # exit 1 if a file differs from what it would write

The rule (29.7, VALUE_SEMANTICS.md 5.9): the output of a sequential UDP
instance has the value of its initial statement from the start of the
simulation, whatever the instance's delay; only the changes after it take
the delay, chosen as for gates (SCHEDULER_SPEC.md 12). The axes: the
initial value (0, 1, none), the delay (none, #0, #3, #(2, 5)), the data
that the first rising edge of the clock takes (0, 1), the time of that
edge (1, inside every delay of the start, and 10, after them), and the
container of the instance (a module body, a generate-if block, a
generate-for block, a child module reached through its ports, and an
array of instances). Every output is read with $strobe at the end of
each time slot, so no read races with the instances.

The expected outputs follow from the rules written again below, with the
table matching of tools/gen_udp_matrix.py, without reading kirimasim's
code.
"""

import argparse
import sys
from pathlib import Path

from gen_udp_matrix import change, parse, primitive

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "nets"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

# A flip-flop on the rising edge of clk, which keeps its state otherwise.
DFF = ["r 0 : ? : 0", "r 1 : ? : 1", "n ? : ? : -", "? * : ? : -"]
INITIALS = {"i0": "0", "i1": "1", "in": None}
DELAYS = {"none": None, "d0": (0,), "d3": (3,), "d25": (2, 5)}
DATA = ["0", "1"]
EDGES = {1: [0, 1, 2, 3, 4, 5, 6, 7], 10: [0, 1, 5, 10, 11, 12, 13, 14, 15, 16]}
CONTAINERS = ["module", "generate_if", "generate_for", "child", "array"]


# --- The rules -------------------------------------------------------------------

def delay_to(delay, value):
    """SCHEDULER_SPEC.md 12: the rise delay on becoming 1, the fall delay
    on 0, the smallest on x; one delay is used for everything."""
    if delay is None:
        return 0
    rise, fall = delay[0], delay[-1]
    return {"1": rise, "0": fall}.get(value, min(rise, fall))


def output(initial, delay, data, edge, t):
    """The output at the end of time slot t. At time 0 clk goes from x to
    0 and d from x to data, and at the edge clk goes to 1."""
    rows = parse(DFF)
    start = initial or "x"
    at0 = change(rows, start, ["x", "x"], ["0", data], [0, 1])
    assert at0 == start, "the changes at time 0 keep the state"
    after = change(rows, at0, ["0", data], ["1", data], [0, 1])
    # The initial value is on the output from time 0, with no delay; only
    # the change at the edge takes it.
    if after != at0 and t >= edge + delay_to(delay, after):
        return after
    return start


# --- The tests -------------------------------------------------------------------

def cells():
    """(name, primitive, initial, delay key, data) of each instance."""
    out = []
    for ikey, initial in INITIALS.items():
        for dkey in DELAYS:
            for data in DATA:
                out.append((f"{ikey}_{dkey}_v{data}", f"dff_{ikey}", initial, dkey, data))
    return out


def delay_text(dkey):
    d = DELAYS[dkey]
    return "" if d is None else f" #{d[0]}" if len(d) == 1 else f" #({d[0]}, {d[1]})"


def instances(container, indent):
    """The instances, bit k of q and d for cell k. An array takes two
    consecutive cells of the same primitive and delay, as its two
    elements."""
    out = ""
    cs = cells()
    k = 0
    while k < len(cs):
        name, prim, _, dkey, _ = cs[k]
        if container == "array":
            base = name.rsplit("_", 1)[0]
            out += f"{indent}{prim}{delay_text(dkey)} u_{base} [1:0] (q[{k + 1}:{k}], clk, d[{k + 1}:{k}]);\n"
            k += 2
        else:
            out += f"{indent}{prim}{delay_text(dkey)} u_{name} (q[{k}], clk, d[{k}]);\n"
            k += 1
    return out


def header(name, container, edge):
    return (f"/*\n:name: {name}\n:description: sequential UDP instances with and without an "
            f"initial value and a delay, in {container.replace('_', ' ')} containers, the clock "
            f"rising at {edge}: the initial value is on the output from time 0 whatever the "
            f"delay, and only the later change takes it\n:tags: nets\n:type: simulation\n"
            f":lrm: 1800-2023 29.7 28.16\n:oracle: spec\n:spec_check: ai\n:fourstate: yes\n"
            f":nondeterministic: no\n:generator: gen_udp_delay_matrix.py@{VERSION}\n"
            f":issue: 26\n:top_module: top\n:expected_stdout: @{name}.expected\n*/\n"
            "// Generated by tools/gen_udp_delay_matrix.py; change the generator, not this file.\n"
            "`timescale 1ns/1ns\n")


def test(container, edge):
    name = f"udp_delay_initial_{container}_edge{edge}"
    cs = cells()
    n = len(cs)
    sv = header(name, container, edge)
    for ikey, initial in INITIALS.items():
        sv += primitive(f"dff_{ikey}", ["clk", "d"], DFF, True, initial)
    if container == "child":
        sv += (f"module holder (input clk, input [{n - 1}:0] d, output [{n - 1}:0] q);\n"
               + instances(container, "  ") + "endmodule\n")
    sv += f"module top;\n  reg clk;\n  reg [{n - 1}:0] d;\n  wire [{n - 1}:0] q;\n"
    if container in ("module", "array"):
        sv += instances(container, "  ")
    elif container == "generate_if":
        sv += "  if (1) begin : g\n" + instances(container, "    ") + "  end\n"
    elif container == "generate_for":
        sv += ("  for (genvar i = 0; i < 1; i++) begin : g\n" + instances(container, "    ")
               + "  end\n")
    else:
        sv += "  holder h (clk, d, q);\n"
    data = "".join(c[4] for c in reversed(cs))
    sv += (f"  initial begin\n    clk = 1'b0;\n    d = {n}'b{data};\n"
           f"    #{edge} clk = 1'b1;\n  end\n")
    fmt = " ".join(f"{c[0]}=%b" for c in cs)
    args = ", ".join(f"q[{k}]" for k in range(n))
    sv += "  initial begin\n"
    exp = ""
    now = 0
    for t in EDGES[edge]:
        wait = f"#{t - now} " if t > now else ""
        sv += f"    {wait}$strobe(\"t=%0d {fmt}\", $time, {args});\n"
        now = t
        exp += f"t={t} " + " ".join(
            f"{c[0]}={output(c[2], DELAYS[c[3]], c[4], edge, t)}" for c in cs) + "\n"
    sv += "  end\nendmodule\n"
    return name, sv, exp


def files():
    out = {}
    for container in CONTAINERS:
        for edge in EDGES:
            name, sv, exp = test(container, edge)
            out[f"{name}.sv"] = sv
            out[f"{name}.expected"] = exp
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_udp_delay_matrix: {path.relative_to(OUT.parent.parent.parent)} is "
                      "out of date; run tools/gen_udp_delay_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
