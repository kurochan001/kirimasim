"""Generate original aggregate assignment value/target-order tests (10.4).

SIR_SPEC 7.3 requires RHS capture before target selectors. Existing scalar
delayed lowering evaluates the delay between those phases. Containers must
be snapshotted before later RHS fields or selectors can mutate their source.
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / 'tests/suite/sched'
VERSION = 1
HOMES = ('initial', 'task', 'function', 'fork', 'interface', 'package', 'program', 'generate')


def wrap(home, declarations, methods, issue, report):
    if home in ('package', 'interface'):
        source = f'{home} worker;\n' + declarations + methods
        source += 'task automatic run();\n' + issue + report + f'endtask\nend{home}\n'
        entry = 'worker w(); initial w.run();' if home == 'interface' else 'initial worker::run();'
        return source + f'module top; {entry} endmodule\n'
    kind = 'program' if home == 'program' else 'module'
    source = f'{kind} worker;\n' if home == 'program' else 'module top;\n'
    if home == 'generate':
        source += 'if (1) begin:g\n'
    source += declarations + methods
    if home in ('task', 'function'):
        source += ('task automatic issue();\n' if home == 'task'
                   else 'function automatic void issue();\n')
        source += issue + ('endtask\n' if home == 'task' else 'endfunction\n')
        source += 'initial begin issue();\n' + report + 'end\n'
    elif home == 'fork':
        source += 'initial begin fork begin\n' + issue + 'end join\n' + report + 'end\n'
    else:
        source += 'initial begin\n' + issue + report + 'end\n'
    if home == 'generate':
        source += 'end\n'
    source += f'end{kind}\n'
    if home == 'program':
        source += 'module top; worker p(); endmodule\n'
    return source


def output(name, source, expected):
    header = f'''/*
:name: {name}
:description: Aggregate assignment captures every RHS value before target effects and retains runtime prefixes
:tags: sched nba arrays
:type: simulation
:lrm: 1800-2023 7.6 9.4.5 10.4.1 10.4.2 10.9
:oracle: spec
:spec_check: ai
:fourstate: yes
:nondeterministic: no
:generator: gen_aggregate_nba_capture_matrix.py@{VERSION}
:top_module: top
:expected_stdout: @{name}.expected
:expected_stderr: @{name}.stderr
*/
// Generated by tools/gen_aggregate_nba_capture_matrix.py; edit the generator.
`timescale 1ns/1ns
'''
    return {name + '.sv': header + source, name + '.expected': expected,
            name + '.stderr': ''}


def case(home, width, domain):
    name = f'aggregate_nba_capture_{home}_{domain}_{width}'
    declarations = f'''typedef {domain} [{width-1}:0] word_t;
typedef struct {{word_t first; word_t second; real fraction; string label;}} pair_t;
pair_t a[7][2], source;
int idx,trace,orders[7],indices[7];
'''
    methods = '''function automatic int choose(); trace=trace*10+2; return idx++; endfunction
function automatic pair_t source_value();
  trace=trace*10+1; idx=1;
  return '{first:'1,second:'z,fraction:2.5,label:"saved"};
endfunction
function automatic pair_t without_index();
  trace=trace*10+1;
  return '{first:'1,second:'z,fraction:2.5,label:"saved"};
endfunction
function automatic int clobber();
  trace=trace*10+2; source='{first:0,second:0,fraction:0.0,label:"changed"};
  return idx++;
endfunction
function automatic int delay_value(); trace=trace*10+3; idx=0; return 2; endfunction
'''
    issue = '''foreach(a[p,q]) a[p][q]='{first:0,second:0,fraction:0.0,label:""};
idx=0; trace=0; a[0][choose()] <= source_value();
orders[0]=trace; indices[0]=idx;
idx=1; trace=0; source='{first:'1,second:'z,fraction:2.5,label:"saved"};
a[1][clobber()] <= source;
orders[1]=trace; indices[1]=idx;
idx=0; trace=0; a[2][choose()] <= #0 source_value();
orders[2]=trace; indices[2]=idx;
idx=0; trace=0; a[3][choose()] <= #(delay_value()) source_value();
orders[3]=trace; indices[3]=idx;
idx=9; trace=0; a[4][choose()] <= #1 without_index();
orders[4]=trace; indices[4]=idx;
idx=0; trace=0; a[5][choose()] = source_value();
orders[5]=trace; indices[5]=idx;
idx=1; trace=0; source='{first:'1,second:'z,fraction:2.5,label:"saved"};
a[6][clobber()] = source;
orders[6]=trace; indices[6]=idx;
'''
    report = '''$display("order %0d %0d %0d %0d %0d %0d %0d",orders[0],orders[1],orders[2],orders[3],orders[4],orders[5],orders[6]);
$display("index %0d %0d %0d %0d %0d %0d %0d",indices[0],indices[1],indices[2],indices[3],indices[4],indices[5],indices[6]);
$display("blocking %b %b %0.1f %s %b %b %0.1f %s",a[5][1].first,a[5][1].second,a[5][1].fraction,a[5][1].label,
  a[6][1].first,a[6][1].second,a[6][1].fraction,a[6][1].label);
$display("before %b %b",a[0][1].first,a[3][0].first);
#0; $display("inactive %b %b",a[0][1].first,a[3][0].first);
#1; $display("pending %b %b",a[2][1].first,a[3][0].first);
#2;
'''
    zeros, ones = '0' * width, '1' * width
    second = 'z' * width if domain == 'logic' else zeros
    expected = ('order 12 2 12 132 12 12 2\nindex 2 2 2 1 10 2 2\n'
                f'blocking {ones} {second} 2.5 saved {ones} {second} 2.5 saved\n'
                f'before {zeros} {zeros}\ninactive {zeros} {zeros}\npending {ones} {zeros}\n')
    for stage, index in ((0, 1), (1, 1), (2, 1), (3, 0)):
        value = f'a[{stage}][{index}]'
        report += (f'$display("value{stage} %b %b %0.1f %s",{value}.first,'
                   f'{value}.second,{value}.fraction,{value}.label);\n')
        expected += f'value{stage} {ones} {second} 2.5 saved\n'
    report += '''$display("neighbors %b %b %b %b %b %b",a[0][0].first,a[1][0].first,
  a[2][0].first,a[3][1].first,a[4][0].first,a[4][1].first);
'''
    expected += 'neighbors ' + ' '.join([zeros] * 6) + '\n'
    return output(name, wrap(home, declarations, methods, issue, report), expected)


def members(home):
    name = f'aggregate_nba_capture_{home}_members'
    declarations = '''typedef logic [64:0] word_t;
typedef struct {word_t words[2:1]; int tag;} row_t;
typedef row_t batch_t[1:0];
row_t rows[2], part[2], static_result;
batch_t batch, original;
word_t grid[2:1][-1:0], source_words[5:6], blocking_grid[2][2];
typedef struct {int data[$]; int tag;} queue_row_t;
queue_row_t queue_rows[2], queue_copies[2], queue_source; int data[$];
typedef int queue_t[$];
queue_t queue_array[5:6], queue_targets[2][2], pattern_result[2];
int idx,trace,order0,order1,order2,order3,observed[2];
'''
    methods = '''function automatic int choose(); trace=trace*10+2; return idx++; endfunction
function automatic row_t make_row();
  trace=trace*10+1; idx=1; return '{words:'{65'd7,65'd9},tag:11};
endfunction
function row_t static_row(); return '{words:'{65'd59,65'd61},tag:67}; endfunction
function automatic int alter_words();
  trace=trace*10+2; source_words='{0,0}; return idx++;
endfunction
function automatic int alter_data(); data[0]=99; return 5; endfunction
function automatic int queue_index();
  trace=trace*10+2; data[0]=123; return idx++;
endfunction
function automatic int source_index(); queue_source.data[0]=88; return 1; endfunction
function automatic int array_index(); queue_array[5][0]=90; return 1; endfunction
function automatic queue_t mutate_array_queue(); queue_array[5][0]=99; return '{47}; endfunction
function automatic void observe(input queue_t items[2]);
  observed[0]=items[0][0]; observed[1]=items[1][0];
endfunction
'''
    issue = '''foreach(rows[i]) begin
  rows[i]='{words:'{0,0},tag:0}; part[i]='{words:'{0,0},tag:0};
  queue_rows[i]='{data:{},tag:0};
  queue_copies[i]='{data:{},tag:0};
end
foreach(grid[i,j]) grid[i][j]=0;
foreach(blocking_grid[i,j]) blocking_grid[i][j]=0;
idx=0; trace=0; rows[choose()] <= #1 make_row(); order0=trace;
idx=1; trace=0; part[choose()].words <= #1 '{65'd13,65'd17}; order1=trace;
idx=1; trace=0; source_words='{65'd19,65'd23};
grid[alter_words()] <= #1 source_words; order2=trace;
data='{7}; idx=1; trace=0;
queue_rows[queue_index()] <= #1 '{data:data,tag:alter_data()}; order3=trace;
queue_source='{data:'{31},tag:37};
queue_copies[source_index()] <= #1 queue_source;
queue_array[5]='{41}; queue_array[6]='{43};
queue_targets[array_index()] <= #1 queue_array;
queue_array[5]='{41};
pattern_result = '{queue_array[5],mutate_array_queue()};
queue_array[5]='{53}; observe('{queue_array[5],mutate_array_queue()});
source_words='{65'd19,65'd23}; idx=1;
blocking_grid[choose()] = source_words;
original='{ '{words:'{65'd29,65'd31},tag:37}, '{words:'{65'd41,65'd43},tag:47}};
batch <= #1 original;
original[1].words[2]=0;
static_result = static_row();
'''
    report = '''$display("orders %0d %0d %0d %0d",order0,order1,order2,order3);
#3;
$display("row %0d %0d %0d %0d",rows[1].words[2],rows[1].words[1],rows[1].tag,rows[0].tag);
$display("member %0d %0d %0d",part[1].words[2],part[1].words[1],part[0].words[2]);
$display("grid %0d %0d %0d",grid[1][-1],grid[1][0],grid[2][-1]);
$display("queue %0d %0d %0d %0d",queue_rows[1].data.size(),queue_rows[1].data[0],queue_rows[1].tag,data[0]);
$display("queue_copy %0d %0d %0d %0d",queue_copies[1].data.size(),queue_copies[1].data[0],queue_copies[1].tag,queue_source.data[0]);
$display("queue_array %0d %0d %0d",queue_targets[1][0][0],queue_targets[1][1][0],queue_array[5][0]);
$display("pattern %0d %0d",pattern_result[0][0],pattern_result[1][0]);
$display("argument %0d %0d",observed[0],observed[1]);
$display("blocking_grid %0d %0d %0d",blocking_grid[1][0],blocking_grid[1][1],blocking_grid[0][0]);
$display("batch %0d %0d %0d %0d",batch[1].words[2],batch[1].words[1],batch[0].tag,original[1].words[2]);
$display("static_return %0d %0d %0d",static_result.words[2],static_result.words[1],static_result.tag);
'''
    expected = ('orders 12 2 2 2\nrow 7 9 11 0\nmember 13 17 0\ngrid 19 23 0\n'
                'queue 1 7 5 123\nqueue_copy 1 31 37 88\nqueue_array 41 43 99\n'
                'pattern 41 47\nargument 53 47\nblocking_grid 19 23 0\nbatch 29 31 47 0\n'
                'static_return 59 61 67\n')
    return output(name, wrap(home, declarations, methods, issue, report), expected)


def files():
    result = {}
    for home in HOMES:
        for width in (1, 32, 65, 129):
            for domain in ('bit', 'logic'):
                result.update(case(home, width, domain))
        result.update(members(home))
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    bad = []
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                bad.append(name)
        else:
            path.write_text(text)
    if bad:
        print('gen_aggregate_nba_capture_matrix: out of date: ' + ', '.join(bad), file=sys.stderr)
    return int(bool(bad))


if __name__ == '__main__':
    sys.exit(main())
