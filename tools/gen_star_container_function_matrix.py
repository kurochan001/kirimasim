"""Original @* argument sensitivity and excluded container function-body reads."""
import argparse
from pathlib import Path
import sys

OUT = Path(__file__).resolve().parent.parent / 'tests/suite/sched'


def programs():
    for home in ('module', 'unit', 'package', 'interface', 'generate', 'class_static'):
        for container in ('queue', 'array'):
            for width in (1, 33, 65, 129):
                for nested in (False, True):
                    q = 'values::q' if home == 'package' else 'Sources::q' if home == 'class_static' else 'q'
                    call = 'values::' if home == 'package' else 'Sources::' if home == 'class_static' else ''
                    dims = '[$]' if container == 'queue' else '[]'
                    static = 'static ' if home == 'class_static' else ''
                    definitions = (f'{static}int q{dims};\n'
                                   f'{static}function int inner(input logic[{width-1}:0] n);\n'
                                   "return q.size() + ((n === '1) ? 10 : 0) + (q.size() ? q[0] : 0);\n"
                                   'endfunction\n')
                    if nested:
                        definitions += (f'{static}function int read_value(input logic[{width-1}:0] n);\n'
                                        'return inner(n);endfunction\n')
                    name = 'read_value' if nested else 'inner'
                    grow = (f'{q}.push_back(7);' if container == 'queue'
                            else f'{q}=new[1];{q}[0]=7;')
                    grow_again = (f'{q}.push_back(8);' if container == 'queue'
                                  else f'{q}=new[2]({q});{q}[1]=8;')
                    actor = (f"logic[{width-1}:0] input_value='0;int observed=-99,hits=0;\n"
                             f'always @* begin observed={call}{name}(input_value);++hits;end\n')
                    body = ('static int errors=0;\n'
                            f'#1;{grow}#1;if(observed!=-99 || hits!=0)++errors;\n'
                            "input_value='1;#1;if(observed!=18 || hits!=1)++errors;\n"
                            f'{grow_again}#1;if(observed!=18 || hits!=1)++errors;\n'
                            "input_value='0;#1;if(observed!=9 || hits!=2)++errors;\n"
                            f'{q}[0]=9;#1;if(observed!=9 || hits!=2)++errors;\n'
                            "input_value='x;#1;if(observed!=11 || hits!=3)++errors;\n"
                            "input_value='z;#1;if(observed!=11 || hits!=4)++errors;\n"
                            f'{q}.delete();#1;if(observed!=11 || hits!=4)++errors;\n'
                            "input_value='1;#1;if(observed!=10 || hits!=5)++errors;\n"
                            '$display("errors=%0d",errors);\n')
                    process = actor + 'initial begin\n' + body + 'end\n'
                    if home == 'unit':
                        source = definitions + 'module top;\n' + process + 'endmodule\n'
                    elif home == 'package':
                        source = 'package values;\n' + definitions + 'endpackage\nmodule top;\n' + process + 'endmodule\n'
                    elif home == 'class_static':
                        source = 'class Sources;\n' + definitions + 'endclass\nmodule top;\n' + process + 'endmodule\n'
                    elif home == 'interface':
                        source = 'interface worker;\n' + definitions + process + 'endinterface\nmodule top;worker u();endmodule\n'
                    else:
                        opening = 'if(1)begin:g\n' if home == 'generate' else ''
                        closing = 'end\n' if home == 'generate' else ''
                        source = 'module top;\n' + opening + definitions + process + closing + 'endmodule\n'
                    label = f'{home}_{container}_{width}_{"nested" if nested else "direct"}'
                    yield label, '`timescale 1ns/1ns\n' + source


def cases():
    for label, source in programs():
        name = 'star_container_function_' + label
        yield name, f'''/*
:name: {name}
:description: Wildcard procedures observe arguments without importing container function-body reads
:tags: sched arrays queue subroutine sensitivity
:type: simulation
:lrm: 1800-2023 9.2.2.2.2 9.4.2.2
:oracle: spec
:spec_check: ai
:fourstate: yes
:nondeterministic: no
:generator: gen_star_container_function_matrix.py@1
:top_module: top
:expected_stdout: errors=0
:timeout: 15
*/
// Generated by tools/gen_star_container_function_matrix.py; edit the generator.
{source}'''


def probes():
    for label, dims, grow in [('queue', '[$]', 'q.push_back(7);'), ('array', '[]', 'q=new[1];')]:
        yield ('star_container_function_' + label, '9.2.2.2.2; 9.4.2.2',
               f'module top;int q{dims};int input_value=0,observed=-99;'
               'function int read_value(input int n);return q.size()+n;endfunction '
               'always @* observed=read_value(input_value);initial begin #1;' + grow +
               '#1;$display("%0d",observed);input_value=1;#1;$display("%0d",observed);'
               'q.delete();#1;$display("%0d",observed);input_value=2;#1;$display("%0d",observed);'
               'end endmodule\n', '-99\n2\n2\n2\n', [])
    yield ('star_container_function_nested', '9.2.2.2.2; 9.4.2.2',
           'module top;int q[$];int input_value=0,observed=-99;'
           'function int inner(input int n);return q.size()+n;endfunction '
           'function int outer(input int n);return inner(n);endfunction '
           'always @* observed=outer(input_value);initial begin #1;q.push_back(7);input_value=1;'
           '#1;$display("%0d",observed);q.push_back(9);#1;$display("%0d",observed);'
           'input_value=2;#1;$display("%0d",observed);end endmodule\n', '2\n2\n4\n', [])
    yield ('star_container_function_no_arguments', '9.2.2.2.2; 9.4.2.2',
           'module top;int q[$];int observed=-99;function int read_value();return q.size();endfunction '
           'always @* observed=read_value();initial begin #1;q.push_back(7);#1;'
           '$display("%0d",observed);end endmodule\n', '-99\n', [])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    failed = False
    generated = dict(cases())
    for name, source in generated.items():
        path = OUT / (name + '.sv')
        if args.check:
            if not path.exists() or path.read_text() != source:
                print('out of date:', path.name)
                failed = True
        else:
            path.write_text(source)
    print(f'wildcard container function matrix: {len(generated)} sources')
    return int(failed)


if __name__ == '__main__':
    sys.exit(main())
