"""Generate original shared automatic-activation tests (6.21, 9.3.2, 13.5.2)."""

import argparse
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / 'tests/suite/sched'
VERSION = 1


def output(name, source, expected):
    name = 'automatic_capture_' + name
    header = f'''/*
:name: {name}
:description: Lexical automatic storage identity survives owner exit and source control flow
:tags: sched fork lifetime
:type: simulation
:lrm: 1800-2023 6.21 9.3.2 13.5.2
:fourstate: yes
:nondeterministic: no
:oracle: spec
:spec_check: ai
:generator: gen_automatic_capture_matrix.py@{VERSION}
:top_module: top
:expected_stdout: @{name}.expected
:expected_stderr: @{name}.stderr
*/
// Generated by tools/gen_automatic_capture_matrix.py (version {VERSION}); do not edit.
`timescale 1ns/1ns
'''
    return {name+'.sv': header+source+'\n', name+'.expected': expected, name+'.stderr': ''}


def wrap(home, declarations, body):
    if home == 'task':
        return f'module top;\n{declarations}\ntask automatic run();\n{body}\nendtask\ninitial begin run();#5;end\nendmodule'
    if home == 'package':
        return (f'package helper;\n{declarations}\ntask automatic run();\n{body}\nendtask\nendpackage\n'
                'module top;initial begin helper::run();#5;end endmodule')
    if home == 'interface':
        return (f'interface helper;\n{declarations}\ninitial begin\n{body}\n#5;end\nendinterface\n'
                'module top;helper h();endmodule')
    if home == 'program':
        return (f'program helper;\n{declarations}\ninitial begin\n{body}\n#5;end\nendprogram\n'
                'module top;helper h();endmodule')
    if home == 'generate':
        return f'module top;\n{declarations}\nif(1) begin: region\ninitial begin\n{body}\n#5;end\nend\nendmodule'
    return f'module top;\n{declarations}\ninitial begin\n{body}\n#5;end\nendmodule'


def sharing(home, state, width, join):
    name = f'{home}_{state}_{width}_{join}'
    before = "'0" if join == 'join_none' else "'1"
    body = f'''automatic word_t value='1;
fork
  begin #1;$display("first %0d",value === {before});value='0;end
  begin #3;$display("shared %0d",value === '0);end
{join}
'''
    if join == 'join_none':
        body += "value='0;\n"
    body += '$display("parent %0d",value === \'0);'
    expected = {'join': 'first 1\nshared 1\nparent 1\n',
                'join_any': 'first 1\nparent 1\nshared 1\n',
                'join_none': 'parent 1\nfirst 1\nshared 1\n'}[join]
    return output(name, wrap(home, f'typedef {state} [{width-1}:0] word_t;', body), expected)


def mechanisms():
    cases = {}
    def add(name, source, expected):
        cases.update(output(name, source, expected))
    for state in ('bit', 'logic'):
        for width in (1, 7, 65, 129):
            add(f'function_{state}_{width}', f'''module top;
function automatic int run();
  {state} [{width-1}:0] value='1;
  fork
    begin #1;$display("function %0d",value === '0);end
  join_none
  value='0;
  return value === '0;
endfunction
initial begin $display("return %0d",run());#3;end
endmodule''', 'return 1\nfunction 1\n')
    # Domains use their typed storage providers; equality prints avoid host formatting.
    domains = {
        'real': ('real value=1.5;', 'value == 1.5', 'value=2.5;', 'value == 2.5'),
        'shortreal': ('shortreal value=1.5;', 'value == 1.5', 'value=2.5;', 'value == 2.5'),
        'string': ('string value="before";', 'value == "before"', 'value="after";', 'value == "after"'),
        'chandle': ('chandle value=null;', 'value == null', 'value=null;', 'value == null'),
        'array': ('logic [128:0] value[-1:0];', "value[-1] === 'x", "value[-1]='z;value[0]='1;", "value[-1] === 'z && value[0] === '1"),
        'struct': ('record_t value;', "value.bits === 'x && value.text == \"\"", "value.bits='z;value.text=\"kept\";", "value.bits === 'z && value.text == \"kept\""),
        'queue': ('int value[$];', 'value.size()==0', 'value.push_back(7);', 'value.size()==1 && value[0]==7'),
        'dynamic': ('int value[];', 'value.size()==0', "value=new[2];value[1]=7;", 'value.size()==2 && value[1]==7'),
    }
    for domain, (declaration, before, store, after) in domains.items():
        for join in ('join', 'join_any', 'join_none'):
            source = f'''module top;
typedef struct {{logic [128:0] bits;string text;}} record_t;
task automatic run();
  {declaration}
  fork
    begin #1;$display("before %0d",{before});{store}end
    begin #3;$display("after %0d",{after});end
  {join}
endtask
initial begin run();#5;end
endmodule'''
            add(f'typed_{domain}_{join}', source, 'before 1\nafter 1\n')
    add('reentry_control', '''module top;
task automatic run();
  for(int i=0;i<4;i++) begin
    automatic int value=i;
    if(i==1) continue;
    if(i==3) break;
    fork begin #1;$display("entry %0d index %0d",value,i);end join_none
  end
  wait fork;
endtask
initial run();endmodule''', 'entry 0 index 3\nentry 2 index 3\n')
    add('fork_initializer_ref', '''module top;
int actual=7;
task automatic run(ref int value);
  fork
    automatic int snapshot=value;
    begin #1;$display("snapshot %0d",snapshot);snapshot=9;end
    begin #2;$display("sibling %0d",snapshot);end
  join_none
endtask
initial begin run(actual);actual=11;#4;$display("actual %0d",actual);end
endmodule''', 'snapshot 7\nsibling 9\nactual 11\n')
    add('nested_forwarding', '''module top;
task automatic run(input int seed);
  int value=seed;
  fork
    begin
      #1;
      fork begin #2;$display("grandchild %0d",value);end join_none
      value=value+1;
    end
  join_none
endtask
initial begin run(7);#5;end
endmodule''', 'grandchild 8\n')
    add('copyback_once', '''module top;
int result;
task automatic run(output int value);
  value=7;
  fork begin #1;value=9;$display("formal %0d",value);end join_none
endtask
initial begin run(result);$display("copyback %0d",result);#3;$display("caller %0d",result);end
endmodule''', 'copyback 7\nformal 9\ncaller 7\n')
    add('ref_join', '''module top;
task automatic run(ref logic [128:0] value);
  fork begin #1;value='z;end begin #2;$display("borrowed %0d",value === 'z);end join
endtask
initial begin automatic logic [128:0] actual='1;run(actual);$display("actual %0d",actual === 'z);end
endmodule''', 'borrowed 1\nactual 1\n')
    add('ref_static', '''module top;
int actual=7;
task automatic run(ref static int value);
  fork begin #1;value=9;end begin #2;$display("static %0d",value);end join_none
endtask
initial begin run(actual);#4;$display("actual %0d",actual);end
endmodule''', 'static 9\nactual 9\n')
    add('guard_and_replacement', '''module top;
task automatic run();
  int value=0;
  int data[$];
  fork
    begin wait(value==7);$display("guard %0d",value);end
    begin wait(data.size()==2);$display("replacement %0d",data[1]);end
    begin #1;value=7;#1;data='{3,9};end
  join_none
endtask
initial begin run();#5;end
endmodule''', 'guard 7\nreplacement 9\n')
    add('nested_named_disable', '''module top;
task automatic run();
  begin: outer
    int value=7;
    fork begin #1;$display("before %0d",value);#5;$display("late");end join_none
    #2;disable outer;
  end
  $display("resumed");
endtask
initial begin run();#8;end
endmodule''', 'before 7\nresumed\n')
    add('return_nested_scope', '''module top;
function automatic int run(input int seed);
  begin: body
    int value=seed;
    fork begin #1;$display("retained %0d",value);end join_none
    return value+1;
  end
endfunction
initial begin $display("returned %0d",run(7));#3;end
endmodule''', 'returned 8\nretained 7\n')
    add('distinct_calls', '''module top;
task automatic run(input int seed);
  int value=seed;
  fork begin #1;$display("call %0d",value);value++;end join_none
endtask
initial begin run(3);run(5);#3;end
endmodule''', 'call 3\ncall 5\n')
    return cases


def generated():
    cases = {}
    for home in ('initial', 'task', 'package', 'interface', 'generate', 'program'):
        for state in ('bit', 'logic'):
            for width in (1, 7, 65, 129):
                for join in ('join', 'join_any', 'join_none'):
                    cases.update(sharing(home, state, width, join))
    cases.update(mechanisms())
    return cases


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    cases = generated()
    stale = [name for name, text in cases.items() if not (OUT/name).exists() or (OUT/name).read_text() != text]
    if args.check:
        if stale:
            print('stale automatic capture files: ' + ', '.join(stale))
            return 1
    else:
        OUT.mkdir(parents=True, exist_ok=True)
        for name, text in cases.items():
            (OUT/name).write_text(text)
    print(f'automatic capture matrix: {len(cases)//3} original source designs')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
