"""The call of a base class's constructor, written and implied.

IEEE 1800-2023 8.7 and 8.17: a constructor that calls no super.new has the call
inserted for it, as has a class with no constructor. The implied call is
super.new(), where each argument takes its default value, evaluated at each call
that uses it (13.5.3); with the default keyword it is super.new(default), which
passes on the arguments the keyword expanded to (8.7). The base is constructed
first, then the properties of the class take their initial values, then the rest
of the constructor runs. Every expected result is computed here from these rules,
not from a run.
"""
import argparse
from pathlib import Path
from typing import NamedTuple

OUT = Path(__file__).resolve().parent.parent / 'tests/suite/proc'
PREFIX = 'class_base_construction_'
WIDE = (1 << 128) | 5


class Kind(NamedTuple):
    prelude: str
    prop: str
    formal: str
    store: str
    fmt: str
    show: str
    default: str
    written: str
    written_text: str


KINDS = {
    'int': Kind('', 'int v;', 'int x = 5', 'v = x;', '%0d', 'k.v', '5', '7', '7'),
    'wide': Kind('', 'logic [128:0] v;', f"logic [128:0] x = 129'h{WIDE:x}", 'v = x;', '%0h', 'k.v',
                 f'{WIDE:x}', "129'h3", '3'),
    'four_state': Kind('', 'logic [3:0] v;', "logic [3:0] x = 4'b1x0z", 'v = x;', '%b', 'k.v', '1x0z',
                       "4'bz01x", 'z01x'),
    'real': Kind('', 'real v;', 'real x = 2.5', 'v = x;', '%0.1f', 'k.v', '2.5', '3.5', '3.5'),
    'string': Kind('', 'string v;', 'string x = "dflt"', 'v = x;', '%s', 'k.v', 'dflt', '"mine"', 'mine'),
    'enum': Kind('typedef enum {RED, GREEN, BLUE} color_t;\n', 'color_t v;', 'color_t x = GREEN', 'v = x;',
                 '%0d', 'k.v', '1', 'BLUE', '2'),
    'struct': Kind('typedef struct {int a; int b;} pair_t;\n', 'int v;\nint w;', "pair_t x = '{1, 2}", 'v = x.a;\nw = x.b;',
                   '%0d %0d', 'k.v, k.w', '1 2', "'{3, 4}", '3 4'),
    'array': Kind('', 'int v[2];', "int x[2] = '{3, 4}", 'v[0] = x[0];\nv[1] = x[1];', '%0d %0d', 'k.v[0], k.v[1]', '3 4',
                  "'{5, 6}", '5 6'),
    'handle': Kind('class item; endclass\nfunction automatic item make_item(); make_item = new; endfunction\n',
                   'item v;', 'item x = null', 'v = x;', '%0d', 'k.v == null', '1', 'make_item()', '0'),
    'two': Kind('', 'int v;', 'int p = 1, int q = 2', 'v = p * 10 + q;', '%0d', 'k.v', '12', '3, 4', '34'),
}


def source(name, description, text, expected, lrm='8.7 8.17 13.5.3'):
    name = PREFIX + name
    return name, f'''/*
:name: {name}
:description: {description}
:tags: proc class
:type: simulation
:lrm: 1800-2023 {lrm}
:oracle: spec
:spec_check: ai
:fourstate: yes
:nondeterministic: no
:generator: gen_class_base_construction_matrix.py@1
:top_module: top
:expected_stdout: {expected}
:timeout: 15
*/
// Generated by tools/gen_class_base_construction_matrix.py; edit the generator.
`timescale 1ns/1ns
{text}'''


def base_of(kind):
    return f'{kind.prelude}class base;\n{kind.prop}\nfunction new({kind.formal});\n{kind.store}\nendfunction\nendclass\n'


def forms(kind):
    """How the derived class is written: its text, the arguments of new, whether they reach the base."""
    written = kind.written
    return {
        'no_constructor': ('class derived extends base;\nendclass\n', '', False),
        'empty_constructor': ('class derived extends base;\nfunction new();\nendfunction\nendclass\n', '', False),
        'body_constructor': ('class derived extends base;\nint own;\nfunction new();\nown = 1;\nendfunction\nendclass\n',
                             '', False),
        'own_argument': ('class derived extends base;\nint own;\nfunction new(int own_x);\nown = own_x;\nendfunction\nendclass\n',
                         '1', False),
        'explicit_super': ('class derived extends base;\nfunction new();\nsuper.new();\nendfunction\nendclass\n', '', False),
        'default_keyword_given': ('class derived extends base;\nfunction new(default);\nendfunction\nendclass\n', written, True),
        'default_keyword_none': ('class derived extends base;\nfunction new(default);\nendfunction\nendclass\n', '', False),
        'default_explicit': ('class derived extends base;\nfunction new(default);\nsuper.new(default);\nendfunction\nendclass\n',
                             written, True),
        'default_around': ('class derived extends base;\nint own;\nfunction new(int a, default, int b);\nown = a + b;\nendfunction\nendclass\n',
                           f'1, {written}, 2', True),
        'extends_default': ('class derived extends base(default);\nfunction new(default);\nendfunction\nendclass\n', written, True),
        'extends_written': (f'class derived extends base({written});\nendclass\n', '', True),
        'super_written': (f'class derived extends base;\nfunction new();\nsuper.new({written});\nendfunction\nendclass\n', '', True),
    }


def kinds_and_forms():
    for kind_name, kind in KINDS.items():
        for form_name, (derived, arguments, reaches) in forms(kind).items():
            text = (f'{base_of(kind)}{derived}module top;\nderived k;\ninitial begin\nk = new({arguments});\n'
                    f'$display("{kind.fmt}", {kind.show});\nend\nendmodule\n')
            yield source(f'{kind_name}_{form_name}', 'A base constructor gets the arguments the form of the class gives it',
                         text, kind.written_text if reaches else kind.default)


LEVEL_A = 'class a;\nint v;\nfunction new(int x = 5);\nv = x;\nendfunction\nendclass\n'


def levels():
    """Each class in a chain takes its implied call from its own base."""
    show = '$display("%0d", k.v);'
    for name, classes, top_class, arguments, display, expected in (
            ('two_with_no_constructor', 'class b extends a;\nendclass\nclass c extends b;\nendclass\n', 'c', '', show, '5'),
            ('three_with_no_constructor', 'class b extends a;\nendclass\nclass c extends b;\nendclass\nclass d extends c;\nendclass\n',
             'd', '', show, '5'),
            ('super_over_no_constructor', 'class b extends a;\nendclass\nclass c extends b;\nfunction new();\nsuper.new();\nendfunction\nendclass\n',
             'c', '', show, '5'),
            ('middle_passes_its_own', 'class b extends a;\nfunction new(int y = 6);\nsuper.new(y + 1);\nendfunction\nendclass\nclass c extends b;\nendclass\n',
             'c', '', show, '7'),
            ('middle_implied', 'class b extends a;\nint w;\nfunction new(int y = 6);\nw = y;\nendfunction\nendclass\nclass c extends b;\nendclass\n',
             'c', '', '$display("%0d %0d", k.v, k.w);', '5 6'),
            ('default_chain_given', 'class b extends a;\nfunction new(default);\nendfunction\nendclass\nclass c extends b;\nfunction new(default);\nendfunction\nendclass\n',
             'c', '8', show, '8'),
            ('default_chain_none', 'class b extends a;\nfunction new(default);\nendfunction\nendclass\nclass c extends b;\nfunction new(default);\nendfunction\nendclass\n',
             'c', '', show, '5')):
        text = f'{LEVEL_A}{classes}module top;\n{top_class} k;\ninitial begin\nk = new({arguments});\n{display}\nend\nendmodule\n'
        yield source(f'level_{name}', 'Each class in a chain takes its implied call from its own base', text, expected)
    # A parameter of the class in a default value.
    text = ('class p #(int N = 3);\nint v;\nfunction new(int x = N);\nv = x;\nendfunction\nendclass\n'
            'class q extends p #(4);\nendclass\nclass r extends p;\nfunction new();\nendfunction\nendclass\n'
            'module top;\nq m;\nr n;\ninitial begin\nm = new;\nn = new;\n$display("%0d %0d", m.v, n.v);\nend\nendmodule\n')
    yield source('level_parameter_in_default', 'A default value takes the parameter of the specialization', text, '4 3')


COUNTER = 'int count = 0;\nfunction automatic int next();\ncount++;\nreturn count;\nendfunction\n'
BASE_COUNTED = 'class a;\nint v;\nfunction new(int x = next());\nv = x;\nendfunction\nendclass\n'
TRACE = 'string trace = "";\nfunction automatic int note(string s, int v);\ntrace = {trace, s};\nreturn v;\nendfunction\n'
BASE_TRACED = ('class a;\nint p = note("i", 1);\nint v;\nfunction new(int x = note("d", 5));\nv = x;\n'
               'trace = {trace, "b"};\nendfunction\nendclass\n')


def effects():
    """A default value is evaluated at each call that uses it, and first of all."""
    run = 'module top;\nb k1, k2;\ninitial begin\nk1 = new;\nk2 = new;\n$display("%0d %0d %0d", k1.v, k2.v, count);\nend\nendmodule\n'
    yield source('effect_each_construction_no_constructor', 'A default value is evaluated at each construction',
                 f'{COUNTER}{BASE_COUNTED}class b extends a;\nendclass\n{run}', '1 2 2')
    yield source('effect_each_construction_constructor', 'A default value is evaluated at each construction',
                 f'{COUNTER}{BASE_COUNTED}class b extends a;\nfunction new();\nendfunction\nendclass\n{run}', '1 2 2')
    yield source('effect_not_used_extends', 'A default value not used is not evaluated',
                 f'{COUNTER}{BASE_COUNTED}class b extends a(9);\nendclass\n{run}', '9 9 0')
    yield source('effect_not_used_super', 'A default value not used is not evaluated',
                 f'{COUNTER}{BASE_COUNTED}class b extends a;\nfunction new();\nsuper.new(9);\nendfunction\nendclass\n{run}', '9 9 0')
    show = 'module top;\nb k;\ninitial begin\nk = new;\n$display("%s %0d %0d", trace, k.v, k.q);\nend\nendmodule\n'
    yield source('effect_order_no_constructor', 'The base is constructed before the properties of the class',
                 f'{TRACE}{BASE_TRACED}class b extends a;\nint q = note("j", 2);\nendclass\n{show}', 'dibj 5 2', '8.7 8.17')
    yield source('effect_order_constructor', 'The base is constructed before the properties and the body of the class',
                 f'{TRACE}{BASE_TRACED}class b extends a;\nint q = note("j", 2);\nfunction new();\ntrace = {{trace, "c"}};\nendfunction\nendclass\n{show}',
                 'dibjc 5 2', '8.7 8.17')


CLASSES = 'class a;\nint v;\nfunction new(int x = 5);\nv = x;\nendfunction\nendclass\n'
DERIVED = {
    'no_constructor': ('class b extends a;\nendclass\n', '', '5'),
    'empty_constructor': ('class b extends a;\nfunction new();\nendfunction\nendclass\n', '', '5'),
    'default_keyword': ('class b extends a;\nfunction new(default);\nendfunction\nendclass\n', '7', '7'),
}


def places():
    """The container does not change the call."""
    for name, (derived, arguments, expected) in DERIVED.items():
        classes = CLASSES + derived
        make = f'k = new({arguments});\n$display("%0d", k.v);\n'
        for place, text in (
                ('task', f'{classes}module top;\ntask automatic run();\nb k;\n{make}endtask\ninitial run();\nendmodule\n'),
                ('function', f'{classes}module top;\nfunction automatic void run();\nb k;\n{make}endfunction\ninitial run();\nendmodule\n'),
                ('fork', f'{classes}module top;\nb k;\ninitial begin\nfork\nbegin\n{make}end\njoin\nend\nendmodule\n'),
                ('generate', f'{classes}module top;\nif (1) begin : g\nb k;\ninitial begin\n{make}end\nend\nendmodule\n'),
                ('interface', f'{classes}interface unit;\nb k;\ninitial begin\n{make}end\nendinterface\nmodule top;\nunit u();\nendmodule\n'),
                ('program', f'{classes}program automatic worker;\nb k;\ninitial begin\n{make}end\nendprogram\nmodule top;\nworker u();\nendmodule\n'),
                ('method', f'{classes}class maker;\nfunction void run();\nb k;\n{make}endfunction\nendclass\nmodule top;\nmaker m;\ninitial begin\nm = new;\nm.run();\nend\nendmodule\n'),
                ('declared_in_module', f'module top;\n{classes}b k;\ninitial begin\n{make}end\nendmodule\n'),
                ('declared_in_package', f'package pkg;\n{classes}endpackage\nmodule top;\nimport pkg::*;\nb k;\ninitial begin\n{make}end\nendmodule\n'),
                ('static_initial', f'{classes}module top;\nb k = new({arguments});\ninitial $display("%0d", k.v);\nendmodule\n'),
                ('property_initial', f'{classes}class holder;\nb k = new({arguments});\nendclass\nmodule top;\nholder h;\ninitial begin\nh = new;\n$display("%0d", h.k.v);\nend\nendmodule\n')):
            yield source(f'place_{name}_{place}', 'The container does not change the call of a base constructor', text, expected)


def illegal():
    """A base constructor with an argument of no default value needs that argument written (8.7)."""
    text = 'class a;\nfunction new(int x);\nendfunction\nendclass\nclass b extends a;{body}\nendclass\nmodule top;\nb k;\nendmodule\n'
    for name, body in (('no_constructor', ''), ('empty_constructor', '\nfunction new();\nendfunction')):
        yield 'illegal_' + PREFIX + name, text.replace('{body}', body)


def illegal_source(name, text):
    head = f'''/*
:name: {name}
:description: illegal: a base constructor with an argument of no default value is not called
:tags: illegal class
:type: elaboration
:lrm: 1800-2023 8.7 8.17
:oracle: spec
:spec_check: ai
:fourstate: no
:nondeterministic: no
:generator: gen_class_base_construction_matrix.py@1
:should_fail_because: a base constructor with an argument of no default value is not called
:expected_error: @LINE@:9: error: class 'b' must provide arguments for constructing base class 'a' via 'super.new' or the 'extends' clause
*/
// Generated by tools/gen_class_base_construction_matrix.py; edit the generator.
'''
    line = (head + text).splitlines().index('class b extends a;') + 1
    return head.replace('@LINE@', str(line)) + text


def cases():
    yield from kinds_and_forms()
    yield from levels()
    yield from effects()
    yield from places()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = {OUT / (name + '.sv'): text for name, text in cases()}
    count = len(generated)
    generated.update({OUT / (name + '.sv'): illegal_source(name, text) for name, text in illegal()})
    failed = False
    for path, text in generated.items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                print(f'out of date: {path.relative_to(OUT.parent.parent.parent)}')
                failed = True
        else:
            path.write_text(text)
    print(f'class base construction matrix: {count} sources, {len(generated) - count} illegal')
    return int(failed)


if __name__ == '__main__':
    raise SystemExit(main())
