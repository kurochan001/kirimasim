"""Generates the matrix test of array input arguments evaluated once, of
TEST_SUITE.md ("Mechanism matrix"), in tests/suite/proc/.

  tools/gen_array_argument_matrix.py           # writes the files
  tools/gen_array_argument_matrix.py --check   # exit 1 if a file differs from what it would write

An input argument is evaluated once, when the subroutine is called, and
its value copied into the formal (4.9.7, 13.5.1, SIR_SPEC.md 8): a
function written once in the actual is called once. A fixed-size
unpacked array argument is copied element by element.

The axes: the actual (an element of a function's two-dimensional value,
at both indices; a function's whole value; an assignment pattern whose
elements call a function; an element of a module variable; an element
of an automatic variable); the subroutine called (a function and a
task); the container (an initial procedure, an automatic task, a
function, which calls no task (13.4), and a fork branch). Each line
shows the sum of the formal's elements and how many times a function of
the actual ran.

The expected outputs follow from the rules above, computed below. A
person checks them once for all the tests made from them (TEST_SUITE.md,
"Sampling by people").
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "proc"
NAME = "array_argument_matrix"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1


def mat(i, j):
    """The elements of g()'s value, and of the variables set like it."""
    return i * 10 + j


# (name, the actual, its sum, how many times a function runs)
ACTUALS = [
    ("call_element1", "g()[1]", sum(mat(1, j) for j in range(3)), 1),
    ("call_element0", "g()[0]", sum(mat(0, j) for j in range(3)), 1),
    ("call_whole", "h()", 1 + 2 + 3, 1),
    ("pattern_calls", "'{one(), one(), one()}", 3, 3),
    ("module_element", "mv[1]", sum(mat(1, j) for j in range(3)), 0),
    ("automatic_element", "am[1]", sum(mat(1, j) for j in range(3)), 0),
]
CALLEES = ["function", "task"]
CONTAINERS = ["initial", "task", "function", "fork"]


def statement(callee, actual, tag):
    if callee == "function":
        return f'calls = 0; s = sumf({actual}); $display("{tag} sum=%0d calls=%0d", s, calls);'
    return f'calls = 0; sumt({actual}, s); $display("{tag} sum=%0d calls=%0d", s, calls);'


def files():
    lines, exp = {c: [] for c in CONTAINERS}, {c: [] for c in CONTAINERS}
    for container in CONTAINERS:
        for callee in CALLEES:
            if container == "function" and callee == "task":
                continue
            for name, actual, total, calls in ACTUALS:
                tag = f"{container} {callee} {name}"
                lines[container].append(statement(callee, actual, tag))
                exp[container].append(f"{tag} sum={total} calls={calls}")
    setup = ["automatic mat_t am;", "int s;", "foreach (am[i, j]) am[i][j] = i * 10 + j;"]
    head = [
        "/*",
        f":name: {NAME}",
        ":description: an array input argument is evaluated once: an element of a function's "
        "value, a function's whole value, an assignment pattern of calls, elements of a module "
        "and of an automatic variable, passed to a function and a task from an initial "
        "procedure, an automatic task, a function and a fork branch",
        ":tags: proc arguments",
        ":type: simulation",
        ":lrm: 1800-2023 13.5.1 4.9.7",
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: no",
        ":nondeterministic: no",
        f":generator: gen_array_argument_matrix.py@{VERSION}",
        ":top_module: top",
        f":expected_stdout: @{NAME}.expected",
        "*/",
        "// Generated by tools/gen_array_argument_matrix.py; change the generator, not this file.",
        "`timescale 1ns/1ns",
        "module top;",
        "  typedef int row_t [0:2];",
        "  typedef int mat_t [0:1][0:2];",
        "  int calls;",
        "  mat_t mv;",
        "  function automatic mat_t g();",
        "    mat_t m;",
        "    calls++;",
        "    foreach (m[i, j]) m[i][j] = i * 10 + j;",
        "    return m;",
        "  endfunction",
        "  function automatic row_t h();",
        "    calls++;",
        "    return '{1, 2, 3};",
        "  endfunction",
        "  function automatic int one();",
        "    calls++;",
        "    return 1;",
        "  endfunction",
        "  function automatic int sumf(row_t r);",
        "    int t = 0;",
        "    foreach (r[k]) t += r[k];",
        "    return t;",
        "  endfunction",
        "  task automatic sumt(input row_t r, output int t);",
        "    t = 0;",
        "    foreach (r[k]) t += r[k];",
        "  endtask",
        "  task automatic in_task();",
    ]
    body = (head + ["    " + x for x in setup + lines["task"]]
            + ["  endtask", "  function automatic void in_function();"]
            + ["    " + x for x in setup + lines["function"]] + ["  endfunction", "  initial begin"]
            + ["    " + x for x in setup]
            + ["    foreach (mv[i, j]) mv[i][j] = i * 10 + j;"]
            + ["    " + x for x in lines["initial"]]
            + ["    in_task();", "    in_function();", "    fork", "      begin"]
            + ["        " + x for x in setup + lines["fork"]]
            + ["      end", "    join", "  end", "endmodule", ""])
    order = exp["initial"] + exp["task"] + exp["function"] + exp["fork"]
    return {f"{NAME}.sv": "\n".join(body), f"{NAME}.expected": "\n".join(order) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_array_argument_matrix: {path.relative_to(OUT.parent.parent.parent)} "
                      "is out of date; run tools/gen_array_argument_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
