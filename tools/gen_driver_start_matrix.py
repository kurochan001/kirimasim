"""Generates the driver start matrix test of TEST_SUITE.md ("Mechanism matrix")
in tests/suite/nets/.

  tools/gen_driver_start_matrix.py           # writes the files
  tools/gen_driver_start_matrix.py --check   # exit 1 if a file differs from what it would write

Until a driver first writes, it drives x on the bits it writes and
nothing on the others (VALUE_SEMANTICS.md 5.3, SIR_SPEC.md 3.5). The
axes: the delayed driver (a continuous assignment, a net declaration
assignment, a gate, a UDP, a port of a child module), the bits it drives
(all of a net, a part of a vector net whose other bits nothing drives),
and what else drives the net (nothing, a weaker driver without a delay,
a pullup, the pull of tri0); a net nothing drives and a variable are
read beside them. Every driver's first write comes 3 steps after time 0,
and the lines are read half a step apart from time 0.

The expected outputs follow from the rule above and the resolution of
VALUE_SEMANTICS.md 5.4 (the rule of gen_resolution_matrix.py), written
without reading kirimasim's code. A person checks them once for all the
tests made from them (TEST_SUITE.md, "Sampling by people").
"""

import argparse
import sys
from pathlib import Path

from gen_resolution_matrix import resolve, value_of

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "nets"
NAME = "net_driver_start"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

DELAY = 3  # every delayed driver's first write
END = 5


def net(kind, drivers):
    """A net of one bit: (value, s1, s0) drivers resolved (5.4)."""
    return value_of(resolve(kind, drivers))


def at(t, before, after):
    return before if t < DELAY else after


# Rows: (label, declarations, expression read, value at time t). The input
# a is 1 from time 0.
ROWS = [
    ("assign", "  wire n1;\n  assign #3 n1 = a;\n", "n1", lambda t: at(t, "x", "1")),
    ("declaration", "  wire #3 n2 = a;\n", "n2", lambda t: at(t, "x", "1")),
    ("gate", "  wire n3;\n  buf #(3) g (n3, a);\n", "n3", lambda t: at(t, "x", "1")),
    ("udp", "  wire n4;\n  ubuf #(3) u (n4, a);\n", "n4", lambda t: at(t, "x", "1")),
    ("port", "  wire n5;\n  child c (n5, a);\n", "n5", lambda t: at(t, "x", "1")),
    # A part: the bits nothing drives stay z.
    ("part", "  wire [3:0] n6;\n  assign #3 n6[1:0] = {a, 1'b0};\n", "n6",
     lambda t: at(t, "zzxx", "zz10")),
    # A weak 0 without a delay against a strong driver's x, then its 1.
    ("against weak", "  wire n7;\n  assign (weak1, weak0) n7 = 1'b0;\n  assign #3 n7 = a;\n", "n7",
     lambda t: at(t, net("wire", [("0", 3, 3), ("x", 6, 6)]), net("wire", [("0", 3, 3), ("1", 6, 6)]))),
    ("pullup", "  wire n8;\n  pullup (n8);\n  assign #3 n8 = ~a;\n", "n8",
     lambda t: at(t, net("wire", [("1", 5, 5), ("x", 6, 6)]), net("wire", [("1", 5, 5), ("0", 6, 6)]))),
    ("tri0", "  tri0 n9;\n  assign #3 n9 = a;\n", "n9",
     lambda t: at(t, net("tri0", [("x", 6, 6)]), net("tri0", [("1", 6, 6)]))),
    ("undriven", "  wire n10;\n", "n10", lambda t: "z"),
    ("variable", "  logic n11;\n  assign #3 n11 = a;\n", "n11", lambda t: at(t, "x", "1")),
]


def files():
    sv = (f"/*\n:name: {NAME}\n:description: Until a driver first writes, it drives x on the bits it "
          "writes and nothing on the others: continuous assignments, net declaration assignments, "
          "gates, UDPs and ports with a delay, alone and with other drivers\n:tags: nets\n"
          ":type: simulation\n:lrm: 1800-2023 6.6 6.7.1 10.3.3 28.16 28.12\n"
          ":oracle: spec iverilog@13.0\n:spec_check: ai\n:fourstate: yes\n:nondeterministic: no\n"
          f":generator: gen_driver_start_matrix.py@{VERSION}\n"
          f":expected_stdout: @{NAME}.expected\n*/\n"
          "// Generated by tools/gen_driver_start_matrix.py; change the generator, not this file.\n"
          "`timescale 1ns/100ps\n"
          "primitive ubuf (y, a);\n  output y;\n  input a;\n  table\n    0 : 0;\n    1 : 1;\n"
          "  endtable\nendprimitive\n"
          "module child(output y, input i);\n  assign #3 y = i;\nendmodule\n"
          "module top;\n  logic a = 1'b1;\n")
    for _, decl, _, _ in ROWS:
        sv += decl
    fmt = " ".join(f"{label.replace(' ', '_')}=%b" for label, _, _, _ in ROWS)
    args = ", ".join(expr for _, _, expr, _ in ROWS)
    sv += (f"  initial begin\n    #0.5;\n    for (int k = 0; k <= {END}; k++) begin\n"
           f"      $display(\"%0d.5 {fmt}\", k, {args});\n      #1;\n    end\n  end\nendmodule\n")
    exp = ""
    for t in range(END + 1):
        exp += f"{t}.5 " + " ".join(f"{label.replace(' ', '_')}={fn(t)}"
                                    for label, _, _, fn in ROWS) + "\n"
    return {f"{NAME}.sv": sv, f"{NAME}.expected": exp}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_driver_start_matrix: {path.relative_to(OUT.parent.parent.parent)} is "
                      "out of date; run tools/gen_driver_start_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
