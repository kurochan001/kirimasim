#!/usr/bin/env python3
"""Generates the matrix tests of calls nested deep, of TEST_SUITE.md
("Mechanism matrix"), in tests/suite/proc/.

  tools/gen_call_depth_matrix.py           # writes the files
  tools/gen_call_depth_matrix.py --check   # exit 1 if a file differs from what it would write

The recursion of automatic subroutines is decided at run time (13.3.1,
13.4.2). Tier 1 lets the calls of one process nest 10000 deep, the calls
of tasks that wait and the others together; one more is a run-time error
of the design at the call: one error line, exit code 2, and final runs
(SCHEDULER_SPEC.md 16.2). The output written before it is kept. The
driver gives the simulation a stack that holds 10000 (RUNTIME_ABI.md 5).

The axes: the subroutine (a function that calls itself, two functions
that call each other, a task that does not wait, a task that waits at the
bottom of its recursion, and a function that calls itself without end);
the place of the first call (an initial procedure, a fork branch, a
package's subroutine called from an initial procedure, a continuous
assignment and a static variable's initializer; tasks only where a
statement can call them); the depth (n = 9999, which nests 10000 calls,
and n = 10000, which needs one more). One file each, since an error ends
the run. The error line of a package's subroutine is not compared, as
SYSTEM_TASKS.md 3.8 does not say yet how a package's name is written.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "proc"
PREFIX = "call_depth_"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1
LIMIT = 10000
ERROR = f"calls nested more than {LIMIT} deep"

# (name, the subroutines with ERR on the line of the call that goes one
# deeper, or ERR_EVEN/ERR_ODD for the two functions, whether it is a task,
# the expression or statement that calls it with {n} and {p} for the
# package prefix, whether it ends)
KINDS = {
    "function": ([
        "function automatic int depth(input int n);",
        "  return n == 0 ? 0 : 1 + depth(n - 1); // ERR",
        "endfunction",
    ], False, "{p}depth({n})", True),
    "mutual": ([
        "function automatic int even(input int n);",
        "  return n == 0 ? 0 : 1 + odd(n - 1); // ERR_EVEN",
        "endfunction",
        "function automatic int odd(input int n);",
        "  return n == 0 ? 0 : 1 + even(n - 1); // ERR_ODD",
        "endfunction",
    ], False, "{p}even({n})", True),
    "task": ([
        "task automatic depth(input int n, output int r);",
        "  if (n == 0) r = 0;",
        "  else begin",
        "    depth(n - 1, r); // ERR",
        "    r = r + 1;",
        "  end",
        "endtask",
    ], True, "{p}depth({n}, r)", True),
    "task_wait": ([
        "task automatic depth(input int n, output int r);",
        "  if (n == 0) #1 r = 0;",
        "  else begin",
        "    depth(n - 1, r); // ERR",
        "    r = r + 1;",
        "  end",
        "endtask",
    ], True, "{p}depth({n}, r)", True),
    "endless": ([
        "function automatic int depth(input int n);",
        "  return depth(n + 1); // ERR",
        "endfunction",
    ], False, "{p}depth({n})", False),
}

PLACES = ["initial", "fork", "package", "assign", "static_init"]


def header(name, over, compared):
    lines = [
        "/*",
        f":name: {name}",
        ":description: the calls of one process may nest 10000 deep; one more is a run-time "
        "error of the design at the call, and final runs",
        ":tags: proc subroutine",
        ":type: simulation",
        ":lrm: 1800-2023 13.3.1 13.4.2",
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: no",
        ":nondeterministic: no",
        f":generator: gen_call_depth_matrix.py@{VERSION}",
        ":issue: 6",
        ":top_module: top",
        f":expected_stdout: @{name}.expected",
    ]
    if over:
        lines.append(":expected_exit: 2")
        if compared:
            lines.append(f":expected_stderr: @{name}.stderr")
    return lines + ["*/",
                    "// Generated by tools/gen_call_depth_matrix.py; change the generator, not "
                    "this file."]


def one(kind, place, n):
    subs, task, call, ends = KINDS[kind]
    over = n >= LIMIT or not ends
    name = f"{PREFIX}{kind}_{place}_{'over' if over else 'fits'}"
    in_package = place == "package"
    call = call.format(n=n, p="p::" if in_package else "")
    # The function that makes the call one deeper than the limit: with two,
    # the 10000th call is to even when 10000 is odd.
    err_tag = "ERR"
    if kind == "mutual":
        err_tag = "ERR_EVEN" if LIMIT % 2 == 1 else "ERR_ODD"
    lines = header(name, over, not in_package)
    body = [f"  {x}" for x in subs]
    if in_package:
        lines += ["package p;"] + body + ["endpackage"]
    lines.append("module top;")
    if not in_package:
        lines += body
    if task:
        lines.append("  int r;")
    printed = "r" if task else call
    out = []
    if place in ("initial", "fork", "package"):
        lines += ["  initial begin", '    $display("started");']
        out.append("started")
        stmt = (f"{call};" if task else "") + f' $display("depth=%0d", {printed});'
        stmt = stmt.strip()
        if place == "fork":
            lines += ["    fork", f"      begin {stmt} end", "    join"]
        else:
            lines += [f"    {stmt}"]
        lines += ["  end"]
    elif place == "assign":
        lines += ["  wire [31:0] w;", f"  assign w = {call};",
                  '  initial #1 $display("depth=%0d", w);']
    else:
        lines += [f"  int x = {call};", '  initial $display("depth=%0d", x);']
    lines += ['  final $display("final ran");', "endmodule", ""]
    err = None
    for number, line in enumerate(lines, 1):
        if f"// {err_tag}" in line:
            err = number
    lines = [line.split(" // ERR")[0] for line in lines]
    if not over:
        out.append(f"depth={n}")
    out.append("final ran")
    files = {f"{name}.sv": "\n".join(lines), f"{name}.expected": "\n".join(out) + "\n"}
    if over and not in_package:
        files[f"{name}.stderr"] = f"{name}.sv:{err}: error: {ERROR} [top @ 0ns]\n"
    return files


def files():
    out = {}
    for kind, (_, task, _, ends) in KINDS.items():
        for place in PLACES:
            if task and place in ("assign", "static_init"):
                continue  # a task is called by a statement
            if kind == "mutual" and place not in ("initial", "static_init"):
                continue
            if not ends and place != "initial":
                continue
            for n in ((LIMIT - 1, LIMIT) if ends else (0,)):
                out.update(one(kind, place, n))
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_call_depth_matrix: {path.relative_to(OUT.parent.parent.parent)} is "
                      "out of date; run tools/gen_call_depth_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
