#!/usr/bin/env python3
"""Generates the matrix test of descriptors that name no open file
(TEST_SUITE.md, "Mechanism matrix") in tests/suite/proc/.

  tools/gen_file_not_open_matrix.py           # writes the files
  tools/gen_file_not_open_matrix.py --check   # exit 1 if a file differs from what it would write

The rules (SYSTEM_TASKS.md 6.1, UNSPECIFIED_BEHAVIOR.md P6 and 4): a
descriptor with x or z bits, an fd that is not open and a bit of an mcd
whose file is not open name no open file. A task given one does nothing
there and gives a run-time warning, once for each place; the warning of
an output task adds that nothing is written there. $fopen with a type
not in Table 21-6 returns 0 with a warning; one that cannot open its
file returns 0 with no message.

The axes: the descriptor (an fd that was closed, an fd never opened, x,
an mcd bit never opened, 0) and the task ($fdisplay, $fwrite, $fstrobe,
$fmonitor, $fclose, $fflush, $fgets). Each call runs twice, from one
place. :expected_stderr: holds the warnings in the order they come.

The expected outputs follow from the rules above, without reading
kirimasim's code.
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "proc"
NAME = "file_not_open"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

# (the descriptor as written, what a warning says of it)
DESCRIPTORS = [
    ("fc", "file descriptor 32'h80000003 names a file that is not open"),
    ("32'h8000_0009", "file descriptor 32'h80000009 names a file that is not open"),
    ("dx", "the descriptor has x or z bits"),
    ("32'h4", "multichannel descriptor 32'h00000004 names a file that is not open"),
    ("0", "multichannel descriptor 32'h00000000 names a file that is not open"),
]
# (the call with D for the descriptor, whether it is an output task)
TASKS = [
    ('$fdisplay(D, "x");', True),
    ('$fwrite(D, "x\\n");', True),
    ('$fstrobe(D, "x");', True),
    ('$fmonitor(D, "x");', True),
    ("$fclose(D);", False),
    ("$fflush(D);", False),
    ("n = $fgets(line, D);", False),
]


def files():
    lines = ["/*", f":name: {NAME}",
             ":description: every file task given a descriptor that names no open file does "
             "nothing there, with one run-time warning for each place; $fopen with a bad type "
             "warns, and one that cannot open is silent",
             ":tags: proc", ":type: simulation", ":lrm: 1800-2023 21.3.1 21.3.2 21.3.4.2",
             ":oracle: spec", ":spec_check: ai", ":fourstate: yes", ":nondeterministic: no",
             f":generator: gen_file_not_open_matrix.py@{VERSION}", ":top_module: top",
             f":expected_stdout: @{NAME}.expected", f":expected_stderr: @{NAME}.stderr", "*/",
             "// Generated by tools/gen_file_not_open_matrix.py; change the generator, not this "
             "file.",
             "`timescale 1ns/1ns", "module top;", "  integer fc, dx, n, f, g;", "  string line;",
             "  initial begin", '    fc = $fopen("closed.txt", "w");', "    $fclose(fc);",
             '    line = "kept";']
    err = []
    for desc, what in DESCRIPTORS:
        for call, output in TASKS:
            text = call.replace("D", desc)
            lines.append(f"    repeat (2) {text}")
            column = lines[-1].index("$") + 1
            task = text[text.index("$"):text.index("(")]
            err.append(f"{NAME}.sv:{len(lines)}:{column}: warning: {task}: {what}"
                       + ("; nothing is written there" if output else ""))
    lines.append('    $display("n=%0d line=%s", n, line);')
    lines.append('    f = $fopen("bad.txt", "rw");')
    err.append(f"{NAME}.sv:{len(lines)}:9: warning: $fopen: \"rw\" is not a type of Table 21-6; "
               "nothing is opened")
    lines += ['    g = $fopen("no/such/dir.txt", "w");',
              '    $display("bad type %0d, cannot open %0d %0d", f, g, $fopen("no/such/dir.txt"));',
              "  end", "endmodule"]
    return {f"{NAME}.sv": "\n".join(lines) + "\n",
            f"{NAME}.expected": "n=0 line=kept\nbad type 0, cannot open 0 0\n",
            f"{NAME}.stderr": "\n".join(err) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_file_not_open_matrix: {path.relative_to(OUT.parent.parent.parent)} is "
                      "out of date; run tools/gen_file_not_open_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
