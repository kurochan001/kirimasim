#!/usr/bin/env python3
"""Generates the matrix test of descriptors that name no open file
(TEST_SUITE.md, "Mechanism matrix") in tests/suite/proc/.

  tools/gen_file_not_open_matrix.py           # writes the files
  tools/gen_file_not_open_matrix.py --check   # exit 1 if a file differs from what it would write

The rules (SYSTEM_TASKS.md 6.1, 6.3, 6.4, UNSPECIFIED_BEHAVIOR.md P6 and
4): a descriptor with x or z bits, an fd that is not open and a bit of an
mcd whose file is not open name no open file. A task given one does
nothing there and gives a run-time warning, once for each place; the
warning of an output task adds that nothing is written there. Input takes
an fd, so for it any mcd is one, and its warning says so. An input
function returns its error value: -1 for $fgetc, $ungetc, $fscanf,
$ftell, $fseek and $rewind, 0 for $fgets, $fread and $feof; $ferror gives
an error number that is not 0, with no warning. $fopen with a type not in
Table 21-6 returns 0 with a warning; one that cannot open its file
returns 0 with no message.

The axes: the descriptor (an fd that was closed, an fd never opened, x,
an mcd bit never opened, 0) and the task ($fdisplay, $fwrite, $fstrobe,
$fmonitor, $fclose, $fflush, and the input functions $fgets, $fgetc,
$ungetc, $fscanf, $fread, $ftell, $fseek, $rewind, $feof). Each call runs
twice, from one place. :expected_stderr: holds the warnings in the order
they come.

The expected outputs follow from the rules above, without reading
kirimasim's code.
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "proc"
NAME = "file_not_open"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 2

# (the descriptor as written, what a warning says of it, and what one of
# input says)
INPUT_MCD = " is not a file descriptor, which input takes"
DESCRIPTORS = [
    ("fc", "file descriptor 32'h80000003 names a file that is not open", None),
    ("32'h8000_0009", "file descriptor 32'h80000009 names a file that is not open", None),
    ("dx", "the descriptor has x or z bits", None),
    ("32'h4", "multichannel descriptor 32'h00000004 names a file that is not open",
     "multichannel descriptor 32'h00000004" + INPUT_MCD),
    ("0", "multichannel descriptor 32'h00000000 names a file that is not open",
     "multichannel descriptor 32'h00000000" + INPUT_MCD),
]
# (the call with D for the descriptor, its kind: output, other or input)
TASKS = [
    ('$fdisplay(D, "x");', "output"),
    ('$fwrite(D, "x\\n");', "output"),
    ('$fstrobe(D, "x");', "output"),
    ('$fmonitor(D, "x");', "output"),
    ("$fclose(D);", "other"),
    ("$fflush(D);", "other"),
    ("n = $fgets(line, D);", "input"),
    ("c = $fgetc(D);", "input"),
    ("u = $ungetc(65, D);", "input"),
    ('s = $fscanf(D, "%d", v);', "input"),
    ("r = $fread(v, D);", "input"),
    ("t = $ftell(D);", "input"),
    ("k = $fseek(D, 0, 0);", "input"),
    ("w = $rewind(D);", "input"),
    ("e = $feof(D);", "input"),
]
# What the input functions return then, in the order of the line printed
# after each descriptor; $ferror gives a number that is not 0.
RESULTS = "n=0 c=-1 u=-1 s=-1 r=0 t=-1 k=-1 w=-1 e=0 error=1 v=7"


def files():
    lines = ["/*", f":name: {NAME}",
             ":description: every file task given a descriptor that names no open file does "
             "nothing there, with one run-time warning for each place; $fopen with a bad type "
             "warns, and one that cannot open is silent",
             ":tags: proc", ":type: simulation", ":lrm: 1800-2023 21.3.1 21.3.2 21.3.4.2",
             ":oracle: spec", ":spec_check: ai", ":fourstate: yes", ":nondeterministic: no",
             f":generator: gen_file_not_open_matrix.py@{VERSION}", ":top_module: top",
             f":expected_stdout: @{NAME}.expected", f":expected_stderr: @{NAME}.stderr", "*/",
             "// Generated by tools/gen_file_not_open_matrix.py; change the generator, not this "
             "file.",
             "`timescale 1ns/1ns", "module top;",
             "  integer fc, dx, n, f, g, c, u, s, r, t, k, w, e, v;", "  string line, why;",
             "  initial begin", '    fc = $fopen("closed.txt", "w");', "    $fclose(fc);",
             '    line = "kept";', "    v = 7;"]
    err = []
    expected = []
    for desc, what, what_in in DESCRIPTORS:
        for call, kind in TASKS:
            text = call.replace("D", desc)
            lines.append(f"    repeat (2) {text}")
            column = lines[-1].index("$") + 1
            task = text[text.index("$"):text.index("(")]
            said = what_in if kind == "input" and what_in else what
            err.append(f"{NAME}.sv:{len(lines)}:{column}: warning: {task}: {said}"
                       + ("; nothing is written there" if kind == "output" else ""))
        lines.append(f'    $display("{desc}: n=%0d c=%0d u=%0d s=%0d r=%0d t=%0d k=%0d w=%0d '
                     f'e=%0d error=%0d v=%0d", n, c, u, s, r, t, k, w, e, $ferror({desc}, why) '
                     "!= 0, v);")
        expected.append(f"{desc}: {RESULTS}")
    lines.append('    $display("n=%0d line=%s", n, line);')
    lines.append('    f = $fopen("bad.txt", "rw");')
    err.append(f"{NAME}.sv:{len(lines)}:9: warning: $fopen: \"rw\" is not a type of Table 21-6; "
               "nothing is opened")
    lines += ['    g = $fopen("no/such/dir.txt", "w");',
              '    $display("bad type %0d, cannot open %0d %0d", f, g, $fopen("no/such/dir.txt"));',
              "  end", "endmodule"]
    return {f"{NAME}.sv": "\n".join(lines) + "\n",
            f"{NAME}.expected": "\n".join(expected) +
                                "\nn=0 line=kept\nbad type 0, cannot open 0 0\n",
            f"{NAME}.stderr": "\n".join(err) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_file_not_open_matrix: {path.relative_to(OUT.parent.parent.parent)} is "
                      "out of date; run tools/gen_file_not_open_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
