"""Generates the matrix test of assignments to a packed part of an element
of a queue or dynamic array (TEST_SUITE.md, "Mechanism matrix") in
tests/suite/containers/.

  tools/gen_container_packed_select_matrix.py           # writes the files
  tools/gen_container_packed_select_matrix.py --check   # exit 1 if a file differs from what it would write

The rule: 7.4.5 and 11.5.1 of the standard with 11.8.1: a select of a
packed element is a place of that many bits, unsigned whatever the
element's type, and the home of the element (a fixed array, a queue or a
dynamic array) does not change what the assignment does. The axes: the
home; the sign and the state of the packed element type (4 parts of 8
bits); the place selected (a part by a constant index, by a variable
index, a part select of a part, and a bit of a part); the assignment (=
and the compound += and -=); and the container of the statement (a
module's initial and an automatic task).

The expected output comes from the model below, which keeps the element
as 32 bits. A person checks it once for all the tests made from it
(TEST_SUITE.md, "Sampling by people").
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "containers"
NAME = "packed_select_of_element_matrix"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

HOMES = [("fixed", "[1]", []), ("queue", "[$]", ["V.push_back('0);"]),
         ("dynamic", "[]", ["V = new[1];", "V[0] = '0;"])]
TYPES = [("bit", "signed"), ("bit", "unsigned"), ("logic", "signed"), ("logic", "unsigned")]
# The statements run on one element that starts at 0, in order: the text
# with E for the element, and what it does to the 32-bit value.


def put(value, lsb, width, bits):
    mask = ((1 << width) - 1) << lsb
    return (value & ~mask) | ((bits << lsb) & mask)


def get(value, lsb, width):
    return (value >> lsb) & ((1 << width) - 1)


STEPS = [
    ("E[1] = 8'h5a;", lambda v: put(v, 8, 8, 0x5A)),
    ("E[1] += 8'd1;", lambda v: put(v, 8, 8, get(v, 8, 8) + 1)),
    ("E[2] = -8'sd2;", lambda v: put(v, 16, 8, 0xFE)),
    ("E[2] -= 8'd3;", lambda v: put(v, 16, 8, get(v, 16, 8) - 3)),
    ("E[k] += 8'd16;", lambda v: put(v, 8, 8, get(v, 8, 8) + 16)),
    ("E[k + 2] = 8'hc3;", lambda v: put(v, 24, 8, 0xC3)),
    ("E[3][7:4] = 4'h9;", lambda v: put(v, 28, 4, 9)),
    ("E[0][k] = 1'b1;", lambda v: put(v, 1, 1, 1)),
    ("E[0][6:5] += 2'd3;", lambda v: put(v, 5, 2, get(v, 5, 2) + 3)),
]
CONTAINERS = ["initial", "task"]


def files():
    sv = [
        "/*",
        f":name: {NAME}",
        ":description: An assignment to a part or a bit of a packed element writes the same "
        "bits whether the element is in a fixed array, a queue or a dynamic array and whether "
        "its type is signed",
        ":tags: containers",
        ":type: simulation",
        ":lrm: 1800-2023 7.4.5 11.5.1 11.8.1 7.10 7.5",
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: no",
        ":nondeterministic: no",
        f":generator: gen_container_packed_select_matrix.py@{VERSION}",
        f":expected_stdout: @{NAME}.expected",
        "*/",
        "// Generated by tools/gen_container_packed_select_matrix.py; change the generator, "
        "not this file.",
        "module top;",
        "  int k = 1;",
    ]
    decls, body, expected = [], {c: [] for c in CONTAINERS}, []
    for container in CONTAINERS:
        for home, dims, setup in HOMES:
            for state, sign in TYPES:
                var = f"{container}_{home}_{state}_{sign}"
                decls.append(f"  {state} {sign} [3:0][7:0] {var} {dims};")
                lines = body[container]
                lines += [f"    {s.replace('V', var)}" for s in setup]
                if home == "fixed":
                    lines.append(f"    {var}[0] = '0;")
                value = 0
                for text, model in STEPS:
                    value = model(value) & 0xFFFFFFFF
                    lines.append(f"    {text.replace('E', var + '[0]')}")
                    lines.append(f'    $display("{container} {home} {state} {sign} '
                                 f'{text.rstrip(";")} -> %h", {var}[0]);')
                    expected.append(f"{container} {home} {state} {sign} {text.rstrip(';')} -> "
                                    f"{value:08x}")
    sv += decls
    sv += ["  task automatic run_task();"] + body["task"] + ["  endtask"]
    sv += ["  initial begin"] + body["initial"] + ["    run_task();", "  end", "endmodule", ""]
    return {f"{NAME}.sv": "\n".join(sv), f"{NAME}.expected": "\n".join(expected) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_container_packed_select_matrix: "
                      f"{path.relative_to(OUT.parent.parent.parent)} is out of date; run "
                      "tools/gen_container_packed_select_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
