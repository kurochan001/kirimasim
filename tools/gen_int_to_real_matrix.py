"""Generates the integer-to-real rounding matrix test of TEST_SUITE.md
("Mechanism matrix") in tests/suite/values/.

  tools/gen_int_to_real_matrix.py           # writes the files
  tools/gen_int_to_real_matrix.py --check   # exit 1 if a file differs from what it would write

The rule: VALUE_SEMANTICS.md 1.5. An integer that a real or a shortreal
cannot hold exactly becomes the nearest value it can hold, a tie going to
the one whose last bit is 0; a shortreal is rounded once, not through a
double, which would round a value just past a tie of 24 bits down to the
tie and then to even. The axes: the value (ties and values just past
them, for 24 and 53 bits, unsigned and signed, of 64 and of 100 bits), the
target (real, shortreal), and the place of the conversion (a variable at
run time, a constant slang converts, a constant front converts because
slang's unary plus is not taken (SIR_SPEC.md 6), a local parameter, a
function's return, an automatic task's local variable). The expected bits
are computed exactly with Python's integers.

A person checks the expected output once for all the tests made from it
(TEST_SUITE.md, "Sampling by people").
"""

import argparse
import struct
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "values"
NAME = "int_to_real_matrix"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

# The values: their type, and the integer.
VALUES = [
    ("longint unsigned", 2**60 + 2**36 + 1),   # just past a 24-bit tie; through a double, a tie
    ("longint unsigned", 2**24 + 1),           # a 24-bit tie: down to even
    ("longint unsigned", 2**24 + 3),           # a 24-bit tie: up to even
    ("longint unsigned", 2**53 + 1),           # a 53-bit tie: down to even
    ("longint unsigned", 2**53 + 3),           # a 53-bit tie: up to even
    ("longint unsigned", 2**63 + 2**39 + 1),   # just past a 24-bit tie, top bit set
    ("longint", -(2**60 + 2**36 + 1)),         # signed: the magnitude rounds alike
    ("logic [99:0]", 2**90 + 2**66 + 1),       # wide: just past a 24-bit tie
    ("logic [99:0]", 2**90 + 2**37 + 1),       # wide: just past a 53-bit tie
    ("logic signed [99:0]", -(2**90 + 2**66 + 1)),
]
TARGETS = [("shortreal", 24, "$shortrealtobits", "f", 8), ("real", 53, "$realtobits", "d", 16)]
PLACES = ["variable", "constant", "folded", "parameter", "function", "task"]


def rounded(n, precision):
    """n rounded once to `precision` significant bits, ties to even."""
    m = abs(n)
    if m.bit_length() > precision:
        drop = m.bit_length() - precision
        kept, rest = m >> drop, m & ((1 << drop) - 1)
        half = 1 << (drop - 1)
        if rest > half or (rest == half and kept & 1):
            kept += 1
        m = kept << drop
    return -m if n < 0 else m


def bits(n, precision, code, digits):
    return f"{struct.unpack('>Q' if code == 'd' else '>I', struct.pack('>' + code, float(rounded(n, precision))))[0]:0{digits}x}"


def literal(t, n):
    width = 100 if "99" in t else 64
    signed = t == "longint" or t.startswith("logic signed")
    text = f"{width}'{'s' if signed else ''}h{abs(n):x}"
    return f"-{text}" if n < 0 else text


def files():
    sv = [
        "/*",
        f":name: {NAME}",
        ":description: an integer converted to real or shortreal is rounded once to the nearest "
        "value, ties to even, wherever the conversion stands",
        ":tags: values real",
        ":type: simulation",
        ":lrm: 1800-2023 6.12.1",
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: no",
        ":nondeterministic: no",
        f":generator: gen_int_to_real_matrix.py@{VERSION}",
        f":expected_stdout: @{NAME}.expected",
        "*/",
        "// Generated by tools/gen_int_to_real_matrix.py; change the generator, not this file.",
        "module top;",
    ]
    body, expected = [], []
    k = 0
    for t, n in VALUES:
        lit = literal(t, n)
        for target, precision, tobits, code, digits in TARGETS:
            want = bits(n, precision, code, digits)
            sv += [f"  {t} x{k} = {lit};",
                   f"  {target} v{k};",
                   f"  localparam {target} P{k} = {lit};",
                   f"  function automatic {target} f{k}({t} a);",
                   "    return a;",
                   "  endfunction",
                   f"  task automatic t{k}();",
                   f"    {t} a = x{k};",
                   f"    {target} r = a;",
                   f'    $display("task {k} %h", {tobits}(r));',
                   "  endtask"]
            body += [f"    v{k} = x{k};",
                     f'    $display("variable {k} %h", {tobits}(v{k}));',
                     f"    v{k} = {lit};",
                     f'    $display("constant {k} %h", {tobits}(v{k}));',
                     f"    v{k} = {target}'(+({lit}));",
                     f'    $display("folded {k} %h", {tobits}(v{k}));',
                     f'    $display("parameter {k} %h", {tobits}(P{k}));',
                     f'    $display("function {k} %h", {tobits}(f{k}(x{k})));',
                     f"    t{k}();"]
            expected += [f"{place} {k} {want}" for place in PLACES]
            k += 1
    sv += ["  initial begin"] + body + ["  end", "endmodule", ""]
    return {f"{NAME}.sv": "\n".join(sv), f"{NAME}.expected": "\n".join(expected) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_int_to_real_matrix: {path.relative_to(OUT.parent.parent.parent)} is "
                      "out of date; run tools/gen_int_to_real_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
