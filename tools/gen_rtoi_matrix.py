"""Generates the $rtoi matrix test of TEST_SUITE.md ("Mechanism matrix") in
tests/suite/values/.

  tools/gen_rtoi_matrix.py           # writes the files
  tools/gen_rtoi_matrix.py --check   # exit 1 if a file differs from what it would write

$rtoi truncates a real toward zero, then keeps the low 32 bits of that
integer's two's complement (its result is an integer) at any magnitude;
NaN and the infinities give x in every bit (SYSTEM_TASKS.md 8, as the
conversion of VALUE_SEMANTICS.md 7.4). The axes: the values of
gen_real_convert_matrix.py; the argument (a real variable at run time,
a constant expression); the container (module variables and automatic
variables of a function).

A person checks the expected output once for all the tests made from it
(TEST_SUITE.md, "Sampling by people").
"""

import argparse
import math
import sys
from pathlib import Path

from gen_real_convert_matrix import VALUES, spell
from gen_wide_matrix import V, allx, hexdigits

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "values"
NAME = "rtoi_matrix"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1


def rtoi(d):
    if math.isnan(d) or math.isinf(d):
        return allx(32)
    return V(32, int(d) % (1 << 32))  # int() truncates toward zero


def files():
    head = [
        "/*",
        f":name: {NAME}",
        ":description: $rtoi truncates toward zero and keeps the low 32 bits at any magnitude; "
        "NaN and the infinities give x; from variables and constants, in module and automatic "
        "variables",
        ":tags: values real",
        ":type: simulation",
        ":lrm: 1800-2023 20.5",
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: yes",
        ":nondeterministic: no",
        f":generator: gen_rtoi_matrix.py@{VERSION}",
        f":expected_stdout: @{NAME}.expected",
        "*/",
        "// Generated by tools/gen_rtoi_matrix.py; change the generator, not this file.",
        "// Icarus Verilog 14.0 (devel) f190dbb and Verilator 5.053 (devel) differ from these values",
        "// and from each other past 32 bits (SYSTEM_TASKS.md 8).",
        "module top;",
        "  real r;",
        "  function automatic integer auto_rtoi(real x);",
        "    real y;",
        "    y = x;",
        "    return $rtoi(y);",
        "  endfunction",
        "  initial begin",
    ]
    st, exp = [], []
    for k, d in enumerate(VALUES):
        want = hexdigits(rtoi(d))
        st += [f"    r = {spell(d)};",
               f"    $display(\"{k} run %h\", $rtoi(r));",
               f"    $display(\"{k} const %h\", $rtoi({spell(d)}));",
               f"    $display(\"{k} function %h\", auto_rtoi(r));"]
        exp += [f"{k} {s} {want}" for s in ("run", "const", "function")]
    sv = head + st + ["  end", "endmodule", ""]
    return {f"{NAME}.sv": "\n".join(sv), f"{NAME}.expected": "\n".join(exp) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_rtoi_matrix: {path.relative_to(OUT.parent.parent.parent)} is out of "
                      "date; run tools/gen_rtoi_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
