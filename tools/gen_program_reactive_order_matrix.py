"""Generates the matrix tests of a program process that wakes on a change
made by a module (TEST_SUITE.md, "Mechanism matrix") in tests/suite/proc/.

  tools/gen_program_reactive_order_matrix.py           # writes the files
  tools/gen_program_reactive_order_matrix.py --check   # exit 1 if a file differs from what it would write

The rule: 4.5 and 24.3.1 of the standard. A process of a program runs in
the Reactive region, and the regions of the Active set (Active,
Inactive, NBA) are emptied before the Reactive region runs. So when a
module changes a variable, everything the modules compute from it in
that time step (continuous assignments, nets through ports, always and
always_comb procedures, nonblocking assignments) is done before a
program process that waits for the change goes on, and the program
reads the new values, by hierarchical names and through its input ports
that are connected to nets; a module process that waits for the same
change prints before it.

Left out: an input port of the program connected to a module variable.
kirimasim updates it with a process of the program's reactive set
(docs/notes/p1-icarus-progress.md, "Program execution"; approved
2026-10-23), so in the Reactive region it and a waiting program process
come in an order that the standard leaves open (4.7). The test only
waits on such a port (pv), and then reads nothing through it.

The axes: what the program waits with (an event control on the module's
variable by a hierarchical name, a wait statement, an event control on
an input port connected to the variable, an event control on an input
port connected to a net), the container of the waiting statement
(an initial procedure of the program, an automatic task, a method of a
class declared in the program), and the change (a blocking and a
nonblocking assignment of the module, two of each). The values the
program reads are the module's variable through a continuous assignment
to a net, an always procedure with a blocking and one with a
nonblocking assignment, an always_comb procedure, a net through the
output port of a child module, and a chain of two continuous
assignments.

The expected output is computed here from the values, without reading
kirimasim's code. A person checks it once for all the tests made from it
(TEST_SUITE.md, "Sampling by people").
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "proc"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

WAITS = {"event": "@(top.v);", "wait": "wait (top.v == k);", "port_variable": "@(pv);",
         "port_net": "@(pw);"}
CONTAINERS = ["initial", "task", "method"]
# The values the program reads: (name in the module, name of the input port
# connected to it, or None).
READS = [("w", "pw"), ("m", None), ("n", None), ("c", None), ("p", "pp"), ("q", "pq")]
CHANGES = ["#10 v = 1;", "#10 v = 2;", "#10 v <= 3;", "#10 v <= 4;"]


def test(wait, container):
    name = f"program_reactive_order_{wait}_{container}"
    how = {"event": "an event control on the module's variable",
           "wait": "a wait statement",
           "port_variable": "an event control on an input port connected to the variable",
           "port_net": "an event control on an input port connected to a net"}[wait]
    where = {"initial": "an initial procedure of the program", "task": "an automatic task",
             "method": "a method of a class in the program"}[container]
    sv = ["/*", f":name: {name}",
          ":description: a program process that waits with "
          f"{how}, in {where}, goes on after the modules have computed everything that depends "
          "on the change, and after a module process that waits for the same change",
          ":tags: proc", ":type: simulation", ":lrm: 1800-2023 4.5 24.3.1", ":oracle: spec",
          ":spec_check: ai", ":fourstate: no", ":nondeterministic: no",
          f":generator: gen_program_reactive_order_matrix.py@{VERSION}", ":top_module: top",
          ":issue: 63", f":expected_stdout: @{name}.expected", "*/",
          "// Generated by tools/gen_program_reactive_order_matrix.py; change the generator, "
          "not this file.", "`timescale 1ns/1ns",
          "module child (input logic [7:0] a, output wire [7:0] y);", "  assign y = a;",
          "endmodule"]
    ports = ", ".join(["pv"] + [port for _, port in READS if port])
    fmt = " ".join(f"{name}=%0d/%0d" if port else f"{name}=%0d" for name, port in READS)
    args = ", ".join(f"top.{name}, {port}" if port else f"top.{name}" for name, port in READS)
    loop = ["for (int k = 1; k <= 4; k++) begin", f"  {WAITS[wait]}",
            f'  $display("program %0d: {fmt}", top.v, {args});', "end"]
    sv += [f"program prog (input logic [7:0] {ports});"]
    if container == "initial":
        sv += ["  initial begin"] + ["    " + x for x in loop] + ["  end"]
    elif container == "task":
        sv += ["  task automatic watch();"] + ["    " + x for x in loop] + ["  endtask"]
        sv += ["  initial watch();"]
    else:
        sv += ["  class watcher;", "    task watch();"] + ["      " + x for x in loop]
        sv += ["    endtask", "  endclass", "  initial begin", "    watcher x = new;",
               "    x.watch();", "  end"]
    sv += ["endprogram",
           "module top;",
           "  logic [7:0] v = 0;",
           "  wire [7:0] w;",
           "  assign w = v;",
           "  logic [7:0] m, n, c;",
           "  always @(v) m = v;",
           "  always @(v) n <= v;",
           "  always_comb c = v;",
           "  wire [7:0] p, q1, q;",
           "  child u (.a(v), .y(p));",
           "  assign q1 = v;",
           "  assign q = q1;",
           '  always @(v) $display("module %0d", v);',
           "  prog pr (.pv(v), " + ", ".join(f".{port}({name})" for name, port in READS if port) +
           ");",
           "  initial begin"] + ["    " + c for c in CHANGES] + ["  end", "endmodule"]
    expected = []
    for k in range(1, len(CHANGES) + 1):
        expected.append(f"module {k}")
        expected.append(f"program {k}: " + " ".join(f"{name}={k}/{k}" if port else f"{name}={k}"
                                                    for name, port in READS))
    return name, sv, expected


def files():
    out = {}
    for wait in WAITS:
        for container in CONTAINERS:
            name, sv, expected = test(wait, container)
            out[f"{name}.sv"] = "\n".join(sv) + "\n"
            out[f"{name}.expected"] = "\n".join(expected) + "\n"
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print("gen_program_reactive_order_matrix: "
                      f"{path.relative_to(OUT.parent.parent.parent)} is out of date; run "
                      "tools/gen_program_reactive_order_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
