"""Generate original integral $fread argument/value/storage tests (21.3.4.4).

Start/count are evaluated as ordinary arguments but do not limit integral
input. The independent bit-list model replaces available bytes from the top
of ceil(width/8), truncates above width and retains unfilled old bits.
SIR_SPEC 8 separately evaluates an inout actual for copy-in and copy-out;
only outputs actually written are copied back (4.9.7 project interpretation).
"""

import argparse
import re
import sys
from pathlib import Path

from gen_dynamic_container_matrix import HOMES, wrap

OUT = Path(__file__).resolve().parent.parent / 'tests/suite/proc'
VERSION = 2
CONTEXTS = (*HOMES, 'function')
WIDTHS = (1, 7, 8, 9, 32, 64, 65, 129)
DATA = bytes((0x81 + 73 * i) % 256 for i in range(40))


def source(home, variables, methods, body):
    if home == 'function':
        return ('module top; ' + variables + '\n' + methods + '\n'
                'function automatic void run();\n' + body + '\nendfunction\n'
                'initial run(); endmodule\n')
    return wrap(home, '', variables, methods, body)


def fixture(name, data):
    lines = [f'fd=$fopen("{name}","wb");']
    for byte in data:
        lines.append(f'$fwrite(fd,"%c",8\'h{byte:02x});')
    lines.append('$fclose(fd);')
    return '\n'.join(lines)


def model(width, seed, data):
    bits = [seed] * width
    count = min(len(data), (width + 7) // 8)
    for byte_index, byte in enumerate(data[:count]):
        low = (((width + 7) // 8) - byte_index - 1) * 8
        for bit in range(8):
            if low + bit < width:
                bits[low + bit] = str((byte >> bit) & 1)
    return count, ''.join(reversed(bits))


def output(name, program, expected):
    header = f'''/*
:name: {name}
:description: Integral fread ignores start/count values, evaluates arguments once and preserves partial input
:tags: proc
:type: simulation
:lrm: 1800-2023 21.3.4.4 11.3.5
:oracle: spec
:spec_check: ai
:fourstate: yes
:nondeterministic: no
:generator: gen_scalar_fread_matrix.py@{VERSION}
:top_module: top
:expected_stdout: @{name}.expected
:expected_stderr: @{name}.stderr
*/
// Generated by tools/gen_scalar_fread_matrix.py; edit the generator.
`timescale 1ns/1ns
'''
    text = header + program
    stderr = ''
    if name.endswith('_evaluation'):
        # Slang diagnoses the intentionally unspecified standard evaluation
        # order. Keep its warning; the oracle tests the approved project LTR rule.
        for number, line in enumerate(text.splitlines(), 1):
            if line.startswith('n=$fread('):
                for match in list(re.finditer(r'\btrace\b', line))[1:]:
                    stderr += (f"{name}.sv:{number}:{match.start()+1}: warning: 'trace' is both "
                               "read and modified in the same expression; the order of "
                               "evaluation is undefined [-Wread-write]\n")
                for target in ('a[0]', 'partial'):
                    spelling = f'clear({target})'
                    if spelling not in line:
                        continue
                    column = line.index(spelling) + len('clear(') + 1
                    stderr += (f"{name}.sv:{number}:{column}: warning: '{target}' is both read "
                               "and modified in the same expression; the order of "
                               "evaluation is undefined [-Wread-write]\n")
    return {name + '.sv': text, name + '.expected': expected, name + '.stderr': stderr}


def value_case(home, width, domain):
    name = f'scalar_fread_{home}_{domain}_{width}'
    nbytes = (width + 7) // 8
    seed = '1' if domain == 'bit' else 'z' if width % 8 else 'x'
    variables = f'{domain} [{width-1}:0] v; int fd,n;'
    partial = DATA[:nbytes-1]
    body = fixture('complete.bin', DATA[:nbytes+1]) + '\n' + fixture('partial.bin', partial)
    expected = ''
    modes = (('plain', ''), ('start', ', -71'), ('count', ', 19, 0'),
             ('omitted', ', , -3'), ('unknown', ", 129'h10000000000000000, 4'bx"))
    for label, extra in modes:
        body += f'''\nv='{seed}; fd=$fopen("complete.bin","rb");
n=$fread(v,fd{extra});
$display("{label} %0d %b %0d",n,v,$fgetc(fd)); $fclose(fd);
'''
        count, bits = model(width, seed, DATA[:nbytes])
        expected += f'{label} {count} {bits} {DATA[nbytes]}\n'
    body += f'''\nv='{seed}; fd=$fopen("partial.bin","rb");
n=$fread(v,fd,0,0); $display("partial %0d %b",n,v);
n=$fread(v,fd,0,0); $display("eof %0d %b",n,v); $fclose(fd);
'''
    count, bits = model(width, seed, partial)
    expected += f'partial {count} {bits}\neof 0 {bits}\n'
    return output(name, source(home, variables, '', body), expected)


def mechanism_case(home):
    name = f'scalar_fread_{home}_evaluation'
    variables = 'logic [23:0] a[2],partial; logic [31:0] bits; int fd,n,trace,idx; int q[$];'
    methods = '''function automatic int mark(ref int trace, input int digit, input int value);
trace=trace*10+digit; return value; endfunction
function automatic int pick(ref int trace, ref int idx);
trace=trace*10+1; return idx++; endfunction
function automatic int replace(ref int q[$]); q='{99}; return 0; endfunction
function automatic int clear(ref logic [23:0] value); value=0; return 0; endfunction
function automatic int read_value(ref logic [23:0] value, input int descriptor);
return $fread(value,descriptor,0,0); endfunction
'''
    body = fixture('data.bin', bytes([0x81, 0x12, 0xa7, 0x00]))
    body += '\n' + fixture('empty.bin', b'')
    body += '\n' + fixture('short.bin', bytes([0x81]))
    for label, file in [('once', 'data.bin'), ('empty', 'empty.bin')]:
        body += f'''
a[0]='1; a[1]='1; trace=0; idx=0; fd=$fopen("{file}","rb");
n=$fread(a[pick(trace,idx)],mark(trace,2,fd),mark(trace,3,0),mark(trace,4,0));
$display("{label} %0d %0d %0d %h %h",n,trace,idx,a[0],a[1]); $fclose(fd);
'''
    body += '''a[0]='1; a[1]='1; trace=0; idx=0; fd=$fopen("data.bin","rb");
n=$fread(a[pick(trace,idx)],mark(trace,2,fd));
$display("plain_once %0d %0d %0d %h %h",n,trace,idx,a[0],a[1]); $fclose(fd);
bits='1; trace=0; fd=$fopen("data.bin","rb");
n=$fread(bits[mark(trace,1,7)+:9],mark(trace,2,fd),mark(trace,3,0),mark(trace,4,0));
$display("part %0d %0d %h",n,trace,bits); $fclose(fd);
a[0]='1; a[1]='1; fd=$fopen("data.bin","rb");
n=$fread({a[0][7:0],a[1][7:0]},fd,0,0);
$display("concat %0d %h %h",n,a[0],a[1]); $fclose(fd);
q='{17}; trace=0; idx=0; fd=$fopen("data.bin","rb");
n=$fread(q[pick(trace,idx)],mark(trace,2,fd),mark(trace,3,0),mark(trace,4,0));
$display("heap %0d %0d %0d %h",n,trace,idx,q[0]); $fclose(fd);
q='{17}; fd=$fopen("data.bin","rb");
n=$fread(q[0],fd,replace(q),0);
$display("held %0d %0d %0d",n,q.size(),q[0]); $fclose(fd);
a[0]='1; fd=$fopen("empty.bin","rb");
n=$fread(a[0],fd,clear(a[0]),0);
$display("no_copyback %0d %h",n,a[0]); $fclose(fd);
a[1]='1; fd=$fopen("data.bin","rb"); n=read_value(a[1],fd);
$display("ref %0d %h",n,a[1]); $fclose(fd);
q='{0}; fd=$fopen("data.bin","rb");
n=$fread(q[0][7+:9],fd,0,0);
$display("heap_part %0d %h",n,q[0]); $fclose(fd);
q='{17}; fd=$fopen("data.bin","rb");
n=$fread(q[99],fd,0,0);
$display("invalid %0d %0d",n,q[0]); $fclose(fd);
q='{17,23}; trace=0; idx=0; fd=$fopen("data.bin","rb");
n=$fread(q[pick(trace,idx)],mark(trace,2,fd),mark(trace,3,0),mark(trace,4,0));
$display("heap_copyout %0d %0d %0d %h %h",n,trace,idx,q[0],q[1]); $fclose(fd);
partial='1; fd=$fopen("short.bin","rb");
n=$fread(partial,fd,clear(partial),0);
$display("copyin %0d %h",n,partial); $fclose(fd);
'''
    part = (0xffffffff & ~(0x1ff << 7)) | (0x112 << 7)
    held = int.from_bytes(bytes([0x81, 0x12, 0xa7, 0x00]), 'big', signed=True)
    expected = ('once 3 12341 2 ffffff 8112a7\nempty 0 1234 1 ffffff ffffff\n'
                'plain_once 3 121 2 ffffff 8112a7\n'
                f'part 2 12341 {part:08x}\nconcat 2 ffff81 ffff12\n'
                f'heap 4 12341 2 00000011\nheld 4 1 {held}\n'
                'no_copyback 0 000000\nref 3 8112a7\n'
                'heap_part 2 00008900\ninvalid 4 17\n'
                'heap_copyout 4 12341 2 00000011 8112a700\ncopyin 1 81ffff\n')
    return output(name, source(home, variables, methods, body), expected)


def files():
    result = {}
    for home in CONTEXTS:
        for width in WIDTHS:
            for domain in ('bit', 'logic'):
                result.update(value_case(home, width, domain))
        result.update(mechanism_case(home))
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    bad = []
    for name, content in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                bad.append(name)
        else:
            path.write_text(content)
    if bad:
        print('gen_scalar_fread_matrix: stale files: ' + ', '.join(bad), file=sys.stderr)
    return int(bool(bad))


if __name__ == '__main__':
    sys.exit(main())
