"""Generates the matrix test of long chains of the conditional operator
(TEST_SUITE.md, "Mechanism matrix") in tests/suite/values/.

  tools/gen_conditional_chain_matrix.py           # writes the files
  tools/gen_conditional_chain_matrix.py --check   # exit 1 if a file differs from what it would write

The rule: VALUE_SEMANTICS.md 3.9 and 11.4.11 of the standard. ?: evaluates
only the side a known condition picks, and both sides when the condition
is x or z, merging them bit by bit. A chain of conditionals 40 deep, each
side a function call, has to compile and run in time that grows with its
length, not with 2 to its length, and each call still runs only when its
side is picked. The axes: the side the chain nests in (else, as a
priority selector, and then); the type of the result (int and real); the
condition picked (the first, one in the middle, the last, none), and for
int one unknown condition, whose two sides merge; and the container (a
module's initial and a function's return). A second test has the same
chains with a string and a class handle as the result, from calls and
from reads through handles that are null on the sides not picked.

The expected output comes from the model below. A person checks it once
for all the tests made from it (TEST_SUITE.md, "Sampling by people").
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "values"
NAME = "conditional_chain_matrix"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1
DEPTH = 40
PICKS = [0, 17, DEPTH - 1, None]
UNKNOWN = 5  # the unknown condition of the merge case; the others are 0


def chain(side, call):
    """The chain: on else, s[0] ? f(0) : s[1] ? f(1) : ... : f(DEPTH); on
    then, s[0] ? (s[1] ? (... f(DEPTH)) : f(1)) : f(0)."""
    text = call(DEPTH)
    for i in reversed(range(DEPTH)):
        text = (f"s[{i}] ? {call(i)} : ({text})" if side == "else"
                else f"s[{i}] ? ({text}) : {call(i)}")
    return text


def conditions(side, pick):
    """The value of s that picks call `pick` (None: the innermost one)."""
    if side == "else":
        return 0 if pick is None else 1 << pick
    return (1 << DEPTH) - 1 if pick is None else (1 << pick) - 1


def merge(a, b):
    return "".join(x if x == y else "x" for x, y in zip(f"{a:032b}", f"{b:032b}"))


def files():
    sv = [
        "/*",
        f":name: {NAME}",
        ":description: A chain of 40 conditional operators with a call on each side compiles "
        "in time that grows with its length, runs only the call that is picked, and merges "
        "the two sides of an unknown condition",
        ":tags: values",
        ":type: simulation",
        ":lrm: 1800-2023 11.4.11",
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: yes",
        ":nondeterministic: no",
        f":generator: gen_conditional_chain_matrix.py@{VERSION}",
        f":expected_stdout: @{NAME}.expected",
        "*/",
        "// Generated by tools/gen_conditional_chain_matrix.py; change the generator, not this "
        "file.",
        "module top;",
        f"  logic [{DEPTH - 1}:0] s;",
        "  int n, yi;",
        "  logic [31:0] yl;",
        "  real yr;",
        "  function automatic int fi(int x);",
        "    n++;",
        "    return x + 100;",
        "  endfunction",
        "  function automatic real fr(int x);",
        "    n++;",
        "    return x + 0.5;",
        "  endfunction",
    ]
    functions, body, expected = [], {"initial": [], "function": []}, []
    for side in ("else", "then"):
        exprs = {"int": chain(side, lambda i: f"fi({i})"),
                 "real": chain(side, lambda i: f"fr({i})")}
        functions += [f"  function automatic int chain_{side}_int();",
                      f"    return {exprs['int']};", "  endfunction",
                      f"  function automatic real chain_{side}_real();",
                      f"    return {exprs['real']};", "  endfunction"]
        for container in ("initial", "function"):
            lines = body[container]
            for pick in PICKS:
                which = DEPTH if pick is None else pick
                label = f"{container} {side} pick={'none' if pick is None else pick}"
                value = conditions(side, pick)
                lines.append(f"    s = {DEPTH}'h{value:x};")
                for kind, var, shown in (("int", "yi", f"{which + 100}"),
                                         ("real", "yr", f"{which + 0.5:.1f}")):
                    rhs = exprs[kind] if container == "initial" else f"chain_{side}_{kind}()"
                    fmt = "%0d" if kind == "int" else "%.1f"
                    lines.append(f"    n = 0; {var} = {rhs};")
                    lines.append(f'    $display("{label} {kind} {fmt} n=%0d", {var}, n);')
                    expected.append(f"{label} {kind} {shown} n=1")
            # One unknown condition, the others 0: both of its sides run and merge.
            label = f"{container} {side} unknown={UNKNOWN}"
            known = conditions(side, None) if side == "then" else 0
            lines.append(f"    s = {DEPTH}'h{known & ~(1 << UNKNOWN):x}; s[{UNKNOWN}] = 1'bx;")
            rhs = exprs["int"] if container == "initial" else f"chain_{side}_int()"
            lines.append(f"    n = 0; yl = {rhs};")
            lines.append(f'    $display("{label} int %b n=%0d", yl, n);')
            # The picked side of the unknown condition is its own call; the other
            # side is the rest of the chain, which ends at the innermost call.
            # The function returns int, so its unknown bits become 0 (6.11.2).
            merged = merge(UNKNOWN + 100, DEPTH + 100)
            if container == "function":
                merged = merged.replace("x", "0")
            expected.append(f"{label} int {merged} n=2")
    sv += functions
    sv += ["  initial begin"] + body["initial"] + body["function"] + ["  end", "endmodule", ""]
    order = {"initial": 0, "function": 1}
    expected.sort(key=lambda line: order[line.split(" ", 1)[0]])
    return {f"{NAME}.sv": "\n".join(sv), f"{NAME}.expected": "\n".join(expected) + "\n"}


REFERENCE = "conditional_chain_reference_matrix"


def reference_files():
    """The same chains with a result that is a string or a class handle:
    the sides are calls, or reads through a handle that is null on every
    side but the one picked, so a side that is evaluated without being
    picked ends the run. With an unknown condition the two sides are
    evaluated once each; values that differ give the empty string or the
    null handle, and equal ones give that value (VALUE_SEMANTICS.md 3.9)."""
    sv = [
        "/*",
        f":name: {REFERENCE}",
        ":description: A chain of 40 conditional operators whose result is a string or a "
        "class handle compiles in time that grows with its length, evaluates only the side "
        "that is picked, and both sides once for an unknown condition",
        ":tags: values",
        ":type: simulation",
        ":lrm: 1800-2023 11.4.11",
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: yes",
        ":nondeterministic: no",
        f":generator: gen_conditional_chain_matrix.py@{VERSION}",
        f":expected_stdout: @{REFERENCE}.expected",
        "*/",
        "// Generated by tools/gen_conditional_chain_matrix.py; change the generator, not this "
        "file.",
        "module top;",
        "  class item;",
        "    string tag;",
        "    function new(string t);",
        "      tag = t;",
        "    endfunction",
        "  endclass",
        f"  logic [{DEPTH - 1}:0] s;",
        "  int n;",
        "  string ys;",
        "  item yh;",
        f"  item made [{DEPTH + 1}];",
        f"  item only [{DEPTH + 1}];",
        "  function automatic string fs(int x);",
        "    n++;",
        '    return $sformatf("s%0d", x);',
        "  endfunction",
        "  function automatic item fh(int x);",
        "    n++;",
        "    return made[x];",
        "  endfunction",
        "  task automatic keep(int a, int b);",
        f"    for (int i = 0; i <= {DEPTH}; i++) only[i] = (i == a || i == b) ? made[i] : null;",
        "  endtask",
    ]
    exprs = {}
    for side in ("else", "then"):
        exprs[side, "string"] = chain(side, lambda i: f"fs({i})")
        exprs[side, "handle"] = chain(side, lambda i: f"fh({i})")
        exprs[side, "read"] = chain(side, lambda i: f"only[{i}].tag")
        sv += [f"  function automatic string chain_{side}_string();",
               f"    return {exprs[side, 'string']};", "  endfunction",
               f"  function automatic item chain_{side}_handle();",
               f"    return {exprs[side, 'handle']};", "  endfunction",
               f"  function automatic string chain_{side}_read();",
               f"    return {exprs[side, 'read']};", "  endfunction"]
    body = {"initial": [], "function": []}
    expected = {"initial": [], "function": []}
    for side in ("else", "then"):
        for container in ("initial", "function"):
            lines = body[container]
            out = expected[container]

            def rhs(kind, side=side, container=container):
                return (exprs[side, kind] if container == "initial"
                        else f"chain_{side}_{kind}()")
            for pick in PICKS:
                which = DEPTH if pick is None else pick
                label = f"{container} {side} pick={'none' if pick is None else pick}"
                lines.append(f"    s = {DEPTH}'h{conditions(side, pick):x}; keep({which}, "
                             f"{which});")
                lines.append(f"    n = 0; ys = {rhs('string')};")
                lines.append(f'    $display("{label} string %s n=%0d", ys, n);')
                out.append(f"{label} string s{which} n=1")
                lines.append(f"    n = 0; yh = {rhs('handle')};")
                lines.append(f'    $display("{label} handle %s n=%0d", yh.tag, n);')
                out.append(f"{label} handle t{which} n=1")
                lines.append(f"    ys = {rhs('read')};")
                lines.append(f'    $display("{label} read %s", ys);')
                out.append(f"{label} read t{which}")
            # One unknown condition, the others 0: its two sides are evaluated
            # once each, and differ.
            label = f"{container} {side} unknown={UNKNOWN}"
            known = conditions(side, None) if side == "then" else 0
            lines.append(f"    s = {DEPTH}'h{known & ~(1 << UNKNOWN):x}; s[{UNKNOWN}] = 1'bx; "
                         f"keep({UNKNOWN}, {DEPTH});")
            lines.append(f"    n = 0; ys = {rhs('string')};")
            lines.append(f'    $display("{label} string [%s] n=%0d", ys, n);')
            out.append(f"{label} string [] n=2")
            lines.append(f"    n = 0; yh = {rhs('handle')};")
            lines.append(f'    $display("{label} handle %0d n=%0d", yh == null, n);')
            out.append(f"{label} handle 1 n=2")
            lines.append(f"    ys = {rhs('read')};")
            lines.append(f'    $display("{label} read [%s]", ys);')
            out.append(f"{label} read []")
            # The same with equal values on the two sides: that value.
            lines.append(f'    made[{UNKNOWN}].tag = "t{DEPTH}"; yh = {rhs("handle")}; '
                         f"ys = {rhs('read')};")
            lines.append(f'    $display("{label} equal read [%s] handle %0d", ys, yh == null);')
            lines.append(f'    made[{UNKNOWN}].tag = "t{UNKNOWN}";')
            out.append(f"{label} equal read [t{DEPTH}] handle 1")
    sv += ["  initial begin",
           f'    for (int i = 0; i <= {DEPTH}; i++) made[i] = new($sformatf("t%0d", i));']
    sv += body["initial"] + body["function"] + ["  end", "endmodule", ""]
    return {f"{REFERENCE}.sv": "\n".join(sv),
            f"{REFERENCE}.expected": "\n".join(expected["initial"] + expected["function"]) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in {**files(), **reference_files()}.items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_conditional_chain_matrix: {path.relative_to(OUT.parent.parent.parent)} "
                      "is out of date; run tools/gen_conditional_chain_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
