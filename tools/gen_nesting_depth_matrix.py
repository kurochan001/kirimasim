#!/usr/bin/env python3
"""Generates the matrix tests of statements and expressions nested deep,
of TEST_SUITE.md ("Mechanism matrix"), in tests/suite/proc/.

  tools/gen_nesting_depth_matrix.py           # writes the files
  tools/gen_nesting_depth_matrix.py --check   # exit 1 if a file differs from what it would write

A design whose statements or expressions nest as deep as slang accepts
compiles and runs: slang does all its work on the thread the driver
sized, not on a thread pool with the system's default stack, and front
recurses over the syntax on that thread too (RUNTIME_ABI.md 5). Before,
these designs crashed kirimasim on macOS while it compiled them (#35).

The axes: the construct (an if with 999 else-if branches, begin nested
1000 deep, a chain of 1000 ?:, parentheses nested 1000 deep, and a sum
of 10000 terms), each at the depth of #35; the container (an initial
procedure, an automatic function, an automatic task, a branch of a fork,
an always_comb, and, for the expressions, a continuous assignment). The
sum, whose file is large, is taken in three containers only. slang's own
limit on nesting (its default of 1024 levels) is above every depth here,
the container's levels included.

The expected outputs are the values the constructs compute: the else-if
chain and the ?: chain pick the branch of n = 999, the begin nest stores
7, the parentheses give a, and the sum 10000 times a, with a = 1.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "proc"
PREFIX = "nesting_depth_"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1
DEPTH = 1000  # the depth of the statements, ?: and parentheses (#35)
TERMS = 10000  # the terms of the sum (#35)

# (clauses, whether it is a statement, the value it gives)
KINDS = {
    "else_if": ("12.4", True, DEPTH - 1),
    "begin": ("9.3.1", True, 7),
    "cond": ("11.4.11", False, DEPTH - 1),
    "paren": ("11.3", False, 1),
    "sum": ("11.4.3", False, TERMS),
}
CONTAINERS = ["initial", "function", "task", "fork", "always_comb", "assign"]
SUM_CONTAINERS = {"initial", "function", "assign"}


def statement(kind: str, target: str) -> str:
    """The construct as one statement that stores its value in target."""
    if kind == "else_if":
        branches = [f"if (n == 0) {target} = 0;"]
        branches += [f"else if (n == {i}) {target} = {i};" for i in range(1, DEPTH)]
        return "\n".join(branches)
    if kind == "begin":
        return "begin " * DEPTH + f"{target} = 7;" + " end" * DEPTH
    return f"{target} = {expression(kind)};"


def expression(kind: str) -> str:
    if kind == "cond":
        return " : ".join(f"n == {i} ? {i}" for i in range(DEPTH)) + " : -1"
    if kind == "paren":
        return "(" * DEPTH + "a" + ")" * DEPTH
    return " + ".join(["a"] * TERMS)


def indent(text: str, by: str) -> list[str]:
    return [by + line for line in text.split("\n")]


def one(kind: str, container: str) -> dict[str, str]:
    clause, is_statement, value = KINDS[kind]
    name = f"{PREFIX}{kind}_{container}"
    lines = [
        "/*",
        f":name: {name}",
        ":description: statements or expressions nested as deep as slang accepts compile and run",
        ":tags: proc",
        ":type: simulation",
        f":lrm: 1800-2023 {clause}",
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: no",
        ":nondeterministic: no",
        f":generator: gen_nesting_depth_matrix.py@{VERSION}",
        ":issue: 35",
        ":top_module: top",
        f":expected_stdout: @{name}.expected",
        "*/",
        "// Generated by tools/gen_nesting_depth_matrix.py; change the generator, not this file.",
        "module top;",
        f"  int a = 1, n = {DEPTH - 1}, x;",
    ]
    if container == "initial":
        lines += ["  initial begin"] + indent(statement(kind, "x"), "    ")
        lines += ['    $display("x=%0d", x);', "  end"]
    elif container == "function":
        lines += ["  function automatic int f();", "    int r;"]
        lines += indent(statement(kind, "r"), "    ") + ["    return r;", "  endfunction"]
        lines += ['  initial $display("x=%0d", f());']
    elif container == "task":
        lines += ["  task automatic t(output int r);"] + indent(statement(kind, "r"), "    ")
        lines += ["  endtask", "  initial begin", "    t(x);", '    $display("x=%0d", x);',
                  "  end"]
    elif container == "fork":
        lines += ["  initial begin", "    fork", "      begin"]
        lines += indent(statement(kind, "x"), "        ")
        lines += ["      end", "    join", '    $display("x=%0d", x);', "  end"]
    elif container == "always_comb":
        lines += ["  always_comb begin"] + indent(statement(kind, "x"), "    ") + ["  end"]
        lines += ['  initial #1 $display("x=%0d", x);']
    else:
        lines += [f"  assign x = {expression(kind)};", '  initial #1 $display("x=%0d", x);']
    lines += ["endmodule", ""]
    return {f"{name}.sv": "\n".join(lines), f"{name}.expected": f"x={value}\n"}


def files() -> dict[str, str]:
    out: dict[str, str] = {}
    for kind, (_, is_statement, _) in KINDS.items():
        for container in CONTAINERS:
            if container == "assign" and is_statement:
                continue  # a continuous assignment takes an expression
            if kind == "sum" and container not in SUM_CONTAINERS:
                continue
            out.update(one(kind, container))
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_nesting_depth_matrix: {path.relative_to(OUT.parent.parent.parent)} is "
                      "out of date; run tools/gen_nesting_depth_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
