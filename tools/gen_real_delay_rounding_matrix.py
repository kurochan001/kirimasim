"""Generates the matrix tests of rounding real delays to the precision, of
TEST_SUITE.md ("Mechanism matrix"), in tests/suite/sched/.

  tools/gen_real_delay_rounding_matrix.py           # writes the files
  tools/gen_real_delay_rounding_matrix.py --check   # exit 1 if a file differs from what it would write

A real delay is rounded to its scope's precision (3.14.1) from its value
as a double (a real literal is a double, 5.7.2; a shortreal is widened):
the value times 10^(unit - precision), computed in double arithmetic,
rounded half away from zero, the same for a constant and for a value
known only at run time (SCHEDULER_SPEC.md 1). So a value whose decimal
text is a tie but whose double is just below it rounds down when the
product is below the half (1.005 at 1ns/10ps is 100 steps), and up when
the product is the half (2.675 is 268 steps, although its double is just
below 2.675).

The axes: the value (exact halves, ties whose product is below the half,
ties whose product is the half, and values that are no tie); the form
(a literal, a localparam, a real variable, a shortreal variable, a
shortreal cast of a literal); the statement (a wait, a nonblocking
assignment and a ->> with a delay; and, for constants, the delay of a
continuous assignment and of a gate). Each test has every value, in a
module of 1ns/10ps, each starting 10ns after the one before, and reports
to a top whose unit is the step, so $time there counts the steps.

The expected outputs follow from the rules above, computed below.
"""

from __future__ import annotations

import argparse
import struct
import sys
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "sched"
PREFIX = "delay_real_rounding_"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1
STEPS = 100  # steps of 10ps in the unit of 1ns
START = 10 * STEPS  # the values start 10ns apart

# Exact halves; ties as written whose product is below the half; ties
# whose double is below the half but whose product is the half; no ties.
VALUES = ["0.125", "0.375", "0.145", "0.285", "1.005", "1.255", "2.675", "0.015", "2.4999",
          "0.004"]
# (name, whether it is a constant, the declaration with {i} and {v} or
# None, the delay expression)
FORMS = [
    ("const", True, None, "({v})"),
    ("localparam", True, "  localparam real p{i} = {v};", "(p{i})"),
    ("var", False, "  real d{i} = {v};", "(d{i})"),
    ("shortreal_var", False, "  shortreal s{i} = {v};", "(s{i})"),
    ("shortreal_const", True, None, "(shortreal'({v}))"),
]
# (name, whether a variable may be the delay, the items of child for the
# value i with {d} for the delay, {t} for the start and {r} for the call
# of the report, what the description calls it, the clauses)
STATEMENTS = [
    ("wait", True, ["initial begin", "  #{t};", "  #{d} {r};", "end"], "a wait", ["9.4.1"]),
    ("nba", True, ["logic q{i} = 1'b0;", "initial begin", "  #{t};", "  q{i} <= #{d} 1'b1;", "end",
                   "always @(posedge q{i}) {r};"], "an intra-assignment delay", ["9.4.5"]),
    ("trigger_nb", True, ["event e{i};", "initial begin", "  #{t};", "  ->> #{d} e{i};", "end",
                          "always @e{i} {r};"], "a delayed ->>", ["15.5.1"]),
    ("assign", False, ["logic a{i} = 1'b0;", "wire w{i};", "assign #{d} w{i} = a{i};",
                       "initial #{t} a{i} = 1'b1;", "always @(posedge w{i}) {r};"],
     "the delay of a continuous assignment", ["10.3.3"]),
    ("gate", False, ["logic a{i} = 1'b0;", "wire w{i};", "buf #{d} g{i} (w{i}, a{i});",
                     "initial #{t} a{i} = 1'b1;", "always @(posedge w{i}) {r};"],
     "the delay of a gate", ["28.16"]),
]


def steps(value, form):
    """The steps of 10ps a delay of `value` ns takes: the double (or the
    shortreal, widened) times 100 in double arithmetic, rounded half away
    from zero."""
    v = float(value)
    if form.startswith("shortreal"):
        v = struct.unpack("f", struct.pack("f", v))[0]
    return int(Decimal(v * STEPS).to_integral_value(rounding=ROUND_HALF_UP))


def header(name, description, lrm):
    return [
        "/*",
        f":name: {name}",
        f":description: {description}",
        ":tags: sched delay",
        ":type: simulation",
        ":lrm: 1800-2023 " + " ".join(lrm),
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: yes",
        ":nondeterministic: no",
        f":generator: gen_real_delay_rounding_matrix.py@{VERSION}",
        ":issue: 18",
        ":top_module: top",
        f":expected_stdout: @{name}.expected",
        "*/",
        "// Generated by tools/gen_real_delay_rounding_matrix.py; change the generator, not "
        "this file.",
    ]


def case(stmt, form):
    sname, _, items, what, clauses = stmt
    fname, const, decl, expr = form
    name = f"{PREFIX}{sname}_{fname}"
    # top counts in steps; child is the scope of the delays.
    lines = ["`timescale 10ps/10ps", "module top;", "  child u();",
             "  function void report(string what);",
             "    $display(\"%s at %0d\", what, $time);", "  endfunction", "endmodule",
             "`timescale 1ns/10ps", "module child;"]
    expected = []
    for i, value in enumerate(VALUES):
        if decl is not None:
            lines.append(decl.format(i=i, v=value))
        d = expr.format(i=i, v=value)
        start = 10 * (i + 1)
        report = f"top.report(\"{value}\")"
        lines += ["  " + x.format(i=i, d=d, t=start, r=report) for x in items]
        expected.append(f"{value} at {start * STEPS + steps(value, fname)}")
    lines.append("endmodule")
    kind = {"const": "a literal", "localparam": "a localparam", "var": "a real variable",
            "shortreal_var": "a shortreal variable",
            "shortreal_const": "a shortreal cast of a literal"}[fname]
    description = (f"{what} of {kind} is rounded to the precision from the double product, half "
                   "away from zero")
    lrm = ["3.14.1", "5.7.2", "6.12.1"] + clauses + ["20.3.1"]
    return name, header(name, description, lrm) + lines, expected


def files():
    out = {}
    for stmt in STATEMENTS:
        for form in FORMS:
            if not stmt[1] and not form[1]:
                continue
            name, text, expected = case(stmt, form)
            out[f"{name}.sv"] = "\n".join(text) + "\n"
            out[f"{name}.expected"] = "\n".join(expected) + "\n"
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_real_delay_rounding_matrix: "
                      f"{path.relative_to(OUT.parent.parent.parent)} is out of date; run "
                      "tools/gen_real_delay_rounding_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
