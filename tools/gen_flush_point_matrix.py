"""Generates the matrix test of the flush points of pending reports, of
TEST_SUITE.md ("Mechanism matrix"), in tests/suite/sched/.

  tools/gen_flush_point_matrix.py           # writes the files
  tools/gen_flush_point_matrix.py --check   # exit 1 if a file differs from what it would write

A violation of unique and priority, and a failed deferred assertion, wait
on their process's queue of pending reports until the Observed region.
The queue is emptied at a flush point only: when the process resumes
from an event control or a wait (expression), or when always_comb starts
again on a change of what it depends on. Resuming after a delay, after
the children of fork-join or join_any end, after wait fork, after a task
that waited returns, or at the end of a block that another process
disabled, is no flush point (12.4.2.1, 16.4.2, SCHEDULER_SPEC.md 15.3,
15.4).

The axes: how the process goes on within the same time slot, before the
Observed region (the eleven cases below; a second process makes the
event, the value or the disable after #0, so that the first one is
already waiting); the report (a failed assert #0, whose action prints,
and a unique if with no true condition, which kirimasim reports on
standard error). Each case has its own time.

The expected outputs follow from the rules above, computed below. A
person checks them once for all the tests made from them (TEST_SUITE.md,
"Sampling by people").
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "sched"
NAME = "flush_point_matrix"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

# (name, the first process's wait with {k}, the second process's action
# after #0 with {k} (or ""), whether the queue is emptied)
CASES = [
    ("event_named", "@ev{k};", "-> ev{k};", True),
    ("event_posedge", "@(posedge s{k});", "s{k} = 1;", True),
    ("wait_expression", "wait (w{k});", "w{k} = 1;", True),
    ("delay_zero", "#0;", "", False),
    ("fork_join", "fork\n        #0;\n      join", "", False),
    ("fork_join_any", "fork\n        #0;\n        #5;\n      join_any", "", False),
    ("wait_fork", "fork\n        #0;\n      join_none\n      wait fork;", "", False),
    ("task_delay", "wait_zero();", "", False),
    ("disable_inner", None, "disable top.a{k}.inner;", False),
]
# always_comb cases: (name, whether the value goes back so that it starts
# again, the queue emptied)
COMB = [("comb_restarted", True, True), ("comb_not_restarted", False, False)]


def files():
    lines = [
        "/*",
        f":name: {NAME}",
        ":description: pending unique-if violations and failed assert #0 are dropped when the "
        "process resumes from an event control or a wait or always_comb starts again, and kept "
        "after #0, fork-join, join_any, wait fork, a task that waited and a disabled inner block",
        ":tags: sched assertions",
        ":type: simulation",
        ":lrm: 1800-2023 12.4.2.1 16.4.2 9.4.2 9.4.3 9.3.2 9.6.1 9.6.2",
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: no",
        ":nondeterministic: no",
        f":generator: gen_flush_point_matrix.py@{VERSION}",
        ":top_module: top",
        f":expected_stdout: @{NAME}.expected",
        f":expected_stderr: @{NAME}.stderr",
        "*/",
        "// Generated by tools/gen_flush_point_matrix.py; change the generator, not this file.",
        "`timescale 1ns/1ns",
        "module top;",
        "  task automatic wait_zero();",
        "    #0;",
        "  endtask",
    ]
    out, err = [], []

    def line_now():
        """The number of the line appended last."""
        return "\n".join(lines).count("\n") + 1

    def report(k, indent):
        """The two reports, returning the line of the unique if."""
        lines.append(f'{indent}assert #0 (c{k}) else $display("%0t case {k} deferred fired", '
                     "$time);")
        lines.append(f"{indent}unique if (u{k} == 1) begin end else if (u{k} == 2) begin end")
        return line_now()

    for k, (name, wait, trigger, flushed) in enumerate(CASES):
        t = 10 * (k + 1)
        lines += [f"  // case {k}: {name}",
                  f"  logic c{k} = 0;",
                  f"  int u{k} = 0;"]
        if name == "event_named":
            lines.append(f"  event ev{k};")
        if name == "event_posedge":
            lines.append(f"  logic s{k} = 0;")
        if name == "wait_expression":
            lines.append(f"  logic w{k} = 0;")
        lines += [f"  initial begin : a{k}", f"    #{t};"]
        if wait is None:
            lines.append("    begin : inner")
            line = report(k, "      ")
            lines += ["      #5;", "    end"]
            scope = f"top.a{k}.inner"
        else:
            line = report(k, "    ")
            lines.append("    " + wait.replace("{k}", str(k)).replace("\n      ", "\n    "))
            scope = f"top.a{k}"
        lines += [f'    $display("%0t case {k} resumed", $time);', "  end"]
        if trigger:
            lines += [f"  initial begin #{t}; #0 {trigger.replace('{k}', str(k))} end"]
        out.append(f"{t} case {k} resumed")
        if not flushed:
            out.append(f"{t} case {k} deferred fired")
            err.append(f"{NAME}.sv:{line}: warning: unique if violation: no condition is true "
                       f"[{scope} @ {t}ns]")

    base = len(CASES)
    for j, (name, back, flushed) in enumerate(COMB):
        k = base + j
        t = 10 * (k + 1)
        lines += [f"  // case {k}: {name}",
                  f"  int g{k} = 1;",
                  f"  always_comb begin : ac{k}",
                  f'    assert #0 (g{k} == 1) else $display("%0t case {k} deferred fired", $time);',
                  f"    unique if (g{k} == 1) begin end else if (g{k} == 2) begin end"]
        line = line_now()
        lines += ["  end",
                  f"  initial begin #{t}; g{k} = 0;"
                  + (f" #0 g{k} = 1;" if back else "") + " end"]
        if not flushed:
            out.append(f"{t} case {k} deferred fired")
            err.append(f"{NAME}.sv:{line}: warning: unique if violation: no condition is true "
                       f"[top.ac{k} @ {t}ns]")
    lines += ["endmodule", ""]
    return {f"{NAME}.sv": "\n".join(lines), f"{NAME}.expected": "\n".join(out) + "\n",
            f"{NAME}.stderr": "\n".join(err) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_flush_point_matrix: {path.relative_to(OUT.parent.parent.parent)} is "
                      "out of date; run tools/gen_flush_point_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
