"""Original named-fork activity checks: IEEE 1800-2023 9.3.2, 9.6.2.

SCHEDULER_SPEC 10.4/10.7/10.8 and SIR_SPEC 7.2/7.5: end every
started activity, retain descendant ancestry, preserve unrelated children,
queued NBAs and confirmed reports, cancel waits and unconfirmed assertions.
"""
import argparse
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / 'tests/suite/sched'
HOMES = ('unit', 'package', 'module', 'interface', 'program', 'generate', 'branch', 'class', 'always')
JOINS = ('join', 'join_any', 'join_none')
STATE = '''int hit=0, elder=0, later=0, after_count=0, copied=0;
event ready;
'''
BLOCKER = '''task automatic blocker(output int n);
n=7; #4; n=11; hit++;
endtask
'''


def wrap(home, body):
    task = 'task automatic exercise();\n' + body + '\nendtask\n'
    unit = STATE + BLOCKER + task
    if home == 'unit':
        return unit + 'module top;initial exercise();endmodule\n'
    if home == 'package':
        return 'package definitions;\n' + unit + 'endpackage\nmodule top;import definitions::*;initial exercise();endmodule\n'
    if home == 'class':
        state = ''.join('static ' + line + '\n' for line in STATE.splitlines())
        return 'class Box;\n' + state + BLOCKER + task + 'endclass\nmodule top;Box object;initial begin object=new;object.exercise();end endmodule\n'
    if home in ('interface', 'program'):
        kind = 'program automatic' if home == 'program' else home
        return kind + ' unit;\n' + unit + 'initial exercise();end' + home + '\nmodule top;unit u();endmodule\n'
    if home == 'generate':
        return 'module top;if(1)begin:g\n' + unit + 'initial exercise();end endmodule\n'
    if home == 'branch':
        return 'module top;\n' + unit + 'initial fork exercise();join endmodule\n'
    if home == 'always':
        return 'module top;\n' + unit + 'bit kick=0;initial #1 kick=1;always @(posedge kick) exercise();endmodule\n'
    return 'module top;\n' + unit + 'initial exercise();endmodule\n'


def emit(name, source, runtime_error=False):
    name = 'named_fork_disable_' + name
    result = ':expected_stdout:\n:expected_exit: 2\n:expected_stderr_regex: error: disable in a function of a block or task outside the function\n' if runtime_error else ':expected_stdout: errors=0\n'
    return name, f'''/*
:name: {name}
:description: Numeric scope activities cancel a named fork and its retained descendants
:tags: sched fork disable lifetime scopes
:type: simulation
:lrm: 1800-2023 9.3.2 9.6.2 9.6.3 10.4.2 16.4
:oracle: spec
:spec_check: ai
:fourstate: yes
:nondeterministic: no
:generator: gen_named_fork_disable_matrix.py@1
:top_module: top
{result}:timeout: 15
*/
// Generated by tools/gen_named_fork_disable_matrix.py; edit the generator.
`timescale 1ns/1ns
{source}'''


def cases():
    for home in HOMES:
        for wait in ('time', 'event', 'task'):
            # Object/event observation is an explicit unconnected boundary.
            if home == 'class' and wait == 'event':
                continue
            victim = {'time': '#4 hit++;', 'event': '@(ready) hit++;', 'task': 'blocker(copied);'}[wait]
            for mode in ('self', 'external', 'retained'):
                for join in JOINS:
                    if mode == 'self':
                        action = f'''fork : workers
 {victim}
 begin #1;disable workers;end
{join}
after_count++;
fork #4 later++;join_none'''
                    elif mode == 'external':
                        action = f'''fork
 begin : runner
  fork : workers {victim} {join}
  after_count++;
  fork #4 later++;join_none
 end
 begin #1;disable runner.workers;end
join'''
                    else:
                        action = f'''fork : workers
 begin fork {victim} join_none #1;end
{join}
after_count++;
fork #4 later++;join_none
#2;disable workers;'''
                    body = f'''int errors=0;
fork #5 elder++; #5 ->ready;join_none
{action}
#6;
if(hit!=0 || elder!=1 || later!=1 || after_count!=1 || copied!=0) ++errors;
$display("errors=%0d",errors);'''
                    yield emit(f'{home}_{mode}_{join}_{wait}', wrap(home, body))
            body = f'''int errors=0;
fork #5 elder++; #5 ->ready;join_none
fork : workers {victim} join_none
disable workers;
fork #4 later++;join_none
#6;
if(hit!=0 || elder!=1 || later!=1 || copied!=0) ++errors;
$display("errors=%0d",errors);'''
            yield emit(f'{home}_before_start_{wait}', wrap(home, body))
    for home in ('unit', 'package', 'module', 'class'):
        body = '''int errors=0;
launch();#5;
if(hit!=0 || after_count!=1)++errors;
$display("errors=%0d",errors);'''
        source = wrap(home, body)
        function = '''function automatic void launch();
fork : workers #3 hit++;join_none
disable workers;after_count++;
endfunction
'''
        source = source.replace('task automatic exercise();', function + 'task automatic exercise();')
        yield emit(f'{home}_function_own_block', source)
    for home in ('module', 'package', 'program', 'class', 'branch'):
        for join in JOINS:
            body = f'''int errors=0;
fork : workers
 automatic int shared=13;
 begin #1;shared++;if(shared!=14)hit++;disable workers;end
 begin #4;hit+=shared;end
{join}
after_count++;
#6;
if(hit!=0 || after_count!=1)++errors;
$display("errors=%0d",errors);'''
            yield emit(f'{home}_captured_declaration_{join}', wrap(home, body))
    for active in (False, True):
        action = 'begin #1;stop_activity();end' if active else '#0;stop_activity();'
        parallel = 'fork : workers #5; ' + action + ' join' if active else 'fork : workers #5;join_none ' + action
        source = 'module top;function void stop_activity();disable top.workers;endfunction\ninitial begin ' + parallel + ' end endmodule\n'
        yield emit('function_outside_' + ('active' if active else 'returned'), source, True)
    yield emit('sequential_returned_scope', '''module top;
int hit=0,later=0;
initial begin
 int errors=0;
 begin : region fork #4 hit++;join_none end
 fork #3 later++;join_none
 #1;disable region;#5;
 if(hit!=0 || later!=1)++errors;
 $display("errors=%0d",errors);
end endmodule
''')
    for width in (1, 65, 129):
        for kind in ('bit', 'logic'):
            source = f'''module top;
{kind}[{width-1}:0] value=0;
initial begin
 int errors=0;
 fork : workers begin value<=#3 '1;#9;end join_none
 #0;disable workers;#4;
 if(value !== '1)++errors;
 $display("errors=%0d",errors);
end endmodule
'''
            yield emit(f'nba_survives_{kind}_{width}', source)
    for delay, expected in (('#0', 0), ('#1', 1)):
        source = f'''module top;
int count=0;
function void note();count++;endfunction
initial begin
 int errors=0;
 fork : workers begin assert #0 (1) note();end join_none
 {delay};disable workers;#2;
 if(count!={expected})++errors;
 $display("errors=%0d",errors);
end endmodule
'''
        yield emit('report_' + ('unconfirmed' if expected == 0 else 'confirmed'), source)
    yield emit('final_report_unconfirmed', '''module top;
initial begin
 fork : workers begin assert final (1) $display("unexpected final action");end join_none
 #0;disable workers;#1;
 $display("errors=0");
end endmodule
''')
    yield emit('hierarchical_external', '''module leaf;
int hit=0,after_count=0;
initial begin
 fork : workers #4 hit++;join
 after_count++;
end endmodule
module top;
leaf u();
initial begin
 int errors=0;
 #1;disable u.workers;#5;
 if(u.hit!=0 || u.after_count!=1)++errors;
 $display("errors=%0d",errors);
end endmodule
''')
    yield emit('empty_block', '''module top;
initial begin
 fork : workers join
disable workers;
$display("errors=0");
end endmodule
''')
    yield emit('reentrant_automatic', '''module top;
int hit=0,after_count=0;
task automatic launch();
 fork : workers #4 hit++;join
 after_count++;
endtask
initial begin
 int errors=0;
 fork launch();launch();begin #1;disable launch.workers;end join
 #5;
 if(hit!=0 || after_count!=2)++errors;
 $display("errors=%0d",errors);
end endmodule
''')
    yield emit('repeated_activation', '''module top;
int hit=0,later=0;
initial begin
 int errors=0;
 repeat(3)begin
  fork : workers #5 hit++;join_none
 end
 fork #4 later++;join_none
 #1;disable workers;#6;
 if(hit!=0 || later!=1)++errors;
 $display("errors=%0d",errors);
end endmodule
''')
    yield emit('distinct_scope_ids', '''module top;
int hit=0,later=0;
initial begin
 int errors=0;
 fork : first #4 hit++;join_none
 fork : second #3 later++;join_none
 #1;disable first;#3;
 if(hit!=0 || later!=1)++errors;
 disable second;
 $display("errors=%0d",errors);
end endmodule
''')
    yield emit('reuse', '''module top;
int hit=0,later=0;
initial begin
 int n=30,errors=0;
 void'($value$plusargs("n=%d",n));
 repeat(n)begin
  fork : workers begin fork #7 hit++;join_none #1;end join
  #1;disable workers;
  fork #1 later++;join_none
  disable workers;
  #8;
 end
 if(hit!=0 || later!=n)++errors;
 $display("errors=%0d",errors);
end endmodule
''')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = dict(cases())
    failed = False
    for name, source in generated.items():
        path = OUT / (name + '.sv')
        if args.check:
            if not path.exists() or path.read_text() != source:
                print('out of date:', path.relative_to(OUT.parent.parent.parent))
                failed = True
        else:
            path.write_text(source)
    print(f'named fork disable matrix: {len(generated)} sources')
    return int(failed)


if __name__ == '__main__':
    raise SystemExit(main())
