"""Generates the matrix test of the order in which unique, unique0 and
priority if evaluate their conditions, of TEST_SUITE.md ("Mechanism
matrix"), in tests/suite/proc/.

  tools/gen_unique_if_order_matrix.py           # writes the files
  tools/gen_unique_if_order_matrix.py --check   # exit 1 if a file differs from what it would write

The rule: SCHEDULER_SPEC.md 15.1 and 12.4.2 of the standard. priority if
evaluates its conditions in the order written up to the first true one;
unique and unique0 evaluate every condition, in the order written in
kirimasim. The statement of the first true condition runs, or the else.
unique and priority report a violation when no condition is true and
there is no else, unique and unique0 when two are true; the report is
settled in the Observed region of the time slot (15.3). The axes: the
check, which conditions are true (the first, the second, both, none),
whether there is an else, and the container (a module's initial, an
automatic task, a function, a fork branch). Each case has its own time
step.

A person checks the expected output once for all the tests made from it
(TEST_SUITE.md, "Sampling by people").
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "proc"
NAME = "unique_if_order_matrix"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

CHECKS = ["priority", "unique", "unique0"]
TRUTHS = [("first", 1, 0), ("second", 0, 1), ("both", 1, 1), ("none", 0, 0)]
CONTAINERS = ["initial", "task", "function", "fork"]


def outcome(check, a, b, has_else):
    """The statement that runs, the calls of the conditions, and the report."""
    which = "first" if a else "second" if b else "else" if has_else else "none"
    calls = (1 if a else 2) if check == "priority" else 2
    report = None
    if a and b and check != "priority":
        report = "more than one condition is true"
    elif not a and not b and not has_else and check != "unique0":
        report = "no condition is true"
    return which, calls, report


def statement(check, a, b, has_else, target, mark):
    lines = [f"{target} = \"none\";",
             f"{check} if (f(1'b{a})) {target} = \"first\";{mark}",
             f"else if (f(1'b{b})) {target} = \"second\";"]
    if has_else:
        lines.append(f"else {target} = \"else\";")
    return lines


def files():
    head = [
        "/*",
        f":name: {NAME}",
        ":description: priority if evaluates its conditions up to the first true one, unique and "
        "unique0 every condition; the first true statement runs and the violations are reported, "
        "in every container",
        ":tags: proc unique",
        ":type: simulation",
        ":lrm: 1800-2023 12.4.2 12.4.2.1",
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: no",
        ":nondeterministic: no",
        f":generator: gen_unique_if_order_matrix.py@{VERSION}",
        ":top_module: top",
        f":expected_stdout: @{NAME}.expected",
        f":expected_stderr: @{NAME}.stderr",
        "*/",
        "// Generated by tools/gen_unique_if_order_matrix.py; change the generator, not this file.",
        "`timescale 1ns/1ns",
        "module top;",
        "  int n;",
        "  string which;",
        "  function automatic bit f(bit v);",
        "    n++;",
        "    return v;",
        "  endfunction",
    ]
    subs, initial, expected, marks = [], [], [], []
    k, time = 0, 0
    for container in CONTAINERS:
        for check in CHECKS:
            for label, a, b in TRUTHS:
                for has_else in (False, True):
                    time += 1
                    tag = f"{container} {check} {label} {'else' if has_else else 'noelse'}"
                    mark = f"  // MARK{k}"
                    show = f'$display("{tag} %s n=%0d", which, n);'
                    if container == "initial":
                        scope = "top"
                        initial += ["    #1 n = 0;"]
                        initial += ["    " + x for x in statement(check, a, b, has_else, "which",
                                                                   mark)]
                        initial += ["    " + show]
                    elif container == "task":
                        scope = f"top.t{k}"
                        subs += [f"  task automatic t{k}();"]
                        subs += ["    " + x for x in statement(check, a, b, has_else, "which",
                                                               mark)]
                        subs += ["  endtask"]
                        initial += [f"    #1 n = 0; t{k}(); {show}"]
                    elif container == "function":
                        scope = f"top.fn{k}"
                        subs += [f"  function automatic string fn{k}();", "    string w;"]
                        subs += ["    " + x for x in statement(check, a, b, has_else, "w", mark)]
                        subs += ["    return w;", "  endfunction"]
                        initial += [f"    #1 n = 0; which = fn{k}(); {show}"]
                    else:
                        scope = "top"
                        initial += ["    #1 n = 0;", "    fork begin"]
                        initial += ["      " + x for x in statement(check, a, b, has_else, "which",
                                                                     mark)]
                        initial += ["    end join", "    " + show]
                    which, calls, report = outcome(check, a, b, has_else)
                    expected.append(f"{tag} {which} n={calls}")
                    if report:
                        marks.append((k, f"{check} if violation: {report} [{scope} @ {time}ns]"))
                    k += 1
    lines = head + subs + ["  initial begin"] + initial + ["  end", "endmodule", ""]
    where = {}
    for number, line in enumerate(lines, 1):
        if "// MARK" in line:
            where[int(line.rsplit("// MARK", 1)[1])] = number
    lines = [line.split("  // MARK")[0] for line in lines]
    reports = [f"{NAME}.sv:{where[k]}: warning: {text}" for k, text in marks]
    return {f"{NAME}.sv": "\n".join(lines), f"{NAME}.expected": "\n".join(expected) + "\n",
            f"{NAME}.stderr": "\n".join(reports) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_unique_if_order_matrix: {path.relative_to(OUT.parent.parent.parent)} is "
                      "out of date; run tools/gen_unique_if_order_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
