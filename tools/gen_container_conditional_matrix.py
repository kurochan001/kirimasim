from gen_dynamic_container_matrix import HOMES as STORAGE_HOMES, wrap as wrap_storage

HOMES = (*STORAGE_HOMES, 'class_static')


def wrap(home, types, variables, methods, body):
    if home != 'class_static':
        return wrap_storage(home, types, variables, methods, body)
    declarations = ''.join(('' if x.strip().startswith('static ') else 'static ') +
                           x.strip() + ';' for x in variables.split(';') if x.strip())
    methods = methods.replace('function automatic', 'static function automatic')
    methods = methods.replace('task automatic', 'static task automatic')
    return (f'module top; class worker; {types} {declarations} {methods}\n'
            f'static task run(); {body} endtask endclass\n'
            'initial worker::run(); endmodule\n')

OUT = Path(__file__).resolve().parent.parent / 'tests/suite/containers'
VERSION = 1


def output(home, label, types, variables, methods, body, expected):
    name = f'container_conditional_{home}_{label}'
    source = wrap(home, types, variables, methods, body)
    source = '\n'.join(line.rstrip() for line in source.splitlines()) + '\n'
    header = f'''/*
:name: {name}
:description: Conditional container values preserve branch effects, complete element equality, snapshots and destination bounds
:tags: arrays queue conditional
:type: simulation
:lrm: 1800-2023 6.8 7.5 7.6 7.10 11.4.5 11.4.11
:oracle: spec
:spec_check: ai
:fourstate: yes
:nondeterministic: no
:generator: gen_container_conditional_matrix.py@{VERSION}
:top_module: top
:expected_stdout: @{name}.expected
:expected_stderr: @{name}.stderr
*/
// Generated by tools/gen_container_conditional_matrix.py; edit the generator.
`timescale 1ns/1ns
'''
    stderr = ''
    if label in ('effects', 'target_order', 'direct_snapshot'):
        # Preserve slang's warning: operand ordering here is the approved
        # project's choice, not a claim of standard-mandated relative order.
        for number, line in enumerate((header+source).splitlines(), 1):
            if 'first(a,left_calls):second(a,right_calls)' in line:
                column = line.index('a,right_calls)') + 1
                stderr += (f"{name}.sv:{number}:{column}: warning: 'a' is both read and modified in the same expression; the order of evaluation is undefined [-Wread-write]\n")
            if 'r=c?a:replace(a);' in line:
                column = line.index('a);') + 1
                stderr += (f"{name}.sv:{number}:{column}: warning: 'a' is both read and modified in the same expression; the order of evaluation is undefined [-Wread-write]\n")
            if 'rows[select_target(a)]=c?a:b;' in line:
                column = line.index('?a:b') + 2
                stderr += (f"{name}.sv:{number}:{column}: warning: 'a' is both read and modified in the same expression; the order of evaluation is undefined [-Wread-write]\n")
    return {name+'.sv': header+source, name+'.expected': expected, name+'.stderr': stderr}


def values(home, width, domain, kind):
    dims = '[]' if kind == 'array' else '[$]'
    types = f'typedef {domain} [{width-1}:0] word_t;'
    variables = f'word_t a{dims},b{dims},r{dims}; logic [128:0] condition;'
    body = '''a='{word_t'(1),word_t'('1),word_t'(0)};
b='{word_t'(1),word_t'(0),word_t'(0)};
condition=1; r=condition?a:b;
$display("true %0d %0d",r.size(),r[1]===word_t'('1));
condition=0; r=condition?a:b;
$display("false %0d %0d",r.size(),r[1]===word_t'(0));
condition='x; r=condition?a:b;
$display("unknown %0d %0d %0d %0d",r.size(),r[0]===word_t'(1),r[1]===word_t'('x),r[2]===word_t'(0));
r[0]=0; $display("independent %0d",a[0]===word_t'(1));
condition='z; r=condition?a:b;
$display("high_z %0d %0d",r.size(),r[1]===word_t'('x));
condition='x; condition[128]=1; r=condition?a:b;
$display("wide_true %0d",r[1]===word_t'('1));
b='{word_t'(1)}; condition='x; r=condition?a:b;
$display("length %0d",r.size());
a.delete(); b.delete(); r=condition?a:b; $display("empty %0d",r.size());
'''
    expected = ('true 3 1\nfalse 3 1\nunknown 3 1 1 1\nindependent 1\nhigh_z 3 1\n'
                'wide_true 1\nlength 0\nempty 0\n')
    if domain == 'logic':
        body += '''a='{word_t'('z),word_t'('x)}; b=a; r=condition?a:b;
$display("xz_equal %0d %0d",r[0]===word_t'('x),r[1]===word_t'('x));
'''
        expected += 'xz_equal 1 1\n'
        if width > 1:
            body += '''a='{word_t'(2)}; b='{word_t'(3)}; r=condition?a:b;
$display("whole_element %0d",r[0]===word_t'('x));
'''
            expected += 'whole_element 1\n'
    return output(home, f'{kind}_{domain}_{width}', types, variables, '', body, expected)


