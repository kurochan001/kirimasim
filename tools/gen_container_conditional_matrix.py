def files():
    result = {}
    for home in HOMES:
        for width in (1, 4, 32, 64, 65, 129):
            for domain in ('bit', 'logic'):
                for kind in ('array', 'queue'):
                    result.update(values(home, width, domain, kind))
        result.update(mechanisms(home))
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    bad = []
    if not args.check:
        OUT.mkdir(parents=True, exist_ok=True)
    for name, text in files().items():
        path = OUT/name
        if args.check:
            if not path.exists() or path.read_text() != text:
                bad.append(name)
        else:
            path.write_text(text)
    if bad:
        print('gen_container_conditional_matrix: out of date: '+', '.join(bad), file=sys.stderr)
    return int(bool(bad))


if __name__ == '__main__':
    sys.exit(main())
