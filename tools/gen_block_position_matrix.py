#!/usr/bin/env python3
"""Generates the matrix tests of where a block statement is placed, of
TEST_SUITE.md ("Mechanism matrix"): a design whose --dump-sir positions
run_cli_tests.py compares, in tests/cli/, and simulation tests of a
run-time error at a fork, in tests/suite/sched/.

  tools/gen_block_position_matrix.py           # writes the files
  tools/gen_block_position_matrix.py --check   # exit 1 if a file differs from what it would write

A block statement, begin ... end or fork ... join, starts at its first
token: the begin or fork keyword, or the label before it. slang gives a
block the source range of its body, which is the one statement's when
the body has one, so front takes the start of a block from its syntax
(Lowerer::startOf). The fork instruction, the process of each statement
of a fork, and the scope.enter and scope.leave of a named block are
placed there, and so is a run-time error at the fork: a fork in the
Postponed region is one (SCHEDULER_SPEC.md 2.2, 16.2).

The axes: the place of the fork (an initial procedure, a task, a
function, the statement of another fork); the join (join, join_any,
join_none; a function has only join_none); the statements of the fork
(one statement, one begin block, one named block, one labelled block,
two statements); a named block that another process disables, with one
statement or two. For the run-time error: a fork with one statement,
one begin block or two statements, in a function that $strobe, $monitor
or the action of assert final calls.

The expected positions follow from the rules above, computed below.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CLI = ROOT / "tests" / "cli"
SUITE = ROOT / "tests" / "suite" / "sched"
NAME = "block_position_matrix"
PREFIX = "block_position_"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1
POSTPONED = "a write or an event in the Postponed region [top @ 1ns]"

# The statements of a fork: (name, the lines, with the index of each line
# a statement starts on and the text it starts with)
SHAPES = {
    "one": (["#1 n = 1;"], [(0, "#1")]),
    "block": (["begin", "  #1 n = 1;", "end"], [(0, "begin")]),
    "named": (["begin : nb{k}", "  #1 n = 1;", "end"], [(0, "begin")]),
    "labelled": (["lb{k}: begin", "  #1 n = 1;", "end"], [(0, "lb{k}")]),
    "two": (["#1 n = 1;", "#2 n = 2;"], [(0, "#1"), (1, "#2")]),
}
JOINS = ["join", "join_any", "join_none"]
PLACES = ["initial", "task", "function", "fork"]


class Design:
    """Lines of a design, with the positions to expect in its SIR."""

    def __init__(self):
        self.lines = []
        self.expected = []

    def add(self, text, marks=()):
        """Adds a line; each mark (what, the text it is at) expects `what`
        at the column of that text."""
        for what, at in marks:
            self.expected.append(f"{what} 0:{len(self.lines) + 1}:{text.index(at) + 1}")
        self.lines.append(text)

    def fork(self, indent, join, shape, k):
        lines, starts = SHAPES[shape]
        self.add(" " * indent + "fork", [("fork", "fork")])
        for i, line in enumerate(lines):
            text = " " * (indent + 2) + line.format(k=k)
            marks = [("branch", at.format(k=k)) for j, at in starts if j == i]
            self.add(text, marks)
        self.add(" " * indent + join)


def cli_files():
    d = Design()
    d.add(f"// Generated by tools/gen_block_position_matrix.py (version {VERSION}); do not edit.")
    d.add("module top;")
    d.add("  int n;")
    k = 0
    for place in PLACES:
        for join in JOINS:
            if place == "function" and join != "join_none":
                continue
            for shape in SHAPES:
                k += 1
                if place == "initial":
                    d.add("  initial begin")
                    d.fork(4, join, shape, k)
                    d.add("  end")
                elif place == "task":
                    d.add(f"  task automatic t{k}();")
                    d.fork(4, join, shape, k)
                    d.add("  endtask")
                    d.add(f"  initial t{k}();")
                elif place == "function":
                    d.add(f"  function automatic void f{k}();")
                    d.fork(4, join, shape, k)
                    d.add("  endfunction")
                    d.add(f"  initial f{k}();")
                else:
                    # The outer fork's one statement is the inner fork, so
                    # its process starts at the inner fork's keyword.
                    d.add("  initial fork", [("fork", "fork")])
                    first = len(d.expected)
                    d.fork(4, join, shape, k)
                    d.expected.insert(first, d.expected[first].replace("fork", "branch", 1))
                    d.add("  join")
    for count in (1, 2):
        k += 1
        d.add(f"  initial begin : blk{k}", [("scope.enter", "begin"), ("scope.leave", "begin")])
        d.add("    #5 n = 3;")
        if count == 2:
            d.add("    #6 n = 4;")
        d.add("  end")
        d.add(f"  initial #1 disable blk{k};")
    d.add("endmodule")
    file = f"{NAME}.sv"
    return {CLI / file: "\n".join(d.lines) + "\n",
            CLI / f"{NAME}.expected": "\n".join(sorted(d.expected)) + "\n"}


def header(name, description):
    return [
        "/*",
        f":name: {name}",
        f":description: {description}",
        ":tags: sched fork",
        ":type: simulation",
        ":lrm: 1800-2023 4.4.2.9 9.3.2 21.2.2",
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: no",
        ":nondeterministic: no",
        f":generator: gen_block_position_matrix.py@{VERSION}",
        ":issue: 20",
        ":top_module: top",
        f":expected_stdout: @{name}.expected",
        ":expected_exit: 2",
        f":expected_stderr: @{name}.stderr",
        "*/",
        "// Generated by tools/gen_block_position_matrix.py; change the generator, not this file.",
        "`timescale 1ns/1ns",
    ]


# (name, the statement of initial that runs touch() in the Postponed region)
CALLERS = [
    ("strobe", "$strobe(\"%0d\", side());"),
    ("monitor", "$monitor(\"%0d\", side());"),
    ("final", "assert final (0) else touch();"),
]


def postponed_case(shape, caller):
    cname, call = caller
    name = f"{PREFIX}postponed_{shape}_{cname}"
    lines = ["module top;", "  int n = 0;", "  function void touch();", "    fork"]
    body, _ = SHAPES[shape]
    lines += ["      " + x.replace("#1 ", "").replace("#2 ", "") for x in body]
    lines += ["    join_none", "  endfunction", "  function int side();", "    touch();",
              "    return 7;", "  endfunction", "  initial begin", "    #1;", f"    {call}",
              "  end", "  final $display(\"final ran\");", "endmodule"]
    what = {"one": "one statement", "block": "one begin block", "two": "two statements"}[shape]
    description = (f"a run-time error at a fork with {what} in the Postponed region is reported "
                   "at the fork")
    head = header(name, description)
    at = len(head) + lines.index("    fork") + 1
    return name, head + lines, ["final ran"], [f"{name}.sv:{at}: error: {POSTPONED}"]


def files():
    out = cli_files()
    for shape in ("one", "block", "two"):
        for caller in CALLERS:
            name, text, expected, stderr = postponed_case(shape, caller)
            out[SUITE / f"{name}.sv"] = "\n".join(text) + "\n"
            out[SUITE / f"{name}.expected"] = "\n".join(expected) + "\n"
            out[SUITE / f"{name}.stderr"] = "\n".join(stderr) + "\n"
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for path, text in files().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_block_position_matrix: {path.relative_to(ROOT)} is out of date; run "
                      "tools/gen_block_position_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
