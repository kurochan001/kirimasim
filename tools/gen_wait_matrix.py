#!/usr/bin/env python3
"""Generates the wait (expression) matrix test of TEST_SUITE.md ("Mechanism matrix")
in tests/suite/sched/.

  tools/gen_wait_matrix.py           # writes the files
  tools/gen_wait_matrix.py --check   # exit 1 if a file differs from what it would write

wait (expr) goes on at once when expr is true (12.4: 1, not 0, x or z), and
else waits until a change of what expr reads makes it true (9.4.3,
SCHEDULER_SPEC.md 9.3, 9.5). The same waits run in every container
(CLAUDE.md, "The container does not change meaning"): an initial procedure,
an always procedure, a branch of a fork, a static task, an automatic task,
and a task called from a branch of a fork. What the conditions read: a
variable, a bit and a part of a vector, an array element at a constant index
and at a variable index (the index changing), a net of a continuous
assignment, a variable of the container (static or automatic), what an
automatic and a static function read, a value that is x, then z, then 1,
ev.triggered, a variable of a child instance by its hierarchical name, and a
package variable.

Step i of a container starts waiting 2(i - 1) steps after the container
starts; a driver then changes what it reads 2i - 1 steps after the start,
which leaves it false, and 2i steps after, which makes it true. Step 0 is
true at once. Each container gets its own window, and everything is set
back before it.

The expected outputs follow from the rules above. A person checks them
once for all the tests made from them (TEST_SUITE.md, "Sampling by people").
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "sched"
NAME = "wait_condition_matrix"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

# Steps: (label, condition, driver's change that leaves it false, driver's
# change that makes it true, what to show after). Step 0 has no driver.
STEPS = [
    ("at once", "ready", None, None, "ready"),
    ("variable", "v == 3", "v = 1;", "v = 3;", "v"),
    ("bit", "vb[2]", "vb = 8'b0000_1011;", "vb[2] = 1'b1;", "vb"),
    ("part", "vp[7:4] == 4'ha", "vp = 8'h5a;", "vp[7:4] = 4'ha;", "vp"),
    ("element", "arr[1] == 5", "arr[0] = 5;", "arr[1] = 5;", "arr[1]"),
    ("variable index", "arr2[k] == 7", "arr2[0] = 6;", "k = 2;", "k"),
    ("net", "w == 4", "nv = 1;", "nv = 3;", "w"),
    ("container variable", "cnt > lim", "cnt = 4;", "cnt = 5;", "cnt"),
    ("automatic function", "above(5)", "g = 5;", "g = 6;", "g"),
    ("static function", "atleast(3)", "h = 2;", "h = 3;", "h"),
    ("x then z then 1", "u", "u = 1'bz;", "u = 1'b1;", "u"),
    ("triggered", "ev.triggered", "-> other;", "-> ev;", "1'b1"),
    ("hierarchical", "c.q == 1", "c.q = 2;", "c.q = 1;", "c.q"),
    ("package", "pk::pv == 2", "pk::pv = 1;", "pk::pv = 2;", "pk::pv"),
]
WINDOW = 2 * len(STEPS) + 4
CONTAINERS = ["initial", "always", "fork branch", "static task", "automatic task",
              "task in a fork"]


def steps(c, pad):
    """The waits of one container and the lines they show."""
    sv = [f"{pad}lim = 4;"]
    exp = []
    for i, (label, cond, _, _, show) in enumerate(STEPS):
        sv.append(f"{pad}wait ({cond}) $display(\"{c}: {label} at %0d, %0d\", $time - t0, {show});")
        exp.append(f"{c}: {label} at {2 * i}, {value_after(i)}")
    return sv, exp


def value_after(i):
    """What step i shows once its condition is true."""
    return {0: "1", 1: "3", 2: "15", 3: "170", 4: "5", 5: "2", 6: "4", 7: "5", 8: "6", 9: "3",
            10: "1", 11: "1", 12: "1", 13: "2"}[i]


def files():
    sv = (f"/*\n:name: {NAME}\n:description: wait (expression) goes on at once when the "
          "expression is true and else when what it reads makes it true: variables, parts, "
          "elements at constant and variable indices, nets, container variables, what functions "
          "read, x and z, triggered, hierarchical names and package variables, in procedures, "
          "fork branches and tasks\n:tags: sched\n"
          ":type: simulation\n:lrm: 1800-2023 9.4.3 12.4 15.5.3\n:oracle: spec\n"
          ":spec_check: ai\n:fourstate: yes\n:nondeterministic: no\n"
          f":generator: gen_wait_matrix.py@{VERSION}\n"
          f":expected_stdout: @{NAME}.expected\n*/\n"
          "// Generated by tools/gen_wait_matrix.py; change the generator, not this file.\n"
          "// Icarus Verilog 13.0 rejects wait on a function call and on triggered.\n"
          "// The function steps never go on in Verilator 5.052, which does not wait on what\n"
          "// a function reads; 9.4.3 waits on the expression's value. With the functions'\n"
          "// bodies written in their conditions, it gives these lines.\n"
          "`timescale 1ns/1ns\n"
          "package pk;\n  int pv;\nendpackage\n"
          "module child;\n  logic [3:0] q;\nendmodule\n"
          "module top;\n"
          "  time t0;\n  logic go = 1'b0;\n  logic ready;\n  int v, cnt, g, h, k, nv;\n"
          "  logic [7:0] vb, vp;\n  int arr[4], arr2[4];\n  logic u;\n  event ev, other;\n"
          "  wire [7:0] w;\n  assign w = nv + 1;\n  child c();\n"
          "  function automatic bit above(int t);\n    return g > t;\n  endfunction\n"
          "  function bit atleast(int t);\n    atleast = h >= t;\n  endfunction\n")
    # Set everything back before a container starts.
    sv += ("  function void reset();\n    ready = 1'b1;\n    v = 0;\n    vb = 0;\n    vp = 0;\n"
           "    arr = '{0, 0, 0, 0};\n    arr2 = '{0, 0, 7, 0};\n    k = 0;\n    nv = 0;\n"
           "    cnt = 0;\n    g = 0;\n    h = 0;\n    u = 1'bx;\n    c.q = 0;\n    pk::pv = 0;\n"
           "  endfunction\n")
    drive = "  task drive();\n"
    for i, (_, _, false_change, true_change, _) in enumerate(STEPS):
        if i == 0:
            continue
        drive += f"    #1 {false_change}\n    #1 {true_change}\n"
    sv += drive + "  endtask\n"
    body = {c: steps(c, "    ") for c in CONTAINERS}
    nested = steps("fork branch", "          ")
    in_fork = steps("task in a fork", "    ")
    sv += ("  task static ts();\n    int lim;\n" + "\n".join(body["static task"][0]) +
           "\n  endtask\n")
    sv += ("  task automatic ta();\n    int lim;\n" + "\n".join(body["automatic task"][0]) +
           "\n  endtask\n")
    sv += "  task static tf();\n    int lim;\n" + "\n".join(in_fork[0]) + "\n  endtask\n"
    sv += ("  always @(posedge go) begin : in_always\n    int lim;\n" +
           "\n".join(body["always"][0]) + "\n  end\n")
    start = "    t0 = $time;\n    reset();\n    fork\n      drive();\n    join_none\n"
    rest = WINDOW - 2 * (len(STEPS) - 1)
    sv += "  initial begin : in_initial\n    int lim;\n" + start
    sv += "\n".join(body["initial"][0]) + f"\n    #{rest};\n"
    sv += start + f"    go = 1'b1;\n    #{WINDOW};\n"
    sv += (start + "    fork\n      begin : in_fork\n        int lim;\n" +
           "\n".join(nested[0]) + "\n      end\n    join\n" + f"    #{rest};\n")
    sv += start + f"    ts();\n    #{rest};\n"
    sv += start + f"    ta();\n    #{rest};\n"
    sv += start + "    fork\n      tf();\n    join\n  end\nendmodule\n"
    exp = []
    for c in CONTAINERS:
        exp += nested[1] if c == "fork branch" else in_fork[1] if c == "task in a fork" else body[c][1]
    return {f"{NAME}.sv": sv, f"{NAME}.expected": "\n".join(exp) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_wait_matrix: {path.relative_to(OUT.parent.parent.parent)} is out of "
                      "date; run tools/gen_wait_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
