"""Generates the matrix tests of defparam on a parameter declared with
only a sign, only a range, or neither, also beside an override in the
instance (TEST_SUITE.md, "Mechanism matrix") in tests/suite/hier/.

  tools/gen_defparam_declared_sign_matrix.py           # writes the files
  tools/gen_defparam_declared_sign_matrix.py --check   # exit 1 if a file differs from what it would write

The rules: 6.20.2 and 23.10 of the standard.

- A parameter declared with no type and no range takes the type and
  range of the final value given to it.
- A parameter declared signed with no range takes the range of the
  final value, and is signed.
- A parameter declared with a range and no sign keeps its range and is
  unsigned; the final value is converted to it.
- When a defparam and an override in the instance (#(...)) both set a
  parameter, the value of the defparam is the final one.

The axes: the declaration (no type, signed only, a range only), the
value of the defparam (wider than the default, of 8 bits with the top
bit set, narrower, signed negative), whether the instance overrides the
parameter too (with a value of 16 bits), and the place of the instance
(the top module, a generate block, a module below the top).

Each instance prints its parameter at a time of its own. The expected
output is computed here from the values, without reading kirimasim's
code. A person checks it once for all the tests made from it
(TEST_SUITE.md, "Sampling by people").
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "hier"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

# (key, the declaration of P).
DECLS = [("untyped", "parameter P = 1'b0"), ("signed", "parameter signed P = 1'b0"),
         ("ranged", "parameter [7:0] P = 1'b0")]
# (key, the value as written, its width, whether it is signed, its bits).
VALUES = [("wider", "12'hf0f", 12, False, 0xF0F), ("top_bit", "8'd200", 8, False, 200),
          ("narrower", "4'b1010", 4, False, 0b1010), ("negative", "6'sh2a", 6, True, 0x2A)]
PLACES = ["top", "generate", "below"]


def final(decl, width, signed, bits):
    """The value, width and sign of the parameter after the defparam."""
    if decl == "ranged":
        # Converted to 8 bits, unsigned: a signed value is extended by its
        # sign first.
        if signed and bits >> (width - 1):
            bits -= 1 << width
        return bits & 0xFF, 8, False
    signed = signed or decl == "signed"
    value = bits - (1 << width) if signed and bits >> (width - 1) else bits
    return value, width, signed


def test(place):
    name = f"defparam_declared_sign_{place}"
    where = {"top": "the top module", "generate": "a generate block",
             "below": "a module below the top"}[place]
    sv = ["/*", f":name: {name}",
          ":description: a defparam gives a parameter declared with no type, or with only a "
          "sign, the range of its value, and wins over an override in the instance, with the "
          f"instances in {where}",
          ":tags: hier", ":type: simulation", ":lrm: 1800-2023 6.20.2 23.10 23.10.1",
          ":oracle: spec", ":spec_check: ai", ":fourstate: no", ":nondeterministic: no",
          f":generator: gen_defparam_declared_sign_matrix.py@{VERSION}", ":top_module: top",
          f":expected_stdout: @{name}.expected", "*/",
          "// Generated by tools/gen_defparam_declared_sign_matrix.py; change the generator, "
          "not this file.", "`timescale 1ns/1ns"]
    for key, decl in DECLS:
        sv += [f"module leaf_{key} #({decl}, parameter string name = \"\", "
               "parameter int at = 0) ();",
               '  initial #at $display("%s: P=%0d bits=%0d negative=%0d", name, P, $bits(P), '
               "P < 0);", "endmodule"]
    body, expected, at = [], [], 0
    for key, _ in DECLS:
        for vkey, text, width, signed, bits in VALUES:
            for both in (False, True):
                at += 1
                label = f"{key} {vkey} {'both' if both else 'defparam'}"
                inst = f"u{at}"
                over = ".P(16'd7), " if both else ""
                body.append(f'leaf_{key} #({over}.name("{label}"), .at({at})) {inst} ();')
                body.append(f"defparam {inst}.P = {text};")
                value, w, s = final(key, width, signed, bits)
                expected.append(f"{label}: P={value} bits={w} negative={1 if value < 0 else 0}")
    if place == "top":
        sv += ["module top;"] + ["  " + b for b in body] + ["endmodule"]
    elif place == "generate":
        sv += ["module top;", "  if (1) begin : g"] + ["    " + b for b in body]
        sv += ["  end", "endmodule"]
    else:
        sv += ["module middle;"] + ["  " + b for b in body] + ["endmodule"]
        sv += ["module top;", "  middle m ();", "endmodule"]
    return name, sv, expected


def files():
    out = {}
    for place in PLACES:
        name, sv, expected = test(place)
        out[f"{name}.sv"] = "\n".join(sv) + "\n"
        out[f"{name}.expected"] = "\n".join(expected) + "\n"
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print("gen_defparam_declared_sign_matrix: "
                      f"{path.relative_to(OUT.parent.parent.parent)} is out of date; run "
                      "tools/gen_defparam_declared_sign_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
