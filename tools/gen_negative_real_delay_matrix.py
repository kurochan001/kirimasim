#!/usr/bin/env python3
"""Generates the matrix tests of negative and non-finite real delays, of
TEST_SUITE.md ("Mechanism matrix"), in tests/suite/sched/.

  tools/gen_negative_real_delay_matrix.py           # writes the files
  tools/gen_negative_real_delay_matrix.py --check   # exit 1 if a file differs from what it would write

A real delay is rounded to its scope's precision, half away from zero
(3.14.1, 6.12.1; SCHEDULER_SPEC.md 1). A negative one is then read as an
unsigned 64-bit count of those steps, two's complement (9.4.1;
SCHEDULER_SPEC.md 8), and scaled to the design's precision: a delay that
takes the time past the largest time, 2^64 - 1 steps, is a run-time
error of the design, one error line at the statement, exit code 2, and
final runs (16.2). NaN and the infinities convert to x
(VALUE_SEMANTICS.md 7.4), and a delay of x is 0 (9.4.1). A constant
gives what the same value held in a variable gives.

The axes: the form (a constant, and a real or shortreal variable); the
statement (a wait, a nonblocking assignment and a ->> with a delay, at
-2.0); the value (-2.5, a tie, -0.4 and -0.5, rounding to 0 and to -1,
and 1.0/0.0, -1.0/0.0 and 0.0/0.0); the scope's time scale (1ns/1ns, the
design's own precision; 1ns/100ps, where -2.75 is 28 steps, read by a
module whose unit is the step; 1s/1s inside a design of 1ns, where -2.0
is 2^64 - 2 seconds, past the largest time). One file each, since the
times are far apart and an error ends the run.

The expected outputs follow from the rules above, computed below.
"""

from __future__ import annotations

import argparse
import sys
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "sched"
PREFIX = "delay_negative_real_"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1
OVERFLOW = "the delay takes the time past the largest time"
TIME = 1 << 64


def ticks(value, steps_per_unit=1):
    """The time a wait from time 0 on the real `value` ends at, in steps of
    a scope whose unit holds steps_per_unit steps. `value` is a decimal
    text that a double holds exactly or that is not near a tie, so the
    rounding here is the one of the double."""
    steps = (Decimal(value) * steps_per_unit).to_integral_value(rounding=ROUND_HALF_UP)
    return int(steps) % TIME


# The forms: (name, the declaration of the variable or None, the delay
# expression; {v} is the value, {t} the type of the variable)
FORMS = [
    ("const", None, "({v})"),
    ("var", "  {t} d = {v};", "d"),
]
# The statements at -2.0 and 1ns/1ns: (name, the statement with {d}, the
# lines of top that print what it does, the line printed with {time})
STATEMENTS = [
    ("wait", "#{d} $display(\"woke at %0d\", $time);", [], "woke at {time}"),
    ("nba", "q <= #{d} 1'b1;", ["  always @q $display(\"q=%b at %0d\", q, $time);"],
     "q=1 at {time}"),
    ("trigger_nb", "->> #{d} ev;", ["  always @ev $display(\"ev at %0d\", $time);"],
     "ev at {time}"),
]
# The values of a wait at 1ns/1ns: (name, the value, the types)
VALUES = [
    ("tie", "-2.5", ["real", "shortreal"]),
    ("to_zero", "-0.4", ["real"]),
    ("to_minus_one", "-0.5", ["real"]),
    ("inf", "1.0/0.0", ["real"]),
    ("minus_inf", "-1.0/0.0", ["real"]),
    ("nan", "0.0/0.0", ["real"]),
]


def header(name, description, lrm, error):
    lines = [
        "/*",
        f":name: {name}",
        f":description: {description}",
        ":tags: sched delay",
        ":type: simulation",
        ":lrm: 1800-2023 " + " ".join(lrm),
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: yes",
        ":nondeterministic: no",
        f":generator: gen_negative_real_delay_matrix.py@{VERSION}",
        ":issue: 12",
        ":top_module: top",
        f":expected_stdout: @{name}.expected",
    ]
    if error:
        lines += [":expected_exit: 2", f":expected_stderr: @{name}.stderr"]
    return lines + ["*/",
                    "// Generated by tools/gen_negative_real_delay_matrix.py; change the "
                    "generator, not this file."]


def delay(form, value, rtype):
    """The declaration of the variable (or None) and the delay expression."""
    _, decl, expr = form
    if decl is None and rtype != "real":
        value = f"{rtype}'({value})"
    return (None if decl is None else decl.format(t=rtype, v=value)), expr.format(v=value)


def statement_case(stmt, form):
    sname, text, prints, line = stmt
    decl, d = delay(form, "-2.0", "real")
    name = f"{PREFIX}{sname}_{form[0]}"
    lines = ["`timescale 1ns/1ns", "module top;", "  logic q = 1'b0;", "  event ev;"]
    lines += [decl] if decl else []
    lines += prints + [f"  initial {text.format(d=d)}", "endmodule"]
    expected = [line.format(time=ticks("-2.0"))]
    what = {"wait": "a wait", "nba": "a nonblocking assignment", "trigger_nb": "a ->>"}[sname]
    description = (f"{what} with a delay of -2.0 as a "
                   f"{'constant' if form[0] == 'const' else 'real variable'} ends 2^64 - 2 steps on")
    lrm = ["3.14.1", "9.4.1", "9.4.5", "15.5.1", "20.3.1"]
    return name, header(name, description, lrm, False) + lines, expected, None


def value_case(vname, value, rtype, form):
    decl, d = delay(form, value, rtype)
    suffix = "" if rtype == "real" else f"_{rtype}"
    name = f"{PREFIX}{vname}{suffix}_{form[0]}"
    lines = ["`timescale 1ns/1ns", "module top;"]
    lines += [decl] if decl else []
    lines += [f"  initial #{d} $display(\"woke at %0d\", $time);", "endmodule"]
    time = 0 if "/" in value else ticks(value)
    what = f"{rtype} constant" if form[0] == "const" else f"{rtype} variable"
    description = f"a wait on {value} as a {what} ends at {time}"
    lrm = ["3.14.1", "6.12.1", "9.4.1", "20.3.1"]
    return name, header(name, description, lrm, False) + lines, [f"woke at {time}"], None


def finer_case(form):
    decl, d = delay(form, "-2.75", "real")
    name = f"{PREFIX}finer_{form[0]}"
    # The watcher's unit is the step of the precision, so $time there is
    # the count of steps.
    lines = ["`timescale 100ps/100ps", "module top;", "  event done;", "  child u();",
             "  initial begin", "    @done;", "    $display(\"woke at %0d\", $time);", "  end",
             "endmodule", "`timescale 1ns/100ps", "module child;"]
    lines += [decl] if decl else []
    lines += [f"  initial #{d} -> top.done;", "endmodule"]
    description = ("a negative real delay is rounded to the precision of its scope before it "
                   "is read as an unsigned count of steps")
    lrm = ["3.14.1", "3.14.3", "9.4.1", "20.3.1"]
    expected = [f"woke at {ticks('-2.75', 10)}"]
    return name, header(name, description, lrm, False) + lines, expected, None


def coarser_case(form):
    decl, d = delay(form, "-2.0", "real")
    name = f"{PREFIX}coarser_{form[0]}"
    lines = ["`timescale 1ns/1ns", "module top;", "  child u();", "endmodule",
             "`timescale 1s/1s", "module child;"]
    lines += [decl] if decl else []
    lines += [f"  initial #{d} $display(\"woke\");", "  final $display(\"final\");",
              "endmodule"]
    error = lines.index(f"  initial #{d} $display(\"woke\");") + 1
    description = ("a negative real delay in a scope coarser than the design's precision takes "
                   "the time past the largest time")
    lrm = ["3.14.3", "9.4.1"]
    text = header(name, description, lrm, True) + lines
    line = len(text) - len(lines) + error
    stderr = [f"{name}.sv:{line}: error: {OVERFLOW} [top.u @ 0ns]"]
    return name, text, ["final"], stderr


def files():
    cases = [statement_case(s, f) for s in STATEMENTS for f in FORMS]
    cases += [value_case(n, v, t, f) for n, v, types in VALUES for t in types for f in FORMS]
    cases += [finer_case(f) for f in FORMS] + [coarser_case(f) for f in FORMS]
    out = {}
    for name, text, expected, stderr in cases:
        out[f"{name}.sv"] = "\n".join(text) + "\n"
        out[f"{name}.expected"] = "\n".join(expected) + "\n"
        if stderr is not None:
            out[f"{name}.stderr"] = "\n".join(stderr) + "\n"
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_negative_real_delay_matrix: "
                      f"{path.relative_to(OUT.parent.parent.parent)} is out of date; run "
                      "tools/gen_negative_real_delay_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
