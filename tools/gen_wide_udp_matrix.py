"""Original wide UDP terminal, listed/unlisted edge, delay and strength cases.

Dense hold-row variants are separate source investigations: pinned slang
can spend exponential time checking their edge coverage. No diagnostic is
disabled; kernel/SIR tests also exercise wide complete input-state views.
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / 'tests/suite/nets'
VERSION = 1
COUNTS = (31, 32, 33, 63, 64, 65, 127, 128, 129, 257)
HOMES = ('module', 'generate', 'interface', 'program', 'instance_array')


def primitive(count, sequential, known_only=False, cover_unused=False):
    names = [f'i{i}' for i in range(count)]
    text = ('primitive udp_value(result,' + ','.join(names) + ');\noutput result;\n' +
            ('reg result;\n' if sequential else '') +
            'input ' + ','.join(names) + ';\n' +
            ("initial result=1'b1;\n" if sequential else '') + 'table\n')
    def row(parts, state, result):
        return ' '.join(parts) + (' : ' + state if sequential else '') + ' : ' + result + ';\n'
    if sequential:
        for data in ('0', '1'):
            parts = ['?'] * count
            parts[-2], parts[-1] = data, '(01)'
            text += row(parts, '?', data)
        parts = ['?'] * count
        parts[-1] = '(?0)'
        text += row(parts, '?', '-')
        for i in (range(count - 1) if cover_unused else (count - 2,)):
            parts = ['?'] * count
            parts[i] = '*'
            text += row(parts, '?', '-')
    elif known_only:
        for value, result in [('b', '1'), ('x', '0')]:
            parts = ['?'] * count
            parts[-1] = value
            text += row(parts, '', result)
    else:
        for left, right, result in [('0', '?', '0'), ('?', '0', '0'), ('1', '1', '1')]:
            parts = ['?'] * count
            parts[-2], parts[-1] = left, right
            text += row(parts, '', result)
    return text + 'endtable\nendprimitive\n'


def wrap(home, count, steps, sequential=False, delay='', strength='', background=''):
    double = home == 'instance_array'
    declarations = f'logic [{count-1}:0] data;\nwire ' + ('[1:0] ' if double else '') + 'result;\n'
    prefix = 'io.' if home == 'interface' else 'top.' if home == 'program' else ''
    values = [prefix + 'result[1]', prefix + 'result[0]'] if double else [prefix + 'result']
    body, expected = '', ''
    for statement, label, value in steps:
        body += statement.replace('data', prefix + 'data') + '\n'
        if label:
            body += ('$display("' + label + ' ' + ' '.join(['%b'] * len(values)) + '",' +
                     ','.join(values) + ');\n')
            expected += label + ' ' + ' '.join([value] * len(values)) + '\n'
    conns = ','.join([prefix + 'result', *(f'{prefix}data[{i}]' for i in range(count))])
    instance = ('udp_value ' + strength + delay + ('cells[1:0]' if double else 'cell0') +
                '(' + conns + ');\n')
    if home == 'interface':
        source = ('interface signals;\n' + declarations + 'initial begin\n' + body +
                  'end\nendinterface\nmodule top;signals io();\n' + instance + 'endmodule\n')
    elif home == 'program':
        source = ('program stimulus;initial begin\n' + body + 'end\nendprogram\nmodule top;\n' +
                  declarations + instance + 'stimulus p();\nendmodule\n')
    else:
        source = ('module top;\n' + ('if(1)begin:scope0\n' if home == 'generate' else '') +
                  declarations + background + instance + 'initial begin\n' + body + 'end\n' +
                  ('end\n' if home == 'generate' else '') + 'endmodule\n')
    return source, expected


def output(name, source, expected):
    header = f'''/*
:name: {name}
:description: UDP terminal transport and matching preserve wide input counts
:tags: udp gates nets
:type: simulation
:lrm: 1800-2023 29.3.2 29.4 29.5 29.6 29.7 29.9
:fourstate: yes
:nondeterministic: no
:oracle: spec
:spec_check: ai
:generator: gen_wide_udp_matrix.py@{VERSION}
:top_module: top
:expected_stdout: @{name}.expected
:expected_stderr: @{name}.stderr
*/
// Generated by tools/gen_wide_udp_matrix.py (version {VERSION}); do not edit.
`timescale 1ns/1ns
'''
    return {name + '.sv': header + source, name + '.expected': expected, name + '.stderr': ''}


def generated(dense_sequential=False):
    cases = {}
    for count in COUNTS:
        for home in HOMES:
            for sequential in (False, True):
                if sequential:
                    statements = [
                        ("data='0;#1;", 'initial', '1' if dense_sequential else 'x'),
                        (f'data[{count-2}]=1;#1;', 'data', '1' if dense_sequential else 'x'),
                        (f'data[{count-1}]=1;#1;', 'rise', '1'),
                        (f'data[{count-1}]=0;#1;', 'fall', '1'),
                        (f'data[{count-2}]=0;#1;', 'hold', '1'),
                        (f'data[{count-1}]=1;#1;', 'zero', '0'),
                        (f"data[{count-1}]=0;#1;data[{count-2}]='x;#1;", 'unknown_data', '0'),
                        (f'data[{count-1}]=1;#1;', 'unknown_clocked', 'x'),
                        (f'data[{count-1}]=0;#1;data[{count-2}]=1;#1;data[{count-1}]=1;#1;', 'recover', '1'),
                        ('data[0]=1;#1;', 'unused', '1' if dense_sequential else 'x'),
                        ("data[0]='z;#1;", 'unused_z', '1' if dense_sequential else 'x'),
                    ]
                else:
                    statements = [
                        ("data='0;#1;", 'zero', '0'),
                        (f'data[{count-1}]=1;#1;', 'one_input', '0'),
                        (f'data[{count-2}]=1;#1;', 'both', '1'),
                        (f"data[{count-1}]='x;#1;", 'unknown', 'x'),
                        (f'data[{count-2}]=0;#1;', 'dominate', '0'),
                        (f"data[{count-2}]='x;data[{count-1}]=0;#1;", 'other_zero', '0'),
                        (f"data[{count-1}]='z;#1;", 'high_z', 'x'),
                        (f'data[{count-2}]=0;#1;', 'z_zero', '0'),
                    ]
                source, expected = wrap(home, count, statements, sequential)
                name = f'wide_udp_{home}_{"seq" if sequential else "comb"}_{count}'
                cases.update(output(name, primitive(count, sequential, cover_unused=dense_sequential) + source, expected))
    for home, count in [('module', 33), ('generate', 65), ('interface', 129), ('program', 257)]:
        steps = [("data='0;#1;", 'initial', '1'),
                 (f'data[{count-1}]=1;#1;', 'before', '1'),
                 ('#3;', 'delivered', '0')]
        source, expected = wrap(home, count, steps, True, delay='#(3) ')
        cases.update(output(f'wide_udp_delayed_{home}_{count}', primitive(count, True, cover_unused=dense_sequential) + source,
                            expected))
    steps = [("data='0;#1;", 'known_zero', '1'), ('data[32]=1;#1;', 'known_one', '1'),
             ("data[32]='x;#1;", 'unknown', '0'), ("data[32]='z;#1;", 'high_z', '0')]
    source, expected = wrap('module', 33, steps)
    cases.update(output('wide_udp_known_symbol_33', primitive(33, False, True) + source, expected))
    steps = [("data='0;#1;", 'weak_zero', '1'), ('data[31]=1;data[32]=1;#1;', 'weak_one', '1')]
    source, expected = wrap('module', 33, steps, strength='(weak1,weak0) ',
                            background="assign (strong1,strong0) result=1'b1;\n")
    cases.update(output('wide_udp_strength_33', primitive(33, False) + source, expected))
    return cases


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--dense-sequential-repro-dir', type=Path,
                        help='emit blocked sequential-source investigations outside the suite')
    args = parser.parse_args()
    cases = generated()
    if args.dense_sequential_repro_dir:
        blocked = {name: text for name, text in generated(True).items()
                   if '_seq_' in name or name.startswith('wide_udp_delayed_')}
        args.dense_sequential_repro_dir.mkdir(parents=True, exist_ok=True)
        for name, text in blocked.items():
            (args.dense_sequential_repro_dir / name).write_text(text)
        print(f'{len(blocked)//3} sequential source investigations written')
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    failed = []
    for name, text in cases.items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                failed.append(name)
        else:
            path.write_text(text)
    if failed:
        print('generated wide UDP files differ: ' + ', '.join(failed), file=sys.stderr)
        return 1
    print(f'{len(cases)//3} wide UDP source cases ' + ('checked' if args.check else 'written'))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
