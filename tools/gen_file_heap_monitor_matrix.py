"""Generate original heap-backed file-monitor lifetime tests (21.3.2).

Cross queue/dynamic storage, mcd/fd descriptors and five call contexts.
SYSTEM_TASKS 4/6.2 requires Postponed reads, independent file monitors,
continued file output under $monitoroff, and cancellation on file closure.
Selected-cell reads, size reads and binding replacement exercise different
dependencies. Exact expected lines follow the scripted values, not a run.
"""

import argparse
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests/suite/proc"
VERSION = 1


def files():
    result = {}
    for storage in ("queue", "dynamic"):
        for descriptor in ("mcd", "fd"):
            for context in ("initial", "task", "function", "fork", "generate"):
                name = f"file_heap_monitor_{storage}_{descriptor}_{context}"
                declaration = "int values[$];" if storage == "queue" else "int values[];"
                def opening(filename):
                    mode = ', "w"' if descriptor == "fd" else ""
                    return f'$fopen("{filename}"{mode})'
                monitor = '''$fmonitor(first, "A %0d %0d", values[index], values.size());
    $fmonitor(second, "B %0d %0d", values[1], values.size());'''
                helpers, invocation = "", monitor
                if context == "task":
                    helpers = f"task install; {monitor} endtask\n"
                    invocation = "install();"
                elif context == "function":
                    helpers = f"function void install(); {monitor} endfunction\n"
                    invocation = "install();"
                elif context == "fork":
                    invocation = f"fork begin {monitor} end join"
                elif context == "generate":
                    helpers = f"if (1) begin : scope task install; {monitor} endtask end\n"
                    invocation = "scope.install();"
                source = f'''/*
:name: {name}
:description: Heap file-monitor dependencies, postponed values and descriptor lifetime in {context}
:tags: proc
:type: simulation
:lrm: 1800-2023 7.5 7.10 21.2.3 21.3.1 21.3.2
:oracle: spec
:spec_check: ai
:fourstate: no
:nondeterministic: no
:generator: gen_file_heap_monitor_matrix.py@{VERSION}
:top_module: top
:expected_stdout: @{name}.expected
*/
// Generated by tools/gen_file_heap_monitor_matrix.py.
`timescale 1ns/1ns
module top;
  {declaration}
  int first, second, reopened, index;
  {helpers}
  task show(input string filename);
    int fd, count;
    string line;
    fd = $fopen(filename, "r");
    count = $fgets(line, fd);
    while (count > 0) begin
      $write("%s: %s", filename, line);
      count = $fgets(line, fd);
    end
    $fclose(fd);
    $display("%s: end", filename);
  endtask
  initial begin
    values = '{{7,8}};
    index = 0;
    first = {opening('first.txt')};
    second = {opening('second.txt')};
    {invocation}
    #1 values[1] = 9;
    #1 begin values[0] = 10; values[0] = 11; end
    #1 index = 1;
    #1 values = '{{20,21,22}};
    #1 begin $monitoroff; values[1] = 23; end
    #1 begin
      $fclose(first);
      reopened = {opening('reopened.txt')};
      $display("reused %0d", reopened == first);
      index = 0;
      values[0] = 24;
    end
    #1 values[1] = 25;
    #1 begin $fclose(second); values[1] = 26; end
    #1 begin
      $fclose(reopened);
      show("first.txt"); show("second.txt"); show("reopened.txt");
    end
  end
endmodule
'''
                expected = ("reused 1\n"
                            "first.txt: A 7 2\nfirst.txt: A 11 2\nfirst.txt: A 9 2\n"
                            "first.txt: A 21 3\nfirst.txt: A 23 3\nfirst.txt: end\n"
                            "second.txt: B 8 2\nsecond.txt: B 9 2\nsecond.txt: B 21 3\n"
                            "second.txt: B 23 3\nsecond.txt: B 25 3\nsecond.txt: end\n"
                            "reopened.txt: end\n")
                result[name + ".sv"] = "\n".join(line.rstrip() for line in source.splitlines()) + "\n"
                result[name + ".expected"] = expected
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    failures = 0
    for name, text in files().items():
        target = OUT / name
        if args.check:
            if not target.exists() or target.read_text() != text:
                print(f"gen_file_heap_monitor_matrix: out of date: {name}")
                failures += 1
        else:
            target.write_text(text)
    return bool(failures)


if __name__ == "__main__":
    raise SystemExit(main())
