#!/usr/bin/env python3
"""Generates the matrix test of where the format of $sformat and $sformatf
comes from, of TEST_SUITE.md ("Mechanism matrix"), in tests/suite/values/.

  tools/gen_format_source_matrix.py           # writes the files
  tools/gen_format_source_matrix.py --check   # exit 1 if a file differs from what it would write

The second argument of $sformat and the first of $sformatf are formats,
whether or not they are string literals (21.3.3, SYSTEM_TASKS.md 3.13).
Every format here is a constant: a string literal, a string localparam,
an untyped parameter (an integral value whose bytes are the text), a
localparam of a package, a concatenation of literals and a constant
conditional expression. A format known only at run time is not
implemented yet (tests/cli/unsupported_matrix). Each format holds %m,
which prints the hierarchical name of the scope that calls the task, an
unnamed fork adding nothing to it (3.8).

The axes: the task; where the format comes from; the container (an
initial procedure, an automatic task, a function, a branch of a fork, and
an initial procedure in a generate block). Each line shows the string made.

The expected outputs follow from the rules above, computed below. A
person checks them once for all the tests made from them (TEST_SUITE.md,
"Sampling by people").
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "values"
NAME = "format_source_matrix"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

FORMAT = "<%m|%0d|%0h>"
A, B = 5, 255

# (name, the format expression)
SOURCES = [
    ("literal", f'"{FORMAT}"'),
    ("localparam", "LS"),
    ("parameter", "P"),
    ("package", "fmt_pkg::PS"),
    ("concatenation", '{"<%m|", "%0d|%0h>"}'),
    ("conditional", f'(W > 2 ? "{FORMAT}" : "<%m>")'),
]
TASKS = ["$sformatf", "$sformat"]
# (name, the scope %m names there)
CONTAINERS = [("initial", "top"), ("task", "top.t"), ("function", "top.f"), ("fork", "top"),
              ("generate", "top.g")]


def statement(task, expr, tag):
    if task == "$sformatf":
        make = f"s = $sformatf({expr}, a, b);"
    else:
        make = f"$sformat(s, {expr}, a, b);"
    return f'{make} $display("{tag} [%s]", s);'


def files():
    lines, exp = {c: [] for c, _ in CONTAINERS}, []
    for container, scope in CONTAINERS:
        for task in TASKS:
            for source, expr in SOURCES:
                tag = f"{container} {task} {source}"
                lines[container].append(statement(task, expr, tag))
                exp.append(f"{tag} [<{scope}|{A}|{B:x}>]")
    head = [
        "/*",
        f":name: {NAME}",
        ":description: the format of $sformat and $sformatf from a string literal, a string "
        "localparam, an untyped parameter, a package localparam, a concatenation and a constant "
        "conditional, with %m, in an initial procedure, an automatic task, a function, a fork "
        "branch and a generate block",
        ":tags: values strings",
        ":type: simulation",
        ":lrm: 1800-2023 21.3.3 21.2.1.5",
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: no",
        ":nondeterministic: no",
        f":generator: gen_format_source_matrix.py@{VERSION}",
        ":top_module: top",
        f":expected_stdout: @{NAME}.expected",
        "*/",
        "// Generated by tools/gen_format_source_matrix.py; change the generator, not this file.",
        "`timescale 1ns/1ns",
        "package fmt_pkg;",
        f'  localparam string PS = "{FORMAT}";',
        "endpackage",
        "",
        "module top;",
        f'  localparam string LS = "{FORMAT}";',
        f'  parameter P = "{FORMAT}";',
        "  localparam int W = 3;",
        "  string s;",
        f"  int a = {A}, b = {B};",
        "  task automatic t();",
    ]
    body = (head + ["    " + x for x in lines["task"]] + ["  endtask", "  function void f();"]
            + ["    " + x for x in lines["function"]] + ["  endfunction", "  initial begin"]
            + ["    " + x for x in lines["initial"]] + ["    t();", "    f();", "    fork",
                                                         "      begin"]
            + ["        " + x for x in lines["fork"]] + ["      end", "    join", "  end",
                                                         "  if (1) begin : g",
                                                         "    initial begin", "      #1;"]
            + ["      " + x for x in lines["generate"]] + ["    end", "  end", "endmodule", ""])
    return {f"{NAME}.sv": "\n".join(body), f"{NAME}.expected": "\n".join(exp) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_format_source_matrix: {path.relative_to(OUT.parent.parent.parent)} is "
                      "out of date; run tools/gen_format_source_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
