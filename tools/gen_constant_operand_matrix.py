"""Generates the constant operand matrix test of TEST_SUITE.md ("Mechanism
matrix") in tests/suite/values/.

  tools/gen_constant_operand_matrix.py           # writes the files
  tools/gen_constant_operand_matrix.py --check   # exit 1 if a file differs from what it would write

The rule: SIR_SPEC.md 6. Where kirimasim reads the standard otherwise than
slang's constant evaluation, front computes the operation at run time
instead of taking slang's constant, wherever the operation stands in the
expression. The operations: atoi of a constant string with an underscore
before the first digit (VALUE_SEMANTICS.md 7.6: "_5" is 5, slang gives 0)
and a unary plus of a four-state constant with an x bit (3.2: every bit
becomes x, slang keeps the value). The axes: the operation, the
expression that holds it (alone, inside, an assignment pattern, a
streaming concatenation, a concatenation and ?:), and the place (a
procedural assignment, a function's return and an argument of $display).

A person checks the expected output once for all the tests made from it
(TEST_SUITE.md, "Sampling by people").
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "values"
NAME = "constant_operand_matrix"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

# The operation as a 4-bit value: its text, the item an inside list
# compares it with, the 4 bits by the rule, and the result of inside
# (3.10: an x in the item matches anything, an x of the left side makes
# the comparison x).
OPERATIONS = [
    ("atoi", "4'(P.atoi())", "4'd5", "0101", "1"),
    ("plus", "(+Q)", "4'b10x1", "xxxx", "x"),
]

# The expression that holds the operation V, and its 8 bits from V's bits
# and the result of inside.
HOLDERS = [
    ("alone", "{4'h0, V}", lambda v, i: "0000" + v),
    ("inside", "8'(V inside {I})", lambda v, i: "0000000" + i),
    ("pattern", "pair_t'{V, 4'h2}", lambda v, i: v + "0010"),
    ("streaming", "pair_t'({<<4{V, 4'h2}})", lambda v, i: "0010" + v),
    ("concatenation", "{V, 4'h2}", lambda v, i: v + "0010"),
    ("conditional", "{4'h0, (hi ? V : 4'h0)}", lambda v, i: "0000" + v),
]

PLACES = ["assign", "function", "display"]


def files():
    sv = [
        "/*",
        f":name: {NAME}",
        ":description: an operation whose constant front computes at run time gives the same "
        "value wherever it stands in an expression and wherever the expression stands",
        ":tags: values",
        ":type: simulation",
        ":lrm: 1800-2023 6.16.9 11.4.3 11.4.13 11.4.14",
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: yes",
        ":nondeterministic: no",
        f":generator: gen_constant_operand_matrix.py@{VERSION}",
        f":expected_stdout: @{NAME}.expected",
        "*/",
        "// Generated by tools/gen_constant_operand_matrix.py; change the generator, not this file.",
        "module top;",
        "  typedef struct packed { logic [3:0] hi, lo; } pair_t;",
        '  localparam string P = "_5";',
        "  localparam logic [3:0] Q = 4'b10x1;",
        "  logic hi;",
        "  logic [7:0] r;",
    ]
    body, expected = [], []
    k = 0
    for op, text, item, bits, inside in OPERATIONS:
        for holder, shape, value in HOLDERS:
            expr = shape.replace("V", text).replace("I", item)
            label = f"{op} {holder}"
            want = value(bits, inside)
            sv += [f"  function automatic logic [7:0] fn{k}();",
                   f"    return {expr};",
                   "  endfunction"]
            body += [f"    r = {expr};",
                     f'    $display("assign {label} %b", r);',
                     f'    $display("function {label} %b", fn{k}());',
                     f'    $display("display {label} %b", {expr});']
            expected += [f"{place} {label} {want}" for place in PLACES]
            k += 1
    sv += ["  initial begin", "    hi = 1;"] + body + ["  end", "endmodule", ""]
    return {f"{NAME}.sv": "\n".join(sv), f"{NAME}.expected": "\n".join(expected) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_constant_operand_matrix: {path.relative_to(OUT.parent.parent.parent)} "
                      "is out of date; run tools/gen_constant_operand_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
