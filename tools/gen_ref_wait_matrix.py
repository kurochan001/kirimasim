#!/usr/bin/env python3
"""Generates the matrix test of waits through ref arguments of
TEST_SUITE.md ("機構の行列") in tests/suite/sched/.

  tools/gen_ref_wait_matrix.py           # writes the files
  tools/gen_ref_wait_matrix.py --check   # exit 1 if a file differs from what it would write

A ref argument names the caller's variable itself (13.5.2), so a wait in
the task on an expression that reads the ref wakes when that variable
changes (9.4.2, 9.4.3; SCHEDULER_SPEC.md 9.5: the monitor record depends
on what the ref refers to when the wait starts).

The axes: the wait (wait on the ref, wait on a comparison, any change,
posedge, posedge of an expression with a module variable, posedge with
iff); what the ref refers to (a variable, an element of an array, a
whole array of which the task reads an element); how the task is reached
(called from an initial procedure, from a fork branch, and through
another task that passes its own ref on). Every waiter has variables of
its own, which start at 0. At time 5 the driver writes the other
variables an expression reads (no wake); at time 10 + k it writes 1 to
what waiter k's ref refers to; each waiter prints the time it goes on.

The expected outputs follow from the rules above, computed below. A
person checks them once for all the tests made from them (TEST_SUITE.md,
"人の抜き取り").
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "sched"
NAME = "ref_wait_matrix"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

# (name, the wait with {e} for the value read through the ref and {s} and
# {g} for module variables set at time 5)
WAITS = [
    ("wait", "wait ({e});"),
    ("wait_eq", "wait ({e} == 1'b1);"),
    ("any", "@({e});"),
    ("posedge", "@(posedge {e});"),
    ("and", "@(posedge ({e} & {s}));"),
    ("iff", "@(posedge {e} iff {g});"),
]
# (name, the formal, what the task reads, the actual with {k}, what the
# driver writes at time 10)
TARGETS = [
    ("variable", "ref logic e", "e", "a{k}", "a{k}"),
    ("element", "ref logic e", "e", "m{k}[2]", "m{k}[2]"),
    ("array", "ref logic e [0:3]", "e[1]", "m{k}", "m{k}[1]"),
]
CALLERS = ["initial", "fork", "nested"]


def files():
    decl, items, at5, at10, exp = [], [], [], [], []
    k = 0
    for wname, wform in WAITS:
        for tname, formal, read, actual, written in TARGETS:
            for caller in CALLERS:
                tag = f"{wname} {tname} {caller}"
                decl.append(f"  logic a{k} = 1'b0, s{k} = 1'b0, g{k} = 1'b0;")
                decl.append(f"  logic m{k} [0:3] = '{{1'b0, 1'b0, 1'b0, 1'b0}};")
                wait = wform.format(e=read, s=f"s{k}", g=f"g{k}")
                items.append(f"  task automatic w{k}({formal});\n    {wait}\n"
                             f'    $display("{tag} %0t", $time);\n  endtask')
                act = actual.format(k=k)
                if caller == "initial":
                    items.append(f"  initial w{k}({act});")
                elif caller == "fork":
                    items.append(f"  initial fork\n    w{k}({act});\n  join_none")
                else:
                    items.append(f"  task automatic n{k}({formal});\n    w{k}(e);\n  endtask")
                    items.append(f"  initial n{k}({act});")
                at5.append(f"s{k} = 1'b1; g{k} = 1'b1;")
                at10.append(f"{written.format(k=k)} = 1'b1;")
                exp.append(f"{tag} {10 + k}")
                k += 1
    head = [
        "/*",
        f":name: {NAME}",
        ":description: waits in a task on expressions read through a ref argument: wait, any "
        "change, posedge, posedge of an expression with a module variable and with iff, on a "
        "ref to a variable, to an element and to a whole array, from initial, fork and a task "
        "that passes its ref on",
        ":tags: sched arguments",
        ":type: simulation",
        ":lrm: 1800-2023 9.4.2 9.4.3 13.5.2",
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: yes",
        ":nondeterministic: no",
        f":generator: gen_ref_wait_matrix.py@{VERSION}",
        ":top_module: top",
        f":expected_stdout: @{NAME}.expected",
        "*/",
        "// Generated by tools/gen_ref_wait_matrix.py; change the generator, not this file.",
        "`timescale 1ns/1ns",
        "module top;",
    ]
    driver = ["  initial begin", "    #5 " + " ".join(at5), "    #5;"]
    driver += [f"    {w} #1;" for w in at10] + ["    $finish;", "  end"]
    sv = head + decl + items + driver + ["endmodule", ""]
    return {f"{NAME}.sv": "\n".join(sv), f"{NAME}.expected": "\n".join(exp) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_ref_wait_matrix: {path.relative_to(OUT.parent.parent.parent)} is out "
                      "of date; run tools/gen_ref_wait_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
