#!/usr/bin/env python3
"""Generates the fork container matrix test of TEST_SUITE.md ("機構の行列")
in tests/suite/sched/.

  tools/gen_fork_matrix.py           # writes the files
  tools/gen_fork_matrix.py --check   # exit 1 if a file differs from what it would write

A fork statement does the same in every container (CLAUDE.md, "器で意味を
変えない"; SIR_SPEC.md 7.5): its children start when the parent waits or
ends, join waits for all of them, join_any for one, join_none for none,
and wait fork for every child still running (9.3.1, 9.3.2, 9.6.1). The
containers: an initial procedure, an always procedure, a branch of
another fork, a static task, an automatic task, and a task called from a
branch of a fork; a function starts a join_none fork whose children run
after it returns (13.4.4).

The expected outputs follow from the rules above. A person checks them
once for all the tests made from them (TEST_SUITE.md, "人の抜き取り").
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "sched"
NAME = "fork_containers"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

# One container's statements take this many time steps; each runs in its
# own window of this length.
WINDOW = 10


def steps(c, pad):
    """The forks of one container and the lines they show."""
    sv = [
        f"{pad}x = 0;",
        f"{pad}fork",
        f"{pad}  #1 x = x + 1;",
        f"{pad}  #2 x = x + 10;",
        f"{pad}join",
        f"{pad}$display(\"{c} join %0d\", x);",
        f"{pad}y = 0;",
        f"{pad}fork",
        f"{pad}  #1 y = 1;",
        f"{pad}  #3 y = 2;",
        f"{pad}join_any",
        f"{pad}$display(\"{c} join_any %0d\", y);",
        f"{pad}wait fork;",
        f"{pad}$display(\"{c} wait fork %0d\", y);",
        f"{pad}z = 0;",
        f"{pad}fork",
        f"{pad}  #1 z = 5;",
        f"{pad}join_none",
        f"{pad}$display(\"{c} join_none %0d\", z);",
        f"{pad}#2 $display(\"{c} later %0d\", z);",
    ]
    exp = [f"{c} join 11", f"{c} join_any 1", f"{c} wait fork 2", f"{c} join_none 0",
           f"{c} later 5"]
    return sv, exp


def files():
    sv = (f"/*\n:name: {NAME}\n:description: join, join_any, join_none and wait fork do the "
          "same in an initial and an always procedure, a fork branch, static and automatic "
          "tasks, a task called from a fork branch, and a function\n:tags: sched\n"
          ":type: simulation\n:lrm: 1800-2023 9.3.1 9.3.2 9.6.1 13.4.4\n:oracle: spec\n"
          ":spec_check: ai\n:fourstate: no\n:nondeterministic: no\n"
          f":generator: gen_fork_matrix.py@{VERSION}\n"
          f":expected_stdout: @{NAME}.expected\n*/\n"
          "// Generated by tools/gen_fork_matrix.py; change the generator, not this file.\n"
          "// Icarus Verilog 13.0 rejects the delays in the join_none fork of the function,\n"
          "// which 13.4.4 allows; Verilator 5.052 gives these lines.\n"
          "module top;\n  int x, y, z, f;\n  logic go = 1'b0;\n")
    containers = ["initial", "always", "fork branch", "static task", "automatic task",
                  "task in a fork"]
    exp = []
    body = {c: steps(c, "    ") for c in containers}
    nested = steps("fork branch", "        ")
    in_fork = steps("task in a fork", "    ")
    sv += "  task static ts();\n" + "\n".join(body["static task"][0]) + "\n  endtask\n"
    sv += "  task automatic ta();\n" + "\n".join(body["automatic task"][0]) + "\n  endtask\n"
    sv += "  task static tf();\n" + "\n".join(in_fork[0]) + "\n  endtask\n"
    sv += ("  function void fn();\n    f = 0;\n    fork\n      #1 f = 7;\n    join_none\n"
           "  endfunction\n")
    sv += "  always @(posedge go) begin\n" + "\n".join(body["always"][0]) + "\n  end\n"
    sv += "  initial begin\n" + "\n".join(body["initial"][0]) + "\n"
    sv += f"    #{WINDOW} go = 1'b1;\n    #{WINDOW};\n"
    sv += "    fork\n      begin\n" + "\n".join(nested[0]) + "\n      end\n    join\n"
    sv += f"    #{WINDOW};\n    ts();\n    #{WINDOW};\n    ta();\n    #{WINDOW};\n"
    sv += "    fork\n      tf();\n    join\n"
    sv += (f"    #{WINDOW};\n    fn();\n    $display(\"function returned %0d\", f);\n"
           "    #2 $display(\"function later %0d\", f);\n  end\nendmodule\n")
    for c in ["initial", "always", "fork branch", "static task", "automatic task"]:
        exp += body[c][1] if c != "fork branch" else nested[1]
    exp += in_fork[1]
    exp += ["function returned 0", "function later 7"]
    return {f"{NAME}.sv": sv, f"{NAME}.expected": "\n".join(exp) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_fork_matrix: {path.relative_to(OUT.parent.parent.parent)} is out of "
                      "date; run tools/gen_fork_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
