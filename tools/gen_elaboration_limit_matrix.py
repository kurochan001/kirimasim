"""Generate original tests for CLI 2.1 and UNSPECIFIED_BEHAVIOR A11/A12.

The four frontend budgets have distinct, finite workloads in four contexts.
No runtime budget or expectation is changed. IEEE 1800 13.4.3 and 27 describe
constant functions and elaboration; numeric budgets belong to pinned slang.
"""

import argparse
import json
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / 'tests/cli/elaboration_limits'
VERSION = 1
FLAGS = ('max-hierarchy-depth', 'max-generate-steps',
         'max-constexpr-depth', 'max-constexpr-steps')
REASONS = ('instantiation exceeded maximum depth of 1',
           'generate loop hit maximum step limit',
           'constant evaluation exceeded maximum depth of 1 calls',
           'constant evaluation hit maximum step limit')


def files():
    prefix = ('// Copyright (c) 2026 The kirimasim Authors\n'
              '// SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception\n'
              f'// Generated by tools/gen_elaboration_limit_matrix.py@{VERSION}.\n')
    sources = {'clean.sv': prefix + 'module top; initial $display("7"); endmodule\n'}
    cases = []
    for index, flag in enumerate(FLAGS):
        for context in range(4):
            name = f'{flag.removeprefix("max-")}_{context}'
            if index == 0:
                middle = ('leaf u();', 'if (1) begin : g leaf u(); end',
                          'leaf u[1:0]();', 'leaf u();')[context]
                kind = 'interface' if context == 3 else 'module'
                source = (f'{kind if context == 3 else "module"} leaf; end{kind if context == 3 else "module"}\n'
                          f'{kind} middle; {middle} end{kind}\n'
                          'module top; middle u(); initial $display("7"); endmodule\n')
            elif index == 1:
                loop = 'for (genvar i=0; i<8; i++) begin : g localparam int P=i; end\n'
                if context == 0:
                    source = 'module top;\n' + loop + 'initial $display("7"); endmodule\n'
                elif context in (1, 2):
                    kind = 'interface' if context == 1 else 'program'
                    source = (f'{kind} holder;\n' + loop + f'end{kind}\n'
                              'module top; holder u(); initial $display("7"); endmodule\n')
                else:
                    source = ('module top; if (1) begin : outer\n' + loop +
                              'end initial $display("7"); endmodule\n')
            else:
                function = ('function automatic int f(input int n);\n'
                            '  if (n == 0) return 7; return f(n-1);\nendfunction\n'
                            if index == 2 else
                            'function automatic int f(input int n);\n'
                            '  int total=0; for (int i=0; i<n; i++) total++;\n'
                            '  return total;\nendfunction\n')
                body = function + f'localparam int P=f({6 if index == 2 else 7});\n'
                if context == 0:
                    source = 'module top;\n' + body + 'initial $display("%0d",P); endmodule\n'
                elif context == 1:
                    source = ('package values;\n' + body + 'endpackage\n'
                              'module top; initial $display("%0d", values::P); endmodule\n')
                elif context == 2:
                    source = ('interface values;\n' + body + 'endinterface\n'
                              'module top; values u(); initial $display("%0d",u.P); endmodule\n')
                else:
                    source = ('module top;\n' + function + 'if (1) begin : g\n' +
                              f'localparam int P=f({6 if index == 2 else 7});\n' +
                              'end initial $display("%0d",g.P); endmodule\n')
            sources[name + '.sv'] = prefix + source
            cases.append({'name': name, 'flag': flag, 'low': 1, 'high': 1024,
                          'reason': REASONS[index], 'stdout': '7\n'})
    endless = {
        'hierarchy': ('module recur #(parameter int N=0); recur #(N+1) u(); endmodule\nmodule top; recur u(); endmodule\n',
                      FLAGS[0], 'maximum depth of 4'),
        'generate': ('module top; for(genvar i=0; 1; i++) begin:g localparam int P=i; end endmodule\n',
                     FLAGS[1], REASONS[1]),
        'call': ('module top; function automatic int f(input int n); return f(n+1); endfunction\n'
                 'localparam int P=f(0); endmodule\n', FLAGS[2], 'maximum depth of 4 calls'),
        'steps': ('module top; function automatic int f(); int n=0; while(1) n++; return n; endfunction\n'
                  'localparam int P=f(); endmodule\n', FLAGS[3], REASONS[3]),
    }
    stops = []
    for name, (source, flag, reason) in endless.items():
        filename = 'endless_' + name + '.sv'
        sources[filename] = prefix + source
        stops.append({'source': filename, 'flag': flag, 'value': 4, 'reason': reason})
    sources['cases.json'] = json.dumps({'finite': cases, 'endless': stops}, indent=2) + '\n'
    return sources


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    failures = []
    for name, content in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                failures.append(name)
        else:
            OUT.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    for name in failures:
        print(f'gen_elaboration_limit_matrix: regenerate {name}')
    return bool(failures)


if __name__ == '__main__':
    raise SystemExit(main())
