"""Check initial force/procedural-assign evaluation against its own changes.

SCHEDULER_SPEC 5/12 and IEEE 1800-2023 4.9.2/10.6 require sensitivity
before the first evaluation too. All values have settled to zero before
the override starts; its first evaluation changes the value to one and
therefore schedules a second evaluation, which leaves the value unchanged.
The called function prints each evaluation. No external test was used.

Axes: module/generate/interface, variable force/net force/procedural assign,
two/four-state function values, and a call used directly or within a bitwise
expression. Net declarations remain four-state; only variables and function
arguments/results take the two-state declaration in that axis.
Only this generator's new files are written or checked; existing tests and
expectations are untouched.
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "sched"


def files():
    result = {}
    for place in ("module", "generate", "interface"):
        for kind in ("force_var", "force_net", "assign_var"):
            for domain in ("two", "four"):
                for rhs in ("call", "expression"):
                    name = f"override_initial_{place}_{kind}_{domain}_{rhs}"
                    clause = "10.6.1" if kind == "assign_var" else "10.6.2"
                    header = [
                        "/*", f":name: {name}",
                        ":description: initial override evaluation observes its own change before sensitivity can be lost",
                        ":tags: sched continuous_assignment",
                        ":type: simulation", f":lrm: 1800-2023 4.9.2 {clause}",
                        ":oracle: spec", ":spec_check: ai",
                        f":fourstate: {'yes' if domain == 'four' else 'no'}",
                        ":nondeterministic: no",
                        ":generator: gen_override_initial_matrix.py@1",
                        ":top_module: top", f":expected_stdout: @{name}.expected", "*/",
                        "// Generated by tools/gen_override_initial_matrix.py; edit the generator.",
                        "`timescale 1ns/1ns",
                    ]
                    value_type = "bit" if domain == "two" else "logic"
                    body = (["wire logic value;", "assign value = 1'b0;"]
                            if kind == "force_net" else [f"{value_type} value = 1'b0;"])
                    body += [f"function automatic {value_type} step(input {value_type} arg);",
                             '  $display("seen=%b", arg);', "  return 1'b1;", "endfunction",
                             "initial begin", "  #1;"]
                    expression = "step(value)" if rhs == "call" else "value | step(value)"
                    operation = "assign" if kind == "assign_var" else "force"
                    body += [f"  {operation} value = {expression};",
                             '  #1 $display("value=%b", value);', "  $finish(0);", "end"]
                    if place == "interface":
                        source = ["interface environment;"] + [f"  {line}" for line in body]
                        source += ["endinterface", "module top;", "  environment env();", "endmodule"]
                    elif place == "generate":
                        source = ["module top;", "  if (1) begin : generated"]
                        source += [f"    {line}" for line in body]
                        source += ["  end", "endmodule"]
                    else:
                        source = ["module top;"] + [f"  {line}" for line in body] + ["endmodule"]
                    result[name + ".sv"] = "\n".join(header + source) + "\n"
                    result[name + ".expected"] = "seen=0\nseen=1\nvalue=1\n"
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    bad = []
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                bad.append(name)
        else:
            path.write_text(text)
    if bad:
        print("override initial matrix: differs: " + ", ".join(bad), file=sys.stderr)
    return int(bool(bad))


if __name__ == "__main__":
    sys.exit(main())
