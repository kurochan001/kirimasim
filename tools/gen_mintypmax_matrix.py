"""Generate min:typ:max tests and their expected output (11.11, CLI.md 2.2).

The selected delay is 2, 5 or 9 ns. Drivers change 20 ns after time zero;
each procedural delay takes the selected duration. Only the selected
side-effecting expression runs. Expected values come from this rule,
independently of the simulator.
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "cli"
NAME = "mintypmax_matrix"
VERSION = 1


def files():
    source = f"""// Generated by tools/gen_mintypmax_matrix.py@{VERSION}; edit the generator.
// IEEE 1800-2023 11.11, SCHEDULER_SPEC.md 12, CLI.md 2.2.
module delayed(input bit a, output wire q);
  timeunit 1ns; timeprecision 1ns;
  assign #(2:5:9) q = a;
endmodule
module top;
  timeunit 1ns; timeprecision 1ns;
  localparam int WIDTH = (2:5:9);
  logic [WIDTH-1:0] sized;
  bit a, nba;
  wire cont, gate_out, child_out;
  int calls[3];
  int lo, typical, hi;
  time cont_at, gate_at, child_at;
  assign #(2:5:9) cont = a;
  buf #(2:5:9) g(gate_out, a);
  delayed u(a, child_out);
  initial @(posedge cont) cont_at = $time;
  initial @(posedge gate_out) gate_at = $time;
  initial @(posedge child_out) child_at = $time;
  function automatic int choose(input int branch, input int value);
    calls[branch]++;
    return value;
  endfunction
  task automatic wait_selected(output time elapsed);
    time start;
    start = $time;
    #(lo:typical:hi);
    elapsed = $time - start;
  endtask
  initial begin
    time start, elapsed;
    int value;
    logic [3:0] unknown;
    lo = 2; typical = 5; hi = 9;
    #20 a = 1;
    #20;
    $display("width %0d", $bits(sized));
    $display("drivers %0d %0d %0d", cont_at, gate_at, child_at);
    start = $time;
    #(2:5:9);
    $display("constant %0d", $time - start);
    start = $time;
    #(lo:typical:hi);
    $display("dynamic %0d", $time - start);
    start = $time;
    value = #(lo:typical:hi) 17;
    $display("blocking %0d %0d", $time - start, value);
    start = $time;
    nba <= #(choose(0, lo):choose(1, typical):choose(2, hi)) 1;
    @(posedge nba);
    $display("nba %0d %0d %0d %0d", $time - start, calls[0], calls[1], calls[2]);
    wait_selected(elapsed);
    $display("task %0d", elapsed);
    start = $time;
    fork
      begin
        #(lo:typical:hi);
      end
    join
    $display("fork %0d", $time - start);
    // The unary plus follows kirimasim's four-state rule in each branch
    // (VALUE_SEMANTICS.md 3.2), even if slang has a folded constant.
    unknown = (+(4'b10x1):+(4'b1z01):+(4'bx011));
    $display("unknown %b", unknown);
  end
endmodule
"""
    result = {NAME + ".sv": source}
    for branch, (mode, delay) in enumerate((("min", 2), ("typ", 5), ("max", 9))):
        called = [int(i == branch) for i in range(3)]
        result[f"{NAME}.{mode}.expected"] = "\n".join([
            f"width {delay}", "drivers " + " ".join([str(20 + delay)] * 3),
            f"constant {delay}", f"dynamic {delay}", f"blocking {delay} 17",
            f"nba {delay} " + " ".join(map(str, called)),
            f"task {delay}", f"fork {delay}", "unknown xxxx", "",
        ])
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"{name}: run tools/gen_mintypmax_matrix.py", file=sys.stderr)
                return 1
        else:
            path.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
