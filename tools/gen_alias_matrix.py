#!/usr/bin/env python3
"""Generates the net alias matrix test of TEST_SUITE.md ("Mechanism matrix") in
tests/suite/nets/.

  tools/gen_alias_matrix.py           # writes the files
  tools/gen_alias_matrix.py --check   # exit 1 if a file differs from what it would write

alias joins whole nets of one type into one net (10.11; SIR_SPEC.md 3.5):
every name reads the same value, and the drivers of all of them resolve
together. The axes: the spelling (two nets, three nets in one statement,
two statements that share a net, an alias written before the nets are
driven), the drivers (one name driven, two names driven, a wand), the
width (one bit, a vector), the container (a module body, a generate
block, a child module), and a force through one name seen through the
others.

The expected outputs follow from the rule above and the resolution of
VALUE_SEMANTICS.md 5.4 (the rule of gen_resolution_matrix.py). A person
checks them once for all the tests made from them (TEST_SUITE.md, "Sampling
by people").
"""

import argparse
import itertools
import sys
from pathlib import Path

from gen_resolution_matrix import resolve, value_of

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "nets"
NAME = "net_alias"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

VALUES = ["0", "1", "x", "z"]


def wire(*drivers):
    return value_of(resolve("wire", [(d, 6, 6) for d in drivers]))


def wand(*drivers):
    return value_of(resolve("wand", [(d, 6, 6) for d in drivers]))


def files():
    sv = (f"/*\n:name: {NAME}\n:description: alias joins whole nets into one: every name reads "
          "its value, the drivers of all names resolve together, and a force through one name "
          "is seen through the others, in several spellings and containers\n:tags: nets\n"
          ":type: simulation\n:lrm: 1800-2023 10.11 6.6.1 6.6.3 10.6.2\n"
          ":oracle: spec\n:spec_check: ai\n:fourstate: yes\n:nondeterministic: no\n"
          f":generator: gen_alias_matrix.py@{VERSION}\n:expected_stdout: @{NAME}.expected\n*/\n"
          "// Generated by tools/gen_alias_matrix.py; change the generator, not this file.\n"
          "// Icarus Verilog 13.0 does not take alias. Verilator 5.052 rejects a net in two\n"
          "// alias statements, which 10.11 allows, and keeps no x or z.\n"
          "module child(input i, input j);\n  wire c1, c2;\n  alias c1 = c2;\n"
          "  assign c1 = i;\n  assign c2 = j;\nendmodule\n"
          "module top;\n  logic p, q;\n  logic [3:0] v;\n"
          # two nets, one driven
          "  wire a1, a2;\n  alias a1 = a2;\n  assign a2 = p;\n"
          # three nets in one statement, driven through two names
          "  wire b1, b2, b3;\n  alias b1 = b2 = b3;\n  assign b1 = p;\n  assign b3 = q;\n"
          # two statements sharing a net
          "  wire c1, c2, c3;\n  alias c1 = c2;\n  alias c2 = c3;\n  assign c3 = q;\n"
          # an alias before the nets are driven, vectors
          "  wire [3:0] d1, d2;\n  alias d2 = d1;\n  assign d1 = v;\n"
          # wand nets driven through both names
          "  wand e1, e2;\n  alias e1 = e2;\n  assign e1 = p;\n  assign e2 = q;\n"
          "  generate\n    if (1) begin : gen\n      wire g1, g2;\n      alias g1 = g2;\n"
          "      assign g1 = q;\n    end\n  endgenerate\n"
          "  child u (p, q);\n"
          "  initial begin\n")
    fmt = ("a=%b%b b=%b%b%b c=%b%b%b d=%h%h e=%b%b gen=%b%b child=%b%b")
    args = ("a1, a2, b1, b2, b3, c1, c2, c3, d1, d2, e1, e2, gen.g1, gen.g2, u.c1, u.c2")
    exp = ""

    def line(tag, p, q, v, forced=None):
        a = p
        b = wire(p, q)
        c = q
        d = v
        e = wand(p, q)
        g = q
        ch = wire(p, q)
        if forced is not None:
            a = forced
        return (f"{tag} a={a}{a} b={b}{b}{b} c={c}{c}{c} d={d}{d} e={e}{e} gen={g}{g} "
                f"child={ch}{ch}\n")

    for p, q in itertools.product(VALUES, VALUES):
        v = {"0": "5", "1": "a", "x": "x", "z": "z"}[p]
        bits = {"5": "0101", "a": "1010", "x": "xxxx", "z": "zzzz"}[v]
        sv += (f"    p = 1'b{p}; q = 1'b{q}; v = 4'b{bits};\n"
               f"    #1 $display(\"{p}{q} {fmt}\", {args});\n")
        exp += line(f"{p}{q}", p, q, v)
    # A force through one name is a force of the one net (10.6.2).
    sv += ("    p = 1'b0;\n    force a2 = 1'b1;\n"
           f"    #1 $display(\"force {fmt}\", {args});\n"
           "    release a2;\n"
           f"    #1 $display(\"release {fmt}\", {args});\n  end\nendmodule\n")
    exp += line("force", "0", "z", "z", forced="1")
    exp += line("release", "0", "z", "z")
    return {f"{NAME}.sv": sv, f"{NAME}.expected": exp}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_alias_matrix: {path.relative_to(OUT.parent.parent.parent)} is out of "
                      "date; run tools/gen_alias_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
