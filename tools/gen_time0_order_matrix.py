"""The order of procedures at time 0, written in every source order.

The standard fixes that static initial values come first and that always_comb
and always_latch start after initial and always procedures (6.8, 10.5, 9.2.2.2,
9.2.2.3). It leaves the rest open (4.7), so each test allows every order it
permits in <name>.expected, and <name>.choice holds the one of SCHEDULER_SPEC.md
6.1: continuous assignments, then always procedures that do not start with an
event control, then initial procedures, then always_comb and always_latch, with
source order within each step. The result does not depend on the source order.
Every expected result is computed here from these rules, not from a run.
"""
import argparse
import itertools
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / 'tests/suite/sched'

PREAMBLE = """logic a=1'b1;
logic r;
logic l;
wire w;
function automatic logic note_cont(); $write("cont,"); return a; endfunction
function automatic logic note_decl(); $write("decl,"); return a; endfunction
function automatic logic note_p(); $write("p,"); return a; endfunction
function automatic logic note_q(); $write("q,"); return a; endfunction
"""
ITEMS = {
    'cont': 'assign w=note_cont();',
    'decl': 'wire n=note_decl();',
    'always': 'always begin $write("always,"); #10; end',
    'initial': 'initial $write("initial,");',
    'comb': 'always_comb begin r=1\'b1; $write("comb,"); end',
    'latch': 'always_latch begin if (a===1\'b1 || a!==1\'b1) l=1\'b1; $write("latch,"); end',
}
PROCEDURES = ('always', 'initial')
LAST = ('comb', 'latch')
RANK = {'cont': 0, 'decl': 0, 'always': 1, 'initial': 2, 'comb': 3, 'latch': 3}
END = 'initial begin #1 $display("end"); $finish; end\n'


def allowed(kinds, tail=()):
    """Every order the standard allows: always_comb and always_latch after every
    always and initial (9.2.2.2, 9.2.2.3). It says nothing of continuous assignments
    against them (4.9.1), or of always_comb against always_latch."""
    orders = []
    for order in itertools.permutations(kinds):
        positions = {k: i for i, k in enumerate(order)}
        if all(positions[a] < positions[b] for a in kinds if a in PROCEDURES for b in kinds if b in LAST):
            orders.append(','.join((*order, *tail, 'end')))
    return orders


def place(home, items):
    if home == 'generate':
        return f'module top;\nif(1) begin:g\n{items}end\nendmodule\n'
    if home == 'interface':
        return f'interface unit;\n{items}endinterface\nmodule top;\nunit u();\nendmodule\n'
    return f'module top;\n{items}endmodule\n'


def source(name, description, text, candidates, choice, lrm):
    assert choice in candidates, (name, choice)
    name = 'time0_' + name
    expected = '---\n'.join(c + '\n' for c in candidates)
    head = f'''/*
:name: {name}
:description: {description}
:tags: sched time0
:type: simulation
:lrm: 1800-2023 {lrm}
:oracle: spec choice
:spec_check: ai
:fourstate: yes
:nondeterministic: yes
:generator: gen_time0_order_matrix.py@1
:top_module: top
:expected_stdout: @{name}.expected
:timeout: 15
*/
// Generated by tools/gen_time0_order_matrix.py; edit the generator.
`timescale 1ns/1ns
'''
    return name, head + text, expected, choice + '\n'


def orders():
    """Every source order of each set of kinds of procedure."""
    sets = (('cont', 'always', 'initial', 'comb'), ('cont', 'always', 'initial', 'latch'),
            ('decl', 'always', 'initial', 'comb'), ('always', 'initial', 'comb', 'latch'))
    for kinds in sets:
        homes = ('module', 'generate', 'interface') if kinds == sets[0] else ('module',)
        candidates = allowed(kinds)
        for home in homes:
            for order in itertools.permutations(kinds):
                chosen = ','.join((*sorted(order, key=lambda k: RANK[k]), 'end'))
                items = PREAMBLE + ''.join(ITEMS[k] + '\n' for k in order) + END
                yield source(f'{home}_{"_".join(order)}', 'The procedures start in the same order, however the source orders them',
                             place(home, items), candidates, chosen, '4.7 4.9.1 9.2.2.2 9.2.2.3')


DRIVERS = {
    'assign': ('wire w;\nassign w=a;', '1'),
    'decl': ('wire w=a;', '1'),
    'gate': ('wire w;\nbuf g(w,a);', '1'),
    'udp': ('wire w;\ninvert g(w,a);', '0'),
    'port': ('wire w;\nsub u(.i(a),.o(w));', '1'),
}
READERS = {
    'initial': 'initial $display("%b",w);',
    'always': 'always begin $display("%b",w); #10; end',
}
HELPERS = """primitive invert(output o,input i);
table
 0 : 1;
 1 : 0;
 x : x;
endtable
endprimitive
module sub(input i,output o);
assign o=i;
endmodule
"""


def values():
    """A procedure reads what the drivers of time 0 give, written before or after them."""
    for home in ('module', 'generate'):
        for driver, (declaration, value) in DRIVERS.items():
            for reader, statement in READERS.items():
                for first in ('driver', 'reader'):
                    parts = (declaration, statement) if first == 'driver' else (statement, declaration)
                    if first == 'reader':
                        # A net is declared before its first use, whatever comes next.
                        head, _, rest = declaration.partition('\n')
                        parts = (head, statement, rest) if rest else (statement, declaration)
                        if not rest:
                            parts = ("wire w;", statement, f'assign w=a;') if driver == 'decl' else parts
                    items = "logic a=1'b1;\n" + '\n'.join(parts) + '\n' + 'initial #1 $finish;\n'
                    text = HELPERS + place(home, items)
                    yield source(f'value_{home}_{driver}_{reader}_{first}_first',
                                 'A procedure at time 0 reads what the drivers give, wherever they are written',
                                 text, [value, 'x'], value, '4.7 4.9.1 10.3')
    for reader, statement in READERS.items():
        for first in ('comb', 'reader'):
            comb = "always_comb w=a;"
            parts = (comb, statement) if first == 'comb' else (statement, comb)
            items = "logic a=1'b1;\nlogic w;\n" + '\n'.join(parts) + '\ninitial #1 $finish;\n'
            yield source(f'value_comb_{reader}_{first}_first', 'always_comb starts after the procedure that reads it',
                         place('module', items), ['x', '1'], 'x', '4.7 9.2.2.2')


WAITERS = {
    'negedge': "always @(negedge r) $display(\"caught\");",
    'ff': "always_ff @(negedge r) $display(\"caught\");",
    'level': "always @(r) $display(\"caught\");",
    'star': "always @* if (r===1'b0) $display(\"caught\");",
    'event': "always @(e) $display(\"caught\");",
    'begin': "always begin @(negedge r) $display(\"caught\"); end",
}


def waiters():
    """A procedure that starts with an event control sees what an initial does at time 0."""
    for home in ('module', 'generate'):
        for kind, waiter in WAITERS.items():
            start = "initial ->e;" if kind == 'event' else "initial r=1'b0;"
            for first in ('waiter', 'initial'):
                parts = (waiter, start) if first == 'waiter' else (start, waiter)
                items = 'logic r;\nevent e;\n' + '\n'.join(parts) + '\ninitial begin #1 $display("end"); $finish; end\n'
                yield source(f'wait_{home}_{kind}_{first}_first',
                             'A procedure that starts with an event control is waiting before anything runs',
                             place(home, items), ['caught\nend', 'end'], 'caught\nend', '4.7 9.4.2 15.5.2')


def within():
    """Within a step, the order of the source; among instances, of the instances."""
    for kind, line in (('cont', 'assign w{0}=note_{0}();'), ('always', 'always begin $write("{0},"); #10; end'),
                       ('initial', 'initial $write("{0},");'), ('comb', 'always_comb begin r{0}=1\'b1; $write("{0},"); end')):
        for names in (('p', 'q'), ('q', 'p')):
            lines = ''.join(line.format(n) + '\n' for n in names)
            decls = "wire wp,wq;\nlogic rp,rq;\n"
            items = "logic a=1'b1;\n" + decls + PREAMBLE.split('wire w;\n')[1] + lines + END
            candidates = [f'{x},{y},end' for x, y in (('p', 'q'), ('q', 'p'))]
            yield source(f'step_{kind}_{names[0]}_first', 'Two procedures of one step start in source order',
                         place('module', items), candidates, f'{names[0]},{names[1]},end', '4.7 9.2.2.2')
    module = '''module sub #(parameter int ID=0)();
always begin $write("always%0d,",ID); #10; end
initial $write("initial%0d,",ID);
endmodule
'''
    tokens = ['always1', 'always2', 'initial1', 'initial2']
    candidates = [','.join((*p, 'end')) for p in itertools.permutations(tokens)]
    for name, ids in (('forward', (1, 2)), ('reverse', (2, 1))):
        insts = ''.join(f'sub #(.ID({i})) u{i}();\n' for i in ids)
        text = module + f'module top;\n{insts}{END}endmodule\n'
        chosen = ','.join((f'always{ids[0]}', f'always{ids[1]}', f'initial{ids[0]}', f'initial{ids[1]}', 'end'))
        yield source(f'instances_{name}', 'A step takes in every instance before the next step starts',
                     text, candidates, chosen, '4.7 23.3')
    # When every program has ended, the run ends (24.7), so a program prints the last word.
    program = 'program unit;\ninitial $display("program,end");\nendprogram\n'
    candidates = allowed(('cont', 'always', 'initial', 'comb'), ('program',))
    for name, before in (('before', True), ('after', False)):
        body = PREAMBLE + ''.join(ITEMS[k] + '\n' for k in ('initial', 'comb', 'always', 'cont')) + END
        inst = 'unit p();\n'
        items = inst + body if before else body + inst
        yield source(f'program_{name}', 'A program starts in Reactive, after the procedures of the design',
                     program + place('module', items), candidates, 'cont,always,initial,comb,program,end',
                     '4.4.3 24.3.1')


def cases():
    yield from orders()
    yield from values()
    yield from waiters()
    yield from within()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = list(cases())
    assert len({c[0] for c in generated}) == len(generated)
    failed = False
    for name, text, expected, choice in generated:
        for suffix, content in (('.sv', text), ('.expected', expected), ('.choice', choice)):
            path = OUT / (name + suffix)
            if args.check:
                if not path.exists() or path.read_text() != content:
                    print(f'out of date: {path.relative_to(OUT.parent.parent.parent)}')
                    failed = True
            else:
                path.write_text(content)
    print(f'time 0 order matrix: {len(generated)} sources')
    return int(failed)


if __name__ == '__main__':
    raise SystemExit(main())
