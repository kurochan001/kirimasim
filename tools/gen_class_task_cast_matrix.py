"""Original class task-cast matrix: approved class contract 5, 6.24.2/8.16.

The oracle is static assignment compatibility or a compatible dynamic object;
literal null succeeds. A failed task cast is a design error, with no store.
Target selection precedes source effects. No reference output is an oracle.
"""
import argparse
import itertools
import sys
from pathlib import Path
from gen_class_static_matrix import wrap

OUT = Path(__file__).resolve().parent.parent / 'tests/suite/proc'
HOMES = ('unit', 'module', 'package', 'interface', 'program', 'generate')
# destination type, source static type, source expression, successful cast
CASES = {
    'derived': ('Derived', 'Base', 'child', True),
    'base': ('Derived', 'Base', 'base', False),
    'typed_null': ('Derived', 'Base', 'null', False),
    'compatible_null': ('Derived', 'Derived', 'null', True),
    'unrelated': ('Derived', 'Other', 'other', False),
    'unrelated_null': ('Derived', 'Other', 'null', False),
    'upcast': ('Base', 'Derived', 'child', True),
    'interface': ('View', 'Base', 'child', True),
    'source_gc': ('Derived', 'Base', 'child', True),
    'literal_null': ('Derived', '', 'null', True),
}
DEFINITIONS = """interface class View; pure virtual function int read_value(); endclass
class Base; int value=3; endclass
class Derived extends Base implements View;
 int extra=7; virtual function int read_value();return extra;endfunction
endclass
class Other; int value=11; endclass
"""


def cases():
    for home in HOMES:
        for target in ('scalar', 'array', 'frame_array'):
            for label, (destination_type, source_type, expression, success) in CASES.items():
                name = f'class_task_cast_{home}_{target}_{label}'
                source_expr = 'source_value()' if source_type else 'null'
                destination = 'dest' if target == 'scalar' else 'dest[target_index()]'
                source_calls = int(bool(source_type))
                target_calls = int(target != 'scalar')
                result_null = expression == 'null' and success
                actor = """Derived child,saved;
Base base;
Other other;
int selected=0,source_calls=0,target_calls=0;
function int target_index();++target_calls;return selected;endfunction
"""
                if target != 'frame_array':
                    actor += destination_type + ' dest' + ('[2]' if target == 'array' else '') + ';\n'
                if source_type:
                    gc = ('Derived temporary;for(int i=0;i<4096;i++)temporary=new;'
                          if label == 'source_gc' else '')
                    actor += (f'function {source_type} source_value();{gc}'
                              f'++source_calls;selected=1;return {expression};endfunction\n')
                initialize = 'dest=saved;' if target == 'scalar' else 'dest[0]=saved;dest[1]=null;'
                read_dest = 'dest' if target == 'scalar' else 'dest[0]'
                check = f'{read_dest}==null' if result_null else f'{read_dest}==child'
                exercise = ("child=new;saved=new;base=new;other=new;" + initialize + '\n'
                            '$display("before");\n' + f'$cast({destination},{source_expr});\n' +
                            f'$display("after %b %0d %0d %0d",{check},'
                            'source_calls,target_calls,selected);\n')
                if target == 'frame_array':
                    actor += (f'task automatic exercise();{destination_type} dest[2];\n' + exercise +
                              'endtask\n')
                    exercise = 'exercise();'
                expected = 'before\n'
                if success:
                    expected += f'after 1 {source_calls} {target_calls} {source_calls}\n'
                else:
                    final_check = ("1'b1" if target == 'frame_array' else f'{read_dest}==saved')
                    actor += (f'final $display("failed %b %0d %0d %0d",{final_check},'
                              'source_calls,target_calls,selected);\n')
                    expected += f'failed 1 {source_calls} {target_calls} {source_calls}\n'
                text = wrap(home, DEFINITIONS, exercise, actor=actor)
                failure = (':expected_exit: 2\n'
                           ':expected_stderr_regex: error: class \\$cast failed\n') if not success else ''
                header = f"""/*
:name: {name}
:description: Class task casts preserve target selection, source effects and failure atomicity
:tags: proc class casts
:type: simulation
:lrm: 1800-2023 6.24.2 8.16
:oracle: spec
:spec_check: ai
:fourstate: yes
:nondeterministic: no
:generator: gen_class_task_cast_matrix.py@1
:top_module: top
:expected_stdout: @{name}.expected
{failure}*/
// Generated by tools/gen_class_task_cast_matrix.py; edit the generator.
`timescale 1ns/1ns
"""
                yield name + '.sv', header + text
                yield name + '.expected', expected


def method_cases():
    # Virtual dispatch and suspension must reach the same task-cast lowering.
    for task in (False, True):
        name = 'class_task_cast_member_' + ('task' if task else 'function')
        declaration = ('virtual task perform(output int errors);' if task
                       else 'virtual function int perform();')
        finish = 'endtask' if task else 'endfunction'
        base_body = 'errors=99;' if task else 'return 99;'
        body = ("Derived child,dest[2];Base source;int selected=0;\n" +
                ('' if task else 'int errors;\n') +
                'errors=0;child=new;source=child;\n' + ('#1;\n' if task else '') +
                '$cast(dest[selected++],source);\n'
                'if(selected!=1 || dest[0]!=child || dest[1]!=null)++errors;\n' +
                ('' if task else 'return errors;\n'))
        call = 'view.perform(errors);' if task else 'errors=view.perform();'
        text = (DEFINITIONS + 'class Runner;\n' + declaration + base_body + finish +
                '\nendclass\nclass Actor extends Runner;\n' + declaration + body + finish +
                '\nendclass\nmodule top;Actor actor;Runner view;int errors;\n'
                'initial begin actor=new;view=actor;' + call +
                '$display("errors=%0d",errors);end endmodule\n')
        header = f"""/*
:name: {name}
:description: Virtual class methods share task-cast lowering across suspension and frames
:tags: proc class casts
:type: simulation
:lrm: 1800-2023 6.24.2 8.16 8.20
:oracle: spec
:spec_check: ai
:fourstate: yes
:nondeterministic: no
:generator: gen_class_task_cast_matrix.py@1
:top_module: top
:expected_stdout: errors=0
*/
// Generated by tools/gen_class_task_cast_matrix.py; edit the generator.
`timescale 1ns/1ns
"""
        yield name + '.sv', header + text


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    bad = False
    for name, text in itertools.chain(cases(), method_cases()):
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                print(f'{name}: regenerate with {Path(__file__).name}', file=sys.stderr)
                bad = True
        else:
            path.write_text(text)
    return int(bad)


if __name__ == '__main__':
    sys.exit(main())
