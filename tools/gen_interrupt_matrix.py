"""Generates the matrix test of SIGINT, of TEST_SUITE.md ("Mechanism
matrix"), in tests/cli/interrupt_matrix/ and tests/cli/interrupt_matrix.expected.

  tools/gen_interrupt_matrix.py           # writes the files
  tools/gen_interrupt_matrix.py --check   # exit 1 if a file differs from what it would write

The first SIGINT stops the run, final procedures run, the output written so
far is kept, the line of the reason interrupted ends standard error, and the
exit code is 130; a second SIGINT ends kirimasim at once
(SCHEDULER_SPEC.md 16.2, CLI.md 5). The kernel looks at the request before
each event and tier 1 at each branch (RUNTIME_ABI.md 4.4), so the axis is
what the run is doing when the signal comes: processes that wake each other
in one region (the kernel's check; in the ring of continuous assignments it
is the only one, as their processes have no branch), a loop that does not
wait in an initial
procedure, a function, a task, a fork branch and a static variable's
initializer (tier 1's check, in each body that can hold the loop), and a run
where time advances. One more file sends a second SIGINT while a final
procedure loops.

The limits that would stop these loops are turned off (--max-slot-events=0,
--max-steps=0). Each design writes a line with $info once the loop is about
to start; tests/cli/run_cli_tests.py waits for it on standard error, which
comes after the design's earlier output, before it sends the signal, so the
time of the end is known. It runs only on POSIX systems.

interrupt_matrix.expected has one JSON object a line: the file, the options,
the $info texts to wait for (one a signal), the whole standard output, and
the time of the end line ("" for a time that is not known in advance, null
for no end line).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

CLI = Path(__file__).resolve().parent.parent / "tests" / "cli"
OUT = CLI / "interrupt_matrix"
EXPECTED = CLI / "interrupt_matrix.expected"
NO_LIMITS = ["--max-slot-events=0", "--max-steps=0"]
WAKEUPS = ["logic a = 0, b = 0;", "always @(a) b = ~b;", "always @(b) a = ~a;"]
SPIN = "forever begin end"

# (name, what it checks, the items of top, the statements of its initial
# procedure after $display("started"), the final procedure's statements,
# the $info texts to wait for, the standard output, the time of the end)
CASES = [
    ("wakeups", "processes that wake each other in one region",
     WAKEUPS, ['#1 $info("looping");', "a = 1;"], ['$display("final ran");'],
     ["looping"], "started\nfinal ran\n", "1 ns"),
    ("assign_ring", "a ring of continuous assignments, whose processes have no branch",
     ["logic en = 0;", "wire a, b;", "assign a = en ? ~b : 1'b0;", "assign b = a;"],
     ['#1 $info("looping");', "en = 1;"], ['$display("final ran");'],
     ["looping"], "started\nfinal ran\n", "1 ns"),
    ("initial", "a loop that does not wait, in an initial procedure",
     [], ['#1 $info("looping");', SPIN], ['$display("final ran");'],
     ["looping"], "started\nfinal ran\n", "1 ns"),
    ("function", "a loop that does not wait, in a function",
     ["function automatic void spin();", f"  {SPIN}", "endfunction"],
     ['#1 $info("looping");', "spin();"], ['$display("final ran");'],
     ["looping"], "started\nfinal ran\n", "1 ns"),
    ("task", "a loop that does not wait, in a task",
     ["task automatic spin();", f"  {SPIN}", "endtask"],
     ['#1 $info("looping");', "spin();"], ['$display("final ran");'],
     ["looping"], "started\nfinal ran\n", "1 ns"),
    ("fork", "a loop that does not wait, in a fork branch",
     [], ['#1 $info("looping");', "fork", f"  {SPIN}", "join"], ['$display("final ran");'],
     ["looping"], "started\nfinal ran\n", "1 ns"),
    ("static_init", "a loop that does not wait, in a static variable's initializer",
     ["function automatic int spin();", '  $info("looping");', f"  {SPIN}", "  return 0;",
      "endfunction", "int x = spin();"],
     [], ['$display("final ran");'],
     ["looping"], "final ran\n", "0 ns"),
    ("time", "a run where time advances",
     ["int n = 0;", "always #1 n++;"], ['#3 $info("looping");'], ['$display("final ran");'],
     ["looping"], "started\nfinal ran\n", ""),
    ("second", "a final procedure that loops after the first one, where a second SIGINT "
     "ends kirimasim at once",
     WAKEUPS, ['#1 $info("looping");', "a = 1;"],
     ['$info("final looping");', SPIN, '$display("final ended");'],
     ["looping", "final looping"], "started\n", None),
]


def design(name, what, items, stmts, final):
    lines = [
        "// Generated by tools/gen_interrupt_matrix.py; change the generator, not this file.",
        f"// SIGINT during {what} (SCHEDULER_SPEC.md 16.2).",
        "module top;",
    ]
    lines += [f"  {x}" for x in items]
    lines += ["  initial begin", '    $display("started");']
    lines += [f"    {x}" for x in stmts]
    lines += ["  end", "  final begin"]
    lines += [f"    {x}" for x in final]
    lines += ["  end", "endmodule", ""]
    return "\n".join(lines)


def files():
    out = {}
    expected = []
    for name, what, items, stmts, final, markers, stdout, end in CASES:
        out[OUT / f"{name}.sv"] = design(name, what, items, stmts, final)
        expected.append(json.dumps({"file": f"interrupt_matrix/{name}.sv", "args": NO_LIMITS,
                                    "markers": markers, "stdout": stdout, "end": end}))
    out[EXPECTED] = "\n".join(expected) + "\n"
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    want = files()
    if args.check:
        have = set(OUT.glob("*.sv")) if OUT.exists() else set()
        for path in sorted(have - set(want)):
            print(f"gen_interrupt_matrix: {path.name} is not generated; remove it", file=sys.stderr)
            bad += 1
    else:
        OUT.mkdir(exist_ok=True)
    for path, text in want.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_interrupt_matrix: {path.relative_to(CLI.parent.parent)} is out of "
                      "date; run tools/gen_interrupt_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
