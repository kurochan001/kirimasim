"""Code the standard allows that slang rejects by default, and kirimasim runs with a warning (CLI.md 2.1).

IEEE 1800-2023 7.4.5: an index out of the bounds of an unpacked array is invalid; reading with it gives the
value of table 7-1 for the element type, and writing with it does nothing. 11.4.12.2: in a concatenation with a
string operand, the other operands are converted to string. 18.3: a constraint may hold a subexpression with
non-integral operands and no random variable. Every expected result is computed here from these rules, not from
a run.
"""
import argparse
from pathlib import Path
from typing import NamedTuple

OUT = Path(__file__).resolve().parent.parent / 'tests/suite/values'
PREFIX = 'relaxed_'


class Kind(NamedTuple):
    prelude: str
    type: str
    values: tuple      # the initial values of a[0] and a[1], as written
    written: str       # a value written with an invalid index
    fmt: str
    show: str          # how one element is shown; {} is the element
    default: str       # table 7-1, as shown
    shown: tuple       # a[0] and a[1], as shown


KINDS = {
    'int': Kind('', 'int', ('1', '2'), '9', '%0d', '{}', '0', ('1', '2')),
    'byte': Kind('', 'byte', ('3', '4'), '9', '%0d', '{}', '0', ('3', '4')),
    'logic8': Kind('', 'logic [7:0]', ("8'd5", "8'd6"), "8'd9", '%b', '{}', 'xxxxxxxx', ('00000101', '00000110')),
    'bit8': Kind('', 'bit [7:0]', ("8'd7", "8'd8"), "8'd9", '%b', '{}', '00000000', ('00000111', '00001000')),
    'real': Kind('', 'real', ('1.5', '2.5'), '9.5', '%0.1f', '{}', '0.0', ('1.5', '2.5')),
    'string': Kind('', 'string', ('"p"', '"q"'), '"z"', '[%s]', '{}', '[]', ('[p]', '[q]')),
    'enum': Kind('typedef enum {RED = 1, GREEN = 2} color_t;\n', 'color_t', ('RED', 'GREEN'), 'GREEN', '%0d', '{}', '0',
                 ('1', '2')),
    'enum4': Kind("typedef enum logic [1:0] {LO = 2'd1, HI = 2'd2} level_t;\n", 'level_t', ('LO', 'HI'), 'HI', '%b', '{}',
                  'xx', ('01', '10')),
    'handle': Kind('class item; endclass\n', 'item', ('null', 'null'), 'null', '%0d', '{} == null', '1', ('1', '1')),
}


def source(name, description, text, expected, lrm, args=''):
    name = PREFIX + name
    return name, f'''/*
:name: {name}
:description: {description}
:tags: values
:type: simulation
:lrm: 1800-2023 {lrm}
:oracle: spec
:spec_check: ai
:fourstate: yes
:nondeterministic: no
:generator: gen_relaxed_diagnostic_matrix.py@1
:top_module: top
:expected_stdout: {expected}
:timeout: 15
*/
// Generated by tools/gen_relaxed_diagnostic_matrix.py; edit the generator.
`timescale 1ns/1ns
{text}'''


def show(kind, element):
    return kind.show.format(element)


def index_forms():
    """Reads and writes with a constant index out of the bounds, in every kind of element."""
    for name, kind in KINDS.items():
        pattern = "'{" + ', '.join(kind.values) + "}"
        decl = f'{kind.prelude}module top;\n{kind.type} a[2] = {pattern};\n{kind.type} d[3:1];\n{kind.type} m[2][2];\n'
        reads = [('a[5]', kind.default), ('a[-1]', kind.default), ('d[0]', kind.default), ('d[4]', kind.default),
                 ('m[2][0]', kind.default), ('m[0][2]', kind.default)]
        fmt = ' '.join(kind.fmt for _ in reads)
        text = (decl + 'initial begin\n' + f'$display("{fmt}", {", ".join(show(kind, r) for r, _ in reads)});\n'
                f'a[5] = {kind.written};\na[-1] = {kind.written};\n'
                f'$display("{kind.fmt} {kind.fmt}", {show(kind, "a[0]")}, {show(kind, "a[1]")});\n'
                'end\nendmodule\n')
        expected = ' '.join(v for _, v in reads) + ' ' + ' '.join(kind.shown)
        # Two display lines become one expected line each; the header holds one line, so join them.
        yield source(f'index_{name}', 'An invalid constant index reads the default of the element and writes nothing',
                     text.replace('$display("' + fmt + '"', '$write("' + fmt + ' "'), expected, '7.4.5')


PLACE_BODY = 'int a[2] = \'{1, 2};\n'
PLACE_DO = 'a[5] = 9;\n$display("%0d %0d %0d", a[5], a[0], a[1]);\n'


def places():
    """The container does not change an invalid index."""
    for name, text in (
            ('task', f'module top;\ntask automatic run();\n{PLACE_BODY}{PLACE_DO}endtask\ninitial run();\nendmodule\n'),
            ('function', f'module top;\nfunction automatic void run();\n{PLACE_BODY}{PLACE_DO}endfunction\ninitial run();\nendmodule\n'),
            ('method', f'class box;\n{PLACE_BODY}function void run();\n{PLACE_DO}endfunction\nendclass\nmodule top;\nbox k;\ninitial begin\nk = new;\nk.run();\nend\nendmodule\n'),
            ('fork', f'module top;\n{PLACE_BODY}initial begin\nfork\nbegin\n{PLACE_DO}end\njoin\nend\nendmodule\n'),
            ('generate', f'module top;\nif (1) begin : g\n{PLACE_BODY}initial begin\n{PLACE_DO}end\nend\nendmodule\n'),
            ('interface', f'interface unit;\n{PLACE_BODY}initial begin\n{PLACE_DO}end\nendinterface\nmodule top;\nunit u();\nendmodule\n'),
            ('continuous', 'module top;\nint a[2] = \'{1, 2};\nwire [31:0] w;\nassign w = a[5];\ninitial #1 $display("%0d %0d %0d", w, a[0], a[1]);\nendmodule\n')):
        yield source(f'index_place_{name}', 'The container does not change an invalid constant index', text, '0 1 2', '7.4.5')


def concatenations():
    """The integral operands of a string concatenation become strings."""
    for name, decl, expression, expected in (
            ('byte_right', 'byte v = "a";', '{s, v}', 'xa'),
            ('byte_left', 'byte v = "a";', '{v, s}', 'ax'),
            ('bits8', "bit [7:0] v = 8'h62;", '{s, v}', 'xb'),
            ('bits16', "bit [15:0] v = 16'h6364;", '{s, v}', 'xcd'),
            ('bits24', "bit [23:0] v = 24'h656667;", '{s, v}', 'xefg'),
            ('between', 'byte v = "a";', '{s, v, s}', 'xax'),
            ('two', 'byte v = "a";\nbyte w = "b";', '{s, v, w}', 'xab')):
        text = f'module top;\nstring s = "x";\n{decl}\nstring r;\ninitial begin\nr = {expression};\n$display("%s", r);\nend\nendmodule\n'
        yield source(f'concat_{name}', 'An integral operand of a string concatenation becomes a string', text, expected,
                     '11.4.12.2 6.16')


def constraints():
    """A constraint may compare strings when no random variable is in the comparison (18.3)."""
    text = ('class c;\nrand bit [3:0] s;\nstring tag = "small";\nconstraint k { (tag == "small") -> s < 4\'d2; }\nendclass\n'
            'module top;\nc h;\ninitial begin\nh = new;\n$display("%s", h.tag);\nend\nendmodule\n')
    yield source('constraint_string', 'A constraint compares strings with no random variable in the comparison', text,
                 'small', '18.3')


def cases():
    yield from index_forms()
    yield from places()
    yield from concatenations()
    yield from constraints()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = dict(cases())
    failed = False
    for name, text in generated.items():
        path = OUT / (name + '.sv')
        if args.check:
            if not path.exists() or path.read_text() != text:
                print(f'out of date: {path.relative_to(OUT.parent.parent.parent)}')
                failed = True
        else:
            path.write_text(text)
    print(f'relaxed diagnostic matrix: {len(generated)} sources')
    return int(failed)


if __name__ == '__main__':
    raise SystemExit(main())
