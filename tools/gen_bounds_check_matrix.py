"""Generate --bounds-check's CLI matrix (CLI.md 2.2, VALUE_SEMANTICS.md 3.11).

Two/four-state words at widths 8, 65, 129 in twelve contexts, including
static/frame/ref arrays and NBA writes. Invalid and partly valid selects,
unknown/very wide indices and both dimensions of an array keep the same
values with warnings on/off. Repeated accesses and read-modify-write must
warn once per source position, without evaluating an index twice.
"""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "tests" / "cli" / "bounds_matrix"
VERSION = 1
CONTAINERS = ("initial", "always", "final", "static_task", "automatic", "function",
              "ref_static", "ref_frame", "fork", "generate", "interface", "nba")


def test(domain, width, container):
    name = f"bounds_{domain}_{width}_{container}"
    four = domain == "logic"
    unknown = "x" if four else "0"
    vector = "10" + "0" * (width - 4) + "10"
    body = ["    for (int round = 0; round < 2; round++) begin",
            "      vector = '0; foreach (data[i, j]) data[i][j] = '1;",
            "      index = round == 0 ? WIDTH - 1 : WIDTH; trace = 0;",
            "      bit_read = «»vector[index_value(index)];",
            '      $display("transition %b %0d", bit_read, trace);',
            "      index = -1; trace = 0;",
            "      bit_read = «»vector[index_value(index)];",
            '      $display("negative %b %0d", bit_read, trace);',
            "      index = 'x; trace = 0;",
            "      bit_read = «»vector[index_value(index)];",
            '      $display("unknown %b %0d", bit_read, trace);',
            "      huge = 129'b1 << 100;",
            "      bit_read = «»vector[huge];",
            '      $display("huge %b", bit_read);',
            "      index = WIDTH - 2;",
            "      part = «»vector[index +: 4];",
            "      «»vector[index +: 4] = 4'b1010;",
            "      index = -2; «»vector[index +: 4] = 4'b1010;",
            '      $display("partial %b %b", part, vector);',
            "      index = WIDTH; «»vector[index]++;",
            '      $display("update %b", vector);',
            "      row = 3; col = 0; trace = 0;",
            "      «»data[index_value(row)][index_value(col)] = '0;",
            '      $display("array_write %b %0d", data[1][0], trace);',
            "      row = 1; col = 1; trace = 0;",
            "      got = «»data[index_value(row)][index_value(col)];",
            '      $display("array_read %b %0d", got, trace);',
            "      col = 0; index = WIDTH; «»data[row][col][index] = 1'b0;",
            "      row = 0; «»data[row][col][0 +: 4] = '0;",
            '      $display("array_bits %b", data[1][0]);',
            "    end"]
    expected = []
    for round_ in range(2):
        expected += [f"transition {'0' if round_ == 0 else unknown} 1",
                     f"negative {unknown} 1", f"unknown {unknown} 1", f"huge {unknown}",
                     f"partial {unknown * 2}00 {vector}", f"update {vector}",
                     f"array_write {'1' * width} 2", f"array_read {unknown * width} 2",
                     f"array_bits {'1' * width}"]
    if container == "nba":
        body += ["    index = WIDTH - 2; «»vector[index +: 4] <= 4'b0101;",
                 "    index = WIDTH + 4; «»data[1][0][index +: 4] <= '0;",
                 "    row = 0; «»data[row][0] <= '0;", "    #1;",
                 '    $display("nba %b %b", vector, data[1][0]);']
        expected += [f"nba 01{'0' * (width - 4)}10 {'1' * width}"]
    declarations = ["    word_t vector, data[2:1][-1:0], got;", "    logic bit_read;",
                    "    logic [3:0] part;", "    logic signed [31:0] index, row, col;",
                    "    logic [128:0] huge;"]
    lines = [f"// Generated by tools/gen_bounds_check_matrix.py (version {VERSION}); do not edit.",
             "`timescale 1ns/1ns", "interface worker;" if container == "interface" else "module top;",
             f"  localparam int WIDTH = {width};", f"  typedef {domain} [WIDTH-1:0] word_t;",
             "  int trace;", "  function automatic logic signed [31:0] index_value(input logic signed [31:0] x);",
             "    trace++; return x;", "  endfunction"]
    if container in ("ref_static", "ref_frame"):
        lines += ["  task automatic run(ref word_t vector, ref word_t data[2:1][-1:0]);"]
        lines += ["    word_t got;"] + declarations[1:] + body + ["  endtask"]
        if container == "ref_frame":
            lines += ["  task automatic drive();", "    word_t vector, data[2:1][-1:0];",
                      "    run(vector, data);", "  endtask", "  initial drive();"]
        else:
            lines += ["  word_t vector, data[2:1][-1:0];", "  initial run(vector, data);"]
    elif container in ("static_task", "automatic", "function"):
        opening = {"static_task": "task run();", "automatic": "task automatic run();",
                   "function": "function automatic void run();"}[container]
        lines += ["  " + opening] + declarations + body
        lines += ["  endfunction" if container == "function" else "  endtask", "  initial run();"]
    else:
        lines += declarations
        if container == "generate":
            lines += ["  if (1) begin : g"]
        if container == "always":
            lines += ["  event go;", "  initial #1 ->go;", "  always @(go) begin"]
        else:
            lines += ["  final begin" if container == "final" else "  initial begin"]
        lines += (["    fork", "      begin"] + body + ["      end", "    join"]
                  if container == "fork" else body)
        lines += ["  end"]
        if container == "generate":
            lines += ["  end"]
    lines += (["endinterface", "module top;", "  worker u();", "endmodule"]
              if container == "interface" else ["endmodule"])
    locations = []
    for n, line in enumerate(lines, 1):
        if "«»" in line:
            locations.append(f"{n}:{line.index('«»') + 1}")
            lines[n - 1] = line.replace("«»", "")
    # The transition access is valid in round 0 and first warns in round
    # 1, after all the other loop accesses have already warned.
    split = len(locations) - (3 if container == "nba" else 0)
    loop = locations[:split]
    locations = loop[1:] + loop[:1] + locations[split:]
    return {name + ".sv": "\n".join(lines) + "\n",
            name + ".expected": "\n".join(expected) + "\n",
            name + ".warnings": "\n".join(locations) + "\n"}


def files():
    return {name: text for domain in ("bit", "logic") for width in (8, 65, 129)
            for container in CONTAINERS for name, text in test(domain, width, container).items()}


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if not args.check:
        OUT.mkdir(exist_ok=True)
    bad = False
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"{name}: run tools/gen_bounds_check_matrix.py", file=sys.stderr)
                bad = True
        else:
            path.write_text(text, encoding="utf-8")
    return int(bad)


if __name__ == "__main__":
    sys.exit(main())
