"""Generates the matrix tests of port expressions that select a part of a
vector (TEST_SUITE.md, "Mechanism matrix") in tests/suite/ports/.

  tools/gen_port_select_expression_matrix.py           # writes the files
  tools/gen_port_select_expression_matrix.py --check   # exit 1 if a file differs from what it would write

The rule: 23.2.2.1 of the standard. In the list of ports of a module
with separate port declarations, a port may be an expression inside the
module: a bit-select or a part-select of a vector, with a name
(".q(v[5:2])") or without one ("m(v[5:2])"). The port then connects to
those bits alone: an output port gives the bits selected, and an input
port drives them and leaves the other bits of the vector undriven (z
for a net).

The axes: the select (one bit, a part, an indexed part), the direction
(output from a reg, input to a net), the form (named, unnamed), whether
two ports select parts of one vector, and the place of the instance
(the top module, a generate block).

The expected output is computed here from the vectors, without reading
kirimasim's code. A person checks it once for all the tests made from it
(TEST_SUITE.md, "Sampling by people"). For reference, checked
2026-11-12: Icarus 14.0 devel prints the same bits for the bit and part
selects and does not take the indexed part as a port; Verilator 5.052
does not take these ports.
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "ports"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

PLACES = ["top", "generate"]

# The outputs: the vector inside is 8 bits; (the port's name, the select
# as written, the bits it takes, high first).
OUTPUTS = [("ob", "vo[6]", [6]), ("op", "vo[5:2]", [5, 4, 3, 2]), ("oi", "vo[1 -: 2]", [1, 0])]
# The inputs: two ports drive parts of one net of 8 bits; bits no port
# drives stay z.
INPUTS = [("ip", "vi[5:2]", [5, 4, 3, 2]), ("ib", "vi[0]", [0])]
VALUES = [0b10110110, 0b01001001]  # what the module writes to vo, in turn
DRIVES = [(0b1001, 1), (0b0110, 0)]  # what the top gives ip and ib, in turn


def bits(value, positions):
    return "".join(str((value >> p) & 1) for p in positions)


def test(place):
    name = f"port_select_expression_{place}"
    sv = ["/*", f":name: {name}",
          ":description: a port expression that selects a bit or a part of a vector connects "
          "those bits alone, as an output and as an input, named and unnamed, with the instance "
          f"in {'the top module' if place == 'top' else 'a generate block'}",
          ":tags: ports", ":type: simulation", ":lrm: 1800-2023 23.2.2.1", ":oracle: spec",
          ":spec_check: ai", ":fourstate: yes", ":nondeterministic: no",
          f":generator: gen_port_select_expression_matrix.py@{VERSION}", ":top_module: top",
          f":expected_stdout: @{name}.expected", "*/",
          "// Generated by tools/gen_port_select_expression_matrix.py; change the generator, not "
          "this file.", "`timescale 1ns/1ns"]
    named = ", ".join(f".{n}({e})" for n, e, _ in OUTPUTS + INPUTS)
    sv += [f"module named ({named});",
           "  output [7:0] vo; reg [7:0] vo;", "  input [7:0] vi;",
           f"  initial begin vo = 8'b{VALUES[0]:08b}; #6 vo = 8'b{VALUES[1]:08b}; end",
           '  initial begin #1 $display("named vi=%b", vi); #6 $display("named vi=%b", vi); end',
           "endmodule"]
    # Without names the ports are connected by position.
    sv += ["module unnamed (vo[5:2], vi[3:2]);",
           "  output [7:0] vo; reg [7:0] vo;", "  input [3:0] vi;",
           f"  initial begin vo = 8'b{VALUES[0]:08b}; #6 vo = 8'b{VALUES[1]:08b}; end",
           '  initial begin #2 $display("unnamed vi=%b", vi); #6 $display("unnamed vi=%b", vi); end',
           "endmodule"]
    body = ["wire ob; wire [3:0] op; wire [1:0] oi; wire [3:0] up;",
            "reg [3:0] ip; reg ib;",
            "named n (.ob(ob), .op(op), .oi(oi), .ip(ip), .ib(ib));",
            "unnamed u (up, ip[1:0]);"]
    stim = [f"ip = 4'b{DRIVES[0][0]:04b}; ib = {DRIVES[0][1]};",
            '#3 $display("outputs: ob=%b op=%b oi=%b up=%b", ob, op, oi, up);',
            f"#3 ip = 4'b{DRIVES[1][0]:04b}; ib = {DRIVES[1][1]};",
            '#3 $display("outputs: ob=%b op=%b oi=%b up=%b", ob, op, oi, up);']
    if place == "top":
        sv += ["module top;"] + ["  " + b for b in body]
        sv += ["  initial begin"] + ["    " + t for t in stim] + ["  end", "endmodule"]
    else:
        sv += ["module top;", "  if (1) begin : g"] + ["    " + b for b in body]
        sv += ["    initial begin"] + ["      " + t for t in stim] + ["    end", "  end",
                                                                      "endmodule"]

    def named_vi(k):
        ip, ib = DRIVES[k]
        return "zz" + f"{ip:04b}" + "z" + str(ib)

    def unnamed_vi(k):
        return f"{DRIVES[k][0] & 3:02b}" + "zz"

    def outputs(k):
        v = VALUES[k]
        return (f"outputs: ob={bits(v, [6])} op={bits(v, [5, 4, 3, 2])} oi={bits(v, [1, 0])} "
                f"up={bits(v, [5, 4, 3, 2])}")
    # Each process prints at times of its own (named at 1 and 7, unnamed at
    # 2 and 8, the top at 3 and 9; the values change at 0 and 6), so the
    # order of the lines does not depend on the order of processes (4.7).
    expected = [f"named vi={named_vi(0)}", f"unnamed vi={unnamed_vi(0)}", outputs(0),
                f"named vi={named_vi(1)}", f"unnamed vi={unnamed_vi(1)}", outputs(1)]
    return name, sv, expected


def files():
    out = {}
    for place in PLACES:
        name, sv, expected = test(place)
        out[f"{name}.sv"] = "\n".join(sv) + "\n"
        out[f"{name}.expected"] = "\n".join(expected) + "\n"
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print("gen_port_select_expression_matrix: "
                      f"{path.relative_to(OUT.parent.parent.parent)} is out of date; run "
                      "tools/gen_port_select_expression_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
