"""Generate tests of for loops with an omitted condition (12.7.1, 12.8).

Axes: omitted, assigned or declared initialization; omitted, single or
multiple steps; initial, automatic task, function or fork branch; direct
or named-block control flow; break or return; and a wait in the body.
At i=1 continue skips the addition; at i=3 break or return leaves with
10 + 30 = 40. A timed body waits four times, including at continue and exit.
"""

import argparse
import itertools
import sys
from pathlib import Path

from gen_loop_matrix import body

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "proc"
NAME = "for_omitted_matrix"
VERSION = 1


def cases():
    for container, spelling, place in itertools.product(
            ("initial", "task", "function", "fork"),
            ("empty-init", "assign", "declare", "bare", "multi-step"),
            ("body", "named", "disabled")):
        for timed in (False, True):
            if timed and container == "function":
                continue
            for leave in (("break", "return") if container in ("task", "function") else ("break",)):
                yield container, spelling, place, timed, leave


def loop(spelling, statements, timed):
    headers = {
        "empty-init": "for (; ; i++)",
        "assign": "for (i = 0; ; i++)",
        "declare": "for (int i = 0; ; i++)",
        "bare": "for (;;) ",
        "multi-step": "for (i = 0, j = 0; ; i++, j += 2)",
    }
    lines = ["i = 0; j = 0;", headers[spelling].rstrip() + " begin"]
    if timed:
        lines.append("  #1;")
    if spelling == "bare":
        lines += ["  j = i;", "  i++;"]
        statements = [s.replace("i ==", "j ==").replace("(i + 1)", "(j + 1)")
                      for s in statements]
    if spelling == "multi-step":
        lines.append('  if (j != 2 * i) $fatal(1, "for steps did not run together");')
    return lines + ["  " + s for s in statements] + ["end"]


def files():
    lines = [
        "/*", f":name: {NAME}",
        ":description: omitted for condition, initialization and steps across containers and waits",
        ":tags: proc loop", ":type: simulation", ":lrm: 1800-2023 12.7.1 12.8",
        ":oracle: spec", ":spec_check: ai", ":fourstate: no", ":nondeterministic: no",
        f":generator: gen_for_omitted_matrix.py@{VERSION}",
        f":expected_stdout: @{NAME}.expected", "*/",
        "// Generated by tools/gen_for_omitted_matrix.py; edit the generator.",
        "module top;", "  timeunit 1ns; timeprecision 1ns;",
    ]
    main, expected = ["  initial begin"], []
    for k, (container, spelling, place, timed, leave) in enumerate(cases()):
        tag = f"{container} {spelling} {place} {'wait' if timed else 'nowait'} {leave}"
        statements = body(k, place, leave)
        if container == "task":
            statements = [s.replace("return;", "begin out = sum; return; end") for s in statements]
        elif container == "function":
            statements = [s.replace("return;", "return sum;") for s in statements]
        code = ["int i, j, sum;", "sum = 0;"] + loop(spelling, statements, timed)
        if container in ("task", "function"):
            start = f"task automatic t{k}(output int out);" if container == "task" else \
                f"function automatic int f{k}();"
            end = ["out = sum;", "endtask"] if container == "task" else ["return sum;", "endfunction"]
            lines += ["  " + start] + ["    " + s for s in code] + ["  " + s for s in end]
        main += ["    begin", "      time started;", "      int result;", "      started = $time;"]
        if container == "function":
            main.append(f"      result = f{k}();")
        elif container == "task":
            main.append(f"      t{k}(result);")
        else:
            prefix = "      "
            if container == "fork":
                main += ["      fork", "        begin"]
                prefix = "          "
            else:
                main.append("      begin")
                prefix = "        "
            main += [prefix + s for s in code] + [prefix + "result = sum;"]
            main.append("        end" if container == "fork" else "      end")
            if container == "fork":
                main.append("      join")
        main += [f'      $display("{tag} %0d %0d", result, $time - started);', "    end"]
        expected.append(f"{tag} 40 {4 if timed else 0}")
    lines += main + ["  end", "endmodule", ""]
    return {NAME + ".sv": "\n".join(lines), NAME + ".expected": "\n".join(expected) + "\n"}


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"{path.name}: run tools/gen_for_omitted_matrix.py", file=sys.stderr)
                return 1
        else:
            path.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
