"""Generates the matrix tests of arrays of sequential UDP instances
(TEST_SUITE.md, "Mechanism matrix") in tests/suite/nets/.

  tools/gen_udp_array_matrix.py           # writes the files
  tools/gen_udp_array_matrix.py --check   # exit 1 if a file differs from what it would write

The rule (28.3.6, VALUE_SEMANTICS.md 5.8 and 5.9): an array of instances
is one instance per element, each with a state of its own, its terminals
connected to the slices of the array's connections. The axes: the range
of the array (descending from 0, ascending, descending from 2, and two
dimensions), the initial value (1, none), and the container of the array
(a module body, a generate-if block, a generate-for block, a child module
reached through its ports). The clock rises twice with different data,
so that each element shows its own state; every output is read with
$strobe at the end of each time slot.

The expected outputs follow from the rule above, without reading
kirimasim's code: after a rising edge, bit k of the outputs is bit k of
the data, and before the first one it is the initial value.
"""

import argparse
import sys
from pathlib import Path

from gen_udp_matrix import primitive

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "nets"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

DFF = ["r 0 : ? : 0", "r 1 : ? : 1", "n ? : ? : -", "? * : ? : -"]
INITIALS = {"i1": "1", "in": None}
# The range of the array as written, and its number of elements.
RANGES = {"down": ("[1:0]", 2), "up": ("[0:3]", 4), "offset": ("[5:2]", 4),
          "two_dims": ("[1:0][1:0]", 4)}
CONTAINERS = ["module", "generate_if", "generate_for", "child"]
# The data at the first and the second rising edge, bit k for bit k of the
# whole vector.
FIRST = "1001101101"
SECOND = "0110010110"


def arrays():
    """(name, primitive, initial, range, low bit, width) of each array."""
    out = []
    low = 0
    for ikey, initial in INITIALS.items():
        for rkey, (rng, width) in RANGES.items():
            out.append((f"{ikey}_{rkey}", f"dff_{ikey}", initial, rng, low, width))
            low += width
    return out


def instances(indent):
    return "".join(f"{indent}{prim} u_{name} {rng} (q[{low + width - 1}:{low}], clk, "
                   f"d[{low + width - 1}:{low}]);\n"
                   for name, prim, _, rng, low, width in arrays())


def header(name, container):
    return (f"/*\n:name: {name}\n:description: arrays of sequential UDP instances of every "
            f"range form, with and without an initial value, in "
            f"{container.replace('_', ' ')} containers: each element keeps its own state\n"
            ":tags: nets\n:type: simulation\n:lrm: 1800-2023 28.3.6 29.6 29.7\n:oracle: spec\n"
            ":spec_check: ai\n:fourstate: yes\n:nondeterministic: no\n"
            f":generator: gen_udp_array_matrix.py@{VERSION}\n:top_module: top\n"
            f":expected_stdout: @{name}.expected\n*/\n"
            "// Generated by tools/gen_udp_array_matrix.py; change the generator, not this file.\n"
            "`timescale 1ns/1ns\n")


def test(container):
    name = f"udp_array_{container}"
    arrs = arrays()
    n = sum(a[5] for a in arrs)
    first = (FIRST * (n // len(FIRST) + 1))[:n]
    second = (SECOND * (n // len(SECOND) + 1))[:n]
    sv = header(name, container)
    for ikey, initial in INITIALS.items():
        sv += primitive(f"dff_{ikey}", ["clk", "d"], DFF, True, initial)
    if container == "child":
        sv += (f"module holder (input clk, input [{n - 1}:0] d, output [{n - 1}:0] q);\n"
               + instances("  ") + "endmodule\n")
    sv += f"module top;\n  reg clk;\n  reg [{n - 1}:0] d;\n  wire [{n - 1}:0] q;\n"
    if container == "module":
        sv += instances("  ")
    elif container == "generate_if":
        sv += "  if (1) begin : g\n" + instances("    ") + "  end\n"
    elif container == "generate_for":
        sv += "  for (genvar i = 0; i < 1; i++) begin : g\n" + instances("    ") + "  end\n"
    else:
        sv += "  holder h (clk, d, q);\n"
    # The strings hold bit k at position k; a literal writes the highest
    # bit first.
    sv += (f"  initial begin\n    clk = 1'b0;\n    d = {n}'b{first[::-1]};\n"
           f"    #1 clk = 1'b1;\n    #1 clk = 1'b0;\n    d = {n}'b{second[::-1]};\n"
           f"    #1 clk = 1'b1;\n  end\n")
    fmt = " ".join(f"{a[0]}=%b" for a in arrs)
    args = ", ".join(f"q[{a[4] + a[5] - 1}:{a[4]}]" for a in arrs)
    sv += (f"  initial begin\n    $strobe(\"t=%0d {fmt}\", $time, {args});\n"
           f"    #1 $strobe(\"t=%0d {fmt}\", $time, {args});\n"
           f"    #2 $strobe(\"t=%0d {fmt}\", $time, {args});\n  end\nendmodule\n")

    def line(t, bits):
        return f"t={t} " + " ".join(
            f"{a[0]}=" + "".join(bits(a, k) for k in reversed(range(a[4], a[4] + a[5])))
            for a in arrs) + "\n"

    exp = line(0, lambda a, k: a[2] or "x")
    exp += line(1, lambda a, k: first[k])
    exp += line(3, lambda a, k: second[k])
    return name, sv, exp


def files():
    out = {}
    for container in CONTAINERS:
        name, sv, exp = test(container)
        out[f"{name}.sv"] = sv
        out[f"{name}.expected"] = exp
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_udp_array_matrix: {path.relative_to(OUT.parent.parent.parent)} is "
                      "out of date; run tools/gen_udp_array_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
