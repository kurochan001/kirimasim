#!/usr/bin/env python3
"""Generates the %s matrix test of TEST_SUITE.md ("機構の行列") in
tests/suite/values/.

  tools/gen_string_format_matrix.py           # writes the files
  tools/gen_string_format_matrix.py --check   # exit 1 if a file differs from what it would write

%s prints an integral value's bytes, the last one in the low 8 bits
(SYSTEM_TASKS.md 3.5): zero bytes before the first nonzero one are not
printed, and pad the automatic width with spaces; a zero byte after it
prints as a space, with %0s too; an explicit width pads on the left. The
axes: where the zero bytes are (leading, inside, trailing, everywhere),
the specifier (%s, %0s, %12s), the width of the value (one and two
words), and the task ($display, and $sformatf into a string).

A person checks the expected output once for all the tests made from it
(TEST_SUITE.md, "人の抜き取り").
"""

import argparse
import itertools
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "values"
NAME = "string_format_matrix"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

# The bytes of the value below its padding, most significant first; 0 is a zero byte.
PLACES = {
    "leading": [0, 0, ord("A"), ord("B")],
    "inside": [ord("A"), 0, 0, ord("B")],
    "trailing": [ord("A"), ord("B"), 0, 0],
    "zero": [0, 0, 0, 0],
}
WIDTHS = [32, 100]
SPECS = ["%s", "%0s", "%12s"]


def text(data, width, spec):
    """What %s, %0s or %<n>s prints for the value of these bytes."""
    nbytes = (width + 7) // 8
    data = [0] * (nbytes - len(data)) + data
    out, started = "", False
    for b in data:
        if b == 0 and not started:
            continue
        started = True
        out += " " if b == 0 else chr(b)
    pad = nbytes if spec == "%s" else 0 if spec == "%0s" else int(spec[1:-1])
    return out.rjust(pad)


def files():
    head = [
        "/*",
        f":name: {NAME}",
        ":description: %s with zero bytes before, inside and after the characters of one- and "
        "two-word values, with the automatic, zero and an explicit width, in $display and "
        "$sformatf",
        ":tags: values string display",
        ":type: simulation",
        ":lrm: 1800-2023 21.2.1.2 21.2.1.7",
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: no",
        ":nondeterministic: no",
        f":generator: gen_string_format_matrix.py@{VERSION}",
        f":expected_stdout: @{NAME}.expected",
        "*/",
        "// Generated by tools/gen_string_format_matrix.py; change the generator, not this file.",
        "module top;",
        "  bit [31:0] v32;",
        "  bit [99:0] v100;",
        "  string s;",
        "  initial begin",
    ]
    st, exp = [], []
    for (place, data), width in itertools.product(PLACES.items(), WIDTHS):
        value = int.from_bytes(bytes(data), "big")
        st.append(f"    v{width} = {width}'h{value:x};")
        for spec in SPECS:
            t = text(data, width, spec)
            st.append(f"    $display(\"{place} {width} {spec[1:]} [{spec}]\", v{width});")
            st.append(f"    s = $sformatf(\"{spec}\", v{width}); $display(\"{place} {width} "
                      f"{spec[1:]} sformatf [%s] %0d\", s, s.len());")
            exp.append(f"{place} {width} {spec[1:]} [{t}]")
            exp.append(f"{place} {width} {spec[1:]} sformatf [{t}] {len(t)}")
    sv = head + st + ["  end", "endmodule", ""]
    return {f"{NAME}.sv": "\n".join(sv), f"{NAME}.expected": "\n".join(exp) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text_ in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text_:
                print(f"gen_string_format_matrix: {path.relative_to(OUT.parent.parent.parent)} is "
                      "out of date; run tools/gen_string_format_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text_, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
