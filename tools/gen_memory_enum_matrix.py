#!/usr/bin/env python3
"""Generates the matrix tests of $readmemb and $readmemh into memories of
an enumerated type (TEST_SUITE.md, "Mechanism matrix") in tests/suite/proc/.

  tools/gen_memory_enum_matrix.py           # writes the files
  tools/gen_memory_enum_matrix.py --check   # exit 1 if a file differs from what it would write

The rules (21.4.2, SYSTEM_TASKS.md 7.1), with those of any memory
(tools/gen_memory_file_matrix.py):

- A word goes into an element as into a memory of the base type: the low
  digits of a longer number, x and z as 0 for a 2-state base type.
- The word must then be the value of one of the type's items. One that is
  not is a run-time error of the design: reading stops, the words read
  before stay, and the run ends with code 2 (final procedures still run).

The axes: the way of reading (the cells below: the radix, the base type,
the address arguments, an address in the file, two dimensions) and the
container of the calls (an initial procedure, a task, a function, a fork
branch, a task in a generate block); two tests end the run, with a number
that is no value and with a z in a 4-state type.

The expected outputs follow from the rules above, without reading
kirimasim's code. For reference, checked 2026-10-21: Icarus 14.0 devel,
which takes no .name of an element of an array, prints the same numbers,
but loads the words that are no value and goes on.
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "proc"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

CONTAINERS = ["initial", "task", "function", "fork", "generate"]

TYPES = ["typedef enum {A = 1, B = 5, C = 9} e_t;",
         "typedef enum logic [1:0] {L0, L2 = 2} l_t;",
         "typedef enum bit [1:0] {K0, K1} k_t;"]
MEMS = ["e_t m [0:2];", "l_t n [0:1];", "k_t k [0:1];", "e_t q [0:1][0:1];"]

# Each cell: (the file and its text, the call, the elements printed and
# their names after it).
CELLS = [
    ("hex", "e0.mem", "1 5 9", '$readmemh("e0.mem", m);',
     ["m[0]", "m[1]", "m[2]"], ["A", "B", "C"]),
    ("low_digits", "l0.mem", "110\\n00", '$readmemb("l0.mem", n);',
     ["n[0]", "n[1]"], ["L2", "L0"]),
    ("two_state_x", "k0.mem", "x 1", '$readmemh("k0.mem", k);',
     ["k[0]", "k[1]"], ["K0", "K1"]),
    ("down", "e1.mem", "9 1", '$readmemh("e1.mem", m, 2, 1);',
     ["m[0]", "m[1]", "m[2]"], ["A", "A", "C"]),
    ("address", "e2.mem", "@1 5", '$readmemh("e2.mem", m);',
     ["m[0]", "m[1]", "m[2]"], ["A", "B", "C"]),
    ("two_dimensions", "q0.mem", "1 5 9 1", '$readmemh("q0.mem", q);',
     ["q[0][0]", "q[0][1]", "q[1][0]", "q[1][1]"], ["A", "B", "C", "A"]),
]


def header(name, description, lrm, exit_code=None):
    lines = ["/*", f":name: {name}", f":description: {description}", ":tags: proc",
             ":type: simulation", f":lrm: 1800-2023 {lrm}", ":oracle: spec", ":spec_check: ai",
             ":fourstate: yes", ":nondeterministic: no",
             f":generator: gen_memory_enum_matrix.py@{VERSION}", ":top_module: top",
             f":expected_stdout: @{name}.expected"]
    if exit_code is not None:
        lines.append(f":expected_exit: {exit_code}")
    lines += [f":expected_stderr: @{name}.stderr", "*/",
              "// Generated by tools/gen_memory_enum_matrix.py; change the generator, not this "
              "file.", "`timescale 1ns/1ns"]
    return lines


def test(container):
    name = f"memory_enum_{container}"
    lines = header(name, "$readmemh and $readmemb into memories of enumerated types take the "
                         "values of their items, called from "
                         f"{'an' if container[0] in 'aeiou' else 'a'} {container}",
                   "21.4 21.4.2 21.4.3")
    lines += ["module top;"] + [f"  {t}" for t in TYPES] + [f"  {m}" for m in MEMS]
    lines.append("  integer fd;")
    body = []
    for key, _, _, call, refs, _ in CELLS:
        names = " ".join("%s" for _ in refs)
        body += [call, f'$display("{key}: {names}", {", ".join(r + ".name" for r in refs)});']
    if container == "task":
        lines += ["  task load;"] + ["    " + b for b in body] + ["  endtask"]
        calls = ["load;"]
    elif container == "function":
        lines += ["  function void load();"] + ["    " + b for b in body] + ["  endfunction"]
        calls = ["load();"]
    elif container == "generate":
        lines += ["  if (1) begin : g", "    task load;"] + ["      " + b for b in body] + [
            "    endtask", "  end"]
        calls = ["g.load;"]
    elif container == "fork":
        calls = ["fork begin"] + ["  " + b for b in body] + ["end join"]
    else:
        calls = body
    lines.append("  initial begin")
    for _, file, text, _, _, _ in CELLS:
        lines.append(f'    fd = $fopen("{file}", "w"); $fwrite(fd, "{text}\\n"); $fclose(fd);')
    lines += ["    " + c for c in calls]
    lines += ["  end", "endmodule"]
    stdout = [f"{key}: {' '.join(values)}" for key, *_, values in CELLS]
    return name, lines, stdout, []


# The tests that end the run: (name, what it shows, memory, its start, the
# task, the file's text, the text the error names, the elements after it).
ERRORS = [
    ("memory_enum_no_value", "a number that is no value of the type", "e_t m [0:2];", "C",
     "$readmemh", "5\\n7\\n1", "7", ["B", "C", "C"]),
    ("memory_enum_z", "a z in a 4-state type, which no item has", "l_t m [0:2];", "L2",
     "$readmemb", "0\\n1z\\n10", "1z", ["L0", "L2", "L2"]),
]


def error_test(cell):
    name, what, decl, start, task, text, bad, kept = cell
    lines = header(name, f"$readmem into a memory of an enumerated type stops at {what}, a "
                         "run-time error that ends the run; the words read before stay",
                   "21.4 21.4.2", 2)
    lines += ["module top;"] + [f"  {t}" for t in TYPES] + [f"  {decl}", "  integer fd;",
                                                             "  initial begin",
                                                             f"    foreach (m[i]) m[i] = {start};",
                                                             '    fd = $fopen("c.mem", "w");',
                                                             f'    $fwrite(fd, "{text}\\n");',
                                                             "    $fclose(fd);",
                                                             f'    #1 {task}("c.mem", m);']
    at = len(lines)
    lines += ['    $display("not reached");', "  end",
              '  final $display("%s %s %s", m[0].name, m[1].name, m[2].name);', "endmodule"]
    stderr = [f'{name}.sv:{at}: error: {task}: "c.mem" line 2: {bad} is no value of the '
              "enumerated type [top @ 1ns]"]
    return name, lines, [" ".join(kept)], stderr


def files():
    out = {}
    tests = [test(c) for c in CONTAINERS] + [error_test(e) for e in ERRORS]
    for name, lines, stdout, stderr in tests:
        out[f"{name}.sv"] = "\n".join(lines) + "\n"
        out[f"{name}.expected"] = "\n".join(stdout) + "\n"
        out[f"{name}.stderr"] = "".join(f"{e}\n" for e in stderr)
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_memory_enum_matrix: {path.relative_to(OUT.parent.parent.parent)} is "
                      "out of date; run tools/gen_memory_enum_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
