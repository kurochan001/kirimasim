#!/usr/bin/env python3
"""Generates the violation report matrix tests of TEST_SUITE.md
("Mechanism matrix") in tests/suite/values/.

  tools/gen_violation_matrix.py           # writes the files
  tools/gen_violation_matrix.py --check   # exit 1 if a file differs from what it would write

The reports of unique, unique0 and priority violations (12.4.2, 12.5.3;
SYSTEM_TASKS.md 10.4; SCHEDULER_SPEC.md 15): every construct (unique,
unique0 and priority case and if) in every place (the body of a
procedure, a named block, a function and a task that the procedure
calls), each in a procedure of its own. A report names the scope of the
statement: top, the named block, or the subroutine. And the order of the
reports of several procedures in one time step: the order of their
numbers, whatever order they ran in.

The expected reports follow from the rules below. A person checks them
against the standard and the spec once for all the tests made from them
(TEST_SUITE.md, "Sampling by people").
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "values"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

# (keyword, kind): unique and unique0 see two matches, priority none.
CONSTRUCTS = [("unique", "case"), ("unique0", "case"), ("priority", "case"),
              ("unique", "if"), ("unique0", "if"), ("priority", "if")]
PLACES = ["body", "block", "function", "task"]


def content(keyword, kind):
    """SYSTEM_TASKS.md 10.4: two or more matches for unique and unique0
    (12.4.2, 12.5.3), no match for priority, which has no else here."""
    if keyword == "priority":
        return "no item matches" if kind == "case" else "no condition is true"
    return "more than one item matches" if kind == "case" else "more than one condition is true"


def statement(keyword, kind, indent):
    """The construct on sel, a and b, all equal when it runs: two items
    or conditions match for unique and unique0; for priority none does."""
    if kind == "case":
        if keyword == "priority":
            items = ["~a: hits++;", "~b: hits++;"]
        else:
            items = ["a: hits++;", "b: hits++;"]
        return ([f"{indent}{keyword} case (sel)"] + [f"{indent}  {i}" for i in items] +
                [f"{indent}endcase"])
    if keyword == "priority":
        return [f"{indent}{keyword} if (sel != a) hits++;", f"{indent}else if (sel != b) hits++;"]
    return [f"{indent}{keyword} if (sel == a) hits++;", f"{indent}else if (sel == b) hits++;"]


def test():
    name = "violation_scopes"
    lines = [
        "/*", f":name: {name}",
        ":description: Unique, unique0 and priority violations of case and if in the body of a "
        "procedure, a named block, a function and a task name the scope of the statement",
        ":tags: case unique deferred", ":type: simulation",
        ":lrm: 1800-2023 12.4.2 12.4.2.1 12.5.3 9.3.5 13", ":oracle: spec", ":spec_check: ai",
        ":fourstate: no", ":nondeterministic: no", f":generator: gen_violation_matrix.py@{VERSION}",
        f":expected_stdout: @{name}.expected", f":expected_stderr: @{name}.stderr", "*/",
        "// Generated by tools/gen_violation_matrix.py; change the generator, not this file.",
        "// Each procedure runs once, at its own time step (go counts them), so each report",
        "// matures alone in the Observed region (SCHEDULER_SPEC.md 15.3); sel, a and b are",
        "// equal, so unique and unique0 see two matches and priority none.",
        "`timescale 1ns/1ns", "module top;", "  logic [1:0] sel, a, b;", "  int hits, go;",
    ]
    reports = []
    k = 0
    for keyword, kind in CONSTRUCTS:
        for place in PLACES:
            t = k + 1
            if place == "function":
                lines.append(f"  function automatic int f{k}();")
                start = len(lines) + 1
                lines += statement(keyword, kind, "    ")
                lines += ["    return 0;", "  endfunction"]
                lines.append(f"  always @(go) if (go == {t}) void'(f{k}());")
                scope = f"top.f{k}"
            elif place == "task":
                lines.append(f"  task automatic t{k}();")
                start = len(lines) + 1
                lines += statement(keyword, kind, "    ")
                lines += ["  endtask"]
                lines.append(f"  always @(go) if (go == {t}) t{k}();")
                scope = f"top.t{k}"
            elif place == "block":
                lines.append(f"  always @(go) if (go == {t}) begin : b{k}")
                start = len(lines) + 1
                lines += statement(keyword, kind, "    ")
                lines.append("  end")
                scope = f"top.b{k}"
            else:
                lines.append(f"  always @(go) if (go == {t}) begin")
                start = len(lines) + 1
                lines += statement(keyword, kind, "    ")
                lines.append("  end")
                scope = "top"
            construct = f"{keyword} {kind}"
            reports.append(f"{name}.sv:{start}: warning: {construct} violation: "
                           f"{content(keyword, kind)} [{scope} @ {t}ns]")
            k += 1
    lines += ["  initial begin", "    sel = 2'd1;", "    a = 2'd1;", "    b = 2'd1;"]
    for t in range(1, k + 1):
        lines.append("    #1 go++;")
    lines += ["    #1 $display(\"hits %0d\", hits);", "  end", "endmodule", ""]
    # Every unique and unique0 statement runs its first match; priority none.
    hits = sum(1 for kw, _ in CONSTRUCTS for _ in PLACES if kw != "priority")
    return name, "\n".join(lines), f"hits {hits}\n", "\n".join(reports) + "\n"


def order_test():
    """Several procedures with a violation in one time step, run in the
    reverse order of their numbers: the reports come in the order of the
    numbers (SCHEDULER_SPEC.md 15.4)."""
    name = "violation_order"
    lines = [
        "/*", f":name: {name}",
        ":description: Violations held by several procedures in one time step are reported in "
        "the order of the procedures, whatever order they ran in",
        ":tags: case unique deferred", ":type: simulation",
        ":lrm: 1800-2023 12.4.2.1 12.5.3", ":oracle: spec", ":spec_check: ai",
        ":fourstate: no", ":nondeterministic: no", f":generator: gen_violation_matrix.py@{VERSION}",
        f":expected_stdout: @{name}.expected", f":expected_stderr: @{name}.stderr", "*/",
        "// Generated by tools/gen_violation_matrix.py; change the generator, not this file.",
        "// The standard leaves the order of reports to the tool (12.4.2.1); kirimasim",
        "// confirms them in the order of the processes, which is the order of the source",
        "// here (SCHEDULER_SPEC.md 15.4). The initial procedure wakes them last first.",
        "`timescale 1ns/1ns", "module top;", "  logic [1:0] sel, a, b;", "  int hits;",
        "  logic " + ", ".join(f"g{k}" for k in range(len(CONSTRUCTS))) + ";",
    ]
    reports = []
    for k, (keyword, kind) in enumerate(CONSTRUCTS):
        lines.append(f"  always @(g{k}) begin")
        start = len(lines) + 1
        lines += statement(keyword, kind, "    ")
        lines.append("  end")
        reports.append(f"{name}.sv:{start}: warning: {keyword} {kind} violation: "
                       f"{content(keyword, kind)} [top @ 1ns]")
    lines += ["  initial begin", "    sel = 2'd1;", "    a = 2'd1;", "    b = 2'd1;", "    #1;"]
    lines += [f"    g{k} = 1'b1;" for k in reversed(range(len(CONSTRUCTS)))]
    lines += ["    #1 $display(\"hits %0d\", hits);", "  end", "endmodule", ""]
    hits = sum(1 for kw, _ in CONSTRUCTS if kw != "priority")
    return name, "\n".join(lines), f"hits {hits}\n", "\n".join(reports) + "\n"


def files():
    out = {}
    for name, sv, exp, err in [test(), order_test()]:
        out.update({f"{name}.sv": sv, f"{name}.expected": exp, f"{name}.stderr": err})
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_violation_matrix: {path.relative_to(OUT.parent.parent.parent)} is "
                      "out of date; run tools/gen_violation_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
