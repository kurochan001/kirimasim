"""Generates the matrix test of defparam on a parameter declared with no
type (TEST_SUITE.md, "Mechanism matrix") in tests/suite/hier/.

  tools/gen_defparam_untyped_matrix.py           # writes the files
  tools/gen_defparam_untyped_matrix.py --check   # exit 1 if a file differs from what it would write

The rule: 6.20.2 and 23.10.1 of the standard. A parameter declared with
no type and no range takes the type and range of the final value given
to it, whether that value comes from an override in the instance (#(...))
or from a defparam. The run-time value, its width and what a generate
condition sees are then the same for the two ways of overriding.

The axes: the new value (wider than the default, narrower, signed
negative, unsigned of the same width), the way of overriding (#(...),
defparam), the place of the instance (the top module, a generate block,
an element of an array of instances), and what reads the parameter (a
procedure at run time, $bits, a shift, a generate
condition).

The expected output is computed here from the values. A person checks it
once for all the tests made from it (TEST_SUITE.md, "Sampling by
people").
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "hier"
NAME = "defparam_untyped_matrix"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

# (key, the value as written, its width, whether it is signed, its bits).
VALUES = [
    ("wider", "16'sh7FFF", 16, True, 0x7FFF),
    ("narrower", "4'd9", 4, False, 9),
    ("negative", "12'sh801", 12, True, 0x801),
    ("unsigned", "8'd200", 8, False, 200),
]
PLACES = ["top", "generate", "array"]


def files():
    sv = ["/*", f":name: {NAME}",
          ":description: A parameter declared with no type takes the type of the value a "
          "defparam gives it, as it does from an override in the instance: the value, its "
          "width, a shift and a generate condition agree",
          ":tags: hier", ":type: simulation", ":lrm: 1800-2023 6.20.2 23.10.1", ":oracle: spec",
          ":spec_check: ai", ":fourstate: no", ":nondeterministic: no",
          f":generator: gen_defparam_untyped_matrix.py@{VERSION}", ":top_module: top",
          f":expected_stdout: @{NAME}.expected", "*/",
          "// Generated by tools/gen_defparam_untyped_matrix.py; change the generator, not this "
          "file.", "`timescale 1ns/1ns",
          "module leaf #(parameter W = 8'shF0, parameter string name = \"\", "
          "parameter int at = 0) ();",
          "  int wide;",
          "  if ($bits(W) > 8) begin : g",
          "    assign wide = 1;",
          "  end",
          "  else begin : g",
          "    assign wide = 0;",
          "  end",
          "  initial begin",
          "    #at;",
          '    $display("%s: W=%0d bits=%0d shifted=%0d wide=%0d", name, W, $bits(W), W >> 2, '
          "wide);",
          "  end", "endmodule", "module top;"]
    expected = []
    at = 0
    for key, text, width, signed, bits in VALUES:
        value = bits - (1 << width) if signed and bits >> (width - 1) else bits
        # W >> 2 is a logical shift of a value of the parameter's own width.
        shifted = bits >> 2
        for place in PLACES:
            for way in ("override", "defparam"):
                label = f"{key} {place} {way}"
                inst = f"u_{key}_{place}_{way}"
                over = f".W({text}), " if way == "override" else ""
                decl = f'leaf #({over}.name("{label}"), .at({at}))'
                if place == "top":
                    sv.append(f"  {decl} {inst} ();")
                    target = inst
                elif place == "generate":
                    sv += [f"  if (1) begin : g_{key}_{way}", f"    {decl} {inst} ();", "  end"]
                    target = f"g_{key}_{way}.{inst}"
                else:
                    sv.append(f"  {decl} {inst} [1:0] ();")
                    target = f"{inst}[1]"
                if way == "defparam":
                    sv.append(f"  defparam {target}.W = {text};")
                if place == "array":
                    # Both elements print; the override reaches both, the
                    # defparam only element 1, element 0 keeping the default.
                    if way == "override":
                        expected += [(at, f"{label}: W={value} bits={width} shifted={shifted} "
                                          f"wide={int(width > 8)}")] * 2
                    else:
                        expected.append((at, f"{label}: W=-16 bits=8 shifted=60 wide=0"))
                        expected.append((at, f"{label}: W={value} bits={width} shifted={shifted} "
                                             f"wide={int(width > 8)}"))
                else:
                    expected.append((at, f"{label}: W={value} bits={width} shifted={shifted} "
                                         f"wide={int(width > 8)}"))
                at += 1
    sv += ["endmodule"]
    return {f"{NAME}.sv": "\n".join(sv) + "\n",
            f"{NAME}.expected": "\n".join(e[1] for e in expected) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_defparam_untyped_matrix: {path.relative_to(OUT.parent.parent.parent)} "
                      "is out of date; run tools/gen_defparam_untyped_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
