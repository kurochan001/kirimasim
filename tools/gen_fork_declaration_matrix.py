"""Generate original fork declaration/lifetime tests (6.21, 9.3.2).

Declarations are not child processes. Static storage is shared; uncaptured
automatic initialization executes in the parent before any children start.
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / 'tests/suite/sched'
VERSION = 1
HOMES = ('initial', 'always', 'task', 'automatic', 'fork', 'generate', 'interface', 'program')


def output(name, source, expected, warn_implicit_static=False):
    text = f'''/*
:name: {name}
:description: Fork declarations initialize in their lifetime and do not become child processes
:tags: sched fork lifetime
:type: simulation
:lrm: 1800-2023 6.21 9.3.2
:fourstate: yes
:nondeterministic: no
:oracle: spec
:spec_check: ai
:generator: gen_fork_declaration_matrix.py@{VERSION}
:top_module: top
:expected_stdout: @{name}.expected
:expected_stderr: @{name}.stderr
*/
// Generated by tools/gen_fork_declaration_matrix.py (version {VERSION}); do not edit.
`timescale 1ns/1ns
{source}
'''
    warnings = ''
    if warn_implicit_static:
        for number, line in enumerate(text.splitlines(), 1):
            if 'word_t saved=seed_value();' in line:
                column = line.index('saved') + 1
                warnings += (f'{name}.sv:{number}:{column}: warning: initializing a static '
                             'variable in a procedural context requires an explicit '
                             "'static' keyword [-Wexplicit-static]\n")
    return {name + '.sv': text, name + '.expected': expected, name + '.stderr': warnings}


def matrix(home, width, state):
    name = f'fork_declaration_{home}_{state}_{width}'
    declaration = 'static ' if home == 'automatic' else ''
    bounds = f'0:{width-1}' if home in ('generate', 'interface') else f'{width-1}:0'
    common = f'''typedef {state} [{bounds}] word_t;
int calls, round, landed;
function automatic word_t seed_value(); calls++; return '1; endfunction
'''
    tail_any = "'x" if state == 'logic' else "'1"
    tail_none = "'z" if state == 'logic' else "'0"
    body = f'''for(round=0; round<2; round++) begin
  fork : all_scope
    {declaration}word_t saved=seed_value();
    begin
      #1; $display("all first %0t %0d %0d",$time,calls,saved === (round==0 ? '1 : '0));
      saved='0;
    end
    begin #2; $display("all shared %0t %0d",$time,saved === '0); end
  join
end
fork : any_scope
  {declaration}word_t saved=seed_value();
  begin
    #2; $display("any first %0t %0d",$time,saved === '1);
    saved={tail_any};
  end
  begin #5; $display("any shared %0t %0d",$time,saved === {tail_any}); end
join_any
$display("any resumed %0t %0d",$time,calls);
wait fork;
fork : none_scope
  {declaration}word_t saved=seed_value();
  begin
    #1; $display("none first %0t %0d",$time,saved === '1);
    saved={tail_none}; landed++;
  end
  begin #3; $display("none shared %0t %0d",$time,saved === {tail_none}); landed++; end
join_none
$display("none parent %0t %0d %0d",$time,calls,landed);
wait fork;
$display("done %0t %0d",$time,landed);
'''
    if home == 'initial':
        source = f'module top;\n{common}initial begin\n{body}end\nendmodule'
    elif home == 'always':
        source = f'module top;\n{common}event go;\nalways @(go) begin\n{body}end\ninitial #1 ->go;\nendmodule'
    elif home in ('task', 'automatic'):
        lifetime = 'automatic ' if home == 'automatic' else ''
        source = f'module top;\n{common}task {lifetime}run();\n{body}endtask\ninitial run();\nendmodule'
    elif home == 'fork':
        source = f'module top;\n{common}initial fork begin\n{body}end join\nendmodule'
    elif home == 'generate':
        source = f'module top;\n{common}if(1) begin:g\ninitial begin\n{body}end\nend\nendmodule'
    else:
        source = f'{home} worker;\n{common}initial begin\n{body}end\nend{home}\nmodule top; worker u(); endmodule'
    start = 1 if home == 'always' else 0
    expected = f'''all first {start+1} 3 1
all shared {start+2} 1
all first {start+3} 3 1
all shared {start+4} 1
any first {start+6} 1
any resumed {start+6} 3
any shared {start+9} 1
none parent {start+9} 3 0
none first {start+10} 1
none shared {start+12} 1
done {start+12} 2
'''
    return output(name, source, expected, home != 'automatic')


def mechanisms():
    cases = {}
    source = '''module top;
int calls, trace;
function int mark(input int value); calls++; trace=trace*10+value; return value; endfunction
task automatic run(input int value);
  fork : phase
    int first=mark(value);
    int second=mark(first+1);
    begin #2; $display("child %0t %0d %0d",$time,calls,trace); end
    begin #5; end
  join_any
  $display("parent %0t %0d %0d",$time,calls,trace);
  wait fork;
endtask
initial begin run(2);run(4);end
endmodule'''
    cases.update(output('fork_declaration_automatic_initializers', source,
                        'child 2 2 23\nparent 2 2 23\nchild 7 4 2345\nparent 7 4 2345\n'))
    source = '''module top;
int calls;
function int mark();calls++;return calls;endfunction
task automatic run();
  fork int first=mark(); join
  $display("all %0t %0d",$time,calls);
  fork int second=mark(); join_any
  $display("any %0t %0d",$time,calls);
  fork int third=mark(); join_none
  wait fork;
  $display("none %0t %0d",$time,calls);
endtask
initial run();
endmodule'''
    cases.update(output('fork_declaration_no_children', source, 'all 0 1\nany 0 2\nnone 0 3\n'))
    source = '''module top;
string path;
function int remember(input string value);path=value;return 7;endfunction
task automatic run();
  fork : phase
    string caller=$sformatf("%m");
    int unused=remember(caller);
    begin #1; end
  join
endtask
initial begin run();$display("%s",path);end
endmodule'''
    cases.update(output('fork_declaration_initializer_scope', source, 'top.run.phase\n'))
    source = '''module top;
int calls, seen[6];
function int mark(input int value);calls++;seen[value]++;return value;endfunction
task automatic run(input int value);
  fork
    int first=mark(value);
    int second=mark(first+1);
    begin #2; end
  join
endtask
initial begin
  fork run(1);run(4);join
  $display("%0t %0d %0d %0d %0d %0d",$time,calls,seen[1],seen[2],seen[4],seen[5]);
end
endmodule'''
    cases.update(output('fork_declaration_concurrent_initializers', source, '2 4 1 1 1 1\n'))
    source = '''module top;
int calls, trace;
function bit permit();calls++;return 0;endfunction
function int mark(input int value);trace=trace*10+value;return value;endfunction
task automatic run();
  fork
    int first=(permit() && permit()) ? mark(1) : mark(2);
    int second=mark(first+1);
    begin #1; end
  join
endtask
initial begin run();$display("%0d %0d",calls,trace);end
endmodule'''
    cases.update(output('fork_declaration_initializer_control_flow', source, '1 23\n'))
    source = '''module top;
initial begin
  fork : phase
    logic [128:0] values[-1:0];
    integer unknown_value;
    bit clear_value;
    real real_value;
    string text;
    begin
      #1;
      $display("defaults %0d %0d %0d %0d %0d",values[-1] === 'x,unknown_value === 'x,clear_value == 0,real_value == 0.0,text == "");
      values[-1]='1;values[0]='z;text="shared";real_value=2.5;
    end
    begin #2;$display("shared %0d %0d %s %0.1f",values[-1] === '1,values[0] === 'z,text,real_value);end
  join
end
endmodule'''
    cases.update(output('fork_declaration_typed_storage', source,
                        'defaults 1 1 1 1 1\nshared 1 1 shared 2.5\n'))
    source = '''module top;
initial begin
  fork
    int queue_value[$];
    event ready;
    begin #1;queue_value.push_back(7);->ready;end
    begin @(ready);$display("%0d %0d",queue_value.size(),queue_value[0]);end
  join
end
endmodule'''
    cases.update(output('fork_declaration_container_event', source, '1 7\n'))
    source = '''module top;
int hits;
function int start_later();
  fork begin #2;hits++;end join_none
  return 7;
endfunction
task automatic run();
  fork int unused=start_later(); join
  $display("parent %0t %0d",$time,hits);
  wait fork;
  $display("done %0t %0d",$time,hits);
endtask
initial run();
endmodule'''
    cases.update(output('fork_declaration_initializer_starts_work', source,
                        'parent 0 0\ndone 2 1\n'))
    return cases


def generated():
    cases = mechanisms()
    for home in HOMES:
        for width in (1, 32, 65, 129):
            for state in ('bit', 'logic'):
                cases.update(matrix(home, width, state))
    return cases


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    cases = generated()
    OUT.mkdir(parents=True, exist_ok=True)
    failed = []
    for name, text in cases.items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                failed.append(name)
        else:
            path.write_text(text)
    if failed:
        print('generated fork declaration files differ: ' + ', '.join(failed), file=sys.stderr)
        return 1
    print(f'{len(cases)//3} fork declaration source cases ' + ('checked' if args.check else 'written'))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
