"""Dynamic arrays and queues in the set of inside and case inside (IEEE 1800-2023 11.4.13).

A container in the set stands for its elements at the time of the operator. An
integral element is compared with ==?, so its x and z bits match any value and
those of the left operand give x; others are compared with ==. The result is the
OR of the comparisons, and an empty container matches nothing. Every expected
result is computed here from these rules, not from a run.
"""
import argparse
from pathlib import Path
from typing import NamedTuple

OUT = Path(__file__).resolve().parent.parent / 'tests/suite/containers'


class Kind(NamedTuple):
    text: str
    width: int      # 0: not integral, compared with ==
    elements: tuple
    needles: tuple


def bits(value, width):
    return value if isinstance(value, str) else format(value & ((1 << width) - 1), f'0{width}b')


def wildcard(needle, element, width):
    """needle ==? element, by bits."""
    result = '1'
    for a, b in zip(bits(needle, width), bits(element, width)):
        if b in 'xz':
            continue
        if a in 'xz':
            result = 'x' if result == '1' else result
        elif a != b:
            return '0'
    return result


def member(needle, element, kind):
    if kind.width:
        return wildcard(needle, element, kind.width)
    return '1' if needle == element else '0'


def any_of(results):
    if '1' in results:
        return '1'
    return 'x' if 'x' in results else '0'


def literal(value, kind):
    if not kind.width:
        return repr(value) if isinstance(value, float) else f'"{value}"'
    return f"{kind.width}'b{bits(value, kind.width)}"


KINDS = {
    'int': Kind('int', 32, (3, 4, 5), (4, 3, 5, 9)),
    'logic8': Kind('logic [7:0]', 8, ('0000001x', 9, 'z0000000'), (2, 3, 9, 128, 7, 'xxxxxxxx', '0000x000')),
    'bit8': Kind('bit [7:0]', 8, (200, 201), (200, 201, 202)),
    'logic129': Kind('logic [128:0]', 129, ((1 << 128) | 1, (1 << 64) + 5), ((1 << 128) | 1, (1 << 64) + 5, (1 << 128) | 3)),
    'string': Kind('string', 0, ('a', 'bc'), ('a', 'bc', 'c')),
    'real': Kind('real', 0, (1.5, 2.5), (1.5, 2.5, 3.0)),
}


def source(name, description, text, expected):
    name = 'inside_container_' + name
    return name, f'''/*
:name: {name}
:description: {description}
:tags: containers inside
:type: simulation
:lrm: 1800-2023 11.4.13 12.5.4 7.5 7.10
:oracle: spec
:spec_check: ai
:fourstate: yes
:nondeterministic: no
:generator: gen_inside_container_matrix.py@1
:top_module: top
:expected_stdout: {expected}
:timeout: 15
*/
// Generated by tools/gen_inside_container_matrix.py; edit the generator.
`timescale 1ns/1ns
{text}'''


def fill(name, container, kind, elements):
    if container == 'queue':
        return f'{name}.delete();\n' + ''.join(f'{name}.push_back({literal(e, kind)});\n' for e in elements)
    return (f'{name}=new[{len(elements)}];\n' +
            ''.join(f'{name}[{i}]={literal(e, kind)};\n' for i, e in enumerate(elements)))


def declare(name, container, kind):
    return f'{kind.text} {name}[$];\n' if container == 'queue' else f'{kind.text} {name}[];\n'


def probes(kind, set_text, elements_results):
    lines = ''
    expected = ''
    for needle in kind.needles:
        lines += f'v={literal(needle, kind)}; r=v inside {{{set_text}}}; $write("%b",r);\n'
        expected += any_of(elements_results(needle))
    return lines + '$display("");\n', expected


def forms():
    for name, kind in KINDS.items():
        for container in ('queue', 'dynamic'):
            head = f'module top;\n{declare("c", container, kind)}{kind.text} v;\nlogic r;\n'
            # All the elements.
            body, expected = probes(kind, 'c', lambda n: [member(n, e, kind) for e in kind.elements])
            yield source(f'{name}_{container}', 'Every element of a container in the set is compared',
                         head + 'initial begin\n' + fill('c', container, kind, kind.elements) + body + 'end\nendmodule\n', expected)
            # With nothing in it.
            body, expected = probes(kind, 'c', lambda n: [])
            yield source(f'{name}_{container}_empty', 'An empty container in the set matches nothing',
                         head + 'initial begin\n' + fill('c', container, kind, ()) + body + 'end\nendmodule\n', expected)
            # Next to a listed value.
            extra = kind.needles[-1]
            body, expected = probes(kind, f'{literal(extra, kind)},c',
                                    lambda n: [member(n, extra, kind)] + [member(n, e, kind) for e in kind.elements])
            yield source(f'{name}_{container}_with_value', 'A container counts with the other members of the set',
                         head + 'initial begin\n' + fill('c', container, kind, kind.elements) + body + 'end\nendmodule\n', expected)
    # The contents at the time of the operator, not earlier.
    text = '''module top;
int q[$];
int v=7;
logic r;
initial begin
q.push_back(1);
r=v inside {q}; $write("%b",r);
q.push_back(7);
r=v inside {q}; $write("%b",r);
q.delete(1);
r=v inside {q}; $display("%b",r);
end
endmodule
'''
    yield source('contents_at_the_operator', 'A container in the set has the contents it has at the operator', text, '010')
    # Two containers, a range and a fixed array of queues.
    text = '''module top;
int q[$];
int d[];
int f[2][$];
int v;
logic r;
initial begin
q.push_back(1);
d=new[1]; d[0]=2;
f[0].push_back(3);
f[1].push_back(4);
v=1; r=v inside {q,d}; $write("%b",r);
v=2; r=v inside {q,d}; $write("%b",r);
v=3; r=v inside {q,d}; $write("%b",r);
v=3; r=v inside {f}; $write("%b",r);
v=4; r=v inside {f}; $write("%b",r);
v=5; r=v inside {f}; $write("%b",r);
v=11; r=v inside {q,[10:12]}; $write("%b",r);
v=13; r=v inside {q,[10:12]}; $display("%b",r);
end
endmodule
'''
    yield source('several_members', 'Containers, ranges and a fixed array of queues share one set', text, '11011010')


PLACE_BODY = '''q.push_back(3);
q.push_back(4);
v=4; r=v inside {q}; $write("%b",r);
v=9; r=v inside {q}; $write("%b",r);
d=new[2]; d[0]=5; d[1]=6;
v=6; r=v inside {d}; $write("%b",r);
v=9; r=v inside {d}; $write("%b",r);
case (4) inside
q: $write("1");
default: $write("0");
endcase
case (9) inside
d: $write("1");
default: $write("0");
endcase
$display("");'''
LOCALS = 'int q[$];\nint d[];\nint v;\nlogic r;\n'
PLACE_EXPECTED = '101010'


def places():
    yield source('place_module', 'A container in the set does not depend on its place',
                 f'module top;\n{LOCALS}initial begin\n{PLACE_BODY}\nend\nendmodule\n', PLACE_EXPECTED)
    yield source('place_automatic_task', 'A container in the set does not depend on its place',
                 f'module top;\ntask automatic run();\n{LOCALS}{PLACE_BODY}\nendtask\ninitial run();\nendmodule\n', PLACE_EXPECTED)
    yield source('place_function', 'A container in the set does not depend on its place',
                 f'module top;\nfunction automatic void run();\n{LOCALS}{PLACE_BODY}\nendfunction\ninitial run();\nendmodule\n', PLACE_EXPECTED)
    yield source('place_fork', 'A container in the set does not depend on its place',
                 f'module top;\n{LOCALS}initial begin\nfork\nbegin\n{PLACE_BODY}\nend\njoin\nend\nendmodule\n', PLACE_EXPECTED)
    yield source('place_generate', 'A container in the set does not depend on its place',
                 f'module top;\nif(1) begin:g\n{LOCALS}initial begin\n{PLACE_BODY}\nend\nend\nendmodule\n', PLACE_EXPECTED)
    yield source('place_method', 'A container in the set does not depend on its place',
                 f'class box;\nfunction void run();\n{LOCALS}{PLACE_BODY}\nendfunction\nendclass\nmodule top;\nbox k;\ninitial begin k=new; k.run(); end\nendmodule\n', PLACE_EXPECTED)
    yield source('place_interface', 'A container in the set does not depend on its place',
                 f'interface unit;\n{LOCALS}initial begin\n{PLACE_BODY}\nend\nendinterface\nmodule top;\nunit u();\nendmodule\n', PLACE_EXPECTED)
    yield source('place_input_argument', 'A container argument in the set has the contents it was given',
                 'module top;\nint q[$];\nfunction automatic void run(input int c[$]);\nint v=4;\nlogic r=v inside {c};\n$display("%b",r);\nendfunction\ninitial begin\nq.push_back(4);\nrun(q);\nend\nendmodule\n', '1')


def cases():
    yield from forms()
    yield from places()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = dict(cases())
    failed = False
    for name, text in generated.items():
        path = OUT / (name + '.sv')
        if args.check:
            if not path.exists() or path.read_text() != text:
                print(f'out of date: {path.relative_to(OUT.parent.parent.parent)}')
                failed = True
        else:
            path.write_text(text)
    print(f'inside container matrix: {len(generated)} sources')
    return int(failed)


if __name__ == '__main__':
    raise SystemExit(main())
