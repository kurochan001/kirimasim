"""Original byte-model matrix for the approved multidimensional fread contract.

The oracle enumerates Cartesian products of numerical indices. It uses no
division/modulo address decoding and no simulator output. Partial leaves
replace supplied high bytes in a padded bit string, retaining unread bits.
"""

import argparse
import itertools
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests/suite/proc"
VERSION = 1
SHAPES = {
    "up": [(0, 1), (0, 2)],
    "down": [(3, 2), (7, 5)],
    "negative": [(-1, 0), (-2, 0)],
    "three": [(2, 1), (-1, 0), (4, 3)],
    "one": [(4, 1)],
}


def locations(ranges):
    return list(itertools.product(*(range(min(a, b), max(a, b) + 1) for a, b in ranges)))


def index_text(indices):
    return "".join(f"[{i}]" for i in indices)


def case(shape, width, four, context):
    ranges = SHAPES[shape]
    indices = locations(ranges)
    low = min(ranges[0]) if len(ranges) == 1 else 0
    high = low + len(indices) - 1
    nbytes = (width + 7) // 8
    old = ("x" if four else "1") * width
    scenarios = [
        ("full", None, None, len(indices) * nbytes + 3),
        ("range", low + 1, 2, len(indices) * nbytes),
        ("partial", None, None, 2 * nbytes + nbytes // 2),
        ("before", low - 1, 2, 20),
        ("zero", low, 0, 20),
        ("negative", low, -2, 20),
        ("last", high, 100, 20),
        ("omitted", None, 2, 20),
        ("after", high + 1, 1, 20),
    ]
    body, expected = "", ""
    for label, start, count, length in scenarios:
        body += "    make_bytes(" + str(length) + ");\n"
        for index in indices:
            body += f"    mem{index_text(index)} = '{'x' if four else '1'};\n"
        body += '    fd = $fopen("bytes.bin", "rb");\n'
        args = "mem, fd"
        if start is not None or count is not None:
            args += ", " + (str(start) if start is not None else "")
        if count is not None:
            args += ", " + str(count)
        body += f"    got = $fread({args});\n"
        exprs = ", ".join("mem" + index_text(i) for i in indices)
        body += (f'    $display("{label} %0d %0d ' + " ".join(["%b"] * len(indices))
                 + f'", got, $ftell(fd), {exprs});\n    $fclose(fd);\n')
        values, offset = [old] * len(indices), 0
        first = low if start is None else start
        left = len(indices) if count is None else count
        data = bytes((i * 37 + 11) & 255 for i in range(length))
        if low <= first <= high:
            # Select a suffix of enumerated coordinates, then visit at most
            # count leaves. This intentionally differs from front's decoder.
            for position in list(range(len(indices)))[first - low:][:max(0, left)]:
                supplied = data[offset:offset + nbytes]
                bits = "0" * (8 * nbytes - width) + values[position]
                replaced = "".join(f"{b:08b}" for b in supplied)
                values[position] = (replaced + bits[len(replaced):])[-width:]
                offset += len(supplied)
                if len(supplied) < nbytes:
                    break
        expected += f"{label} {offset} {offset} " + " ".join(values) + "\n"
    declaration = "logic" if four else "bit"
    dims = "".join(f"[{a}:{b}]" for a, b in ranges)
    types = f"typedef {declaration} [{width - 1}:0] word_t;\ntypedef word_t memory_t{dims};\n"
    locals_ = "int fd, got;\n"
    if context == "initial":
        run = "memory_t mem;\n" + locals_ + "initial begin\n" + body + "end\n"
    elif context == "automatic":
        run = "task automatic run; memory_t mem;\n" + locals_ + body + "endtask\ninitial run();\n"
    else:
        run = ("memory_t mem;\ntask automatic run(ref memory_t mem);\n" + locals_
               + body + "endtask\ninitial run(mem);\n")
    name = f"multidim_fread_{shape}_{context}_{'four' if four else 'two'}_{width}"
    text = f'''/*
:name: {name}
:description: Binary memory input, numerical traversal and partial leaves in {context}
:tags: proc
:type: simulation
:lrm: 1800-2023 7.4.4 21.3.4.4
:oracle: spec
:spec_check: ai
:fourstate: {'yes' if four else 'no'}
:nondeterministic: no
:generator: gen_multidim_fread_matrix.py@{VERSION}
:top_module: top
:expected_stdout: @{name}.expected
*/
// Generated by tools/gen_multidim_fread_matrix.py.
// Multidimensional scalar start/count follows the approved project interpretation.
module top;
{types}
task automatic make_bytes(input int count);
  int file;
  file = $fopen("bytes.bin", "wb");
  for (int i = 0; i < count; i++) $fwrite(file, "%c", (i * 37 + 11) & 255);
  $fclose(file);
endtask
{run}
endmodule
'''
    return name, text, expected


def prefix_case(context, remaining):
    name = f"multidim_fread_prefix_{context}_{remaining}"
    target = "mem[prefix()]" + ("[2]" if remaining == 1 else "")
    body = f'''    foreach (mem[i,j,k]) mem[i][j][k] = 0;
    fd = $fopen("prefix.bin", "wb");
    $fwrite(fd, "%c%c%c", 17, 34, 51); $fclose(fd);
    fd = $fopen("prefix.bin", "rb");
    selected = 0; trace = 0;
    got = $fread({target}, descriptor(), start(), amount());
    $display("%0d %0d %0d %0d %0d %0d %0d", trace, selected, got,
             mem[0][2][-1], mem[0][2][0], mem[0][2][1], mem[1][2][1]);
    $fclose(fd);
'''
    if context == "initial":
        run = "memory_t mem; int got; initial begin\n" + body + "end\n"
    elif context == "automatic":
        run = ("task automatic run; memory_t mem; int got; #1;\n" + body
               + "endtask\ninitial run();\n")
    else:
        run = ("memory_t mem; task automatic run(ref memory_t mem); int got; #1;\n"
               + body + "endtask\ninitial run(mem);\n")
    source = f'''/*
:name: {name}
:description: Capture runtime selected memory prefix before descriptor/start/count effects
:tags: proc
:type: simulation
:lrm: 1800-2023 7.4.4 21.3.4.4
:oracle: spec
:spec_check: ai
:fourstate: no
:nondeterministic: no
:generator: gen_multidim_fread_matrix.py@{VERSION}
:top_module: top
:expected_stdout: @{name}.expected
*/
// Generated by tools/gen_multidim_fread_matrix.py.
module top;
typedef bit [7:0] memory_t[1:0][3:2][-1:1];
int selected, trace, fd;
function int prefix(); trace = trace * 10 + 1; return selected; endfunction
function int descriptor(); trace = trace * 10 + 2; selected = 1; return fd; endfunction
function int start(); trace = trace * 10 + 3; return 1; endfunction
function int amount(); trace = trace * 10 + 4; return 2; endfunction
{run}
endmodule
'''
    expected = "1234 1 1 0 0 17 0\n" if remaining == 1 else "1234 1 2 0 17 34 0\n"
    return name, source, expected


def files():
    out = {}
    for shape in SHAPES:
        for width in (1, 9, 32, 65, 129):
            for four in (False, True):
                for context in ("initial", "automatic", "ref"):
                    name, source, expected = case(shape, width, four, context)
                    out[name + ".sv"] = source
                    out[name + ".expected"] = expected
    for context in ("initial", "automatic", "ref"):
        for remaining in (1, 2):
            name, source, expected = prefix_case(context, remaining)
            out[name + ".sv"] = source
            out[name + ".expected"] = expected
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    failures = 0
    for name, text in files().items():
        p = OUT / name
        if args.check:
            if not p.exists() or p.read_text() != text:
                print(f"gen_multidim_fread_matrix: out of date: {name}")
                failures += 1
        else:
            p.write_text(text)
    return bool(failures)


if __name__ == "__main__":
    raise SystemExit(main())
