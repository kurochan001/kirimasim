"""Generates the matrix tests of the size of an address in the file of
$readmemb and $readmemh (TEST_SUITE.md, "Mechanism matrix") in
tests/suite/proc/.

  tools/gen_memory_address_matrix.py           # writes the files
  tools/gen_memory_address_matrix.py --check   # exit 1 if a file differs from what it would write

The rules (21.4, SYSTEM_TASKS.md 7.1), with those of any memory
(tools/gen_memory_file_matrix.py):

- An address in the file is a hexadecimal number, in both tasks. It is
  the number that is written, however many digits it has: zeros in front
  do not change it, and a number too large for the range is outside the
  range whatever its low digits are.
- An address outside the range is an error of the file: a warning names
  it, reading stops, and the words read before stay.

The axes: the address (in the range; in the range with zeros in front,
past 16 digits; 17 digits whose low 16 are an address of the range, and
whose low 16 are zero; 20 digits; 16 digits, all f), the task, the memory
(4-state with a rising range, 2-state with a falling range, signed) and the container of the
calls (an initial procedure, a task, a function).

Each file gives one word, which goes to the lowest address, then the
address and a second word. The expected outputs follow from the rules
above, without reading kirimasim's code. For reference, checked
2026-11-12 with the first memory: Icarus 14.0 devel takes an address of
17 or 20 digits as outside the range too, and names another address than
the one written in its error.
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "proc"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

CONTAINERS = ["initial", "task", "function"]

# (key, the address as written, the element it names or None, the address
# as the warning names it).
ADDRESSES = [
    ("in", "2", 2, None),
    ("zeros", "00000000000000000002", 2, None),
    ("low_in", "10000000000000002", None, "10000000000000002"),
    ("low_zero", "10000000000000000", None, "10000000000000000"),
    ("twenty", "FFFFFFFFFFFFFFFFFFFF", None, "FFFFFFFFFFFFFFFFFFFF"),
    ("sixteen", "ffffffffffffffff", None, "ffffffffffffffff"),
]

# (task, the first word, the second word, their values in hexadecimal).
TASKS = [("$readmemh", "11", "5a", "11", "5a"), ("$readmemb", "11", "101", "03", "05")]

# (name, declaration, statement that makes its elements or None).
MEMORIES = [("m", "logic [7:0] m [0:3];", None),
            ("d", "bit [7:0] d [3:0];", None),
            ("s", "logic signed [7:0] s [0:3];", None)]


def cells():
    for task, first, second, v1, v2 in TASKS:
        for mem, _, _ in MEMORIES:
            for key, written, element, named in ADDRESSES:
                yield task, first, second, v1, v2, mem, key, written, element, named


def test(container):
    name = f"memory_address_size_{container}"
    lines = ["/*", f":name: {name}",
             ":description: an address in the file of $readmemh and $readmemb is the number "
             "written, whatever its number of digits, called from "
             f"{'an' if container[0] in 'aeiou' else 'a'} {container}",
             ":tags: proc", ":type: simulation", ":lrm: 1800-2023 21.4", ":oracle: spec",
             ":spec_check: ai", ":fourstate: yes", ":nondeterministic: no",
             f":generator: gen_memory_address_matrix.py@{VERSION}", ":top_module: top",
             f":expected_stdout: @{name}.expected", f":expected_stderr: @{name}.stderr", "*/",
             "// Generated by tools/gen_memory_address_matrix.py; change the generator, not this "
             "file.", "`timescale 1ns/1ns", "module top;"]
    lines += [f"  {decl}" for _, decl, _ in MEMORIES] + ["  integer fd;"]
    indent = {"initial": "    ", "task": "    ", "function": "    "}[container]
    body, stdout, calls = [], [], []
    for n, (task, first, second, v1, v2, mem, key, written, element, named) in enumerate(cells()):
        label = f"{task[1:]} {mem} {key}"
        body.append(f"foreach ({mem}[i]) {mem}[i] = 8'hee;")
        body.append(f'{task}("a{n}.mem", {mem});')
        calls.append((len(body) - 1, task, named))
        body.append(f'$display("{label}: %h %h %h %h", {mem}[0], {mem}[1], {mem}[2], {mem}[3]);')
        values = [v1, "ee", "ee", "ee"]
        if element is not None:
            values[element] = v2
        stdout.append(f"{label}: {' '.join(values)}")
    if container == "task":
        lines += ["  task load;"]
    elif container == "function":
        lines += ["  function void load();"]
    else:
        lines += ["  initial begin"]
        for _, _, make in MEMORIES:
            if make:
                lines.append(f"    {make}")
        for n, (_, first, second, _, _, _, _, written, _, _) in enumerate(cells()):
            lines.append(f'    fd = $fopen("a{n}.mem", "w"); '
                         f'$fwrite(fd, "{first} @{written} {second}\\n"); $fclose(fd);')
    start = len(lines)
    lines += [indent + b for b in body]
    if container == "task":
        lines += ["  endtask"]
    elif container == "function":
        lines += ["  endfunction"]
    if container != "initial":
        lines += ["  initial begin"]
        for _, _, make in MEMORIES:
            if make:
                lines.append(f"    {make}")
        for n, (_, first, second, _, _, _, _, written, _, _) in enumerate(cells()):
            lines.append(f'    fd = $fopen("a{n}.mem", "w"); '
                         f'$fwrite(fd, "{first} @{written} {second}\\n"); $fclose(fd);')
        lines.append("    load;" if container == "task" else "    load();")
    lines += ["  end", "endmodule"]
    stderr = [f"{name}.sv:{start + at + 1}:{len(indent) + 1}: warning: {task}: address "
              f"@{named} in the file is outside the range 0 to 3"
              for at, task, named in calls if named is not None]
    return name, lines, stdout, stderr


def files():
    out = {}
    for container in CONTAINERS:
        name, lines, stdout, stderr = test(container)
        out[f"{name}.sv"] = "\n".join(lines) + "\n"
        out[f"{name}.expected"] = "\n".join(stdout) + "\n"
        out[f"{name}.stderr"] = "".join(f"{e}\n" for e in stderr)
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_memory_address_matrix: {path.relative_to(OUT.parent.parent.parent)} "
                      "is out of date; run tools/gen_memory_address_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
