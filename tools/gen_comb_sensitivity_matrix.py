"""Generates the matrix tests of the implicit sensitivity of always_comb
and always_latch, of TEST_SUITE.md ("Mechanism matrix"), in
tests/suite/proc/.

  tools/gen_comb_sensitivity_matrix.py           # writes the files
  tools/gen_comb_sensitivity_matrix.py --check   # exit 1 if a file differs from what it would write

The block runs again when a variable it reads changes: in the block, in
the functions it calls (and those they call), in the arguments of the
tasks it calls, and in the expressions of its immediate assertions. What
the body of a called task reads is no part of the sensitivity, nor what
the action blocks of its assertions read, in the block or in a function
it calls, nor what a function called from an action block reads
(9.2.2.2.1, 16.3; SCHEDULER_SPEC.md 6.3). always_latch has the same
sensitivity (9.2.2.3).

The axes: the block (always_comb, always_latch); where it reads v (the
places above). Each test changes v once, after the block ran at time 0,
and prints how many times it ran: 2 if v is in the sensitivity, 1 if
not.

The expected outputs follow from the rules above, computed below.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "proc"
PREFIX = "comb_sensitivity_"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

F = ["function automatic logic [7:0] f(logic [7:0] x);", "  return x + v;", "endfunction"]
# (name, the items of the module before the block, the statements of the
# block after runs++, whether v is in the sensitivity, what the
# description calls the place, the clauses)
PLACES = [
    ("block", [], ["y = a + v;"], True, "in the block", ["9.2.2.2.1"]),
    ("function", F, ["y = f(a);"], True, "in a function it calls", ["9.2.2.2.1"]),
    ("function_nested", F + ["function automatic logic [7:0] g(logic [7:0] x);",
                             "  return f(x);", "endfunction"],
     ["y = g(a);"], True, "in a function that a function it calls calls", ["9.2.2.2.1"]),
    ("task_argument", ["task automatic t(input logic [7:0] x, output logic [7:0] r);",
                       "  r = x;", "endtask"],
     ["t(v, y);"], True, "in an argument of a task it calls", ["9.2.2.2.1"]),
    ("task_body", ["task automatic t(input logic [7:0] x, output logic [7:0] r);",
                   "  r = x + v;", "endtask"],
     ["t(a, y);"], False, "in the body of a task it calls", ["9.2.2.2.1"]),
    ("task_body_function", F + ["task automatic t(input logic [7:0] x, output logic [7:0] r);",
                                "  r = f(x);", "endtask"],
     ["t(a, y);"], False, "in a function that a task it calls calls", ["9.2.2.2.1"]),
    ("assert_expression", [], ["y = a;", "assert (v != 8'd5);"], True,
     "in the expression of an immediate assertion", ["9.2.2.2.1", "16.3"]),
    ("assert_pass_action", [], ["y = a;", "assert (a != 8'd0) if (v == 8'd9) $display(\"v\");"],
     False, "in the pass action of an immediate assertion", ["9.2.2.2.1", "16.3"]),
    ("assert_fail_action", [],
     ["y = a;", "assert (a != 8'd0) else if (v == 8'd9) $display(\"v\");"], False,
     "in the fail action of an immediate assertion", ["9.2.2.2.1", "16.3"]),
    ("action_function", F, ["y = a;", "assert (a != 8'd0) else $display(\"%0d\", f(a));"],
     False, "in a function an action block calls", ["9.2.2.2.1", "16.3"]),
    ("deferred_action", [], ["y = a;", "assert #0 (a != 8'd0) else $display(\"%0d\", v);"],
     False, "in the action of a deferred assertion", ["9.2.2.2.1", "16.4"]),
    ("deferred_final_action", [],
     ["y = a;", "assert final (a != 8'd0) else $display(\"%0d\", v);"], False,
     "in the action of a final deferred assertion", ["9.2.2.2.1", "16.4"]),
    ("function_action", ["function automatic logic [7:0] h(logic [7:0] x);",
                         "  assert (x != 8'd0) else if (v == 8'd9) $display(\"v\");",
                         "  return x;", "endfunction"],
     ["y = h(a);"], False, "in an action block of an assertion in a function it calls",
     ["9.2.2.2.1", "16.3"]),
]
BLOCKS = ["always_comb", "always_latch"]


def header(name, description, lrm):
    return [
        "/*",
        f":name: {name}",
        f":description: {description}",
        ":tags: proc",
        ":type: simulation",
        ":lrm: 1800-2023 " + " ".join(lrm),
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: no",
        ":nondeterministic: no",
        f":generator: gen_comb_sensitivity_matrix.py@{VERSION}",
        ":issue: 21",
        ":top_module: top",
        f":expected_stdout: @{name}.expected",
        "*/",
        "// Generated by tools/gen_comb_sensitivity_matrix.py; change the generator, not this "
        "file.",
        "`timescale 1ns/1ns",
    ]


def case(block, place):
    pname, items, stmts, sensitive, where, clauses = place
    name = f"{PREFIX}{block}_{pname}"
    lines = ["module top;", "  logic [7:0] a = 8'd1, v = 8'd0, y;", "  int runs;"]
    lines += [f"  {x}" for x in items]
    lines += [f"  {block} begin", "    runs++;"] + [f"    {x}" for x in stmts] + ["  end"]
    lines += ["  initial begin", "    #1 v = 8'd3;", "    #1 $display(\"runs=%0d\", runs);", "  end",
              "endmodule"]
    lrm = clauses + (["9.2.2.3"] if block == "always_latch" else [])
    description = (f"{block} reads v {where}: a change of v runs it again"
                   if sensitive else f"{block} reads v {where}: a change of v does not run it")
    return name, header(name, description, lrm) + lines, [f"runs={2 if sensitive else 1}"]


def files():
    out = {}
    for block in BLOCKS:
        for place in PLACES:
            name, text, expected = case(block, place)
            out[f"{name}.sv"] = "\n".join(text) + "\n"
            out[f"{name}.expected"] = "\n".join(expected) + "\n"
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_comb_sensitivity_matrix: {path.relative_to(OUT.parent.parent.parent)} "
                      "is out of date; run tools/gen_comb_sensitivity_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
