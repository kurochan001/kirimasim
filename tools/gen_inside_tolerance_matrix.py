"""The tolerance ranges of inside and case inside: [A +/- B] and [A +%- B].

By IEEE 1800-2023 11.4.13 and VALUE_SEMANTICS.md 3.10 the bounds are A minus and
plus the tolerance in A's type, swapped if needed; [A +%- B] has A*B/100.0 as its
tolerance; and a real tolerance becomes integral by truncation, not by rounding.
A set member is compared at the type of the comparison (11.8.2). An x or z in the
left operand or in a bound makes the comparison x. Every expected result is
computed here from these rules, not from a run.
"""
import argparse
import math
from pathlib import Path
from typing import NamedTuple

OUT = Path(__file__).resolve().parent.parent / 'tests/suite/values'


class Kind(NamedTuple):
    text: str
    width: int
    signed: bool
    four: bool
    real: bool = False


TYPES = {
    'int': Kind('int', 32, True, False),
    'byte': Kind('byte', 8, True, False),
    'logic8': Kind('logic [7:0]', 8, False, True),
    'signed8': Kind('logic signed [7:0]', 8, True, True),
    'bit8': Kind('bit [7:0]', 8, False, False),
    'logic65': Kind('logic [64:0]', 65, False, True),
    'logic129': Kind('logic [128:0]', 129, False, True),
    'signed129': Kind('logic signed [128:0]', 129, True, True),
    'real': Kind('real', 64, True, False, True),
}
CASES = {
    'plain': (40, 3),
    'zero': (40, 0),
    'negative_b': (40, -3),
    'real_b': (40, 2.9),
    'negative_real_b': (40, -2.9),
    'small_a': (2, 5),
}


def wrap(value, kind):
    mask = (1 << kind.width) - 1
    value = int(value) & mask
    if kind.signed and value >> (kind.width - 1):
        value -= 1 << kind.width
    return value


def bounds(a, b, relative, kind):
    """The range the rules give, in A's type."""
    tolerance = float(a) * float(b) / 100.0 if relative else b
    if kind.real:
        tolerance = float(tolerance)
        low, high = float(a) - tolerance, float(a) + tolerance
    else:
        tolerance = wrap(math.trunc(tolerance), kind)
        low, high = wrap(a - tolerance, kind), wrap(a + tolerance, kind)
    return (high, low) if low > high else (low, high)


def literal(value, kind):
    if kind.real:
        return repr(float(value))
    if value < 0:
        return f"-{kind.width}'sd{-value}" if kind.signed else f"{kind.width}'d{value & ((1 << kind.width) - 1)}"
    return f"{kind.width}'{'s' if kind.signed else ''}d{value}"


def needles(low, high, kind):
    """Next to the bounds, at the bounds and between them, and all in the type."""
    if kind.real:
        step = 0.5
        points = [low - step, low, (low + high) / 2, high, high + step]
    else:
        points = [wrap(low - 1, kind), low, wrap((low + high) // 2, kind), high, wrap(high + 1, kind)]
    return points


def source(name, description, text, expected, lrm='11.4.13 11.8.2'):
    name = 'inside_tolerance_' + name
    head = f'''/*
:name: {name}
:description: {description}
:tags: values inside
:type: simulation
:lrm: 1800-2023 {lrm}
:oracle: spec
:spec_check: ai
:fourstate: yes
:nondeterministic: no
:generator: gen_inside_tolerance_matrix.py@1
:top_module: top
:expected_stdout: {expected}
:timeout: 15
*/
// Generated by tools/gen_inside_tolerance_matrix.py; edit the generator.
`timescale 1ns/1ns
{text}'''
    return name, head


def scoped(place, declarations, statements):
    body = f'{statements}\n$display("%s",result);'
    if place == 'initial':
        return f'module top;\n{declarations}\ninitial begin\n{body}\nend\nendmodule\n'
    if place == 'task':
        return (f'module top;\n{declarations}\ntask automatic run();\n{body}\nendtask\n'
                'initial run();\nendmodule\n')
    if place == 'function':
        return (f'module top;\n{declarations}\nfunction automatic void run();\n{body}\nendfunction\n'
                'initial run();\nendmodule\n')
    if place == 'method':
        return (f'class box;\n{declarations}\nfunction void run();\n{body}\nendfunction\nendclass\n'
                'module top;\nbox k;\ninitial begin k=new; k.run(); end\nendmodule\n')
    if place == 'fork':
        return (f'module top;\n{declarations}\ninitial begin\nfork\nbegin\n{body}\nend\njoin\nend\nendmodule\n')
    return f'module top;\nif(1) begin:g\n{declarations}\ninitial begin\n{body}\nend\nend\nendmodule\n'


def exercise(kind, a, b, relative, place, form='expression'):
    op = '+%-' if relative else '+/-'
    low, high = bounds(a, b, relative, kind)
    points = needles(low, high, kind)
    b_kind = 'real' if isinstance(b, float) else 'int'
    declarations = f'{kind.text} a;\n{b_kind} b;\n{kind.text} v;\nstring result="";'
    lines = [f'a={literal(a, kind)};', f'b={b!r};' if isinstance(b, float) else f'b={b};']
    expected = ''
    for point in points:
        lines.append(f'v={literal(point, kind)};')
        if form == 'expression':
            lines.append(f'if ((v inside {{[a {op} b]}}) === 1\'b1) result={{result,"1"}}; else result={{result,"0"}};')
        else:
            lines.append(f'case (v) inside\n[a {op} b]: result={{result,"1"}};\ndefault: result={{result,"0"}};\nendcase')
        expected += '1' if low <= point <= high else '0'
    return scoped(place, declarations, '\n'.join(lines)), expected


def forms():
    """Every type with both kinds and every combination of signs."""
    for name, kind in TYPES.items():
        for case, (a, b) in CASES.items():
            if not kind.signed and not kind.real and (a < 0):
                continue
            for relative in (False, True):
                text, expected = exercise(kind, a, b, relative, 'initial')
                yield source(f'{name}_{case}_{"relative" if relative else "absolute"}',
                             'A tolerance range is the bounds the rules give, in the type of A', text, expected)
        if kind.signed:
            for relative in (False, True):
                text, expected = exercise(kind, -40, 3, relative, 'initial')
                yield source(f'{name}_negative_a_{"relative" if relative else "absolute"}',
                             'A negative A swaps the bounds of a relative range', text, expected)


def places():
    """The same range in every container, as an operator and as a case item."""
    for name in ('int', 'logic129', 'real'):
        kind = TYPES[name]
        for place in ('task', 'function', 'method', 'fork', 'generate'):
            for relative in (False, True):
                for form in ('expression', 'case'):
                    text, expected = exercise(kind, 40, 3, relative, place, form)
                    yield source(f'{place}_{name}_{form}_{"relative" if relative else "absolute"}',
                                 'A tolerance range does not depend on its container or its form', text, expected,
                                 '11.4.13 11.8.2 12.5.4')


def unknowns():
    """An x or z makes the comparison x; a match elsewhere in the set outweighs it."""
    module = """module top;
logic [7:0] a=8'd40;
logic [7:0] b=8'd3;
logic [7:0] v=8'd40;
logic r;
initial begin
{setup}
r=v inside {set};
$display("%b",r);
end
endmodule
"""
    for name, setup, members, expected in (
            ('needle_x', "v=8'bx;", '{[a +/- b]}', 'x'),
            ('needle_z_bit', "v=8'b0010100z;", '{[a +/- b]}', 'x'),
            ('a_x', "a=8'bx;", '{[a +/- b]}', 'x'),
            ('b_x', "b=8'bx;", '{[a +/- b]}', 'x'),
            ('relative_a_x', "a=8'bx;", '{[a +%- b]}', 'x'),
            # A*B/100.0 is real, and an x converted to real is 0 (6.12.1): the range is [40:40].
            ('relative_b_x', "b=8'bx;", '{[a +%- b]}', '1'),
            ('relative_b_x_other_needle', "b=8'bx; v=8'd41;", '{[a +%- b]}', '0'),
            ('match_outweighs_x', "a=8'bx;", '{[a +/- b], v}', '1'),
            ('known_miss', "v=8'd100;", '{[a +/- b]}', '0')):
        yield source(f'unknown_{name}', 'An x or z in a tolerance range makes the comparison x',
                     module.replace('{setup}', setup).replace('{set}', members), expected, '11.4.13 11.4.6')
    # Bit storage has no x: what a variable stores is what counts.
    yield source('unknown_two_state_storage', 'Two-state storage holds no x for a tolerance range',
                 "module top;\nbit [7:0] a;\nbit [7:0] v=8'd3;\nlogic r;\ninitial begin\na=8'bx;\nr=v inside {[a +/- 3]};\n$display(\"%b\",r);\nend\nendmodule\n",
                 '1', '11.4.13 6.11.2')


def widths():
    """A's type sets the range; the comparison then takes the wider unsigned side."""
    template = """module top;
{a_type} a={a};
int b={b};
{v_type} v;
string result="";
initial begin
{lines}
$display("%s",result);
end
endmodule
"""
    # A signed 32-bit A of -32 with a 15 percent tolerance is [-36:-28] in its own type; an
    # unsigned 33-bit needle zero-extends those bounds.
    a_kind, v_kind = TYPES['int'], Kind('logic [32:0]', 33, False, True)
    for op, relative, b in (('+%-', True, 15), ('+%-', True, -15), ('+/-', False, 4)):
        low, high = bounds(-32, b, relative, a_kind)
        low_u, high_u = low & 0xffffffff, high & 0xffffffff
        points = [low_u - 1, low_u, (low_u + high_u) // 2, high_u, high_u + 1]
        lines = []
        expected = ''
        for point in points:
            lines.append(f"v=33'd{point}; if ((v inside {{[a {op} b]}}) === 1'b1) result={{result,\"1\"}}; else result={{result,\"0\"}};")
            expected += '1' if low_u <= point <= high_u else '0'
        text = (template.replace('{a_type}', 'int').replace('{a}', '-32').replace('{b}', str(b))
                .replace('{v_type}', v_kind.text).replace('{lines}', '\n'.join(lines)))
        yield source(f'wider_unsigned_needle_{"relative" if relative else "absolute"}{"_negative_b" if b < 0 else ""}',
                     'A range in the type of A is then compared at the wider unsigned type', text, expected)
    # A narrow A wraps in its own type before the comparison widens it.
    for op, relative, b in (('+/-', False, 3), ):
        kind = TYPES['logic8']
        low, high = bounds(1, b, relative, kind)
        points = [high - 1, high, high + 1, low, low + 1]
        lines = []
        expected = ''
        for point in points:
            lines.append(f"v=16'd{point}; if ((v inside {{[a {op} b]}}) === 1'b1) result={{result,\"1\"}}; else result={{result,\"0\"}};")
            expected += '1' if low <= point <= high else '0'
        text = (template.replace('{a_type}', 'logic [7:0]').replace('{a}', "8'd1").replace('{b}', str(b))
                .replace('{v_type}', 'logic [15:0]').replace('{lines}', '\n'.join(lines)))
        yield source('narrow_a_wraps_in_its_own_type', 'A range wraps and swaps in the type of A, not of the comparison',
                     text, expected)


def cases():
    yield from forms()
    yield from places()
    yield from unknowns()
    yield from widths()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = dict(cases())
    failed = False
    for name, text in generated.items():
        path = OUT / (name + '.sv')
        if args.check:
            if not path.exists() or path.read_text() != text:
                print(f'out of date: {path.relative_to(OUT.parent.parent.parent)}')
                failed = True
        else:
            path.write_text(text)
    print(f'inside tolerance matrix: {len(generated)} sources')
    return int(failed)


if __name__ == '__main__':
    raise SystemExit(main())
