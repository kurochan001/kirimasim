"""Generates the matrix tests of variables written by functions that
continuous assignments call, of TEST_SUITE.md ("Mechanism matrix"), in
tests/suite/cont/.

  tools/gen_cont_function_write_matrix.py           # writes the files
  tools/gen_cont_function_write_matrix.py --check   # exit 1 if a file differs from what it would write

A write inside a function is a procedural statement, even when a
continuous assignment calls the function: any number of processes may
make such writes to a variable (6.5), and the variable takes the value
written last. It is no continuous assignment to the variable either, so
release after force, and deassign after assign, leave the variable with
its value until the next procedural assignment (10.6.1, 10.6.2;
SCHEDULER_SPEC.md 14.3). What a continuous assignment drives is only its
own left side (SIR_SPEC.md 3.4).

The axes: the caller (assign, a net declaration assignment, a port
connection); the other writers of the variable (none, a second
continuous assignment calling the same function, one calling another
function that writes the inverse, an initial procedure); the target (a
variable, a bit of a vector, an element of an array); what is observed
(the value after each write; release after force and deassign after
assign, on a variable). The values are printed 1ns after each step, so
no two writes are in one time slot; nothing is printed at time 0, where
the continuous assignments run in an order the standard leaves open.

The expected outputs follow from the rules above, computed below.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "cont"
PREFIX = "cont_function_write_"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

# (name, the line of top for the call {C} with the input {I} and the
# number {n}, what the description calls it)
CALLERS = [
    ("assign", ["wire w{n};", "assign w{n} = {C};"], "assign"),
    ("net_decl", ["wire w{n} = {C};"], "a net declaration assignment"),
    ("port", ["child c{n}(.i({C}));"], "a port connection"),
]
# (name, the declaration, the place the functions write, what is printed,
# what the description calls it)
TARGETS = [
    ("var", "logic t = 1'b0;", "t", "t", "a variable"),
    ("bit", "logic [3:0] t = 4'h0;", "t[1]", "t[1]", "a bit of a vector"),
    ("element", "logic t [0:3];", "t[2]", "t[2]", "an element of an array"),
]
# (name, the second writer: None, "f" or "g" for a second continuous
# assignment on b, or "initial"; the steps, each ("a" or "b", value) for an
# input of a continuous assignment, or ("t", value) for initial)
WRITERS = [
    ("alone", None, [("a", 1), ("a", 0), ("a", 1)]),
    ("same_function", "f", [("a", 1), ("a", 0), ("b", 1), ("b", 0)]),
    ("other_function", "g", [("a", 1), ("b", 1), ("a", 0), ("b", 0)]),
    ("initial", "initial", [("a", 1), ("t", 0), ("a", 0), ("t", 1)]),
]
# (name, the statement that holds t, the one that lets it go)
OVERRIDES = [
    ("release", "force t = 1'b1;", "release t;"),
    ("deassign", "assign t = 1'b1;", "deassign t;"),
]


def header(name, description, lrm):
    return [
        "/*",
        f":name: {name}",
        f":description: {description}",
        ":tags: cont function",
        ":type: simulation",
        ":lrm: 1800-2023 " + " ".join(lrm),
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: yes",
        ":nondeterministic: no",
        f":generator: gen_cont_function_write_matrix.py@{VERSION}",
        ":issue: 19",
        ":top_module: top",
        f":expected_stdout: @{name}.expected",
        "*/",
        "// Generated by tools/gen_cont_function_write_matrix.py; change the generator, not "
        "this file.",
        "`timescale 1ns/1ns",
    ]


def design(caller, target, second):
    """The lines of the design before the steps: the functions, the
    continuous assignments and the child of a port connection."""
    _, items, _ = caller
    _, decl, place, _, _ = target
    lines = []
    if caller[0] == "port":
        lines += ["module child(input logic i);", "endmodule"]
    lines += ["module top;", "  logic a = 1'b0;", "  logic b = 1'b0;", f"  {decl}",
              "  function automatic logic f(logic v);", f"    {place} = v;", "    return v;",
              "  endfunction"]
    if second == "g":
        lines += ["  function automatic logic g(logic v);", f"    {place} = ~v;", "    return v;",
                  "  endfunction"]
    lines += ["  " + x.format(n=1, C="f(a)") for x in items]
    if second in ("f", "g"):
        lines += ["  " + x.format(n=2, C=f"{second}(b)") for x in items]
    return lines


def value_case(caller, target, writer):
    wname, second, steps = writer
    name = f"{PREFIX}{caller[0]}_{wname}_{target[0]}"
    lines = design(caller, target, second)
    lines += ["  initial begin"]
    value = None
    out = []
    for k, (what, v) in enumerate(steps):
        if what == "t":
            lines.append(f"    #10 {target[2]} = 1'b{v};")
            value = v
        else:
            lines.append(f"    #10 {what} = 1'b{v};")
            # The continuous assignment on this input calls its function.
            value = (1 - v) if (what == "b" and second == "g") else v
        lines.append(f"    #1 $display(\"step {k + 1}: %b\", {target[3]});")
        out.append(f"step {k + 1}: {value}")
    lines += ["  end", "endmodule"]
    others = {"alone": "alone", "same_function": "with a second continuous assignment calling it",
              "other_function": "with a second continuous assignment calling another function",
              "initial": "with an initial procedure"}[wname]
    description = (f"a function called from {caller[2]} writes {target[4]} procedurally, "
                   f"{others}: the value written last holds")
    lrm = ["6.5", "10.3.2", "13.4"] + (["23.3.3"] if caller[0] == "port" else [])
    return name, header(name, description, lrm) + lines, out


def override_case(caller, writer, override):
    wname, second, _ = writer
    oname, hold, let_go = override
    target = TARGETS[0]
    name = f"{PREFIX}{caller[0]}_{wname}_{oname}"
    lines = design(caller, target, second)
    # t is 1, then 0, then held at 1, let go, and written by the function
    # again: it keeps 1 until then, as no continuous assignment drives it.
    lines += ["  initial begin", "    #10 a = 1'b1;", "    #10 a = 1'b0;",
              "    #1 $display(\"written: %b\", t);", f"    #9 {hold}",
              "    #1 $display(\"held: %b\", t);", f"    #9 {let_go}",
              f"    #1 $display(\"after {oname}: %b\", t);", "    #9 a = 1'b1;",
              "    #10 a = 1'b0;", "    #1 $display(\"written again: %b\", t);", "  end",
              "endmodule"]
    out = ["written: 0", "held: 1", f"after {oname}: 1", "written again: 0"]
    others = "alone" if second is None else "with a second continuous assignment calling it"
    description = (f"a variable a function called from {caller[2]} writes, {others}, keeps its "
                   f"value after {oname}: no continuous assignment drives it")
    lrm = ["6.5", "10.6.1" if oname == "deassign" else "10.6.2", "13.4"]
    return name, header(name, description, lrm) + lines, out


def files():
    cases = [value_case(c, TARGETS[0], w) for c in CALLERS for w in WRITERS]
    cases += [value_case(CALLERS[0], t, w) for t in TARGETS[1:] for w in WRITERS]
    cases += [override_case(c, w, o) for c in CALLERS for w in WRITERS[:2] for o in OVERRIDES]
    out = {}
    for name, text, expected in cases:
        out[f"{name}.sv"] = "\n".join(text) + "\n"
        out[f"{name}.expected"] = "\n".join(expected) + "\n"
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_cont_function_write_matrix: "
                      f"{path.relative_to(OUT.parent.parent.parent)} is out of date; run "
                      "tools/gen_cont_function_write_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
