def array_arguments():
    name = "array_arguments"
    head = header(name, "Fixed-size unpacked array arguments of static and automatic functions "
                  "and tasks: input, output and inout, two dimensions, a row, a pattern, a "
                  "descending actual and a copied input, in several containers",
                  "13.5 13.5.1 7.6 6.22.2 4.9.7")
    head += (
        "module top;\n"
        "  int sa [0:3];\n  int sb [3:0];\n  int out [0:3];\n  int m [0:1][0:2];\n  int s;\n"
        "  function int fsum_s(int a [0:3]);\n    fsum_s = 0;\n"
        "    foreach (a[j]) fsum_s += a[j];\n  endfunction\n"
        "  function automatic int fsum_a(int a [0:3]);\n    return a.sum();\n  endfunction\n"
        "  function automatic void frev(input int a [0:3], output int r [0:3]);\n"
        "    foreach (a[j]) r[3 - j] = a[j];\n  endfunction\n"
        "  function automatic void finc(inout int a [0:3]);\n    foreach (a[j]) a[j]++;\n"
        "  endfunction\n"
        "  function automatic int fmod(int a [0:3]);\n    a[0] = 99;\n    return a[0];\n"
        "  endfunction\n"
        "  function automatic int fsum2(int a [0:1][0:2]);\n    int t = 0;\n"
        "    foreach (a[j, k]) t += a[j][k] * (j + 1);\n    return t;\n  endfunction\n"
        "  function automatic int frow(int r [0:2]);\n    return r[0] * 100 + r[1] * 10 + r[2];\n"
        "  endfunction\n"
        "  task static tsum(input int a [0:3], output int t);\n    t = 0;\n"
        "    foreach (a[j]) t += a[j];\n  endtask\n"
        "  task automatic twait(input int a [0:3], output int r [0:3]);\n"
        "    #1 foreach (a[j]) r[j] = a[j] * 2;\n  endtask\n")

    def locals_decl(pad):
        return f"{pad}automatic int lb [0:3];\n"

    def run(c, pad):
        sv, exp = [], []

        def show(label, fmt, args, values):
            sv.append(f"{pad}$display(\"{c} {label} {fmt}\", {args});")
            exp.append(f"{c} {label} " + " ".join(str(v) for v in values))

        sv.append(f"{pad}sa = '{{1, 2, 3, 4}};\n{pad}lb = '{{10, 20, 30, 40}};")
        show("static function", "%0d", "fsum_s(sa)", [10])
        show("automatic function", "%0d %0d", "fsum_a(sa), fsum_a(lb)", [10, 100])
        show("pattern", "%0d", "fsum_a('{5, 6, 7, 8})", [26])
        sv.append(f"{pad}frev(sa, out);")
        show("output", "%0d %0d %0d %0d", "out[0], out[1], out[2], out[3]", [4, 3, 2, 1])
        sv.append(f"{pad}frev(lb, lb);")
        show("output to the input", "%0d %0d %0d %0d", "lb[0], lb[1], lb[2], lb[3]",
             [40, 30, 20, 10])
        sv.append(f"{pad}finc(sa);")
        show("inout", "%0d %0d %0d %0d", "sa[0], sa[1], sa[2], sa[3]", [2, 3, 4, 5])
        show("copied input", "%0d %0d", "fmod(sa), sa[0]", [99, 2])
        # A descending actual: a[0] is sb[3] (6.22.2).
        sv.append(f"{pad}sb = '{{1, 2, 3, 4}};\n{pad}frev(sb, out);")
        show("descending", "%0d %0d %0d %0d", "out[0], out[1], out[2], out[3]", [4, 3, 2, 1])
        sv.append(f"{pad}m = '{{'{{1, 2, 3}}, '{{4, 5, 6}}}};")
        show("two dimensions", "%0d", "fsum2(m)", [1 + 2 + 3 + 2 * (4 + 5 + 6)])
        show("row", "%0d %0d", "frow(m[1]), frow(m[0])", [456, 123])
        sv.append(f"{pad}tsum(sa, s);")
        show("static task", "%0d", "s", [14])
        sv.append(f"{pad}twait(sa, out);")
        show("task that waits", "%0d %0d %0d %0d", "out[0], out[1], out[2], out[3]",
             [4, 6, 8, 10])
        sv.append(f"{pad}#1;")
        return sv, exp

    return assemble(name, head, run, locals_decl)


