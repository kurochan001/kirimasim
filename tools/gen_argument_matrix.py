def automatic_arrays():
    name = "automatic_arrays"
    head = header(name, "Automatic fixed-size unpacked arrays: default and initializer at each "
                  "entry of their scope, one per call in recursion and in tasks running at the "
                  "same time, and bits of automatic variables and elements, in several "
                  "containers", "6.21 6.8 13.3 13.3.1 7.6")
    head += (
        "module top;\n"
        "  int r1, r2, sum;\n"
        "  function automatic int count(input int k);\n    int a [0:3];\n    a[k] = a[k] + 1;\n"
        "    return a.sum();\n  endfunction\n"
        "  function automatic int first(input int k);\n    int a [0:2] = '{1, 2, 3};\n"
        "    a[0] = a[0] + k;\n    return a[0] * 100 + a[1] * 10 + a[2];\n  endfunction\n"
        "  function automatic int fact(input int n);\n    int keep [0:0];\n    keep[0] = n;\n"
        "    if (n <= 1) return 1;\n    return fact(n - 1) * keep[0];\n  endfunction\n"
        "  function automatic logic [7:0] unknown();\n    logic [7:0] a [0:1];\n"
        "    return a[1];\n  endfunction\n"
        "  task automatic both(input int base, output int r);\n    int a [0:1];\n"
        "    a[0] = base;\n    #1 a[1] = base + 1;\n    r = a[0] + a[1];\n  endtask\n")

    def locals_decl(pad):
        return f"{pad}automatic logic [7:0] v;\n{pad}automatic logic [7:0] e [0:1];\n"

    def run(c, pad):
        sv, exp = [], []

        def show(label, fmt, args, values):
            sv.append(f"{pad}$display(\"{c} {label} {fmt}\", {args});")
            exp.append(f"{c} {label} " + " ".join(str(v) for v in values))

        show("default each call", "%0d %0d %0d", "count(0), count(0), count(3)", [1, 1, 1])
        show("initializer each call", "%0d %0d", "first(1), first(5)", [223, 623])
        show("default x", "%b", "unknown()", ["xxxxxxxx"])
        show("recursion", "%0d", "fact(5)", [120])
        sv.append(f"{pad}sum = 0;\n{pad}for (int j = 0; j < 3; j++) begin\n"
                  f"{pad}  automatic int t [0:1];\n{pad}  t[0] = t[0] + j;\n"
                  f"{pad}  sum += t[0];\n{pad}end")
        show("each iteration", "%0d", "sum", [3])
        sv.append(f"{pad}v = 8'h00;\n{pad}v[3:0] = 4'hf;\n{pad}v[7] = 1'b1;")
        show("bits", "%h", "v", ["8f"])
        sv.append(f"{pad}e[0] = 8'h00;\n{pad}e[1] = 8'h00;\n{pad}e[1][2:0] = 3'b101;\n"
                  f"{pad}e[0][7:6] = 2'b11;")
        show("element bits", "%h %h", "e[0], e[1]", ["c0", "05"])
        sv.append(f"{pad}fork\n{pad}  both(10, r1);\n{pad}  both(20, r2);\n{pad}join")
        show("tasks at the same time", "%0d %0d", "r1, r2", [21, 41])
        sv.append(f"{pad}#1;")
        return sv, exp

    return assemble(name, head, run, locals_decl)


def files():
    out = {}
    for f in (ref_arguments(), array_arguments(), automatic_arrays()):
        out.update(f)
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_argument_matrix: {path.relative_to(OUT.parent.parent.parent)} is out "
                      "of date; run tools/gen_argument_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
