#!/usr/bin/env python3
"""Generates the argument matrix tests of TEST_SUITE.md ("機構の行列") in
tests/suite/proc/: ref arguments, fixed-size unpacked array arguments and
automatic arrays.

  tools/gen_argument_matrix.py           # writes the files
  tools/gen_argument_matrix.py --check   # exit 1 if a file differs from what it would write

ref arguments (13.5.2, SIR_SPEC.md 8): the actual is a static variable,
an automatic variable of the caller, an element of a static array chosen
by a constant or a run-time index, an element of an automatic array, a
member of an unpacked structure, an array (ascending and descending, its
elements matched from the left bound), an automatic array, a ref argument
passed on, and an element of an array ref argument passed on; the callee
reads, writes, adds to, writes bits of, fills and sums what it refers to;
a task writes through a ref across waits, seen at once by another
process; const ref only reads.

Array arguments (13.5, 7.6, SIR_SPEC.md 8): static and automatic
functions and tasks with input, output and inout arrays, two-dimensional
arrays and a row of one, a pattern as the actual, a descending actual,
and an input changed in the callee, which the caller does not see.

Automatic arrays (6.21, 13.3, SIR_SPEC.md 7.4): their default and their
initializer each time the scope is entered (each call, each loop
iteration), one array per call in recursion and in tasks that run at
the same time, and bits of automatic variables and elements.

Each runs in several containers (an initial procedure, a static task, an
always procedure and a branch of a fork). The expected outputs follow
from the rules above, worked out below without reading kirimasim's code.
A person checks them once for all the tests made from them
(TEST_SUITE.md, "人の抜き取り").
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "proc"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

CONTAINERS = ["initial", "task", "always", "fork"]


def header(name, description, lrm):
    return (f"/*\n:name: {name}\n:description: {description}\n:tags: proc\n:type: simulation\n"
            f":lrm: 1800-2023 {lrm}\n:oracle: spec\n:spec_check: ai\n:fourstate: no\n"
            f":nondeterministic: no\n:generator: gen_argument_matrix.py@{VERSION}\n"
            f":expected_stdout: @{name}.expected\n*/\n"
            "// Generated by tools/gen_argument_matrix.py; change the generator, not this file.\n")


def assemble(name, sv_head, run, locals_decl):
    """The module: run(container, pad) gives (statements, expected lines)
    for one container, which runs them in its own time window."""
    sv = sv_head + "  logic go = 1'b0;\n"
    exp = []
    body, e = run("initial", "      ")
    exp += e
    steps = sum(1 for line in body if "#1" in line) + 2
    sv += ("  initial begin\n    begin\n" + locals_decl("      ") + "\n".join(body) +
           "\n    end\n")
    sv += f"    run();\n    go = 1'b1;\n    #{steps};\n    fork\n      begin\n"
    fork_body, fork_exp = run("fork", "        ")
    sv += locals_decl("        ") + "\n".join(fork_body) + "\n      end\n    join\n  end\n"
    task_body, task_exp = run("task", "    ")
    sv += "  task static run();\n" + locals_decl("    ") + "\n".join(task_body) + "\n  endtask\n"
    always_body, always_exp = run("always", "    ")
    sv += ("  always @(posedge go) begin\n" + locals_decl("    ") + "\n".join(always_body) +
           "\n  end\nendmodule\n")
    exp += task_exp + always_exp + fork_exp
    return {f"{name}.sv": sv, f"{name}.expected": "\n".join(exp) + "\n"}


# --- ref arguments ---------------------------------------------------------------------

def ref_arguments():
    name = "ref_arguments"
    head = header(name, "ref and const ref arguments to variables, elements, members and arrays "
                  "of static and automatic variables, read, written, passed on and written "
                  "across waits, in several containers", "13.5.2 7.6 6.22.2 9.3.2")
    head += (
        "module top;\n"
        "  typedef struct { int a; int b; } pair_t;\n"
        "  int s, i;\n  int sa [0:3];\n  int sb [3:0];\n  pair_t ps;\n  logic [7:0] bv;\n"
        "  function automatic void add(ref int v, input int k);\n    v = v + k;\n  endfunction\n"
        "  function automatic int get(const ref int v);\n    return v;\n  endfunction\n"
        "  function automatic void setbits(ref logic [7:0] v);\n    v[3:0] = 4'ha;\n"
        "  endfunction\n"
        "  function automatic void fill(ref int v [0:3], input int k);\n"
        "    foreach (v[j]) v[j] = k + j;\n  endfunction\n"
        "  function automatic int total(const ref int v [0:3]);\n    return v.sum();\n"
        "  endfunction\n"
        "  function automatic void pass_on(ref int v, input int k);\n    add(v, k);\n"
        "  endfunction\n"
        "  function automatic void pass_elem(ref int v [0:3], input int j, input int k);\n"
        "    add(v[j], k);\n  endfunction\n"
        "  task automatic slow(ref int v);\n    #1 v = v + 1;\n    #1 v = v + 1;\n  endtask\n")

    def locals_decl(pad):
        return f"{pad}automatic int la;\n{pad}automatic int lb [0:3];\n"

    def run(c, pad):
        sv, exp = [], []

        def show(label, fmt, args, values):
            sv.append(f"{pad}$display(\"{c} {label} {fmt}\", {args});")
            exp.append(f"{c} {label} " + " ".join(str(v) for v in values))

        sv.append(f"{pad}s = 10;\n{pad}add(s, 5);")
        show("static", "%0d", "s", [15])
        sv.append(f"{pad}la = 20;\n{pad}add(la, 7);")
        show("automatic", "%0d", "la", [27])
        sv.append(f"{pad}sa = '{{1, 2, 3, 4}};\n{pad}add(sa[2], 10);")
        show("element", "%0d %0d %0d %0d", "sa[0], sa[1], sa[2], sa[3]", [1, 2, 13, 4])
        sv.append(f"{pad}i = 1;\n{pad}add(sa[i], 100);")
        show("element at run time", "%0d", "sa[1]", [102])
        sv.append(f"{pad}lb = '{{5, 6, 7, 8}};\n{pad}add(lb[3], 1);")
        show("automatic element", "%0d %0d", "lb[2], lb[3]", [7, 9])
        sv.append(f"{pad}ps.b = 4;\n{pad}add(ps.b, 3);")
        show("member", "%0d", "ps.b", [7])
        show("const", "%0d %0d", "get(s), get(lb[3])", [15, 9])
        sv.append(f"{pad}bv = 8'h55;\n{pad}setbits(bv);")
        show("bits", "%h", "bv", ["5a"])
        sv.append(f"{pad}fill(sa, 10);")
        show("array", "%0d %0d %0d %0d %0d", "sa[0], sa[1], sa[2], sa[3], total(sa)",
             [10, 11, 12, 13, 46])
        # A descending array: v[0] is sb[3], the left bound (6.22.2).
        sv.append(f"{pad}fill(sb, 20);")
        show("descending array", "%0d %0d %0d %0d", "sb[3], sb[2], sb[1], sb[0]", [20, 21, 22, 23])
        sv.append(f"{pad}fill(lb, 30);")
        show("automatic array", "%0d %0d", "lb[0], total(lb)", [30, 126])
        sv.append(f"{pad}pass_on(s, 2);\n{pad}pass_elem(sa, 1, 5);\n{pad}pass_elem(sb, 0, 5);")
        show("passed on", "%0d %0d %0d", "s, sa[1], sb[3]", [17, 16, 25])
        # The task writes through the ref at time 1 and 2; the other branch
        # reads after the Active region of time 1.
        sv.append(f"{pad}fork\n{pad}  slow(s);\n{pad}  begin\n{pad}    #1;\n{pad}    #0;\n"
                  f"{pad}    $display(\"{c} during %0d\", s);\n{pad}  end\n{pad}join")
        exp.append(f"{c} during 18")
        show("after", "%0d", "s", [19])
        sv.append(f"{pad}#1;")
        return sv, exp

    return assemble(name, head, run, locals_decl)


