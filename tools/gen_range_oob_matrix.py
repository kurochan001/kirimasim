"""Generates the matrix tests of constant part-selects that reach outside
their vector (TEST_SUITE.md, "Mechanism matrix") in tests/suite/values/.

  tools/gen_range_oob_matrix.py           # writes the files
  tools/gen_range_oob_matrix.py --check   # exit 1 if a file differs from what it would write

The rule: 11.5.1 of the standard, CLI.md 2.1. A part-select whose
range is partly or wholly outside the vector is allowed. Read, the bits
outside are x for a 4-state vector and 0 for a 2-state one; written, the
bits inside take their values and the bits outside are dropped. slang
reports such a select with a constant range (range-oob), which kirimasim
makes a warning by default, as it does index-oob.

The axes: how far the range reaches (above the vector, below it, wholly
outside), the form of the select (a range, an indexed part), the vector
(4-state, 2-state, bounds that do not start at 0, bounds that rise), the
use (read, written), and the container (an initial procedure, a
function).

The expected output and warnings are computed here from the vectors,
without reading kirimasim's code. A person checks them once for all the
tests made from them (TEST_SUITE.md, "Sampling by people"). For
reference, checked 2026-11-12: Icarus 14.0 devel prints the same values
for the 4-state vectors, and x where the standard gives 0 for the bits
outside a 2-state vector.
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "values"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

# The vectors: name, type as slang names it, left and right bound, 4-state, value (bits from the left).
VECTORS = {
    "v": ("logic[3:0]", 3, 0, True, "1010"),
    "b": ("bit[3:0]", 3, 0, False, "1010"),
    "h": ("logic[7:4]", 7, 4, True, "0110"),
    "a": ("logic[0:3]", 0, 3, True, "1010"),
}
# The reads: label, vector, the select as written, the range it names (left, right).
READS = [
    ("above", "v", "5:2", (5, 2)),
    ("outside", "v", "5:4", (5, 4)),
    ("below", "v", "1:-1", (1, -1)),
    ("two_state", "b", "5:2", (5, 2)),
    ("offset_bounds", "h", "5:2", (5, 2)),
    ("rising_bounds", "a", "2:5", (2, 5)),
    ("indexed_outside", "v", "4 +: 2", (5, 4)),
    ("indexed_above", "v", "2 +: 3", (4, 2)),
]
# The writes to w, a logic [3:0] of zeros: label, the select, its range, the value written (bits).
WRITES = [
    ("write_above", "5:2", (5, 2), "1111"),
    ("write_outside", "7:6", (7, 6), "11"),
    ("write_below", "1:-2", (1, -2), "1111"),
]
CONTAINERS = ["initial", "function"]


def positions(left, right):
    step = 1 if right >= left else -1
    return list(range(left, right + step, step))


def read_bits(vector, rng):
    _, left, right, four, value = VECTORS[vector]
    held = dict(zip(positions(left, right), value))
    return "".join(held.get(p, "x" if four else "0") for p in positions(*rng))


def write_bits(rng, value):
    held = dict(zip(positions(3, 0), "0000"))
    for p, bit in zip(positions(*rng), value):
        if p in held:
            held[p] = bit
    return "".join(held[p] for p in positions(3, 0))


def test(container):
    name = f"range_oob_{container}"
    sv = ["/*", f":name: {name}",
          ":description: a constant part-select that reaches outside its vector reads x (0 for "
          "a 2-state vector) for the bits outside and writes only the bits inside, with a "
          f"warning, in {'an' if container == 'initial' else 'a'} {container}",
          ":tags: values", ":type: simulation", ":lrm: 1800-2023 11.5.1", ":oracle: spec",
          ":spec_check: ai", ":fourstate: yes", ":nondeterministic: no",
          f":generator: gen_range_oob_matrix.py@{VERSION}", ":top_module: top",
          f":expected_stdout: @{name}.expected", f":expected_stderr: @{name}.stderr", "*/",
          "// Generated by tools/gen_range_oob_matrix.py; change the generator, not this file.",
          "`timescale 1ns/1ns", "module top;",
          "  logic [3:0] v = 4'b1010;", "  bit [3:0] b = 4'b1010;", "  logic [7:4] h = 4'b0110;",
          "  logic [0:3] a = 4'b1010;", "  logic [3:0] w;"]
    indent = "    "
    sv += ["  function void run();"] if container == "function" else ["  initial begin"]
    expected, warnings = [], []

    def warn(line_text, select, rng, vector_type):
        column = line_text.index(select) + 1
        warnings.append(f"{name}.sv:{len(sv)}:{column}: warning: cannot select range of "
                        f"[{rng[0]}:{rng[1]}] from '{vector_type}' [-Wrange-oob]")

    for label, vector, select, rng in READS:
        text = f'{indent}$display("{label}: %b", {vector}[{select}]);'
        sv.append(text)
        warn(text, f"{select}]", rng, VECTORS[vector][0])
        expected.append(f"{label}: {read_bits(vector, rng)}")
    for label, select, rng, value in WRITES:
        sv.append(f"{indent}w = 4'b0000;")
        text = f"{indent}w[{select}] = {len(value)}'b{value};"
        sv.append(text)
        warn(text, f"{select}]", rng, "logic[3:0]")
        sv.append(f'{indent}$display("{label}: %b", w);')
        expected.append(f"{label}: {write_bits(rng, value)}")
    sv += ["  endfunction", "  initial run();"] if container == "function" else ["  end"]
    sv += ["endmodule"]
    return name, sv, expected, warnings


def files():
    out = {}
    for container in CONTAINERS:
        name, sv, expected, warnings = test(container)
        out[f"{name}.sv"] = "\n".join(sv) + "\n"
        out[f"{name}.expected"] = "\n".join(expected) + "\n"
        out[f"{name}.stderr"] = "\n".join(warnings) + "\n"
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_range_oob_matrix: {path.relative_to(OUT.parent.parent.parent)} is "
                      "out of date; run tools/gen_range_oob_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
