#!/usr/bin/env python3
"""Generates the built-in gate matrix tests of TEST_SUITE.md ("Mechanism matrix",
"4-state matrix") in tests/suite/nets/.

  tools/gen_gate_matrix.py           # writes the files
  tools/gen_gate_matrix.py --check   # exit 1 if a file differs from what it would write

The axes: every logic gate (and, nand, or, nor, xor, xnor) with two and
three inputs, and buf and not with two outputs, on every combination of 0,
1, x and z; every three-state gate (bufif0, bufif1, notif0, notif1) on
every combination of data and control, alone on its net and against a
second driver of each driving strength and value, where its L and H
resolve as x with one side (VALUE_SEMANTICS.md 5.8); pullup and pulldown
alone, against drivers of each strength, and with a strength given; gates
with drive strengths; and the containers of a gate: a module body, a
generate block, a child module, and arrays of gates whose connections
slang slices (28.3.6), one of them on a vector net that resolves bit by
bit.

The expected outputs follow from the rules of VALUE_SEMANTICS.md 5.8 and
5.4, written again below without reading kirimasim's code (the resolution
rule is the one of gen_resolution_matrix.py). A person checks the rules
against the standard once for all the tests made from them (TEST_SUITE.md,
"Sampling by people").
"""

import argparse
import itertools
import sys
from pathlib import Path

from gen_resolution_matrix import STRENGTHS, resolve, value_of

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "nets"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

VALUES = ["0", "1", "x", "z"]
DRIVING = [7, 6, 5, 3]


# --- The rules of VALUE_SEMANTICS.md 5.8 ------------------------------------------

def known(v):
    """An input z reads as x (28.4, 28.5)."""
    return "x" if v == "z" else v


def and2(a, b):
    a, b = known(a), known(b)
    if "0" in (a, b):
        return "0"
    return "1" if a == b == "1" else "x"


def or2(a, b):
    a, b = known(a), known(b)
    if "1" in (a, b):
        return "1"
    return "0" if a == b == "0" else "x"


def xor2(a, b):
    a, b = known(a), known(b)
    if "x" in (a, b):
        return "x"
    return "1" if a != b else "0"


def inv(v):
    return {"0": "1", "1": "0"}.get(v, "x")


LOGIC = {
    "and": (and2, False), "nand": (and2, True), "or": (or2, False),
    "nor": (or2, True), "xor": (xor2, False), "xnor": (xor2, True),
}


def logic_gate(kind, inputs):
    """28.4: the operator over the inputs in order, inverted for nand, nor
    and xnor."""
    op, negated = LOGIC[kind]
    v = known(inputs[0])
    for x in inputs[1:]:
        v = op(v, x)
    return inv(v) if negated else v


def tri_gate(kind, data, ctrl):
    """28.6, table 28-5: the data when the control enables, z when it
    disables; when the control is x or z, L for a 0 and H for a 1, x for
    an x."""
    d = inv(data) if kind.startswith("not") else known(data)
    on = "1" if kind.endswith("1") else "0"
    if ctrl == on:
        return d
    if ctrl in ("0", "1"):
        return "z"
    return {"0": "L", "1": "H"}.get(d, "x")


# resolve() takes (value, s1, s0) drivers; one with an L or H value is
# given as the x of the strengths that the range keeps.
def driver(v, s1, s0):
    if v == "L":
        return ("x", 0, s0)
    if v == "H":
        return ("x", s1, 0)
    return (v, s1, s0)


def resolved(drivers, kind="wire"):
    return value_of(resolve(kind, [driver(*d) for d in drivers]))


def shown(v):
    """%b of a net: L and H read as x (5.2)."""
    return "x" if v in ("L", "H") else v


# --- The tests ---------------------------------------------------------------------

def header(name, description, lrm, note=""):
    return (f"/*\n:name: {name}\n:description: {description}\n:tags: nets\n:type: simulation\n"
            f":lrm: 1800-2023 {lrm}\n:oracle: spec iverilog@13.0\n:spec_check: ai\n"
            f":fourstate: yes\n:nondeterministic: no\n:generator: gen_gate_matrix.py@{VERSION}\n"
            f":expected_stdout: @{name}.expected\n*/\n"
            "// Generated by tools/gen_gate_matrix.py; change the generator, not this file.\n"
            + note)


def strength_spec(s1, s0):
    return f"({STRENGTHS[s1]}1, {STRENGTHS[s0]}0)"


def logic_gates():
    """Every logic gate with two and three inputs, buf and not with two
    outputs, on every combination of 0, 1, x and z."""
    name = "gate_logic"
    sv = header(name, "Every logic gate with two and three inputs and buf and not with two "
                "outputs, on every combination of 0, 1, x and z", "28.4 28.5")
    sv += "module top;\n  logic a, b, c;\n"
    for k in LOGIC:
        sv += f"  wire {k}2, {k}3;\n  {k} ({k}2, a, b);\n  {k} g_{k}3 ({k}3, a, b, c);\n"
    sv += "  wire buf_o1, buf_o2, not_o1, not_o2;\n"
    sv += "  buf (buf_o1, buf_o2, a);\n  not n1 (not_o1, not_o2, a);\n"
    sv += "  initial begin\n"
    exp = ""
    two = " ".join(f"{k}=%b" for k in LOGIC)
    two_args = ", ".join(f"{k}2" for k in LOGIC)
    for a, b in itertools.product(VALUES, VALUES):
        sv += (f"    a = 1'b{a}; b = 1'b{b};\n"
               f"    #1 $display(\"{a}{b} {two}\", {two_args});\n")
        exp += f"{a}{b} " + " ".join(f"{k}={logic_gate(k, [a, b])}" for k in LOGIC) + "\n"
    three_args = ", ".join(f"{k}3" for k in LOGIC)
    for a, b, c in itertools.product(VALUES, VALUES, VALUES):
        sv += (f"    a = 1'b{a}; b = 1'b{b}; c = 1'b{c};\n"
               f"    #1 $display(\"{a}{b}{c} {two}\", {three_args});\n")
        exp += f"{a}{b}{c} " + " ".join(f"{k}={logic_gate(k, [a, b, c])}" for k in LOGIC) + "\n"
    for a in VALUES:
        sv += (f"    a = 1'b{a};\n"
               f"    #1 $display(\"{a} buf=%b%b not=%b%b\", buf_o1, buf_o2, not_o1, not_o2);\n")
        bv, nv = known(a), inv(a)
        exp += f"{a} buf={bv}{bv} not={nv}{nv}\n"
    sv += "  end\nendmodule\n"
    return name, sv, exp


TRI = ["bufif0", "bufif1", "notif0", "notif1"]
# The second driver of a three-state gate's net: (strength, value).
OTHERS = [(6, "1"), (6, "0"), (5, "1"), (5, "0"), (3, "1"), (3, "0"), (6, "z")]


def tri_gates():
    """Every three-state gate on every combination of data and control,
    alone and against a second driver of each strength and value."""
    name = "gate_tristate"
    sv = header(name, "Every three-state gate on every combination of data and control, alone "
                "and against a second driver of each strength and value, where L and H resolve "
                "as x with one side", "28.6 28.11 28.12.2 28.12.3")
    sv += "module top;\n  logic d, c;\n"
    nets = []
    for k in TRI:
        sv += f"  wire {k}_alone;\n  {k} ({k}_alone, d, c);\n"
        nets.append(f"{k}_alone")
        for i, (s, v) in enumerate(OTHERS):
            n = f"{k}_r{i}"
            sv += (f"  wire {n};\n  {k} ({n}, d, c);\n"
                   f"  assign {strength_spec(s, s)} {n} = 1'b{v};\n")
            nets.append(n)
    sv += "  initial begin\n"
    exp = ""
    for k in TRI:
        labels = " ".join(["alone=%b"] + [f"{STRENGTHS[s][:2]}{v}=%b" for s, v in OTHERS])
        args = ", ".join([f"{k}_alone"] + [f"{k}_r{i}" for i in range(len(OTHERS))])
        for d, c in itertools.product(VALUES, VALUES):
            g = tri_gate(k, d, c)
            sv += (f"    d = 1'b{d}; c = 1'b{c};\n"
                   f"    #1 $display(\"{k} {d}{c} {labels}\", {args});\n")
            exp += (f"{k} {d}{c} alone={shown(g)} " +
                    " ".join(f"{STRENGTHS[s][:2]}{v}={resolved([(g, 6, 6), (v, s, s)])}"
                             for s, v in OTHERS) + "\n")
    sv += "  end\nendmodule\n"
    return name, sv, exp


def pulls():
    """pullup and pulldown alone, against a driver of each strength, with
    a strength given; and gates with drive strengths."""
    name = "gate_pulls_strengths"
    sv = header(name, "pullup and pulldown alone, against a driver of each strength and value "
                "and with a strength given; logic and three-state gates with drive strengths "
                "against other drivers", "28.3.2 28.10 28.11 28.12.1 28.12.2")
    sv += "module top;\n  logic a, b;\n  wire up, down;\n  pullup (up);\n  pulldown (down);\n"
    nets = []  # (name, drivers from a and b as a function)
    for s in DRIVING:
        for k, pv in (("pullup", "1"), ("pulldown", "0")):
            n = f"{k}_{STRENGTHS[s]}"
            sv += f"  wire {n};\n  {k} ({n});\n  assign {strength_spec(s, s)} {n} = a;\n"
            nets.append((n, lambda a, b, pv=pv, s=s: resolved([(pv, 5, 5), (a, s, s)])))
    # Pulls with a strength given; the other side's strength is ignored
    # (28.10).
    sv += ("  wire up_supply, down_weak;\n  pullup (supply1) (up_supply);\n"
           "  assign up_supply = a;\n  pulldown (weak0) (down_weak);\n"
           "  assign (weak1, weak0) down_weak = a;\n")
    nets.append(("up_supply", lambda a, b: resolved([("1", 7, 7), (a, 6, 6)])))
    nets.append(("down_weak", lambda a, b: resolved([("0", 3, 3), (a, 3, 3)])))
    # Gates with drive strengths against a strong or pull driver.
    sv += ("  wire and_weak, or_pull, buf_mixed, bufif_weak;\n"
           "  and (weak1, weak0) (and_weak, a, b);\n  assign (pull1, pull0) and_weak = b;\n"
           "  or (pull1, pull0) (or_pull, a, b);\n  assign (weak1, weak0) or_pull = 1'b0;\n"
           "  buf (strong1, weak0) (buf_mixed, a);\n  assign (pull1, pull0) buf_mixed = b;\n"
           "  bufif1 (weak1, weak0) (bufif_weak, a, b);\n  assign (weak1, weak0) bufif_weak = 1'b1;\n")
    nets.append(("and_weak", lambda a, b: resolved([(logic_gate("and", [a, b]), 3, 3),
                                                     (b, 5, 5)])))
    nets.append(("or_pull", lambda a, b: resolved([(logic_gate("or", [a, b]), 5, 5),
                                                    ("0", 3, 3)])))
    nets.append(("buf_mixed", lambda a, b: resolved([(known(a), 6, 3), (b, 5, 5)])))
    nets.append(("bufif_weak", lambda a, b: resolved([(tri_gate("bufif1", a, b), 3, 3),
                                                      ("1", 3, 3)])))
    sv += "  initial begin\n"
    labels = " ".join(["up=%b down=%b"] + [f"{n}=%b" for n, _ in nets])
    args = ", ".join(["up", "down"] + [n for n, _ in nets])
    exp = ""
    for a, b in itertools.product(VALUES, VALUES):
        sv += f"    a = 1'b{a}; b = 1'b{b};\n    #1 $display(\"{a}{b} {labels}\", {args});\n"
        exp += f"{a}{b} up=1 down=0 " + " ".join(f"{n}={f(a, b)}" for n, f in nets) + "\n"
    sv += "  end\nendmodule\n"
    return name, sv, exp


def containers():
    """A gate in a module body, a generate block, a child module, and
    arrays of gates with sliced and shared connections, one of them on a
    vector net that resolves bit by bit."""
    name = "gate_containers"
    sv = header(name, "Gates in a module body, a generate block and a child module, and arrays "
                "of gates whose connections are sliced or shared, one on a vector net with "
                "another driver", "28.3.5 28.3.6 28.4 28.6 27.5 23.3.3.5")
    sv += ("module child(output o, input a, b);\n  nand (o, a, b);\nendmodule\n"
           "module top;\n  logic [3:0] a;\n  logic b, en;\n"
           "  wire body, from_child;\n  wire [3:0] arr, bus;\n  wire [1:0] tri_arr;\n"
           "  xor (body, a[0], b);\n"
           "  generate\n    if (1) begin : gen\n      wire o;\n      or (o, a[1], b);\n"
           "    end\n  endgenerate\n"
           "  child u (from_child, a[2], b);\n"
           "  and g [3:0] (arr, a, b);\n"
           "  bufif1 t [0:1] (tri_arr, a[1:0], en);\n"
           "  bufif0 bb [3:0] (bus, a, en);\n"
           "  assign (pull1, pull0) bus = 4'b1010;\n"
           "  initial begin\n")
    exp = ""
    for av, bv, ev in [("0110", "1", "0"), ("1001", "1", "1"), ("1x0z", "0", "x"),
                       ("z1x0", "1", "z"), ("1111", "x", "0")]:
        sv += (f"    a = 4'b{av}; b = 1'b{bv}; en = 1'b{ev};\n"
               "    #1 $display(\"%b %b %b body=%b gen=%b child=%b arr=%b tri=%b bus=%b\", "
               "a, b, en, body, gen.o, from_child, arr, tri_arr, bus);\n")
        bits = list(reversed(av))  # bits[i] is a[i]
        body = logic_gate("xor", [bits[0], bv])
        gen = logic_gate("or", [bits[1], bv])
        child = logic_gate("nand", [bits[2], bv])
        arr = "".join(logic_gate("and", [bits[i], bv]) for i in reversed(range(4)))
        tri = "".join(shown(tri_gate("bufif1", bits[i], ev)) for i in reversed(range(2)))
        pull = "1010"[::-1]  # pull[i] is the pull driver's bit i
        bus = "".join(resolved([(tri_gate("bufif0", bits[i], ev), 6, 6), (pull[i], 5, 5)])
                      for i in reversed(range(4)))
        exp += f"{av} {bv} {ev} body={body} gen={gen} child={child} arr={arr} tri={tri} bus={bus}\n"
    sv += "  end\nendmodule\n"
    return name, sv, exp


def files():
    out = {}
    for name, sv, exp in [logic_gates(), tri_gates(), pulls(), containers()]:
        out[f"{name}.sv"] = sv
        out[f"{name}.expected"] = exp
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_gate_matrix: {path.relative_to(OUT.parent.parent.parent)} is out of "
                      "date; run tools/gen_gate_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
