#!/usr/bin/env python3
"""Generates the matrix test of what a wait's expression depends on, of
TEST_SUITE.md ("Mechanism matrix"), in tests/suite/sched/.

  tools/gen_watch_reads_matrix.py           # writes the files
  tools/gen_watch_reads_matrix.py --check   # exit 1 if a file differs from what it would write

A wait on an expression is evaluated again when a variable it reads
changes, and wakes when its value changes, or, for wait, becomes true
(9.4.2, 9.4.3, SCHEDULER_SPEC.md 9.5); $monitor shows its arguments again
when one of them changes (21.2.3). A static variable of a function, read
by a hierarchical name (13.3.1, 23.6), is such a variable. The variables
of a function that the expression itself calls are left out: the call
sets them again (SCHEDULER_SPEC.md 9.5).

A function called from another wait's expression may write such a
variable, or trigger an event, while the scheduler is still announcing
the change that made it run; the change is announced once that is done
(RUNTIME_ABI.md 5), in the same time slot.

The axes: how the waiter reads the function's variable (an event control
on an expression of it, wait on a condition, an event control on the
variable itself, $monitor); what writes it (a process that calls the
function, another wait's expression that calls it when its own operand
changes); and an event triggered by a function in a wait's expression,
when the value it is given is not 0, whose value stays 0, so that the
wait goes on waiting while the event's waiter wakes.
Each case has its own function and time.

The expected outputs follow from the rules above, computed below. A
person checks them once for all the tests made from them (TEST_SUITE.md,
"Sampling by people").
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "sched"
NAME = "watch_reads_matrix"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

WAITERS = {
    "event_expression": "@(~top.f{k}.t);",
    "wait_condition": "wait (top.f{k}.t == {t});",
    "event_variable": "@(top.f{k}.t);",
}
WRITERS = ["process_call", "watch_call"]


def files():
    lines = [
        "/*",
        f":name: {NAME}",
        ":description: a wait on an expression, a wait on a condition, an event control and "
        "$monitor that read a function's static variable by a hierarchical name wake when a "
        "process, or another wait's expression, calls the function and changes it; a trigger "
        "made by a function in a wait's expression wakes the event's waiter",
        ":tags: sched waits",
        ":type: simulation",
        ":lrm: 1800-2023 9.4.2 9.4.3 13.3.1 21.2.3 23.6",
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: no",
        ":nondeterministic: no",
        # A wait that came to depend on its own trigger would loop.
        ":timeout: 60",
        f":generator: gen_watch_reads_matrix.py@{VERSION}",
        ":top_module: top",
        f":expected_stdout: @{NAME}.expected",
        "*/",
        "// Generated by tools/gen_watch_reads_matrix.py; change the generator, not this file.",
        "`timescale 1ns/1ns",
        "module top;",
    ]
    out = []
    k = 0
    for waiter, wait in WAITERS.items():
        for writer in WRITERS:
            t = 10 * (k + 1)
            tag = f"case {k} {waiter} {writer}"
            lines += [f"  // {tag}",
                      f"  int r{k}, a{k} = 0;",
                      f"  function int f{k}(int x);",
                      "    int t;",
                      "    t = x;",
                      "    return x;",
                      "  endfunction",
                      "  initial begin",
                      "    " + wait.format(k=k, t=t),
                      f'    $display("%0t {tag} woke", $time);',
                      "  end"]
            if writer == "process_call":
                lines.append(f"  initial #{t} r{k} = f{k}({t});")
            else:
                lines += [f"  initial @(f{k}(a{k})) r{k} = a{k};",
                          f"  initial #{t} a{k} = {t};"]
            out.append(f"{t} {tag} woke")
            k += 1
    # An event triggered by a function in a wait's expression.
    t = 10 * (k + 1)
    tag = f"case {k} trigger watch_call"
    lines += [f"  // {tag}",
              f"  int b{k} = 0;",
              f"  event e{k};",
              f"  function int g{k}(int x);",
              # Not when the wait first evaluates it at time 0, whose order
              # against the waiter of the event is not set (9.3.2).
              f"    if (x != 0) -> e{k};",
              # The value never changes, so the wait stays; were it to wait
              # on the event it triggers, it would trigger it again and
              # again.
              "    return 0;",
              "  endfunction",
              f"  initial begin @(g{k}(b{k})); end",
              f'  initial begin @(e{k}); $display("%0t {tag} woke", $time); end',
              f"  initial #{t} b{k} = 1;"]
    out.append(f"{t} {tag} woke")
    k += 1
    # $monitor, which shows its arguments at time 0 and after a change.
    t = 10 * (k + 1)
    lines += [f"  // case {k} monitor process_call",
              f"  int r{k};",
              f"  function int f{k}(int x);",
              "    int t;",
              "    t = x;",
              "    return x;",
              "  endfunction",
              f'  initial $monitor("%0t case {k} monitor process_call %0d", $time, top.f{k}.t);',
              f"  initial #{t} r{k} = f{k}({t});"]
    out.insert(0, f"0 case {k} monitor process_call 0")
    out.append(f"{t} case {k} monitor process_call {t}")
    lines += ["endmodule", ""]
    return {f"{NAME}.sv": "\n".join(lines), f"{NAME}.expected": "\n".join(out) + "\n"}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_watch_reads_matrix: {path.relative_to(OUT.parent.parent.parent)} is "
                      "out of date; run tools/gen_watch_reads_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
