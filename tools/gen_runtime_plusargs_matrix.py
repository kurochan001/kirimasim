"""Generate runtime value-plusargs formats (21.6, SYSTEM_TASKS.md 9).

Axes: string, packed, function, array element, conditional; ten procedure
and storage contexts; radix, wide X/Z, empty/bad/missing values, real and
string outputs, duplicate matches, same-callsite format changes and
copyback indices. Expected values are derived here from the written inputs,
independently of the implementation.
"""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "tests" / "suite" / "proc"
VERSION = 1
KINDS = ("string", "packed", "function", "array", "conditional")
CONTAINERS = ("initial", "always", "final", "static_task", "automatic", "function", "ref",
              "fork", "generate", "interface")
HEX = "1z23456789abcdef0123456789abcdef01"
WIDE = "".join("zzzz" if c == "z" else format(int(c, 16), "04b") for c in HEX)[-129:]
ARGS = ("+num=42 +num=99 +bin=10xz +neg=-17 +wide=" + HEX +
        " +empty= +bad=12q +text=hello +real=1.25 +exp=2.5e1")
# tag, format, target, display format, displayed expression, count, value
CASES = [
    ("decimal", "num=%d", "a", "%0d", "a", 1, "42"),
    ("hex", "num=%h", "a", "%0d", "a", 1, str(int("42", 16))),
    ("octal", "num=%o", "a", "%0d", "a", 1, str(int("42", 8))),
    ("upper_zero", "num=%0D", "a", "%0d", "a", 1, "42"),
    ("binary", "bin=%b", "bits[5:2]", "%b", "bits", 1, "1110xz11"),
    ("signed", "neg=%d", "a", "%0d", "a", 1, "-17"),
    ("wide", "wide=%X", "wide", "%b", "wide", 1, WIDE),
    ("two_state", "wide=%x", "clean", "%b", "clean", 1, WIDE.replace("z", "0")),
    ("empty_int", "empty=%d", "a", "%0d", "a", 1, "0"),
    ("empty_string", "empty=%s", "s", "[%s]", "s", 1, "[]"),
    ("empty_real", "empty=%g", "r", "%0.2f", "r", 1, "0.00"),
    ("bad", "bad=%d", "wide", "%b", "wide", 1, "x" * 129),
    ("bad_two_state", "bad=%d", "clean", "%b", "clean", 1, "0" * 129),
    ("string", "text=%s", "s", "%s", "s", 1, "hello"),
    ("packed_string", "text=%s", "text_bits", "%h", "text_bits", 1, "656c6c6f"),
    ("real", "real=%F", "r", "%0.2f", "r", 1, "1.25"),
    ("exponent", "exp=%e", "r", "%0.2f", "r", 1, "25.00"),
    ("general", "exp=%G", "r", "%0.2f", "r", 1, "25.00"),
    ("copyback", "num=%d", "items[choose()]", "%0d %0d", "items[0], items[1]", 1, "77 42"),
    ("missing", "absent=%d", "items[choose()]", "%0d %0d", "items[0], items[1]", 0, "77 -9"),
    ("empty_prefix", "%s", "s", "%s", "s", 1, "num=42"),
]


def test(kind, container):
    name = f"runtime_plusargs_{kind}_{container}"
    expr = {"string": "fmt", "packed": "packed_fmt", "function": "get_format(fmt)",
            "array": "formats[0]", "conditional": '(select_format ? fmt : "invalid")'}[kind]
    declarations = ["    int a, items[2];", "    byte_bits_t bits;", "    wide_t wide;",
                    "    clean_t clean;", "    text_t text_bits;", "    string s;", "    real r;"]
    locals_ = ["    int n;", "    string fmt, formats[1];", "    logic [255:0] packed_fmt;",
               "    bit select_format;"]
    body, expected = [], []
    for tag, fmt, target, display, args, count, value in CASES:
        body += ['    a = -9; items[0] = 77; items[1] = -9; s = "seed"; r = 2.5;',
                 "    bits = 8'b11000011; wide = '0; clean = '1; text_bits = '0;",
                 f'    fmt = "{fmt}"; packed_fmt = "{fmt}"; formats[0] = fmt; select_format = 1;',
                 "    trace = 0;", f"    n = $value$plusargs({expr}, {target});",
                 f'    $display("{tag} %0d {display} %0d", n, {args}, trace);']
        trace = "1" if kind == "function" else ""
        if tag == "copyback":
            trace += "2"
        expected += [f"{tag} {count} {value} {trace or '0'}"]
    body += ["    for (int i = 0; i < 2; i++) begin",
             '      fmt = i == 0 ? "num=%d" : "num=%h";',
             '      packed_fmt = i == 0 ? "num=%d" : "num=%h";',
             "      formats[0] = fmt; select_format = 1; trace = 0;",
             f"      n = $value$plusargs({expr}, a);",
             '      $display("repeat %0d %0d %0d", n, a, trace);', "    end"]
    trace = 1 if kind == "function" else 0
    expected += [f"repeat 1 42 {trace}", f"repeat 1 66 {trace}"]
    lines = ["/*", f":name: {name}",
             f":description: Runtime plusarg formats from {kind} in {container}",
             ":tags: proc plusargs", ":type: simulation", ":lrm: 1800-2023 21.6",
             ":oracle: spec", ":spec_check: ai", ":fourstate: yes", ":nondeterministic: no",
             f":generator: gen_runtime_plusargs_matrix.py@{VERSION}", ":top_module: top",
             f":args: {ARGS}", f":expected_stdout: @{name}.expected",
             f":expected_stderr: @{name}.stderr", "*/",
             "// Generated by tools/gen_runtime_plusargs_matrix.py; edit the generator.",
             "`timescale 1ns/1ns", "interface worker;" if container == "interface" else "module top;",
             "  typedef logic [7:0] byte_bits_t;", "  typedef logic [128:0] wide_t;",
             "  typedef bit [128:0] clean_t;", "  typedef logic [31:0] text_t;", "  int trace;",
             "  function automatic string get_format(input string f);",
             "    trace = trace * 10 + 1; return f;", "  endfunction",
             "  function automatic int choose();", "    trace = trace * 10 + 2; return 1;",
             "  endfunction"]
    if container == "ref":
        lines += declarations + ["  task automatic run(ref int a, ref int items[2],",
                                 "      ref byte_bits_t bits, ref wide_t wide, ref clean_t clean,",
                                 "      ref text_t text_bits, ref string s, ref real r);"]
        lines += locals_ + body + ["  endtask",
                                   "  initial run(a, items, bits, wide, clean, text_bits, s, r);"]
    elif container in ("automatic", "static_task", "function"):
        opening = {"automatic": "task automatic run();", "static_task": "task run();",
                   "function": "function automatic void run();"}[container]
        lines += ["  " + opening] + declarations + locals_ + body
        lines += ["  endfunction" if container == "function" else "  endtask", "  initial run();"]
    else:
        lines += declarations
        if container == "generate":
            lines += ["  if (1) begin : g"]
        if container == "always":
            lines += ["  event go;", "  initial #1 ->go;", "  always @(go) begin"]
        else:
            lines += ["  final begin" if container == "final" else "  initial begin"]
        lines += locals_
        lines += (["    fork", "      begin"] + body + ["      end", "    join"]
                  if container == "fork" else body)
        lines += ["  end"]
        if container == "generate":
            lines += ["  end"]
    lines += (["endinterface", "module top;", "  worker u();", "endmodule"]
              if container == "interface" else ["endmodule"])
    return {name + ".sv": "\n".join(lines) + "\n",
            name + ".expected": "\n".join(expected) + "\n", name + ".stderr": ""}


def files():
    return {name: text for kind in KINDS for container in CONTAINERS
            for name, text in test(kind, container).items()}


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    bad = False
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"{name}: run tools/gen_runtime_plusargs_matrix.py", file=sys.stderr)
                bad = True
        else:
            path.write_text(text, encoding="utf-8")
    return int(bad)


if __name__ == "__main__":
    sys.exit(main())
