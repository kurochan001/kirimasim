"""Generates the matrix tests of functions that schedule work to run after
they return, of TEST_SUITE.md ("Mechanism matrix"): a design whose calls
are all errors, in tests/cli/ (run_cli_tests.py compares its error and
note lines), and simulation tests of the calls that are allowed, in
tests/suite/proc/.

  tools/gen_later_work_matrix.py           # writes the files
  tools/gen_later_work_matrix.py --check   # exit 1 if a file differs from what it would write

A function that schedules an event that can become active only after it
returns, with a nonblocking assignment, a nonblocking trigger ->> or a
fork ... join_none, or that calls a function that does, may be called
only from a thread of an initial or always procedure, or of a fork in
one (13.4.4). kirimasim reports any other call at compile time: from the
initial value of a static variable, a continuous assignment (assign, a
net declaration assignment, a port connection) or a final procedure, as
an error at the call, with a note at the statement, and exit code 2
(SCHEDULER_SPEC.md 6.5). always_comb and always_ff are always procedures
(9.2.2). A blocking ->, $strobe and a deferred assertion do not count.

The axes: the caller (the initial value of a static variable of a
module, a package, the compilation unit, a block of an initial
procedure, a static function, a generate block and a module the top
instantiates, as in the matrix of #5; assign, a net declaration
assignment, a port connection, final; and the allowed initial, always,
always_comb, always_ff and a fork branch); the statement (<=, ->> and
fork ... join_none; and ->, $strobe and a deferred assertion, which do
not count); the depth (the function itself, or a function that calls
it).

The expected outputs follow from the rules above, computed below.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CLI = ROOT / "tests" / "cli"
SUITE = ROOT / "tests" / "suite" / "proc"
NAME = "later_work_matrix"
PREFIX = "later_work_"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1
ERROR = ("'{f}' schedules work that runs after it returns, so it can be called only from an "
         "initial or always procedure, not from {caller}")
STATIC = "the initial value of a static variable"

# The statements that count: (name, the lines of the function's body
# before its return, what the note calls it, the text the note points at)
COUNTED = [
    ("nba", ["q <= v;"], "a nonblocking assignment", "q <= v;"),
    ("trigger", ["->> ev;"], "a nonblocking event trigger", "->> ev;"),
    ("fork", ["fork", "  $display(\"forked\");", "join_none"], "a fork with join_none", "fork"),
]


def package_lines():
    """Package p: the functions that schedule, and those that call them."""
    lines = ["package p;", "  logic q;", "  event ev;"]
    for name, body, _, _ in COUNTED:
        lines += [f"  function automatic logic f_{name}(logic v);"]
        lines += [f"    {x}" for x in body]
        lines += ["    return v;", "  endfunction"]
    for name, _, _, _ in COUNTED:
        lines += [f"  function automatic logic g_{name}(logic v);",
                  f"    return f_{name}(v);", "  endfunction"]
    return lines


def cli_files():
    """The design whose calls are all errors, and its error and note lines."""
    calls = [(depth, name) for depth in ("f", "g") for name, _, _, _ in COUNTED]
    lines = [f"// Generated by tools/gen_later_work_matrix.py (version {VERSION}); do not edit."]
    lines += package_lines()
    # (the caller, the line with {C} for the call) for every call
    sites = []
    lines_pkg = [f"  logic p_{d}_{n} = {d}_{n}(1'b1);" for d, n in calls]
    sites += [(STATIC, x) for x in lines_pkg]
    lines += lines_pkg + ["endpackage", "import p::*;"]
    unit = [f"logic u_{d}_{n} = {d}_{n}(1'b1);" for d, n in calls]
    sites += [(STATIC, x) for x in unit]
    lines += unit
    lines += ["module child(input logic i);", "endmodule", "module inner;"]
    inner = [f"  logic i_{d}_{n} = {d}_{n}(1'b1);" for d, n in calls]
    sites += [(STATIC, x) for x in inner]
    lines += inner + ["endmodule", "module top;", "  logic a = 1'b0;", "  inner u();"]
    groups = [
        (STATIC, lambda d, n: [f"  logic m_{d}_{n} = {d}_{n}(1'b1);"]),
        (STATIC, lambda d, n: [f"  if (1) begin : gen_{d}_{n}",
                               f"    logic v = {d}_{n}(1'b1);", "  end"]),
        (STATIC, lambda d, n: [f"  initial begin : blk_{d}_{n}",
                               f"    static logic s = {d}_{n}(1'b1);", "  end"]),
        (STATIC, lambda d, n: [f"  function logic h_{d}_{n}();",
                               f"    static logic s = {d}_{n}(1'b1);", "    return s;",
                               "  endfunction", f"  initial void'(h_{d}_{n}());"]),
        ("a continuous assignment", lambda d, n: [f"  wire w_{d}_{n};",
                                                  f"  assign w_{d}_{n} = {d}_{n}(a);"]),
        ("a continuous assignment", lambda d, n: [f"  wire n_{d}_{n} = {d}_{n}(a);"]),
        ("a continuous assignment", lambda d, n: [f"  child c_{d}_{n}_i(.i({d}_{n}(a)));"]),
        ("a final procedure", lambda d, n: [f"  final void'({d}_{n}(1'b1));"]),
    ]
    for caller, make in groups:
        for d, n in calls:
            block = make(d, n)
            call = f"{d}_{n}("
            site = next(x for x in block if call in x and "function" not in x)
            sites.append((caller, site))
            lines += block
    # A function whose static variable's initial value makes the call: the
    # initial value is the caller, not the continuous assignment, as static
    # initialization runs it (SCHEDULER_SPEC.md 6.5). The initial value of
    # an automatic variable runs with each call, at the top of the function
    # and in a block inside it.
    block = ["  function logic k_static();", "    static logic s = f_nba(1'b1);", "    return s;",
             "  endfunction", "  wire w_k;", "  assign w_k = k_static();"]
    sites.append((STATIC, block[1]))
    lines += block
    autos = [("m_auto", ["  function automatic logic m_auto(logic v);", "    logic t = f_nba(v);",
                         "    return t;", "  endfunction", "  wire w_m = m_auto(a);"]),
             ("n_auto", ["  function automatic logic n_auto(logic v);", "    begin : inner",
                         "      logic t = f_nba(v);", "      return t;", "    end",
                         "  endfunction", "  wire w_n = n_auto(a);"])]
    for _, block in autos:
        lines += block
    lines += ["endmodule"]
    file = f"{NAME}.sv"
    notes = {}
    for name, body, what, text in COUNTED:
        at = next(i for i, x in enumerate(lines) if x.strip() == text and i > lines.index(
            f"  function automatic logic f_{name}(logic v);"))
        notes[name] = (at + 1, lines[at].index(text) + 1, f"{what} in 'f_{name}'")
    stderr = []
    used = set()
    for caller, site in sites:
        at = next(i for i, x in enumerate(lines) if x == site and i not in used)
        used.add(at)
        for d, n in calls:
            call = f"{d}_{n}("
            if call in site:
                column = lines[at].index(call) + 1
                stderr.append(f"{file}:{at + 1}:{column}: error: "
                              + ERROR.format(f=f"{d}_{n}", caller=caller))
                line, col, what = notes[n]
                stderr.append(f"{file}:{line}:{col}: note: {what}")
    for fname, block in autos:
        at = lines.index(block[-1])
        stderr.append(f"{file}:{at + 1}:{lines[at].index(fname) + 1}: error: "
                      + ERROR.format(f=fname, caller="a continuous assignment"))
        line, col, what = notes["nba"]
        stderr.append(f"{file}:{line}:{col}: note: {what}")
    return {CLI / file: "\n".join(lines) + "\n", CLI / f"{NAME}.stderr": "\n".join(stderr) + "\n"}


def header(name, description, lrm):
    return [
        "/*",
        f":name: {name}",
        f":description: {description}",
        ":tags: proc function",
        ":type: simulation",
        ":lrm: 1800-2023 " + " ".join(lrm),
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: no",
        ":nondeterministic: no",
        f":generator: gen_later_work_matrix.py@{VERSION}",
        ":issue: 13",
        ":top_module: top",
        f":expected_stdout: @{name}.expected",
        "*/",
        "// Generated by tools/gen_later_work_matrix.py; change the generator, not this file.",
        "`timescale 1ns/1ns",
    ]


# The allowed callers: (name, the items of top that call {F}(...) at time
# 1 (and at 0 for always_comb), the times the function is called at)
ALLOWED = [
    ("initial", ["initial begin", "  #1;", "  void'({F}(1'b1));", "end"], [1]),
    ("always", ["always @(a) void'({F}(a));", "initial #1 a = 1'b1;"], [1]),
    ("always_comb", ["always_comb y = {F}(a);", "initial #1 a = 1'b1;"], [0, 1]),
    ("always_ff", ["always_ff @(posedge clk) y <= {F}(1'b1);", "initial #1 clk = 1'b1;"], [1]),
    ("fork", ["initial begin", "  #1;", "  fork", "    void'({F}(1'b1));", "  join", "end"], [1]),
]


def allowed_case(caller, items, times, statement, depth):
    sname, body, _, _ = statement
    name = f"{PREFIX}{caller}_{sname}" + ("_through" if depth == "g" else "")
    f = f"{depth}_{sname}"
    lines = ["module top;", "  logic a = 1'b0;", "  logic clk = 1'b0;", "  logic y;",
             "  logic q = 1'b0;", "  event ev;", f"  function automatic logic f_{sname}(logic v);"]
    lines += [f"    {x}" for x in body]
    lines += ["    return v;", "  endfunction"]
    if depth == "g":
        lines += [f"  function automatic logic g_{sname}(logic v);",
                  f"    return f_{sname}(v);", "  endfunction"]
    lines += [f"  {x.replace('{F}', f)}" for x in items]
    if sname == "trigger":
        lines += ["  always @ev $display(\"ev at %0t\", $time);"]
    if sname == "fork":
        lines = [x.replace("$display(\"forked\");", "$display(\"forked at %0t\", $time);")
                 for x in lines]
    lines += ["  initial #2 $display(\"q=%b\", q);", "endmodule"]
    out = []
    if sname == "trigger":
        out += [f"ev at {t}" for t in times]
    if sname == "fork":
        out += [f"forked at {t}" for t in times]
    # q takes the last value written: 1'b1, or a, which is 1 by then; 0
    # when the statement is not the nonblocking assignment.
    out.append("q=1" if sname == "nba" else "q=0")
    through = " through another function" if depth == "g" else ""
    description = (f"a function with {statement[2]} called{through} from {caller.replace('_', ' ')}"
                   " runs, as 13.4.4 allows")
    lrm = ["9.2.2", "13.4.4"] if caller.startswith("always_") else ["13.4.4"]
    return name, header(name, description, lrm) + lines, out


# The statements that do not count, and the callers that would be errors
# if they did: (name, the function's body before its return)
UNCOUNTED = [
    ("blocking_trigger", ["-> ev;"]),
    ("strobe", ["$strobe(\"strobe at %0t\", $time);"]),
    ("deferred", ["assert #0 (v == 1'b0) else $display(\"deferred failed at %0t\", $time);"]),
]
# (caller, the items of top, the lines printed with {S} for those the
# statement adds)
UNCOUNTED_CALLERS = [
    ("static", ["int x = f(1'b1);", "initial #2 $display(\"x=%0d\", x);"]),
    ("assign", ["wire w;", "assign w = f(a);", "initial #1 a = 1'b1;",
                "initial #2 $display(\"w=%b\", w);"]),
    ("final", ["final begin", "  void'(f(1'b1));", "  $display(\"final\");", "end"]),
]


def uncounted_case(statement, caller):
    sname, body = statement
    cname, items = caller
    name = f"{PREFIX}{sname}_{cname}"
    lines = ["module top;", "  logic a = 1'b0;", "  event ev;",
             "  function automatic logic f(logic v);"]
    lines += [f"    {x}" for x in body] + ["    return v;", "  endfunction"]
    lines += [f"  {x}" for x in items] + ["endmodule"]
    # What the statement prints: $strobe at the end of each time the
    # function runs; the deferred assertion in the Observed region of each
    # time it runs with v = 1; nothing in final, as no time slot follows.
    runs = {"static": [(0, 1)], "assign": [(0, 0), (1, 1)], "final": []}[cname]
    out = []
    for t, v in runs:
        if sname == "strobe":
            out.append(f"strobe at {t}")
        if sname == "deferred" and v == 1:
            out.append(f"deferred failed at {t}")
    out.append({"static": "x=1", "assign": "w=1", "final": "final"}[cname])
    what = {"blocking_trigger": "a blocking ->", "strobe": "a $strobe",
            "deferred": "a deferred assertion"}[sname]
    where = {"static": "the initial value of a static variable",
             "assign": "a continuous assignment", "final": "a final procedure"}[cname]
    description = f"a function with {what} may be called from {where}: it schedules no later work"
    lrm = ["13.4.4", "16.4", "21.2.2"] if sname != "blocking_trigger" else ["13.4.4", "15.5.1"]
    return name, header(name, description, lrm) + lines, out


def files():
    out = cli_files()
    cases = [allowed_case(c, items, times, s, "f") for c, items, times in ALLOWED for s in COUNTED]
    cases += [allowed_case(c, items, times, COUNTED[0], "g") for c, items, times in ALLOWED]
    # $strobe and the deferred assertion print nothing from final, so final
    # is tried with the blocking trigger only.
    cases += [uncounted_case(s, c) for s in UNCOUNTED for c in UNCOUNTED_CALLERS
              if c[0] != "final" or s[0] == "blocking_trigger"]
    for name, text, expected in cases:
        out[SUITE / f"{name}.sv"] = "\n".join(text) + "\n"
        out[SUITE / f"{name}.expected"] = "\n".join(expected) + "\n"
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for path, text in files().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_later_work_matrix: {path.relative_to(ROOT)} is out of date; run "
                      "tools/gen_later_work_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
