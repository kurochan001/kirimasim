"""Generates the matrix tests of ports whose variable is an unpacked
structure (TEST_SUITE.md, "Mechanism matrix") in tests/suite/ports/.

  tools/gen_struct_port_matrix.py           # writes the files
  tools/gen_struct_port_matrix.py --check   # exit 1 if a file differs from what it would write

The rule: 23.3.3 of the standard. A port connection is a continuous
assignment, from the expression outside to an input port and from an
output port to the variable outside, whatever the data type of the port
is (23.2.2.3). A port of an unpacked structure type therefore follows
its source member by member, at the start and at each change.

The axes: the structure (plain members; a packed structure member; an
unpacked array member; an array of structures as the port), the
direction (an input read by always_comb, an output written by a
procedure, an output of one instance into the input of another), and
the place of the instances (the top module, a generate loop, a module
below the top).

Each test passes a value through the ports, prints what arrives, then
changes one member and prints again. The expected output is computed
here from the values, without reading kirimasim's code. A person checks
it once for all the tests made from it (TEST_SUITE.md, "Sampling by
people").
"""

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "ports"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

# (key, the members after `int a;`, their names, the value of each as a
# function of n, how each is printed).
STRUCTS = [
    ("plain", "logic [3:0] b;", [("b", lambda n: (n + 2) % 16)]),
    ("packed_member", "struct packed { logic [1:0] x; logic y; } p;",
     [("p", lambda n: (n + 1) % 8)]),
    ("array_member", "int r [2];", [("r[0]", lambda n: n + 10), ("r[1]", lambda n: n + 20)]),
]
PLACES = ["top", "generate", "below"]


def members(struct):
    return ["a"] + [m for m, _ in struct[2]]


def values(struct, n):
    return [n] + [f(n) for _, f in struct[2]]


def assigns(struct, target, n):
    return " ".join(f"{target}.{m} = {v};" for m, v in zip(members(struct), values(struct, n)))


def show(label, struct, target):
    names = members(struct)
    fmt = " ".join("%0d" for _ in names)
    return f'$display("{label}: {fmt}", {", ".join(f"{target}.{m}" for m in names)});'


def line(label, struct, n):
    return f"{label}: " + " ".join(str(v) for v in values(struct, n))


def test(struct, place):
    key = struct[0]
    name = f"struct_port_{key}_{place}"
    where = {"top": "the top module", "generate": "a generate loop",
             "below": "a module below the top"}[place]
    sv = ["/*", f":name: {name}",
          ":description: ports of an unpacked structure type follow their source member by "
          f"member: input, output and output into input, with the instances in {where}",
          ":tags: ports", ":type: simulation", ":lrm: 1800-2023 23.3.3 23.2.2.3", ":oracle: spec",
          ":spec_check: ai", ":fourstate: yes", ":nondeterministic: no",
          f":generator: gen_struct_port_matrix.py@{VERSION}", ":top_module: top",
          f":expected_stdout: @{name}.expected", "*/",
          "// Generated by tools/gen_struct_port_matrix.py; change the generator, not this file.",
          "`timescale 1ns/1ns",
          f"typedef struct {{ int a; {struct[1]} }} st_t;",
          # An input and an output: the output is the input, read by always_comb.
          "module pass (input var st_t s, output var st_t so);",
          "  always_comb so = s;",
          "endmodule",
          # An output written by a procedure, once at the start and once later.
          "module source (output st_t o);",
          f"  initial begin {assigns(struct, 'o', 3)} #5 o.a = 4; end",
          "endmodule",
          # An array of structures as the port, its elements swapped.
          "module swap (input var st_t s [2], output var st_t so [2]);",
          "  always_comb begin so[0] = s[1]; so[1] = s[0]; end",
          "endmodule"]
    body = ["st_t s, so, m, mo;", "st_t as [2], aso [2];",
            "pass u (.s(s), .so(so));",
            "source v (.o(m));",
            "pass w (.s(m), .so(mo));",
            "swap x (.s(as), .so(aso));"]
    stim = [assigns(struct, "s", 1), assigns(struct, "as[0]", 5), assigns(struct, "as[1]", 6),
            "#1;", show("input", struct, "so"), show("output", struct, "m"),
            show("chained", struct, "mo"), show("element 0", struct, "aso[0]"),
            show("element 1", struct, "aso[1]"),
            "s.a = 2; as[0].a = 7;",
            "#1;", show("input changed", struct, "so"),
            show("element changed", struct, "aso[1]"),
            "#5;", show("output changed", struct, "m"), show("chained changed", struct, "mo")]
    if place == "top":
        sv += ["module top;"] + ["  " + b for b in body]
        sv += ["  initial begin"] + ["    " + t for t in stim] + ["  end", "endmodule"]
    elif place == "generate":
        sv += ["module top;", "  for (genvar i = 0; i < 2; i++) begin : g"]
        sv += ["    " + b for b in body]
        # Only the first block prints; both hold the instances.
        sv += ["    if (i == 0) begin : first", "      initial begin"]
        sv += ["        " + t for t in stim] + ["      end", "    end", "  end", "endmodule"]
    else:
        sv += ["module middle;"] + ["  " + b for b in body]
        sv += ["  initial begin"] + ["    " + t for t in stim] + ["  end", "endmodule"]
        sv += ["module top;", "  middle n ();", "endmodule"]
    changed = values(struct, 1)
    changed[0] = 2
    element = values(struct, 5)
    element[0] = 7
    source = values(struct, 3)
    source[0] = 4
    expected = [line("input", struct, 1), line("output", struct, 3), line("chained", struct, 3),
                line("element 0", struct, 6), line("element 1", struct, 5),
                "input changed: " + " ".join(str(v) for v in changed),
                "element changed: " + " ".join(str(v) for v in element),
                "output changed: " + " ".join(str(v) for v in source),
                "chained changed: " + " ".join(str(v) for v in source)]
    return name, sv, expected


def files():
    out = {}
    for struct in STRUCTS:
        for place in PLACES:
            name, sv, expected = test(struct, place)
            out[f"{name}.sv"] = "\n".join(sv) + "\n"
            out[f"{name}.expected"] = "\n".join(expected) + "\n"
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for name, text in files().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"gen_struct_port_matrix: {path.relative_to(OUT.parent.parent.parent)} is "
                      "out of date; run tools/gen_struct_port_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
