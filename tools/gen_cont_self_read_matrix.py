#!/usr/bin/env python3
"""Generates the matrix tests of processes that read what they write, of
TEST_SUITE.md ("Mechanism matrix"), in tests/suite/sched/.

  tools/gen_cont_self_read_matrix.py           # writes the files
  tools/gen_cont_self_read_matrix.py --check   # exit 1 if a file differs from what it would write

A continuous assignment, a gate, a UDP instance and a procedural assign or
force are processes sensitive to the elements of their right side, so a
change they make to one of those elements evaluates them again, as any
other change does (4.9.1, 4.9.2, 10.3.2; SCHEDULER_SPEC.md 5, 12). A
procedure is not: it waits on an event control only when it reaches it,
so it does not see what it wrote before (9.4.2).

The axes: the construct that makes the process (an assign statement on a
net and on a variable, a net declaration assignment, an assign statement
in an instance whose input and output ports connect to one net, a gate, a
UDP instance, a procedural assign and a force); and what the change does:
it settles, as with a | en, where the evaluation after the change gives the
same value (a function in the right side prints each evaluation after time
0, where the order of starting is not fixed; gates and UDPs cannot call
one), or it loops with a delay of 2, so that time advances and $finish
ends the run (procedural assign and force take no delay). Two procedures
whose body reads what it writes, always @* and always @(en or a), run once.
Loops that do not advance time are in tools/gen_zero_time_loop_matrix.py.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "suite" / "sched"
PREFIX = "cont_self_read_"
# The version of the rules below (TEST_SUITE.md, :generator:). Raise it
# whenever they change.
VERSION = 1

FUNCTION = [
    "function automatic logic f(input logic x, input logic e);",
    '  if ($time > 0) $display("f(%b, %b)", x, e);',
    "  return x | e;",
    "endfunction",
]
OR_UDP = [
    "primitive or_udp(output o, input x, input y);",
    "  table",
    "    1 ? : 1;",
    "    ? 1 : 1;",
    "    0 0 : 0;",
    "  endtable",
    "endprimitive",
]
NAND_UDP = [
    "primitive nand_udp(output o, input x, input y);",
    "  table",
    "    0 ? : 1;",
    "    ? 0 : 1;",
    "    1 1 : 0;",
    "  endtable",
    "endprimitive",
]


def child(body):
    return ["module child(input e, input i, output o);"] + [f"  {x}" for x in body] + ["endmodule"]


# How each construct makes the process: (the lines before module top, the
# items of top, the statements of the initial procedure before #1 en = 1,
# the clauses of the standard). {d} is the delay, "" or "#2 ".
SETTLES = {
    "assign_net": ([], FUNCTION + ["wire a;", "assign a = f(a, en);"], [], "10.3.2"),
    "assign_var": ([], FUNCTION + ["logic a;", "assign a = f(a, en);"], [], "10.3.2"),
    "net_decl": ([], FUNCTION + ["wire a = f(a, en);"], [], "10.3.1"),
    "port": (child(FUNCTION + ["assign o = f(i, e);"]),
             ["wire a;", "child u(.e(en), .i(a), .o(a));"], [], "10.3.2 23.3.3"),
    "gate": ([], ["wire a;", "or g(a, a, en);"], [], "28.4"),
    "udp": (OR_UDP, ["wire a;", "or_udp u(a, a, en);"], [], "29.3"),
    "proc_assign": ([], FUNCTION + ["logic a;"], ["assign a = f(a, en);"], "10.6.1"),
    "force": ([], FUNCTION + ["wire a;"], ["force a = f(a, en);"], "10.6.2"),
}
LOOPS = {
    "assign_net": ([], ["wire a;", "assign #2 a = ~(en & a);"], "10.3.2 10.3.3"),
    "assign_var": ([], ["logic a;", "assign #2 a = ~(en & a);"], "10.3.2 10.3.3"),
    "net_decl": ([], ["wire #2 a = ~(en & a);"], "10.3.1 10.3.3"),
    "port": (child(["assign #2 o = ~(e & i);"]), ["wire a;", "child u(.e(en), .i(a), .o(a));"],
             "10.3.3 23.3.3"),
    "gate": ([], ["wire a;", "nand #2 g(a, en, a);"], "28.4 28.16"),
    "udp": (NAND_UDP, ["wire a;", "nand_udp #2 u(a, en, a);"], "29.3 28.16"),
}
PROCEDURES = {
    "always_star": ["always @* begin"],
    "always_event": ["always @(en or a) begin"],
}
PRINTS = ("gate", "udp")  # cannot call the function that prints


def header(name, description, lrm, tags):
    return [
        "/*",
        f":name: {name}",
        f":description: {description}",
        f":tags: {tags}",
        ":type: simulation",
        f":lrm: 1800-2023 4.9.1 4.9.2 {lrm}",
        ":oracle: spec",
        ":spec_check: ai",
        ":fourstate: yes",
        ":nondeterministic: no",
        f":generator: gen_cont_self_read_matrix.py@{VERSION}",
        ":issue: 15",
        ":top_module: top",
        f":expected_stdout: @{name}.expected",
        "*/",
        "// Generated by tools/gen_cont_self_read_matrix.py; change the generator, not this file.",
    ]


def text(lines, before, items, initial):
    lines = lines + before + ["module top;", "  logic en = 0;"]
    lines += [f"  {x}" for x in items]
    lines += ["  initial begin"] + [f"    {x}" for x in initial] + ["  end", "endmodule", ""]
    return "\n".join(lines)


def files():
    out = {}
    for kind, (before, items, first, lrm) in SETTLES.items():
        name = f"{PREFIX}{kind}_settles"
        lines = header(name, "a process sensitive to what it writes is evaluated again after its "
                       "own change, which settles", lrm, "scheduling continuous_assignment")
        if kind in PRINTS:
            items = items + ["int n = 0;", "always @(a) if ($time > 0) n++;"]
            want = "a=1 n=1\n"
            last = '#1 $display("a=%b n=%0d", a, n);'
        else:
            want = "f(x, 1)\nf(1, 1)\na=1\n"
            last = '#1 $display("a=%b", a);'
        out[f"{name}.sv"] = text(lines, before, items, first + ["#1 en = 1;", last])
        out[f"{name}.expected"] = want
    for kind, (before, items, lrm) in LOOPS.items():
        name = f"{PREFIX}{kind}_loops"
        lines = header(name, "a process with a delay that reads what it writes loops as time "
                       "advances", lrm, "scheduling continuous_assignment")
        items = items + ['always @(a) $display("%0t a=%b", $time, a);']
        out[f"{name}.sv"] = text(lines, before, items, ["#5 en = 1;", "#7 $finish;"])
        out[f"{name}.expected"] = "2 a=1\n7 a=0\n9 a=1\n11 a=0\n"
    for kind, start in PROCEDURES.items():
        name = f"{PREFIX}{kind}_runs_once"
        lines = header(name, "a procedure does not wake on what it wrote before it reached its "
                       "event control", "9.2.2.2.2 9.4.2", "scheduling always")
        items = ["logic a = 1;"] + start + ['  $display("run en=%b a=%b", en, a);',
                                            "  a = ~(en & a);", "end"]
        out[f"{name}.sv"] = text(lines, [], items, ["#1 en = 1;", '#1 $display("a=%b", a);'])
        out[f"{name}.expected"] = "run en=1 a=1\na=0\n"
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    want = files()
    if args.check:
        have = {p.name for p in OUT.glob(f"{PREFIX}*")}
        for name in sorted(have - set(want)):
            print(f"gen_cont_self_read_matrix: {name} is not generated; remove it",
                  file=sys.stderr)
            bad += 1
    for name, content in want.items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                print(f"gen_cont_self_read_matrix: {path.relative_to(OUT.parent.parent.parent)} is "
                      "out of date; run tools/gen_cont_self_read_matrix.py", file=sys.stderr)
                bad += 1
        else:
            path.write_text(content, encoding="utf-8")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
